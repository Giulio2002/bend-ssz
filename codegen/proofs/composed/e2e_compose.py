def law_files():
    """{law name: bridge file path}"""
    man = json.loads((E2E / 'manifest.json').read_text())
    out = {}
    for f, es in man['files'].items():
        for e in es:
            for l in e['laws']:
                out[l] = E2E / f
    return out


def sig(mod, name):
    """([(mode, binder, type text)], conclusion text) of a def of mod"""
    d = mod.defs[name]
    k = d.index('(')
    depth, j = 0, k
    while True:
        c = d[j]
        if c in '([{':
            depth += 1
        elif c in ')]}':
            depth -= 1
            if depth == 0:
                break
        j += 1
    ps = []
    for p in W.split_top(d[k + 1:j]):
        mode = p[0] if p[0] in '+-' else ''
        b, t = p.lstrip('+-').split(':', 1)
        ps.append((mode, b.strip(), t.strip()))
    rest = d[j + 1:]
    rest = rest[re.match(r'\s*->\s*', rest).end():]
    depth, q = 0, 0
    while q < len(rest):
        c = rest[q]
        if c in '([{':
            depth += 1
        elif c in ')]}':
            depth -= 1
        elif c == ':' and depth == 0 and (q + 1 == len(rest) or rest[q + 1] in ' \n'):
            break
        q += 1
    return ps, rest[:q].strip()


def some_lhs(concl, fn):
    """(X, V) of a conclusion {Some{X} == API.<fn>(Spec, V) : ...}"""
    m = re.match(r'\{Some\{(.*)\} == API\.' + fn + r'\((.*)\) : Maybe<&2, \+List<U32>>\}$', concl, re.S)
    if not m:
        return None
    a = W.split_top(m.group(2))
    return m.group(1), a[0], a[1]


def build(name, lf):
    if EXT is not None:
        r = EXT.build(name, lf, sys.modules[__name__])
        if r is not None:
            return r
    return build_std(name, lf)


BRANCH_E = ['t', 'dw', 'hd', 'pf', 'cap']   # the branch names' laws state the object as O.Words{thaw(t), N} for a perfect tree t
BRANCH_R = ['h', 't', 'dw', 'hd', 'pf', 'cap']
TOBJ = re.compile(r'\w+\.Words\{\w+\.array__thaw\(U32, t\), \d+\}')


def build_std(name, lf):
    dl = lf.get(f'{name}_e2e_decode_accept') or lf.get(f'{name}_e2e_decode_view')
    kind = 'accept' if f'{name}_e2e_decode_accept' in lf else 'view'
    el, rl = lf.get(f'{name}_e2e_encode'), lf.get(f'{name}_e2e_root')
    if not (dl and el and rl):
        return None, 'no decode, encode or root bridge'
    dm, em, rm = W.Mod.get(dl), W.Mod.get(el), W.Mod.get(rl)
    eps, ec = sig(em, f'{name}_e2e_encode')
    rps, rc = sig(rm, f'{name}_e2e_root')
    lit = None
    if [b for _, b, _ in eps] != ['o'] or [b for _, b, _ in rps] != ['h', 'o']:
        extra = sorted({b for _, b, _ in eps + rps} - {'o', 'h'})
        why = 'the (i)/(iv) bridges take ' + ', '.join(extra) + ' (decoded-object laws pending)'
        if name in DR.PROVERS and kind == 'view' and 'd_acc' in dm.defs and 'd_none' in dm.defs:
            # a variable-size name with its decoded-object premises (e2e_decrep.py)
            lit = ('var', why)
        else:
            # a fixed-size decoder's object written out (<X>_d_some / _d_none): its premises are computed
            br_ = [b for _, b, _ in eps] == BRANCH_E and [b for _, b, _ in rps] == BRANCH_R
            if ('o' not in [b for _, b, _ in eps] and not br_) or kind != 'view' or f'{name}_d_some' not in dm.defs or f'{name}_d_none' not in dm.defs:
                return None, why
            sps, sc = sig(dm, f'{name}_d_some')
            if [b for _, b, _ in sps] != ['bs', 'n', 'hn', 'hd', 'ec']:
                return None, why
            mk = re.match(r'\{Nat\.is_eq\(List\.length\(&2, U32, bs\), (\d+)n\) == True\{\} : Bool\}$', sps[4][2])
            ms = re.match(r'\{(.*) == Some\{(.*)\} : (Maybe<&1, [\w.]+>)\}$', sc, re.S)
            if 'U32.and(' in ms.group(2) or 'byte_sel(' in ms.group(2):
                return None, why + '; the decoded words are masked (bit-level lemmas pending)'
            if int(mk.group(1)) > 1500:
                return None, why + '; the decoded object is too large to compute its premises (FuluCell, FuluMatrixEntry: 2048+ bytes)'
            lit = (int(mk.group(1)), ms.group(2), why)
    dps, dc = sig(dm, f'{name}_e2e_decode_{kind}')
    W.PREFER.clear()
    W.PREFER[dm.path] = 'DB'
    if em.path not in W.PREFER:
        W.PREFER[em.path] = 'EB'
    if rm.path not in W.PREFER:
        W.PREFER[rm.path] = 'RB'
    W.PREFER[(E2E / 'e2e_comp.bend').resolve()] = 'C'
    W.PREFER[(ROOT / 'types/schema.bend').resolve()] = 'S'
    W.PREFER[(ROOT / 'src/buffer.bend').resolve()] = 'B'
    W.PREFER[(ROOT / 'src/model.bend').resolve()] = 'API'
    taken = set(W.PREFER.values())
    for m_ in (em, rm, dm):
        for a, pth in m_.imports.items():
            if pth not in W.PREFER and a not in taken:
                W.PREFER[pth] = a
                taken.add(a)
    ctx = W.Ctx()
    for p_ in (dm.path, em.path, rm.path, (E2E / 'e2e_comp.bend').resolve()):
        ctx.alias(p_)
    DB, EB, RB = W.PREFER[dm.path], W.PREFER[em.path], W.PREFER[rm.path]
    enc = some_lhs(ec, 'serialize')
    rt = some_lhs(rc, 'hash_tree_root')
    if not enc or not rt:
        return None, 'unexpected (i)/(iv) conclusion'
    X = ctx.lift(em, enc[0])
    SPEC = ctx.lift(em, enc[1])
    V = ctx.lift(em, enc[2])
    R = ctx.lift(rm, rt[0])
    def same_view(a, b):   # equal, or equal but for bitlist_rep's thin wrappers (bview, rep_bits) over bitlist_obj_light's
        if a == b:
            return True
        rep = [al for al, pth in ctx.used.items() if pth.name == 'bitlist_rep.bend']
        obj = [al for al, pth in ctx.used.items() if pth.name == 'bitlist_obj_light.bend']
        return bool(rep and obj) and a.replace(rep[0] + '.', obj[0] + '.') == b.replace(rep[0] + '.', obj[0] + '.')
    if not same_view(ctx.lift(rm, rt[2]), V) or ctx.lift(rm, rt[1]) != SPEC:
        return None, 'the (i) and (iv) views differ textually'
    if [b for _, b, _ in eps] == BRANCH_E:   # the object is the statements' O.Words{thaw(t), N}; its view is the decode bridge's <Name>_ov
        X, R = TOBJ.sub('o', X), TOBJ.sub('o', R)
        V = f'{DB}.{name}_ov(o)'
    if kind == 'accept':
        mo = re.match(r'\(\{(.*?) == Some\{o\} : (Maybe<&1, [^>]*>)\} -> (\{API\.deserialize\(.*?\} : Maybe<&2, S\.Value>\})\) & \((.*)\)$', dc, re.S)
        DEC, MT, ACC, BWD = ctx.lift(dm, mo.group(1)), ctx.lift(dm, mo.group(2)), ctx.lift(dm, mo.group(3)), ctx.lift(dm, mo.group(4))
        hyps = [(m_, b, ctx.lift(dm, t)) for m_, b, t in dps if b not in ('bs', 'n', 'o')]
        DV = f'Some{{{V}}}'
        args = ', '.join(b for _, b, _ in dps)
        acc_body = (f'  Pair.fst({{{DEC} == Some{{o}} : {MT}}} -> {ACC}, {BWD}, {DB}.{name}_e2e_decode_accept({args}))(dec)')
        accT = ACC
    else:
        mo = re.match(r'\{(\w+)\((.*)\) == (API\.deserialize\(.*\)) : Maybe<&2, S\.Value>\}$', dc, re.S)
        MV, DEC, DES = mo.group(1), ctx.lift(dm, mo.group(2)), ctx.lift(dm, mo.group(3))
        MT = re.search(r'Pair\.snd\(B\.Buf, (Maybe<&1, [\w.]+>)', dc).group(1)
        MT = ctx.lift(dm, MT)
        hyps = [(m_, b, ctx.lift(dm, t)) for m_, b, t in dps if b not in ('bs', 'n')]
        args = ', '.join(b for _, b, _ in dps)
        accT = f'{{{DES} == Some{{{V}}} : Maybe<&2, S.Value>}}'
        acc_body = (f'  Equal.trans(Maybe<&2, S.Value>, {DES}, {DB}.{MV}({DEC}), Some{{{V}}},\n'
                    f'    Equal.sym(Maybe<&2, S.Value>, {DB}.{MV}({DEC}), {DES}, {DB}.{name}_e2e_decode_view({args})),\n'
                    f'    Equal.cong({MT}, Maybe<&2, S.Value>, z => {DB}.{MV}(z), {DEC}, Some{{o}}, dec))')
    OT = MT[len('Maybe<&1, '):-1]
    if lit and lit[0] == 'var':
        return build_var(name, ctx, dm, em, rm, eps, rps, DB, EB, RB, X, SPEC, V, R, DEC, MT, OT, accT, acc_body, hyps)
    if lit:
        return build_lit(name, lit, ctx, dm, em, rm, eps, rps, DB, EB, RB, X, SPEC, V, R, DEC, MT, OT, accT, acc_body, hyps, kind)
    hp = ''.join(f', {m_}{b}: {t}' for m_, b, t in hyps)
    ha = ''.join(f', {b}' for _, b, _ in hyps)
    dect = f'dec: {{{DEC} == Some{{o}} : {MT}}}'
    body = [f'# {name}: decoding accepted bytes, then re-encoding / hashing the object (codegen/proofs/composed/e2e_compose.py)', '',
            f'# the value deserialize gives for the accepted bytes is the decoded object\'s view',
            f'def acc(+bs: +List<U32>, +n: U32, +o: {OT}{hp}, {dect})\n    -> {accT}:\n{acc_body}', '',
            f'# (i) after (ii): the decoded object re-encodes to exactly the input bytes',
            f'def {name}_e2e_decode_encode(+bs: +List<U32>, +n: U32, +o: {OT}{hp}, {dect})\n    -> {{{X} == bs : +List<U32>}}:\n'
            f'  C.dec_enc({SPEC}, bs, {V}, {X}, acc(bs, n, o{ha}, dec), {EB}.{name}_e2e_encode(o))', '',
            f'# (iv) after (ii): the decoded object\'s root is the spec root of the value deserialize gives for the input bytes',
            f'def {name}_e2e_decode_root(h: B.Buf, +bs: +List<U32>, +n: U32, +o: {OT}{hp}, {dect})\n    -> {{Some{{{R}}} == C.droot({SPEC}, bs) : Maybe<&2, +List<U32>>}}:\n'
            f'  C.dec_root({SPEC}, bs, {V}, {R}, acc(bs, n, o{ha}, dec), {RB}.{name}_e2e_root(h, o))', '']
    return finish(ctx, body), None


def finish(ctx, body):
    for p_ in ('types/schema.bend', 'src/buffer.bend', 'src/model.bend'):
        ctx.alias(ROOT / p_)
    lines = ['import Base']
    for a, pth in sorted(ctx.used.items(), key=lambda x: x[1].relative_to(ROOT).as_posix()):
        rel = ('./' + pth.name) if pth.parent == E2E else (Path('..') / pth.relative_to(ROOT)).as_posix()
        lines.append(f'import {rel} as {a}')
    return '\n'.join(lines) + '\n\n' + HEADER + '\n' + '\n'.join(body)


def sub_o(t, obj):
    return re.sub(r'(?<![\w.])o(?![\w{(])', lambda m: obj, t)


def build_lit(name, lit, ctx, dm, em, rm, eps, rps, DB, EB, RB, X, SPEC, V, R, DEC, MT, OT, accT, acc_body, hyps, kind, over=None):
    K, obj0, why = lit
    OBJ = ctx.lift(dm, obj0)
    ctx.alias(ROOT / 'proofs/compact/found.bend')
    FDA = W.canon(ROOT / 'proofs/compact/found.bend')
    syn = LSynth(ctx)
    model = lit_model(OBJ)
    omode = ([m_ for m_, b, _ in eps if b == 'o'] or ['-'])[0]
    body = [f'# {name}: decoding accepted bytes, then re-encoding / hashing the object (codegen/proofs/composed/e2e_compose.py). The decoder\'s',
            f'# object is written out ({DB}.{name}_d_some): the (i)/(iv) premises are proved of it, and the statements\' object is it.', '']
    prem, tys = {}, {}
    br = [b for _, b, _ in eps] == BRANCH_E
    for tag, mod, ps in (('e', em, eps), ('r', rm, rps)):
        for m_, b, t in ps:
            if b in ('o', 'h') or br:
                continue
            try:
                term = over[b] if over and b in over else syn.prove(mod, t, {'o': model, '__subj': None, '__e': {'o': OBJ}})
            except SystemExit as ex:
                return None, why + f'; no synthesized proof ({str(ex)[:80]})'
            ty = sub_o(ctx.lift(mod, t), OBJ)
            same = [k for k, v in tys.items() if v == ty]
            if same:
                prem[(tag, b)] = prem[same[0]]
                continue
            tys[(tag, b)] = ty
            prem[(tag, b)] = f'p{tag}_{b}'
            body.append(f'def p{tag}_{b}(+bs: +List<U32>) -> {ty}:\n  {term}\n')
    for nm in sorted(syn.lemmas):
        body.insert(2, syn.lemmas[nm] + '\n')
    dect = f'dec: {{{DEC} == Some{{o}} : {MT}}}'
    ecT = f'{{Nat.is_eq(List.length(&2, U32, bs), {K}n) == c : Bool}}'
    SOME = f'{DB}.{name}_d_some(bs, n, hn, hd, ec)'
    if br:   # the object as the laws state it, O.Words{thaw(t), N} at t = freeze(the written-out array): syntactically the laws' own, so nothing is compared by evaluation
        OA = re.match(r'(\w+)\.Words\{', OBJ).group(1)
        OBJ_NEW = f'{OA}.Words{{{FDA}.array__thaw(U32, {FDA}.array__freeze(U32, {model.arr})), {model.n}}}'
        body.append(f'def dsome(+bs: +List<U32>, +n: U32, +hn: {{List.length(&2, U32, bs) == U32.to_nat(n) : Nat}}, +hd: {{SP_.bytes_domain(bs) == True{{}} : Bool}}, +ec: {{Nat.is_eq(List.length(&2, U32, bs), {K}n) == True{{}} : Bool}})\n'
                    f'    -> {{{DEC} == Some{{{OBJ_NEW}}} : {MT}}}:\n  {SOME}\n')
        OBJ, SOME = OBJ_NEW, 'dsome(bs, n, hn, hd, ec)'
    eqo = (f'Equal.cong({MT}, {OT}, z => gm(z, {OBJ}), Some{{o}}, Some{{{OBJ}}}, '
           f'Equal.trans({MT}, Some{{o}}, {DEC}, Some{{{OBJ}}}, Equal.sym({MT}, {DEC}, Some{{o}}, dec), {SOME}))')
    none = (f'{FDA}.logic__false_true(Equal.cong({MT}, Bool, z => isS(z), None{{}}, Some{{o}}, '
            f'Equal.trans({MT}, None{{}}, {DEC}, Some{{o}}, Equal.sym({MT}, {DEC}, None{{}}, {DB}.{name}_d_none(bs, n, hn, ec)), dec)))')
    if br:   # the tree of the written-out object, perfect at its depth (all computed)
        arr = model.arr
        T0 = f'{FDA}.array__freeze(U32, {arr})'
        ea = f'{T0}, {model.d}n, {{==}}, {{==}}, {{==}}'
        ra = ea
    else:
        ea = ', '.join(f'{prem[("e", b)]}(bs)' for _, b, _ in eps if b != 'o')
        ra = ', '.join(f'{prem[("r", b)]}(bs)' for _, b, _ in rps if b not in ('o', 'h'))
    XO, RO, VO = sub_o(X, OBJ), sub_o(R, OBJ), sub_o(V, OBJ)
    body += [f'def gm(m: {MT}, d: {OT}) -> {OT}:\n  match m:\n    case Some{{x}}: x\n    case None{{}}: d',
             f'def isS(m: {MT}) -> Bool:\n  match m:\n    case Some{{x}}: True{{}}\n    case None{{}}: False{{}}', '',
             f'# the value deserialize gives for the accepted bytes is the decoded object\'s view',
             f'def acc(+bs: +List<U32>, +n: U32, -o: {OT}, +hn: {{List.length(&2, U32, bs) == U32.to_nat(n) : Nat}}, +hd: {{SP_.bytes_domain(bs) == True{{}} : Bool}}, {dect})\n    -> {accT}:\n{acc_body}', '',
             f'def ge(+bs: +List<U32>, +n: U32, {omode}o: {OT}, +hn: {{List.length(&2, U32, bs) == U32.to_nat(n) : Nat}}, +hd: {{SP_.bytes_domain(bs) == True{{}} : Bool}}, {dect},\n'
             f'    +c: Bool, +ec: {ecT}) -> {{{X} == bs : +List<U32>}}:\n'
             f'  match c:\n    case True{{}}:\n'
             f'      %Equal.sym({OT}, o, {OBJ}, {eqo}) :\n        {{{sub_o(X, "_")} == bs : +List<U32>}}\n'
             f'      C.dec_enc({SPEC}, bs, {VO}, {XO}, acc(bs, n, {OBJ}, hn, hd, {SOME}), {EB}.{name}_e2e_encode({ea if br else OBJ + (", " + ea if ea else "")}))\n'
             f'    case False{{}}:\n      Empty.absurd({{{X} == bs : +List<U32>}}, {none})', '',
             f'def gr(h: B.Buf, +bs: +List<U32>, +n: U32, {omode}o: {OT}, +hn: {{List.length(&2, U32, bs) == U32.to_nat(n) : Nat}}, +hd: {{SP_.bytes_domain(bs) == True{{}} : Bool}}, {dect},\n'
             f'    +c: Bool, +ec: {ecT}) -> {{Some{{{R}}} == C.droot({SPEC}, bs) : Maybe<&2, +List<U32>>}}:\n'
             f'  match c:\n    case True{{}}:\n'
             f'      %Equal.sym({OT}, o, {OBJ}, {eqo}) :\n        {{Some{{{sub_o(R, "_")}}} == C.droot({SPEC}, bs) : Maybe<&2, +List<U32>>}}\n'
             f'      C.dec_root({SPEC}, bs, {VO}, {RO}, acc(bs, n, {OBJ}, hn, hd, {SOME}), {RB}.{name}_e2e_root(h, {ra if br else OBJ + (", " + ra if ra else "")}))\n'
             f'    case False{{}}:\n      Empty.absurd({{Some{{{R}}} == C.droot({SPEC}, bs) : Maybe<&2, +List<U32>>}}, {none})', '',
             f'# (i) after (ii): the decoded object re-encodes to exactly the input bytes',
             f'def {name}_e2e_decode_encode(+bs: +List<U32>, +n: U32, {omode}o: {OT}, +hn: {{List.length(&2, U32, bs) == U32.to_nat(n) : Nat}}, +hd: {{SP_.bytes_domain(bs) == True{{}} : Bool}}, {dect})\n'
             f'    -> {{{X} == bs : +List<U32>}}:\n  ge(bs, n, o, hn, hd, dec, Nat.is_eq(List.length(&2, U32, bs), {K}n), {{==}})', '',
             f'# (iv) after (ii): the decoded object\'s root is the spec root of the value deserialize gives for the input bytes',
             f'def {name}_e2e_decode_root(h: B.Buf, +bs: +List<U32>, +n: U32, {omode}o: {OT}, +hn: {{List.length(&2, U32, bs) == U32.to_nat(n) : Nat}}, +hd: {{SP_.bytes_domain(bs) == True{{}} : Bool}}, {dect})\n'
             f'    -> {{Some{{{R}}} == C.droot({SPEC}, bs) : Maybe<&2, +List<U32>>}}:\n  gr(h, bs, n, o, hn, hd, dec, Nat.is_eq(List.length(&2, U32, bs), {K}n), {{==}})', '']
    SPA = ctx.alias(ROOT / 'spec/primitives.bend')
    body = [l.replace('SP_.', SPA + '.') for l in body]
    return finish(ctx, body), None


def outputs():
    lf = law_files()
    names = sorted({re.sub(r'_e2e_\w+$', '', l) for l in lf if l.endswith('_e2e_encode')})
    outs = {E2E / 'e2e_comp.bend': SUPPORT}
    if EXT is not None and hasattr(EXT, 'outputs'):
        outs.update(EXT.outputs())
    EXTRA.clear()
    rows = []
    for n in names:
        t, why = build(n, lf)
        if t and 'WT.len_isq' in t and 'e2e_wit.bend as WT' not in t:   # the length facts of the written-out tree
            t = t.replace('import Base\n', 'import Base\nimport ./e2e_wit.bend as WT\n', 1)
        if t:
            outs[E2E / f'{n}_e2e_comp_generated.bend'] = t
            rows.append(f'{n}\tcomposed')
        else:
            rows.append(f'{n}\tpending: {why}')
    outs.update(EXTRA)
    done = sum(1 for r in rows if r.endswith('\tcomposed'))
    outs[E2E / 'COMPOSED.txt'] = (f'# GENERATED by codegen/proofs/composed/e2e_compose.py. Do not edit.\n# {done} of {len(names)} names have their composed '
                                  f'decode;encode and decode;root theorems (e2e/<Name>_e2e_comp_generated.bend)\n' + '\n'.join(rows) + '\n')
    return outs


def main():
    check = '--check' in sys.argv
    outs = outputs()
    stale = [p.name for p, t in outs.items() if not p.exists() or p.read_text() != t]
    have = {p.name for p in E2E.glob('*_e2e_comp_generated.bend')} | {p.name for p in E2E.glob('*_e2e_decrep_generated.bend')}
    orphans = sorted(have - {p.name for p in outs})
    if check:
        if stale or orphans:
            print('stale: ' + ', '.join(stale + [o + ' (orphan)' for o in orphans]))
            sys.exit(1)
        print(f'e2e_compose: {len(outs)} files up to date')
        return
    for p, t in outs.items():
        if not p.exists() or p.read_text() != t:
            p.write_text(t)
    for o in orphans:
        (E2E / o).unlink()
    print(f'e2e_compose: wrote {len(stale)} of {len(outs)}')


if __name__ == '__main__':
    main()
