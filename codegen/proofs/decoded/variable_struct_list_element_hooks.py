def main():
    p = E2E / 'e2e_hkv.bend'
    t = text()
    if '--check' in sys.argv:
        if not p.exists() or p.read_text() != t:
            print('stale: ' + p.name)
            sys.exit(1)
        print('variable_struct_list_element_hooks: up to date')
        return
    if not p.exists() or p.read_text() != t:
        p.write_text(t)
    print('variable_struct_list_element_hooks: 1 file')


if __name__ == '__main__':
    main()
