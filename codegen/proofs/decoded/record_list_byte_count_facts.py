#!/usr/bin/env python3
"""Generates e2e/e2e_drq.bend: the record lists' byte counts against their windows. WLL (the encode records' byte count of a
decoded record list) is the records times the record size: wq_<list>; eq_<list>(window): the window's length is WLL of its
list (from e2e_drl's ln). rq: the execution requests window's 12 fixed bytes and three lists add up to the window.

Usage: python3 codegen/proofs/decoded/record_list_byte_count_facts.py [--check]"""
import sys as _sys
import pathlib as _pathlib
_sys.path.insert(0, str(_pathlib.Path(__file__).resolve().parents[3]))  # the repository root: `codegen` is importable when this file runs as a script
import sys

from codegen.core.repository_paths import ROOT  # noqa: E402
OUT = ROOT / 'e2e' / 'e2e_drq.bend'

LISTS = [('VE', 'l16_SignedVoluntaryExit', 112, 'Fulu_list_SignedVoluntaryExit_16_d', 'e2e_dl_l16_SignedVoluntaryExit'),
         ('BC', 'l16_SignedBLSToExecutionChange', 172, 'Fulu_list_SignedBLSToExecutionChange_16_d', 'e2e_dl_l16_SignedBLSToExecutionChange'),
         ('DQ0', 'l8192_DepositRequest', 192, 'Fulu_list_DepositRequest_8192_d', 'e2e_dl_l8192_DepositRequest'),
         ('DQ1', 'l16_WithdrawalRequest', 76, 'Fulu_list_WithdrawalRequest_16_d', 'e2e_dl_l16_WithdrawalRequest'),
         ('DQ2', 'l2_ConsolidationRequest', 116, 'Fulu_list_ConsolidationRequest_2_d', 'e2e_dl_l2_ConsolidationRequest')]
TPW = '+t: FD.array__Tree<U32>, +x: Nat, +off: U32, +n: U32'
HC = '+hchk: {W.CHKw(t, x, off, n) == True{} : Bool}'
TN = lambda e: f'U32.to_nat({e})'


def _sz(args, first):
    s = first
    for a in args:
        s = f'Nat.add({s}, {a})'
    return s


def text():
    out = ['import Base', 'import ../proofs/compact/found.bend as FD', 'import ../proofs/compact/arith.bend as A', 'import ../proofs/obj/vbuf.bend as VB',
           'import ../proofs/obj/root_types_light.bend as RT', 'import ../proofs/obj/var_winx_ExecutionRequests.bend as W', 'import ./e2e_dep.bend as DEP']
    for al, stem, esz, seqm, dl in LISTS:
        out.append(f'import ./{dl}.bend as {al}')
        out.append(f'import ./e2e_drl_{stem}.bend as R_{stem}')
        out.append(f'import ../proofs/obj/var_winx_{stem}.bend as V_{stem}')
        out.append(f'import ../types/{seqm[:-2]}_def_generated.bend as {seqm}')
    t = '\n'.join(out) + '\n'
    t += '\n# GENERATED by record_list_byte_count_facts (codegen). Do not edit.\n# The record lists\' encoded byte counts (WLL) against their windows, and the execution requests window\'s size.\n'
    for al, stem, esz, seqm, dl in LISTS:
        ST = f'{seqm}.{stem}_Seq'
        OB = f'V_{stem}.OBJw(d, t, x, off, len)'
        t += (f'\ndef wq_{stem}(w: {ST}) -> {{{al}.WLL(w) == Nat.mul(U32.to_nat(RT.xlen_o_{stem}(w)), {esz}n) : Nat}}:\n'
              f'  match w:\n    case {ST}{{arr, +nn}}: DEP.qmul(U32.to_nat(nn), {esz // 4}n)\n'
              f'\n# the window\'s length is the list\'s encoded byte count\n'
              f'def eq_{stem}(+d: Nat, +t: FD.array__Tree<U32>, +x: Nat, +off: U32, +len: U32, +hchk: {{V_{stem}.CHKw(t, x, off, len) == True{{}} : Bool}})\n'
              f'    -> {{U32.to_nat(len) == {al}.WLL({OB}) : Nat}}:\n'
              f'  Equal.sym(Nat, {al}.WLL({OB}), U32.to_nat(len), Equal.trans(Nat, {al}.WLL({OB}), '
              f'Nat.mul(U32.to_nat(RT.xlen_o_{stem}({OB})), {esz}n), U32.to_nat(len), wq_{stem}({OB}), R_{stem}.ln(d, t, x, off, len, hchk)))\n')
    O = lambda i: f'W.O{i}(t, x)' if i < 3 else 'n'
    L = lambda i: f'W.L{i}(t, x)' if i < 2 else 'W.L2(t, x, n)'
    for i in range(2):
        it = f'W.h{"C" if i == 0 else "D"}(t, x, off, n, hchk)'
        a, b = f'U32.is_le({O(i)}, {O(i + 1)})', f'U32.is_le({O(i + 1)}, n)'
        t += (f'def ord{i}({TPW}, {HC}) -> {{Nat.is_le({TN(O(i))}, {TN(O(i + 1))}) == True{{}} : Bool}}: DEP.u2n({O(i)}, {O(i + 1)}, FD.logic__and_left({a}, {b}, {it}))\n'
              f'def top{i}({TPW}, {HC}) -> {{Nat.is_le({TN(O(i + 1))}, U32.to_nat(n)) == True{{}} : Bool}}: DEP.u2n({O(i + 1)}, n, FD.logic__and_right({a}, {b}, {it}))\n')
    for i in range(3):
        ordi = f'ord{i}(t, x, off, n, hchk)' if i < 2 else 'top1(t, x, off, n, hchk)'
        t += (f'def lsum{i}({TPW}, {HC}) -> {{Nat.add({TN(O(i))}, {TN(L(i))}) == {TN(O(i + 1))} : Nat}}:\n'
              f'  Equal.trans(Nat, Nat.add({TN(O(i))}, {TN(L(i))}), Nat.add({TN(O(i))}, Nat.sub({TN(O(i + 1))}, {TN(O(i))})), {TN(O(i + 1))},\n'
              f'    Equal.cong(Nat, Nat, z => Nat.add({TN(O(i))}, z), {TN(L(i))}, Nat.sub({TN(O(i + 1))}, {TN(O(i))}), FD.u32__sub_nat({O(i + 1)}, {O(i)}, {ordi})),\n'
              f'    FD.nat__sub_add({TN(O(i + 1))}, {TN(O(i))}, {ordi}))\n')
    PJ = lambda k: f'RT.pj_ExecutionRequests_{k}(W.OBJw(d, t, x, off, n))'
    ts = [f'{LISTS[2 + k][0]}.WLL({PJ(k)})' for k in range(3)]
    stems = [LISTS[2 + k][1] for k in range(3)]
    XF = [('W.X0(t, x)', 'W.F0(off, t, x)'), ('W.X1(t, x)', 'W.F1(off, t, x)'), ('W.X2(t, x)', 'W.F2(off, t, x)')]
    ees = [f'eq_{stems[k]}(d, t, {XF[k][0]}, {XF[k][1]}, {L(k)}, W.h{"EFG"[k]}(t, x, off, n, hchk))' for k in range(3)]
    lens = [TN(L(i)) for i in range(3)]
    lines = []
    cur = list(ts)
    for k in range(3):
        hole = cur[:k] + ['_'] + cur[k + 1:]
        # ees[k]: len == WLL; rewrite WLL -> len in the goal: the proof is Equal.sym of it
        lines.append(f'  %{ees[k]} : {{{_sz(hole, "12n")} == U32.to_nat(n) : Nat}}')
        cur[k] = lens[k]
    e0 = f'Equal.cong(U32, Nat, z => U32.to_nat(z), {O(0)}, 12, FD.u32alg__eq_of({O(0)}, 12, W.hB(t, x, off, n, hchk)))'
    lines.append(f'  %{e0} : {{{_sz(lens, "_")} == U32.to_nat(n) : Nat}}')
    acc = TN(O(0))
    for k in range(3):
        lines.append(f'  %Equal.sym(Nat, Nat.add({acc}, {lens[k]}), {TN(O(k + 1))}, lsum{k}(t, x, off, n, hchk)) : {{{_sz(lens[k + 1:], "_")} == U32.to_nat(n) : Nat}}')
        acc = TN(O(k + 1))
    lines.append('  {==}')
    t += (f'\n# the 12 fixed bytes and the three lists\' encodings add up to the window\ndef rq(+d: Nat, {TPW}, {HC}) -> {{{_sz(ts, "12n")} == U32.to_nat(n) : Nat}}:\n' + '\n'.join(lines) + '\n')
    return t


def main():
    t = text()
    if '--check' in sys.argv:
        if not OUT.exists() or OUT.read_text() != t:
            print('stale: e2e/e2e_drq.bend')
            sys.exit(1)
        print('record_list_byte_count_facts: up to date')
        return
    OUT.write_text(t)
    print('record_list_byte_count_facts: wrote e2e/e2e_drq.bend')


if __name__ == '__main__':
    main()
