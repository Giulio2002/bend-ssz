def uintdom_lib():
    out = [UINT_HDR + '\n' + HEADER + '\n# The spec has no encoding of a value above its uint8 / uint16 range (API.serialize is None).\n', UINT_PRE]
    for w, lim in ((8, 255), (16, 65535)):
        dig = [8, 16, 24] if w == 8 else [16, 24]
        orig = {8: 'U32.and(U32.shrn(x, 8n), 255)', 16: 'U32.and(U32.shrn(x, 16n), 255)', 24: 'U32.shrn(x, 24n)'}
        ZS = 'SP.zero_suffix([' + ', '.join(orig[k] for k in dig) + '])'
        low = '[U32.and(x, 255)]' if w == 8 else '[U32.and(x, 255), U32.and(U32.shrn(x, 8n), 255)]'
        sch = 'Spec.uint8()' if w == 8 else 'GS.uint16()'
        V = 'S.UnsignedValue{P.UInt{x, 0, 0, 0, 0, 0, 0, 0}}'
        out.append(gen(w))
        out.append(
            f'def u{w}_enc(+x: U32, +z: {{{ZS} == False{{}} : Bool}}) -> {{Encoding.encoding_for_legal_type({sch}, {V}) == None{{}} : Maybe<&2, +List<U32>>}}:\n'
            f'  %Equal.sym(Maybe<&2, +List<U32>>, RR.basic_one({V}, S.Unsigned{{P.U{w}{{}}}}), SP.optional({ZS}, {low}), PBM.u{w}h(x, 0, 0, 0, 0, 0, 0, 0, PBM.zt0())) :\n'
            f'    {{Encoding.bytes(Encoding.one(_, Some{{{w // 8}n}})) == None{{}} : Maybe<&2, +List<U32>>}}\n'
            f'  %Equal.sym(Bool, {ZS}, False{{}}, z) : {{Encoding.bytes(Encoding.one(SP.optional(_, {low}), Some{{{w // 8}n}})) == None{{}} : Maybe<&2, +List<U32>>}}\n'
            f'  {{==}}')
        out.append(
            f'def u{w}_parts(+x: U32, +z: {{{ZS} == False{{}} : Bool}}) -> {{Encoding.parts({V}, S.Unsigned{{P.U{w}{{}}}}) == None{{}} : Maybe<&2, +List<S.Part>>}}:\n'
            f'  %Equal.sym(Maybe<&2, +List<U32>>, RR.basic_one({V}, S.Unsigned{{P.U{w}{{}}}}), SP.optional({ZS}, {low}), PBM.u{w}h(x, 0, 0, 0, 0, 0, 0, 0, PBM.zt0())) :\n'
            f'    {{Encoding.one(_, Some{{{w // 8}n}}) == None{{}} : Maybe<&2, +List<S.Part>>}}\n'
            f'  %Equal.sym(Bool, {ZS}, False{{}}, z) : {{Encoding.one(SP.optional(_, {low}), Some{{{w // 8}n}}) == None{{}} : Maybe<&2, +List<S.Part>>}}\n'
            f'  {{==}}')
        out.append(
            f'def u{w}_parts_none(+x: U32, +v: {{U32.is_le(x, {lim}) == False{{}} : Bool}}) -> {{Encoding.parts({V}, S.Unsigned{{P.U{w}{{}}}}) == None{{}} : Maybe<&2, +List<S.Part>>}}:\n'
            f'  u{w}_parts(x, uz{w}(x, v))')
        out.append(
            f'def u{w}_none(+x: U32, +v: {{U32.is_le(x, {lim}) == False{{}} : Bool}}) -> {{API.serialize({sch}, {V}) == None{{}} : Maybe<&2, +List<U32>>}}:\n'
            f'  Equal.trans(Maybe<&2, +List<U32>>, API.serialize({sch}, {V}), Encoding.encoding_for_legal_type({sch}, {V}), None{{}},\n'
            f'    E.serialize_legal({sch}, {V}, VS.public_sound({sch}, {{==}})), u{w}_enc(x, uz{w}(x, v)))')
    return '\n\n'.join(out) + '\n'
