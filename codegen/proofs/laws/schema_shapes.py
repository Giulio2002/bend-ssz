"""Emit proofs/obj/schema_shapes.bend: constructor tests, projections and
shape laws for types/schema.bend `Schema`.

For a constructor C with fields f1..fk this emits
  is_C(s) -> Bool                      True exactly on C{..}
  C_fj(s) -> T_j                       the field (a default elsewhere)
  C_shape(s, e: {is_C(s) == True}) : {s == C{C_f1(s), .., C_fk(s)}}
so a proof about a schema variable can expose its shape from a Bool fact that
the checker evaluates, without comparing the schema's (possibly large) sizes.

    python3 codegen/proofs/laws/schema_shapes.py [--check]
"""
import sys as _sys
import pathlib as _pathlib
_sys.path.insert(0, str(_pathlib.Path(__file__).resolve().parents[3]))  # the repository root: `codegen` is importable when this file runs as a script
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
OUT = ROOT / 'proofs/obj/schema_shapes.bend'

# (constructor, [(field, type, default)])
CTORS = [
    ('Boolean', []),
    ('Unsigned', [('width', 'P.Width', 'P.U8{}')]),
    ('ByteVector', [('length', 'Nat', '0n')]),
    ('ByteList', [('limit', 'Nat', '0n')]),
    ('BitVector', [('length', 'Nat', '0n')]),
    ('BitList', [('limit', 'Nat', '0n')]),
    ('Vector', [('element', 'S.Schema', 'S.Null{}'), ('length', 'Nat', '0n')]),
    ('ListOf', [('element', 'S.Schema', 'S.Null{}'), ('limit', 'Nat', '0n')]),
    ('Container', [('names', '+List<String>', '[]'), ('fields', 'S.Schema', 'S.Null{}')]),
    ('Union', [('options', 'S.Schema', 'S.Null{}')]),
    ('Null', []),
    ('Chain', [('head', 'S.Schema', 'S.Null{}'), ('tail', 'S.Schema', 'S.Null{}')]),
    ('End', []),
    ('Repeat', [('element', 'S.Schema', 'S.Null{}')]),
    ('Named', [('name', 'String', '""'), ('schema', 'S.Schema', 'S.Null{}')]),
    ('ProgressiveList', [('element', 'S.Schema', 'S.Null{}')]),
    ('ProgressiveBits', []),
    ('ProgressiveContainer', [('names', '+List<String>', '[]'), ('fields', 'S.Schema', 'S.Null{}'), ('active', '+List<Bool>', '[]')]),
    ('CompatibleUnion', [('selectors', '+List<U32>', '[]'), ('options', 'S.Schema', 'S.Null{}')]),
]

# The constructors a root law exposes; the others only appear as refuted cases.
EXPOSED = ['ByteVector', 'ByteList', 'BitVector', 'BitList', 'Vector', 'ListOf', 'Container',
           'Chain', 'End', 'Union', 'ProgressiveList', 'ProgressiveBits', 'ProgressiveContainer',
           'CompatibleUnion', 'Boolean', 'Unsigned']


def pat(c, fs, plus=False):
    if not fs:
        return f'S.{c}{{}}'
    return f'S.{c}{{' + ', '.join(('+' if plus else '') + f'x{i}' for i in range(len(fs))) + '}'


def emit():
    L = ['import Base', 'import ../../types/schema.bend as S', 'import ../../types/primitive.bend as P',
         'import ./mtree_defs.bend as MD', '',
         '# GENERATED by codegen/proofs/laws/schema_shapes.py. Do not edit.',
         '# Constructor tests, projections and shape laws for schemas (see the generator).', '']
    w = L.append
    for c, fs in CTORS:
        if c not in EXPOSED:
            continue
        w(f'def is_{c}(s: S.Schema) -> Bool:')
        w('  match s:')
        w(f'    case {pat(c, fs)}: True{{}}')
        w('    case _: False{}')
        w('')
        for j, (f, T, d) in enumerate(fs):
            w(f'def {c}_{f}(s: S.Schema) -> {T}:')
            w('  match s:')
            w(f'    case {pat(c, fs, True)}: x{j}')
            w(f'    case _: {d}')
            w('')
        proj = ', '.join(f'{c}_{f}(s)' for f, _, _ in fs)
        shape = f'S.{c}{{{proj}}}' if fs else f'S.{c}{{}}'
        w(f'law {c}_shape:')
        w('  for +s: S.Schema')
        w(f'  for +e: {{is_{c}(s) == True{{}} : Bool}}')
        w(f'  {{s == {shape} : S.Schema}}')
        w(f'def {c}_shape(s, e):')
        w('  match s:')
        for c2, fs2 in CTORS:
            p2 = pat(c2, fs2, True)
            if c2 == c:
                w(f'    case {p2}: {{==}}')
            else:
                q2 = pat(c2, fs2)
                inst = shape.replace('(s)', f'({q2})')
                w(f'    case {p2}: Empty.absurd({{{q2} == {inst} : S.Schema}}, MD.false_true(e))')
        w('')
    return '\n'.join(L) + '\n'


def main():
    text = emit()
    if '--check' in sys.argv:
        if OUT.read_text() != text:
            print(f'{OUT} is stale; run codegen/proofs/laws/schema_shapes.py')
            return 1
        return 0
    OUT.write_text(text)
    return 0


if __name__ == '__main__':
    sys.exit(main())
