"""Progressive-container root trees (codegen/proofs/laws/root_laws_generic.py writes
proofs/obj/pcont.bend with them).

A progressive container's runtime root (codegen/impl/generate.py
`emit_pcontainer_root`) is O.mix_len(hl, T, mask): T is a fixed tree of node
hashes over the active fields' digests, zero chunks (D.zero()) at the inactive
positions and zero-subtree constants (D.zconst(k)) where a whole subtree is
inactive or past the last slot; mask is the active bit vector as a number.

Per active pattern K this emits, over OPAQUE field digests x0.. and a symbolic
hash length hl (with hl == 64n):
  K_teq  T is prog_root.bend `pr` over the slot digests (fields and D.zero()):
         syntactically, once the zero-subtree constants that stand for inactive
         slots are rewritten to the zero subtrees `pr` builds (zs*: closed
         facts, one concrete hash each);
  K_mk   Progressive.merkleize(slots) == Some{D.bytes(T)}, by `pmerk` (pr_spec
         over a LIMIT_LEMMAS digest list, instantiated: the specification's tree
         over the concrete slots is never unfolded, which is what made a direct
         bytes-level proof of the 22-slot pattern take hours);
  K_ar   RR.active_root(active, chunks, [D.bytes(O.mix_len(hl, T, mask))]):
         the specification's rule for the container's root.
A per-shape law instantiates the x_i with the fields' digests.
"""

