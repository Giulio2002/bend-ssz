def segments(L):
    """generate.prog_segments: [(k, start, cap)] covering L slots."""
    out, k = [], 0
    while True:
        start = ((1 << (2 * k)) - 1) // 3
        cap = 1 << (2 * k)
        out.append((k, start, cap))
        if start + cap >= L:
            return out
        k += 1


def tree(active):
    """The runtime tree of generate.emit_pcontainer_root as nodes:
    ('x', j) field j, ('0',) D.zero(), ('z', lv) D.zconst(lv), ('n', a, b)."""
    L = len(active)
    slots, j = [], 0
    for b in active:
        if b:
            slots.append(j)
            j += 1
        else:
            slots.append(None)
    acc = ('0',)
    for k, start, cap in reversed(segments(L)):
        level = []
        for i in range(cap):
            idx = start + i
            level.append(('x', slots[idx]) if idx < L and slots[idx] is not None else ('Z', 0))
        lv = 0
        while len(level) > 1:
            nxt = []
            for i in range(0, len(level), 2):
                a, b = level[i], level[i + 1]
                if a[0] == 'Z' and b[0] == 'Z':
                    nxt.append(('Z', lv + 1))
                else:
                    nxt.append(('n', conc(a), conc(b)))
            level = nxt
            lv += 1
        acc = ('n', conc(acc), conc(level[0]))
    return conc(acc)


def pr_tree(active):
    """prog_root.bend `pr(L + 1, True, hl, 0, 0, L, Ls)` unfolded on the slot
    digests Ls (fields and D.zero()), with MD.rtree unfolded the same way."""
    L = len(active)
    slots, j = [], 0
    for b in active:
        if b:
            slots.append(('x', j))
            j += 1
        else:
            slots.append(('0',))

    def rt(d, inside, s):
        if not inside:
            return ('z0',) if d == 0 else ('z', d)
        if d == 0:
            return slots[s]
        h = 1 << (d - 1)
        return ('n', rt(d - 1, True, s), rt(d - 1, s + h < L, s + h))

    def pr(g, inside, dep, s):
        if g == 0 or not inside:
            return ('0',)
        P = 1 << dep
        return ('n', pr(g - 1, s + P < L, dep + 2, s + P), rt(dep, True, s))
    return pr(L + 1, True, 0, 0)


def diffs(t, q, path=()):
    """Positions where the runtime tree t holds a zero-subtree constant and the
    reference tree q a subtree of zero chunks: [(path, k, q)]."""
    if t == q or (t[0] in ('0', 'z0') and q[0] in ('0', 'z0')):
        return []
    if t[0] == 'n' and q[0] == 'n':
        return diffs(t[1], q[1], path + (1,)) + diffs(t[2], q[2], path + (2,))
    assert t[0] == 'z' and 'x' not in repr(q), (t, q)
    return [(path, t[1], q)]


def put(t, path, v):
    if not path:
        return v
    if path[0] == 1:
        return ('n', put(t[1], path[1:], v), t[2])
    return ('n', t[1], put(t[2], path[1:], v))


def hole_expr(t, xs):
    return expr(t, xs).replace('D.zconst(99n)', '_')


def conc(node):
    if node[0] == 'Z':
        return ('0',) if node[1] == 0 else ('z', node[1])
    return node


def expr(t, xs):
    if t[0] == 'x':
        return xs[t[1]]
    if t[0] == '0':
        return 'D.zero()'
    if t[0] == 'z0':
        return 'D.zconst(0n)'
    if t[0] == 'z':
        return f'D.zconst({t[1]}n)'
    return f'D.node(hl, {expr(t[1], xs)}, {expr(t[2], xs)})'



def key(active):
    return 'pc_' + ''.join('1' if a else '0' for a in active)


def mask(active):
    return sum(1 << i for i, b in enumerate(active) if b)


def act_term(active):
    return '[' + ', '.join('True{}' if a else 'False{}' for a in active) + ']'


def emit(active, w):
    K = key(active)
    n = sum(1 for a in active if a)
    xs = [f'x{i}' for i in range(n)]
    T = expr(tree(active), xs)
    ls, j = [], 0
    for a in active:
        if a:
            ls.append(xs[j])
            j += 1
        else:
            ls.append('D.zero()')
    Ls = '[' + ', '.join(ls) + ']'
    L = len(active)
    xa = ', '.join(f'+{x}: D.Digest' for x in xs)
    xc = ', '.join(xs)
    w(f'# ---- active {act_term(active)} ----')
    # the runtime tree is prog_root's `pr` over the slot digests: its zero-subtree
    # constants are the zero subtrees `pr` builds (zs_*, one concrete hash each
    # level), then prog_root.pr_spec gives the specification's progressive tree.
    rt, pt_ = tree(active), pr_tree(active)
    PRX = f'PR.pr(1n+{L}n, Nat.is_lt(0n, {L}n), hl, 0n, 0n, {L}n, {Ls})'
    w(f'def {K}_teq(+hl: Nat, +ehl: {{hl == 64n : Nat}}, {xa})')
    w(f'    -> {{{T} == {PRX} : D.Digest}}:')
    cur = rt
    for path, k, q in diffs(rt, pt_):
        ctx = hole_expr(put(cur, path, ('z', 99)), xs)
        S = expr(q, xs)
        ZS[S] = (k, ZS.get(S, (k, f'zs{len(ZS)}'))[1])
        zn = ZS[S][1]
        w(f'  %Equal.sym(D.Digest, D.zconst({k}n), {S}, Equal.sym(D.Digest, {S}, D.zconst({k}n), {zn}(hl, ehl))) :')
        w(f'    {{{ctx} == {PRX} : D.Digest}}')
        cur = put(cur, path, q)
    w('  {==}')
    dw = max(0, (L - 1).bit_length())
    w(f'def {K}_mk(+hl: Nat, +ehl: {{hl == 64n : Nat}}, {xa})')
    w(f'    -> {{PS.merkleize(MD.bytes_list({Ls})) == Some{{D.bytes({T})}} : Maybe<&2, +List<U32>>}}:')
    w(f'  %Equal.sym(D.Digest, {T}, {PRX}, {K}_teq(hl, ehl, {xc})) :')
    w(f'    {{PS.merkleize(MD.bytes_list({Ls})) == Some{{D.bytes(_)}} : Maybe<&2, +List<U32>>}}')
    w(f'  pmerk(hl, ehl, {L}n, {Ls}, {dw}n, {{==}}, {{==}}, {{==}})')
    A = act_term(active)
    LB = f'List.append(&2, U32, Bp.pack({A}), SP.zero_bytes(Nat.sub(32n, List.length(&2, U32, Bp.pack({A})))))'
    placed = 'Unit{}'
    for _ in active:
        placed = f'({{==}}, {placed})'
    w(f'def {K}_ar(+hl: Nat, +ehl: {{hl == 64n : Nat}}, {xa})')
    w(f'    -> RR.active_root({A}, MD.bytes_list([{xc}]), [D.bytes(O.mix_len(hl, {T}, {mask(active)}))]):')
    w(f'  (MD.bytes_list({Ls}), ({placed}, (D.bytes({T}),')
    w(f'    ({K}_mk(hl, ehl, {xc}), ml(hl, ehl, {T}, {mask(active)}, {LB}, {{==}})))))')
    w('')


def emit_msel(k, w):
    """A union's selector mixed into an option's root (spec/mixing.bend)."""
    w(f'def msel_{k}(+hl: Nat, +ehl: {{hl == 64n : Nat}}, +r: D.Digest) -> RR.single(Mx.mix_in_selector(D.bytes(r), {k}), [D.bytes(O.mix_len(hl, r, {k}))]):')
    w('  %Equal.sym(Bool, SP.byte_scope(32n, D.bytes(r)), True{}, SN.digest_scope(r)) :')
    w(f'    {{Mx.selector_checked(Bool.and(_, U32.is_lt({k}, 256)), D.bytes(r), {k}) == Some{{D.bytes(D.node(hl, r, O.len_chunk({k})))}} : Maybe<&2, +List<U32>>}}')
    w(f'  %Equal.sym(+List<U32>, D.bytes(D.node(hl, r, O.len_chunk({k}))), VF.sha256_bytes(List.append(&2, U32, D.bytes(r), D.bytes(O.len_chunk({k})))), SN.node_at(hl, ehl, r, O.len_chunk({k}))) :')
    w(f'    {{Mx.selector_checked(True{{}}, D.bytes(r), {k}) == Some{{_}} : Maybe<&2, +List<U32>>}}')
    w('  {==}')
    w('')


def emit_file(patterns, selectors=()):
    L = list(HEAD)
    L.append(LEMMAS)
    L.append('def zc0() -> {D.zconst(0n) == D.zero() : D.Digest}: {==}')
    L.append('')
    for k in sorted(set(selectors)):
        emit_msel(k, L.append)
    ZS.clear()
    body = []
    seen = set()
    for a in patterns:
        a = tuple(a)
        if a in seen:
            continue
        seen.add(a)
        emit(a, body.append)
    L.append('# Zero subtrees built from zero chunks are the zero-subtree constants (a')
    L.append('# closed fact: the hash length is 64 and every digest is known).')
    for S, (k, zn) in ZS.items():
        L.append(f'def {zn}(+hl: Nat, +ehl: {{hl == 64n : Nat}}) -> {{{S} == D.zconst({k}n) : D.Digest}}:')
        L.append(f'  %Equal.sym(Nat, hl, 64n, ehl) : {{{S.replace("D.node(hl,", "D.node(_,")} == D.zconst({k}n) : D.Digest}}')
        if S == 'D.node(hl, D.zero(), D.zero())':
            # digest_facts.zero_node (the fast zero-subtree table of zero_roots, already in this
            # module's import closure through mtree_spec): evaluating the node ran SHA-256 (3.9 s)
            L.append('  %zc0() : {D.node(64n, _, D.zero()) == D.zconst(1n) : D.Digest}')
            L.append('  %zc0() : {D.node(64n, D.zconst(0n), _) == D.zconst(1n) : D.Digest}')
            L.append('  DF.zero_node(0n, {==})')
        else:
            L.append('  {==}')
    L.append('')
    return '\n'.join(L + body) + '\n'


