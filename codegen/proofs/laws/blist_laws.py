def and_lets(conj, ind='  '):
    """let-bind the conjuncts of fold(conj) from `ok`: c0 .. c{n-1}."""
    out = []
    prev = 'ok'

    def fold(cs):
        t = cs[-1]
        for c in reversed(cs[:-1]):
            t = f'Bool.and({c}, {t})'
        return t
    for j in range(len(conj) - 1):
        rest = fold(conj[j + 1:])
        out.append(f'{ind}+c{j} = DK.and_l({conj[j]}, {rest}, {prev})')
        if j == len(conj) - 2:
            out.append(f'{ind}+c{j + 1} = DK.and_r({conj[j]}, {rest}, {prev})')
        else:
            out.append(f'{ind}+k{j + 1} = DK.and_r({conj[j]}, {rest}, {prev})')
            prev = f'k{j + 1}'
    return out, fold(conj)


