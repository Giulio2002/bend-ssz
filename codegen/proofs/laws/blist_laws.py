    w('      (+eo, +w4) = w3')
    w(f'      %Equal.sym(O.Words, o, {W_}, eo) : RR.roots(hview(_), {SCH}, [D.bytes(bdig(hl, _, depth, 5n))])')
    w('      lh_core(hl, ehl, t, N, L, depth, eq_nh(o, t, N, eo, eN), lenh(o, t, N, L, eo, hv), hmin, hdep)')
    w('    case Inr{w}:')
    w('      (+t, w1) = w')
    w('      (+dw, w2) = w1')
    w('      (+N, w3) = w2')
    w('      (+q, w4) = w3')
    w('      (+r, w5) = w4')
    w('      (+eo, +w6) = w5')
    w(f'      %Equal.sym(O.Words, o, {W_}, eo) : RR.roots(hview(_), {SCH}, [D.bytes(bdig(hl, _, depth, 5n))])')
    w('      lh_core(hl, ehl, t, N, L, depth, eq_nh(o, t, N, eo, eN), lenh(o, t, N, L, eo, hv), hmin, hdep)')
    w('')
    w('# A list of Bytes32: its digest is a specification root of its elements.')
    w('def lh_rs(+hl: Nat, +ehl: {hl == 64n : Nat}, -h: B.Buf, -o: O.Words, +s: S.Schema, +depth: Nat, +dU: U32, +seg: U32,')
