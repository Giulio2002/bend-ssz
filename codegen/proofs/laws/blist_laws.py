    w(f'  %MR.clist_len({c}, {SL}, 0n) :')
    w(f'    RR.roots(S.Sequence{{WR.items({c}, {SL}, 0n)}}, {SCH}, [D.bytes(O.mix_len(hl, MD.rtree(depth, Nat.is_lt(0n, _), hl, {Lc}, 0n), U32.shrn(N, 5n)))])')
    hlen = f'UL.rw_le_l({c}, MD.dlen({Lc}), L, Equal.sym(Nat, MD.dlen({Lc}), {c}, MR.clist_len({c}, {SL}, 0n)), hvN)'
    w(f'  (MD.bytes_list({Lc}), (WR.items_roots({c}, {SL}, 0n), (D.bytes({R}),')
