def bytes32_kind(w):
    E = 'S.ByteVector{32n}'
    SCH = f'S.ListOf{{{E}, L}}'
    c = 'U32.to_nat(U32.shrn(N, 5n))'
    w('# ---- List[Bytes32] ' + '-' * 50)
    w('')
    w('def hview(o: O.Words) -> S.Value:')
    w('  match o:')
    w('    case O.Words{ws, +n}: S.Sequence{WR.items(U32.to_nat(U32.shrn(n, 5n)), F.array__slots(U32, F.array__freeze(U32, ws)), 0n)}')
    w('')
    w('# The object represents a value of the list schema s: byte storage of whole')
    w('# 32-byte elements, at most the limit of them.')
    w('def rep_lh(o: O.Words, +s: S.Schema) -> Data:')
    w('  DK.P2(LO.wfl(o), DK.P2({U32.to_nat(WO.len(o)) == WS.e32(cnth(o)) : Nat}, {Nat.is_le(cnth(o), SH.ListOf_limit(s)) == True{} : Bool}))')
    w('def rep_wfh(-o: O.Words, +s: S.Schema, +rep: rep_lh(o, s)) -> LO.wfl(o):')
    w('  (+wf, +r1) = rep')
    w('  wf')
    w('')
    conj = ['SH.is_ListOf(s)', 'SH.is_ByteVector(SH.ListOf_element(s))', 'Nat.is_eq(SH.ByteVector_length(SH.ListOf_element(s)), 32n)',
            'Lim.minimal(SH.ListOf_limit(s), depth)']
    lets, okt = and_lets(conj)
    w('# The schema is a list of Bytes32 whose limit has minimal depth `depth`.')
    w(f'def ok_lh(+s: S.Schema, +depth: Nat) -> Bool: {okt}')
    w('')
    w('def eq_nh(-o: O.Words, +t: F.array__Tree<U32>, +N: U32, +eo: {o == O.Words{F.array__thaw(U32, t), N} : O.Words},')
    w(f'    +eN: {{U32.to_nat(WO.len(o)) == WS.e32(cnth(o)) : Nat}}) -> {{U32.to_nat(N) == WS.e32({c}) : Nat}}:')
    w('  %Equal.cong(O.Words, U32, WO.len, o, O.Words{F.array__thaw(U32, t), N}, eo) : {U32.to_nat(_) == WS.e32(U32.to_nat(U32.shrn(_, 5n))) : Nat}')
    w('  eN')
    w('')
    w(f'def chq(+N: U32, +eNN: {{U32.to_nat(N) == WS.e32({c}) : Nat}}) -> {{O.chunks_of(N) == {c} : Nat}}:')
    w(f'  %Equal.sym(Nat, U32.to_nat(N), WS.e32({c}), eNN) : {{Nat.div(Nat.add(_, 31n), 32n) == {c} : Nat}}')
    w(f'  hdiv({c})')
    w('')
    # the core over the destructured object
    Lc = f'MR.clist({c}, {SL}, 0n)'
    R = f'MD.rtree(depth, Nat.is_lt(0n, MD.dlen({Lc})), hl, {Lc}, 0n)'
    w('def lh_core(+hl: Nat, +ehl: {hl == 64n : Nat}, +t: F.array__Tree<U32>, +N: U32, +L: Nat, +depth: Nat,')
    w(f'    +eNN: {{U32.to_nat(N) == WS.e32({c}) : Nat}},')
    w(f'    +hvN: {{Nat.is_le({c}, L) == True{{}} : Bool}},')
    w('    +hmin: {Lim.minimal(L, depth) == True{} : Bool},')
    w('    +hdep: {Nat.is_lt(depth, 64n) == True{} : Bool})')
    w(f'    -> RR.roots(hview({W_}), {SCH}, [D.bytes(bdig(hl, {W_}, depth, 5n))]):')
    w('  %Equal.sym(F.array__Tree<U32>, F.array__freeze(U32, F.array__thaw(U32, t)), t, F.array__freeze_thaw(U32, t)) :')
    w(f'    RR.roots(S.Sequence{{WR.items({c}, F.array__slots(U32, _), 0n)}}, {SCH}, [D.bytes(O.mix_len(hl, MD.rtree(depth, Nat.is_lt(0n, O.chunks_of(N)), hl, MR.clist(O.chunks_of(N), F.array__slots(U32, _), 0n), 0n), U32.shrn(N, 5n)))])')
    w(f'  %Equal.sym(Nat, O.chunks_of(N), {c}, chq(N, eNN)) :')
