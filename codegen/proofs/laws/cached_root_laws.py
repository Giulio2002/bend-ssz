def app_guard(name):
    types = RR.mono_text('fulu')
    m = re.search(rf'^def {name}_append\(.*\n.*\n.*_app_in\(U32\.is_le\(\(n \+ 1 : U32\), (\d+)\), arr, n, v\)', types, re.M)
    return m.group(1) if m else None


def elem_size(name, elem):
    types = RR.mono_text('fulu')
    m = re.search(rf'^def {name}_read\(.*U32\.div\(len, (\d+)\)', types, re.M)
    rd = re.search(rf'^def {name}_rd\((?:.*\n){{1,8}}?.*{elem}_read\(buf, \(off \+ \(i \+ 1 : U32\) \* (\d+) : U32\), (\d+)\)', types, re.M)
    if not m or not rd or not (m.group(1) == rd.group(1) == rd.group(2)):
        raise SystemExit(f'{name}: element read loop not in the expected form')
    return m.group(1)


def build_seq(name, elem, guard):
    return PSEQ.replace('@L', name).replace('@E', elem).replace('@G', guard).replace('@SZ', elem_size(name, elem))


def merge(a, b):
    """One file with a's and b's definitions (imports merged): the pair shares
    its expensive imports, so it is checked once."""
    la, lb = a.split('\n'), b.split('\n')
    ia = [l for l in la if l.startswith('import')]
    ib = [l for l in lb if l.startswith('import') and l not in ia]
    body_a = [l for l in la if not l.startswith('import')]
    body_b = [l for l in lb if not l.startswith('import') and not l.startswith('# GENERATED')]
    return '\n'.join(ia + ib + body_a + ['# ==== producers ' + '=' * 60] + body_b)


def spec_eq(name):
    rt = (OBJ / 'root_types.bend').read_text()
    m = re.search(rf'^def rs_{name}\(.*\+eq: (\{{SH\.ListOf_element\(s\) == .*? : S\.Schema\}})\)\s*$', rt, re.M)
    return m.group(1) if m else None


def build_spec(name, elem, depth, eq):
    return SPEC.replace('@EQ', eq).replace('@L', name).replace('@E', elem).replace('@D', str(depth))


def app_guard_cached(name):
    types = RR.mono_text('fulu')
    m = re.search(rf'^def {name}_capp\(.*\n.*\n.*_capp_in\(U32\.is_le\(\(n \+ 1 : U32\), (\d+)\), arr', types, re.M)
    if not m:
        raise SystemExit(f'{name}: capp guard not in the expected form')
    return m.group(1)


def targets():
    out, skipped = [], []
    for name, elem, depth in cached_lists():
        if name == T_LIST:
            continue
        (out if data_kind(elem) else skipped).append((name, elem, depth))
    return out, skipped


def main():
    out, skipped = targets()
    if '--status' in sys.argv:
        print(f'{T_LIST}: the checked instance')
        for name, elem, depth in out:
            link = 'with spec link' if spec_eq(name) else 'no uncached law to link'
            print(f'{name}: generated (element {elem}, depth {depth}; {link})')
        for name, elem, depth in skipped:
            print(f'{name}: not generated (element {elem} is a Type-kind name)')
        return 0
    stale = []
    for name, elem, depth in out:
        outs = [(OBJ / f'cached_{name}.bend', build(name, elem, depth))]
        eq = spec_eq(name)
        if eq:
            outs.append((OBJ / f'cspec_{name}.bend', build_spec(name, elem, depth, eq)))
            guard = app_guard(name)
            if guard is None:
                raise SystemExit(f'{name}: append guard not found')
            outs[-1] = (outs[-1][0], merge(outs[-1][1], build_seq(name, elem, guard)))
        outs = RR.rewire_out(outs)
        for path, text in outs:
            if '--check' in sys.argv:
                if not path.exists() or path.read_text() != text:
                    stale.append(str(path))
            else:
                if not path.exists() or path.read_text() != text:
                    path.write_text(text)
    if stale:
        print('stale: ' + ', '.join(stale))
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main())
