"""Generate the cached-root laws of every `_Cached` list whose elements are a
Data-kind name, from the checked BeaconState.validators instance.

The instance is proofs/obj/cloop.bend, cloop2.bend, cloop3.bend, cset.bend,
cmut.bend, capi.bend, cgrow.bend and chist.bend (list `l1099511627776_Validator`, element `Validator`, limit depth
40). The generated runtime code of every `_Cached` list is the same up to the
list's name, its element type and its limit depth (codegen/impl/typed_object_runtime.py), so
each other list's laws are the instance with those three substituted. They are
written into one file per list, proofs/obj/cached_<list>.bend, with the seven
parts' definitions side by side (their names do not collide). For the lists
whose uncached root law `rs_<list>` is in root_types.bend, the spec link is
written into proofs/obj/cspec_<list>.bend (template SPEC below): the cached
root's digest satisfies the independent relation RR.roots for the list's value,
and the same file (template PSEQ appended) proves that the list's public
producers (default, uncache, set, append) establish RT.rep_<list>, the root
law's hypothesis.

Elements that are Type-kind names (whose root law needs a representation
invariant per element: ProposerSlashing, AttesterSlashing, Attestation,
Deposit, bit lists) are not generated; `--status` lists them.

    python3 codegen/proofs/laws/cached_root_laws.py            # write the files
    python3 codegen/proofs/laws/cached_root_laws.py --check    # fail if a file is stale
    python3 codegen/proofs/laws/cached_root_laws.py --status
"""
