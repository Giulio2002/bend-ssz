SELF = {'./cloop.bend', './cloop2.bend', './cloop3.bend', './cset.bend', './cmut.bend', './capi.bend', './cgrow.bend'}
T_LIST, T_ELEM, T_DEPTH = 'l1099511627776_Validator', 'Validator', 40


def cached_lists():
    types = RR.mono_text('fulu')
    out = []
    for m in re.finditer(r"def (l\d+)_(\w+?)_croot_pad\(.*?\n  .*?Nat\.sub\((\d+)n, d\)", types):
        out.append((f'{m.group(1)}_{m.group(2)}', m.group(2), int(m.group(3))))
    return out


def data_kind(elem):
    rn = (OBJ / 'root_names.bend').read_text()
    return f'def st_{elem}(' in rn and f'def d_{elem}(' in rn


def build(name, elem, depth):
    imports, bodies = [], []
    for part in PARTS:
        # the instance modules import the runtime split; the template works on T.<sym> (RR.unwire), and the
        # output's T import is rewired again (main)
        lines = RR.unwire((OBJ / f'{part}.bend').read_text()).split('\n')
        i = 0
        while i < len(lines) and lines[i].startswith('import'):
            if RR.SPLIT_IMP.match(lines[i]):
                lines[i] = 'import ../../types/fulu_obj.bend as T'
            if lines[i].split()[1] not in SELF and lines[i] not in imports:
                imports.append(lines[i])
            i += 1
        body = '\n'.join(lines[i:]).strip('\n')
        if part in ('cloop3', 'capi', 'cgrow', 'chist'):
            body = body.replace(f'{T_DEPTH}n', f'{depth}n').replace(f'depth {T_DEPTH}', f'depth {depth}')
        bodies.append(f'# ==== from the instance {part}.bend ' + '=' * 40 + '\n\n' + body)
    aliases = {}
    for line in imports:
        path, alias = line.split()[1], line.split()[-1]
        if aliases.setdefault(alias, path) != path:
            raise SystemExit(f'import alias {alias} names two modules')
    text = '\n\n'.join(bodies)
    for alias in ('CL2.', 'CL.', 'L2.', 'L3.', 'CS.', 'CM.', 'CA.', 'CG.'):
        text = re.sub(r'(?<![A-Za-z0-9_])' + re.escape(alias), '', text)
    guard = app_guard_cached(name)
    text = text.replace('def guard(+n: U32) -> Bool: True{}', f'def guard(+n: U32) -> Bool: U32.is_le((n + 1 : U32), {guard})')
    text = text.replace(T_LIST, name)
    text = text.replace(f'T.{T_ELEM}_default()', f'T.{elem}_default()').replace(f'T.{T_ELEM}_root(', f'T.{elem}_root(')
    text = text.replace(f'RN.d_{T_ELEM}(', f'RN.d_{elem}(').replace(f'RN.st_{T_ELEM}(', f'RN.st_{elem}(')
    text = re.sub(rf'\bT\.{T_ELEM}\b', f'T.{elem}', text)
    text = text.replace('BeaconState.validators', f'the list {name}').replace(f'd_{T_ELEM}', f'd_{elem}')
    if re.search(rf'\b{T_ELEM}\b|_{T_ELEM}\b', text):
        bad = sorted(set(l.strip()[:80] for l in text.split('\n') if re.search(rf'\b{T_ELEM}\b|_{T_ELEM}\b', l)))
        raise SystemExit(f'{name}: instance names left after substitution: {bad[:5]}')
    head = imports + ['', f'# GENERATED by cached_root_laws (codegen) from the checked {T_LIST} instance. Do not edit.',
                      f'# The cached root of {name} (element {elem}, limit depth {depth}): see cloop*.bend,',
                      '# cset.bend, cmut.bend, capi.bend, cgrow.bend and chist.bend for the statements and their reading.', '']
    return '\n'.join(head) + '\n' + text + '\n'


