#!/usr/bin/env python3
"""Emit the root laws: every generated `X_hash_tree_root` against the
independent relational root specification (spec/root_relation.bend `roots`).

    python3 codegen/proofs/laws/root_laws.py [--check]

Outputs:
  proofs/obj/root_leaf.bend    leaves shared by every name (bytes of a chunk
                               word, bool, uint64, ...)

The rules that keep the checker from ever normalizing SHA-256 on a concretely
shaped message (see codegen/proofs/laws/sha_laws.py):
  * runtime roots are taken at an abstract message length `hl` (the public
    entry points pass 64n) and carry the equation `hl == 64n`;
  * the specification side only ever sees digests that are stuck on a
    variable (an object or a field), and objects are cased only in lemmas
    that hash nothing (chunking, byte views).
"""
