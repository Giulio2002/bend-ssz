# Per shape: the view (the specification value of an object), the digest
# (stuck on the object), the state law (the runtime root returns the hasher
# unchanged and that digest) and the spec law (the relational root of the view
# is the digest's bytes).

SCH = {}      # shape key -> spec schema term


class Skip(Exception):
    pass


def qual(rep):
    return LW.qual(rep)


def pattern(R, xs):
    return f'{R}{{' + ', '.join('+' + x for x in xs) + '}'


# Small unsigned leaves (uint8/16/32 held in a U32) as phase A shapes, with the
# representation fact of uint8/16 (the value is below 2^8 / 2^16). Enabled by
# the generic forms' generator only (codegen/proofs/laws/root_laws_generic.py): the Fulu
# names' leaves have their own laws (proofs/obj/leaf_small.bend).
EXTRA_LEAVES = False
# Partial-word bit vector records admitted as phase A shapes (generic only: the
# shape keys, and the emitter of their laws, set by root_laws_generic.py).
PARTIAL_OK = set()
PARTIAL_HOOK = None


def partial_bits(s):
    return s.kind == 'rec' and s.t.kind == 'bits' and s.t.size % 32 and s.p in PARTIAL_OK


SMALL = {'u8': ('P.U8{}', '256'), 'u16': ('P.U16{}', '65536'), 'u32': ('P.U32Width{}', None)}


def needs_rep(s):
    """The shape's root law needs a representation fact of its object."""
    if s.kind in ('u8', 'u16'):
        return True
    if partial_bits(s):
        return True
    if s.kind == 'container':
        return any(needs_rep(fs) for _, fs in s.fields)
    return False


def spec_schema(s):
    t, k = s.t, s.kind
    if k in SMALL and EXTRA_LEAVES:
        return f'S.Unsigned{{{SMALL[k][0]}}}'
    if k == 'bool':
        return 'S.Boolean{}'
    if k == 'u64':
        return 'S.Unsigned{P.U64{}}'
    if k == 'uwide':
        return {16: 'S.Unsigned{P.U128{}}', 32: 'S.Unsigned{P.U256{}}'}[t.size]
    if k == 'rec' and t.kind == 'bytes':
        return f'S.ByteVector{{{t.size}n}}'
    if k == 'rec' and t.kind == 'bits':
        return f'S.BitVector{{{t.size}n}}'
    if k == 'container' and t.kind == 'container':
        names = '[' + ', '.join(f'"{f}"' for f, _ in t.fields) + ']'
        chain = 'S.End{}'
        for _, fs in reversed(s.fields):
            chain = f'S.Chain{{{spec_schema(fs)}, {chain}}}'
        return f'S.Container{{{names}, {chain}}}'
    if k == 'container' and t.kind == 'pcontainer' and EXTRA_LEAVES:
        names = '[' + ', '.join(f'"{f}"' for f, _ in t.fields) + ']'
        chain = 'S.End{}'
        for _, fs in reversed(s.fields):
            chain = f'S.Chain{{{spec_schema(fs)}, {chain}}}'
        act = '[' + ', '.join('True{}' if a else 'False{}' for a in t.active) + ']'
        return f'S.ProgressiveContainer{{{names}, {chain}, {act}}}'
    raise Skip(f'kind {k}/{t.kind}')


LEAVES = ('bool', 'u64')


def covered(s):
    """Phase A: data shapes built from bool, uint64, uint128/256 and
    word-aligned byte records, in plain containers of at most 8 fields."""
    k, t = s.kind, s.t
    if k in LEAVES:
        return
    if k in SMALL and EXTRA_LEAVES:
        return
    if k == 'uwide':
        return
    if k == 'rec':
        if t.kind == 'bits':
            if t.size % 32 and not partial_bits(s):
                raise Skip('bit vector record of a partial word')
            return
        if t.size % 4:
            raise Skip('byte vector of a partial word')
        return
    if k == 'container':
        if t.kind != 'container' and not (t.kind == 'pcontainer' and EXTRA_LEAVES):
            raise Skip('progressive container')
        if not s.data:
            raise Skip('container held by pointer (Type kind)')
        if len(s.fields) > G.GROUP:
            raise Skip('wide container (field groups)')
        for f, fs in s.fields:
            if fs.kind == 'box':
                raise Skip(f'boxed field {f}')
            try:
                covered(fs)
            except Skip as e:
                raise Skip(f'field {f}: {e}')
        return
    raise Skip(f'kind {k}')


def emit_shape_laws(s, w):
    p, k, t = s.p, s.kind, s.t
    R = qual(s.rep)
    sch = spec_schema(s)
    if k in SMALL and EXTRA_LEAVES:
        wd, bound = SMALL[k]
        w(f'def v_{p}(o: U32) -> S.Value: S.UnsignedValue{{P.UInt{{o, 0, 0, 0, 0, 0, 0, 0}}}}')
        w(f'def d_{p}(+hl: Nat, o: U32) -> D.Digest: O.u32_chunk(o)')
        w(f'def st_{p}(+hl: Nat, -h: B.Buf, +o: U32, +seg: U32) -> {{T.{p}_root(hl, h, o, seg) == (h, d_{p}(hl, o)) : B.Buf & D.Digest}}: {{==}}')
        if bound is None:
            w(f'def rs_{p}(+hl: Nat, +ehl: {{hl == 64n : Nat}}, +o: U32) -> RR.roots(v_{p}(o), {sch}, [D.bytes(d_{p}(hl, o))]): LS.u32_root(o)')
            return
        w(f'def rp_{p}(+o: U32) -> Data: {{U32.is_lt(o, {bound}) == True{{}} : Bool}}')
        if k == 'u8':
            shape, lem, law = 'PD.embed8(WSp.take(8n, 32n, PD.bits(o)))', 'ID.byte_shape', 'LS.u8_w(WSp.take(8n, 32n, PD.bits(o)))'
        else:
            shape, lem, law = 'U32{WSp.join(16n, 16n, WSp.take(16n, 32n, PD.bits(o)), Word.zero(16n))}', 'GL.half_shape', 'GL.u16_w(WSp.take(16n, 32n, PD.bits(o)))'
        w(f'def rs_{p}(+hl: Nat, +ehl: {{hl == 64n : Nat}}, +o: U32, +rp: rp_{p}(o)) -> RR.roots(v_{p}(o), {sch}, [D.bytes(d_{p}(hl, o))]):')
        w(f'  %Equal.sym(U32, o, {shape}, {lem}(o, rp)) :')
        w(f'    RR.roots(S.UnsignedValue{{P.UInt{{_, 0, 0, 0, 0, 0, 0, 0}}}}, {sch}, [D.bytes(O.u32_chunk(_))])')
        w(f'  {law}')
        return
    if k == 'bool':
        w(f'def v_{p}(o: Bool) -> S.Value: S.BooleanValue{{o}}')
        w(f'def d_{p}(+hl: Nat, o: Bool) -> D.Digest: O.bool_chunk(o)')
        w(f'def st_{p}(+hl: Nat, -h: B.Buf, +o: Bool, +seg: U32) -> {{T.{p}_root(hl, h, o, seg) == (h, d_{p}(hl, o)) : B.Buf & D.Digest}}: {{==}}')
        w(f'def rs_{p}(+hl: Nat, +ehl: {{hl == 64n : Nat}}, +o: Bool) -> RR.roots(v_{p}(o), {sch}, [D.bytes(d_{p}(hl, o))]): RL.bool_root(o)')
        return
    if k == 'u64':
        w(f'def v_{p}(o: O.U64) -> S.Value: RL.view_u64(o)')
        w(f'def d_{p}(+hl: Nat, o: O.U64) -> D.Digest: O.u64_chunk(o)')
        w(f'def st_{p}(+hl: Nat, -h: B.Buf, +o: O.U64, +seg: U32) -> {{T.{p}_root(hl, h, o, seg) == (h, d_{p}(hl, o)) : B.Buf & D.Digest}}: {{==}}')
        w(f'def rs_{p}(+hl: Nat, +ehl: {{hl == 64n : Nat}}, +o: O.U64) -> RR.roots(v_{p}(o), {sch}, [D.bytes(d_{p}(hl, o))]): RL.u64_root(o)')
        return
    if partial_bits(s):
        PARTIAL_HOOK(s, w)
        return
    if k in ('rec', 'uwide'):
        nw, nb = s.nw, s.nbytes
        ws = [f'w{i}' for i in range(nw)]
        pat = pattern(R, ws)
        nc = G.chunks_of(nb)
        depth = G.log2ceil(nc)
        for c in range(nc):
            cw = ws[8 * c:8 * c + 8]
            dig = 'D.D{' + ', '.join([f'B.swap32({x})' for x in cw] + ['0'] * (8 - len(cw))) + '}'
            w(f'def c{c}_{p}(o: {R}) -> D.Digest:')
            w('  match o:')
            w(f'    case {pat}: {dig}')
        Lc = '[' + ', '.join(f'c{c}_{p}(o)' for c in range(nc)) + ']'
        w(f'def d_{p}(+hl: Nat, +o: {R}) -> D.Digest: MD.rtree({depth}n, True{{}}, hl, {Lc}, 0n)')
        w(f'def st_{p}(+hl: Nat, -h: B.Buf, +o: {R}, +seg: U32) -> {{T.{p}_root(hl, h, o, seg) == (h, d_{p}(hl, o)) : B.Buf & D.Digest}}:')
        w('  match o:')
        w(f'    case {pat}: {{==}}')
        if k == 'uwide':
            v = 'P.UInt{' + ', '.join(ws + ['0'] * (8 - nw)) + '}'
            wd = {16: 'P.U128{}', 32: 'P.U256{}'}[t.size]
            w(f'def v_{p}(o: {R}) -> S.Value:')
            w('  match o:')
            w(f'    case {pat}: S.UnsignedValue{{{v}}}')
            w(f'def rs_{p}(+hl: Nat, +ehl: {{hl == 64n : Nat}}, +o: {R}) -> RR.roots(v_{p}(o), {sch}, [D.bytes(d_{p}(hl, o))]):')
            w('  match o:')
            w(f'    case {pat}:')
            dig = 'D.D{' + ', '.join([f'B.swap32({x})' for x in ws] + ['0'] * (8 - nw)) + '}'
            w(f'      %IE.uint_hash_tree_root_correct({wd}, {v}) :')
            w(f'        {{_ == Some{{D.bytes({dig})}} : Maybe<&2, +List<U32>>}}')
            w(f'      %Equal.sym(+List<U32>, D.bytes({dig}), List.append(&2, U32, F.limbs([{", ".join(ws)}]), SP.zero_bytes({4 * (8 - nw)}n)), RL.bytes_{nw}({", ".join(ws)})) :')
            w(f'        {{I.uint_root({wd}, {v}) == Some{{_}} : Maybe<&2, +List<U32>>}}')
            w('      {==}')
            return
        # byte vector record (a bit vector record adds its bit view below)
        w(f'def vb_{p}(o: {R}) -> +List<U32>:')
        w('  match o:')
        w(f'    case {pat}: F.limbs([{", ".join(ws)}])')
        if t.kind != 'bits':
            w(f'def v_{p}(o: {R}) -> S.Value: S.BytesValue{{vb_{p}(o)}}')
        # chunks of the view
        w(f'def chunks_{p}(+o: {R}) -> {{Br.chunks(vb_{p}(o)) == MD.bytes_list({Lc}) : +List<+List<U32>>}}:')
        w('  match o:')
        w(f'    case {pat}:')
        for c in range(nc):
            cw = ws[8 * c:8 * c + 8]
            m = len(cw)
            done = [f'List.append(&2, U32, F.limbs([{", ".join(ws[8 * j:8 * j + 8])}]), SP.zero_bytes({4 * (8 - len(ws[8 * j:8 * j + 8]))}n))' for j in range(c)]
            rest = [f'D.bytes(c{j}_{p}({pat.replace("+", "")}))' for j in range(c + 1, nc)]
            lst = '[' + ', '.join(done + ['_'] + rest) + ']'
            dig = 'D.D{' + ', '.join([f'B.swap32({x})' for x in cw] + ['0'] * (8 - m)) + '}'
            w(f'      %Equal.sym(+List<U32>, D.bytes({dig}), List.append(&2, U32, F.limbs([{", ".join(cw)}]), SP.zero_bytes({4 * (8 - m)}n)), RL.bytes_{m}({", ".join(cw)})) :')
            w(f'        {{Br.chunks(F.limbs([{", ".join(ws)}])) == {lst} : +List<+List<U32>>}}')
        w('      {==}')
        w(f'def domain_{p}(+o: {R}) -> {{VD.bytevector_domain({nb}n, vb_{p}(o)) == True{{}} : Bool}}:')
        w('  match o:')
        w(f'    case {pat}: F.scope_limbs([{", ".join(ws)}])')
        if t.kind == 'bits':
            emit_bits_record(w, p, R, pat, ws, t.size, depth, Lc, sch)
            return
        # the two components as their own defs (rewrites need a statement position)
        body = [
            f'def rs_canon_{p}(+o: {R}) -> {{Br.canonical_depth(vb_{p}(o), {depth}n) == True{{}} : Bool}}:',
            f'  %Equal.sym(+List<+List<U32>>, Br.chunks(vb_{p}(o)), MD.bytes_list({Lc}), chunks_{p}(o)) :',
            f'    {{Lim.minimal(List.length(&2, +List<U32>, _), {depth}n) == True{{}} : Bool}}',
            '  {==}',
            f'def rs_gate_{p}(+hl: Nat, +ehl: {{hl == 64n : Nat}}, +o: {R}) -> {{RR.bytevector_at_depth({nb}n, {depth}n, vb_{p}(o)) == Some{{D.bytes(d_{p}(hl, o))}} : Maybe<&2, +List<U32>>}}:',
            f'  %Equal.sym(Bool, VD.bytevector_domain({nb}n, vb_{p}(o)), True{{}}, domain_{p}(o)) :',
            f'    {{Br.gate(_, {depth}n, vb_{p}(o)) == Some{{D.bytes(d_{p}(hl, o))}} : Maybe<&2, +List<U32>>}}',
            f'  %Equal.sym(+List<+List<U32>>, Br.chunks(vb_{p}(o)), MD.bytes_list({Lc}), chunks_{p}(o)) :',
            f'    {{Some{{Tr.tree({depth}n, _)}} == Some{{D.bytes(d_{p}(hl, o))}} : Maybe<&2, +List<U32>>}}',
            f'  %MS.rtree_spec({depth}n, True{{}}, hl, {Lc}, 0n, {{==}}, {{==}}, ehl) :',
            f'    {{Some{{_}} == Some{{D.bytes(d_{p}(hl, o))}} : Maybe<&2, +List<U32>>}}',
            '  {==}',
        ]
        for line in body:
            w(line)
        w(f'def rs_{p}(+hl: Nat, +ehl: {{hl == 64n : Nat}}, +o: {R}) -> RR.roots(v_{p}(o), {sch}, [D.bytes(d_{p}(hl, o))]):')
        w(f'  ({depth}n, (rs_canon_{p}(o), rs_gate_{p}(hl, ehl, o)))')
        return
    if k == 'container':
        F_ = s.fields
        n = len(F_)
        xs = [f'x{i}' for i in range(n)]
        pat = pattern(R, xs)
        depth = G.log2ceil(n)
        items = 'S.EmptyItems{}'
        for i in range(n - 1, -1, -1):
            items = f'S.Items{{v_{F_[i][1].p}({xs[i]}), {items}}}'
        w(f'def v_{p}(o: {R}) -> S.Value:')
        w('  match o:')
        w(f'    case {pat}: S.Sequence{{{items}}}')
        Ld = '[' + ', '.join(f'd_{fs.p}(hl, {xs[i]})' for i, (_, fs) in enumerate(F_)) + ']'
        prog = t.kind == 'pcontainer'
        w(f'def d_{p}(+hl: Nat, +o: {R}) -> D.Digest:')
        w('  match o:')
        if prog:
            from codegen.proofs.laws import pcont_laws as PCL
            dls = [f'd_{fs.p}(hl, {xs[i]})' for i, (_, fs) in enumerate(F_)]
            w(f'    case {pat}: O.mix_len(hl, {PCL.expr(PCL.tree(t.active), dls)}, {PCL.mask(t.active)})')
        else:
            w(f'    case {pat}: MD.rtree({depth}n, True{{}}, hl, {Ld}, 0n)')
        # state law: rewrite each stuck field root call in its step
        w(f'def st_{p}(+hl: Nat, -h: B.Buf, +o: {R}, +seg: U32) -> {{T.{p}_root(hl, h, o, seg) == (h, d_{p}(hl, o)) : B.Buf & D.Digest}}:')
        w('  match o:')
        w(f'    case {pat}:')
        rhs = f'(h, d_{p}(hl, {pat.replace("+", "")}))'
        for i, (f, fs) in enumerate(F_):
            if fs.kind in LEAVES or (EXTRA_LEAVES and fs.kind in SMALL):
                continue
            done = [f'd_{F_[j][1].p}(hl, {xs[j]})' for j in range(i)]
            args = ', '.join(['hl', 'seg'] + xs + done + ['_'])
            w(f'      %Equal.sym(B.Buf & D.Digest, T.{fs.p}_root(hl, h, {xs[i]}, seg), (h, d_{fs.p}(hl, {xs[i]})), st_{fs.p}(hl, h, {xs[i]}, seg)) :')
            w(f'        {{T.{p}_rt{i}({args}) == {rhs} : B.Buf & D.Digest}}')
        w('      {==}')
        # spec law (with the fields' representation facts when some field needs one)
        reps = [i for i, (_, fs) in enumerate(F_) if needs_rep(fs)]
        if reps:
            parts = [f'rp_{F_[i][1].p}({xs[i]})' for i in reps]
            ty = parts[-1]
            for q in reversed(parts[:-1]):
                ty = f'DK.P2({q}, {ty})'
            w(f'def rp_{p}(o: {R}) -> Data:')
            w('  match o:')
            w(f'    case {pat}: {ty}')
            w(f'def rs_{p}(+hl: Nat, +ehl: {{hl == 64n : Nat}}, +o: {R}, +rp: rp_{p}(o)) -> RR.roots(v_{p}(o), {sch}, [D.bytes(d_{p}(hl, o))]):')
        else:
            w(f'def rs_{p}(+hl: Nat, +ehl: {{hl == 64n : Nat}}, +o: {R}) -> RR.roots(v_{p}(o), {sch}, [D.bytes(d_{p}(hl, o))]):')
        w('  match o:')
        w(f'    case {pat}:')
        rpn = {}
        if reps:
            cur = 'rp'
            for j, i in enumerate(reps):
                if j == len(reps) - 1:
                    rpn[i] = cur
                else:
                    w(f'      (+r{i}, +k{i}) = {cur}')
                    rpn[i] = f'r{i}'
                    cur = f'k{i}'
        def items_proof(i):
            if i == n:
                return '{==}'
            rest = '[' + ', '.join(f'd_{F_[j][1].p}(hl, {xs[j]})' for j in range(i + 1, n)) + ']'
            call = f'rs_{F_[i][1].p}(hl, ehl, {xs[i]}' + (f', {rpn[i]})' if i in rpn else ')')
            return (f'([D.bytes(d_{F_[i][1].p}(hl, {xs[i]}))], (MD.bytes_list({rest}), '
                    f'({call}, ({items_proof(i + 1)}, {{==}}))))')
        w(f'      (MD.bytes_list({Ld}), ({items_proof(0)},')
        if prog:
            w(f'        PCN.{PCL.key(t.active)}_ar(hl, ehl, {", ".join(dls)})))')
        else:
            w(f'        RS.aggregate_digests({n}n, {depth}n, hl, {Ld}, {{==}}, {{==}}, {{==}}, ehl)))')
        return
    raise Skip(k)


def emit_bits_record(w, p, R, pat, ws, nbits, depth, Lc, sch):
    """The bit view of a bit vector record and its specification root."""
    q = pat.replace('+', '')
    bl = '[]'
    for x in reversed(ws):
        bl = f'List.append(&2, Bool, BL.wbits({x}), {bl})'
    w(f'def bits_{p}(o: {R}) -> +List<Bool>:')
    w('  match o:')
    w(f'    case {pat}: {bl}')
    w(f'def v_{p}(o: {R}) -> S.Value: S.BitsValue{{bits_{p}(o)}}')
    w(f'def packv_{p}(+o: {R}) -> {{Bp.pack(bits_{p}(o)) == vb_{p}(o) : +List<U32>}}:')
    w('  match o:')
    w(f'    case {pat}:')
    target = f'F.limbs([{", ".join(ws)}])'
    for i, x in enumerate(ws):
        rest = '[]'
        for y in reversed(ws[i + 1:]):
            rest = f'List.append(&2, Bool, BL.wbits({y}), {rest})'
        ctx = '_'
        for y in reversed(ws[:i]):
            ctx = f'List.append(&2, U32, I.limb({y}), {ctx})'
        w(f'      %Equal.sym(+List<U32>, Bp.pack(List.append(&2, Bool, BL.wbits({x}), {rest})), List.append(&2, U32, I.limb({x}), Bp.pack({rest})), BL.pack_word({x}, {rest})) :')
        w(f'        {{{ctx} == {target} : +List<U32>}}')
    w('      {==}')
    w(f'def blen_{p}(+o: {R}) -> {{List.length(&2, Bool, bits_{p}(o)) == {nbits}n : Nat}}:')
    w('  match o:')
    w(f'    case {pat}:')
    for i, x in enumerate(ws):
        rest = '[]'
        for y in reversed(ws[i + 1:]):
            rest = f'List.append(&2, Bool, BL.wbits({y}), {rest})'
        ctx = '_'
        for _ in range(i):
            ctx = f'Nat.add(32n, {ctx})'
        w(f'      %Equal.sym(Nat, List.length(&2, Bool, List.append(&2, Bool, BL.wbits({x}), {rest})), Nat.add(32n, List.length(&2, Bool, {rest})), BL.len_app_w({x}, {rest})) :')
        w(f'        {{{ctx} == {nbits}n : Nat}}')
    w('      {==}')
    w(f'def rs_gate_{p}(+hl: Nat, +ehl: {{hl == 64n : Nat}}, +o: {R}) -> {{Bits.bitvector_at_depth({nbits}n, {depth}n, bits_{p}(o)) == Some{{D.bytes(d_{p}(hl, o))}} : Maybe<&2, +List<U32>>}}:')
    w('  match o:')
    w(f'    case {pat}:')
    w(f'      %Equal.sym(Nat, List.length(&2, Bool, bits_{p}({q})), {nbits}n, blen_{p}({q})) :')
    w(f'        {{Bits.vector_gate(Bool.and(Nat.is_lt(0n, {nbits}n), Nat.is_eq(_, {nbits}n)), {nbits}n, {depth}n, bits_{p}({q})) == Some{{D.bytes(d_{p}(hl, {q}))}} : Maybe<&2, +List<U32>>}}')
    w(f'      %Equal.sym(+List<U32>, Bp.pack(bits_{p}({q})), vb_{p}({q}), packv_{p}({q})) :')
    w(f'        {{Lim.at_depth(Bits.chunk_limit({nbits}n), {depth}n, Pack.scan(_, 31n, [], [])) == Some{{D.bytes(d_{p}(hl, {q}))}} : Maybe<&2, +List<U32>>}}')
    w(f'      %Equal.sym(+List<+List<U32>>, Br.chunks(vb_{p}({q})), MD.bytes_list({Lc.replace("(o)", f"({q})")}), chunks_{p}({q})) :')
    w(f'        {{Lim.at_depth(Bits.chunk_limit({nbits}n), {depth}n, _) == Some{{D.bytes(d_{p}(hl, {q}))}} : Maybe<&2, +List<U32>>}}')
    Lq = Lc.replace('(o)', f'({q})')
    w(f'      %Equal.sym(Maybe<&2, +List<U32>>, Lim.at_depth(Bits.chunk_limit({nbits}n), {depth}n, MD.bytes_list({Lq})), Some{{D.bytes(MD.rtree({depth}n, Nat.is_lt(0n, MD.dlen({Lq})), hl, {Lq}, 0n))}}, RS.at_depth_tree(Bits.chunk_limit({nbits}n), {depth}n, hl, {Lq}, {{==}}, {{==}}, ehl)) :')
    w(f'        {{_ == Some{{D.bytes(d_{p}(hl, {q}))}} : Maybe<&2, +List<U32>>}}')
    w('      {==}')
    w(f'def rs_{p}(+hl: Nat, +ehl: {{hl == 64n : Nat}}, +o: {R}) -> RR.roots(v_{p}(o), {sch}, [D.bytes(d_{p}(hl, o))]):')
    w(f'  ({depth}n, ({{==}}, rs_gate_{p}(hl, ehl, o)))')


def emit_name_law(w, name, s):
    p = s.p
    R = qual(s.rep)
    rep = needs_rep(s) and EXTRA_LEAVES
    w(f'# {name}: the root of every {name} object' + (' (with its representation facts)' if rep else '') + ' is its specification root.')
    w(f'law {name}_root_correct:')
    w('  for -h: B.Buf')
    w(f'  for +o: {R}')
    if rep:
        w(f'  for +rp: rp_{p}(o)')
    w(f'  RR.roots(v_{p}(o), Spec.{name}(), [D.bytes(Pair.snd(B.Buf, D.Digest, T.{name}_hash_tree_root(h, o)))])')
    w(f'def {name}_root_correct(h, o{", rp" if rep else ""}):')
    w(f'  %Equal.sym(B.Buf & D.Digest, T.{p}_root(64n, h, o, 0), (h, d_{p}(64n, o)), st_{p}(64n, h, o, 0)) :')
    w(f'    RR.roots(v_{p}(o), Spec.{name}(), [D.bytes(Pair.snd(B.Buf, D.Digest, _))])')
    w(f'  rs_{p}(64n, {{==}}, o{", rp" if rep else ""})')
    w('')


def emit_decoded_law(w, name, s, node):
    """The root of the object the decoder builds from any valid encoding is
    the specification root of the value those bytes encode: `node.val` is the
    value spec_codec's `{name}_spec_encode` relates to the bytes limbs(words),
    `node.dec` the object spec_input's `{name}_spec_input` decodes them to.
    The decoded object stays abstract (`o`, with `e: o == dec`), so the root is
    never unfolded on concretely shaped words."""
    p = s.p
    R = qual(s.rep)
    sig = ', '.join(f'+{v}: U32' for v in node.words)
    args = ', '.join(node.words)
    w(f'def {name}_view_link({sig}) -> {{v_{p}({node.dec}) == {node.val} : S.Value}}: {{==}}')
    w(f'law {name}_decoded_root_correct:')
    for v in node.words:
        w(f'  for +{v}: U32')
    w('  for -h: B.Buf')
    w(f'  for +o: {R}')
    w(f'  for +e: {{o == {node.dec} : {R}}}')
    w(f'  RR.roots({node.val}, Spec.{name}(), [D.bytes(Pair.snd(B.Buf, D.Digest, T.{name}_hash_tree_root(h, o)))])')
    w(f'def {name}_decoded_root_correct({args}, h, o, e):')
    w(f'  %{name}_view_link({args}) : RR.roots(_, Spec.{name}(), [D.bytes(Pair.snd(B.Buf, D.Digest, T.{name}_hash_tree_root(h, o)))])')
    w(f'  %e : RR.roots(v_{p}(_), Spec.{name}(), [D.bytes(Pair.snd(B.Buf, D.Digest, T.{name}_hash_tree_root(h, o)))])')
    w(f'  {name}_root_correct(h, o)')
    w('')


