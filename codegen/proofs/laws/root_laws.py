SWAP_L = ['(U32.shrn(B.swap32(x), 24n) .&. 255 : U32)', '(U32.shrn(B.swap32(x), 16n) .&. 255 : U32)',
          '(U32.shrn(B.swap32(x), 8n) .&. 255 : U32)', '(B.swap32(x) .&. 255 : U32)']
SWAP_R = ['U32.and(x, 255)', 'U32.and(U32.shrn(x, 8n), 255)', 'U32.and(U32.shrn(x, 16n), 255)', 'U32.shrn(x, 24n)']


def sub(e, x):
    return e.replace('(x', f'({x}').replace('(B.swap32(x)', f'(B.swap32({x})').replace('B.swap32(x)', f'B.swap32({x})')


def emit_leaf():
    L = []
    w = L.append
    for line in ['import Base', 'import ../../src/buffer.bend as B', 'import ../../src/digest.bend as D',
                 'import ../../src/obj.bend as O', 'import ../../src/primitives.bend as I',
                 'import ../../types/schema.bend as S', 'import ../../types/primitive.bend as P',
                 'import ../../spec/root_relation.bend as RR', 'import ../../spec/primitives.bend as SP',
                 'import ../../proofs/compact/bits.bend as BT', 'import ../../proofs/integer_encoding.bend as IE',
                 'import ./spec_fixed.bend as F', '',
                 '# GENERATED by root_laws (codegen). Do not edit.',
                 '# Root laws of the leaves every name is built from.', '']:
        w(line)
    res = bitfix.load()
    for j in range(4):
        bitfix.emit(w, f'swap{j}', None, SWAP_L[j], SWAP_R[j], res[f'swap{j}'])
        w('')
    # bytes of one chunk word
    w('# The four big-endian bytes the SHA-256 message holds for a chunk word are')
    w('# the word\'s four little-endian bytes, which is what SSZ packs.')
    w('law bytes_swap:')
    w('  for +x: U32')
    w('  for +t: +List<U32>')
    w('  {D.be_bytes(B.swap32(x), t) == List.append(&2, U32, I.limb(x), t) : +List<U32>}')
    w('def bytes_swap(x, t):')
    cur = [sub(SWAP_L[j], 'x') for j in range(4)]
    for j in range(4):
        parts = cur[:j] + ['_'] + cur[j + 1:]
        lst = f'{parts[0]} <> ({parts[1]} <> ({parts[2]} <> ({parts[3]} <> t)))'
        w(f'  %Equal.sym(U32, {sub(SWAP_L[j], "x")}, {sub(SWAP_R[j], "x")}, swap{j}(x)) :')
        w(f'    {{{lst} == List.append(&2, U32, I.limb(x), t) : +List<U32>}}')
        cur[j] = sub(SWAP_R[j], 'x')
    w('  {==}')
    w('')
    # bool
    w('# boolean: the chunk of the value.')
    w('law bool_root:')
    w('  for +b: Bool')
    w('  RR.roots(S.BooleanValue{b}, S.Boolean{}, [D.bytes(O.bool_chunk(b))])')
    w('def bool_root(b):')
    w('  match b:')
    w('    case True{}: {==}')
    w('    case False{}: {==}')
    w('')
    # uint64
    w('def view_u64(o: O.U64) -> S.Value:')
    w('  match o:')
    w('    case O.U64{+lo, +hi}: S.UnsignedValue{P.UInt{lo, hi, 0, 0, 0, 0, 0, 0}}')
    w('')
    w('# uint64: the chunk of its two words.')
    w('law u64_root:')
    w('  for +o: O.U64')
    w('  RR.roots(view_u64(o), S.Unsigned{P.U64{}}, [D.bytes(O.u64_chunk(o))])')
    w('def u64_root(o):')
    w('  match o:')
    w('    case O.U64{+lo, +hi}:')
    v = 'P.UInt{lo, hi, 0, 0, 0, 0, 0, 0}'
    goal = lambda l, r: f'{{{l} == Some{{{r}}} : Maybe<&2, +List<U32>>}}'
    Z24 = 'D.be_bytes(0, D.be_bytes(0, D.be_bytes(0, D.be_bytes(0, D.be_bytes(0, D.be_bytes(0, []))))))'
    w(f'      %IE.uint_hash_tree_root_correct(P.U64{{}}, {v}) :')
    w(f'        {goal("_", f"D.be_bytes(B.swap32(lo), D.be_bytes(B.swap32(hi), {Z24}))")}')
    w(f'      %Equal.sym(+List<U32>, D.be_bytes(B.swap32(lo), D.be_bytes(B.swap32(hi), {Z24})), List.append(&2, U32, I.limb(lo), D.be_bytes(B.swap32(hi), {Z24})), bytes_swap(lo, D.be_bytes(B.swap32(hi), {Z24}))) :')
    w(f'        {goal(f"I.uint_root(P.U64{{}}, {v})", "_")}')
    w(f'      %Equal.sym(+List<U32>, D.be_bytes(B.swap32(hi), {Z24}), List.append(&2, U32, I.limb(hi), {Z24}), bytes_swap(hi, {Z24})) :')
    w(f'        {goal(f"I.uint_root(P.U64{{}}, {v})", "List.append(&2, U32, I.limb(lo), _)")}')
    w('      {==}')
    w('')
    emit_bytes_m(w)
    return '\n'.join(L) + '\n'


def emit_bytes_m(w):
    """bytes_m: the bytes of a chunk of m swapped words and 8 - m zero words."""
    for m in range(1, 9):
        ws = [f'w{i}' for i in range(m)]
        dig = 'D.D{' + ', '.join([f'B.swap32({x})' for x in ws] + ['0'] * (8 - m)) + '}'
        rhs = f'List.append(&2, U32, F.limbs([{", ".join(ws)}]), SP.zero_bytes({4 * (8 - m)}n))'
        w(f'law bytes_{m}:')
        for x in ws:
            w(f'  for +{x}: U32')
        w(f'  {{D.bytes({dig}) == {rhs} : +List<U32>}}')
        w(f'def bytes_{m}({", ".join(ws)}):')
        tail = '[]'
        for _ in range(8 - m):
            tail = f'D.be_bytes(0, {tail})'
        # rewrite the words front to back
        cur = [f'D.be_bytes(B.swap32({x}), _R_)' for x in ws]
        for i, x in enumerate(ws):
            # build the list with word i as the hole, earlier words already limbs
            def chain(i):
                t = tail
                for j in range(m - 1, -1, -1):
                    if j < i:
                        t = f'List.append(&2, U32, I.limb({ws[j]}), {t})'
                    elif j == i:
                        t = '_'
                        # everything after j is still swapped
                        inner = tail
                        for k in range(m - 1, i, -1):
                            inner = f'D.be_bytes(B.swap32({ws[k]}), {inner})'
                        hole_tail = inner
                    else:
                        t = f'D.be_bytes(B.swap32({ws[j]}), {t})'
                return t
            inner = tail
            for k in range(m - 1, i, -1):
                inner = f'D.be_bytes(B.swap32({ws[k]}), {inner})'
            ctx = '_'
            for j in range(i - 1, -1, -1):
                ctx = f'List.append(&2, U32, I.limb({ws[j]}), {ctx})'
            w(f'  %Equal.sym(+List<U32>, D.be_bytes(B.swap32({x}), {inner}), List.append(&2, U32, I.limb({x}), {inner}), bytes_swap({x}, {inner})) :')
            w(f'    {{{ctx} == {rhs} : +List<U32>}}')
        w('  {==}')
        w('')


