"""Emit proofs/obj/bitlist_pack.bend: the bits of a word list, cut at any
length k, pack (spec/bit_packing.bend `pack`) to the first ceil(k/8) bytes of
the words, provided the bits of the last byte past k are zero.

  bitsof(ws)      the bits of the words, least significant first (bits_leaf wbits)
  btk(k, xs)    the first k bits
  zt(ws, k)     the bits k .. 8*ceil(k/8) - 1 are zero
  bpack(k, ws)  Bp.pack(btk(k, bitsof(ws))) == WS.btake(Bp.byte_count(k), FX.limbs(ws))

The proof walks the words 32 bits at a time (bits_leaf `pack_word`); a cut
inside a word (k = 1 .. 31) is one generated lemma per k, over the word's 32
bits as Bool parameters: the bits that must be zero are cased (a set bit
contradicts zt), the partial octet is the byte (bits_leaf `oct8`, len_bridge
`byte0..3`).

    python3 codegen/proofs/laws/bitlist_laws.py [--check]
"""
import sys as _sys
import pathlib as _pathlib
_sys.path.insert(0, str(_pathlib.Path(__file__).resolve().parents[3]))  # the repository root: `codegen` is importable when this file runs as a script
import sys

from codegen.proofs.support import bitfix  # noqa: E402

from codegen.core.paths import ROOT  # noqa: E402
OUT = ROOT / 'proofs/obj/bitlist_pack.bend'
A = bitfix.BITS
LIMB = ['U32.and({W}, 255)', 'U32.and(U32.shrn({W}, 8n), 255)', 'U32.and(U32.shrn({W}, 16n), 255)', 'U32.shrn({W}, 24n)']


def bc(k):
    return (k + 7) // 8


def emit():
    L = ['import Base', 'import ../../src/primitives.bend as I', 'import ../../spec/bit_packing.bend as Bp',
         'import ./len_bridge.bend as LB', 'import ./bits_leaf.bend as BLf', 'import ./spec_fixed.bend as FX',
         'import ./words_spec.bend as WS', 'import ./mtree_defs.bend as MD', '',
         '# GENERATED by bitlist_laws (codegen). Do not edit.', '']
    w = L.append
    w('def bitsof(ws: +List<U32>) -> +List<Bool>:')
    w('  match ws:')
    w('    case Nil{}: []')
    w('    case Con{+x, rest}: List.append(&2, Bool, BLf.wbits(x), bitsof(rest))')
    w('')
    w('def btk(k: Nat, xs: +List<Bool>) -> +List<Bool>:')
    w('  match k:')
    w('    case 0n: []')
    w('    case 1n+p:')
    w('      match xs:')
    w('        case Nil{}: []')
    w('        case Con{+b, t}: b <> btk(p, t)')
    w('')
    # zero tests inside a word, as functions of the bits
    for k in range(1, 32):
        zs = list(range(k, 8 * bc(k)))
        w(f'def zb{k}({", ".join(f"+{a}: Bool" for a in A)}) -> Bool:')
        if not zs:
            w('  True{}')
        else:
            e = 'True{}'
            for j in reversed(zs):
                e = f'Bool.and(Bool.not(a{j}), {e})'
            w(f'  {e}')
    w('def zw(+k: Nat, +x: U32) -> Bool:')
    w('  match k:')
    w('    case 0n: True{}')
    for k in range(1, 32):
        w(f'    case {k}n:')
        w('      match x:')
        w(f'        case {bitfix.word(["+" + a for a in A])}: zb{k}({", ".join(A)})')
    w('    case 32n+p: True{}')
    w('')
    w('def zt(+ws: +List<U32>, +k: Nat) -> Bool:')
    w('  match ws:')
    w('    case Nil{}: True{}')
    w('    case Con{+x, rest}:')
    w('      match k:')
    for k in range(32):
        w(f'        case {k}n: zw({k}n, x)')
    w('        case 32n+p: zt(rest, p)')
    w('')
    # a whole word, then the rest
    Wd = bitfix.word(A)
    w('law btk_w:')
    w('  for +p: Nat')
    w('  for +x: U32')
    w('  for +r: +List<Bool>')
    w('  {btk(32n+p, List.append(&2, Bool, BLf.wbits(x), r)) == List.append(&2, Bool, BLf.wbits(x), btk(p, r)) : +List<Bool>}')
    w('def btk_w(p, x, r):')
    w('  match x:')
    w(f'    case {Wd}: {{==}}')
    w('')
    w('law btk_nil:')
    w('  for +k: Nat')
    w('  {btk(k, []) == [] : +List<Bool>}')
    w('def btk_nil(k):')
    w('  match k:')
    w('    case 0n: {==}')
    w('    case 1n+p: {==}')
    w('')
    w('law btake_nil:')
    w('  for +n: Nat')
    w('  {WS.btake(n, []) == [] : +List<U32>}')
    w('def btake_nil(n):')
    w('  match n:')
    w('    case 0n: {==}')
    w('    case 1n+p: {==}')
    w('')
    # a cut inside a word
    for k in range(1, 32):
        nb = bc(k)
        zs = list(range(k, 8 * nb))
        goal = (f'{{Bp.pack(btk({k}n, List.append(&2, Bool, BLf.wbits({Wd}), bitsof(rest)))) == '
                f'WS.btake(Bp.byte_count({k}n), List.append(&2, U32, I.limb({Wd}), FX.limbs(rest))) : +List<U32>}}')
        w(f'def cut{k}({", ".join(f"+{a}: Bool" for a in A)}, +rest: +List<U32>, +z: {{zb{k}({", ".join(A)}) == True{{}} : Bool}})')
        w(f'    -> {goal}:')
        ind = '  '

        def refined(done):
            return [('False{}' if (j in zs and j in done) else A[j]) for j in range(32)]

        def body(i, ind):
            if i < len(zs):
                j = zs[i]
                bits_now = refined(zs[:i])
                g = goal.replace(Wd, bitfix.word(bits_now))
                w(f'{ind}match a{j}:')
                w(f'{ind}  case True{{}}: Empty.absurd({g.replace(bitfix.word(bits_now), bitfix.word(bits_now[:j] + ["True{}"] + bits_now[j + 1:]))}, MD.false_true(z))')
                w(f'{ind}  case False{{}}:')
                body(i + 1, ind + '    ')
                return
            B = refined(zs)
            WB = bitfix.word(B)
            # the octets of the cut bits (pack pads the last one with False)
            cutb = B[:k] + ['False{}'] * (8 * nb - k)
            octs = [f'Bp.octet({", ".join(cutb[8 * m:8 * m + 8])})' for m in range(nb)]
            bytes_ = [bitfix.word(cutb[8 * m:8 * m + 8] + ['False{}'] * 24) for m in range(nb)]
            limbs = [LIMB[m].format(W=WB) for m in range(nb)]

            def show(l, r):
                return f'{{[{", ".join(l)}] == [{", ".join(r)}] : +List<U32>}}'
            lhs, rhs = list(octs), list(limbs)
            for m in range(nb):
                l2 = lhs[:m] + ['_'] + lhs[m + 1:]
                w(f'{ind}%Equal.sym(U32, {octs[m]}, {bytes_[m]}, BLf.oct8({", ".join(cutb[8 * m:8 * m + 8])})) :')
                w(f'{ind}  {show(l2, rhs)}')
                lhs[m] = bytes_[m]
            for m in range(nb):
                r2 = rhs[:m] + ['_'] + rhs[m + 1:]
                w(f'{ind}%Equal.sym(U32, {limbs[m]}, {bytes_[m]}, LB.byte{m}({", ".join(B)})) :')
                w(f'{ind}  {show(lhs, r2)}')
                rhs[m] = bytes_[m]
            w(f'{ind}{{==}}')
        body(0, ind)
        w('')
        goalx = (f'{{Bp.pack(btk({k}n, List.append(&2, Bool, BLf.wbits(x), bitsof(rest)))) == '
                 f'WS.btake(Bp.byte_count({k}n), List.append(&2, U32, I.limb(x), FX.limbs(rest))) : +List<U32>}}')
        w(f'def cutw{k}(+x: U32, +rest: +List<U32>, +z: {{zw({k}n, x) == True{{}} : Bool}}) -> {goalx}:')
        w('  match x:')
        w(f'    case {bitfix.word(["+" + a for a in A])}: cut{k}({", ".join(A)}, rest, z)')
        w('')
    # the word walk
    w('law bpack:')
    w('  for +ws: +List<U32>')
    w('  for +k: Nat')
    w('  for +z: {zt(ws, k) == True{} : Bool}')
    w('  {Bp.pack(btk(k, bitsof(ws))) == WS.btake(Bp.byte_count(k), FX.limbs(ws)) : +List<U32>}')
    w('def bpack(ws, k, z):')
    w('  match ws:')
    w('    case Nil{}:')
    w('      %Equal.sym(+List<Bool>, btk(k, []), [], btk_nil(k)) : {Bp.pack(_) == WS.btake(Bp.byte_count(k), []) : +List<U32>}')
    w('      %Equal.sym(+List<U32>, WS.btake(Bp.byte_count(k), []), [], btake_nil(Bp.byte_count(k))) : {Bp.pack([]) == _ : +List<U32>}')
    w('      {==}')
    w('    case Con{+x, +rest}:')
    w('      match k:')
    w('        case 0n: {==}')
    for k in range(1, 32):
        w(f'        case {k}n: cutw{k}(x, rest, z)')
    w('        case 32n+p:')
    w('          %Equal.sym(+List<Bool>, btk(32n+p, List.append(&2, Bool, BLf.wbits(x), bitsof(rest))), List.append(&2, Bool, BLf.wbits(x), btk(p, bitsof(rest))), btk_w(p, x, bitsof(rest))) :')
    w('            {Bp.pack(_) == WS.btake(Bp.byte_count(32n+p), List.append(&2, U32, I.limb(x), FX.limbs(rest))) : +List<U32>}')
    w('          %Equal.sym(+List<U32>, Bp.pack(List.append(&2, Bool, BLf.wbits(x), btk(p, bitsof(rest)))), List.append(&2, U32, I.limb(x), Bp.pack(btk(p, bitsof(rest)))), BLf.pack_word(x, btk(p, bitsof(rest)))) :')
    w('            {_ == WS.btake(Bp.byte_count(32n+p), List.append(&2, U32, I.limb(x), FX.limbs(rest))) : +List<U32>}')
    w('          %Equal.sym(+List<U32>, Bp.pack(btk(p, bitsof(rest))), WS.btake(Bp.byte_count(p), FX.limbs(rest)), bpack(rest, p, z)) :')
    w('            {List.append(&2, U32, I.limb(x), _) == WS.btake(Bp.byte_count(32n+p), List.append(&2, U32, I.limb(x), FX.limbs(rest))) : +List<U32>}')
    w('          {==}')
    return '\n'.join(L) + '\n'


def main():
    text = emit()
    if '--check' in sys.argv:
        if OUT.read_text() != text:
            print(f'{OUT} is stale; run codegen/proofs/laws/bitlist_laws.py')
            return 1
        print('bitlist laws are current')
        return 0
    OUT.write_text(text)
    return 0


if __name__ == '__main__':
    sys.exit(main())
