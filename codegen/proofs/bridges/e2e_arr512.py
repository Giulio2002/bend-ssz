def build(amap, readable):
    """readable: generated name -> manifest name R"""
    files, cover = {}, {}
    for X in NAMES + NAMES513:
        if X not in amap['map']:
            continue
        i = info(X, amap) if X in NAMES else info513(X, amap)
        if not i:
            continue
        R = readable.get(X, X)
        fn = f'{R}_e2e_dec_generated.bend'
        files[fn] = bridge_text(X, i) if X in NAMES else bridge513_text(X, i)
        cover[R] = (fn, [f'{R}_e2e_decode_view', f'{R}_e2e_decode_reject'])
    support = {'e2e_vw512.bend': support_text() + support513_text()} if files else {}
    return support, files, cover


