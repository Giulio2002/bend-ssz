#!/usr/bin/env python3
"""Premise-satisfiability witnesses of the collection statements (proofs/obj/coll_api_*.bend, coll_root.bend): for every
`<coll>_api_<law>` with premises, e2e/<coll>_api_witness_generated.bend applies the law to a concrete object of its
collection and proves every premise of it by computation, so a law whose premises no object meets cannot hide.

  <stmt>_witness() : the law's conclusion at the concrete arguments  =  <stmt>(arguments, proofs of the premises)

The concrete object: a perfect tree of depth 6 of zeros (F.array__trep, the default element for record lists), a
size of up to four elements (n = K * min(4, limit), K the element size in bytes), the index 0 (1 and 0 for a pair of
distinct indices), a growth from the empty collection for an append. The Nat witnesses of the `hq`-style premises
({E == q}) are the expression E itself.

    python3 codegen/proofs/witnesses/coll_witness.py [--check] [--only A,B]
"""
import sys as _sys
import pathlib as _pathlib
_sys.path.insert(0, str(_pathlib.Path(__file__).resolve().parents[3]))  # the repository root: `codegen` is importable when this file runs as a script
import glob
import re
import sys
from pathlib import Path

from codegen.proofs.witnesses import e2e_witness as W  # noqa: E402

ROOT = W.ROOT
E2E = W.E2E
HEADER = '# GENERATED by coll_witness (codegen). Do not edit.'
DEPTH = 6

# statements whose premises cannot be met by an object built here, with the reason (listed in e2e/COLL_WITNESS.txt)
SKIP = {}


def Mod_text(pth):
    return W.Mod.get(pth).text


def split_param(p):
    name, _, ty = p.partition(':')
    return name.strip().lstrip('+-'), ty.strip(), p.strip().startswith('-')


def subst_vars(expr, env):
    def sub(m):
        v = m.group(0)
        return env[v] if v in env else v
    return re.sub(r'(?<![\w.])[A-Za-z_]\w*(?![\w.])', sub, expr)


def elem_default(ctx, mod, ty, name):
    """(element type text, default element expression) of an element type as written in mod"""
    ty = ty.strip()
    if ty == 'U32':
        return 'U32', '0'
    if ty == 'Bool':
        return 'Bool', 'True{}'
    OA = ctx.alias(ROOT / 'src/obj.bend')
    if ty == 'O.U64':
        return f'{OA}.U64', f'{OA}.U64{{0, 0}}'
    if ty == 'O.Words':
        return f'{OA}.Words', f'{OA}.words_new(0)'
    if ty == 'O.Bits':
        return f'{OA}.Bits', f'{OA}.bits_new(0)'
    m = re.match(r'^O\.Boxed<(.*)>$', ty)
    if m:
        return ctx.lift(mod, ty), f'{OA}.BNone{{}}'
    dmod, call = W.default_of(ctx, mod, ty, name)
    return ctx.lift(mod, ty), (ctx.lift(dmod, call) if dmod is not None else call)


def build_stmt(ctx, mod, name, txt):
    _, concl, _ = mod.signature(name)
    ps = list(mod.fullp)
    pl = [split_param(p) for p in ps]
    coll = name.split('_api_')[0]
    law = name.split('_api_')[1]
    alltext = ' '.join(t for _, t, _ in pl) + ' ' + concl
    mk = re.search(r'U32\.div\(n, (\d+)\)', alltext)
    K = int(mk.group(1)) if mk else 1
    mn = re.match(r'^(?:l|v|bl|b|bits)(\d+)_', coll + '_')
    lim = int(mn.group(1)) if mn else 4
    M = min(4, lim)
    appendish = 'append' in law
    env = {}
    tyof = {n: t for n, t, _ in pl}
    have = set(tyof)
    FD = ctx.alias(ROOT / 'proofs/compact/found.bend')
    dd = 3 if 'hfull' in have and '== False' in tyof['hfull'] else (12 if 'tv' in have else DEPTH)   # a growth: too small a tree; a word list: room for the value's words
    if 'dv' in have:
        env['dv'] = '9n'
    env['d'] = f'{dd}n'
    # the element type and its default, from the tree or array parameter
    fill = None
    etype = None
    for n, t, _ in pl:
        mt = re.match(r'^F\.array__Tree<(.*)>$', t)
        ma = re.match(r'^Array<(.*)>$', t)
        if mt:
            etype, fill = elem_default(ctx, mod, mt.group(1), coll)
        elif ma and fill is None:
            etype, fill = elem_default(ctx, mod, ma.group(1), coll)
    rep_arg = None
    rs_env = {}
    if law == 'root_set':
        mr = re.match(r'^(\w+)\.(rep_pv|rep_ev|rep_el)\(o, s\)$', tyof['rep'])
        if not mr:
            return None, f'the representation premise {tyof["rep"][:60]} is not read'
        kind = mr.group(2)
        E = 32 if kind == 'rep_pv' else 48
        if kind == 'rep_el':
            C, limit = 2, int(re.match(r'^l(\d+)_', coll).group(1))
        else:
            C = limit = int(re.match(r'^v(\d+)_', coll).group(1))
        if C >= 4096:
            return None, (f'the object holds {C} elements: its premises compare Nat numbers of that size in unary (the length {C}, '
                          f'e32 of {C - 1}, pow2 of {(8 * C - 1).bit_length()}), deeper than the rigid checker\'s stack; the vectors up to 512 elements are witnessed')
        NN = E * C
        need = 8 * C if kind == 'rep_pv' else 12 * C
        dw = max(0, (need - 1).bit_length())
        depth = max(0, (limit - 1).bit_length())
        OA = ctx.alias(ROOT / 'src/obj.bend')
        SA = ctx.alias(ROOT / 'types/schema.bend')
        BA = ctx.alias(ROOT / 'src/buffer.bend')
        T = f'{FD}.array__trep(U32, {dw}n, 0)'
        PF = f'{FD}.array__trep_perfect(U32, {dw}n, 0)'
        rs_env.update({'hl': '64n', 'h': f'{BA}.alloc(0)', 'o': f'{OA}.Words{{{FD}.array__thaw(U32, {T}), {NN}}}',
                    'depth': f'{depth}n', 'dU': str(depth), 'seg': '0', 'i': '0', 'n': str(NN)})
        rs_env['s'] = (f'{SA}.ListOf{{{SA}.ByteVector{{48n}}, {limit}n}}' if kind == 'rep_el'
                    else f'{SA}.Vector{{{SA}.ByteVector{{{E}n}}, {C}n}}')
        if kind == 'rep_pv':
            tail = f'({C - 1}n, ({{==}}, ({PF}, ({{==}}, ({{==}}, {{==}})))))'
            rep_arg = f'(({T}, ({dw}n, ({NN}, {tail}))), {{==}})'
        else:
            rep_arg = f'(({T}, ({dw}n, ({NN}, ({{==}}, ({PF}, ({{==}}, {{==}})))))), {{==}})'
    if 'j' in have and M < 2:
        return None, 'needs two distinct indices and the collection holds one element'
    mc = re.search(r'\{U32\.is_le\(\(n \+ 1 : U32\), (\d+)\) == False\{\}', alltext) or \
        re.search(r'\{U32\.is_le\(\(\(U32\.div\(n, \d+\)\) \+ 1 : U32\), (\d+)\) == False\{\}', alltext)
    if re.search(r'\{True\{\} == False\{\}', alltext):
        return None, ('the premise is literally {True == False}: the list limit exceeds the U32 range, so the list is never '
                      'full and the rejection statement is vacuous by design; the accepted direction of the same premise structure (append while the length is below the limit) '
                      'is witnessed by the append_flag, append_length, read_append and view_append statements of this collection')
    cap = int(mc.group(1)) if mc else None
    if cap is not None and cap >= 2 ** 32:
        return None, (f'the premise is_le(n + 1, {cap}) == False cannot hold: the limit exceeds U32, so the list is never full '
                      f'and the rejection statement is vacuous by design')
    env['n'] = str(K * cap) if cap is not None and cap < 2 ** 32 // max(K, 1) else ('0' if appendish or cap is not None else str(K * M))
    if law in ('set_rejected', 'get_outside'):
        env['i'] = env['n']
    elif law == 'other_set_before':
        env['i'], env['j'] = '1', '0'
    else:
        env['i'], env['j'] = '0', '1'
    for k in range(12):
        env[f'x{k}'] = '1'   # the stored words are zero: the value written differs from them
    env['m'] = '0n'
    env.update(rs_env)
    if 'tv' in have:
        env['tv'] = f'{FD}.array__trep(U32, {env.get("dv", str(dd) + "n")}, 0)'
    if 't' in have:
        env['t'] = f'{FD}.array__trep({etype}, {dd}n, {fill})'
    if 'ws' in have:
        env['ws'] = f'Array.new(U32, {dd}n, 0)'
    if 'arr' in have:
        if etype.startswith(ctx.alias(ROOT / 'src/obj.bend') + '.Boxed'):
            for a_, pth in mod.imports.items():
                if f'def {coll}_fill(' in Mod_text(pth):
                    env['arr'] = f'{ctx.alias(pth)}.{coll}_fill({dd}n)'
        else:
            env['arr'] = f'Array.new({etype}, {dd}n, {fill})'
    # objects of the statement that are not collections: elements, bytes, bits
    for n, t, _ in pl:
        if n in ('v', 'x', 'y') and n not in env:
            if t in ('U32',):
                env[n] = '256' if re.search(r'U32\.is_le\(v, 255\)\)? == False', alltext) else '1'   # a value different from the stored zero
            elif t == 'Bool':
                env[n] = 'True{}'
            else:
                et, df = elem_default(ctx, mod, t, coll)
                env[n] = df
    # Nat witnesses: the expression of a premise {E == q}
    for n, t, _ in pl:
        if t == 'Nat' and n not in env:
            for n2, t2, _ in pl:
                m = re.match(r'^\{(.*) == ' + re.escape(n) + r' : Nat\}$', t2, re.S)
                if m and not re.search(r'(?<![\w.])' + re.escape(n) + r'(?![\w.])', m.group(1)):
                    env[n] = '(' + subst_vars(m.group(1), env) + ')'
                    break
            else:
                env[n] = '0n'
    args = []
    for n, t, lin in pl:
        if n == 'rep' and rep_arg is not None:
            args.append(rep_arg)
        elif t.startswith('{'):
            mp = re.match(r'^\{F\.array__perfect\((.*?), (\w+), (\w+)\) == True\{\} : Bool\}$', t)
            if mp:
                et1 = etype if mp.group(1) != 'U32' else 'U32'
                args.append(f'{FD}.array__trep_perfect({et1}, {env[mp.group(2)]}, {fill if et1 != "U32" else "0"})')
            else:
                args.append('{==}')
        else:
            if n not in env:
                return None, f'no value for {n}: {t[:60]}'
            args.append(env[n])
    # the conclusion at the arguments
    cenv = {n: env[n] for n, t, _ in pl if not t.startswith('{') and n in env}
    c2 = subst_vars(ctx.lift(mod, concl), {k: v for k, v in cenv.items()})
    return (c2, f'{ctx.alias(mod.path)}.{name}(' + ', '.join(args) + ')'), None


def build_file(coll, items, mod):
    ctx = W.Ctx()
    out = []
    skipped = []
    for name, txt in items:
        try:
            r, why = build_stmt(ctx, mod, name, txt)
        except SystemExit as e:
            r, why = None, str(e)[:160]
        if r is None:
            skipped.append((name, why))
            continue
        c2, call = r
        out.append(f'def {name}_witness() -> {c2}:\n  {call}')
    if not out:
        return None, skipped
    return W.imports_text(ctx) + '\n\n' + HEADER + '\n' + f'# {coll}: every collection statement applied to a concrete object, its premises proved.\n\n' + '\n\n'.join(out) + '\n', skipped


# ---------------------------------------------------------------- the setter compositions

def field_names(tmod, tname):
    """the constructor's field names of the object type (types/<X>_def_generated.bend), in order; the groups of a grouped
    container (constructors X_g0, X_g1, ...) are expanded in place, as the default's model flattens them"""
    m = re.search(rf'^  {re.escape(tname)}\{{(.*)\}}\s*$', tmod.text, re.M)
    if not m:
        return None
    names = []
    for f in W.split_top(m.group(1)):
        fn, _, ty = f.partition(':')
        mg = re.match(rf'^(?:\w+\.)?({re.escape(tname)}_g\d+)$', ty.strip())
        if mg:
            sub = field_names(tmod, mg.group(1))
            if sub is None:
                return None
            names.extend(sub)
        else:
            names.append(fn.strip())
    return names


def distinct_value(ctx, wexpr):
    """a value of the field's type different from its default (written as a constant), or None: the default of a scalar
    (0, False, O.u64_zero(), a constructor of numerals) with its first numeral raised to 1"""
    m = re.match(r'^(\w+)\.(\w+)\(\)$', wexpr)
    if not m or m.group(1) not in ctx.used:
        return None
    mod = W.Mod.get(ctx.used[m.group(1)])
    if m.group(2) not in mod.defs:
        return None
    body = mod.signature(m.group(2))[2].strip()
    if body == '0':
        return '1'
    if body == 'False{}':
        return 'True{}'
    if body == 'O.u64_zero()':
        return f'{ctx.alias(ROOT / "src/obj.bend")}.U64{{1, 0}}'
    mc = re.match(r'^([\w.]+)\{((?:\s*\d+\s*,?)+)\}$', body)
    if mc:
        return ctx.lift(mod, mc.group(1)) + '{' + re.sub(r'\d+', '1', mc.group(2), count=1) + '}'
    return None


def build_set_file(path):
    """e2e/<Name>_e2e_set_witness_generated.bend: each setter composition with premises (rep of the object, the new value's
    invariant, the value guard) applied to the default object with the value its own field holds (set to itself)"""
    mod = W.Mod.get(path)
    name = Path(path).name[:-len('_e2e_set_generated.bend')]
    W.PREFER.clear()
    W.PREFER[mod.path] = 'SET'
    taken = {'SET', 'WT', 'FD', 'O', 'B'}
    for a, pth in mod.imports.items():
        if pth not in W.PREFER and a not in taken:
            W.PREFER[pth] = a
            taken.add(a)
    for pth_, al_ in ((ROOT / 'proofs/compact/found.bend', 'FD'), (ROOT / 'src/obj.bend', 'O'), (ROOT / 'src/buffer.bend', 'B'),
                      (E2E / 'e2e_wit.bend', 'WT')):
        W.PREFER[pth_.resolve()] = al_
    ctx = W.Ctx()
    ctx.alias(mod.path)
    syn = W.Synth(ctx)
    stm = [(d, t) for d, t in mod.defs.items() if '_e2e_set_' in d and re.match(r'def \w+\(', t)]
    if not stm:
        return None, []
    # the object type, from the first statement
    _, _, _ = mod.signature(stm[0][0])
    ps0 = [split_param(p) for p in mod.fullp]
    otype = next(t for n, t, _ in ps0 if n == 'o')
    tmod, dflt = W.default_of(ctx, mod, otype, name)
    D = f'{ctx.alias(tmod.path)}.{dflt}'
    obj = W.model_of(ctx, tmod, dflt)
    tname = otype.strip().rpartition('.')[2]
    fnames = field_names(tmod, tname)
    if not fnames:
        return None, [(name, f'the object type {tname} is not read')]
    if not isinstance(obj, W.Cont):
        return None, [(name, 'the default object is not a container model')]
    out, skipped, seen = [], [], {}
    BUF = ctx.alias(ROOT / 'src/buffer.bend') + '.alloc(0)'
    for d, txt in stm:
        _, ret, _ = mod.signature(d)
        pl = [split_param(p) for p in mod.fullp]
        prem = [(n, t) for n, t, _ in pl if n not in ('h', 'o', 'w')]
        if not prem:
            continue
        mf = re.match(rf'^{name}_e2e_set_(.+)_(view|root|encode|flag|rejected|go)$', d)
        if not mf or mf.group(2) in ('flag', 'rejected', 'go'):
            skipped.append((d, 'a guard statement over a raw object, not a composition'))
            continue
        fld = mf.group(1)
        if fld not in fnames:
            skipped.append((d, f'the field {fld} is not of the constructor'))
            continue
        k = fnames.index(fld)
        if k >= len(obj.fields):
            skipped.append((d, 'the field is not in the default model'))
            continue
        wexpr, wmodel = obj.fields[k]
        nv = distinct_value(ctx, wexpr) if isinstance(wmodel, W.Leaf) else None
        if nv is not None:
            wexpr, wmodel = nv, W.Leaf(nv)
        env = {'o': obj, 'w': wmodel}
        args = []
        try:
            defs_ = []
            for n, t, _ in pl:
                if n == 'h':
                    args.append(BUF)
                elif n == 'o':
                    args.append(D)
                elif n == 'w':
                    args.append(wexpr)
                else:
                    env['__subj'] = None
                    ty = ctx.lift(mod, t)
                    ty = re.sub(r'(?<![\w.])o(?=[),])', D, ty)
                    ty = re.sub(r'(?<![\w.])w(?=[),])', wexpr, ty)
                    term = syn.prove(mod, t, env)
                    if ty in seen:
                        args.append(seen[ty] + '()')
                        continue
                    nm = f'{d}_{n}'
                    seen[ty] = nm
                    defs_.append(f'def {nm}() -> {ty}:\n  {term}')
                    args.append(nm + '()')
        except SystemExit as e:
            skipped.append((d, str(e).replace('\n', ' ')[:160]))
            continue
        c2 = ctx.lift(mod, ret)
        c2 = re.sub(r'(?<![\w.])o(?=[),])', D, c2)
        c2 = re.sub(r'(?<![\w.])w(?=[),])', wexpr, c2)
        c2 = re.sub(r'(?<![\w.])h(?=[),])', BUF, c2)
        out.extend(defs_)
        out.append(f'def {d}_witness() -> {c2}:\n  SET.{d}({", ".join(args)})')
    if not out:
        return None, skipped
    lem = [syn.lemmas[k_] for k_ in sorted(syn.lemmas)]
    ctx.alias(ROOT / 'src/obj.bend')
    ctx.alias(ROOT / 'proofs/compact/found.bend')
    return (W.imports_text(ctx) + '\n\n' + HEADER + '\n' +
            f'# {name}: every setter composition with premises applied to the default object (the new value is the field\'s own\n'
            f'# value), each premise proved of it.\n\n' + '\n\n'.join(lem + out) + '\n'), skipped


def sources():
    files = sorted(glob.glob(str(ROOT / 'proofs/obj/coll_api_*.bend'))) + [str(ROOT / 'proofs/obj/coll_root.bend')]
    by = {}
    for f in files:
        m = W.Mod.get(f)
        for d, txt in m.defs.items():
            if '_api_' in d and re.match(r'def \w+\(', txt):
                by.setdefault(d.split('_api_')[0], []).append((d, txt, m))
    return by


def main():
    check = '--check' in sys.argv
    only = sys.argv[sys.argv.index('--only') + 1].split(',') if '--only' in sys.argv else None
    outs, rows = {}, []
    for coll, items in sorted(sources().items()):
        if only and coll not in only:
            continue
        W.PREFER.clear()
        text, skipped = None, []
        # one module per file: group by module
        mods = {}
        for d, txt, m in items:
            mods.setdefault(m.path, (m, []))[1].append((d, txt))
        texts = []
        for p_, (m, its) in mods.items():
            t, sk = build_file(coll, its, m)
            skipped += sk
            if t:
                texts.append(t)
                suffix = '_api_root_witness_generated.bend' if m.path.name == 'coll_root.bend' else '_api_witness_generated.bend'
                outs[E2E / f'{coll}{suffix}'] = t
        n_ok = sum(t.count('_witness() ->') for t in texts)
        rows.append(f'{coll}\t{n_ok} witnessed' + ''.join(f'\n  pending {n}: {w}' for n, w in skipped))
    for f_ in sorted(glob.glob(str(E2E / '*_e2e_set_generated.bend'))):
        nm_ = Path(f_).name[:-len('_e2e_set_generated.bend')]
        if only and nm_ not in only:
            continue
        W.Mod.cache.clear()
        try:
            t, sk = build_set_file(f_)
        except SystemExit as e:
            t, sk = None, [(nm_, str(e).replace('\n', ' ')[:160])]
        if t:
            outs[E2E / f'{nm_}_e2e_set_witness_generated.bend'] = t
        n_ok = t.count('_witness() ->') if t else 0
        rows.append(f'{nm_} (setters)\t{n_ok} witnessed' + ''.join(f'\n  pending {n}: {w}' for n, w in sk))
    if not only:
        outs[E2E / 'COLL_WITNESS.txt'] = ('# GENERATED by coll_witness (codegen). Do not edit.\n# per collection: the statements whose premises are witnessed '
                                          '(e2e/<coll>_api_witness_generated.bend) and those that are not, with the reason\n' + '\n'.join(rows) + '\n')
    stale = []
    for p, t in outs.items():
        if not p.exists() or p.read_text() != t:
            stale.append(p.name)
            if not check:
                p.write_text(t)
    if not only:
        for p in sorted(E2E.glob('*_api_witness_generated.bend')) + sorted(E2E.glob('*_api_root_witness_generated.bend')) + sorted(E2E.glob('*_e2e_set_witness_generated.bend')):
            if p not in outs:
                if check:
                    stale.append(p.name + ' (orphan)')
                else:
                    p.unlink()
    if check:
        if stale:
            print('stale: ' + ', '.join(stale))
            sys.exit(1)
        print(f'coll_witness: {len(outs)} files up to date')
    else:
        print(f'coll_witness: wrote {len(stale)} of {len(outs)}')


if __name__ == '__main__':
    main()
