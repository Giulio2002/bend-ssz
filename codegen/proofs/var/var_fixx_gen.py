def bvn_mod(N, HEAD, sig, TR, TRUE):
    """Bitvector[N] (N <= 8, one byte) of the generic containers at any byte position: the reader
    keeps the low byte of the four-byte read at x (vedge.bend: only that byte need be in the
    buffer). For N < 8 the validator checks bits N..7 of the byte clear (CHK) and prt holds under
    CHK; for N = 8 every byte is a value (its high bits are clear: the window's bytes are bytes)."""
    import itertools
    chk = N < 8
    p = f'bv{N}'
    Tn = f'T.Bitvector{N}'
    P = 'A.quad(VB.pw(d))'
    SCH = f'S.BitVector{{{N}n}}'
    B_ = lambda b: 'True{}' if b else 'False{}'
    MP = 'Maybe<&2, +List<S.Part>>'
    a = [f'a{i}' for i in range(32)]

    def word(bits):
        t = 'WNil{}'
        for x in reversed(bits):
            t = f'WCon{{{x}, {t}}}'
        return f'U32{{{t}}}'
    L = generic_head(HEAD) + ['', '# GENERATED by var_fixx (codegen: var_fixx_gen). Do not edit.',
                              f'# {p} (Bitvector[{N}], one byte) of the generic containers at any byte position: see codegen/proofs/var/var_fixx_gen.py.', '']
    w = L.append
    w(common(TR, TRUE))
    if chk:
        w(TPL.render('bvn_mod', N=N, TR=TR))
    w(TPL.render('bvn_mod_OBJ', P=P, TR=TR, TRUE=TRUE, Tn=Tn, p=p, sig=sig))
    if chk:
        w(TPL.render('bvn_mod_2', N=N, P=P, p=p, sig=sig))
    pat = ''.join(f'WCon{{{a[i]}, ' for i in range(N)) + 'r' + '}' * N
    w(TPL.render('bvn_mod_VBN', N=N, TR=TR, a=a, pat=pat))
    goalv = lambda v: f'{{Codec.parts(VBN({v}), {SCH}) == Some{{[S.Fixed{{[{v}]}}]}} : {MP}}}'
    w(f"# the value's parts are the byte, when bits {N}..31 are clear: by cases on the bits, highest first,")
    w(f"# then the {N} low bits")
    zw = lambda i: word(a[:i + 1] + ['False{}'] * (31 - i))
    w(f'def z{N - 1}({", ".join("+" + x + ": Bool" for x in a[:N])}) -> {goalv(zw(N - 1))}:')
    w(f'  match {" ".join(a[:N])}:')
    for lo in itertools.product([False, True], repeat=N):
        w(f'    case {" ".join(B_(b) for b in lo)}: {{==}}')
    for i in range(N, 32 if chk else N):
        ps = ", ".join("+" + x + ": Bool" for x in a[:i + 1])
        w(f'def z{i}({ps}, +h: {{CHKv({zw(i)}) == {TRUE}}}) -> {goalv(zw(i))}:')
        w(f'  match {a[i]}:')
        wt = word(a[:i] + ['True{}'] + ['False{}'] * (31 - i))
        w(f'    case True{{}}: Empty.absurd({goalv(wt)}, FD.logic__false_true(h))')
        nxt = f'z{i - 1}({", ".join(a[:i])})' if i == N else f'z{i - 1}({", ".join(a[:i])}, h)'
        w(f'    case False{{}}: {nxt}')
    w('')
    if chk:
        w(f'def bvp(+v: U32, +h: {{CHKv(v) == {TRUE}}}) -> {goalv("v")}:')
        w('  match v:')
        w(f'    case {word(["+" + x for x in a])}: z31({", ".join(a)}, h)')
    else:
        w('# a byte: the embedding of its eight bits')
        w(f'def bvp8(+w8: Word(8n)) -> {goalv("PD.embed8(w8)")}:')
        w('  match w8:')
        w('    case ' + ''.join(f'WCon{{+{x}, ' for x in a[:8]) + 'WNil{}' + '}' * 8 + f': z7({", ".join(a[:8])})')
    w('')
    HB = f'+hb: {{Nat.is_le(Nat.add(x, 1n), {P}) == {TRUE}}}'
    if chk:
        w(TPL.render('bvn_mod_prt', HB=HB, MP=MP, SCH=SCH, TR=TR, TRUE=TRUE))
    else:
        w(TPL.render('bvn_mod_3', HB=HB, MP=MP, SCH=SCH, TR=TR, TRUE=TRUE))
        return '\n'.join(L) + '\n'
    # ---- the inversion: every value whose parts are the window's byte passes the check
    w(TPL.render('bvn_mod_CHKL', MP=MP, TRUE=TRUE))
    bs = [f'b{i}' for i in range(N)]
    AB = f'Empty.absurd({{CHKL(ys) == {TRUE}}}, FD.logic__none_some(+List<S.Part>, [S.Fixed{{ys}}], e))'
    OCT = 'Bp.octet(' + ', '.join(bs + ['False{}'] * (8 - N)) + ')'
    w(f'def chko({", ".join("+" + b + ": Bool" for b in bs)}) -> {{CHKL([{OCT}]) == {TRUE}}}:')
    w(f'  match {" ".join(bs)}:')
    for lo in itertools.product([False, True], repeat=N):
        w(f'    case {" ".join(B_(b) for b in lo)}: {{==}}')
    w('')
    w(f'# any bits value whose parts are one fixed part ys: the first byte of ys has bits {N}..7 clear')
    w(f'def bvinv(+v: S.Value, +ys: +List<U32>, +e: {{Codec.parts(v, {SCH}) == Some{{[S.Fixed{{ys}}]}} : {MP}}}) -> {{CHKL(ys) == {TRUE}}}:')
    w('  match v:')
    w('    case S.BitsValue{+bs}:')
    ind = '      '
    w(f'{ind}match bs:')
    cur = 'bs'
    for i in range(N):
        w(f'{ind}  case Nil{{}}: {AB}')
        w(f'{ind}  case Con{{+b{i}, +r{i}}}:')
        ind += '    '
        w(f'{ind}match r{i}:')
    w(f'{ind}  case Con{{+b{N}, +r{N}}}: {AB}')
    w(f'{ind}  case Nil{{}}:')
    w(f'{ind}    +ey = Equal.cong({MP}, +List<U32>, z => fxs(z), Some{{[S.Fixed{{[{OCT}]}}]}}, Some{{[S.Fixed{{ys}}]}}, e)')
    w(f'{ind}    %Equal.sym(+List<U32>, ys, [{OCT}], Equal.sym(+List<U32>, [{OCT}], ys, ey)) : {{CHKL(_) == {TRUE}}}')
    w(f'{ind}    chko({", ".join(bs)})')
    for c in ['S.BooleanValue{+b}', 'S.UnsignedValue{+u}', 'S.BytesValue{+xs}', 'S.Sequence{+it}', 'S.Items{+hh, +tl}', 'S.EmptyItems{}',
              'S.Selected{+sel, +sv}', 'S.NullValue{}']:
        w(f'    case {c}: {AB}')
    w('')
    w(TPL.render('bvn_mod_inv', MP=MP, SCH=SCH, TR=TR, TRUE=TRUE))
    return '\n'.join(L) + '\n'


def generic_small(names, small_mod):
    """Fixed types of the generic containers read word by word (var_fixx.py's small_mod) with the
    generic runtime: {prefix: text}."""
    from codegen.impl import generate as G
    g = G.Gen()
    for t in names.values():
        g.shape(t)
    out = {}
    for cont, fld, sch in GENERIC_SMALL:
        p, txt = small_mod(g, dict(names[cont].fields)[fld], sch)
        txt = txt.replace('import ../../types/fulu_obj.bend as T', 'import ../../types/generic_obj.bend as T')
        txt = txt.replace('import ./arr_vec.bend as AV\n', 'import ./arr_vec.bend as AV\nimport ./spec_bits.bend as FB\n', 1)
        txt = txt.replace('# GENERATED by var_fixx (codegen). Do not edit.', '# GENERATED by var_fixx (codegen: var_fixx_gen: generic_obj). Do not edit.')
        out[p] = txt
    return out


