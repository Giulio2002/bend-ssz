def bvw1_mod(HEAD, sig, TR, TRUE, N=257):
    """Bitvector[257] of the generic containers at any byte position: eight whole words and a last
    byte of one bit (bits 1..7 clear: the validator's CHK). The reader reads the words at x .. x + 28
    and keeps the low byte of the read at x + 32 (vedge.bend); the value's bits are the words' then
    the last byte's low bit, packed (pack_app) to the 33 window bytes."""
    M = (N - 1) // 32
    C = 4 * M
    S = C + 1
    NB = N
    copy = N > 512
    p, Tn = f'bv{N}', ('O.Words' if copy else f'T.Bitvector{N}')
    P = 'A.quad(VB.pw(d))'
    SCH = f'S.BitVector{{{N}n}}'
    MP = 'Maybe<&2, +List<S.Part>>'
    a = [f'a{i}' for i in range(32)]
    F7 = ', '.join(['False{}'] * 7)

    def word(bits):
        t = 'WNil{}'
        for x in reversed(bits):
            t = f'WCon{{{x}, {t}}}'
        return f'U32{{{t}}}'
    L = generic_head(HEAD) + ['import ./spec_bits.bend as FB', '',
                              '# GENERATED by var_fixx (codegen: var_fixx_gen). Do not edit.',
                              f'# {p} (Bitvector[{N}], {S} bytes) of the generic containers at any byte position: see codegen/proofs/var/var_fixx_gen.py.', '']
    w = L.append
    w(common(TR, TRUE))
    X32 = f'Nat.add({C}n, x)'
    words = ['UR.RWN(t, x)'] + [f'UR.RWN(t, Nat.add({4 * k}n, x))' for k in range(1, M)]
    OBJ = f'{Tn}{{{", ".join(words)}, O.keep(1, UR.RWN(t, {X32}))}}'
    if copy:
        import re as _re2
        dz = int(_re2.search(rf'^def {p}_read\(.*Array\.new\(U32, (\d+)n, 0\)\)$', GEN_SRC(), _re2.M).group(1))
        ky = (S + 31 - 1).bit_length()
        OBJ = f'O.Words{{FD.array__thaw(U32, VXB.CTN(d, t, x, {S}, {dz}n)), {S}}}'
    w(TPL.render('bvw1_mod', OBJ=OBJ, P=P, S=S, TR=TR, TRUE=TRUE, Tn=Tn, X32=X32))
    # rdx
    if copy:
        w(TPL.render('bvw1_mod_2', S=S, dz=dz, ky=ky, p=p, sig=sig))
    if not copy:
        w(TPL.render('bvw1_mod_3', C=C, P=P, S=S, TRUE=TRUE, Tn=Tn, X32=X32, p=p, sig=sig))
        got = []
        RHS = f'(UA.BF(t, n), OBJ(d, t, x)) : B.Buf & {Tn}'
        for k in range(M):
            c = 4 * k
            X = 'off' if k == 0 else f'U32.add(off, {c})'
            pos = 'x' if k == 0 else f'Nat.add({c}n, x)'
            eo = 'e' if k == 0 else f'ec(d, off, x, {c}, {c}n, e, hd, {{==}}, {{==}}, hb)'
            room = f'VXG.roomc(x, {S}n, 0n, 4n, {P}, hb, {{==}})' if k == 0 else f'rm(x, {c}n, 4n, {{==}}, {P}, hb)'
            if k == 0:
                room = f'FD.logic__subst(Nat, z => {{Nat.is_le(Nat.add(z, 4n), {P}) == {TRUE}}}, Nat.add(x, 0n), x, FD.nat__add_zero(x), {room})'
            args = ', '.join(['off'] + got + ['_'])
            w(f"""  %Equal.sym(B.Buf & U32, B.read32(UA.BF(t, n), {X}), (UA.BF(t, n), UR.RWN(t, {pos})), UR.rwx(d, t, n, {X}, {pos}, {eo}, hd31, pf, {room})) :
    {{T.{p}_r{k}({args}) == {RHS}}}""")
            got.append(f'UR.RWN(t, {pos})')
        X = f'U32.add(off, {C})'
        args = ', '.join(['off'] + got + ['_'])
        w(TPL.render('bvw1_mod_4', M=M, RHS=RHS, Tn=Tn, X=X, X32=X32, args=args, got=got, p=p))
    # ok
    w(TPL.render('bvw1_mod_5', C=C, P=P, S=S, X32=X32, p=p, sig=sig))
    # value, pack_app, octet lemma
    WS = f'UR.RWS({M}n, t, x)'
    BITS = f'List.append(&2, Bool, FB.bitsof({WS}), [LB(BX(t, {X32}))])'
    w(TPL.render('bvw1_mod_VAL', BITS=BITS, TR=TR, a=a, word=word))
    Htxt = word(a)
    O4txt = '[' + ', '.join(f'Bp.octet({", ".join(a[8 * j:8 * j + 8])})' for j in range(4)) + ']'
    import re as _re
    L[-1] = _re.sub(r'\bO4\b', O4txt, _re.sub(r'\bH\b', Htxt, L[-1].split('law pack_app:')[1])).join([L[-1].split('law pack_app:')[0] + 'law pack_app:', ''])
    goal = lambda v: f'{{Bp.octet(LB({v}), {F7}) == {v} : U32}}'
    zw = lambda i: word(a[:i + 1] + ['False{}'] * (31 - i))
    w('# a byte with bits 1..31 clear is the octet of its low bit')
    w(f'def z0(+a0: Bool) -> {goal(zw(0))}:')
    w('  match a0:')
    w('    case True{}: {==}')
    w('    case False{}: {==}')
    for i in range(1, 32):
        ps = ", ".join("+" + x + ": Bool" for x in a[:i + 1])
        w(f'def z{i}({ps}, +h: {{CHKv({zw(i)}) == {TRUE}}}) -> {goal(zw(i))}:')
        w(f'  match {a[i]}:')
        wt = word(a[:i] + ['True{}'] + ['False{}'] * (31 - i))
        w(f'    case True{{}}: Empty.absurd({goal(wt)}, FD.logic__false_true(h))')
        nxt = f'z{i - 1}({", ".join(a[:i])})' if i == 1 else f'z{i - 1}({", ".join(a[:i])}, h)'
        w(f'    case False{{}}: {nxt}')
    w(f'def ob1(+v: U32, +h: {{CHKv(v) == {TRUE}}}) -> {goal("v")}:')
    w('  match v:')
    w(f'    case {word(["+" + x for x in a])}: z31({", ".join(a)}, h)')
    w('')
    APP = f'List.append(&2, U32, F.limbs({WS}), [BX(t, {X32})])'
    APPO = f'List.append(&2, U32, F.limbs({WS}), [Bp.octet(LB(BX(t, {X32})), {F7})])'
    w(TPL.render('bvw1_mod_wx', APP=APP, BITS=BITS, C=C, M=M, MP=MP, NB=NB, P=P, S=S, SCH=SCH, TR=TR, TRUE=TRUE, WS=WS, X32=X32))
    # inversion
    bs = [f'b{i}' for i in range(8)]
    w(TPL.render('bvw1_mod_GE', MP=MP, TRUE=TRUE))
    G = lambda lst: f'{{CHKv(VBL.nthb(Bp.pack({lst}), 1n+p)) == {TRUE}}}'
    w('def pkl(m, bs, h):')
    w('  match m bs:')
    w('    case 0n _: pk0(bs, h)')
    ind = '  '
    pre = []
    for i in range(8):
        lst = ' <> '.join(pre + ['Nil{}']) if pre else 'Nil{}'
        k = len(pre)
        if i == 0:
            w(f'    case 1n+ +p Nil{{}}: Empty.absurd({G(lst)}, FD.logic__false_true(Equal.cong(Nat, Bool, z => GE(8n, z), {k}n, 8n+LEN(p), h)))')
            w(f'    case 1n+ +p Con{{+b{i}, +r{i}}}:')
            ind = '      '
        else:
            w(f'{ind}  case Nil{{}}: Empty.absurd({G(lst)}, FD.logic__false_true(Equal.cong(Nat, Bool, z => GE(8n, z), {k}n, 8n+LEN(p), h)))')
            w(f'{ind}  case Con{{+b{i}, +r{i}}}:')
            ind += '    '
        pre.append(f'b{i}')
        w(f'{ind}match r{i}:' if i < 7 else '')
    # after 8 elements: r7 is the tail
    body = f'pkl(p, r7, Equal.cong(Nat, Nat, z => FD.nat__pred(FD.nat__pred(FD.nat__pred(FD.nat__pred(FD.nat__pred(FD.nat__pred(FD.nat__pred(FD.nat__pred(z)))))))), 8n+List.length(&2, Bool, r7), 8n+LEN(p), h))'
    L.pop()
    w(f'{ind}{body}')
    w('')
    AB = f'Empty.absurd({{CHK(t, x) == {TRUE}}}, FD.logic__none_some(+List<S.Part>, [S.Fixed{{UW.WX(t, x, {S}n)}}], e))'
    w(TPL.render('bvw1_mod_ivb', AB=AB, C=C, MP=MP, NB=NB, S=S, SCH=SCH, TR=TR, TRUE=TRUE, X32=X32))
    for c in ['S.BooleanValue{+b}', 'S.UnsignedValue{+u}', 'S.BytesValue{+xs}', 'S.Sequence{+it}', 'S.Items{+hh, +tl}', 'S.EmptyItems{}',
              'S.Selected{+sel, +sv}', 'S.NullValue{}']:
        w(f'    case {c}: {AB}')
    w('')
    return '\n'.join(L) + '\n'


