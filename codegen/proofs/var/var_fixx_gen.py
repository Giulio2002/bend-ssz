from codegen.core.shared_var_b import Templates  # noqa: E402
TPL = Templates('var_fixx_gen', globals())
"""Fixed readers of the generic containers' short fields (types/generic_obj.bend), for
codegen/proofs/var/var_fixx.py: vfx_u8, vfx_u16 (and the one-byte bitvectors vfx_bv1/bv2/bv8).

Each module has the vfx_<p> interface (OBJ, rdx, VAL, prt), with the room hb: x + S <= 4 2^d
for the field's own size S: the runtime's four-byte read at a field near the end of the
buffer is proved by proofs/obj/vedge.bend (the bytes it keeps are in the buffer).
"""


def GEN_SRC():
    return __import__('codegen.impl.runtime_refs', fromlist=['_']).mono_text('generic')


def bvc_mod(N, HEAD, sig, TR, TRUE):
    """Bitvector[N], N a multiple of 32 read by copy_into (the generic runtime's fixwords): its words
    at x are the window's bytes, their bits the value's (after var_fixx.py's vec_text)."""
    import re
    p = f'bv{N}'
    S, M = N // 8, N // 32
    dz = int(re.search(rf'^def {p}_read\(.*Array\.new\(U32, (\d+)n, 0\)\)$', GEN_SRC(), re.M).group(1))
    ky = (S + 31 - 1).bit_length()
    SCH = f'S.BitVector{{{N}n}}'
    MP = 'Maybe<&2, +List<S.Part>>'
    L = generic_head(HEAD) + ['import ./spec_bits.bend as FB', '', '# GENERATED by var_fixx (codegen: var_fixx_gen). Do not edit.',
                              f'# {p} (Bitvector[{N}], {S} bytes, read by copy_into) of the generic containers at any byte position.', '']
    L.append(TPL.render('bvc_mod', M=M, MP=MP, N=N, S=S, SCH=SCH, TR=TR, TRUE=TRUE, dz=dz, ky=ky, p=p, sig=sig))
    return '\n'.join(L) + '\n'


