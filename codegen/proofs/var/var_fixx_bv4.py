"""justification_bits (Bitvector[4], one byte) at any byte position, for codegen/proofs/var/var_fixx.py.

The reader keeps the low byte of the word at x; the validator checks bits 4..7 of the byte
clear (CHK); the value is the byte's four low bits. prt holds under CHK (by cases on the
byte's bits: a set bit 4..31 makes CHK false), and inv: any value whose parts are the
window's byte passes CHK.
"""
import itertools
from codegen.core.shared_var_b import Templates  # noqa: E402
TPL = Templates('var_fixx_bv4', globals())


def bv4_mod(HEAD, sig, TR, TRUE):
    P = 'A.quad(VB.pw(d))'
    B = lambda b: 'True{}' if b else 'False{}'
    MP = 'Maybe<&2, +List<S.Part>>'
    a = [f'a{i}' for i in range(32)]

    def word(bits):
        t = 'WNil{}'
        for x in reversed(bits):
            t = f'WCon{{{x}, {t}}}'
        return f'U32{{{t}}}'
    L = list(HEAD) + ['import ./vbrt.bend as VR', 'import ./vbitl.bend as VBL', 'import ./vcopy.bend as VC', 'import ./vfxg.bend as VXG',
                      'import ../../spec/bit_packing.bend as Bp', '',
                      '# GENERATED by var_fixx (codegen: var_fixx_bv4). Do not edit.',
                      '# bv4 (Bitvector[4], one byte) at any byte position: see codegen/proofs/var/var_fixx_bv4.py.', '']
    w = L.append
    w(TPL.render('bv4_mod', P=P, TR=TR, TRUE=TRUE, sig=sig))
    goalv = lambda v: f'{{Codec.parts(VB4({v}), S.BitVector{{4n}}) == Some{{[S.Fixed{{[{v}]}}]}} : {MP}}}'
    w("# the value's parts are the byte, when bits 4..31 are clear: by cases on the bits, highest first")
    w("# (U32.is_eq compares from the high bit), then the four low bits")
    zw = lambda i: word(a[:i + 1] + ['False{}'] * (31 - i))
    w(f'def z3({", ".join("+" + x + ": Bool" for x in a[:4])}) -> {goalv(zw(3))}:')
    w('  match a0 a1 a2 a3:')
    for lo in itertools.product([False, True], repeat=4):
        w(f'    case {" ".join(B(b) for b in lo)}: {{==}}')
    for i in range(4, 32):
        ps = ", ".join("+" + x + ": Bool" for x in a[:i + 1])
        w(f'def z{i}({ps}, +h: {{CHKv({zw(i)}) == {TRUE}}}) -> {goalv(zw(i))}:')
        w(f'  match {a[i]}:')
        wt = word(a[:i] + ['True{}'] + ['False{}'] * (31 - i))
        w(f'    case True{{}}: Empty.absurd({goalv(wt)}, FD.logic__false_true(h))')
        nxt = f'z{i - 1}({", ".join(a[:i])})' if i == 4 else f'z{i - 1}({", ".join(a[:i])}, h)'
        w(f'    case False{{}}: {nxt}')
    w('')
    w(f'def bvp(+v: U32, +h: {{CHKv(v) == {TRUE}}}) -> {goalv("v")}:')
    w('  match v:')
    w(f'    case {word(["+" + x for x in a])}: z31({", ".join(a)}, h)')
    w('')
    w(TPL.render('bv4_mod_prt', MP=MP, P=P, TR=TR, TRUE=TRUE))
    AB = f'Empty.absurd({{CHKL(ys) == {TRUE}}}, FD.logic__none_some(+List<S.Part>, [S.Fixed{{ys}}], e))'
    OCT = 'Bp.octet(b0, b1, b2, b3, False{}, False{}, False{}, False{})'
    w(f'def chko(+b0: Bool, +b1: Bool, +b2: Bool, +b3: Bool) -> {{CHKL([{OCT}]) == {TRUE}}}:')
    w('  match b0 b1 b2 b3:')
    for lo in itertools.product([False, True], repeat=4):
        w(f'    case {" ".join(B(b) for b in lo)}: {{==}}')
    w('')
    w('# any bits value whose parts are one fixed part ys: the first byte of ys has bits 4..7 clear')
    w(f'def bvinv(+v: S.Value, +ys: +List<U32>, +e: {{Codec.parts(v, S.BitVector{{4n}}) == Some{{[S.Fixed{{ys}}]}} : {MP}}}) -> {{CHKL(ys) == {TRUE}}}:')
    w('  match v:')
    w('    case S.BitsValue{+bs}:')
    w('      match bs:')
    w(f'        case Nil{{}}: {AB}')
    w('        case Con{+b0, +r0}:')
    w('          match r0:')
    w(f'            case Nil{{}}: {AB}')
    w('            case Con{+b1, +r1}:')
    w('              match r1:')
    w(f'                case Nil{{}}: {AB}')
    w('                case Con{+b2, +r2}:')
    w('                  match r2:')
    w(f'                    case Nil{{}}: {AB}')
    w('                    case Con{+b3, +r3}:')
    w('                      match r3:')
    w(f'                        case Con{{+b4, +r4}}: {AB}')
    w('                        case Nil{}:')
    w(f'                          +ey = Equal.cong({MP}, +List<U32>, z => fxs(z), Some{{[S.Fixed{{[{OCT}]}}]}}, Some{{[S.Fixed{{ys}}]}}, e)')
    w(f'                          %Equal.sym(+List<U32>, ys, [{OCT}], Equal.sym(+List<U32>, [{OCT}], ys, ey)) : {{CHKL(_) == {TRUE}}}')
    w('                          chko(b0, b1, b2, b3)')
    for c in ['S.BooleanValue{+b}', 'S.UnsignedValue{+u}', 'S.BytesValue{+xs}', 'S.Sequence{+it}', 'S.Items{+hh, +tl}', 'S.EmptyItems{}',
              'S.Selected{+sel, +sv}', 'S.NullValue{}']:
        w(f'    case {c}: {AB}')
    w('')
    w(TPL.render('bv4_mod_inv', MP=MP, TR=TR, TRUE=TRUE))
    return '\n'.join(L) + '\n'
