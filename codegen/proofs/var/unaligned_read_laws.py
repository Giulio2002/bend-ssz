"""The unaligned-offset layer: the runtime's word reads and copies at any byte
offset, related to the buffer's spec bytes.

    python3 codegen/proofs/var/unaligned_read_laws.py [--check]

proofs/obj/vua_bits.bend (generated here, stock): the byte structure of the
runtime's unaligned word join B.join_sel(j, lo, hi) (j = 1, 2, 3): its four
limbs are the last 4 - j limbs of lo followed by the first j limbs of hi. The
proofs compute each output bit symbolically (a simulator of Word.and/or/shift
below) and close every position with one of five one-bit lemmas; no case
split over the words' bits is needed.

proofs/obj/vua.bend (hand-written, stock) builds U1 on it: B.read32 at any
byte offset returns a word whose limbs are the buffer's spec bytes there.

proofs/obj/vua_ci<s>_generated.bend (s = 0..3; manual audit round 13,
s01-copy/09, /10): O.copy_in, the decoder of every byte range, on a literal
buffer of 32 marked bytes at the offsets s and 4 + s and every length 1 to 9:
the copy's length and words are the source bytes shifted to byte 0, the rest
zero (laws ci_o<off>_n<n>, by computation). vcopy.bend proves copy_in for a
word-aligned range only; these pin the dispatch on off & 3.
"""
