def le_words(data, k):
    data = data.ljust(4 * k, b'\0')
    return [int.from_bytes(data[4 * i:4 * i + 4], 'little') for i in range(k)]


def emit_ci(s):
    """(round 13: s01-copy/09, /10) O.copy_in on a literal buffer of 32 marked bytes at the byte offsets s and 4 + s, for every length 1 to 9:
    the length and the first CI_WORDS words of the copy are the source bytes [off, off + n) shifted to byte 0, the rest of the last word and the
    words after it zero. proofs/obj/vcopy.bend proves copy_in for a word-aligned range only, so a dispatch on off & 3 that picks the wrong
    shifted loop (scopy1 for s = 2) was caught only by the corpus."""
    src = 'Array.new(U32, 3n, 0)'
    for i, w in enumerate(le_words(CI_SRC, 8)):
        src = f'Array.set(U32, {src}, {i}, {w})'
    def nest(xs):
        return xs[0] if len(xs) == 1 else f'({xs[0]}, {nest(xs[1:])})'

    def tnest(k):
        return 'U32' if k == 1 else f'U32 & ({tnest(k - 1)})'
    tup = tnest(CI_WORDS + 1)
    L = ['import Base', 'import ../../src/buffer.bend as B', 'import ../../src/obj.bend as O', '',
         '# GENERATED by unaligned_read_laws (codegen). Do not edit.',
         f'# O.copy_in at byte offsets {s} and {4 + s} (offset & 3 = {s}) of a literal buffer, lengths 1 to 9 (round 13: s01-copy/09, /10;',
         '# see emit_ci in codegen/proofs/var/unaligned_read_laws.py).', '',
         f'def ci_src() -> B.Buf: B.Buf{{{src}, 32}}', '',
         f'def ci_c{CI_WORDS - 1}(pair: Array<U32> & U32) -> U32: Pair.snd(Array<U32>, U32, pair)', '']
    for i in range(CI_WORDS - 2, -1, -1):
        L += [f'def ci_c{i}(pair: Array<U32> & U32) -> {tnest(CI_WORDS - i)}:', '  (ws, +x) = pair', f'  (x, ci_c{i + 1}(Array.get(U32, ws, {i + 1})))', '']
    L += [f'def ci_rd(w: O.Words) -> {tup}:', '  match w:', '    case O.Words{ws, +n}: (n, ci_c0(Array.get(U32, ws, 0)))', '']
    for off in (s, 4 + s):
        for n in range(1, 10):
            want = nest([str(x) for x in [n] + le_words(CI_SRC[off:off + n], CI_WORDS)])
            L += [f'def ci_o{off}_n{n}() -> {{ci_rd(Pair.snd(B.Buf, O.Words, O.copy_in(ci_src(), {off}, {n}))) == {want} : {tup}}}:', '  {==}', '']
    return '\n'.join(L)


