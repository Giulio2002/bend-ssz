#!/usr/bin/env python3
"""The bit-list codec laws (runtime O.ok_bitlist / O.bits_in against
spec/bitfields.bend list_encoding).

    python3 codegen/proofs/var/bit_list_codec_laws.py [--check]

Generic forms BitList[N] (the 18 of the official ssz_generic suite):
proofs/obj/var_bits_<X>{,_unique,_rej}.bend, stock: ok_eval, decode_accept,
decode_none, decode_spec (the buffer's bytes are the spec delimiter encoding of
VAL = BitsValue{bl(bytes)}: the bits cut before the last byte's highest set
bit), decode_unique, decode_reject, for every buffer on a perfect word tree of
depth d < 28 with n <= 4 2^d.

proofs/obj/vbyte.bend (generated here, stock): the byte facts by a decision on
the high bit of a byte w (U32 value PD.embed8(w)), the bits below it symbolic:

    oct_pack   pack(b8(w) ++ R) == embed8(w) :: pack(R)
    last_pack  embed8(w) != 0: pack(btk(h, b8(w)) ++ [True]) == [embed8(w)],
               h = O.high_bit(embed8(w)), the runtime's delimiter position
    last_len   |btk(h, b8(w))| == h
    inv_k      (k = 0..7) the byte octet(b0..b_{k-1}, True, 0..) is non-zero
               and its high bit is k.

The byte-list development on top of it is proofs/obj/vbitl.bend.
"""
import sys as _sys
import pathlib as _pathlib
_sys.path.insert(0, str(_pathlib.Path(__file__).resolve().parents[3]))  # the repository root: `codegen` is importable when this file runs as a script
from codegen.proofs.var.check_or_write_outputs import finish  # noqa: E402
from codegen.proofs.support import zeros_without_case_split as ZD  # noqa: E402


from codegen.core.repository_paths import ROOT  # noqa: E402
from codegen.core.template_loader_positional import Templates  # noqa: E402
TPL = Templates('bit_list_codec_laws', globals())
BYTE = ROOT / 'proofs/obj/vbyte.bend'


def word(bs):
    return ''.join(f'WCon{{{b}, ' for b in bs) + 'WNil{}' + '}' * len(bs)


def tf(b):
    return 'True{}' if b else 'False{}'


def byte_module():
    L = ['import Base', 'import ../../src/obj.bend as O', 'import ../../spec/bit_packing.bend as Bp',
         'import ../../proofs/power_division.bend as PD', 'import ../../proofs/word_split.bend as WSp',
         'import ../compact/found.bend as F', 'import ./bits_leaf.bend as BLf', 'import ./dk.bend as DK', '',
         '# GENERATED by bit_list_codec_laws (codegen). Do not edit.',
         '# Byte facts of the bit-list codec, by a decision on the high bit of a',
         '# byte (see the module docstring of codegen/proofs/var/bit_list_codec_laws.py).', '']
    w = L.append
    C = [f'c{i}' for i in range(8)]
    W8 = 'WCon{+c0, WCon{+c1, WCon{+c2, WCon{+c3, WCon{+c4, WCon{+c5, WCon{+c6, WCon{+c7, WNil{}}}}}}}}}'
    w(TPL.text('byte_module') + W8 + TPL.text('byte_module_2'))
    # The high bit at k with the k bits below it symbolic: U32.is_ge(byte, 2^k) never reads them
    # (fge: Word.cmp.fin of a bit against a zero bit keeps EQ/GT), and the higher pick tests of
    # O.high_bit fail by whnf, so each fact is one decision per high-bit position.
    def e8(bs):
        return f'PD.embed8({word(bs)})'

    def bk(k, var='b'):
        return [f'{var}{i}' for i in range(k)]

    def hk(k, var='b'):
        return bk(k, var) + ['True{}'] + ['False{}'] * (7 - k)

    def chain(v, k):  # O.high_bit's picks from 2^k down
        t = '0'
        for j in range(1, k + 1):
            t = f'O.pick(U32.is_ge({v}, {2 ** j}), {j}, {t})'
        return t
    w(TPL.text('byte_module_fge'))
    for k in range(1, 8):
        bs = bk(k)
        E = e8(hk(k))
        fa = ''.join(f'  for +{b}: Bool\n' for b in bs)
        xs = ['EQ{}']
        for i in reversed(range(k)):
            xs.insert(0, f'Word.cmp.fin(b{i}, False{{}}, {xs[0]})')
        pf = '{==}'
        for i in reversed(range(k)):
            pf = f'fge(b{i}, {xs[i + 1]}, {pf})'
        w(f'law ge{k}:\n{fa}  {{U32.is_ge({E}, {2 ** k}) == True{{}} : Bool}}')
        w(f'def ge{k}({", ".join(bs)}):\n  {pf}\n')
        w(f'law hb{k}:\n{fa}  {{{k}n == hb({E}) : Nat}}')
        w(f'def hb{k}({", ".join(bs)}):')
        w(f'  %Equal.sym(Bool, U32.is_ge({E}, {2 ** k}), True{{}}, ge{k}({", ".join(bs)})) :')
        w(f'    {{{k}n == U32.to_nat(O.pick(_, {k}, {chain(E, k - 1)})) : Nat}}')
        w('  {==}\n')
    # last_pack / last_len: a decision on the high bit, the bits below it symbolic
    PAT = 'WCon{+c0, WCon{+c1, WCon{+c2, WCon{+c3, WCon{+c4, WCon{+c5, WCon{+c6, WCon{+c7, WNil{}}}}}}}}}'
    for name, stmt in [('last_pack', lambda e, w8: f'{{Bp.pack(List.append(&2, Bool, btk(hb({e}), b8({w8})), [True{{}}])) == [{e}] : +List<U32>}}'),
                       ('last_len', lambda e, w8: f'{{List.length(&2, Bool, btk(hb({e}), b8({w8}))) == hb({e}) : Nat}}')]:
        def leaf(k, ind, name=name):
            cs = bk(k, 'c')
            W = word(hk(k, 'c'))
            E = f'PD.embed8({W})'
            if name == 'last_pack':
                oct = 'Bp.octet(' + ', '.join(hk(k, 'c')) + ')'
                return (f'{ind}%hb{k}({", ".join(cs)}) : {{Bp.pack(List.append(&2, Bool, btk(_, b8({W})), [True{{}}])) == [{E}] : +List<U32>}}\n'
                        f'{ind}Equal.cong(U32, +List<U32>, z => [z], {oct}, {E}, BLf.oct8({", ".join(hk(k, "c"))}))')
            return (f'{ind}%hb{k}({", ".join(cs)}) : {{List.length(&2, Bool, btk(_, b8({W}))) == _ : Nat}}\n'
                    f'{ind}{{==}}')

        # {name}_k: the bits above k are False; one match per level (a def per level: Bend matches a
        # parameter once).
        for k in range(8):
            Wk = word(bk(k + 1, 'c') + ['False{}'] * (7 - k))
            w(f'law {name}_{k}:')
            for i in range(k + 1):
                w(f'  for +c{i}: Bool')
            w(f'  for +nz: {{U32.is_eq(PD.embed8({Wk}), 0) == False{{}} : Bool}}')
            w(f'  {stmt(f"PD.embed8({Wk})", Wk)}')
            w(f'def {name}_{k}({", ".join(bk(k + 1, "c"))}, nz):')
            w(f'  match c{k}:')
            w('    case True{}:')
            w('      {==}' if k == 0 else leaf(k, '      '))
            w('    case False{}:')
            if k == 0:
                W0 = word(['False{}'] * 8)
                w(f'      Empty.absurd({stmt(f"PD.embed8({W0})", W0)}, F.logic__true_false(nz))')
            else:
                w(f'      {name}_{k - 1}({", ".join(bk(k, "c"))}, nz)')
            w('')
        for line in TPL.render('byte_module_lines', PAT=PAT, name=name, stmt=stmt).split('\n'):
            w(line)
    # inv_k
    for k in range(8):
        bs = [f'b{i}' for i in range(k)]
        oct = 'Bp.octet(' + ', '.join(bs + ['True{}'] + ['False{}'] * (7 - k)) + ')'
        w(f'law inv{k}:')
        for b in bs:
            w(f'  for +{b}: Bool')
        w(f'  DK.P2({{U32.is_eq({oct}, 0) == False{{}} : Bool}}, {{{k}n == hb({oct}) : Nat}})')
        w(f'def inv{k}(' + ', '.join(bs) + '):')
        if k == 0:
            w('  ({==}, {==})')
        else:
            E = e8(hk(k))
            for line in TPL.render('byte_module_lines_2', E=E, bs=bs, hk=hk, k=k, oct=oct).split('\n'):
                w(line)
        w('')
    return '\n'.join(L) + '\n'


# ---- the generic bit lists (whole buffer = one BitList[N]) --------------------------------------

def ceil_log2(x):
    return max(0, (x - 1).bit_length())


GHEAD = ['import Base', 'import ../../src/buffer.bend as B', 'import ../../src/obj.bend as O', 'import ../../types/generic_obj.bend as T',
         'import ../../types/schema.bend as S', 'import ../compact/found.bend as FD', 'import ../compact/arith.bend as A',
         'import ../../proofs/nat_order.bend as Order', 'import ../../spec/primitives.bend as SP', 'import ../../spec/codec.bend as Codec',
         'import ../../spec/decoding_relation.bend as Decoding', 'import ../../spec/bitfields.bend as Bits', 'import ../../spec/bit_packing.bend as Bp',
         'import ./generic_specs.bend as GS', 'import ./spec_fixed.bend as FX', 'import ./vspec.bend as VS', 'import ./vbuf.bend as VB',
         'import ./vcopy.bend as VC', 'import ./vdepth.bend as VD', 'import ./vu32.bend as VU', 'import ./vlist.bend as VL',
         'import ./vbitl.bend as VBL', 'import ./vbyte.bend as VY', 'import ./vbrt.bend as VR']

GBODY = TPL.text('GBODY')

GBODY2 = TPL.text('GBODY2')


def zeros_at_text(KK):
    return ZD.zeros_at_text(KK)


def gbits_names():
    from codegen.core import generic_form_schemas as gen
    from codegen.impl import typed_object_runtime as G
    g = G.Gen()
    out = []
    for n, t, err in gen.inventory_all():
        if err:
            continue
        try:
            s = g.shape(t)
        except Exception:
            continue
        if t.kind == 'bitlist':
            out.append((n, t.size, s.p))
    return out


def gbits_text(X, N, p):
    C = N // 8
    BMAX = C + 1
    YMAX = 31 + BMAX
    K = ceil_log2((YMAX >> 2) + 8)
    KB = ceil_log2(YMAX)
    assert KB < 31 and K <= 30
    body = GBODY + '\n' + zeros_at_text(K) + GBODY2
    for k, v in [('@BMAXn', f'{BMAX}n'), ('@YMAXn', f'{YMAX}n'), ('@Cn', f'{C}n'), ('@Kn', f'{K}n'), ('@KBn', f'{KB}n'), ('@Nn', f'{N}n'), ('@N', str(N)),
                 ('@X_', f'{X}_'), ('@X(', f'{X}('), ('@p_', f'{p}_')]:
        body = body.replace(k, v)
    L = GHEAD + ['', '# GENERATED by bit_list_codec_laws (codegen). Do not edit.',
                 f'# {X}: BitList[{N}] (runtime {p}): the validator, the decoder and the spec relation',
                 '# (see the module docstring of codegen/proofs/var/bit_list_codec_laws.py).', '']
    return '\n'.join(L) + body


def gbits_unique(X):
    return TPL.render('gbits_unique', X=X)


GREJ = TPL.text('GREJ')


def gbits_rej(X, N):
    body = GREJ
    for k, v in [('@Nn', f'{N}n'), ('@N', str(N)), ('@X(', f'{X}(')]:
        body = body.replace(k, v)
    L = GHEAD + [f'import ./var_bits_{X}.bend as DC', '', '# GENERATED by bit_list_codec_laws (codegen). Do not edit.',
                 f'# {X}: every byte string the spec relates to a value passes the validator.', '']
    return '\n'.join(L) + body


def main():
    # accepts '--check' (check_or_write_outputs.finish reads it)
    out = {BYTE: byte_module()}
    for X, N, p in gbits_names():
        out[ROOT / f'proofs/obj/var_bits_{X}.bend'] = gbits_text(X, N, p)
        out[ROOT / f'proofs/obj/var_bits_{X}_unique.bend'] = gbits_unique(X)
        out[ROOT / f'proofs/obj/var_bits_{X}_rej.bend'] = gbits_rej(X, N)
    orphans = sorted(str(q.relative_to(ROOT)) for q in (ROOT / 'proofs/obj').glob('var_bits_*.bend') if q not in out and not q.name.startswith('var_bits_enc_'))
    return finish(out, 'stale generated bit-list laws: ', 'generated bit-list laws are current', orphans)


if __name__ == '__main__':
    main()
