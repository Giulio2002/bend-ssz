"""Reads of short fields near the end of the buffer (proofs/obj/vedge.bend).

    python3 codegen/proofs/var/vedge.py [--check]

The runtime reads a field of k < 4 bytes at byte X with B.read32(buf, X) and keeps its
low k bytes. At an unaligned X the read joins word q = X >> 2 with word q + 1; near the
end of the buffer word q + 1 lies past it (Array.get wraps the index), but when
(X & 3) + k <= 4 the kept bytes come from word q alone. This module proves:
  - rd_same: read32 leaves the buffer as it is (every Array.get does), whatever X;
  - kv<k>:   the kept k bytes are those of UA.RW(t, X) when the k bytes are in the buffer.
"""
