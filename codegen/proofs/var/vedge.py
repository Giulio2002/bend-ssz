def kv_text(k):
    L = []
    RW = 'UA.RW(t, X)'
    G = f'{{O.keep({k}, RV(t, n, X)) == O.keep({k}, {RW}) : U32}}'
    SIG = ('+d: Nat, +t: F.array__Tree<U32>, +n: U32, +X: U32, +hd: {Nat.is_lt(d, 31n) == True{} : Bool}, +pf: {F.array__perfect(U32, d, t) == True{} : Bool},\n'
           f'    +hb: {{Nat.is_le(Nat.add(U32.to_nat(X), {k}n), A.quad(VB.pw(d))) == True{{}} : Bool}}')
    BFn = 'UA.BF(t, n)'
    lo = 'VB.slot(t, VR.QX(X))'
    hi = 'VB.slot(t, 1n+VR.QX(X))'
    I1 = 'U32.add(U32.shrn(X, 2n), 1)'
    L.append(f'# The low {k} byte(s) the runtime reads at X are those of RW(t, X), for X + {k} inside the buffer')
    L.append('# (word q + 1 may lie past it: its bytes are then not kept).')
    L.append(f'def kvr{k}({SIG}, +r: Nat, +er: {{VR.RX(X) == r : Nat}}, +hr: {{Nat.is_lt(r, 4n) == True{{}} : Bool}}) -> {G}:')
    L.append('  match r:')
    RDW0 = f'VR.rdw(d, t, n, U32.shrn(X, 2n), VR.QX(X), {{==}}, VB.lt32(d, hd), hq, pf)'
    for j in range(4):
        L.append(f'    case {j}n:')
        L.append(f'      +e3 = F.u32__injective(U32.and(X, 3), {j}, er)')
        L.append(f'      +hq = VR.hiX(d, X, U32.to_nat(X), {{==}}, VXG.ltx(U32.to_nat(X), {k}n, A.quad(VB.pw(d)), {{==}}, hb))')
        L.append(f'      %Equal.sym(U32, U32.and(X, 3), {j}, e3) : {{O.keep({k}, Pair.snd(B.Buf, U32, B.read32_choose(X, _, U32.is_eq(_, 0), {BFn}))) == O.keep({k}, {RW}) : U32}}')
        if j == 0:
            L.append(f'      %Equal.sym(B.Buf & U32, B.word({BFn}, U32.shrn(X, 2n)), ({BFn}, {lo}), {RDW0}) :')
            L.append(f'        {{O.keep({k}, Pair.snd(B.Buf, U32, _)) == O.keep({k}, {RW}) : U32}}')
            L.append(f'      %Equal.sym(Nat, VR.RX(X), 0n, er) : {{O.keep({k}, {lo}) == O.keep({k}, UA.jn(_, {lo}, {hi})) : U32}}')
            L.append('      {==}')
            continue
        L.append(f'      %Equal.sym(B.Buf & U32, B.word({BFn}, U32.shrn(X, 2n)), ({BFn}, {lo}), {RDW0}) :')
        L.append(f'        {{O.keep({k}, Pair.snd(B.Buf, U32, B.read32_split(X, {j}, _))) == O.keep({k}, {RW}) : U32}}')
        if j + k <= 4:
            GWt = f'GW(t, {I1})'
            L.append(f'      %Equal.sym(B.Buf & U32, B.word({BFn}, {I1}), ({BFn}, {GWt}), wsame(t, n, {I1})) :')
            L.append(f'        {{O.keep({k}, Pair.snd(B.Buf, U32, B.join_words({j}, {lo}, _))) == O.keep({k}, {RW}) : U32}}')
            L.append(f'      %Equal.sym(Nat, VR.RX(X), {j}n, er) : {{O.keep({k}, B.join_sel({j}, {lo}, {GWt})) == O.keep({k}, UA.jn(_, {lo}, {hi})) : U32}}')
            a, z, b = (f'O.keep({k}, B.join_sel({j}, {lo}, {GWt}))', f'O.keep({k}, B.join_sel({j}, {lo}, 0))', f'O.keep({k}, B.join_sel({j}, {lo}, {hi}))')
            L.append(f'      Equal.trans(U32, {a}, {z}, {b}, kz{j}{k}({lo}, {GWt}), Equal.sym(U32, {b}, {z}, kz{j}{k}({lo}, {hi})))')
        else:
            L.append(f'      +e4 = Equal.trans(Nat, U32.to_nat(X), Nat.add(A.quad(VR.QX(X)), VR.RX(X)), Nat.add(A.quad(VR.QX(X)), {j}n), VC.split4(X),')
            L.append(f'        Equal.cong(Nat, Nat, z => Nat.add(A.quad(VR.QX(X)), z), VR.RX(X), {j}n, er))')
            L.append(f'      +hq1 = q1x(VR.QX(X), VB.pw(d), F.logic__subst(Nat, z => {{Nat.is_le(Nat.add(z, {k}n), A.quad(VB.pw(d))) == True{{}} : Bool}}, U32.to_nat(X), Nat.add(A.quad(VR.QX(X)), {j}n), e4, hb))')
            L.append(f'      %Equal.sym(B.Buf & U32, B.word({BFn}, {I1}), ({BFn}, {hi}),')
            L.append(f'          VR.rdw(d, t, n, {I1}, 1n+VR.QX(X), VB.add_le_at(U32.shrn(X, 2n), 1, VR.QX(X), d, {{==}}, hd, F.nat__lt_le(1n+VR.QX(X), VB.pw(d), hq1)), VB.lt32(d, hd), hq1, pf)) :')
            L.append(f'        {{O.keep({k}, Pair.snd(B.Buf, U32, B.join_words({j}, {lo}, _))) == O.keep({k}, {RW}) : U32}}')
            L.append(f'      %Equal.sym(Nat, VR.RX(X), {j}n, er) : {{O.keep({k}, B.join_sel({j}, {lo}, {hi})) == O.keep({k}, UA.jn(_, {lo}, {hi})) : U32}}')
            L.append('      {==}')
    L.append(f'    case 4n+s: Empty.absurd({G}, F.nat__lt_zero_absurd(s, hr))')
    L.append('')
    L.append(f'def kv{k}({SIG}) -> {G}:')
    L.append(f'  kvr{k}(d, t, n, X, hd, pf, hb, VR.RX(X), {{==}}, UA.rx_lt(X))')
    L.append('')
    return '\n'.join(L)


def main_text():
    return '\n'.join(HEAD) + bits_text() + ARR + kv_text(1) + '\n' + kv_text(2) + '\n'


def main():
    txt = main_text()
    if '--check' in sys.argv:
        if not OUT.exists() or OUT.read_text() != txt:
            print('stale: proofs/obj/vedge.bend')
            sys.exit(1)
        print('vedge is current')
        return
    OUT.write_text(txt)
    print('wrote proofs/obj/vedge.bend')


if __name__ == '__main__':
    main()
