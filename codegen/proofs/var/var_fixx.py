def gen_text():
    """proofs/obj/vfxg.bend: the readers and values, for every size (instantiated by the
    vfx_<p> modules with closed facts that evaluate to True)."""
    L = list(GEN_HEAD) + ['', '# GENERATED by var_fixx (codegen). Do not edit.',
                          '# Fixed fields at any byte position, for every size: see codegen/proofs/var/var_fixx.py.', '']
    P = 'A.quad(VB.pw(d))'
    L.append(TEMPLATES.render('gen_text'))
    L.append(TEMPLATES.render('gen_text_2', P=P))
    L.append(TEMPLATES.render('gen_text_3', P=P))
    for ch, mm, vp, el in (('ch8', 'm8', 'vparts8', 'S.ByteVector{32n}'), ('chu2', 'm2', 'vpartsu2', 'S.Unsigned{P.U64{}}'), ('ch12', 'm12', 'vparts12', 'S.ByteVector{48n}')):
        W = 'UR.RWS(M, t, x)'
        L.append(TEMPLATES.render('gen_text_4', ch=ch, el=el, mm=mm, P=P, W=W, vp=vp))
    L.append(sc_text())
    out = []
    for blk in L:
        for X, X0 in (('prt_', 'prt0_'), ('offc(', 'offc0('), ('splitC(', 'splitC0(')):
            if f'def {X0}' in blk:
                a = blk.index(f'def {X}')
                b = blk.index(f'def {X0}')
                e = blk.find('\n\n', b)
                e = len(blk) if e < 0 else e + 1
                blk = blk[:a] + blk[b:e].rstrip('\n') + '\n' + blk[a:b] + blk[e:]
        out.append(blk)
    return '\n'.join(out) + '\n'


