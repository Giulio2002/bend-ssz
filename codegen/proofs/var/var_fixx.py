def rt_depth(p):
    """The zero storage depth the runtime reader of p allocates."""
    import re
    src = RR.mono_text('fulu')
    m = re.search(rf'^def {p}_read\(.*Array\.new\(U32, (\d+)n, 0\)\)$', src, re.M)
    return int(m.group(1))


def big_pow(S):
    """A byte size handled symbolically (proofs/obj/vbig.bend): a power of two of at least 2^16."""
    return S >= 65536 and S & (S - 1) == 0


def vec_text(p, S, k, sch, ch, el):
    """A Vector of k elements, S bytes, read by copy_into."""
    M = S // 4
    EL = {'ch8': 'S.ByteVector{32n}', 'chu2': 'S.Unsigned{P.U64{}}', 'ch12': 'S.ByteVector{48n}'}[ch]
    dz = rt_depth(p)
    ky = log2c(S + 31)
    L = list(HEAD) + ['import ./schema_shapes.bend as SH', 'import ./vfxg.bend as VXG'] + (['import ./vbig.bend as VG'] if big_pow(S) and ch != 'ch12' else []) + [
        '', '# GENERATED by var_fixx (codegen). Do not edit.',
        f'# {p}: Vector[{el}, {k}] ({S} bytes) at any byte position: see codegen/proofs/var/var_fixx.py.', '']
    if big_pow(S) and ch != 'ch12':
        # the size as U32.to_nat(S) and the counts over U32.to_nat(k): the facts are symbolic
        # (vbig.bend); closed, they were unary work of millions of steps
        r, e = S.bit_length() - 1, k.bit_length() - 1
        q = r - 2
        mm, es = ('m8', 'es_pow') if ch == 'ch8' else ('m2', 'es_pow2')
        SN, KN = f'U32.to_nat({S})', f'U32.to_nat({k})'
        EK = f'VG.u32pow({k}, {e}n, {{==}}, {{==}})'
        L.append(TEMPLATES.render('vec_text', S=S, dz=dz, SN=SN, p=p, ky=ky, q=q, r=r, ch=ch, mm=mm, KN=KN, sch=sch, EL=EL, e=e, EK=EK, es=es))
        return fx_deep('\n'.join(L) + '\n')
    L.append(TEMPLATES.render('vec_text_2', S=S, dz=dz, p=p, ky=ky, ch=ch, M=M, sch=sch, k=k, EL=EL))
    return fx_deep('\n'.join(L) + '\n')


