def log2c(n):
    k = 0
    while (1 << k) < n:
        k += 1
    return k


def sig(name, S, rest='', sn=None):
    return (f'def {name}(+d: Nat, +t: {TR}, +n: U32, +off: U32, +x: Nat, +e: {{U32.to_nat(off) == x : Nat}},\n'
            f'    +hd: {{Nat.is_lt(d, 28n) == {TRUE}}}, +pf: {{FD.array__perfect(U32, d, t) == {TRUE}}},\n'
            f'    +hb: {{Nat.is_le(Nat.add(x, {sn or str(S) + "n"}), A.quad(VB.pw(d))) == {TRUE}}}){rest}')


