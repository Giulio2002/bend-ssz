def have(f):
    src = (ROOT / f'proofs/obj/{f}').read_text()
    return {ln.split('(')[0][len('def rdx_'):] for ln in src.splitlines() if ln.startswith('def rdx_')}


def seq_head(sch, val, proof, W, exact):
    """For a fulu container Spec.X() whose walk() proof is F.aggregate_fixed(Codec.parts(items, chain), ..):
    first rewrite Codec.parts(VAL(t, x), Spec.X()) to Codec.aggregate(Codec.parts(items, chain), Some{n}) by
    VSQ.seq_parts (proofs/obj/vseq.bend), and chain the fields by VS.chain_fixed. Otherwise the conversion to aggregate_fixed's
    statement evaluates the whole container's parts (checker_findings item 2)."""
    import re
    from codegen.proofs.var import var_laws as VLW
    from codegen.proofs.var import var_bytes_x as VBX
    m = re.fullmatch(r'Spec\.(\w+)\(\)', sch)
    head = 'F.aggregate_fixed('
    if exact or not m or not proof.startswith(head) or not val.startswith('S.Sequence{'):
        return proof
    try:
        names = VBX.spec_names(m.group(1))
    except AssertionError:
        return proof
    args = VLW._split_args(proof[len(head):-1])
    assert len(args) == 5 and proof.endswith(')'), args
    a, n = args[0], args[2]
    items, chain = VLW._split_args(a[len('Codec.parts('):-1])
    assert val == f'S.Sequence{{{items}}}', (val, items)
    MP = 'Maybe<&2, +List<S.Part>>'
    RHS = f'Some{{[S.Fixed{{F.limbs(UR.RWS({W}n, t, x))}}]}}'
    return (TEMPLATES.render('seq_head', MP=MP, sch=sch, a=a, chain=chain, items=items, names=names, RHS=RHS, n=n, proof=proof, VLW=VLW))


def small_mod(g, t, sch, exact=False):
    """A fixed type read word by word: thin wrappers over vua_fix / vbx_fix (or a reader here).
    exact: the spec-parts proof in spec_laws' SL.EXACT form, the schema rewritten to its node's first."""
    from codegen.proofs.var import var_laws as VLW
    from codegen.proofs.var import var_ua as VUA
    ft = VLW.FT(g, t)
    p, S, W = ft.p, ft.size, ft.W
    vtx, xf = have('vua_fix.bend'), have('vbx_fix.bend')
    word = lambda k: 'UR.RWN(t, x)' if k == 0 else f'UR.RWN(t, {4 * k}n+x)'
    OBJ = ft.obj([word(k) for k in range(W)])
    nd = VLW.SL.walk(g, t, iter(range(100000)))
    mp = {int(w_[1:]): word(j) for j, w_ in enumerate(nd.words)}
    val, proof = VLW.subst_words(nd.val, mp), VLW.subst_words(nd.proof, mp)
    proof = seq_head(sch, val, proof, W, exact)
    L = list(HEAD) + (['import ../../spec/schema.bend as SC', 'import ./vseq.bend as VSQ'] if 'SC.' in proof else []) + [
        '', '# GENERATED by var_fixx (codegen). Do not edit.', f'# {p} ({S} bytes) at any byte position: see codegen/proofs/var/var_fixx.py.', '']
    local = []
    for dep in ft.deps():
        if dep.p in vtx or dep.p in xf:
            continue
        for ln in VUA.rdx_lemma(dep):
            ln = ln.replace('ltp(', 'VTX.ltp(').replace('F.', 'FD.')
            for kp in vtx:
                ln = ln.replace(f'rdx_{kp}(', f'VTX.rdx_{kp}(')
            for kp in xf:
                ln = ln.replace(f'rdx_{kp}(', f'XF.rdx_{kp}(')
            L.append(ln)
        L.append('')
        local.append(dep.p)
    ref = f'VTX.rdx_{p}' if p in vtx else (f'XF.rdx_{p}' if p in xf else f'rdx_{p}')
    if p in xf:
        L.insert(L.index('import ./vua_fix.bend as VTX') + 1, 'import ./vbx_fix.bend as XF')
    P = 'A.quad(VB.pw(d))'
    xrw = (f'  %Equal.sym(S.Schema, {sch}, {nd.sch}, {{==}}) : {{Codec.parts(VAL(t, x), _) == Some{{[S.Fixed{{F.limbs(UR.RWS({W}n, t, x))}}]}} : Maybe<&2, +List<S.Part>>}}\n'
           if exact else '')
    L.append(TEMPLATES.render('small_mod', ft=ft, OBJ=OBJ, S=S, p=p, ref=ref, val=val, P=P, sch=sch, W=W, xrw=xrw, proof=proof))
    return p, fx_deep('\n'.join(L) + '\n')



