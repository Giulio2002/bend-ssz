#!/usr/bin/env python3
"""List[uint16, N] of the generic containers (types/generic_obj.bend) at a window of any
byte offset: the interface of proofs/obj/vua_win.bend (CHKw, ok_evalw, OBJw, readw, VALw,
specw, invw), for each N in LISTS.

    python3 codegen/proofs/var/var_winl16.py [--check]

The runtime copies the window's words (O.copy_in) and checks whole elements, at most N;
the value is the 2-byte items of the window's bytes (pb_min.it2). The item and parts
lemmas follow codegen/proofs/var/var_plist_sub.py's ProgressiveList[uint16] window.
"""
import sys as _sys
import pathlib as _pathlib
_sys.path.insert(0, str(_pathlib.Path(__file__).resolve().parents[3]))  # the repository root: `codegen` is importable when this file runs as a script
import sys
from codegen.core.bendtext import generic  # noqa: E402
from codegen.core import writer  # noqa: E402

from codegen.proofs.var import var_win as VW  # noqa: E402

from codegen.core.paths import ROOT  # noqa: E402
from codegen.core.shared_var_a import Templates  # noqa: E402
TEMPLATES = Templates('var_winl16', globals())
LISTS = [1024, 128, 123]
HDR = '# GENERATED by var_winl16 (codegen). Do not edit.'


TEMPLATE = TEMPLATES.text('TEMPLATE')


def rep16_text():
    """vspec.bend's inversion of repeated uint64 parts, for uint16 (2 bytes each)."""
    src = (ROOT / 'proofs/obj/vspec.bend').read_text().split('\n')
    a = src.index('def REPF(+its: S.Value, +ps: +List<S.Part>) -> Type:')
    b = next(i for i in range(a, len(src)) if src[i].startswith('law allfix_pay:'))
    txt = '\n'.join(src[a:b]).rstrip()
    for o, n in [('F.', 'FD.'), ('x8(', 'Nat.double('), ('8n+Nat.double', '2n+Nat.double'), ('== 8n', '== 2n'), ('SP.prefix(8n,', 'SP.prefix(2n,'),
                 ('Some{8n}', 'Some{2n}'), (', 8n, l8)', ', 2n, l8)'), ('{8n+_', '{2n+_'), ('U64S()', 'U16S()'), ('P.U64{}', 'P.U16{}'), ('allfix(', 'VS.allfix(')]:
        txt = txt.replace(o, n)
    assert '8n' not in txt and 'x8' not in txt, txt
    return txt


def absurd_v(goal):
    L = []
    for c, args in VW.VALUE_CTORS:
        if c == 'Sequence':
            continue
        pat = f'S.{c}{{' + ', '.join('+' + a for a in args) + '}'
        L.append(f'    case {pat}: Empty.absurd({goal}, FD.logic__none_some(+List<S.Part>, [S.Variable{{UW.WX(t, x, U32.to_nat(len))}}], e))')
    return '\n'.join(L)


IMPORTS = ['import ../../spec/root_relation.bend as RR', 'import ./vua_rd.bend as UR', 'import ./vvlz.bend as VZG', 'import ./vu8.bend as U8',
           'import ./vmv.bend as VMV', 'import ./pb_min.bend as PB']


def win_text(N):
    p = f'l{N}_u16'
    body = TEMPLATE.replace('@REP', rep16_text()).replace('@ABSURDV', absurd_v('{CHKw(t, x, off, len) == True{} : Bool}'))
    body = body.replace('@Nn', f'{N}n').replace('@N', str(N)).replace('@p_', f'{p}_')
    assert '@' not in body.replace('&2', '').replace('@+', ''), [ln for ln in body.splitlines() if '@' in ln.replace('&2', '').replace('@+', '')][:3]
    L = generic(VW.HEADX) + IMPORTS + ['', HDR, f'# List[uint16, {N}] ({p}) at a window of any byte offset x: the interface of proofs/obj/vua_win.bend,',
                                       '# at any depth d < 31 (the limit bounds the copy: var_vlist.bounded_text).', '']
    return deep_text('\n'.join(L) + VW.COMMONX + body, N)


RD_OLD = """  +hL = hlen(d, x, len, hw)
  +hz = VLS.hdz29(d, len, hd, hL)
  +ez = FD.logic__subst(Nat, z => {B.zeros(B.words_depth_u(VC.WZ(len))) == Array.new(U32, z, 0) : Array<U32>}, U32.to_nat(B.words_depth_u(VC.WZ(len))), VLS.DZ(len),
    VD.wdu(VC.WZ(len)), VZG.zg(B.words_depth_u(VC.WZ(len))))
  UCT.copy_in_at(d, t, n, off, len, VLS.DZ(len), VLS.KK(d), pf, FD.nat__lt_trans(d, 28n, 31n, hd, {==}), FD.nat__le_lt_trans(VLS.DZ(len), 29n, 31n, hz, {==}), ez,
    UW.hsx(d, off, x, len, eo, hd, hw), VLS.hrg(d, len, hd, hL), VLS.kk_lt(d, hd), VLS.hyn(d, len, hL))"""
FIT_OLD = 'VFT.fits4(2n+d, U32.to_nat(len), hlen(d, x, len, hw), FD.nat__lt_trans(d, 28n, 30n, hd, {==}))'


def deep_text(text, N):
    """The window at any depth d < 31: at most 2 N bytes (eLc, hcL), so the copy's bounds are the limit's
    (var_vlist.bounded_text, copy_in_at with UW.hsxB); fits of a U32; var_win.deep_x threads hw32."""
    from codegen.proofs.var import var_vlist as VVG
    for a in (RD_OLD, FIT_OLD):
        assert a in text, a[:60]
    B = 2 * N
    KB, K, bounds = VVG.bounded_text(B)
    hb = TEMPLATES.render('deep_text', B=B, N=N) + bounds
    text = text.replace(RD_OLD, '  +hb = hB(t, x, off, len, hchk)\n  +hz = hdzK(len, hb)\n' + VVG.bounded_copy(KB, K))
    text = text.replace(FIT_OLD, 'VFT.fits4lt(U32.to_nat(len), VB.u32_lt(len))')
    a = text.index('\n# The reader on the window')
    text = text[:a] + '\n' + hb + text[a:]
    text = VVG._keep_sig(text, 'hlen')
    return VW.deep_x(text)


def outputs():
    return {ROOT / f'proofs/obj/var_winx_l{N}_u16.bend': win_text(N) for N in LISTS}


def main():
    out = outputs()
    from codegen.impl import runtime_refs as RR  # the runtime split: the modules import the per-name files they use
    out = RR.rewire_out(out)
    if '--check' in sys.argv:
        return writer.check(out, 'stale: ', 'uint16 list windows are current')
    for p, t in out.items():
        p.write_text(t)
    print('wrote ' + ', '.join(str(p.relative_to(ROOT)) for p in out))


if __name__ == '__main__':
    main()
