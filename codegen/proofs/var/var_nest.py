"""Window laws of the var_laws.py family, for nesting.

A name X of codegen/proofs/var/var_laws.py read at a symbolic word-aligned window of a
buffer (byte offset off = 4 i, length len) instead of the whole buffer:
proofs/obj/<big_>var_codec_X_win.bend holds

    ok_evalw   X_ok(BF(t, n), off, len) returns the buffer and CHKw(t, i, len);
    readw      CHKw holds: X_read(BF(t, n), off, len) returns OBJw(t, i, len);
    encpw      the spec parts of VALw(t, i, len) are one variable part holding
               the limbs of the window's words (lim_eqw),

for every perfect tree t of depth d < 29 with 4 i + len <= 4 2^d. They are the
building blocks of containers whose fields are X (codegen/proofs/var/var_nest.py
AttesterSlashing).
"""
from codegen.proofs.var import var_laws as VL
from codegen.proofs.support import lim_pow as LPW
from codegen.core.shared_var_b import Templates  # noqa: E402
TPL = Templates('var_nest', globals())


def win_module_text(g, x):
    n, FS, H, po, K = x.n, x.FS, x.H, x.po, x.K
    Tn = f'T.{n}'
    cvar = x.var['c']
    KK = max(K, x.KO)
    L = list(VL.DEC_HEAD) + [f'import ./{VL.fname(x).name} as DC'] + VL.lim_imports(x) + VL.SPEC_IMPORTS + ['',
                             '# GENERATED by var_nest (codegen). Do not edit.',
                             f'# {n} at a word-aligned window (off = 4 i, len) of a buffer: the validator,',
                             '# the reader and the spec parts of the value, for nesting (see the module',
                             '# docstring of codegen/proofs/var/var_nest.py).', '']
    w = L.append
    WH = ('+eo: {U32.to_nat(off) == A.quad(i) : Nat}, +hd: {Nat.is_lt(d, 31n) == True{} : Bool},\n'
          '    +hw: {Nat.is_le(Nat.add(A.quad(i), U32.to_nat(len)), A.quad(VB.pw(d))) == True{} : Bool},\n'
          '    +hw32: {Nat.is_lt(Nat.add(A.quad(i), U32.to_nat(len)), FD.spec_common__pow2(32n)) == True{} : Bool}')
    PF = '+pf: {FD.array__perfect(U32, d, t) == True{} : Bool}'
    HA = f'+ha: {{U32.is_le({FS}, len) == True{{}} : Bool}}'
    HC = '+hc: {DC.whole(DC.LL(len)) == True{} : Bool}'
    s = 'FD.array__slots(U32, t)'
    NW = 'VC.NW(DC.LL(len))'
    w(TPL.render('win_module_text', FS=FS, H=H, HA=HA, HC=HC, NW=NW, PF=PF, Tn=Tn, WH=WH, cvar=cvar, po=po))
    # ---- the reader ----
    objs = []
    for f in x.fields:
        if f['kind'] == 'fix':
            objs.append(f['ft'].obj([f'VB.slot(t, Nat.add({f["k"] + j}n, i))' for j in range(f['ft'].W)]))
        else:
            objs.append(f'O.Words{{FD.array__thaw(U32, VB.mone({NW}, Nat.add({H}n, i), 0n, dz, VC.ZT(dz), t)), DC.LL(len)}}')
    OBJz = f'{Tn}{{' + ', '.join(objs) + '}'
    RHS = f'(DC.BF(t, n), {OBJz})'
    TY = f'B.Buf & {Tn}'
    for line in TPL.render('win_module_text_lines', FS=FS, H=H, HA=HA, NW=NW, PF=PF, RHS=RHS, TY=TY, Tn=Tn, WH=WH, cvar=cvar, po=po).split('\n'):
        w(line)

    def read_term(f, o):
        if f['kind'] == 'fix':
            ft = f['ft']
            return f'T.{ft.p}_read(DC.BF(t, n), U32.add(off, {f["c"]}), {ft.size})'
        return f'T.{x.lp}_read(DC.BF(t, n), U32.add(off, {o}), U32.sub(len, {o}))'
    w(f'  %Equal.sym(U32, SPOw(t, i), {FS}, epo) :')
    w(f'    {{{Tn}_rd1(off, len, _, {read_term(x.fields[0], "_")}) == {RHS} : {TY}}}')
    for j, f in enumerate(x.fields):
        args = ', '.join(['off', 'len', f'{FS}'] + objs[:j])
        if f['kind'] == 'fix':
            ft = f['ft']
            k = f['k']
            hb = (f'FD.nat__le_trans(Nat.add({ft.W}n, Nat.add({k}n, i)), Nat.add({H}n, i), VB.pw(d), '
                  f'Order.left_below_sum({H - ft.W - k}n, Nat.add({ft.W}n, Nat.add({k}n, i))), hHi)')
            w(f'  %Equal.sym(B.Buf & {ft.rep()}, {read_term(f, FS)}, (DC.BF(t, n), {objs[j]}),')
            w(f'      VT.rdd_{ft.p}(d, t, n, U32.add(off, {f["c"]}), Nat.add({k}n, i), eoc(d, i, off, len, {k}n, {f["c"]}, {{==}}, {{==}}, eo, hd, hw, hw32, ha), hd, pf, {hb})) :')
        else:
            eF = f'eoc(d, i, off, len, {H}n, {FS}, {{==}}, {{==}}, eo, hd, hw, hw32, ha)'
            for line in TPL.render('win_module_text_lines_2', FS=FS, H=H, eF=eF, j=j, objs=objs).split('\n'):
                w(line)
        w(f'    {{{Tn}_rd{j + 1}({args}, _) == {RHS} : {TY}}}')
    w('  {==}')
    w('')
    OBJ = OBJz.replace('dz', 'DC.DZ(len)')
    w(f'def OBJw(+t: FD.array__Tree<U32>, +i: Nat, +len: U32) -> {Tn}: {OBJ}')
    w(TPL.render('win_module_text_rdw_go', FS=FS, HA=HA, HC=HC, K=K, KK=KK, PF=PF, TY=TY, Tn=Tn, WH=WH))
    # ---- the spec side ----
    ITEMS, CHAIN, PL, CAT, PRE, POST, hdr, LIMN, YS = VL.spec_parts(g, x, lambda k: f'VB.slot(t, Nat.add({k}n, i))')
    LP = LPW.LimPow(LIMN)  # the closed fits fact: `{==}` for a small limit, symbolic (codegen/proofs/support/lim_pow.py) for 2^p
    K_FIT = LP.fits(LP.add(FS, LP.x8()), LP.bound(LP.add(FS, LP.x8()))) if LP.big else '{==}'
    HDR = ' <> '.join(hdr)
    ENCR = f'List.append(&2, U32, List.append(&2, U32, F.flat({PRE}), List.append(&2, U32, N.digits(4n, VS.FSZ({PRE}, {POST})), F.flat({POST}))), F.limbs({YS}))'
    MP = 'Maybe<&2, +List<S.Part>>'
    M = 'Maybe<&2, +List<U32>>'
    RP = f'Some{{[S.Variable{{F.limbs({HDR} <> {YS})}}]}}'
    MM = f'VB.mone({NW}, Nat.add({H}n, i), 0n, DC.DZ(len), VC.ZT(DC.DZ(len)), t)'
    LM = f'VB.lm({NW}, Nat.add({H}n, i), 0n, FD.array__slots(U32, VC.ZT(DC.DZ(len))), {s})'
    hdrs = ' <> '.join(h if j != po else 'SPOw(t, i)' for j, h in enumerate(hdr))
    hdrh = ' <> '.join(h if j != po else '_' for j, h in enumerate(hdr))
    RW = f'F.limbs(VF.app(VF.wpre({H}n, i, {s}), VS.wtake({NW}, VB.wdr(Nat.add({H}n, i), {s}))))'
    WIN = f'F.limbs(VS.wtake(Nat.add({H}n, {NW}), VB.wdr(i, {s})))'
    w(TPL.render('win_module_text_XVw', CAT=CAT, CHAIN=CHAIN, ENCR=ENCR, FS=FS, H=H, HA=HA, HC=HC, HDR=HDR, ITEMS=ITEMS, K_FIT=K_FIT, LIMN=LIMN, LM=LM, M=M, MM=MM, MP=MP, NW=NW, PF=PF, PL=PL, POST=POST, PRE=PRE, RP=RP, RW=RW, WIN=WIN, YS=YS, hdrh=hdrh, hdrs=hdrs, n=n, s=s))
    return '\n'.join(L) + '\n'


# ---- a container of two variable-size family fields (AttesterSlashing) ----------------------------

AS_DEC = TPL.text('AS_DEC')


def as_module_text(g, xc, parent='AttesterSlashing'):
    FS, H = xc.FS, xc.H
    P, C = f'T.{parent}', f'T.{xc.n}'
    L = list(VL.DEC_HEAD) + [f'import ./{VL.fname(xc).name} as DC', f'import ./{VL.fname(xc, "_win").name} as W',
                             'import ./vdig.bend as VG', 'import ./vfits.bend as VFT', 'import ../../src/primitives.bend as I', '',
                             '# GENERATED by var_nest (codegen). Do not edit.',
                             f'# {parent}: a container of two variable-size {xc.n} fields, decoded through',
                             f'# the window laws of {VL.fname(xc, "_win").name}.', '']
    txt = AS_DEC
    for k, v in [('@P_', f'{P}_'), ('@C_', f'{C}_'), ('Spec.@C()', f'Spec.{xc.n}()'), ('Spec.@N()', f'Spec.{parent}()'), ('@P', P), ('@C', C), ('@Hn', f'{H}n'), ('@FSn', f'{FS}n'), ('@FS', str(FS))]:
        txt = txt.replace(k, v)
    L.append(txt)
    return '\n'.join(L) + '\n'



# ---- rejection of the two-field container ------------------------------------------------------

AS_REJ = TPL.text('AS_REJ')

VALUE_CTORS = [('BooleanValue', ['b0']), ('UnsignedValue', ['u0']), ('BytesValue', ['xs0']), ('BitsValue', ['bs0']),
               ('Sequence', ['it0']), ('Items', ['hd0', 'tl0']), ('EmptyItems', []), ('Selected', ['sel0', 'sv0']), ('NullValue', [])]


def as_rej_text(g, xc, parent='AttesterSlashing'):
    n, FS, po = xc.n, xc.FS, xc.po
    P = 4 * po
    LIMN = VL.spec_lim(n, [f['kind'] for f in xc.fields].index('var'))
    fsb = [FS & 255, (FS >> 8) & 255, (FS >> 16) & 255, (FS >> 24) & 255]
    FSL = '[' + ', '.join(map(str, fsb)) + ']'
    kids, _ = VL.spec_schemas(parent)
    S46 = f'Spec.{kids[0]}()'
    assert kids[0] == kids[1]
    pre = '' if VL.is_big(xc) else ''
    L = list(VL.DEC_HEAD) + [f'import ./{VL.fname(xc).name} as DC', f'import ./{VL.fname(xc, "_win").name} as W',
                             f'import ./{VL.fname(xc, "_rej").name} as R', f'import ./{pre}var_codec_{parent}.bend as M',
                             'import ./vdig.bend as VG', 'import ./vfits.bend as VFT', 'import ./vnest.bend as VN',
                             'import ../../proofs/decode_shape.bend as DS', 'import ../../proofs/decode_facts.bend as DF', '',
                             '# GENERATED by var_nest (codegen). Do not edit.',
                             f'# Rejection of {parent}: every byte string the spec relates to a value is two',
                             f'# {n} encodings behind their offsets, and then every check of the validator',
                             '# passes; so when CHK(t, n) is False no value is related to the buffer\'s bytes.', '']
    txt = AS_REJ
    for k, v in [('@FSL', FSL), ('@FSn', f'{FS}n'), ('@FS', str(FS)), ('@POn', f'{po}n'), ('@Pn', f'{P}n'), ('@LIMN', LIMN), ('@LIM', str(xc.LIM))]:
        txt = txt.replace(k, v)
    L.append('''def u32le(+a: U32, +b: U32, +h: {Nat.is_le(U32.to_nat(a), U32.to_nat(b)) == True{} : Bool}) -> {U32.is_le(a, b) == True{} : Bool}:
  FD.logic__subst(Bool, z => {z == True{} : Bool}, Nat.is_le(U32.to_nat(a), U32.to_nat(b)), U32.is_le(a, b), Equal.sym(Bool, U32.is_le(a, b), Nat.is_le(U32.to_nat(a), U32.to_nat(b)), VU.le_u32(a, b)), h)''')
    L.append(txt)
    w = L.append
    CTX = ('+d: Nat, +t: FD.array__Tree<U32>, +n: U32, +pf: {FD.array__perfect(U32, d, t) == True{} : Bool}, +hd: {Nat.is_lt(d, 31n) == True{} : Bool},\n'
           '    +hn: {Nat.is_le(U32.to_nat(n), A.quad(VB.pw(d))) == True{} : Bool}, +hchk: {M.CHK(t, n) == False{} : Bool}')
    CA = 'd, t, n, pf, hd, hn, hchk'
    MB = 'Maybe<&2, +List<U32>>'
    VWt = 'M.VW(t, n)'

    def absurd():
        return f'FD.logic__none_some(+List<U32>, {VWt}, e)'

    def match_value(var, keep, body):
        out = [f'  match {var}:']
        for c, args in VALUE_CTORS:
            if c == keep[0]:
                out.append(f'    case S.{c}{{' + ', '.join('+' + a for a in keep[1]) + f'}}: {body}')
            else:
                out.append(f'    case S.{c}{{' + ', '.join('+' + a for a in args) + f'}}: {absurd()}')
        return out

    def CC(parts, X):
        for p in reversed(parts):
            X = f'Codec.concatenate(Some{{[{p}]}}, {X})'
        return X

    def E(parts, X):
        return f'{{Codec.bytes(Codec.aggregate({CC(parts, X)}, None{{}})) == Some{{{VWt}}} : {MB}}}'
    CH = [f'S.Chain{{{S46}, S.Chain{{{S46}, S.End{{}}}}}}', f'S.Chain{{{S46}, S.End{{}}}}', 'S.End{}']
    PL2 = '[S.Variable{y1}, S.Variable{y2}]'
    b5 = f'Bool.and(Layout.bytes_valid({PL2}), N.fits(4n, Nat.add(Layout.fixed_size({PL2}), List.length(&2, U32, Layout.payloads({PL2})))))'
    w(TPL.render('as_rej_text', CA=CA, CTX=CTX, MB=MB, VWt=VWt, absurd=absurd))
    parts = ['S.Variable{y1}', 'S.Variable{y2}']
    w(f'def st2({CTX}, +y1: +List<U32>, f1: R.FACTS(y1), +y2: +List<U32>, f2: R.FACTS(y2), +items: S.Value, +e: {E(parts, "Codec.parts(items, S.End{})")}) -> Empty:')
    L.extend(match_value('items', ('EmptyItems', []), f'fin({CA}, y1, f1, y2, f2, {b5}, e)'))
    w('')
    for i in (1, 0):
        pdecl = '' if i == 0 else ', +y1: +List<U32>, f1: R.FACTS(y1)'
        pargs = '' if i == 0 else 'y1, f1, '
        prev = parts[:i]
        yv = f'y{i + 1}'
        nxt = f'Codec.parts(r, {CH[i + 1]})'
        w(f'def fp{i}({CTX}{pdecl}, +h: S.Value, +ps: +List<S.Part>, hf: DF.single(None{{}}, ps), +em: {{Codec.parts(h, {S46}) == Some{{ps}} : Maybe<&2, +List<S.Part>>}},')
        w(f'    +r: S.Value, +e: {E(prev, f"Codec.concatenate(Some{{ps}}, {nxt})")}) -> Empty:')
        w('  match ps:')
        w('    case Nil{}: hf')
        w('    case Con{S.Fixed{+xs}, Nil{}}: FD.logic__none_some(Nat, List.length(&2, U32, xs), hf)')
        w(f'    case Con{{S.Variable{{+{yv}}}, Nil{{}}}}:')
        w(f'      st{i + 1}({CA}, {pargs}{yv}, R.inv_v(h, {yv}, Equal.cong(Maybe<&2, +List<S.Part>>, {MB}, z => Codec.bytes(z), Codec.parts(h, {S46}), Some{{[S.Variable{{{yv}}}]}}, em)), r, e)')
        w('    case Con{S.Fixed{+xs}, Con{+a, +b}}: hf')
        w('    case Con{S.Variable{+xs}, Con{+a, +b}}: hf')
        w('')
        w(f'def fm{i}({CTX}{pdecl}, +h: S.Value, +mm: Maybe<&2, +List<S.Part>>, hf: DF.single_result(None{{}}, mm), +em: {{Codec.parts(h, {S46}) == mm : Maybe<&2, +List<S.Part>>}},')
        w(f'    +r: S.Value, +e: {E(prev, f"Codec.concatenate(mm, {nxt})")}) -> Empty:')
        w('  match mm:')
        w(f'    case None{{}}: {absurd()}')
        w(f'    case Some{{+ps}}: fp{i}({CA}, {pargs}h, ps, hf, em, r, e)')
        w('')
        w(f'def st{i}({CTX}{pdecl}, +items: S.Value, +e: {E(prev, f"Codec.parts(items, {CH[i]})")}) -> Empty:')
        L.extend(match_value('items', ('Items', ['h', 'r']), f'fm{i}({CA}, {pargs}h, Codec.parts(h, {S46}), DS.facts(h, {S46}, {{==}}), {{==}}, r, e)'))
        w('')
    w(f'def inv_v({CTX}, +v: S.Value, +e: {{Codec.encoding_for_legal_type(Spec.{parent}(), v) == Some{{{VWt}}} : {MB}}}) -> Empty:')
    L.extend(match_value('v', ('Sequence', ['items']), f'st0({CA}, items, e)'))
    w(TPL.render('as_rej_text_decode_reject', CA=CA, VWt=VWt, parent=parent))
    return '\n'.join(L) + '\n'
