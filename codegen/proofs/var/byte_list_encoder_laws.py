#!/usr/bin/env python3
"""The encoder laws of the names of codegen/proofs/var/byte_list_codec_laws.py.

For a name X (word-aligned fixed fields around one byte list) this writes
proofs/obj/var_bytes_<X>_enc.bend:

    putw          X_putn at a word-aligned position pos = 4 P of any perfect
                  output tree D writes the object: the result is an explicit
                  tree (layers of word writes over D) and the object's size;
    bytesw_enc    the bytes of that window are the header's words and the
                  byte list's bytes;
    encode_eval   the encoder returns the object and B.Buf{thaw(OUT), FS + N};
    encode_spec   whose bytes are the spec/codec.bend encoding of the object's
                  value XE,

for every object whose fixed fields hold free words, whose byte vectors of
packed words have perfect storage trees with room for their words, and whose
byte list is O.Words{thaw(TX), N}, N <= limit, on a perfect tree with room for
its words and no bytes past N in its last word (the runtime's storage check).
proofs/obj/var_bytes_wput.bend holds the writers of the packed word fields.
"""
