#!/usr/bin/env python3
"""BitList[N] of the generic containers (types/generic_obj.bend) at a window of any byte
offset: codegen/proofs/var/nested_type_window_laws.py's bit-list window (the interface of proofs/obj/vua_win.bend) with
the generic runtime and the literal schema S.BitList{Nn} (generic_specs inlines it).

    python3 codegen/proofs/var/generic_bit_list_window.py [--check]
"""
import sys as _sys
import pathlib as _pathlib
_sys.path.insert(0, str(_pathlib.Path(__file__).resolve().parents[3]))  # the repository root: `codegen` is importable when this file runs as a script
import sys
from codegen.core import generated_file_writer as writer  # noqa: E402

from codegen.proofs.var import nested_type_window_laws as VW  # noqa: E402

from codegen.core.repository_paths import ROOT  # noqa: E402
LISTS = [5, 6, 256, 257, 1280, 1281]


def win_text(N):
    b = VW.Bits(N, f'bits{N}', f'S.BitList{{{N}n}}', f'{N}n')
    txt = VW.bitsx_text(b, deep=True)
    out = []
    for ln in txt.split('\n'):
        ln = ln.replace('import ../../types/fulu_obj.bend as T', 'import ../../types/generic_obj.bend as T')
        ln = ln.replace('import ../../spec/fulu_schemas.bend as Spec', 'import ./generic_specs.bend as Spec')
        ln = ln.replace('# GENERATED by nested_type_window_laws (codegen). Do not edit.', '# GENERATED by generic_bit_list_window (codegen: nested_type_window_laws). Do not edit.')
        out.append(ln)
    return '\n'.join(out)


def outputs():
    return {ROOT / f'proofs/obj/var_winx_g_bits{N}.bend': win_text(N) for N in LISTS}


def main():
    out = outputs()
    from codegen.impl import runtime_file_split as RR  # the runtime split: the modules import the per-name files they use
    out = RR.rewire_out(out)
    if '--check' in sys.argv:
        return writer.check(out, 'stale: ', 'generic bit-list windows are current')
    for p, t in out.items():
        p.write_text(t)
    print('wrote ' + ', '.join(str(p.relative_to(ROOT)) for p in out))


if __name__ == '__main__':
    main()
