def u16_text():
    # per r = k: the second byte's word q1 and byte r1, and 1 + (4 q + k) == 4 q1 + r1 (eqP, as 4 q1 + r1 == 1 + P)
    cases = []
    for k in range(4):
        P = f'Nat.add(A.quad(q), {k}n)'
        if k < 3:
            q1, r1 = 'q', f'{k + 1}n'
            eqP = f'FD.nat__add_succ(A.quad(q), {k}n)'
            hl_a = 'hl'                  # the first byte's room: q + 1 <= 2^dd
            hl_b = 'hl'                  # the second byte's room
            hq_a = 'UWD.le_q(q, 0n, VB.pw(dd), hl)'
            hq_b = hq_a
        else:
            q1, r1 = '1n+q', '0n'
            eqP = ('Equal.trans(Nat, Nat.add(A.quad(1n+q), 0n), A.quad(1n+q), 1n+Nat.add(A.quad(q), 3n), FD.nat__add_zero(A.quad(1n+q)), '
                   'Equal.trans(Nat, Nat.add(4n, A.quad(q)), Nat.add(A.quad(q), 4n), 1n+Nat.add(A.quad(q), 3n), FD.nat__add_comm(4n, A.quad(q)), FD.nat__add_succ(A.quad(q), 3n)))')
            hl_a = 'FD.nat__le_trans(Nat.add(q, 1n), Nat.add(q, 2n), VB.pw(dd), Order.add_left(q, 1n, 2n, {==}), hl)'
            hl_b = f'FD.logic__subst(Nat, z => {{Nat.is_le(z, VB.pw(dd)) == {TRUE}}}, Nat.add(q, 2n), 1n+Nat.add(q, 1n), FD.nat__add_succ(q, 1n), hl)'
            hq_b = 'UWD.le_q(q, 1n, VB.pw(dd), hl)'
            hq_a = f'FD.nat__lt_trans(q, 1n+q, VB.pw(dd), FD.nat__lt_succ(q), {hq_b})'
        cases.append(dict(k=k, P=P, q1=q1, r1=r1, eqP=eqP, hl_a=hl_a, hl_b=hl_b, hq_a=hq_a, hq_b=hq_b))

    L = [TPL.render('u16_text')]
    for c in cases:
        L.append(f'    case {c["k"]}n: W8X({c["r1"]}, dd, W8X({c["k"]}n, dd, D, q, x), {c["q1"]}, U32.shrn(x, 8n))')
    L.append('    case 4n+t: D\n')
    L.append(f'''def w16x_perfect(+r: Nat, +dd: Nat, +D: {TR}, +q: Nat, +x: U32, +pf: {{FD.array__perfect(U32, dd, D) == {TRUE}}})
    -> {{FD.array__perfect(U32, dd, W16X(r, dd, D, q, x)) == {TRUE}}}:
  match r:''')
    for c in cases:
        L.append(f'    case {c["k"]}n: w8x_perfect({c["r1"]}, dd, W8X({c["k"]}n, dd, D, q, x), {c["q1"]}, U32.shrn(x, 8n), w8x_perfect({c["k"]}n, dd, D, q, x, pf))')
    L.append('    case 4n+ +t: pf\n')

    def e1(c):
        # to_nat(X + 1) == 4 q1 + r1
        hP1 = f'bnd({c["q1"]}, {c["r1"]}, VB.pw(dd), {c["hq_b"]}, {{==}})'
        h = f'FD.logic__subst(Nat, z => {{Nat.is_lt(z, {Q}) == {TRUE}}}, Nat.add(A.quad({c["q1"]}), {c["r1"]}), 1n+{c["P"]}, {c["eqP"]}, {hP1})'
        return (f'Equal.trans(Nat, U32.to_nat(U32.add(X, 1)), 1n+{c["P"]}, Nat.add(A.quad({c["q1"]}), {c["r1"]}), '
                f'UR.offx(dd, X, 1, {c["P"]}, e, FD.nat__lt_trans(dd, 29n, 30n, hd, {{==}}), {h}), Equal.sym(Nat, Nat.add(A.quad({c["q1"]}), {c["r1"]}), 1n+{c["P"]}, {c["eqP"]}))')
    L.append(TPL.render('u16_text_w16_any'))
    for c in cases:
        D1 = f'W8X({c["k"]}n, dd, D, q, x)'
        L.append(TPL.render('u16_text_2', D1=D1, c=c, e1=e1))
    L.append(f'    case 4n+ +t: Empty.absurd({{T.u16_put(FD.array__thaw(U32, D), X, x) == FD.array__thaw(U32, W16X(4n+t, dd, D, q, x)) : Array<U32>}}, FD.nat__lt_zero_absurd(t, hr))\n')
    L.append(TPL.render('u16_text_w16_any_bytes'))
    for c in cases:
        k = c['k']
        P = c['P']
        D1 = f'W8X({k}n, dd, D, q, x)'
        L.append(TPL.render('u16_text_3', D1=D1, P=P, c=c, k=k))
    L.append(f'    case 4n+ +t: Empty.absurd({{UA.BYT(W16X(4n+t, dd, D, q, x)) == UW.SPL(UA.BYT(D), Nat.add(A.quad(q), 4n+t), [U32.and(x, 255), U32.and(U32.shrn(x, 8n), 255)]) : +List<U32>}}, FD.nat__lt_zero_absurd(t, hr))\n')
    return '\n'.join(L)


