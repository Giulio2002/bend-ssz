"""Codec laws of the bare progressive lists of sub-word elements: the generic forms
ProgressiveList[uint8] (proglist_uint8), ProgressiveList[uint16] (proglist_uint16) and
ProgressiveList[boolean] (proglist_bool).

    python3 codegen/proofs/var/progressive_small_list_codec_laws.py [--check]

Writes, for each element kind k in u8, u16, bool:

    proofs/obj/var_winp_<k>.bend   the list at a window of any byte offset x and
        length len of a buffer (the interface of proofs/obj/vua_win.bend: CHKw,
        ok_evalw, OBJw, readw, VALw, specw, invw), so that a container holding
        such a list can import it as a child window;
    proofs/obj/var_plist_<X>_top.bend     ok_eval, decode_accept, decode_none,
        decode_spec, decode_reject: the window at x = 0, off = 0, len = n
        (codegen/proofs/var/nested_type_window_laws.py's top template);
    proofs/obj/var_plist_<X>_top_unique.bend   decode_unique;
    proofs/obj/var_plist_<X>_enc.bend     encode_eval, encode_spec.

The window modules are BIG (checked with `checkq --big`): the reader's list storage
is B.zeros(u) at every depth u (vvlz.bend's zg).
"""
