def _cm_windows(x, FS, H, po, fixed, V, NCa, TD, ST, SA, LT, q, w, pfd, hb, SP_):
    """the window builders and the header window of each field"""
    def win(m, p, j):
        return f'VF.WIN({m}, {p}, FD.array__slots(U32, {TD(j)}))'

    def peel_chain(m, p, lo_hi, stop, last_term, last_proof):
        steps = []
        for gg in range(len(fixed) - 1, stop - 1, -1):
            fg = fixed[gg]
            kind = lo_hi(fg)
            pr = f'V2.peel_{kind}({V(fg)}, DO(K), {TD(gg)}, {fg["k"]}n, {m}, {p}, {pfd(gg)}, {hb(fg)}, {{==}})'
            steps.append((win(m, p, gg + 1), win(m, p, gg), pr))
        out = last_proof
        for a_, b_, pr in reversed(steps):
            out = f'Equal.trans({LT}, {a_}, {b_}, {last_term}, {pr},\n    {out})'
        return out

    def rel(fg, k0):
        return 'lo' if fg['k'] + fg['ft'].W <= k0 else 'hi'
    # own segments
    MTK = f'VBT.MT(DO(K), OUT1(K), T, {H}n, K)'
    VV = f'U32.or(VB.slot({MTK}, Nat.add({H}n, {q})), VBT.DMK(U32.add(0, {FS}), K))'
    LM = f'VB.lm(VC.NW(O.bits_nbytes(K)), 0n, {H}n, FD.array__slots(U32, OUT1(K)), {ST})'
    for i, f in enumerate(x.fields):
        if f['kind'] == 'fix':
            j = fixed.index(f)
            k0, W0 = f['k'], f['ft'].W
            last = f'V2.own({V(f)}, DO(K), {TD(j)}, {k0}n, {pfd(j)}, {hb(f)})'
            body = peel_chain(f'{W0}n', f'{k0}n', lambda fg: rel(fg, k0), j + 1, V(f), last)
            w(f'def seg{i}({SP_}) -> {{{win(f"{W0}n", f"{k0}n", len(fixed))} == {V(f)} : {LT}}}:')
            w('  ' + body)
            w('')
        else:
            tail = (TPL.render('tail', FS=FS, H=H, LM=LM, LT=LT, MTK=MTK, NCa=NCa, SA=SA, ST=ST, VV=VV, po=po, q=q))
            body = peel_chain('1n', f'{po}n', lambda fg: rel(fg, po), 0, f'[{FS}]', tail)
            w(f'def seg{i}({SP_}) -> {{{win("1n", f"{po}n", len(fixed))} == [{FS}] : {LT}}}:')
            w('  ' + body)
            w('')
    # header window
    return win, peel_chain


def _cm_window_eqs(x, FS, H, kb, fixed, WA, V, NC, NCa, ALLP, HN, OUT, SO, SA, HDRL, LT, q, w, SP_, SPa, win, peel_chain):
    """the header and payload windows against the header list and the payload bytes"""
    S3 = SO
    w(f'def hdr_eq({SP_}) -> {{{win(f"{H}n", "0n", len(fixed))} == {HDRL} : {LT}}}:')
    segs = []
    for i, f in enumerate(x.fields):
        segs.append((i, f['ft'].W if f['kind'] == 'fix' else 1, f['k'], V(f) if f['kind'] == 'fix' else f'[{FS}]'))
    R, s_ = H, 0
    pre = lambda t: t  # noqa: E731
    for idx, (i, Wd, k, Vs) in enumerate(segs):
        assert k == s_
        if idx < len(segs) - 1:
            w(f'  %Equal.sym({LT}, {win(f"Nat.add({Wd}n, {R - Wd}n)", f"{s_}n", len(fixed))}, VF.app({win(f"{Wd}n", f"{s_}n", len(fixed))}, {win(f"{R - Wd}n", f"Nat.add({s_}n, {Wd}n)", len(fixed))}),')
            w(f'      VF.win_split({Wd}n, {R - Wd}n, {s_}n, {S3})) :')
            w(f'    {{{pre("_")} == {HDRL} : {LT}}}')
            w(f'  %Equal.sym({LT}, {win(f"{Wd}n", f"{s_}n", len(fixed))}, {Vs}, seg{i}({SPa})) :')
            p0 = pre
            rest = win(f'{R - Wd}n', f'{s_ + Wd}n', len(fixed))
            w(f'    {{{p0(f"VF.app(_, {rest})")} == {HDRL} : {LT}}}')
            pre = (lambda p0, Vs: (lambda t: p0(f'VF.app({Vs}, {t})')))(p0, Vs)
            R, s_ = R - Wd, s_ + Wd
        else:
            assert R == Wd
            w(f'  %Equal.sym({LT}, {win(f"{Wd}n", f"{s_}n", len(fixed))}, {Vs}, seg{i}({SPa})) :')
            w(f'    {{{pre("_")} == {HDRL} : {LT}}}')
    w('  {==}')
    w('')
    # payload window: the fixed fields are below H
    MQ = f'Nat.add({q}, 1n)'
    body = peel_chain(MQ, f'{H}n', lambda fg: 'lo', 0, f'VF.WIN({MQ}, {H}n, {SA})', '{==}')
    w(f'def pay_eq({SP_}) -> {{{win(MQ, f"{H}n", len(fixed))} == VF.WIN({MQ}, {H}n, {SA}) : {LT}}}:')
    w('  ' + body)
    w('')
    Y = f'VS.bt(U32.to_nat(CO.NK(K)), F.limbs(VB.wdr({H}n, {SA})))'
    BY = f'VS.bt(U32.to_nat(SFS(K)), F.limbs({SO}))'
    RHS = f'List.append(&2, U32, F.limbs({HDRL}), {Y})'
    w(TPL.render('_cm_window_eqs', ALLP=ALLP, BY=BY, FS=FS, H=H, HDRL=HDRL, HN=HN, LT=LT, MQ=MQ, NC=NC, NCa=NCa, OUT=OUT, RHS=RHS, SA=SA, SO=SO, SPa=SPa, WA=WA, Y=Y, fixed=fixed, kb=kb, q=q))
    return Y, BY, RHS


def _cm_spec_side(g, x, VL, n, FS, H, N, vi, LIMN, WS, WA, OBB, NCa, ALLP, ALLa, HN, SA, M, MP, L, w, ps, Y, BY, RHS):
    """the spec side: the value, schema and parts of the object, and encode_spec"""
    nodes = VL.field_nodes(g, x, lambda k: f'w{k}')
    VALB = f'S.BitsValue{{BO.bview({OBB})}}'
    vals, schs, parts = [], [], []
    for f, nd in zip(x.fields, nodes):
        if f['kind'] == 'fix':
            vals.append(nd['val'])
            schs.append(nd['sch'])
            parts.append(f'S.Fixed{{F.limbs([{", ".join(nd["words"])}])}}')
        else:
            vals.append(VALB)
            schs.append(f'S.BitList{{{LIMN}}}')
            parts.append(f'S.Variable{{{Y}}}')

    def items(i):
        return 'S.EmptyItems{}' if i == len(vals) else f'S.Items{{{vals[i]}, {items(i + 1)}}}'

    def chain(i):
        return 'S.End{}' if i == len(vals) else f'S.Chain{{{schs[i]}, {chain(i + 1)}}}'

    def cat(i):
        if i == len(vals):
            return '{==}'
        rest = '[' + ', '.join(parts[i + 1:]) + ']'
        if x.fields[i]['kind'] == 'fix':
            return (f'VS.chain_fixed({vals[i]}, {items(i + 1)}, {schs[i]}, {chain(i + 1)}, F.limbs([{", ".join(nodes[i]["words"])}]), '
                    f'{rest}, {nodes[i]["proof"]}, {cat(i + 1)})')
        return (f'VS.chain_var({vals[i]}, {items(i + 1)}, {schs[i]}, {chain(i + 1)}, {Y}, {rest}, '
                f'bparts({ALLa}), {cat(i + 1)})')
    PRE = '[' + ', '.join('[' + ', '.join(nd['words']) + ']' for nd in nodes[:vi]) + ']'
    POST = '[' + ', '.join('[' + ', '.join(nd['words']) + ']' for nd in nodes[vi + 1:]) + ']'
    NAMES = '[' + ', '.join('"' + f['name'] + '"' for f in x.fields) + ']'
    ENCR = f'List.append(&2, U32, List.append(&2, U32, F.flat({PRE}), List.append(&2, U32, N.digits(4n, VS.FSZ({PRE}, {POST})), F.flat({POST}))), {Y})'
    RHSk = f'Some{{{RHS}}}'
    MOT = 'Codec.bytes(Codec.one(Bits.encoding(@D, List.append(&2, Bool, @B, [True{}])), None{}))'
    BITS = 'CO.BITS(T, K)'
    w(TPL.render('_cm_spec_side', ALLP=ALLP, ALLa=ALLa, BITS=BITS, ENCR=ENCR, FS=FS, H=H, HN=HN, LIMN=LIMN, M=M, MP=MP, N=N, NAMES=NAMES, NCa=NCa, POST=POST, PRE=PRE, RHSk=RHSk, SA=SA, VALB=VALB, VL=VL, WA=WA, WS=WS, Y=Y, cat=cat, chain=chain, items=items, n=n, parts=parts))
    w('# The bytes the encoder writes are the spec/codec.bend encoding of the object\'s value.')
    w('law encode_spec:')
    for p_ in ps:
        w(f'  for {p_}')
    w(f'  Decoding.decodes(Spec.{n}(), {BY}, VAL({WA}, T, K))')
    w(f'def encode_spec({ALLa}):')
    w(f'  Equal.trans({M}, Codec.encoding_for_legal_type(Spec.{n}(), VAL({WA}, T, K)), {RHSk}, Some{{{BY}}},')
    w(f'    encE({ALLa}),')
    w(f'    Equal.cong(+List<U32>, {M}, z => Some{{z}}, {RHS}, {BY}, Equal.sym(+List<U32>, {BY}, {RHS}, out_eq({ALLa}))))')
    txt = '\n'.join(L) + '\n'
    if LIMN != f'{N}n':
        txt = re.sub(rf'\b{N}n\b', LIMN, txt)
    return txt


def cont_module(g, x, src):
    VL, n, FS, H, po, N, lp, vi, LIMN, Tn, kb, KY, KO, PB, kb2, fixed, WS, WA, V, fobj, OBB, objs, OBJ, FIXOBJS, NC, NCa, ALLP, ALLa, HN, TD, OUT, SO, ST, SA = _cm_names(x, src)
    HDRL, LT, M, MP, q, L, w, CF = _cm_header(x, VL, n, FS, H, po, N, vi, Tn, fixed, WS, V, objs, TD)
    pfd, hb = _cm_tree_laws(FS, H, po, N, kb, KY, KO, PB, kb2, fixed, WS, WA, V, NC, NCa, ALLP, HN, TD, LT, q, w, CF)
    RS, RP, TP = _cm_size_put_eval(FS, H, po, N, lp, Tn, kb, fixed, fobj, OBB, OBJ, FIXOBJS, NCa, ALLP, ALLa, HN, TD, OUT, w, pfd, hb)
    ps = _cm_encode_eval(Tn, KO, OBJ, NCa, ALLP, ALLa, HN, OUT, w, RS, RP, TP)
    SP_, SPa = _cm_hdstw(H, kb, WS, WA, NC, NCa, q, w, CF)

    win, peel_chain = _cm_windows(x, FS, H, po, fixed, V, NCa, TD, ST, SA, LT, q, w, pfd, hb, SP_)
    Y, BY, RHS = _cm_window_eqs(x, FS, H, kb, fixed, WA, V, NC, NCa, ALLP, HN, OUT, SO, SA, HDRL, LT, q, w, SP_, SPa, win, peel_chain)
    # ---- spec ----
    return _cm_spec_side(g, x, VL, n, FS, H, N, vi, LIMN, WS, WA, OBB, NCa, ALLP, ALLa, HN, SA, M, MP, L, w, ps, Y, BY, RHS)


