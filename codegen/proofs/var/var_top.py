#!/usr/bin/env python3
"""Whole-buffer decoder laws (ok_eval, decode_accept, decode_spec, decode_unique,
decode_reject, decode_none) of names whose byte-offset window modules exist but
whose top modules no other generator writes: the window at x = 0, off = 0, len = n
(the template of codegen/proofs/var/var_rlist_er.py's top_text, as codegen/proofs/var/var_winb.py uses it).

    python3 codegen/proofs/var/var_top.py [--check]

  ExecutionPayload  proofs/obj/var_codec_ExecutionPayload.bend
                    (window proofs/obj/var_winx_ExecutionPayload.bend, codegen/proofs/var/var_winx_c.py;
                    big children, so the top is a big_ file)
  Transaction       proofs/obj/var_codec_Transaction.bend
                    (window proofs/obj/vvlb_bl1073741824.bend, codegen/proofs/var/var_vlist.py).
                    Transaction's runtime validator and reader are the ByteList[2^30] ones
                    (T.bl1073741824_ok/_read) and its object is O.Words. The spec parts of a
                    value are read without DS.facts (which would evaluate the 2^30 limit):
                    rjt splits the value and keeps ByteList.domain(limit, xs) as a variable.
  Transaction's encoder: proofs/obj/var_codec_Transaction_enc.bend (encode_eval, encode_spec).
"""
