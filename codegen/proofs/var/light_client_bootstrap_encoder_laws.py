"""LightClientBootstrap's encoder laws (big: its 24820-byte header), for
codegen/proofs/var/nested_byte_list_encoder_laws.py: proofs/obj/var_bytes_LightClientBootstrap_enc.bend.

Bootstrap = [header: LightClientHeader (variable), current_sync_committee:
SyncCommittee (6144 packed words of pubkeys then a Bytes48), the branch (48 words)].
The object's SyncCommittee pubkeys are a tree TS; the writer copies them with
vbenc.put_words_any (one VB.mone run), so the output's pubkey window is
VS.wtake(6144, slots TS) and is never unfolded word by word. The spec side lays the
header out as segments [[24820], app(wtake(6144, slots TS), [g..]), branch words]
(as the decoder's light_client_bootstrap_helpers.spec_part_seg does over the window), with the
SyncCommittee's parts from vsc.sc_parts. Header-size facts are stated for
symbolic sizes and closed once through Nat.is_eq (see vbsize.bend).
"""
from codegen.proofs.var import byte_list_codec_laws as VBY
from codegen.proofs.var import nested_byte_list_codec_laws as VBN
from codegen.core.template_loader_positional import Templates  # noqa: E402
TPL = Templates('light_client_bootstrap_encoder_laws', globals())

FS, H = 24820, 6205
HY_ = 61  # LightClientHeader's header words
SCW, SCG = 6144, 12  # pubkey words, aggregate words
KB, WB = 6157, 48  # the branch
TRUE = 'True{} : Bool'
LT = 'List<&2, U32>'
MP = 'Maybe<&2, +List<S.Part>>'
M = 'Maybe<&2, +List<U32>>'


def enc_text(x, C, DO):
    assert (x.FS, x.H) == (FS, H)
    Y = x.Y
    G = [f'g{j}' for j in range(SCG)]
    GL = '[' + ', '.join(G) + ']'
    own_p = ['+dS: Nat', '+TS: FD.array__Tree<U32>'] + [f'+{q}: U32' for q in G] + ['+dB: Nat', '+TB: FD.array__Tree<U32>']
    own_a = ['dS', 'TS'] + G + ['dB', 'TB']
    own_h = [f'+pfS: {{FD.array__perfect(U32, dS, TS) == {TRUE}}}', f'+hdS: {{Nat.is_lt(dS, 31n) == {TRUE}}}',
             f'+hrS: {{Nat.is_le({SCW}n, VB.pw(dS)) == {TRUE}}}',
             f'+pfB: {{FD.array__perfect(U32, dB, TB) == {TRUE}}}', f'+hdB: {{Nat.is_lt(dB, 31n) == {TRUE}}}',
             f'+hrB: {{Nat.is_le({WB}n, VB.pw(dB)) == {TRUE}}}']
    own_ha = ['pfS', 'hdS', 'hrS', 'pfB', 'hdB', 'hrB']
    params, args = own_p + C.params, own_a + C.args
    hyps, hargs = own_h + C.hyps, own_ha + C.hargs
    EP, EA = ', '.join(params), ', '.join(args)
    MAX = FS + C.MAX
    KS = VBY.kfit(MAX + 1)
    Tn = f'T.{x.n}'
    PUB = f'O.Words{{FD.array__thaw(U32, TS), {SCW * 4}}}'
    AGG = f'T.Bytes48{{{", ".join(G)}}}'
    SCO = f'T.SyncCommittee{{{PUB}, {AGG}}}'
    BRO = f'O.Words{{FD.array__thaw(U32, TB), {WB * 4}}}'
    YO = f'YE.OBJE({C.A})'
    OBJE = f'{Tn}{{{YO}, {SCO}, {BRO}}}'
    DP = f'{EP}, +dd: Nat, +D: FD.array__Tree<U32>, +P: Nat'
    DA = f'{EA}, dd, D, P'
    OBJ = f'OBJE({EA})'
    PC = f'Nat.add({H}n, P)'
    HN = f'+hN: {{Nat.is_le(U32.to_nat(N), 32n) == {TRUE}}}'
    HDST = f'+hdst: {{Nat.is_le(ROOM(N, P), VB.pw(dd)) == {TRUE}}}'
    PFD = f'+pf: {{FD.array__perfect(U32, dd, D) == {TRUE}}}'
    HDD = f'+hdd: {{Nat.is_lt(dd, 29n) == {TRUE}}}'
    HZ = '+hz0: {VB.slot(D, KZ(N, P)) == 0 : U32}'
    HZS = f'+hzs: {{VB.slot(D, Nat.add({1 + SCW}n, P)) == 0 : U32}}'
    KYS = VBY.kfit(31 + SCW * 4)
    D2 = f'VF.updv([{FS}], dd, D, Nat.add(0n, P))'
    WLB = 'WP.WL_v6_b32(TB)'
    # the output tree's layers, inline: a def around VB.mone(6144n, ..) is evaluated when compared
    # with its body, and the run unrolled
    def layers(dd, D, P):
        l1 = f'YE.OUTW({C.A}, {dd}, VF.updv([{FS}], {dd}, {D}, Nat.add(0n, {P})), Nat.add({H}n, {P}))'
        l2 = f'VB.mone(VC.NW({SCW * 4}), 0n, Nat.add(1n, {P}), {dd}, {l1}, TS)'
        l3 = f'VF.updv({GL}, {dd}, {l2}, Nat.add(VC.NW({SCW * 4}), Nat.add(1n, {P})))'
        l4 = f'VF.updv({WLB}, {dd}, {l3}, Nat.add({KB}n, {P}))'
        return l1, l2, l3, l4
    L1, L2, L3, L4 = layers('dd', 'D', 'P')

    L = list(VBN.HEAD) + VBN.HEAD_COMP + ['import ./venc.bend as VE', 'import ./venc2.bend as V2', 'import ./var_bytes_wput.bend as WP',
                                          f'import ./{VBY.fname(type("X", (), {"n": Y}), "_enc").name} as YE', '',
                                          '# GENERATED by nested_byte_list_encoder_laws (codegen: light_client_bootstrap_encoder_laws). Do not edit.',
                                          f'# The encoder of {x.n} (see the module docstring of codegen/proofs/var/light_client_bootstrap_encoder_laws.py).', '']
    w = L.append
    w(TPL.render('enc_text', C=C, D2=D2, DA=DA, DP=DP, EP=EP, GL=GL, HDD=HDD, HDST=HDST, HN=HN, KS=KS, L1=L1, L2=L2, L3=L3, L4=L4, MAX=MAX, OBJE=OBJE, PC=PC, PFD=PFD, Tn=Tn, WLB=WLB))
    # ---- the nested field's writer (codegen/proofs/var/nested_byte_list_encoder_laws.py vput with po = cvar = 0) ----
    RX = f'(FD.array__thaw(U32, YE.OUTW({C.A}, dd, VF.updv([{FS}], dd, D1, Nat.add(0n, P)), {PC})), ({YO}, SFS(N)))'
    TX_ = f'Array<U32> & (T.{Y} & U32)'
    D2v = f'VF.updv([{FS}], dd, D1, Nat.add(0n, P))'
    hbw = lambda W, k: f'hb({W}n, {k}n, P, dd, {{==}}, hHP(N, dd, P, hdst))'  # noqa: E731
    ecv = f'eoc(0n, 0, P, pos, dd, eP, hdd, {{==}}, hbq(1n, 0n, P, dd, {hbw(1, 0)}))'
    ecF = f'eoc({H}n, {FS}, P, pos, dd, eP, hdd, {VBN.ecq(H, FS)}, hbq(0n, {H}n, P, dd, hHP(N, dd, P, hdst)))'
    w(TPL.render('enc_text_vput', C=C, D2v=D2v, HDD=HDD, HDST=HDST, PC=PC, RX=RX, TX_=TX_, Y=Y, YO=YO, ecF=ecF, ecv=ecv, hbw=hbw))
    # ---- the SyncCommittee's writer ----
    MON = f'VB.mone(VC.NW({SCW * 4}), 0n, P1, dd, D1, TS)'
    SCR = f'(FD.array__thaw(U32, VF.updv({GL}, dd, {MON}, Nat.add(VC.NW({SCW * 4}), P1))), ({SCO}, 0))'
    STY = 'Array<U32> & (T.SyncCommittee & U32)'
    w(TPL.render('enc_text_hq4', AGG=AGG, G=G, GL=GL, HDD=HDD, KYS=KYS, MON=MON, PUB=PUB, SCO=SCO, SCR=SCR, STY=STY, own_h=own_h, own_p=own_p))
    # ---- the writer ----
    KS1 = f'Nat.add({SCW}n, Nat.add(1n, P))'
    HZS = f'+hzs: {{VB.slot(D, {KS1}) == 0 : U32}}'
    RHS = f'(FD.array__thaw(U32, {L4}), ({OBJ}, SFS(N)))'
    TY = f'Array<U32> & ({Tn} & U32)'
    SL = lambda t: f'FD.array__slots(U32, {t})'  # noqa: E731
    lenL = lambda t, pft: (f'FD.logic__subst(Nat, z => {{Nat.is_lt({KS1}, z) == {TRUE}}}, VB.pw(dd), VB.len({SL(t)}), '  # noqa: E731
                           f'Equal.sym(Nat, VB.len({SL(t)}), VB.pw(dd), FD.array__slots_length(U32, dd, {t}, {pft})), hks)')
    pf2 = f'VF.updv_perfect([{FS}], dd, D, Nat.add(0n, P), pf)'
    w(TPL.text('enc_text_sh2'))
    w(f'''# The writer at pos = 4 P over any perfect tree D (depth dd < 29) with room for the encoding, a zero
# word under the child's innermost byte list and a zero word after the SyncCommittee's pubkeys.
def putw({DP}, {", ".join(hyps)}, +pos: U32, +eP: {{U32.to_nat(pos) == A.quad(P) : Nat}},
    {HDD}, {PFD}, {HDST}, {HZ}, {HZS})
    -> {{{Tn}_putn(FD.array__thaw(U32, D), pos, {OBJ}) == {RHS} : {TY}}}:
  +hH = hHP(N, dd, P, hdst)
  +hks = FD.nat__lt_le_trans({KS1}, Nat.add(1n, {KS1}), VB.pw(dd), FD.nat__lt_succ({KS1}), hb({SCW + 1}n, 1n, P, dd, {{==}}, hH))
  +hfr = FD.logic__subst(Nat, z => {{Nat.is_le(z, {PC}) == {TRUE}}}, Nat.add({SCW + 2}n, P), Nat.add(1n, {KS1}), Equal.sym(Nat, Nat.add(1n, {KS1}), Nat.add({SCW + 2}n, P), sh2({SCW}n, P)),
    Order.add_right({SCW + 2}n, {H}n, P, {{==}}))
  +hzl = Equal.trans(U32, VB.slot({L1}, {KS1}), VB.slot({D2}, {KS1}), 0,
    VBZ.win1_slot({SL(L1)}, {SL(D2)}, {KS1}, {lenL(L1, f"pfL1({DA}, pf)")}, {lenL(D2, pf2)},
      YE.frame_lo({C.A}, dd, {D2}, {PC}, {pf2}, hdst, 1n, {KS1}, hfr)),
    Equal.trans(U32, VB.slot({D2}, {KS1}), VB.slot(D, {KS1}), 0,
      VBE.slot_updv_hi([{FS}], dd, D, Nat.add(0n, P), {KS1}, pf, {hbw(1, 0)}, Order.left_below_sum({SCW}n, Nat.add(1n, P))), hzs))
  %Equal.sym({TX_}, T.{Y}_putv(FD.array__thaw(U32, D), pos, 0, {FS}, {YO}), (FD.array__thaw(U32, {L1}), ({YO}, SFS(N))),
      vput(dd, D, pos, P, eP, hdd, pf, {C.A}, hdst, {", ".join(C.hargs)}, hz0)) :
    {{{Tn}_pw0(pos, {SCO}, {BRO}, _) == {RHS} : {TY}}}
  %Equal.sym(Array<U32> & (T.SyncCommittee & U32), T.SyncCommittee_putk(FD.array__thaw(U32, {L1}), U32.add(pos, 4), {SCO}), (FD.array__thaw(U32, {L3}), ({SCO}, 0)),
      scput(dd, {L1}, U32.add(pos, 4), Nat.add(1n, P), eoc(1n, 4, P, pos, dd, eP, hdd, {{==}}, hbq({SCW + SCG}n, 1n, P, dd, {hbw(SCW + SCG, 1)})), hdd,
        pfL1({DA}, pf), dS, TS, {", ".join(G)}, pfS, hdS, hrS, {hbw(SCW + SCG, 1)}, hzl)) :
    {{{Tn}_pw1(pos, SFS(N), {YO}, {BRO}, _) == {RHS} : {TY}}}
  %Equal.sym(Array<U32> & (O.Words & U32), T.v6_b32_putk(FD.array__thaw(U32, {L3}), U32.add(pos, {KB * 4}), {BRO}), (FD.array__thaw(U32, {L4}), ({BRO}, 0)),
      WP.wput_v6_b32(dd, {L3}, U32.add(pos, {KB * 4}), Nat.add({KB}n, P), eoc({KB}n, {KB * 4}, P, pos, dd, eP, hdd, {VBN.ecq(KB, KB * 4)}, hbq({WB}n, {KB}n, P, dd, {hbw(WB, KB)})),
        hdd, pfL3({DA}, pf), {hbw(WB, KB)}, dB, TB, pfB, hdB, hrB)) :
    {{{Tn}_pw2(pos, U32.or(SFS(N), 0), {YO}, {SCO}, _) == {RHS} : {TY}}}
  %Equal.sym(U32, U32.or(SFS(N), 0), SFS(N), VE.or_zero_u(SFS(N))) :
    {{(FD.array__thaw(U32, {L4}), ({OBJ}, U32.or(_, 0))) == {RHS} : {TY}}}
  %Equal.sym(U32, U32.or(SFS(N), 0), SFS(N), VE.or_zero_u(SFS(N))) :
    {{(FD.array__thaw(U32, {L4}), ({OBJ}, _)) == {RHS} : {TY}}}
  {{==}}
''')
    # ---- encode_eval ----
    T0 = layers(f'{DO}n', f'VC.ZT({DO}n)', '0n')[3]
    A0 = f'{EA}, {DO}n, VC.ZT({DO}n), 0n'
    REST = f'Nat.add(146n, Nat.add({HY_}n, Nat.add({H}n, 0n)))'
    HD0 = (f'FD.nat__le_trans(ROOM(N, 0n), Nat.add(8n, {REST}), VB.pw({DO}n), '
           f'Order.add_right(VC.NW(N), 8n, {REST}, YE.hNW(N, hN)), {{==}})')
    RE = f'({OBJ}, B.Buf{{FD.array__thaw(U32, {T0}), SFS(N)}})'
    w('# The encoder returns the object and the buffer of the output tree.')
    w('law encode_eval:')
    w('\n'.join(f'  for {q}' for q in params + hyps))
    w(f'  {{{Tn}_encode({OBJ}) == {RE} : {Tn} & B.Buf}}')
    w(TPL.render('enc_text_encode_eval', A0=A0, DO=DO, HD0=HD0, KS=KS, OBJ=OBJ, RE=RE, T0=T0, TY=TY, Tn=Tn, args=args, hargs=hargs))
    L.extend(spec_text(x, C, dict(EP=EP, EA=EA, params=params, args=args, hyps=hyps, hargs=hargs, MAX=MAX, KS=KS, OBJ=OBJ, DP=DP, DA=DA,
                                  PC=PC, HN=HN, HDST=HDST, PFD=PFD, HDD=HDD, D2=D2, L1=L1, L2=L2, L3=L3, L4=L4, WLB=WLB, G=G, GL=GL,
                                  hbw=hbw, Tn=Tn, DO=DO, layers=layers, pf2=pf2)))
    assert DO == 13 and f'{x.n}_encode(o: {x.n}) -> {x.n} & B.Buf: {x.n}_enc_put({x.n}_putn(O.out_at({DO}n), 0, o))' in VBY.src()
    return L, dict(EP=EP, EA=EA, params=params, args=args, hyps=hyps, hargs=hargs, MAX=MAX, KS=KS, OBJ=OBJ, OBJE=OBJE, DP=DP, DA=DA,
                   PC=PC, HN=HN, HDST=HDST, PFD=PFD, HDD=HDD, HZ=HZ, HZS=HZS, D2=D2, L1=L1, L2=L2, L3=L3, L4=L4, WLB=WLB, G=G, GL=GL,
                   SCO=SCO, BRO=BRO, YO=YO, hbw=hbw, Tn=Tn, own_p=own_p, own_a=own_a, DO=DO)


def spec_text(x, C, c):
    from codegen.proofs.var import light_client_bootstrap_helpers as VBB
    L = []
    w = L.append
    EP, EA, DP, DA, PC, L1, L2, L3, L4 = c['EP'], c['EA'], c['DP'], c['DA'], c['PC'], c['L1'], c['L2'], c['L3'], c['L4']
    G, GL, WLB, hbw, Tn, DO, pf2 = c['G'], c['GL'], c['WLB'], c['hbw'], c['Tn'], c['DO'], c['pf2']
    HN, HDST, PFD, HDD, D2 = c['HN'], c['HDST'], c['PFD'], c['HDD'], c['D2']
    Y = x.Y
    S_ = f'FD.array__slots(U32, {L4})'
    WPK = f'VS.wtake(VC.NW({SCW * 4}), FD.array__slots(U32, TS))'
    bw = [f'VB.slot(TB, {j}n)' for j in range(WB)]

    def word(k):
        if 1 + SCW <= k < 1 + SCW + SCG:
            return G[k - 1 - SCW]
        if KB <= k < KB + WB:
            return bw[k - KB]
        raise AssertionError(k)
    ITEMS, CHAIN, PL, CAT = VBB.spec_items_seg(x, 'V', 'Yb', 'hv', 'SLOTS', word)
    wk = f'VF.WIN({SCW}n, Nat.add(1n, i), SLOTS)'
    ITEMS, PL, CAT = (t.replace(wk, WPK) for t in (ITEMS, PL, CAT))
    assert 'SLOTS' not in ITEMS + PL + CAT and ', i)' not in ITEMS
    SEGC = f'VF.app({WPK}, {GL})'
    BWL = '[' + ', '.join(bw) + ']'
    SEGSv = f'[[{FS}], {SEGC}, {BWL}]'
    PRE, POST = '[]', f'[{SEGC}, {BWL}]'
    ENC = f'List.append(&2, U32, F.limbs(VZ.cat({SEGSv})), Yb)'
    ENCR = f'List.append(&2, U32, List.append(&2, U32, F.flat({PRE}), List.append(&2, U32, N.digits(4n, VS.FSZ({PRE}, {POST})), F.flat({POST}))), Yb)'
    HLW = f'+hlW: {{FD.spec_common__length(U32, {WPK}) == {SCW}n : Nat}}'
    OWN = ', '.join(c_ for c_ in ['+dS: Nat', '+TS: FD.array__Tree<U32>'] + [f'+{q}: U32' for q in G] + ['+dB: Nat', '+TB: FD.array__Tree<U32>'])
    OWA = ', '.join(['dS', 'TS'] + G + ['dB', 'TB'])
    SUM = f'Nat.add(A.quad(0n), 4n+A.quad(Nat.add({SCW + SCG}n, Nat.add({WB}n, 0n))))'
    w(TPL.render('spec_text', BWL=BWL, C=C, CAT=CAT, CHAIN=CHAIN, ENC=ENC, ENCR=ENCR, EP=EP, GL=GL, HLW=HLW, ITEMS=ITEMS, OWA=OWA, OWN=OWN, PL=PL, POST=POST, PRE=PRE, SEGC=SEGC, SUM=SUM, WPK=WPK, Y=Y, x=x))
    hyps, hargs = c['hyps'], c['hargs']
    WP_ = f'{DP}, {", ".join(hyps)}, {PFD}, {HDST}'
    WA_ = f'{DA}, {", ".join(hargs)}, pf, hdst'
    SL = lambda t: f'FD.array__slots(U32, {t})'  # noqa: E731
    p0, pk, pg, pb = 'Nat.add(0n, P)', 'Nat.add(1n, P)', f'Nat.add(VC.NW({SCW * 4}), Nat.add(1n, P))', f'Nat.add({KB}n, P)'
    NWS = f'VC.NW({SCW * 4})'
    pf1 = f'pfL1({DA}, pf)'
    pfl2 = f'pfL2({DA}, pf)'
    pfl3 = f'pfL3({DA}, pf)'
    W4 = lambda m, p: f'VF.WIN({m}, {p}, {S_})'  # noqa: E731
    Wt = lambda m, p, t: f'VF.WIN({m}, {p}, {SL(t)})'  # noqa: E731
    EQG = f'eqg(P)'
    # the aggregate key's offset 1 + NW + P, spelled as the window split leaves it (not {1 + SCW}n + P):
    # a conversion between the two spellings would walk NW = {SCW} in unary
    p45 = f'Nat.add(Nat.add(1n, {NWS}), P)'
    hb45 = (f'hb({SCG}n, Nat.add(1n, {NWS}), P, dd, FD.logic__subst(Nat, z => {{Nat.is_le(Nat.add({SCG}n, Nat.add(1n, z)), {H}n) == {TRUE}}}, '
            f'{SCW}n, {NWS}, nwS(), le45()), hHP(N, dd, P, hdst))')
    hbG = f'FD.logic__subst(Nat, z => {{Nat.is_le(Nat.add({SCG}n, z), VB.pw(dd)) == {TRUE}}}, {p45}, {pg}, {EQG}, {hb45})'
    hbM = (f'FD.nat__le_trans(Nat.add({NWS}, {pk}), Nat.add({SCW + SCG}n, {pk}), VB.pw(dd), Order.add_right({NWS}, {SCW + SCG}n, {pk}, {{==}}), '
           f'{hbw(SCW + SCG, 1)})')

    def lepg(a, cc):
        # Nat.add(a, pg) <= Nat.add(cc, P)
        return (f'FD.logic__subst(Nat, z => {{Nat.is_le(Nat.add({a}n, z), Nat.add({cc}n, P)) == {TRUE}}}, {p45}, {pg}, {EQG}, '
                f'posle({a}n, {1 + SCW}n, {cc}n, P, {{==}}))')

    def chain(terms, proofs):
        out = proofs[-1]
        for j in range(len(proofs) - 2, -1, -1):
            out = f'Equal.trans({LT}, {terms[j]}, {terms[j + 1]}, {terms[-1]}, {proofs[j]},\n    {out})'
        return out
    w(TPL.render('spec_text_posle', p45=p45, pg=pg))
    # ---- the header segments of the output ----
    m1 = [W4('1n', p0), Wt('1n', p0, L3), Wt('1n', p0, L2), Wt('1n', p0, L1), Wt('1n', p0, D2), f'[{FS}]']
    pr1 = [f'V2.peel_hi({WLB}, dd, {L3}, {pb}, 1n, {p0}, {pfl3}, {hbw(WB, KB)}, posle(1n, 0n, {KB}n, P, {{==}}))',
           f'V2.peel_hi({GL}, dd, {L2}, {pg}, 1n, {p0}, {pfl2}, {hbG}, FD.logic__subst(Nat, z => {{Nat.is_le(Nat.add(1n, {p0}), z) == {TRUE}}}, Nat.add({1 + SCW}n, P), {pg}, {EQG}, posle(1n, 0n, {1 + SCW}n, P, {{==}})))',
           f'VBE.peel_mone_hi({NWS}, 0n, {pk}, dd, {L1}, TS, 1n, {p0}, {pf1}, {hbM}, Order.reflexive({pk}))',
           f'YE.frame_lo({C.A}, dd, {D2}, {PC}, {pf2}, hdst, 1n, {p0}, posle(1n, 0n, {H}n, P, {{==}}))',
           f'V2.own([{FS}], dd, D, {p0}, pf, {hbw(1, 0)})']
    m2 = [W4(NWS, pk), Wt(NWS, pk, L3), Wt(NWS, pk, L2), WPK]
    pr2 = [f'V2.peel_hi({WLB}, dd, {L3}, {pb}, {NWS}, {pk}, {pfl3}, {hbw(WB, KB)}, posle({NWS}, 1n, {KB}n, P, {{==}}))',
           f'V2.peel_hi({GL}, dd, {L2}, {pg}, {NWS}, {pk}, {pfl2}, {hbG}, Order.reflexive({pg}))',
           f'VBE.own_mone({NWS}, {pk}, dd, {L1}, dS, TS, {pf1}, pfS, {hbM}, hrS)']
    m3 = [W4(f'{SCG}n', p45), W4(f'{SCG}n', pg), Wt(f'{SCG}n', pg, L3), GL]
    pr3 = [f'Equal.cong(Nat, {LT}, z => VF.WIN({SCG}n, z, {S_}), {p45}, {pg}, {EQG})',
           f'V2.peel_hi({WLB}, dd, {L3}, {pb}, {SCG}n, {pg}, {pfl3}, {hbw(WB, KB)}, {lepg(SCG, KB)})',
           f'V2.own({GL}, dd, {L2}, {pg}, {pfl2}, {hbG})']
    BWL_ = BWL
    m4 = [W4(f'{WB}n', pb), BWL_]
    pr4 = [f'V2.own({WLB}, dd, {L3}, {pb}, {pfl3}, {hbw(WB, KB)})']
    for nm, ms, prs in [('seg0', m1, pr1), ('seg1', m2, pr2), ('seg2', m3, pr3), ('seg3', m4, pr4)]:
        w(f'def {nm}({WP_}) -> {{{ms[0]} == {ms[-1]} : {LT}}}:')
        w('  ' + chain(ms, prs))
