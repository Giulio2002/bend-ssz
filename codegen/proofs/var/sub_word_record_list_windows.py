TPL = Templates('sub_word_record_list_windows', globals())

HDR = '# GENERATED by sub_word_record_list_windows (codegen). Do not edit.'
U8S, U16S = 'S.Unsigned{P.U8{}}', 'S.Unsigned{P.U16{}}'
# record type -> (size RS, schema, fields [(byte position c, field size, vfx module alias, the field's object at byte y, field schema)])
RECS = {
    'ProgressiveSingleFieldContainerTestStruct': (1, 'S.ProgressiveContainer{["f_A"], S.Chain{S.Unsigned{P.U8{}}, S.End{}}, [True{}]}',
                     [(0, 1, 'FXA', lambda y: f'VRB.BX(t, {y})', U8S)]),
    'SmallTestStruct': (4, 'S.Container{["f_A", "f_B"], S.Chain{S.Unsigned{P.U16{}}, S.Chain{S.Unsigned{P.U16{}}, S.End{}}}}',
                     [(0, 2, 'FXB', lambda y: f'O.keep(2, UR.RWN(t, {y}))', U16S), (2, 2, 'FXB', lambda y: f'O.keep(2, UR.RWN(t, {y}))', U16S)]),
}
FXMOD = {'FXA': 'vfx_u8.bend', 'FXB': 'vfx_u16.bend'}
# (runtime list prefix, record type, limit (None: a progressive list))
LISTS = [('l10_ProgressiveSingleFieldContainerTestStruct', 'ProgressiveSingleFieldContainerTestStruct', 10), ('pl_SmallTestStruct', 'SmallTestStruct', None)]

HEAD = [x.replace('../../types/fulu_obj.bend as T', '../../types/generic_obj.bend as T').replace('../../spec/fulu_schemas.bend as Spec', './generic_specs.bend as Spec')
        for x in RL.HEAD] + ['import ./vlist.bend as VLS', 'import ./vbrt.bend as VR', 'import ./vbitl.bend as VBL', 'import ./vrejb.bend as VRB',
                             'import ./vmv.bend as VMV', 'import ./sub_pack.bend as SP2', 'import ./dk.bend as DK'] + [f'import ./{m} as {a}' for a, m in FXMOD.items()]


def fname(p, LIM):
    return ROOT / f'proofs/obj/{"" if LIM else ""}var_winx_{p}.bend'


def pos(c, y):
    return y if c == 0 else f'{c}n+{y}'


READER = TPL.text('READER')

SPEC = TPL.text('SPEC')

REQ_LIM = TPL.text('REQ_LIM')

REQ_PROG = r"""  %Equal.sym(@MP, Codec.parts(RITEMS(c, t, x), S.Repeat{@SCH}), Some{BP(c, t, x)}, prt_items(c, d, t, x, pf, hf)) :
    {Codec.aggregate(_, None{}) == Some{[S.Variable{Y}]} : @MP}"""

PINV = TPL.text('PINV')


def subst(text, mp):
    for k in sorted(mp, key=len, reverse=True):
        text = text.replace(k, mp[k])
    return text


def list_text(p, R, LIM):
    RS, sch, fields = RECS[R]
    TR = 'FD.array__Tree<U32>'
    TRUE = 'True{} : Bool'
    MP = 'Maybe<&2, +List<S.Part>>'
    Q = 'A.quad(VB.pw(d))'
    LSCH = f'S.ListOf{{{sch}, {LIM}n}}' if LIM else f'S.ProgressiveList{{{sch}}}'
    CW = (f'+d: Nat, +t: {TR}, +n: U32, +x: Nat, +off: U32, +len: U32, +eo: {{U32.to_nat(off) == x : Nat}},\n'
          f'    +hd: {{Nat.is_lt(d, 28n) == {TRUE}}}, +hw: {{Nat.is_le(Nat.add(x, U32.to_nat(len)), {Q}) == {TRUE}}},\n'
          f'    +pf: {{FD.array__perfect(U32, d, t) == {TRUE}}}')
    CA = 'd, t, n, x, off, len, eo, hd, hw, pf'
    HC = f'+hchk: {{CHKw(t, x, off, len) == {TRUE}}}'
    CHK = (f'Bool.and(U32.is_eq(len, (U32.div(len, {RS}) * {RS} : U32)), U32.is_le(U32.div(len, {RS}), {LIM}))' if LIM
           else f'Bool.and(U32.is_eq(len, (U32.div(len, {RS}) * {RS} : U32)), True{{}})')
    mp = {'@TRR': f'FD.array__Tree<T.{R}>', '@TRUE': TRUE, '@TR': TR, '@RD': f'B.Buf & Array<T.{R}>', '@RSn': f'{RS}n', '@RS': str(RS),
          '@RM1': f'{RS - 1}n', '@R': R, '@p': p, '@CW': CW, '@CA': CA, '@HC': HC, '@Q': Q, '@LSCH': LSCH, '@SCH': sch, '@MP': MP,
          '@LIMn': f'{LIM}n'}
    desc = f'List[{R}, {LIM}]' if LIM else f'ProgressiveList[{R}]'
    L = list(HEAD) + ['', HDR, f'# The byte-offset window module of {p} ({desc}, records of {RS} byte{"s" if RS > 1 else ""}): see the',
                      '# module docstring of codegen/proofs/var/sub_word_record_list_windows.py and the interface in proofs/obj/vua_win.bend.', '']
    w = L.append

    def its(i):
        t_ = 'S.EmptyItems{}'
        for c, _, a, _, _ in reversed(fields[i:]):
            t_ = f'S.Items{{{a}.VAL(t, {pos(c, "y")}), {t_}}}'
        return t_

    def chs(i):
        t_ = 'S.End{}'
        for _, _, _, _, fs in reversed(fields[i:]):
            t_ = f'S.Chain{{{fs}, {t_}}}'
        return t_

    def pls(i):
        return '[' + ', '.join(f'S.Fixed{{UW.WX(t, {pos(c, "y")}, {sz}n)}}' for c, sz, _, _, _ in fields[i:]) + ']'

    pf_term = '{==}'
    for i in range(len(fields) - 1, -1, -1):
        c, sz, a, _, fs = fields[i]
        room = f'UR.roomf(y, {RS}n, {c}n, {sz}n, {Q}, hb, {{==}})'
        pf_term = (f'F.cat_fixed(Codec.parts({a}.VAL(t, {pos(c, "y")}), {fs}), UW.WX(t, {pos(c, "y")}, {sz}n), Codec.parts({its(i + 1)}, {chs(i + 1)}), {pls(i + 1)},\n'
                   f'        {a}.prt(d, t, {pos(c, "y")}, pf, {room}, {fs}, {{==}}), {pf_term})')
    fc = '[]'
    for c, sz, _, _, _ in reversed(fields):
        fc = f'List.append(&2, U32, UW.WX(t, {pos(c, "y")}, {sz}n), {fc})'
    if len(fields) == 1:
        fcat_eq = f'VS.app_nil(UW.WX(t, y, {RS}n))'
    else:
        (c0, s0, _, _, _), (c1, s1, _, _, _) = fields
        assert len(fields) == 2 and c1 == s0 and s0 + s1 == RS
        fcat_eq = (f'Equal.trans(+List<U32>, {fc}, List.append(&2, U32, UW.WX(t, y, {s0}n), UW.WX(t, {pos(c1, "y")}, {s1}n)), UW.WX(t, y, {RS}n),\n'
                   f'    Equal.cong(+List<U32>, +List<U32>, z => List.append(&2, U32, UW.WX(t, y, {s0}n), z), List.append(&2, U32, UW.WX(t, {pos(c1, "y")}, {s1}n), []), UW.WX(t, {pos(c1, "y")}, {s1}n), VS.app_nil(UW.WX(t, {pos(c1, "y")}, {s1}n))),\n'
                   f'    Equal.sym(+List<U32>, UW.WX(t, y, Nat.add({s0}n, {s1}n)), List.append(&2, U32, UW.WX(t, y, {s0}n), UW.WX(t, Nat.add({s0}n, y), {s1}n)), UW.splitWX(t, y, {s0}n, {s1}n)))')
    RXT = f'T.{R}{{' + ', '.join(f(pos(c, 'y')) for c, _, _, f, _ in fields) + '}'
    w(TPL.render('list_text', MP=MP, Q=Q, R=R, RS=RS, RXT=RXT, TR=TR, TRUE=TRUE, chs=chs, fc=fc, fcat_eq=fcat_eq, its=its, pf_term=pf_term, pls=pls, sch=sch))
    rr = [TPL.render('list_text_rdb', Q=Q, R=R, RS=RS, TR=TR, TRUE=TRUE)]
    got = []
    for i, (c, sz, a, f, _) in enumerate(fields):
        room = f'UR.roomf(x, {RS}n, {c}n, {sz}n, {Q}, hb, {{==}})'
        ex = (f'UR.offx(d, off, {c}, x, e, FD.nat__lt_trans(d, 28n, 30n, hd, {{==}}), '
              f'FD.nat__lt_le_trans({pos(c, "x")}, Nat.add({pos(c, "x")}, {sz}n), {Q}, VTX.ltp({pos(c, "x")}, {sz - 1}n), {room}))')
        rdf = 'u8_read' if sz == 1 else 'u16_read'
        ctx = f'T.{R}_rd{i}(off, {RS}, ' + ''.join(g + ', ' for g in got) + '_)'
        rr.append(f'  %Equal.sym(B.Buf & U32, T.{rdf}(BF(t, n), U32.add(off, {c}), {sz}), (BF(t, n), {a}.OBJ(d, t, {pos(c, "x")})),\n'
                  f'      {a}.rdx(d, t, n, U32.add(off, {c}), {pos(c, "x")}, {ex}, hd, pf, {room})) :\n'
                  f'    {{{ctx} == (BF(t, n), RX(t, x)) : B.Buf & T.{R}}}')
        got.append(f'{a}.OBJ(d, t, {pos(c, "x")})')
    rr.append('  {==}\n')
    w('\n'.join(rr))
    if LIM:
        ec_def = (TPL.render('ec_def', CHK=CHK, LIM=LIM, RS=RS, TRUE=TRUE))
    else:
        ec_def = (f'''def ecw(+len: U32, +h: {{{CHK} == {TRUE}}})
    -> {{U32.to_nat(len) == Nat.mul(CC(len), {RS}n) : Nat}}:
  VLS.whole_t1(len, {RS}, vR(), {{==}}, {{==}}, {{==}}, h)''')
    w(f'''# ---- the validator ------------------------------------------------------------------------------

def CHKw(+t: {TR}, +x: Nat, +off: U32, +len: U32) -> Bool:
  {CHK}

def ok_evalw({CW}) -> {{T.{p}_ok(BF(t, n), off, len) == (BF(t, n), CHKw(t, x, off, len)) : B.Buf & Bool}}:
  {{==}}

def vR() -> Word(31n): FD.spec_numeric__from_nat(31n, {RS}n)

# The window is c whole records{f", c <= {LIM}" if LIM else ""}.
def NN(+len: U32) -> U32: U32.div(len, {RS})
def CC(+len: U32) -> Nat: U32.to_nat(NN(len))
{ec_def}
''')
    w(subst(READER, mp))
    w(subst(SPEC.replace('@REQ', REQ_LIM if LIM else REQ_PROG), mp))
    if LIM:
        w(RL.inv_text(sch, RS, str(LIM), LSCH, CW, CA))
    else:
        w(subst(PINV, mp))
    txt = '\n'.join(L) + '\n'
    # the record storage depth from the window, not from a bound
    txt = txt.replace('      +hdd = FD.nat__le_lt_trans(B.words_depth(NN(len)), 99n, 32n, VD.wd_min(NN(len), 99n, hcl), {==})\n',
                      '      +hdd = FD.nat__le_lt_trans(B.words_depth(NN(len)), 99n, \n')
    txt = txt.replace('      +hcp = VD.wd_cover(NN(len), 99n, {==}, FD.nat__le_trans(c, U32.to_nat(0), O.pow2n(99n), hcl, {==}))\n',
                      '      +hcp = VD.wd_cover(NN(len), 99n, {==}, FD.nat__le_trans(c, U32.to_nat(\n')
    return rs_deep(RL.sym_depth(txt, RS, 99), RS, LIM)


def rs_deep(text, RS, LIM):
    """The record list's decode window at any depth d < 31 (record_list_offset_windows.deep_rlist's pattern): the read loop
    carries the records' end below 2^32 (hb32: VRL.posU32 / succU32), the fields by their vfx modules' rdxD
    (UR.offx31), the storage depth from the limit (LIM: c <= LIM) or from records of four bytes (c <= 2^d)."""
    from codegen.proofs.var import nested_type_window_laws as VWN
    T = 'True{} : Bool'
    P32 = 'FD.spec_common__pow2(32n)'
    POS = lambda j: f'VRL.pos({j}, {RS}n, x)'
    a = text.index('      +hcN = ')
    b = text.index('      +hcP = ')
    if LIM:
        K = max(LIM - 1, 1).bit_length()
        hc = (f'      +hcN = FD.nat__le_trans(c, U32.to_nat({LIM}), O.pow2n({K}n), hcw(len, hchk), {{==}})\n'
              f'      +hcp = VD.wd_cover(NN(len), {K}n, {{==}}, hcN)\n')
        hdd = f'      +hdd = FD.nat__le_lt_trans(B.words_depth(NN(len)), {K}n, 32n, VD.wd_min(NN(len), {K}n, hcN), {{==}})\n'
    else:
        assert RS >= 4, RS
        hc = (TPL.render('hc', RS=RS, T=T))
        hdd = '      +hdd = FD.nat__le_lt_trans(B.words_depth(NN(len)), d, 32n, VD.wd_min(NN(len), d, hcN), FD.nat__lt_trans(d, 31n, 32n, hd, {==}))\n'
    hb32 = (TPL.render('hb32', P32=P32, POS=POS, RS=RS, T=T))
    text = text[:a] + hb32 + hc + text[b:]
    a = text.index('      +hdd = ')
    text = text[:a] + hdd + text[text.index('\n', a) + 1:]
    reps = [
        (f"+hb: {{Nat.is_le({POS('Nat.add(1n+k, j)')}, A.quad(VB.pw(d))) == {T}}},\n",
         f"+hb: {{Nat.is_le({POS('Nat.add(1n+k, j)')}, A.quad(VB.pw(d))) == {T}}}, +hb32: {{Nat.is_lt({POS('Nat.add(1n+k, j)')}, {P32}) == {T}}},\n"),
        (f"      +hx = VRL.nextfit(j, q, {RS}n, x, A.quad(VB.pw(d)), hb)\n",
         TPL.render('rs_deep', P32=P32, POS=POS, RS=RS, T=T)),
        (f"      +ex = VRL.posU(d, off, x, i, j, {RS}, {RS - 1}n, {{==}}, eo, ej, hd, hx)", f"      +ex = VRL.posU32(off, x, i, j, {RS}, {RS - 1}n, {{==}}, eo, ej, hx32)"),
        (f"VRL.succU(d, i, j, {RS - 1}n, x, ej, hd, hx), hd, pf, hb2, hdd, hk2,", f"VRL.succU32(i, j, {RS - 1}n, x, ej, hx32), hd, pf, hb2, hb232, hdd, hk2,"),
        ("eo, {==}, hd, pf, hb, hdd, hk,", "eo, {==}, hd, pf, hb, hb32, hdd, hk,"),
        ("FD.nat__lt_trans(d, 28n, 30n, hd, {==}), FD.nat__lt_le_trans(", "hd, FD.nat__lt_le_trans("),
        (f"  +hf = FD.logic__subst(Nat, z => {{Nat.is_le(Nat.add(x, z), A.quad(VB.pw(d))) == {T}}}, U32.to_nat(len), Nat.mul(c, {RS}n), ec, hw)\n",
         f"  +hf = FD.logic__subst(Nat, z => {{Nat.is_le(Nat.add(x, z), A.quad(VB.pw(d))) == {T}}}, U32.to_nat(len), Nat.mul(c, {RS}n), ec, hw)\n"
         f"  +hf32 = FD.logic__subst(Nat, z => {{Nat.is_lt(Nat.add(x, z), {P32}) == {T}}}, U32.to_nat(len), Nat.mul(c, {RS}n), ec, hw32)\n"),
        (f"VFT.fits4(2n+d, Nat.mul(c, {RS}n), FD.nat__le_trans(Nat.mul(c, {RS}n), Nat.add(x, Nat.mul(c, {RS}n)), A.quad(VB.pw(d)), Order.left_below_sum(x, Nat.mul(c, {RS}n)), hf), FD.nat__lt_trans(d, 28n, 30n, hd, {{==}}))",
         f"VFT.fits4lt(Nat.mul(c, {RS}n), FD.nat__le_lt_trans(Nat.mul(c, {RS}n), Nat.add(x, Nat.mul(c, {RS}n)), {P32}, Order.left_below_sum(x, Nat.mul(c, {RS}n)), hf32))"),
    ]
    for x_, y_ in reps:
        assert text.count(x_) >= 1, (text.count(x_), x_[:90])
        text = text.replace(x_, y_)
    text = text.replace('UR.offx(', 'UR.offx31(')
    text = re.sub(r'(?<![\w.])(FX[AB])\.rdx\(', r'\1.rdxD(', text)
    assert 'nat__lt_trans(d, 28n' not in text, [l for l in text.split('\n') if 'nat__lt_trans(d, 28n' in l][:2]
    return VWN.deep_x(text)


def outputs():
    return {fname(p, LIM): list_text(p, R, LIM) for p, R, LIM in LISTS}


def main():
    # accepts '--check' (check_or_write_outputs.finish reads it)
    out = outputs()
    mine = sorted((ROOT / 'proofs/obj').glob('*var_winx_*.bend'))
    mine = [q for q in mine if q.read_text().find(HDR) >= 0]
    orphans = [str(q.relative_to(ROOT)) for q in mine if q not in out]
    return finish(out, 'stale generated record lists: ', 'generated record lists are current', orphans)


if __name__ == '__main__':
    main()
