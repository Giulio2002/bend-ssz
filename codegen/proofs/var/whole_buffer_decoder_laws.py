#!/usr/bin/env python3
"""Whole-buffer decoder laws (ok_eval, decode_accept, decode_spec, decode_unique,
decode_reject, decode_none) of names whose byte-offset window modules exist but
whose top modules no other generator writes: the window at x = 0, off = 0, len = n
(the template of codegen/proofs/var/execution_requests_window.py's top_text, as codegen/proofs/var/block_body_offset_windows.py uses it).

    python3 codegen/proofs/var/whole_buffer_decoder_laws.py [--check]

  ExecutionPayload  proofs/obj/var_codec_ExecutionPayload.bend
                    (window proofs/obj/var_winx_ExecutionPayload.bend, codegen/proofs/var/multi_variable_container_windows.py;
                    big children, so the top is a big_ file)
  Transaction       proofs/obj/var_codec_Transaction.bend
                    (window proofs/obj/vvlb_bl1073741824.bend, codegen/proofs/var/variable_element_list_windows.py).
                    Transaction's runtime validator and reader are the ByteList[2^30] ones
                    (T.bl1073741824_ok/_read) and its object is O.Words. The spec parts of a
                    value are read without DS.facts (which would evaluate the 2^30 limit):
                    rjt splits the value and keeps ByteList.domain(limit, xs) as a variable.
  Transaction's encoder: proofs/obj/var_codec_Transaction_enc.bend (encode_eval, encode_spec).
"""
import sys as _sys
import pathlib as _pathlib
_sys.path.insert(0, str(_pathlib.Path(__file__).resolve().parents[3]))  # the repository root: `codegen` is importable when this file runs as a script
import re
import sys
from codegen.core import generated_file_writer as writer  # noqa: E402
import types

from codegen.core.repository_paths import ROOT  # noqa: E402
from codegen.core.template_loader import Templates  # noqa: E402
TEMPLATES = Templates('whole_buffer_decoder_laws', globals())

HDR = '# GENERATED by whole_buffer_decoder_laws (codegen). Do not edit.'


def ep_text():
    from codegen.proofs.var import block_body_offset_windows as WB
    txt = WB.top_text(types.SimpleNamespace(name='ExecutionPayload'), 'var_winx_ExecutionPayload.bend')
    return txt.replace('# GENERATED by block_body_offset_windows (codegen). Do not edit.', HDR)


VALUES = ['S.BooleanValue{+b0}', 'S.UnsignedValue{+u0}', None, 'S.BitsValue{+bs0}', 'S.Sequence{+it0}',
          'S.Items{+hd0, +tl0}', 'S.EmptyItems{}', 'S.Selected{+sel0, +sv0}', 'S.NullValue{}']

LIM = 'U32.to_nat(1073741824)'


def rjt_text():
    PT = 'Maybe<&2, +List<S.Part>>'
    g = f'{{Codec.parts(v, Spec.Transaction()) == Some{{[S.Variable{{ys}}]}} : {PT}}}'
    L = ["# A value encoding to the buffer's bytes has them as its one variable part (the limit",
         '# test ByteList.domain(limit, xs) stays a variable b).',
         'def rjb(+xs: +List<U32>, +b: Bool, +ys: +List<U32>, +e: {Codec.bytes(Codec.one(SP.optional(b, xs), None{})) == Some{ys} : Maybe<&2, +List<U32>>})',
         f'    -> {{Codec.one(SP.optional(b, xs), None{{}}) == Some{{[S.Variable{{ys}}]}} : {PT}}}:',
         '  match b:',
         f'    case False{{}}: Empty.absurd({{Codec.one(SP.optional(False{{}}, xs), None{{}}) == Some{{[S.Variable{{ys}}]}} : {PT}}}, FD.logic__none_some(+List<U32>, ys, e))',
         '    case True{}:',
         f'      %FD.logic__some_inj(+List<U32>, xs, ys, e) : {{Codec.one(SP.optional(True{{}}, xs), None{{}}) == Some{{[S.Variable{{_}}]}} : {PT}}}',
         '      {==}',
         '',
         'def rjt(+v: S.Value, +ys: +List<U32>, +e: {Codec.encoding_for_legal_type(Spec.Transaction(), v) == Some{ys} : Maybe<&2, +List<U32>>})',
         f'    -> {g}:',
         '  match v:']
    for c in VALUES:
        if c is None:
            L.append(f'    case S.BytesValue{{+xs}}: rjb(xs, ByteList.domain({LIM}, xs), ys, e)')
        else:
            gc = g.replace('Codec.parts(v,', f'Codec.parts({re.sub(r"[+]", "", c)},')
            L.append(f'    case {c}: Empty.absurd({gc}, FD.logic__none_some(+List<U32>, ys, e))')
    return '\n'.join(L) + '\n\n'


def tx_text():
    from codegen.proofs.var import execution_requests_window as ER
    from codegen.proofs.var import record_list_offset_windows as RL
    txt = ER.top_text(RL.HEAD)
    txt = txt.replace('import ./var_winx_ExecutionRequests.bend as EW',
                      'import ../../spec/byte_list.bend as ByteList\nimport ./vvlb_bl1073741824.bend as EW')
    txt = txt.replace('# GENERATED by record_list_offset_windows (codegen: execution_requests_window). Do not edit.', HDR)
    # Transaction's runtime validator / reader are ByteList[2^30]'s; its object is O.Words
    txt = txt.replace('T.ExecutionRequests_ok(', 'T.bl1073741824_ok(').replace('T.ExecutionRequests_read(', 'T.bl1073741824_read(')
    txt = txt.replace('Maybe<&1, T.ExecutionRequests>', 'Maybe<&1, O.Words>').replace('B.Buf & T.ExecutionRequests,', 'B.Buf & O.Words,')
    txt = txt.replace('-> T.ExecutionRequests:', '-> O.Words:')
    txt = txt.replace('ExecutionRequests', 'Transaction')
    a = txt.index("# A value encoding to the buffer's bytes")
    b = txt.index('def rej_f(')
    txt = txt[:a] + rjt_text() + txt[b:]
    old = 'rj_m(v, VW(t, n), Codec.parts(v, Spec.Transaction()), DS.facts(v, Spec.Transaction(), {==}), {==}, e)'
    assert old in txt
    txt = txt.replace(old, 'rjt(v, VW(t, n), e)')
    assert 'T.Transaction,' not in txt and 'T.Transaction>' not in txt and 'T.Transaction_ok' not in txt
    return txt


TX_ENC = TEMPLATES.text('TX_ENC')


def tx_enc_deep(text, LIM='1073741824'):
    """Transaction's encoder laws at any tree depth dw < 31: the copy's storage bounds from 31 + N <= UMAX
    (N <= the list limit <= NMAX: VB.le_nmax), never from the tree's depth."""
    HN = f'+hN: {{U32.is_le(N, {LIM}) == True{{}} : Bool}}'
    HY = f'VB.le_nmax(N, VB.u32le_trans(N, {LIM}, VB.NMAX(), hN, {{==}}))'
    reps = [
        ('VBR.nwle(dw, N, hdw, hn)', f'VBR.nwleU(dw, N, {HY}, hn)'),
        ('FD.nat__le_lt_trans(VL.DO(N), dw, 31n, VD.wd_min(VC.nwu(N), dw, nwp(dw, N, hdw, hn)), FD.nat__lt_trans(dw, 28n, 31n, hdw, {==}))',
         'FD.nat__le_lt_trans(VL.DO(N), dw, 31n, VD.wd_min(VC.nwu(N), dw, nwp(dw, N, hdw, hn, hN)), hdw)'),
        ('FD.nat__le_trans(dw, 28n, 32n, FD.nat__lt_le(dw, 28n, hdw), {==})', 'FD.nat__le_trans(dw, 31n, 32n, FD.nat__lt_le(dw, 31n, hdw), {==})'),
        ('  +hdw31 = FD.nat__lt_trans(dw, 28n, 31n, hdw, {==})\n', '  +hdw31 = hdw\n'),
        ('VBE.put_words_any(D, dw, VC.ZT(D), T, 0, 0n, N, VL.KK(dw), FD.array__trep_perfect(U32, D, 0), pfT, hDO(dw, N, hdw, hn), hdw31, {==}, {==},\n'
         '        VL.kk_lt(dw, hdw), VL.hyn(dw, N, hn), hroom,',
         'VBE.put_words_anyU(D, dw, VC.ZT(D), T, 0, 0n, N, FD.array__trep_perfect(U32, D, 0), pfT, hDO(dw, N, hdw, hn), hdw31, {==}, {==},\n'
         f'        {HY}, hroom,'),
        ('VZ.quad_nw_ge(N, VL.KK(dw), VL.kk_lt(dw, hdw), VL.hyn(dw, N, hn))', f'VZ.quad_nw_geU(N, {HY})'),
        ('VBZ.fitq(dw, U32.to_nat(N), hn, FD.nat__lt_trans(dw, 28n, 30n, hdw, {==}))', 'VFT.fits4lt(U32.to_nat(N), VB.u32_lt(N))'),
    ]
    for a, b in reps:
        assert a in text, a[:80]
        text = text.replace(a, b)
    text = text.replace('Nat.is_lt(dw, 28n)', 'Nat.is_lt(dw, 31n)')
    # hN reaches the helpers: nwp, hDO, hdst, obytes take it after hn; their calls pass it
    import re as _re
    HNd = '+hn: {Nat.is_le(U32.to_nat(N), A.quad(VB.pw(dw))) == True{} : Bool})\n    ->'
    assert text.count(HNd) == 4, text.count(HNd)
    text = text.replace(HNd, HNd.replace('Bool})', 'Bool}, ' + HN + ')'))
    text = text.replace('import ./vbsize.bend as VBZ\n', 'import ./vbsize.bend as VBZ\nimport ./vfits.bend as VFT\n', 1)
    assert 'as VFT' in text
    for f in ('nwp', 'hDO', 'hdst', 'obytes'):
        text = _re.sub(r'(?<![\w.])%s\((dw, (?:T, )?N, (?:pfT, )?hdw, hn)\)' % f, r'%s(\1, hN)' % f, text)
    assert '28n' not in text, [l for l in text.split('\n') if '28n' in l][:3]
    return text


def main():
    out = {}
    # the whole-buffer laws at any depth d < 31 over the (hwN) windows' D interface, n <= NMAX their premise hN
    from codegen.proofs.var import block_body_offset_windows as WB
    out[ROOT / 'proofs/obj/var_codec_ExecutionPayload.bend'] = WB.top_deep(ep_text(), 'EW', 'hwN')
    out[ROOT / 'proofs/obj/var_codec_Transaction.bend'] = WB.top_deep(tx_text(), 'EW', 'hwN')
    out[ROOT / 'proofs/obj/var_codec_Transaction_enc.bend'] = tx_enc_deep(TX_ENC)
    from codegen.impl import runtime_file_split as RR  # the runtime split: the modules import the per-name files they use
    out = RR.rewire_out(out)
    if '--check' in sys.argv:
        return writer.check(out, 'stale generated top modules: ', 'generated top modules are current')
    for p, t in out.items():
        p.write_text(t)
    print(', '.join(str(p.relative_to(ROOT)) for p in out))


if __name__ == '__main__':
    main()
