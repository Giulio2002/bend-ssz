#!/usr/bin/env python3
"""BitList[N] of the generic containers (types/generic_obj.bend) at a window of any byte
offset: codegen/proofs/var/var_win.py's bit-list window (the interface of proofs/obj/vua_win.bend) with
the generic runtime and the literal schema S.BitList{Nn} (generic_specs inlines it).

    python3 codegen/proofs/var/var_winbits.py [--check]
"""
import sys as _sys
import pathlib as _pathlib
_sys.path.insert(0, str(_pathlib.Path(__file__).resolve().parents[3]))  # the repository root: `codegen` is importable when this file runs as a script
import sys
from pathlib import Path

from codegen.proofs.var import var_win as VW  # noqa: E402

ROOT = Path(__file__).resolve().parents[3]
LISTS = [5, 6, 256, 257, 1280, 1281]


def win_text(N):
    b = VW.Bits(N, f'bits{N}', f'S.BitList{{{N}n}}', f'{N}n')
    txt = VW.bitsx_text(b, deep=True)
    out = []
    for ln in txt.split('\n'):
        ln = ln.replace('import ../../types/fulu_obj.bend as T', 'import ../../types/generic_obj.bend as T')
        ln = ln.replace('import ../../spec/fulu_schemas.bend as Spec', 'import ./generic_specs.bend as Spec')
        ln = ln.replace('# GENERATED by codegen/proofs/var/var_win.py. Do not edit.', '# GENERATED by codegen/proofs/var/var_winbits.py (codegen/proofs/var/var_win.py). Do not edit.')
        out.append(ln)
    return '\n'.join(out)


def outputs():
    return {ROOT / f'proofs/obj/var_winx_g_bits{N}.bend': win_text(N) for N in LISTS}


def main():
    out = outputs()
    from codegen.impl import runtime_refs as RR  # the runtime split: the modules import the per-name files they use
    out = RR.rewire_out(out)
    if '--check' in sys.argv:
        stale = [str(p.relative_to(ROOT)) for p, t in out.items() if not p.exists() or p.read_text() != t]
        if stale:
            print('stale: ' + ', '.join(stale))
            sys.exit(1)
        print('generic bit-list windows are current')
        return
    for p, t in out.items():
        p.write_text(t)
    print('wrote ' + ', '.join(str(p.relative_to(ROOT)) for p in out))


if __name__ == '__main__':
    main()
