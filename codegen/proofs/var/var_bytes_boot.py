#!/usr/bin/env python3
"""LightClientBootstrap: a container nesting LightClientHeader whose header also
holds a SyncCommittee (6156 words, array-backed). Helpers for codegen/proofs/var/var_bytes_nest.py:
proofs/obj/vsc.bend, the spec parts of a SyncCommittee value over any word list
of 6144 words (adapted from spec_arr_SyncCommittee.bend's tree-based statement).
"""
import re

from codegen.core.bendtext import wsplit  # noqa: E402
from codegen.proofs.var import var_bytes as VBY
from codegen.core.shared_var_b import Templates  # noqa: E402
TPL = Templates('var_bytes_boot', globals())

ROOT = VBY.ROOT
AB = 'F.spec_common__append(U32, F.array__slots(U32, a), F.array__slots(U32, b))'
LEN2 = ('AS.len2(F.array__slots(U32, a), F.array__slots(U32, b), 4096n, 2048n, 6144n, AS.len_tree(12n, a, 4096n, pa, {==}), '
        'AS.len_tree(11n, b, 2048n, pb, {==}), {==})')



def vsc_text():
    src = (ROOT / 'proofs/obj/spec_arr_SyncCommittee.bend').read_text().split('\n')
    i0 = [i for i, l in enumerate(src) if l.startswith('def SyncCommittee_spec_parts(')][0]
    i1 = i0 + 1
    while not src[i1].startswith('def ') and not src[i1].startswith('#'):
        i1 += 1
    body = src[i0:i1]
    head = [l for l in src if l.startswith('import ')]
    G = '[g0, g1, g2, g3, g4, g5, g6, g7, g8, g9, g10, g11]'
    gs = ', '.join(f'+g{j}: U32' for j in range(12))
    VAL = f'S.Sequence{{S.Items{{S.Sequence{{AV.ch12(W)}}, S.Items{{S.BytesValue{{SF.limbs({G})}}, S.EmptyItems{{}}}}}}}}'
    out = head + ['', '# GENERATED by var_bytes_boot (codegen). Do not edit.',
                  '# The spec parts of a SyncCommittee value over any list W of 6144 words (the',
                  '# statement of spec_arr_SyncCommittee.bend SyncCommittee_spec_parts with the two',
                  '# trees replaced by a word list).', '',
                  f'def sc_parts(+W: List<&2, U32>, {gs}, +hl: {{F.spec_common__length(U32, W) == 6144n : Nat}}, +s: S.Schema, +es: {{s == Spec.SyncCommittee() : S.Schema}})',
                  f'    -> {{Codec.parts({VAL}, s) == Some{{[S.Fixed{{SF.limbs(F.spec_common__append(U32, W, {G}))}}]}} : Maybe<&2, +List<S.Part>>}}:',
                  f'  %Equal.sym(+List<U32>, SF.limbs(F.spec_common__append(U32, W, {G})), List.append(&2, U32, SF.limbs(W), SF.limbs({G})), AS.limbs_app(W, {G})) :',
                  f'    {{Codec.parts({VAL}, s) == Some{{[S.Fixed{{_}}]}} : Maybe<&2, +List<S.Part>>}}']
    rest = '\n'.join(body[10:])
    assert LEN2 in rest
    rest = rest.replace(LEN2, 'hl').replace(AB, 'W')
    out.append(rest)
    return '\n'.join(out).rstrip('\n') + '\n'


def outputs():
    return {ROOT / 'proofs/obj/vsc.bend': vsc_text()}


# ---- the SyncCommittee field ---------------------------------------------------------------------

def comp_field(g, ft, inner, size):
    """A Type record [packed words of Vector[ByteVector[48], k], a byte record]: SyncCommittee."""
    (n0, s0), (n1, s1) = inner.fields
    (_, t0), (_, t1) = ft.fields
    if not (s0.kind == 'packed_elems' and t0.kind == 'vector' and t0.elem.kind == 'bytes' and t0.elem.size == 48):
        raise VBY.Skip('record: first field not a vector of Bytes48')
    ws = t0.fixed_size()
    m = re.search(rf'^def {s0.p}_read\(buf: B\.Buf, \+off: U32, \+len: U32\) -> B\.Buf & O\.Words: '
                  rf'O\.copy_into\(buf, off, {ws}, Array\.new\(U32, (\d+)n, 0\)\)$', VBY.src(), re.M)
    if not m:
        raise VBY.Skip('record: words reader shape')
    rft = VBY.FTW(g, t1)
    assert ws + rft.size == size and ws // 48 == 512
    return {'kind': 'comp', 'p': inner.p, 'size': size, 'W': size // 4, 'wp': s0.p, 'wsize': ws, 'wW': ws // 4,
            'wdz': int(m.group(1)), 'rft': rft}


def comp_obj(x, f, i='i'):
    k, wW, dz = f['k'], f['wW'], f['wdz']
    words = [x.slot(k + wW + j) for j in range(f['rft'].W)]
    return (f'T.{f["p"]}{{O.Words{{FD.array__thaw(U32, VB.mone({wW}n, Nat.add({k}n, i), 0n, {dz}n, VC.ZT({dz}n), t)), {f["wsize"]}}}, '
            f'{f["rft"].obj(words)}}}')


def rd_comp_lemma(f):
    from codegen.proofs.var import var_bytes_nest as VBN
    p, wW, dz, ws, rft = f['p'], f['wW'], f['wdz'], f['wsize'], f['rft']
    W = f['W']
    words = [f'VB.slot(t, Nat.add({wW + j}n, i))' for j in range(rft.W)]
    WO = f'O.Words{{FD.array__thaw(U32, VB.mone({wW}n, i, 0n, {dz}n, VC.ZT({dz}n), t)), {ws}}}'
    RO = rft.obj(words)
    RHS = f'(VF.BF(t, n), T.{p}{{{WO}, {RO}}})'
    TY = f'B.Buf & T.{p}'
    kw = VBY.kfit(31 + ws)
    MN = f'VB.mone(VC.NW({ws}), i, 0n, {dz}n, VC.ZT({dz}n), t)'
    MO = f'VB.mone({wW}n, i, 0n, {dz}n, VC.ZT({dz}n), t)'
    MKT = f'VY.MK({ws}, {dz}n, {MN})'
    return [TPL.render('rd_comp_lemma', MKT=MKT, MN=MN, MO=MO, RHS=RHS, RO=RO, TY=TY, VBN=VBN, W=W, WO=WO, dz=dz, f=f, kw=kw, p=p, rft=rft, wW=wW, ws=ws)]


def rd_comp_shift(f, k):
    """rd_comp_<p> read at k + i restates its record's words at Nat.add(k + w, i) (OBJw's spelling)
    instead of Nat.add(w, Nat.add(k, i)): one motive per word over shiftk at a symbolic word index, so no
    conversion compares the two spellings by walking the word index in unary. [shiftk, the lemma]."""
    p, wW, dz, ws, rft = f['p'], f['wW'], f['wdz'], f['wsize'], f['rft']
    WO = f'O.Words{{FD.array__thaw(U32, VB.mone({wW}n, Nat.add({k}n, i), 0n, {dz}n, VC.ZT({dz}n), t)), {ws}}}'

    def ty(m, hole=None):
        words = [f'VB.slot(t, Nat.add({k + wW + j}n, i))' if j < m else f'VB.slot(t, Nat.add({wW + j}n, Nat.add({k}n, i)))'
                 for j in range(rft.W)]
        if hole is not None:
            words[hole] = 'VB.slot(t, z)'
        return f'{{T.{p}_read(VF.BF(t, n), off, {f["size"]}) == (VF.BF(t, n), T.{p}{{{WO}, {rft.obj(words)}}}) : B.Buf & T.{p}}}'
    body = 'h'
    for j in range(rft.W):
        body = (f'FD.logic__subst(Nat, z => {ty(j, j)}, Nat.add({wW + j}n, Nat.add({k}n, i)), Nat.add({k + wW + j}n, i), '
                f'shiftk({k}n, {wW + j}n, i), {body})')
    shk = TPL.text('shk')
    lem = (f"# rd_comp_{p} at {k} + i, its record's words restated at {k + wW} + i .. (OBJw's spelling)\n"
           f'def rdc_shift_{p}_{k}(+d: Nat, +t: FD.array__Tree<U32>, +n: U32, +off: U32, +i: Nat,\n'
           f'    +h: {ty(0)})\n    -> {ty(rft.W)}:\n  {body}\n')
    return shk, lem


# ---- the spec side with symbolic word segments ----------------------------------------------------

def segments(x, S, word):
    """Header segments in order: (kind, k, W, value term, buffer term, field).
    word(k) is the term of header word k; S the slot list term."""
    out = []
    for f in x.fields:
        if f['kind'] == 'var':
            out.append(('off', f['k'], 1, f'[{x.FS}]', f'[{word(f["k"])}]', f))
        elif f['kind'] == 'comp':
            WPK = f'VF.WIN({f["wW"]}n, Nat.add({f["k"]}n, i), {S})'
            G = '[' + ', '.join(word(f['k'] + f['wW'] + j) for j in range(f['rft'].W)) + ']'
            t = f'VF.app({WPK}, {G})'
            out.append(('comp', f['k'], f['W'], t, t, f))
        else:
            ws = '[' + ', '.join(word(f['k'] + j) for j in range(f['W'])) + ']'
            out.append(('lit', f['k'], f['W'], ws, ws, f))
    return out


def comp_val(f, S, word):
    WPK = f'VF.WIN({f["wW"]}n, Nat.add({f["k"]}n, i), {S})'
    G = ', '.join(word(f['k'] + f['wW'] + j) for j in range(f['rft'].W))
    return WPK, G, f'S.Sequence{{S.Items{{S.Sequence{{AV.ch12({WPK})}}, S.Items{{S.BytesValue{{F.limbs([{G}])}}, S.EmptyItems{{}}}}}}}}'


def spec_items_seg(x, V, Yb, hv, S, word):
    vals, schs, parts, proofs = [], [], [], []
    for f in x.fields:
        if f['kind'] == 'var':
            vals.append(V)
            schs.append(f'Spec.{x.Y}()')
            parts.append(f'S.Variable{{{Yb}}}')
            proofs.append(None)
        elif f['kind'] == 'comp':
            WPK, G, v = comp_val(f, S, word)
            vals.append(v)
            schs.append(f'Spec.{f["p"]}()')
            parts.append(f'S.Fixed{{F.limbs(VF.app({WPK}, [{G}]))}}')
            proofs.append((f'F.limbs(VF.app({WPK}, [{G}]))', f'VSC.sc_parts({WPK}, {G}, hlW, Spec.{f["p"]}(), {{==}})'))
        else:
            nd = x.node(f, lambda f_, j: word(f_['k'] + j))
            vals.append(nd['val'])
            schs.append(nd['sch'])
            parts.append(f'S.Fixed{{F.limbs([{", ".join(nd["words"])}])}}')
            proofs.append((f'F.limbs([{", ".join(nd["words"])}])', nd['proof']))
    m = len(vals)

    def items(i):
        return 'S.EmptyItems{}' if i == m else f'S.Items{{{vals[i]}, {items(i + 1)}}}'

    def chain(i):
        return 'S.End{}' if i == m else f'S.Chain{{{schs[i]}, {chain(i + 1)}}}'

    def cat(i):
        if i == m:
            return '{==}'
        rest = '[' + ', '.join(parts[i + 1:]) + ']'
        if proofs[i] is not None:
            return (f'VS.chain_fixed({vals[i]}, {items(i + 1)}, {schs[i]}, {chain(i + 1)}, {proofs[i][0]}, '
                    f'{rest}, {proofs[i][1]}, {cat(i + 1)})')
        return (f'VS.chain_var({vals[i]}, {items(i + 1)}, {schs[i]}, {chain(i + 1)}, {Yb}, {rest}, '
                f'{hv}, {cat(i + 1)})')
    return items(0), chain(0), '[' + ', '.join(parts) + ']', cat(0)


def spec_part_seg(x):
    n, FS, H, po, Y = x.n, x.FS, x.H, x.po, x.Y
    FSN = x.FSN
    HA = f'+ha: {{U32.is_le({FS}, len) == True{{}} : Bool}}'
    s = 'FD.array__slots(U32, t)'
    word = lambda k: f'VB.slot(t, Nat.add({k}n, i))'  # noqa: E731
    segs = segments(x, s, word)
    vi = [j for j, sg in enumerate(segs) if sg[0] == 'off'][0]
    comps = [sg for sg in segs if sg[0] == 'comp']
    assert len(comps) == 1
    cf = comps[0][5]
    WPK, G, _ = comp_val(cf, s, word)
    CT = f'VF.app({WPK}, [{G}])'
    PRE = '[' + ', '.join(sg[3] for sg in segs[:vi]) + ']'
    POST = '[' + ', '.join(sg[3] for sg in segs[vi + 1:]) + ']'
    SEGSv = '[' + ', '.join(sg[3] for sg in segs) + ']'
    SEGSs = '[' + ', '.join(sg[4] for sg in segs) + ']'
    SEGSh = '[' + ', '.join(sg[4] if j != vi else '[_]' for j, sg in enumerate(segs)) + ']'
    ITEMS, CHAIN, PL, CAT = spec_items_seg(x, 'V', 'Yb', 'hv', s, word)
    MP = 'Maybe<&2, +List<S.Part>>'
    M = 'Maybe<&2, +List<U32>>'
    HDRB = f'F.limbs(VZ.cat({SEGSv}))'
    ENC = f'List.append(&2, U32, {HDRB}, Yb)'
    ENCR = f'List.append(&2, U32, List.append(&2, U32, F.flat({PRE}), List.append(&2, U32, N.digits(4n, VS.FSZ({PRE}, {POST})), F.flat({POST}))), Yb)'
    HLW = f'+hlW: {{FD.spec_common__length(U32, {WPK}) == {cf["wW"]}n : Nat}}'
    WIN = f'VS.bt(U32.to_nat(len), F.limbs(VB.wdr(i, {s})))'
    YT = f'VS.bt(U32.to_nat(LL(len)), F.limbs(VB.wdr(Nat.add({H}n, i), {s})))'
    VY_ = f'YW.VALw(t, Nat.add({H}n, i), LL(len))'
    pre_t = [sg[3] for sg in segs[:vi]]
    post_t = [sg[3] for sg in segs[vi + 1:]]
    CWn = f'{cf["W"]}n'
    # FSZ(PRE, POST) = 4 lsum PRE + 4 + 4 lsum POST with each segment's length given by a
    # hypothesis (the comp's by lcomp): the symbolic segments are never unfolded
    def lsum_pf(sgs):
        if not sgs:
            return '0n', 'VBZ.lsum_nil()'
        sg = sgs[0]
        C, hc = (CWn, 'lcomp(t, i, hlW)') if sg[0] == 'comp' else (f'{sg[2]}n', '{==}')
        R, hr = lsum_pf(sgs[1:])
        rest = '[' + ', '.join(g[3] for g in sgs[1:]) + ']'
        return f'Nat.add({C}, {R})', f'VBZ.lsum_c({sg[3]}, {rest}, {C}, {R}, {hc}, {hr})'
    Pn, hp = lsum_pf(segs[:vi])
    Qn, hq = lsum_pf(segs[vi + 1:])
    SUM = f'Nat.add(A.quad({Pn}), 4n+A.quad({Qn}))'
    ENH = 'enH' if x.big else 'enFS'
    EQ = f'FD.nat__eq_from_is_eq({SUM}, {FSN}, {{==}})' if x.big else '{==}'
    HFS = (f'  Equal.trans(Nat, VS.FSZ({PRE}, {POST}), {SUM}, {FSN},\n'
           f'    VBZ.fsz_lsum({PRE}, {POST}, {Pn}, {Qn}, {hp}, {hq}),\n    {EQ})')
    L = [TPL.render('spec_part_seg', CAT=CAT, CHAIN=CHAIN, CT=CT, ENC=ENC, ENCR=ENCR, FS=FS, FSN=FSN, G=G, HFS=HFS, HLW=HLW, ITEMS=ITEMS, M=M, MP=MP, PL=PL, POST=POST, PRE=PRE, VY_=VY_, WPK=WPK, Y=Y, cf=cf, n=n)]
    w = L.append
    # the header window as the concatenated segments
    w('# Order.left_below_sum at a symbolic k, with the sum\'s literal part named 1 + k; instantiated at')
    w('# k = H - 1 it converts to H + i without walking H - 1 in unary')
    w('def lbs1(+k: Nat, +i: Nat) -> {Nat.is_le(Nat.add(1n, Nat.add(0n, i)), Nat.add(Nat.add(1n, k), i)) == True{} : Bool}:')
    w('  FD.logic__subst(Nat, z => {Nat.is_le(Nat.add(1n, Nat.add(0n, i)), z) == True{} : Bool}, Nat.add(k, Nat.add(1n, Nat.add(0n, i))), '
      'Nat.add(Nat.add(1n, k), i), FD.nat__add_succ(k, i), Order.left_below_sum(k, Nat.add(1n, Nat.add(0n, i))))')
    w('')
    w(f'def winH(+d: Nat, +t: FD.array__Tree<U32>, +i: Nat, +len: U32, {VBY.PF}, +hw: {{Nat.is_le(Nat.add(A.quad(i), U32.to_nat(len)), A.quad(VB.pw(d))) == True{{}} : Bool}}, {HA})')
    w(f'    -> {{VS.wtake({H}n, VB.wdr(i, {s})) == VZ.cat({SEGSs}) : List<&2, U32>}}:')
    w(f'  +hsl = FD.logic__subst(Nat, z => {{Nat.is_le(Nat.add({H}n, i), z) == True{{}} : Bool}}, VB.pw(d), VB.len({s}), Equal.sym(Nat, VB.len({s}), VB.pw(d), FD.array__slots_length(U32, d, t, pf)), hHi(d, i, len, hw, ha))')
    LT = 'List<&2, U32>'

    def win(m, p):
        return f'VF.WIN({m}, {p}, {s})'

    def hpre(W, k):
        # the first word (W = 1 at k = 0) through lbs1 at a symbolic bound: left_below_sum at the
        # literal H - 1 would be compared with H + i by walking H - 1 in unary
        lbs = (f'lbs1({H - 1}n, i)' if (W, k) == (1, 0) else
               f'Order.left_below_sum({H - W - k}n, Nat.add({W}n, Nat.add({k}n, i)))')
        return (f'FD.nat__le_trans(Nat.add({W}n, Nat.add({k}n, i)), Nat.add({H}n, i), VB.len({s}), '
                f'{lbs}, hsl)')
    R, pos_ = H, 0
    pre = lambda t: t  # noqa: E731
    RHS = f'VZ.cat({SEGSs})'
    w(f'  %VBZ.win0({H}n, i, {s}) : {{_ == {RHS} : {LT}}}')
    for idx, (kind, k, Wd, tv, tb, f) in enumerate(segs):
        assert k == pos_
        rest = R - Wd
        s1, s3, sl = wsplit(Wd, rest, pos_)
        w(f'  %Equal.sym({LT}, {win(s1, f"Nat.add({pos_}n, i)")}, VF.app({win(f"{Wd}n", f"Nat.add({pos_}n, i)")}, {win(f"{rest}n", f"Nat.add({s3}, i)")}),')
        w(f'      {sl}({Wd}n, {rest}n, {pos_}n, i, {s})) :')
        w(f'    {{{pre("_")} == {RHS} : {LT}}}')
        nxt = win(f'{rest}n', f'Nat.add({pos_ + Wd}n, i)')
        if kind == 'comp':
            wW, gW = f['wW'], f['rft'].W
            s1, s3, sl = wsplit(wW, gW, pos_)
            w(f'  %Equal.sym({LT}, {win(s1, f"Nat.add({pos_}n, i)")}, VF.app({win(f"{wW}n", f"Nat.add({pos_}n, i)")}, {win(f"{gW}n", f"Nat.add({s3}, i)")}),')
            w(f'      {sl}({wW}n, {gW}n, {pos_}n, i, {s})) :')
            w(f'    {{{pre(f"VF.app(_, {nxt})")} == {RHS} : {LT}}}')
            w(f'  %Equal.sym({LT}, {win(f"{gW}n", f"Nat.add({pos_ + wW}n, i)")}, [{G}], VF.wt_pre({gW}n, 0n, Nat.add({pos_ + wW}n, i), {s}, {hpre(gW, pos_ + wW)})) :')
            w(f'    {{{pre(f"VF.app(VF.app({win(f"{wW}n", f"Nat.add({pos_}n, i)")}, _), {nxt})")} == {RHS} : {LT}}}')
        else:
            w(f'  %Equal.sym({LT}, {win(f"{Wd}n", f"Nat.add({pos_}n, i)")}, {tb}, VF.wt_pre({Wd}n, 0n, Nat.add({pos_}n, i), {s}, {hpre(Wd, pos_)})) :')
            w(f'    {{{pre(f"VF.app(_, {nxt})")} == {RHS} : {LT}}}')
        pre = (lambda p0, tb: (lambda t: p0(f'VF.app({tb}, {t})')))(pre, tb)
        R, pos_ = rest, pos_ + Wd
    # the last window is empty; unfold the RHS's cat into the same chain of appends
    W0 = win('0n', f'Nat.add({H}n, i)')
    w(f'  %Equal.sym({LT}, {W0}, [], VBZ.win_nil(Nat.add({H}n, i), {s})) : {{{pre("_")} == {RHS} : {LT}}}')
    LHSF = pre('[]')
    sb = [sg[4] for sg in segs]
    rpre = lambda t: t  # noqa: E731
    for j in range(len(sb)):
        cur = 'VZ.cat([' + ', '.join(sb[j:]) + '])'
        rest_ = '[' + ', '.join(sb[j + 1:]) + ']'
        w(f'  %Equal.sym({LT}, {cur}, VF.app({sb[j]}, VZ.cat({rest_})), VBZ.cat_cons({sb[j]}, {rest_})) : {{{LHSF} == {rpre("_")} : {LT}}}')
        rpre = (lambda p0, x: (lambda t: p0(f'VF.app({x}, {t})')))(rpre, sb[j])
    w(f'  %Equal.sym({LT}, VZ.cat([]), [], VBZ.cat_nil()) : {{{LHSF} == {rpre("_")} : {LT}}}')
    w('  {==}')
    w('')
    L.append(TPL.render('spec_part_seg_hlWw', ENH=ENH, FS=FS, FSN=FSN, H=H, HA=HA, HDRB=HDRB, MP=MP, SEGSh=SEGSh, SEGSs=SEGSs, VY_=VY_, WIN=WIN, WPK=WPK, YT=YT, cf=cf, n=n, s=s))
    return L
