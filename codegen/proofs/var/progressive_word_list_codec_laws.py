def deep_helpers():
    """nwm / hsg / lim_eq_g of vlist.bend without the depth bound: from n <= NMAX (31 + n <= UMAX) the list storage is at most 2^30 words."""
    vl = (ROOT / 'proofs/obj/vlist.bend').read_text()
    a = vl.index('def lim_eq_g(')
    b = vl.index('\n\n', a)
    lim = vl[a:b]
    HY = '{Nat.is_le(VC.YL(n), U32.to_nat(VB.UMAX())) == True{} : Bool}'
    lim = lim.replace('def lim_eq_g(', 'def limU(').replace('    +hd: {Nat.is_lt(d, 28n) == True{} : Bool}, +hn:', '    +hn:')
    lim = lim.replace('    +em: {U32.to_nat(n) == A.quad(m) : Nat})', '    +hy: ' + HY + ', +em: {U32.to_nat(n) == A.quad(m) : Nat})', 1)
    lim = lim.replace('hrg(d, n, hd, hn)', 'VC.hrgU(n, hy)').replace('hsg(d, n, m, hd, hn, em)', 'hsgU(d, n, m, hn, hy, em)').replace('nwm(d, n, m, hd, hn, em)', 'nwmU(n, m, hy, em)')
    assert 'hd,' not in lim and 'hd)' not in lim, lim
    lim = lim.replace('F.', 'FD.')
    lim = re.sub(r'(?<![\w.])(MMg|DZ)\(', r'VL.\1(', lim)
    return TEMPLATES.render('deep_helpers', HY=HY) + lim + '\n'


