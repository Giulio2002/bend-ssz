#!/usr/bin/env python3
"""proofs/obj/halfword.bend: the bytes of a word after a halfword (two bytes) is merged into it.

The uint16 lists store two elements per word; a set of element j writes the halfword at byte offset s = 0 or 2 of the word q with O.merge_word(old, v, s, 2)
(mask_at(s, 2), view_bytes.bend does the same for one byte). The bytes of the written word are the low byte of v at s, the next byte of v at s + 1 (v >> 8) and the
old bytes elsewhere; no bound on v is needed (the mask keeps two bytes). Per offset s and byte j (bit patterns of the two words, as byte_bits.bend):

    hw_go_<s>_<j>      lo8 of byte j of the merged word is the bits of v (j = s, s + 1) or of old (otherwise)
    hw_rw_<s>_<j>      the same through U32.and(.., 255)
    limb_hw_<s>        I.limb(merge_word(old, v, s, 2)) is the limbs of old with the bytes s and s + 1 replaced
    limbs_upd_hw_<s>   the bytes of a word list after the word q is rewritten are the old bytes with two replaced (VS.list_set twice)

    python3 codegen/proofs/collections/halfword.py            # write
    python3 codegen/proofs/collections/halfword.py --check    # nonzero exit if the output is stale
"""
