"""proofs/obj/bitz.bend: the zero tails of a bit list's storage words, kept by setting one bit.

The encode bridge of a bit list (proofs/obj/encx_bits<N>.bend) requires, in OKT, three facts about words of the bit storage:

    DL.HZ(r, w)                      the bits r .. 31 of w are zero, as zlist(bdrB(r, wbits w)) (var_bits_enc_bw.bend)
    O.bits_above_zero(r, w)          the same, as the runtime tests it: is_eq(w .&. mask_r, 0), a literal mask per r = 0 .. 31
    O.tail_zero(r, w)                the bytes r .. 3 of w are zero: is_eq(w >> 8 r, 0), r = 1 .. 3

Setting bit i (O.bit_merge(v, w, shl_by(1, i & 31)), bits_view.bend's wset_i: the bits of the merged word are lset(wbits w, i & 31, v)) keeps all three when i & 31 is below r (below 8 r for
the byte tail). Per fact, once and symbolically:

    eq0_zl, u_eq0_zl     is_eq(w, 0) is zlist(wbits w) (Word.cmp.fin: a set bit decides, a clear bit passes on)
    zm_gen               zlist of the bits ANDed with r clear bits and s set bits is zlist(bdrB(r, bits)) (and(b, False) = False, and(b, True) = b)
    bz_<r>, tz_<r>       the runtime's test at the literal r is zlist(bdrB(r or 8 r, wbits w)) (one closed mask per r)
    bz_conv, tz_conv     the same for r given as a number (a case per value)
    hz_lset              zlist(bdrB(r, lset(L, k, v))) = zlist(bdrB(r, L)) for k < r (one induction)
    bz_pres, tz_pres, hz_pres   the three facts after the bit merge, from the old ones and k < r

    python3 codegen/proofs/collections/bitz.py            # write
    python3 codegen/proofs/collections/bitz.py --check    # nonzero exit if the output is stale
"""
