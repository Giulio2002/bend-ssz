"""The view of a byte collection after one byte is written (helper of codegen/proofs/collections/packed_list_set_view.py, which writes
proofs/obj/view_bytes.bend from bytes_file()).

The runtime writes byte p into word q = p >> 2 (O.merge_word at byte offset p & 3). The spec view of the storage is the list of
its bytes, the limbs of its words cut at the object's length (words_root_light.bend's view, wview): a ByteList / ByteVector
value (BytesValue{wview(o)}), or the Sequence of its bytes (packed_bytes_light.bend's vview1, the list of uint8).

    limb_set_<s>      the four bytes of a word after the merge at byte s are the old four with byte s replaced
    limbs_upd_<s>     the bytes of a word list after the merge at word q, byte s: the old bytes with byte 4 q + s replaced
    limbs_upd_p       the same at the offset p & 3 of any p
    btake_set         cutting to the length commutes with replacing a byte
    view_set          BytesValue{wview} after the write = VS.bytes_set(BytesValue{wview} before, to_nat(p), v)
    view_set_u8       vview1 after the write = VS.field_set(vview1 before, to_nat(p), UInt{v})

(to_nat(p) = 4 q + (p & 3) is u32split.bend's split2.) No relation between the storage and the length is assumed: replacing
a byte past the end changes nothing on either side."""

HEADER = '# GENERATED by packed_list_set_view (codegen). Do not edit.'


def wpat(bits, tail='WNil{}'):
    s = tail
    for b in reversed(bits):
        s = 'WCon{%s, %s}' % (b, s)
    return s


def elem(k, M):
    """the k-th byte of a word as I.limb writes it"""
    if k == 0:
        return 'U32.and(%s, 255)' % M
    if k == 3:
        return 'U32.shrn(%s, 24n)' % M
    return 'U32.and(U32.shrn(%s, %dn), 255)' % (M, 8 * k)


