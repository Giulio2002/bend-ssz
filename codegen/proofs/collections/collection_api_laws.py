    JWj = 'U32.shrn(%s, 2n)' % Pj
    GETJ = lambda o: '%s.%s_get(%s, j)' % (DA, c, o)
    ggj = re.sub(r'(?<![\w.])i(?![\w.])', 'j', GG)
