def paren_arg(s, i):
    """the text inside the parenthesis opening at s[i]"""
    d = 0
    for j in range(i, len(s)):
        if s[j] == '(':
            d += 1
        elif s[j] == ')':
            d -= 1
            if d == 0:
                return s[i + 1:j], j
    raise SystemExit('unbalanced')


def data_names():
    out = []
    for f in sorted((ROOT / 'types').glob('*_encode_ssz_generated.bend')):
        m = re.search(r'^def (\w+)_ser_pick\(', f.read_text(), re.M)
        if m:
            out.append((m.group(1), f))
    return out


def linear_names(lf):
    """the non-Data names whose serializer is `X_senc_out(P_putk(O.out_at(k), 0, o))` with `P_putk` the leaf form
    `P_pk(out, pos, P_valid(o))` and whose encoder is `X_enc_out(P_put(O.out_at(k), 0, o))`: the packed vectors
    and the byte vectors (Blob, Cell). {name: (types file, P, k)}"""
    out = {}
    for f in sorted((ROOT / 'types').glob('*_encode_ssz_generated.bend')):
        t = f.read_text()
        if '_ser_pick(' in t:
            continue
        for m in re.finditer(r'^def (\w+)_serialize\(([^)]*)\) -> [^:]*: (.*)$', t, re.M):
            n, _, b = m.groups()
            ms = re.match(rf'{n}_senc_out\((\w+)_putk\(O\.out_at\((\d+)n\), 0, o\)\)$', b)
            if not ms:
                continue
            P, k = ms.groups()
            pk = re.search(rf'^def {P}_putk\([^)]*\) -> [^:]*: (.*)$', t, re.M)
            me = re.search(rf'^def {n}_encode\([^)]*\) -> [^:]*: (.*)$', t, re.M)
            if pk and pk.group(1) == f'{P}_pk(out, pos, {P}_valid(o))' and me and \
                    me.group(1) == f'{n}_enc_out({P}_put(O.out_at({k}n), 0, o))':
                n2 = n if f'{n}_e2e_encode' in lf else 'Fulu' + n
                b0 = W.params_of(W.Mod.get(lf[f'{n2}_e2e_encode']).defs[f'{n2}_e2e_encode'])[0]
                if re.match(r'^[+-]?o:', b0[0]):
                    out[n] = (f, P, int(k))
    return out



def brace_args(text, head):
    """the top-level arguments of `head{...}` at the start of text"""
    text = text.strip()
    assert text.startswith(head + '{') and text.endswith('}'), (head, text[:80])
    return W.split_top(text[len(head) + 1:-1])


def struct_domain(ctx, n2, R, VAL, cons, xs, expr, concl2, O_):
    """<Name>_e2e_serialize_domain for a container of uint8 / uint16 fields: a refused object has a field the spec has no
    encoding for, so the spec has none for the whole value (one or two checked fields: the head, or the second of two)"""
    m = re.search(r' == API\.serialize\((.*?), (\S*\.?v_\w+\(o\))\) : Maybe<&2, \+List<U32>>\}$', concl2, re.S)
    sch, view = m.group(1), m.group(2)
    gsm = W.Mod.get(ROOT / 'proofs/obj/generic_specs.bend')
    sname = sch.rpartition('.')[2].rstrip('()')
    _, _, sbody = gsm.signature(sname)
    vname = view.rpartition('.')[2].split('(')[0]
    vmod = W.Mod.get(ROOT / 'proofs/obj/root_gnames_light.bend')
    _, _, vbody = vmod.signature(vname)
    mvw = re.match(r'^match o:\n\s+case ([\w.]+)\{([^}]*)\}: (.*)$', vbody.strip(), re.S)
    ve = mvw.group(3)
    xs = [f.strip().lstrip('+') for f in mvw.group(2).split(',')]
    cons = ctx.lift(vmod, mvw.group(1))
    items = brace_args(brace_args(ve, 'S.Sequence')[0], 'S.Items')
    H, T = ctx.lift(vmod, items[0]), ctx.lift(vmod, items[1])
    if sbody.strip().startswith('S.ProgressiveContainer'):
        names, chain, act = (ctx.lift(gsm, x) for x in brace_args(sbody, 'S.ProgressiveContainer'))
        pc = True
    else:
        names, chain = (ctx.lift(gsm, x) for x in brace_args(sbody, 'S.Container'))
        act, pc = None, False
    s1, rest = brace_args(chain, 'S.Chain')
    leaf = {'S.Unsigned{P.U8{}}': 'u8', 'S.Unsigned{P.U16{}}': 'u16'}
    obj = f'{cons}{{{", ".join(xs)}}}'
    viewc = view.replace('(o)', f'({obj})')
    tr = lambda last: (f'Equal.trans(Maybe<&2, +List<U32>>, API.serialize({sch}, {viewc}), Encoding.encoding_for_legal_type({sch}, {viewc}), None{{}},\n'
                       f'      E.serialize_legal({sch}, {viewc}, VS.public_sound({sch}, {{==}})), {last})')
    goal = f'{{API.serialize({sch}, {viewc}) == None{{}} : Maybe<&2, +List<U32>>}}'
    ctx.alias(E2E / 'ser_e2e_uintdom_generated.bend')
    for a_ in ('proofs/type_validator_soundness.bend', 'spec/codec.bend', 'e2e/e2e_support.bend', 'e2e/e2e_valid.bend'):
        ctx.alias(ROOT / a_)
    head = (f'V.pcont_head_none({names}, {s1}, {rest}, {act}, {H}, {T}, ' if pc else f'V.cont_head_none({names}, {s1}, {rest}, {H}, {T}, ')
    mand = re.match(r'^Bool\.and\((.*)\)$', expr.strip(), re.S)
    if not mand:
        lw = leaf[s1]
        return (f'def {n2}_e2e_serialize_domain(+o: {R}, +v: {{{VAL}(o) == False{{}} : Bool}}) -> '
                f'{{API.serialize({sch}, {view}) == None{{}} : Maybe<&2, +List<U32>>}}:\n'
                f'  match o:\n    case {obj}:\n      {tr(head + f"UD.{lw}_parts_none({xs[0]}, v))")}')
    # two checked fields
    if pc:
        raise SystemExit(f'validating_serializer_bridges: {n2}: two checked fields of a progressive container')
    s2, end = brace_args(rest, 'S.Chain')
    h2 = brace_args(T, 'S.Items')
    lw = leaf[s1]
    assert leaf[s2] == lw
    lim = 255 if lw == 'u8' else 65535
    go = (f'def {n2}_dom_go(+a: Bool, +b: Bool, +{xs[0]}: U32, +{xs[1]}: U32, +ha: {{U32.is_le({xs[0]}, {lim}) == a : Bool}}, '
          f'+hb: {{U32.is_le({xs[1]}, {lim}) == b : Bool}}, +e: {{Bool.and(a, b) == False{{}} : Bool}}) -> {goal}:\n'
          f'  match a:\n    case False{{}}: {tr(head + f"UD.{lw}_parts_none({xs[0]}, ha))")}\n'
          f'    case True{{}}:\n      match b:\n'
          f'        case False{{}}: {tr(f"V.cont_second_none({names}, {s1}, {s2}, {end}, {H}, {h2[0]}, UD.{lw}_parts_none({xs[1]}, hb))")}\n'
          f'        case True{{}}: Empty.absurd({goal}, FD.logic__true_false(e))')
    main = (f'def {n2}_e2e_serialize_domain(+o: {R}, +v: {{{VAL}(o) == False{{}} : Bool}}) -> '
            f'{{API.serialize({sch}, {view}) == None{{}} : Maybe<&2, +List<U32>>}}:\n'
            f'  match o:\n    case {obj}: {n2}_dom_go(U32.is_le({xs[0]}, {lim}), U32.is_le({xs[1]}, {lim}), {xs[0]}, {xs[1]}, {{==}}, {{==}}, v)')
    return go + '\n\n' + main


def default_for(ctx, bmod, otype, n2):
    """(module, call) of the default object of the object type: W.default_of, and for an alias of a shared object type
    (O.U64 of the Fulu integer aliases) the default of the file that defines it"""
    try:
        return W.default_of(ctx, bmod, otype, n2)
    except SystemExit:
        tn = otype.strip().rpartition('.')[2]
        for f in sorted((ROOT / 'types').glob('*_def_generated.bend')):
            tm = W.Mod.get(f)
            for d in tm.defs:
                if d.endswith('_default') and '_bx_' not in d:
                    ps, ret, _ = tm.signature(d)
                    if not ps and ret.strip().split('.')[-1] == tn and f.name in ('uint64_def_generated.bend', 'uint128_def_generated.bend',
                                                                                  'uint256_def_generated.bend', 'boolean_def_generated.bend'):
                        return tm, f'{d}()'
        raise


def decoded_hv(ctx, n2, tmod, VAL, R):
    """<Name>_e2e_decoded_hv: what the decoder returns for accepted bytes satisfies `hv` (the validity pass returns the object
    unchanged with True), for the names whose composed decode (e2e/<Name>_e2e_comp_generated.bend) writes the decoded object
    out and whose validity pass reads no word (no `bools_ok`): the pass is computed of the written-out object. The proof is the
    composed file's own `ge` (decoded object re-encodes to the input) with the conclusion replaced."""
    cp = E2E / f'{n2}_e2e_comp_generated.bend'
    if not cp.exists():
        return None
    vb = tmod.defs.get(VAL.rpartition('.')[2], '')
    if 'bools_ok' in vb:
        return None
    cm = W.Mod.get(cp)
    ge = cm.defs.get('ge')
    if not ge:
        return None
    mh = re.match(r'def ge\((.*?)\)\s*->\s*\{E\.obytes', ge, re.S)
    mt = re.search(r'case True\{\}:\n\s+%Equal\.sym\(O\.Words, o, ', ge)
    mf = re.search(r'case False\{\}:\n\s+Empty\.absurd\(', ge)
    if not (mh and mt and mf):
        return None
    sym, _ = paren_arg(ge, mt.end() - 1 - len('Equal.sym') + len('Equal.sym'))
    args = W.split_top(sym)
    OBJ, PROOF = args[0] if False else None, None
    # the arguments of Equal.sym(O.Words, o, OBJ, PROOF)
    i0 = ge.index('Equal.sym(', mt.start())
    inner, _ = paren_arg(ge, i0 + len('Equal.sym'))
    sa = W.split_top(inner)
    OBJ, PROOF = sa[2], sa[3]
    j0 = ge.index('Empty.absurd(', mf.start())
    inner2, _ = paren_arg(ge, j0 + len('Empty.absurd'))
    ab = W.split_top(inner2)
    ABS = ab[1]
    if not re.search(r'\d', OBJ):
        return None
    mlen = re.search(r'Nat\.is_eq\(List\.length\(&2, U32, bs\), (.*?)\) == c : Bool', mh.group(1))
    if not mlen or int(re.findall(r'\d+', mlen.group(1))[-1]) > 8192:
        return None     # the validity pass over a larger tree is walked word by word: deeper than the checkers' stacks
    lf_ = lambda e: ctx.lift(cm, e)
    for al in set(re.findall(r'(?<![\w.])([A-Za-z_]\w*)\.', OBJ + PROOF + ABS)):
        if al in cm.imports:
            ctx.alias(cm.imports[al])
    OA = ctx.alias(ROOT / 'src/obj.bend')
    FDA = ctx.alias(ROOT / 'proofs/compact/found.bend')
    ctx.alias(cp)
    OBJl, PROOFl, ABSl = lf_(OBJ), lf_(PROOF), lf_(ABS)
    hdr = lf_(mh.group(1)).replace(', dec:', ',\n    dec:', 1)
    hvo = f'def {n2}_hvo(+bs: +List<U32>) -> {{({OBJl}, True{{}}) == {VAL}({OBJl}) : {OA}.Words & Bool}}:\n  {{==}}\n\n'
    goal = f'{{(o, True{{}}) == {VAL}(o) : {OA}.Words & Bool}}'
    return (hvo + f'def {n2}_e2e_decoded_hv({hdr})\n    -> {goal}:\n'
            f'  match c:\n    case True{{}}:\n'
            f'      {FDA}.logic__subst({OA}.Words, z => {{(z, True{{}}) == {VAL}(z) : {OA}.Words & Bool}}, {OBJl}, o,\n'
            f'        Equal.sym({OA}.Words, o, {OBJl}, {PROOFl}),\n'
            f'        {n2}_hvo(bs))\n'
            f'    case False{{}}:\n'
            f'      Empty.absurd({goal}, {ABSl})')


def build_linear(n, tfile, P, k, lf):
    """the linear (object-threading) serializer of a fixed-size name: given `X_valid(o) == (o, True)`, it is the
    encoder's object and END_TO_END's bytes"""
    W.Mod.cache.clear()
    ctx = W.Ctx()
    tmod = W.Mod.get(tfile)
    n2 = n if f'{n}_e2e_encode' in lf else 'Fulu' + n
    bmod = W.Mod.get(lf[f'{n2}_e2e_encode'])
    ps, concl = W.params_of(bmod.defs[f'{n2}_e2e_encode'])
    R = ctx.lift(bmod, ps[0].split(':', 1)[1].strip())
    O_ = ctx.alias(ROOT / 'src/obj.bend')
    Bf = ctx.alias(ROOT / 'src/buffer.bend')
    q = lambda x: ctx.lift(tmod, x)
    SER, ENC, SENC, PK, PKOK, PUT, ENCO, VAL = (q(x) for x in (f'{n}_serialize', f'{n}_encode', f'{n}_senc_out', f'{P}_pk',
                                                                 f'{P}_pk_ok', f'{P}_put', f'{n}_enc_out', f'{P}_valid'))
    BR = f'{ctx.alias(bmod.path)}.{n2}_e2e_encode'
    binders = ', '.join(ctx.lift(bmod, re.sub(r'^[+-]', '', x) if i == 0 else x) for i, x in enumerate(ps))
    args = ', '.join(x.split(':', 1)[0].strip().lstrip('+-') for x in ps)
    ENCP = f'Pair.snd({R}, {Bf}.Buf, {ENC}(o))'
    ENCF = f'Pair.fst({R}, {Bf}.Buf, {ENC}(o))'
    RES = f'({ENCF}, {O_}.encoded({ENCP}))'
    OUT = f'{O_}.out_at({k}n)'
    HT = f'{{(o, True{{}}) == {VAL}(o) : {R} & Bool}}'
    HF = f'{{(o, False{{}}) == {VAL}(o) : {R} & Bool}}'
    L = ctx.lift(bmod, concl)
    if ENCP.replace(' ', '') not in L.replace(' ', ''):
        raise SystemExit(f'validating_serializer_bridges: {n}: the bridge does not encode {ENCP!r}')
    concl2 = L.replace(ENCP, f'{O_}.ser_out(Pair.snd({R}, {O_}.Encoded, {SER}(o)))', 1)
    # the lemma over the writer's result P (the pair the put returns), so nothing is stuck on the object
    RESP = (f'(Pair.fst({R}, {Bf}.Buf, {ENCO}(P)), {O_}.encoded(Pair.snd({R}, {Bf}.Buf, {ENCO}(P))))')
    l1 = (f'def {n2}_ser_l2(P: Array<U32> & {R}) -> {{{SENC}({PKOK}(P)) == {RESP} : {R} & {O_}.Encoded}}:\n'
          f'  match P:\n    case Tuple{{out, o}}: {{==}}\n\n'
          f'def {n2}_ser_l1(o: {R}) -> {{{SENC}({PKOK}({PUT}({OUT}, 0, o))) == {RES} : {R} & {O_}.Encoded}}:\n'
          f'  {n2}_ser_l2({PUT}({OUT}, 0, o))')
    ok = (f'def {n2}_e2e_serialize_ok({binders}, +hv: {HT}) -> {{{SER}(o) == {RES} : {R} & {O_}.Encoded}}:\n'
          f'  %hv : {{{SENC}({PK}({OUT}, 0, _)) == {RES} : {R} & {O_}.Encoded}}\n'
          f'  {n2}_ser_l1(o)')
    refused = (f'def {n2}_e2e_serialize_refused({binders}, +hv: {HF}) -> {{{SER}(o) == (o, {O_}.refused()) : {R} & {O_}.Encoded}}:\n'
               f'  %hv : {{{SENC}({PK}({OUT}, 0, _)) == (o, {O_}.refused()) : {R} & {O_}.Encoded}}\n'
               f'  {{==}}')
    main = (f'def {n2}_e2e_serialize({binders}, +hv: {HT}) -> {concl2}:\n'
            f'  %Equal.sym({R} & {O_}.Encoded, {SER}(o), {RES}, {n2}_e2e_serialize_ok({args}, hv)) : '
            f'{concl2.replace(f"Pair.snd({R}, {O_}.Encoded, {SER}(o))", f"Pair.snd({R}, {O_}.Encoded, _)", 1)}\n'
            f'  {BR}({args})')
    # non-vacuity: the validity pass returns the default object unchanged with True
    dmod, dcall = default_for(ctx, bmod, ps[0].split(':', 1)[1], n2)
    DEF = ctx.lift(dmod, dcall) if dmod is not None else dcall
    vdef = f'def {n2}_e2e_valid_default() -> {{({DEF}, True{{}}) == {VAL}({DEF}) : {R} & Bool}}:\n  {{==}}'
    extra_defs = [vdef]
    dh = decoded_hv(ctx, n2, tmod, VAL, R)
    if dh:
        extra_defs.append(dh)
    return W.imports_text(ctx) + '\n\n' + HEADER + '\n' + \
        f'# {n2}: given that the validity pass returns the object with True, the checked serializer is the encoder,\n' \
        f'# and its bytes are END_TO_END\'s serialize of the object\'s value.\n\n' + '\n\n'.join([l1, ok, refused, main] + extra_defs) + '\n'


def valid_body(tmod, vname):
    """(module, text of the validity predicate's body) of X_valid as written in tmod"""
    m2, nm = tmod.resolve(vname)
    params, ret, body = m2.signature(nm)
    return m2, body


def struct_term(ctx, vmod, expr, pf, need, depth=0):
    """the bridge's rp premise of a container from the validity expression: a Bool.and of the fields' checks"""
    expr = expr.strip()
    ma = re.match(r'^Bool\.and\((.*)\)$', expr, re.S)
    if ma:
        a, b = W.split_top(ma.group(1))
        la, lb = ctx.lift(vmod, a), ctx.lift(vmod, b)
        return (f'({struct_term(ctx, vmod, a, f"FD.logic__and_left({la}, {lb}, {pf})", need, depth + 1)}, '
                f'{struct_term(ctx, vmod, b, f"FD.logic__and_right({la}, {lb}, {pf})", need, depth + 1)})')
    mu = re.match(r'^(\w+)\.u(8|16)_valid\((\w+)\)$', expr)
    if not mu:
        raise SystemExit(f'validating_serializer_bridges: cannot read the validity check {expr!r}')
    r = int(mu.group(2))
    need.add(r)
    return f'ltp{r}({mu.group(3)}, {pf})'


def struct_conv(ctx, vmod, expr, pv, need, k=0):
    """(lines, term): the validity `expr == True` of a container from the pair pv of its fields' rp facts
    (the converse of struct_term)"""
    expr = expr.strip()
    ma = re.match(r'^Bool\.and\((.*)\)$', expr, re.S)
    if ma:
        a, b = W.split_top(ma.group(1))
        la, lb = ctx.lift(vmod, a), ctx.lift(vmod, b)
        pl, pr = f'pl{k}', f'pr{k}'
        l1, ta = struct_conv(ctx, vmod, a, pl, need, k + 1)
        l2, tb = struct_conv(ctx, vmod, b, pr, need, k + 100)
        return [f'({pl}, {pr}) = {pv}'] + l1 + l2, f'FD.logic__and_intro({la}, {lb}, {ta}, {tb})'
    mu = re.match(r'^(\w+)\.u(8|16)_valid\((\w+)\)$', expr)
    if not mu:
        raise SystemExit(f'validating_serializer_bridges: cannot read the validity check {expr!r}')
    r = int(mu.group(2))
    need.add(r)
    return [], f'ltq{r}({mu.group(3)}, {pv})'


def build(n, tfile, lf):
    W.Mod.cache.clear()
    ctx = W.Ctx()
    tmod = W.Mod.get(tfile)
    n2 = n if f'{n}_e2e_encode' in lf else 'Fulu' + n
    bpath = lf[f'{n2}_e2e_encode']
    bmod = W.Mod.get(bpath)
    ps, concl = W.params_of(bmod.defs[f'{n2}_e2e_encode'])
    if len(ps) > 2:
        raise SystemExit(f'validating_serializer_bridges: {n}: more than one premise')
    sparams, sret, sbody = tmod.signature(f'{n}_serialize')
    R = ctx.lift(tmod, tmod.fullp[0].split(':', 1)[1].strip())
    mv = re.match(rf'^{n}_ser_pick\((.*)\(o\), o\)$', sbody)
    if not mv:
        raise SystemExit(f'validating_serializer_bridges: {n}: cannot read {sbody!r}')
    vname = mv.group(1)
    VAL = ctx.lift(tmod, vname)
    SER = ctx.lift(tmod, f'{n}_serialize')
    ENC = ctx.lift(tmod, f'{n}_encode')
    PICK = ctx.lift(tmod, f'{n}_ser_pick')
    O_ = ctx.alias(ROOT / 'src/obj.bend')
    VT = f'{{{VAL}(o) == True{{}} : Bool}}'
    VF = f'{{{VAL}(o) == False{{}} : Bool}}'
    BR = f'{ctx.alias(bmod.path)}.{n2}_e2e_encode'
    # the conclusion, with the checked serializer's bytes for the encoder's
    L = ctx.lift(bmod, concl)
    mo = re.search(r'(\w+)\.obytes\(', L)
    inner, end = paren_arg(L, mo.end() - 1)
    if inner.replace(' ', '') != f'{ENC}(o)'.replace(' ', ''):
        raise SystemExit(f'validating_serializer_bridges: {n}: the bridge encodes {inner!r}, not {ENC}(o)')
    concl2 = L[:mo.end()] + f'{O_}.ser_out({SER}(o))' + L[end:]
    defs = []
    ok = (f'def {n2}_e2e_serialize_ok(+o: {R}, +v: {VT}) -> {{{SER}(o) == {O_}.encoded({ENC}(o)) : {O_}.Encoded}}:\n'
          f'  %Equal.sym(Bool, {VAL}(o), True{{}}, v) : {{{PICK}(_, o) == {O_}.encoded({ENC}(o)) : {O_}.Encoded}}\n  {{==}}')
    refused = (f'def {n2}_e2e_serialize_refused(+o: {R}, +v: {VF}) -> {{{SER}(o) == {O_}.refused() : {O_}.Encoded}}:\n'
               f'  %Equal.sym(Bool, {VAL}(o), False{{}}, v) : {{{PICK}(_, o) == {O_}.refused() : {O_}.Encoded}}\n  {{==}}')
    conv = None
    domain = None
    # the bridge's premise from validity
    if len(ps) == 1:
        prem, callp = None, f'{BR}(o)'
    else:
        ptype = ctx.lift(bmod, ps[1].split(':', 1)[1].strip())
        for a_ in ('e2e/e2e_valid.bend', 'proofs/compact/found.bend', 'proofs/word_split.bend', 'proofs/power_division.bend'):
            ctx.alias(ROOT / a_)
        vmod, vb = valid_body(tmod, vname)
        mm = re.match(r'^match o:\n\s+case ([\w.]+)\{([^}]*)\}: (.*)$', vb, re.S)
        pname = ps[1].split(':', 1)[0].strip().lstrip('+-')
        need = set()
        cons = ctx.lift(vmod, mm.group(1)) if mm else None
        fields = [f.strip().lstrip('+') for f in mm.group(2).split(',')] if mm else None
        expr = mm.group(3).strip() if mm else vb.strip()
        if pname == 'e' and re.search(r'is_lt\(o, 256\)', ptype) and not mm:
            need.add(8)
            pdef = '  ltp8(o, v)'
        elif pname == 'e' and 'b1_byte' in ptype:
            pdef = f'  match o:\n    case {cons}{{+{fields[0]}}}: v'
        elif pname == 'e' and 'join(' in ptype:
            r, m = (int(x) for x in re.search(r'join\((\d+)n, (\d+)n', ptype).groups())
            mu = re.match(r'^U32\.is_lt\((\w+), (\d+)\)$', expr)
            if not mu or int(mu.group(2)) != 1 << r or r + m != 32:
                raise SystemExit(f'validating_serializer_bridges: {n}: cannot read {expr!r} against {ptype[:80]!r}')
            defs.append(
                f'def bvs{r}(+w: U32, +e: {{U32.is_lt(w, {1 << r}) == True{{}} : Bool}}) -> '
                f'{{w == U32{{WSp.join({r}n, {m}n, WSp.take({r}n, 32n, PD.bits(w)), Word.zero({m}n))}} : U32}}:\n'
                f'  match w:\n    case U32{{+x}}:\n'
                f'      Equal.cong(Word(32n), U32, z => U32{{z}}, x, WSp.join({r}n, {m}n, WSp.take({r}n, 32n, x), Word.zero({m}n)), V.shz({r}n, {m - 1}n, x, e))')
            pdef = (f'  match o:\n    case {cons}{{{", ".join("+" + f for f in fields)}}}: bvs{r}({mu.group(1)}, v)')
        elif pname == 'rp' and mm:
            pdef = (f'  match o:\n    case {cons}{{{", ".join("+" + f for f in fields)}}}: '
                    f'{struct_term(ctx, vmod, expr, "v", need)}')
        elif pname == 'rp' and re.search(r'rp_u16\(o\)', ptype) is not None or (pname == 'rp' and 'is_lt(o, 65536)' in ptype):
            need.add(16)
            pdef = '  ltp16(o, v)'
        else:
            raise SystemExit(f'validating_serializer_bridges: {n}: no derivation of the premise {ps[1][:120]!r}')
        for r in sorted(need):
            defs.append(f'def ltp{r}(+o: U32, +v: {{U32.is_le(o, {(1 << r) - 1}) == True{{}} : Bool}}) -> {{U32.is_lt(o, {1 << r}) == True{{}} : Bool}}:\n'
                        f'  match o:\n    case U32{{+x}}: V.le_lt({r}n, {31 - r}n, x, v)')
        prem = (f'def {n2}_ser_prem(+o: {R}, +v: {VT}) -> {ptype}:\n{pdef}')
        # the converse: the premise gives validity (so refusal is exactly the failure of the bridge's premise)
        PT = f'{{{VAL}(o) == True{{}} : Bool}}'
        if pname == 'e' and re.search(r'is_lt\(o, 256\)', ptype) and not mm:
            cneed = {8}
            cbody = '  ltq8(o, p)'
        elif pname == 'e' and 'b1_byte' in ptype:
            cneed = set()
            cbody = f'  match o:\n    case {cons}{{{", ".join("+" + f for f in fields)}}}: p'
        elif pname == 'e' and 'join(' in ptype:
            cneed = set()
            cbody = (f'  match o:\n    case {cons}{{{", ".join("+" + f for f in fields)}}}: bvt{r}({mu.group(1)}, p)')
            defs.append(
                f'def bvt{r}(+w: U32, +e: {{w == U32{{WSp.join({r}n, {m}n, WSp.take({r}n, 32n, PD.bits(w)), Word.zero({m}n))}} : U32}}) -> '
                f'{{U32.is_lt(w, {1 << r}) == True{{}} : Bool}}:\n'
                f'  %Equal.sym(U32, w, U32{{WSp.join({r}n, {m}n, WSp.take({r}n, 32n, PD.bits(w)), Word.zero({m}n))}}, e) : {{U32.is_lt(_, {1 << r}) == True{{}} : Bool}}\n'
                f'  V.lt_sh({r}n, {m - 1}n, WSp.take({r}n, 32n, PD.bits(w)))')
        elif pname == 'rp' and mm:
            cneed = set()
            ls, tm = struct_conv(ctx, vmod, expr, 'p', cneed)
            cbody = (f'  match o:\n    case {cons}{{{", ".join("+" + f for f in fields)}}}:\n' +
                     ''.join(f'      {l}\n' for l in ls) + f'      {tm}')
        elif pname == 'rp':
            cneed = {16}
            cbody = '  ltq16(o, p)'
        else:
            raise SystemExit(f'validating_serializer_bridges: {n}: no converse for {ps[1][:120]!r}')
        if pname == 'e' and re.search(r'is_lt\(o, 256\)', ptype) and not mm:
            ctx.alias(E2E / 'ser_e2e_uintdom_generated.bend')
            rhs = re.search(r' == (API\.serialize\(.*\)) : Maybe<&2, \+List<U32>>\}$', concl2, re.S).group(1)
            domain = (f'def {n2}_e2e_serialize_domain(+o: {R}, +v: {{{VAL}(o) == False{{}} : Bool}}) -> '
                      f'{{{rhs} == None{{}} : Maybe<&2, +List<U32>>}}:\n  UD.u8_none(o, v)')
        elif pname == 'rp' and not mm and ('rp_u16' in ptype or 'is_lt(o, 65536)' in ptype):
            ctx.alias(E2E / 'ser_e2e_uintdom_generated.bend')
            rhs = re.search(r' == (API\.serialize\(.*\)) : Maybe<&2, \+List<U32>>\}$', concl2, re.S).group(1)
            domain = (f'def {n2}_e2e_serialize_domain(+o: {R}, +v: {{{VAL}(o) == False{{}} : Bool}}) -> '
                      f'{{{rhs} == None{{}} : Maybe<&2, +List<U32>>}}:\n  UD.u16_none(o, v)')
        for r_ in sorted(cneed):
            defs.append(f'def ltq{r_}(+o: U32, +v: {{U32.is_lt(o, {1 << r_}) == True{{}} : Bool}}) -> {{U32.is_le(o, {(1 << r_) - 1}) == True{{}} : Bool}}:\n'
                        f'  match o:\n    case U32{{+x}}: V.lt_le({r_}n, {31 - r_}n, x, v)')
        conv = f'def {n2}_e2e_valid_of_prem(+o: {R}, +p: {ptype}) -> {PT}:\n{cbody}'
        if pname == 'rp' and mm:
            domain = struct_domain(ctx, n2, R, VAL, cons, [f.strip().lstrip('+') for f in mm.group(2).split(',')], expr, concl2, O_)
        if pname == 'e' and 'b1_byte' in ptype:
            # a byte above 255 has no encoding: a refused object is one the spec has no bytes for
            rhs = re.search(r' == (API\.serialize\(.*\)) : Maybe<&2, \+List<U32>>\}$', concl2, re.S).group(1)
            domain = (f'def {n2}_e2e_serialize_domain(+o: {R}, +v: {{{VAL}(o) == False{{}} : Bool}}) -> '
                      f'{{{rhs} == None{{}} : Maybe<&2, +List<U32>>}}:\n'
                      f'  match o:\n    case {cons}{{{", ".join("+" + f for f in fields)}}}: V.b1_none({fields[0]}, v)')

        callp = f'{BR}(o, {n2}_ser_prem(o, v))'
    # non-vacuity: the validity predicate holds of the default object (and of every object, when it is trivial)
    dmod, dcall = default_for(ctx, bmod, ps[0].split(':', 1)[1], n2)
    DEF = ctx.lift(dmod, dcall) if dmod is not None else dcall
    vdef = (f'def {n2}_e2e_valid_default() -> {{{VAL}({DEF}) == True{{}} : Bool}}:\n  {{==}}')
    extra = [vdef]
    if len(ps) == 1:
        vmod, vb = valid_body(tmod, vname)
        mt = re.match(r'^match o:\n\s+case ([\w.]+)\{([^}]*)\}: True\{\}$', vb.strip(), re.S)
        if vb.strip() == 'True{}':
            extra.append(f'def {n2}_e2e_valid_total(+o: {R}) -> {VT}:\n  {{==}}')
        elif mt:
            cons = ctx.lift(vmod, mt.group(1))
            extra.append(f'def {n2}_e2e_valid_total(+o: {R}) -> {{{VAL}(o) == True{{}} : Bool}}:\n'
                         f'  match o:\n    case {cons}{{{", ".join("+" + f.strip().lstrip("+") for f in mt.group(2).split(","))}}}: {{==}}')
        else:
            raise SystemExit(f'validating_serializer_bridges: {n}: premise-free but the validity is {vb[:80]!r}')
    if conv:
        extra.append(conv)
    if domain:
        extra.append(domain)
    main = (f'def {n2}_e2e_serialize(+o: {R}, +v: {VT}) -> {concl2}:\n'
            f'  %Equal.sym({O_}.Encoded, {SER}(o), {O_}.encoded({ENC}(o)), {n2}_e2e_serialize_ok(o, v)) : '
            f'{concl2.replace(f"{O_}.ser_out({SER}(o))", f"{O_}.ser_out(_)", 1)}\n'
            f'  {callp}')
    body = defs + [ok, refused] + ([prem] if prem else []) + [main] + extra
    return W.imports_text(ctx) + '\n\n' + HEADER + '\n' + \
        f'# {n2}: the checked serializer of a valid object is END_TO_END\'s serialize of its value.\n\n' + '\n\n'.join(body) + '\n'


def main():
    check = '--check' in sys.argv
    only = sys.argv[sys.argv.index('--only') + 1].split(',') if '--only' in sys.argv else None
    lf = W.law_files()
    W.PREFER.clear()
    for pth, a in ((ROOT / 'src/obj.bend', 'O'), (ROOT / 'src/model.bend', 'API'), (ROOT / 'types/schema.bend', 'S'),
                   (ROOT / 'types/primitive.bend', 'P'), (E2E / 'e2e_support.bend', 'E'), (E2E / 'e2e_valid.bend', 'V'),
                   (ROOT / 'proofs/word_split.bend', 'WSp'), (ROOT / 'proofs/power_division.bend', 'PD'),
                   (ROOT / 'proofs/compact/found.bend', 'FD'), (E2E / 'ser_e2e_uintdom_generated.bend', 'UD'), (ROOT / 'spec/codec.bend', 'Encoding'),
                   (ROOT / 'proofs/type_validator_soundness.bend', 'VS')):
        W.PREFER[pth.resolve()] = a
    outs = {}
    for n, tfile in data_names():
        if only and n not in only:
            continue
        n2 = n if f'{n}_e2e_encode' in lf else 'Fulu' + n
        outs[E2E / f'{n2}_e2e_ser_generated.bend'] = build(n, tfile, lf)
    for n, (tfile, P, k) in linear_names(lf).items():
        if only and n not in only:
            continue
        n2 = n if f'{n}_e2e_encode' in lf else 'Fulu' + n
        outs[E2E / f'{n2}_e2e_ser_generated.bend'] = build_linear(n, tfile, P, k, lf)
    if not only:
        outs[E2E / 'ser_e2e_uintdom_generated.bend'] = uintdom.uintdom_lib()
    stale = []
    for p, t in outs.items():
        if not p.exists() or p.read_text() != t:
            stale.append(p.name)
            if not check:
                p.write_text(t)
    if not only:
        for p in sorted(E2E.glob('*_e2e_ser_generated.bend')):
            if p not in outs:
                if check:
                    stale.append(p.name + ' (orphan)')
                else:
                    p.unlink()
    if check:
        if stale:
            print('stale: ' + ', '.join(stale))
            sys.exit(1)
        print(f'validating_serializer_bridges: {len(outs)} files up to date')
    else:
        print(f'validating_serializer_bridges: wrote {len(stale)} of {len(outs)}')


if __name__ == '__main__':
    main()
