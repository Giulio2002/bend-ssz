#!/usr/bin/env python3
"""The validating serializer, end to end: for every name whose object is Data (its `X_serialize` is
`X_ser_pick(X_valid(o), o)`), one file e2e/<Name>_e2e_ser_generated.bend with three public statements

  <Name>_e2e_serialize(+o, +v: {X_valid(o) == True})
      : Some{E.obytes(O.ser_out(X_serialize(o)))} == API.serialize(Spec.X(), view(o))
      (END_TO_END's serialize of the object's value: the same conclusion as the encode bridge
      <Name>_e2e_encode, with the checked serializer in place of the encoder)
  <Name>_e2e_serialize_ok(+o, +v)     : X_serialize(o) == O.encoded(X_encode(o))
  <Name>_e2e_serialize_refused(+o, +v: {X_valid(o) == False}) : X_serialize(o) == O.refused()

The encode bridge's premise beyond the object (none, `e`, `rp`) is derived from `X_valid(o) = True`
(<Name>_ser_prem, by the shape of the validity predicate; lemmas in e2e/e2e_valid.bend), so the
statement has no premise but validity. Only Data names here: for the fixed-size packed and byte vectors (`linear_names`), whose serializer threads the
object, the same three statements take the bridge's premises plus `hv: (o, True) == X_valid(o)` (the pass returns
the object unchanged with True) and prove `X_serialize(o) == (object of encode, encoded(bytes of encode))`. For the others the bridge premises (rep,
storage depth) assert the shape of the object's word tree, which X_valid does not (docs/PREMISES.md).

    python3 codegen/proofs/collections/validating_serializer_bridges.py [--check] [--only A,B]
"""
