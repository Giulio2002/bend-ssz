#!/usr/bin/env python3
"""proofs/obj/tz_merge.bend: a byte or halfword written inside the last word keeps the bits above the bytes in use zero.

The encode bridges of the byte, uint8 and uint16 lists (encx_<list>.bend) require OKT(dw, T, N), which contains O.tail_zero(N & 3, slot(T, N >> 2)):
the last word of the N bytes has zero bytes past the r = N & 3 in use. A set of an element inside the bytes in use writes O.merge_word(old, x, s, b)
into that word (s the byte offset, b the width in bytes, s + b <= r), so the written tree must keep the fact. Stated once, symbolically in old and x:

    shr_merge(k, old, x, s, b)   shrn(old, k) = 0 and shrn(mask_at(s, b), k) = 0 give shrn(merge_word(old, x, s, b), k) = 0
                                 (shrn distributes over .&. and .|., a zero operand makes .&. zero)
    tzc_<r>_<s>_<b>              tail_zero(r, merge_word(old, x, s, b)) from tail_zero(r, old), for the literal r in 1 .. 3, s, b with s + b <= r
    tz_merge(r, s, b, old, x)    the same for the U32 values r = N & 3, s, b given as numbers: s + b <= r <= 3, b in 1 .. 2 (case split on the numbers; the
                                 literal case lemmas are transported along the equalities of the values, F.u32__injective)

    python3 codegen/proofs/collections/subword_tz.py            # write
    python3 codegen/proofs/collections/subword_tz.py --check    # nonzero exit if the output is stale
"""
