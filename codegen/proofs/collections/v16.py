#!/usr/bin/env python3
"""proofs/obj/v16_rt.bend: a uint16 is the join of its two bytes.

The element of a list of uint16 is read from two bytes of its storage: pb_min.bend's v16of(x0, x1) joins the low bytes of x0 and x1 into one value. The setter of such a list
writes v with O.merge_word(old, v, s, 2); the bytes the encode value then reads are lo = v & 255 and hi = (v >> 8) & 255 (halfword.bend). For a value that fits sixteen bits
the join of these two bytes is v again:

    chain16     the comparison of a word with 65535 is above when its upper 16 bits compare above zero (as u32bits.bend's chain8 for 255)
    v16_rt      U32.is_le(v, 65535) == True gives v16of(v & 255, (v >> 8) & 255) == v

so the element value of encset_h_<list>.bend, UnsignedValue{UInt{v16of(lo, hi), ..}}, is UnsignedValue{UInt{v, ..}} for every v the setter accepts.

    python3 codegen/proofs/collections/v16.py            # write
    python3 codegen/proofs/collections/v16.py --check    # nonzero exit if the output is stale
"""
import sys as _sys
import pathlib as _pathlib
_sys.path.insert(0, str(_pathlib.Path(__file__).resolve().parents[3]))  # the repository root: `codegen` is importable when this file runs as a script
from codegen.core.paths import ROOT  # noqa: E402
from codegen.core.shared_laws import run_single  # noqa: E402

OUT = ROOT / 'proofs/obj/v16_rt.bend'

HEAD = '''import Base
import ./u32bits.bend as UB
import ./pb_min.bend as PM

# GENERATED by v16 (codegen). Do not edit.
# A uint16 is the join of its two bytes: see codegen/proofs/collections/v16.py.

'''


def wpat(bits, tail):
    s_ = tail
    for b in reversed(bits):
        s_ = 'WCon{%s, %s}' % (b, s_)
    return s_


def text():
    bs = ['b%d' % k for k in range(16)]
    fin = 'c'
    for b in reversed(bs):
        fin = 'Word.cmp.fin(%s, True{}, %s)' % (b, fin)
    L = [HEAD]
    L.append('def chain16(%s, +c: Cmp, +h: {Cmp.is_le(%s) == True{} : Bool}) -> {Cmp.is_gt(c) == False{} : Bool}:' % (', '.join('+%s: Bool' % b for b in bs), fin))
    L.append('  match c:')
    L.append('    case LT{}: {==}')
    L.append('    case EQ{}: {==}')
    L.append('    case GT{}: Equal.sym(Bool, False{}, True{}, h)')
    L.append('')
    V = lambda t: 'U32{%s}' % wpat(bs, t)
    L.append('def v16_go(%s, +t: Word(16n), +ht: {t == Word.zero(16n) : Word(16n)}) -> {PM.v16of(UB.lo8(%s), UB.lo8(U32.shrn(%s, 8n))) == %s : U32}:' % (', '.join('+%s: Bool' % b for b in bs), V('t'), V('t'), V('t')))
    L.append('  %%Equal.sym(Word(16n), t, Word.zero(16n), ht) : {PM.v16of(UB.lo8(%s), UB.lo8(U32.shrn(%s, 8n))) == %s : U32}' % (V('_'), V('_'), V('_')))
    L.append('  {==}')
    L.append('')
    L.append('def v16_rt(+v: U32, +h: {U32.is_le(v, 65535) == True{} : Bool}) -> {PM.v16of(U32.and(v, 255), U32.and(U32.shrn(v, 8n), 255)) == v : U32}:')
    L.append('  match v:')
    L.append('    case U32{%s}:' % wpat(['+' + b for b in bs], '+t'))
    L.append('      +ht = UB.tail_zero(16n, t, chain16(%s, Word.cmp(16n, t, Word.zero(16n)), h))' % ', '.join(bs))
    L.append('      +e1 = UB.and255(%s)' % V('t'))
    L.append('      +e2 = UB.and255(U32.shrn(%s, 8n))' % V('t'))
    L.append('      Equal.trans(U32, PM.v16of(U32.and(%s, 255), U32.and(U32.shrn(%s, 8n), 255)), PM.v16of(UB.lo8(%s), UB.lo8(U32.shrn(%s, 8n))), %s,' % (V('t'), V('t'), V('t'), V('t'), V('t')))
    L.append('        Equal.trans(U32, PM.v16of(U32.and(%s, 255), U32.and(U32.shrn(%s, 8n), 255)), PM.v16of(UB.lo8(%s), U32.and(U32.shrn(%s, 8n), 255)), PM.v16of(UB.lo8(%s), UB.lo8(U32.shrn(%s, 8n))),' % (V('t'), V('t'), V('t'), V('t'), V('t'), V('t')))
    L.append('          Equal.cong(U32, U32, z => PM.v16of(z, U32.and(U32.shrn(%s, 8n), 255)), U32.and(%s, 255), UB.lo8(%s), e1),' % (V('t'), V('t'), V('t')))
    L.append('          Equal.cong(U32, U32, z => PM.v16of(UB.lo8(%s), z), U32.and(U32.shrn(%s, 8n), 255), UB.lo8(U32.shrn(%s, 8n)), e2)),' % (V('t'), V('t'), V('t')))
    L.append('        v16_go(%s, t, ht))' % ', '.join(bs))
    return '\n'.join(L) + '\n'


def main():
    run_single('v16', OUT, text())


if __name__ == '__main__':
    main()
