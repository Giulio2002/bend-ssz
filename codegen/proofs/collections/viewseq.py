def seq_file():
    specs = seq_specs()
    imps = {'S': '../../types/schema.bend', 'F': '../compact/found.bend', 'VS': './value_set.bend', 'WR': './words_rw.bend'}
    for M_, f_ in SOURCES:
        imps[M_] = './' + f_
    for sp in specs.values():
        imps.update(sp['imports'])
    out = ['import Base'] + ['import %s as %s' % (p, a) for a, p in imps.items()]
    out += ['', HEADER,
            '# The view xv_<list> (root_types_light.bend) of a list of Data elements after one element is written: the view before with',
            "# that item replaced by the new element's view (value_set.bend's field_set). See codegen/proofs/collections/view_laws.py.", '', HELPER]
    for c, sp in specs.items():
        E, V = sp['E'], sp['V']

        def upd(W, J='J', e='e'):
            return 'F.spec_common__update(%s, %s, %s, %s)' % (E, W, J, e)

        def XAT(W, i):
            return '%s.xat_%s(%s, %s)' % (sp['M'], c, W, i)

        def XI(k, W, i):
            return '%s.xi_%s(%s, %s, %s)' % (sp['M'], c, k, W, i)
        out.append('# ---- %s ----' % c)
        if sp.get('VDEF'):
            out.append(sp['VDEF'] + '\n')
        out.append(XAT_LEMMAS % dict(c=c, E=E, xs=XAT(upd('W'), 'J'), xn=XAT(upd('Nil{}'), 'J'), xu=XAT(upd('W'), 'i'), xw=XAT('W', 'i'),
                                     xu0=XAT(upd('Con{x, t}', '0n', 'e').replace('J', '0n'), '0n'), xw0=XAT('Con{x, t}', '0n')))
        out.append(XI_LEMMAS % dict(c=c, E=E, V=V, a=XI('k', upd('W'), 'i0'), b=XI('k', 'W', 'i0'), xu=XAT(upd('W'), 'i0'), xw=XAT('W', 'i0'), xz=XAT(upd('W'), 'z'),
                                    tu=XI('q', upd('W'), '1n+i0'), tw=XI('q', 'W', '1n+i0')))
        TU = 'F.array__upd(%s, d, t, J, e)' % E
        out.append(XI_APP % dict(c=c, E=E, V=V, a1=XI('1n+k', upd('W'), 'i0'), b=XI('k', 'W', 'i0'), xu=XAT(upd('W'), 'i0'), xw=XAT('W', 'i0'), xz=XAT(upd('W'), 'z'),
                                 tu1=XI('1n+p', upd('W'), '1n+i0'), tw=XI('p', 'W', '1n+i0')))

        def SL(T):
            return 'F.array__slots(%s, %s)' % (E, T)

        def FT(T):
            return 'F.array__freeze(%s, F.array__thaw(%s, %s))' % (E, E, T)
        out.append(VIEW_SET % dict(c=c, E=E, V=V, M=sp['M'], xa='%s.xi_%s(c, %s, 0n)' % (sp['M'], c, SL(FT(TU))), xb='%s.xi_%s(c, %s, 0n)' % (sp['M'], c, SL(FT('t'))),
                                   ftu=FT(TU), tu=TU, ft=FT('t'), xi_='%s.xi_%s(c, %s, 0n)' % (sp['M'], c, SL('_')),
                                   xa2='%s.xi_%s(c, %s, 0n)' % (sp['M'], c, SL(TU)), xi2='%s.xi_%s(c, %s, 0n)' % (sp['M'], c, SL('_')),
                                   slu=SL(TU), upd=upd(SL('t')), slt=SL('t')))
        TUc = 'F.array__upd(%s, d, t, c, e)' % E
        out.append(VIEW_APP % dict(c=c, E=E, V=V, M=sp['M'], xa='%s.xi_%s(c2, %s, 0n)' % (sp['M'], c, SL(FT(TUc))), xb='%s.xi_%s(c, %s, 0n)' % (sp['M'], c, SL(FT('t'))),
                                   xa_='%s.xi_%s(_, %s, 0n)' % (sp['M'], c, SL(FT(TUc))),
                                   ftu=FT(TUc), tu=TUc, ft=FT('t'), xi_='%s.xi_%s(1n+c, %s, 0n)' % (sp['M'], c, SL('_')),
                                   xa2='%s.xi_%s(1n+c, %s, 0n)' % (sp['M'], c, SL(TUc)), xi2='%s.xi_%s(c, %s, 0n)' % (sp['M'], c, SL('_')),
                                   slu=SL(TUc), upd=upd(SL('t'), 'c'), slt=SL('t')))
    return '\n'.join(out)
