class Q:
    """An equation lhs == rhs : T with its proof term."""
    def __init__(s, T, l, r, p): s.T, s.l, s.r, s.p = T, l, r, p
    def then(s, o):
        assert s.r == o.l, ('chain mismatch', s.r, o.l)
        return Q(s.T, s.l, o.r, f'Equal.trans({s.T}, {s.l}, {s.r}, {o.r}, {s.p}, {o.p})')
    def ctx(s, T2, f):
        return Q(T2, f(s.l), f(s.r), f'Equal.cong({s.T}, {T2}, zq_ => {f("zq_")}, {s.l}, {s.r}, {s.p})')
