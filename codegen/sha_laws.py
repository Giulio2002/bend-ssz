    t1, q_t1 = enc_tree(T1u); t2, q_t2 = enc_tree(T2u)
    t0, q_0 = enc_tree(('add', ('lem', q_t1), ('lem', q_t2)))
    # ('lem', q) above uses q.l[4:-1] = the u32 term inside enc(...)
    t4, q_4 = enc_tree(('add', 'd', ('lem', q_t1)))
    ls = [q_0.l] + [E(v) for v in S[:3]] + [q_4.l] + [E(v) for v in S[4:7]]
    rs = [q_0.r] + [E(v) for v in S[:3]] + [q_4.r] + [E(v) for v in S[4:7]]
    es = [q_0.p, '{==}', '{==}', '{==}', q_4.p, '{==}', '{==}', '{==}']
    w('law step_e:'); w('  for +s: Types.State'); w('  for +k: U32'); w('  for +x: U32')
    w('  {encs(SF.stepf(s, k, x)) == hstep(encs(s), enc(k), enc(x)) : HS}')
    w('def step_e(s, k, x):'); w('  match s:'); w(f'    case Types.H{{{", ".join("+" + v for v in S)}}}:')
    w(f'      hs_eq({", ".join(ls)}, {", ".join(rs)}, {", ".join(es)})'); w('')
    # rounds
    w('law rounds_e:'); w(f'  for +ks: {LU}'); w(f'  for +ws: {LU}'); w('  for +s: Types.State')
    w('  {encs(SF.roundsf(ks, ws)(s)) == hrounds(encl(ks), encl(ws))(encs(s)) : HS}')
    w('def rounds_e(ks, ws, s):'); w('  match ks ws:')
    w('    case Nil{} Nil{}: {==}'); w('    case Nil{} Con{+x, +wt}: {==}'); w('    case Con{+k, +kt} Nil{}: {==}')
    w('    case Con{+k, +kt} Con{+x, +wt}:')
    q = Q('HS', 'encs(SF.roundsf(kt, wt)(SF.stepf(s, k, x)))', 'hrounds(encl(kt), encl(wt))(encs(SF.stepf(s, k, x)))', 'rounds_e(kt, wt, SF.stepf(s, k, x))')
