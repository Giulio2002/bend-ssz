def emit_hex_sha(L, w):
    def law(name, params, stmt, body):
        w(f'law {name}:')
        for p, t in params: w(f'  for +{p}: {t}')
        w(f'  {stmt}')
        w(f'def {name}({", ".join(p for p, _ in params)}):')
        for line in body: w(f'  {line}')
        w('')
    def E(t): return f'enc({t})'
    # generic lemma instances as Q objects
    def xorq(a, b): return Q('W8', E(f'U32.xor({a}, {b})'), f'wxor({E(a)}, {E(b)})', f'xor_e({a}, {b})')
    def andq(a, b): return Q('W8', E(f'U32.and({a}, {b})'), f'wand({E(a)}, {E(b)})', f'and_e({a}, {b})')
    def notq(a): return Q('W8', E(f'U32.not({a})'), f'wnot({E(a)})', f'not_e({a})')
    def addq(a, b): return Q('W8', E(f'U32.add({a}, {b})'), f'wadd({E(a)}, {E(b)})', f'add_e({a}, {b})')
    def shq(nm, a): return Q('W8', E(f'SF.{nm}({a})'), f'h{nm}({E(a)})', f'{nm}_e({a})')
    def op2(opname, q0, la, ra, qa, qb):
        """q0: E(..) == opname(la, ra); qa: la == la2 (or None); qb: ra == ra2 (or None)."""
        r = q0
        cur_a, cur_b = la, ra
        if qa is not None:
            assert qa.l == la
            r = r.then(qa.ctx('W8', lambda z, b=cur_b: f'{opname}({z}, {b})')); cur_a = qa.r
        if qb is not None:
            assert qb.l == ra
            r = r.then(qb.ctx('W8', lambda z, a=cur_a: f'{opname}({a}, {z})')); cur_b = qb.r
        return r
    def op1(opname, q0, la, qa):
        if qa is None: return q0
        return q0.then(qa.ctx('W8', lambda z: f'{opname}({z})'))
    # E of a term built from xor/and/not/add/SF shifts, given as a tree
    def enc_tree(t):
        """t: ('xor'|'and'|'add', t1, t2) | ('not', t1) | ('sh', nm, t1) | ('lem', Q) | str (leaf).
        Returns (u32 term, Q or None) with Q: enc(term) == hex term."""
        if isinstance(t, str): return t, None
        if t[0] == 'lem': return t[1].l[4:-1], t[1]
        if t[0] == 'not':
            a, qa = enc_tree(t[1])
            q0 = notq(a)
            return f'U32.not({a})', op1('wnot', q0, E(a), qa)
        if t[0] == 'sh':
            a, qa = enc_tree(t[2])
            q0 = shq(t[1], a)
            return f'SF.{t[1]}({a})', op1(f'h{t[1]}', q0, E(a), qa)
        op = t[0]
        a, qa = enc_tree(t[1]); b, qb = enc_tree(t[2])
        mk = {'xor': xorq, 'and': andq, 'add': addq}[op]
        q0 = mk(a, b)
        return f'U32.{op}({a}, {b})', op2('w' + op, q0, E(a), E(b), qa, qb)
    # sigma / sum
    FAMS = [('sigma0', ('rot', 7), ('rot', 18), ('shr', 3)), ('sigma1', ('rot', 17), ('rot', 19), ('shr', 10)),
            ('sum0', ('rot', 2), ('rot', 13), ('rot', 22)), ('sum1', ('rot', 6), ('rot', 11), ('rot', 25))]
    for nm, a, b, c in FAMS:
        tree = ('xor', ('xor', ('sh', f'{a[0]}{a[1]}', 'x'), ('sh', f'{b[0]}{b[1]}', 'x')), ('sh', f'{c[0]}{c[1]}', 'x'))
        _, q = enc_tree(tree)
        law(f'{nm}_e', [('x', 'U32')], f'{{enc(SF.{nm}f(x)) == h{nm}(enc(x)) : W8}}', [q.p])
    _, q = enc_tree(('xor', ('and', 'x', 'y'), ('and', ('not', 'x'), 'z')))
    law('ch_e', [('x', 'U32'), ('y', 'U32'), ('z', 'U32')], '{enc(VF.ch(x, y, z)) == hch(enc(x), enc(y), enc(z)) : W8}', [q.p])
    _, q = enc_tree(('xor', ('xor', ('and', 'x', 'y'), ('and', 'x', 'z')), ('and', 'y', 'z')))
    law('maj_e', [('x', 'U32'), ('y', 'U32'), ('z', 'U32')], '{enc(VF.maj(x, y, z)) == hmaj(enc(x), enc(y), enc(z)) : W8}', [q.p])
    def sigq(nm, a): return Q('W8', E(f'SF.{nm}f({a})'), f'h{nm}({E(a)})', f'{nm}_e({a})')
    def chq(x, y, z): return Q('W8', E(f'VF.ch({x}, {y}, {z})'), f'hch({E(x)}, {E(y)}, {E(z)})', f'ch_e({x}, {y}, {z})')
    def majq(x, y, z): return Q('W8', E(f'VF.maj({x}, {y}, {z})'), f'hmaj({E(x)}, {E(y)}, {E(z)})', f'maj_e({x}, {y}, {z})')
    # lists
    w('law nth_e:'); w('  for +h: List<&2, U32>'); w('  for +i: Nat')
    w('  {enc(VF.nth(h, i)) == hnth(encl(h), i) : W8}')
    w('def nth_e(h, i):'); w('  match h i:')
    w('    case Nil{} 0n: {==}'); w('    case Nil{} 1n+ +p: {==}')
    w('    case Con{+x, +t} 0n: {==}'); w('    case Con{+x, +t} 1n+ +p: nth_e(t, p)'); w('')
    law('prev_e', [('h', LU), ('lag', 'Nat')], '{enc(VF.previous(h, lag)) == hprev(encl(h), lag) : W8}', ['nth_e(h, Nat.sub(lag, 1n))'])
    def prevq(h, n): return Q('W8', E(f'VF.previous({h}, {n}n)'), f'hprev(encl({h}), {n}n)', f'prev_e({h}, {n}n)')
    P = lambda n: f'VF.previous(h, {n}n)'
    tree = ('add', ('add', ('add', ('lem', sigq('sigma1', P(2))), ('lem', prevq('h', 7))), ('lem', sigq('sigma0', P(15)))), ('lem', prevq('h', 16)))
    # the sigma lemma leaves hsigma(enc(prev)), rewrite the prev inside afterwards
    _, q = enc_tree(tree)
    q = q.then(prevq('h', 2).ctx('W8', lambda z: q.r.replace(f'hsigma1({E(P(2))})', f'hsigma1({z})')))
    q = q.then(prevq('h', 15).ctx('W8', lambda z: q.r.replace(f'hsigma0({E(P(15))})', f'hsigma0({z})')))
    law('rec_e', [('h', LU)], '{enc(SF.recurrencef(h)) == hrec(encl(h)) : W8}', [q.p])
    # extension
    Rr = 'SF.recurrencef(h)'
    w('law ext_e:'); w('  for +r: Nat'); w(f'  for +h: {LU}')
    w('  {encl(SF.extensionf(r, h)) == hext(r, encl(h)) : List<&2, W8>}')
    w('def ext_e(r, h):'); w('  match r:'); w('    case 0n: {==}'); w('    case 1n+ +p:')
    q1 = Q(LW, f'encl(SF.extensionf(p, Con{{{Rr}, h}}))', f'hext(p, encl(Con{{{Rr}, h}}))', f'ext_e(p, Con{{{Rr}, h}})')
    q1 = q1.then(Q(LW, q1.r, f'hext(p, Con{{enc({Rr}), encl(h)}})', '{==}')).ctx(LW, lambda z: f'Con{{enc({Rr}), {z}}}')
    rq = Q('W8', f'enc({Rr})', 'hrec(encl(h))', 'rec_e(h)')
    q2 = rq.ctx(LW, lambda z: f'Con{{enc({Rr}), hext(p, Con{{{z}, encl(h)}})}}')
    q3 = rq.ctx(LW, lambda z: f'Con{{{z}, hext(p, Con{{hrec(encl(h)), encl(h)}})}}')
    w(f'      {chain(q1, q2, q3).p}'); w('')
    w('law app_e:'); w(f'  for +a: {LU}'); w(f'  for +b: {LU}')
    w('  {encl(List.append(&2, U32, a, b)) == List.append(&2, W8, encl(a), encl(b)) : List<&2, W8>}')
    w('def app_e(a, b):'); w('  match a:'); w('    case Nil{}: {==}'); w('    case Con{+x, +t}:')
    w(f'      {Q(LW, "encl(List.append(&2, U32, t, b))", "List.append(&2, W8, encl(t), encl(b))", "app_e(t, b)").ctx(LW, lambda z: f"Con{{enc(x), {z}}}").p}'); w('')
    w('law revgo_e:'); w(f'  for +xs: {LU}'); w(f'  for +acc: {LU}')
    w('  {encl(List.reverse.go(&2, U32, xs, acc)) == List.reverse.go(&2, W8, encl(xs), encl(acc)) : List<&2, W8>}')
    w('def revgo_e(xs, acc):'); w('  match xs:'); w('    case Nil{}: {==}'); w('    case Con{+x, +t}: revgo_e(t, Con{x, acc})'); w('')
    law('rev_e', [('xs', LU)], '{encl(List.reverse(&2, U32, xs)) == List.reverse(&2, W8, encl(xs)) : List<&2, W8>}', ['revgo_e(xs, Nil{})'])
    RV = 'List.reverse(&2, U32, block)'
    EX = f'SF.extensionf(extra, {RV})'
    q = Q(LW, f'encl(List.append(&2, U32, block, {EX}))', f'List.append(&2, W8, encl(block), encl({EX}))', f'app_e(block, {EX})')
    q = q.then(Q(LW, f'encl({EX})', f'hext(extra, encl({RV}))', f'ext_e(extra, {RV})').ctx(LW, lambda z: f'List.append(&2, W8, encl(block), {z})'))
    q = q.then(Q(LW, f'encl({RV})', 'List.reverse(&2, W8, encl(block))', 'rev_e(block)').ctx(LW, lambda z: f'List.append(&2, W8, encl(block), hext(extra, {z}))'))
    law('schedf_e', [('extra', 'Nat'), ('block', LU)], '{encl(SF.schedulef(extra, block)) == hsched(extra, encl(block)) : List<&2, W8>}', [q.p])
    q = Q(LU, 'SF.schedulef(extra, block)', 'VF.schedule(extra, block)', 'SF.schedule_eq(extra, block)').ctx(LW, lambda z: f'encl({z})').sym()
    q = q.then(Q(LW, 'encl(SF.schedulef(extra, block))', 'hsched(extra, encl(block))', 'schedf_e(extra, block)'))
    law('sched_e', [('extra', 'Nat'), ('block', LU)], '{encl(VF.schedule(extra, block)) == hsched(extra, encl(block)) : List<&2, W8>}', [q.p])
    # step
    S = ['a', 'b', 'c', 'd', 'e', 'f', 'g', 'h']
    T1u = ('add', ('add', ('add', ('add', 'h', ('lem', sigq('sum1', 'e'))), ('lem', chq('e', 'f', 'g'))), 'k'), 'x')
