    w(f'    case Types.H{{{", ".join("+" + v for v in X)}}} Types.H{{{", ".join("+" + v for v in Y)}}}:')
    qs = [addq(a, b) for a, b in zip(X, Y)]
    w(f'      hs_eq({", ".join(q.l for q in qs)}, {", ".join(q.r for q in qs)}, {", ".join(q.p for q in qs)})'); w('')
    # compress
    q = Q('Types.State', 'SF.roundsf(ks, ws)(s)', 'VF.rounds(ks, ws)(s)', 'SF.rounds_eq(ks, ws, s)').ctx('HS', lambda z: f'encs(VF.feedforward(s, {z}))').sym()
    q = q.then(Q('HS', 'encs(VF.feedforward(s, SF.roundsf(ks, ws)(s)))', 'hff(encs(s), encs(SF.roundsf(ks, ws)(s)))', 'ff_e(s, SF.roundsf(ks, ws)(s))'))
    q = q.then(Q('HS', 'encs(SF.roundsf(ks, ws)(s))', 'hrounds(encl(ks), encl(ws))(encs(s))', 'rounds_e(ks, ws, s)').ctx('HS', lambda z: f'hff(encs(s), {z})'))
    law('comp_e', [('ws', LU), ('ks', LU), ('s', 'Types.State')], '{encs(VF.compress(ws, ks, s)) == hcomp(encl(ws), encl(ks), encs(s)) : HS}', [q.p])
    # back from digits
    w('law des:'); w('  for +s: Types.State'); w('  {decs(encs(s)) == s : Types.State}')
    w('def des(s):'); w('  match s:'); w(f'    case Types.H{{{", ".join("+" + v for v in S)}}}:')
    w(f'      st_eq({", ".join(f"dec(enc({v}))" for v in S)}, {", ".join(S)}, {", ".join(f"de({v})" for v in S)})'); w('')
    # closed facts
    w('law k_e:'); w('  {encl(VF.constants()) == KH() : List<&2, W8>}'); w('def k_e(): {==}'); w('')
    w('law iv_e:'); w('  {encs(VF.initial()) == IVH() : HS}'); w('def iv_e(): {==}'); w('')
    q = Q(LW, f'encl(VF.schedule(48n, {PADL}))', f'hsched(48n, encl({PADL}))', f'sched_e(48n, {PADL})').then(Q(LW, f'hsched(48n, encl({PADL}))', 'hpads()', '{==}'))
    w('law pads_e:'); w(f'  {{encl(VF.schedule(48n, {PADL})) == hpads() : List<&2, W8>}}'); w('def pads_e():'); w(f'  {q.p}'); w('')

