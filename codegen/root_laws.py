def emit_names():
    names = schema.load(ROOT / 'codegen/fulu.yaml')
    g = G.Gen()
    for n, t in names.items():
        g.shape(t)
    covered_shapes, skipped = [], {}
    for s in g.order:
        if s.kind == 'box':
            continue
        try:
            covered(s)
            spec_schema(s)
            covered_shapes.append(s)
        except Skip as e:
            skipped[s.p] = str(e)
    lines = list(HEAD) + ['', '# GENERATED by codegen/root_laws.py. Do not edit.',
                          '# Root laws of the generated object API against spec/root_relation.bend.', '']
    w = lines.append
    PRE.clear()
    body = []
    for s in covered_shapes:
        body.append(f'# ---- {s.p} ({s.kind}) ----')
        emit_shape_laws(s, body.append)
        body.extend(PRE)
        PRE.clear()
        body.append('')
    good = {s.p for s in covered_shapes}
    name_laws = []
    status = {}
    for n, t in names.items():
        s = g.shape(t)
        if s.p in good:
            emit_name_law(name_laws.append, n, s)
            status[n] = 'proved'
            if t.fixed() and LW.word_aligned(t):
                try:
                    node = SL.walk(g, t, iter(range(10000)))
                except SL.Skip:
                    node = None
                if node is not None:
                    emit_decoded_law(name_laws.append, n, s, node)
                    status[n] = 'proved (+ decoded)'
        else:
            status[n] = skipped.get(s.p, 'not covered')
    return '\n'.join(lines + body + name_laws) + '\n', status


