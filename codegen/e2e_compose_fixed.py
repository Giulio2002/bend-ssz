#!/usr/bin/env python3
"""The fixed-size names codegen/e2e_compose.py leaves to this module (its extension point).

    (imported by codegen/e2e_compose.py; not run on its own)

Masked words. A fixed-size decoder writes a partial last word (or a byte) as U32.and(x, 2^k - 1) (or
B.byte_sel(0, x)) of an input word x. The encode and root premises of such an object (a bit vector's
padding bits `e`, a byte vector's zero tail in wf1) are closed facts about the high bits of that word,
and U32.and on a symbolic x does not compute them. e2e/e2e_mask.bend (written here) gives, for each
width k used, the clean form cf<k>(x) = U32{WCon{Bool.and(b0(x), True{}), .., Bool.and(b<k-1>(x),
True{}), Word.zero(32 - k)}}: the low bits opaque, the high bits literally zero, and the law
mk<k>(x): {U32.and(x, 2^k - 1) == cf<k>(x)} (one rewrite by wz: a word and-ed with zeros is zero).
The composed file states the decoder's object OBJ' with every masked word in clean form, proves
OBJ == OBJ' (one rewrite per masked word), so the decoder gives Some{OBJ'}, and the premises of OBJ'
are computed as for the unmasked names (e2e_compose.build_lit).
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
E2E = ROOT / 'e2e'
MASK = E2E / 'e2e_mask.bend'
HEADER = '# GENERATED by codegen/e2e_compose.py (codegen/e2e_compose_fixed.py). Do not edit.'


def pat(k):
    """U32{WCon{a0, .. WCon{a<k-1>, t}}}"""
    s = 't'
    for i in reversed(range(k)):
        s = f'WCon{{a{i}, {s}}}'
    return f'U32{{{s}}}'


# the padded last bytes the bit vectors use: (byte j of the word, r bits used in it)
PADS = [(0, r) for r in range(1, 8)] + [(1, 1), (1, 7), (2, 1), (3, 7)]


def full(fixed=()):
    """U32{WCon{a0, .. WCon{a31, WNil{}}}}, with the bits in fixed written False{}"""
    s = 'WNil{}'
    for i in reversed(range(32)):
        s = f'WCon{{{"False{}" if i in fixed else f"a{i}"}, {s}}}'
    return f'U32{{{s}}}'


def pz_lemmas(j, r):
    """pz<j>_<r>(x, h): the decoder's last word of a bit vector whose last used byte is byte j of the word with r
    bits used, given the decoder's padding check h, in clean form (bits past 8j + r literally zero)"""
    k = 8 * j + r

    def forms(fixed):
        X = full(fixed)
        if j < 3:
            H = f'{{U32.is_eq(U32.and(cf8(U32.shrn({X}, {8 * j}n)), U32.not(O.low_mask({r}))), 0) == True{{}} : Bool}}'
            goal = f'{{cf{8 * j + 8}({X}) == cf{k}({X}) : U32}}'
        else:
            H = f'{{U32.is_eq(U32.and(B.byte_sel(3, {X}), U32.not(O.low_mask({r}))), 0) == True{{}} : Bool}}'
            goal = f'{{{X} == cw{k}({X}) : U32}}'
        return X, H, goal

    # pc<j>_<r>_<i>: the pad bits a[i] .. a[8j+r], from the top, the bits above i already False{} (one def per
    # bit: a match is on a parameter); a True one makes the padding check false
    pads = list(range(8 * j + 7, 8 * j + r - 1, -1))
    out = []
    for n_, i in enumerate(pads):
        fixed = set(pads[:n_])
        free = [b for b in range(32) if b not in fixed]
        X, H, goal = forms(fixed)
        ps = ', '.join(f'+a{b}: Bool' for b in free)
        if n_ + 1 < len(pads):
            nxt = f'pc{j}_{r}_{pads[n_ + 1]}(' + ', '.join(f'a{b}' for b in free if b != i) + ', h)'
        else:
            nxt = '{==}'
        out.append(f'def pc{j}_{r}_{i}({ps}, +h: {H}) -> {goal}:\n  match a{i}:\n'
                   f'    case True{{}}: Empty.absurd({goal}, FD.logic__false_true(h))\n    case False{{}}: {nxt}\n')
    out.reverse()   # a def is used after it is declared
    X, H, goal = forms(())
    alla = ', '.join(f'a{b}' for b in range(32))
    if j < 3:
        lhs, cf = f'U32.and(x, {2 ** (8 * j + 8) - 1})', f'cf{k}(x)'
        sub = (f'FD.logic__subst(U32, z => {{U32.is_eq(U32.and(z, U32.not(O.low_mask({r}))), 0) == True{{}} : Bool}}, '
               f'U32.and(U32.shrn({X}, {8 * j}n), 255), cf8(U32.shrn({X}, {8 * j}n)), mk8(U32.shrn({X}, {8 * j}n)), h)')
        pf = (f'Equal.trans(U32, U32.and({X}, {2 ** (8 * j + 8) - 1}), cf{8 * j + 8}({X}), cf{k}({X}), mk{8 * j + 8}({X}), '
              f'pc{j}_{r}_{8 * j + 7}({alla}, {sub}))')
    else:
        lhs, cf = 'x', f'cw{k}(x)'
        pf = f'pc{j}_{r}_{8 * j + 7}({alla}, h)'
    out.append(f'def pz{j}_{r}(+x: U32, +h: {{U32.is_eq(U32.and(B.byte_sel({j}, x), U32.not(O.low_mask({r}))), 0) == True{{}} : Bool}})\n'
               f'    -> {{{lhs} == {cf} : U32}}:\n  match x:\n    case {X}:\n      {pf}\n')
    return out


def mask_lib(ks):
    out = ['import Base', 'import ../src/buffer.bend as B', 'import ../src/obj.bend as O',
           'import ../proofs/compact/found.bend as FD', '', HEADER,
           '# Masked words in clean form: cf<k>(x) keeps the low k bits of x (opaque) and has its high bits',
           '# literally zero; mk<k>(x) is the decoder\'s mask U32.and(x, 2^k - 1) in that form.', '']
    for i in range(32):
        out.append(f'def b{i}(x: U32) -> Bool:\n  match x:\n    case {pat(i + 1)}: a{i}\n')
    out.append('''# a word and-ed with zeros is zero
def wz(+n: Nat, +w: Word(n)) -> {Word.and(n, w, Word.zero(n)) == Word.zero(n) : Word(n)}:
  match n w:
    case 0n WNil{}: {==}
    case 1n+p WCon{b, t}:
      match b:
        case True{}: Equal.cong(Word(p), Word(1n+p), z => WCon{False{}, z}, Word.and(p, t, Word.zero(p)), Word.zero(p), wz(p, t))
        case False{}: Equal.cong(Word(p), Word(1n+p), z => WCon{False{}, z}, Word.and(p, t, Word.zero(p)), Word.zero(p), wz(p, t))
''')
    for k in sorted(ks):
        m = 32 - k
        low = f'Word.zero({m}n)'
        mot = '_'
        for i in reversed(range(k)):
            low = f'WCon{{Bool.and(b{i}(x), True{{}}), {low}}}'
            mot = f'WCon{{Bool.and(a{i}, True{{}}), {mot}}}'
        out.append(f'def cf{k}(+x: U32) -> U32: U32{{{low}}}\n')
        out.append(f'def mk{k}(+x: U32) -> {{U32.and(x, {2 ** k - 1}) == cf{k}(x) : U32}}:\n  match x:\n    case {pat(k)}:\n'
                   f'      %Equal.sym(Word({m}n), Word.and({m}n, t, Word.zero({m}n)), Word.zero({m}n), wz({m}n, t)) : '
                   f'{{U32{{{mot}}} == cf{k}({pat(k)}) : U32}}\n      {{==}}\n')
    for k in range(25, 32):
        raw = f'Word.zero({32 - k}n)'
        for i in reversed(range(k)):
            raw = f'WCon{{b{i}(x), {raw}}}'
        out.append(f'# the low {k} bits of x as they are, the rest zero\ndef cw{k}(+x: U32) -> U32: U32{{{raw}}}\n')
    for j, r in PADS:
        out += pz_lemmas(j, r)
    return '\n'.join(out)


def outputs():
    return {MASK: mask_lib(range(1, 32))}


def balanced(s, i):
    """the index after the parenthesised group opening at s[i] == '('"""
    d = 0
    for j in range(i, len(s)):
        if s[j] == '(':
            d += 1
        elif s[j] == ')':
            d -= 1
            if d == 0:
                return j + 1
    raise ValueError('unbalanced')


def masked(obj):
    """[(start, end, inner x, k)] of the masked words U32.and(x, 2^k - 1) / B.byte_sel(0, x) of a term"""
    out = []
    for m in re.finditer(r'(?<![\w.])(U32\.and|[\w]+\.byte_sel)\(', obj):
        e = balanced(obj, m.end() - 1)
        args = split_args(obj[m.end():e - 1])
        if m.group(1) == 'U32.and' and len(args) == 2 and re.fullmatch(r'\d+', args[1].strip()):
            v = int(args[1])
            if v & (v + 1) == 0 and 0 < v < 2 ** 32 - 1:
                out.append((m.start(), e, args[0].strip(), v.bit_length()))
        elif m.group(1).endswith('byte_sel') and len(args) == 2 and args[0].strip() == '0':
            out.append((m.start(), e, args[1].strip(), 8))
    # innermost last is not needed: the decoders never nest masks
    return out


def split_args(s):
    out, d, cur = [], 0, ''
    for c in s:
        if c in '([{':
            d += 1
        elif c in ')]}':
            d -= 1
        if c == ',' and d == 0:
            out.append(cur)
            cur = ''
        else:
            cur += c
    out.append(cur)
    return out


def clean(obj, ms):
    s, last = '', 0
    for a, b, x, k in ms:
        s += obj[last:a] + f'MK.cf{k}({x})'
        last = b
    return s + obj[last:]


def pad_word(eht):
    """(j, r, x) of a bit vector's padding check U32.is_eq(U32.and(B.byte_sel(j, x), U32.not(O.low_mask(r))), 0)"""
    m = re.match(r'\{U32\.is_eq\(U32\.and\((\w+)\.byte_sel\((\d), (.*)\), U32\.not\((\w+)\.low_mask\((\d)\)\)\), 0\) == True\{\} : Bool\}$', eht, re.S)
    if not m:
        return None
    return int(m.group(2)), int(m.group(5)), m.group(3)


def build(name, lf, api):
    W = api.W
    dl = lf.get(f'{name}_e2e_decode_view')
    el, rl = lf.get(f'{name}_e2e_encode'), lf.get(f'{name}_e2e_root')
    if not (dl and el and rl):
        return None
    dm, em, rm = W.Mod.get(dl), W.Mod.get(el), W.Mod.get(rl)
    if f'{name}_d_some' not in dm.defs or f'{name}_d_none' not in dm.defs:
        return None
    sps, sc = api.sig(dm, f'{name}_d_some')
    binders = [b for _, b, _ in sps]
    if binders not in (['bs', 'n', 'hn', 'hd', 'ec'], ['bs', 'n', 'hn', 'hd', 'ec', 'eh']):
        return None
    eps, ec = api.sig(em, f'{name}_e2e_encode')
    rps, rc = api.sig(rm, f'{name}_e2e_root')
    if 'o' not in [b for _, b, _ in eps]:
        return None
    mk = re.match(r'\{Nat\.is_eq\(List\.length\(&2, U32, bs\), (\d+)n\) == True\{\} : Bool\}$', sps[4][2])
    ms = re.match(r'\{(.*) == Some\{(.*)\} : (Maybe<&1, [\w.]+>)\}$', sc, re.S)
    if not mk or not ms:
        return None
    K, obj0 = int(mk.group(1)), ms.group(2)
    extra = sorted({b for _, b, _ in eps + rps} - {'o', 'h'})
    why = 'the (i)/(iv) bridges take ' + ', '.join(extra) + ' (decoded-object laws pending)'
    eh = sps[5][2] if len(binders) == 6 else None
    pw = pad_word(eh) if eh else None
    if eh and not pw:
        return None        # an eh that is not a bit vector's padding check (vec_bool): not yet
    mw = masked(obj0)
    padx = None
    if pw:
        j, r, x = pw
        padx = f'U32.and({x}, {2 ** (8 * j + 8) - 1})' if j < 3 else x
        if padx not in obj0:
            return None, why + '; the padded word is not in the decoder\'s object'
        mw = [m for m in mw if obj0[m[0]:m[1]] != padx]
    if (not mw and not pw) or K > 1500:
        return None        # unmasked or large: e2e_compose.py's own path
    obj1 = clean(obj0, mw)
    if pw:
        cf = f'MK.cf{8 * j + r}({x})' if j < 3 else f'MK.cw{24 + r}({x})'
        a2 = [m.start() for m in re.finditer(re.escape(padx) + r'(?=[},])', obj1)][-1]
        obj1 = obj1[:a2] + cf + obj1[a2 + len(padx):]
    kind = 'view'
    dps, dc = api.sig(dm, f'{name}_e2e_decode_{kind}')
    W.PREFER.clear()
    W.PREFER[dm.path] = 'DB'
    W.PREFER.setdefault(em.path, 'EB')
    W.PREFER.setdefault(rm.path, 'RB')
    W.PREFER[(E2E / 'e2e_comp.bend').resolve()] = 'C'
    W.PREFER[(ROOT / 'types/schema.bend').resolve()] = 'S'
    W.PREFER[(ROOT / 'src/buffer.bend').resolve()] = 'B'
    W.PREFER[(ROOT / 'src/model.bend').resolve()] = 'API'
    W.PREFER[MASK.resolve()] = 'MK'
    taken = set(W.PREFER.values())
    for m_ in (em, rm, dm):
        for a, pth in m_.imports.items():
            if pth not in W.PREFER and a not in taken:
                W.PREFER[pth] = a
                taken.add(a)
    ctx = W.Ctx()
    for p_ in (dm.path, em.path, rm.path, (E2E / 'e2e_comp.bend').resolve(), MASK.resolve()):
        ctx.alias(p_)
    DB, EB, RB = W.PREFER[dm.path], W.PREFER[em.path], W.PREFER[rm.path]
    enc = api.some_lhs(ec, 'serialize')
    rt = api.some_lhs(rc, 'hash_tree_root')
    if not enc or not rt:
        return None, 'unexpected (i)/(iv) conclusion'
    X, SPEC, V = ctx.lift(em, enc[0]), ctx.lift(em, enc[1]), ctx.lift(em, enc[2])
    R = ctx.lift(rm, rt[0])
    if ctx.lift(rm, rt[2]) != V or ctx.lift(rm, rt[1]) != SPEC:
        return None, 'the (i) and (iv) views differ textually'
    mo = re.match(r'\{(\w+)\((.*)\) == (API\.deserialize\(.*\)) : Maybe<&2, S\.Value>\}$', dc, re.S)
    MV, DEC, DES = mo.group(1), ctx.lift(dm, mo.group(2)), ctx.lift(dm, mo.group(3))
    MT = ctx.lift(dm, re.search(r'Pair\.snd\(B\.Buf, (Maybe<&1, [\w.]+>)', dc).group(1))
    hyps = [(m_, b, ctx.lift(dm, t)) for m_, b, t in dps if b not in ('bs', 'n')]
    args = ', '.join(b for _, b, _ in dps)
    accT = f'{{{DES} == Some{{{V}}} : Maybe<&2, S.Value>}}'
    acc_body = (f'  Equal.trans(Maybe<&2, S.Value>, {DES}, {DB}.{MV}({DEC}), Some{{{V}}},\n'
                f'    Equal.sym(Maybe<&2, S.Value>, {DB}.{MV}({DEC}), {DES}, {DB}.{name}_e2e_decode_view({args})),\n'
                f'    Equal.cong({MT}, Maybe<&2, S.Value>, z => {DB}.{MV}(z), {DEC}, Some{{o}}, dec))')
    OT = MT[len('Maybe<&1, '):-1]
    # everything this file adds is lifted before build_lit writes the imports
    OBJ, OBJ1 = ctx.lift(dm, obj0), ctx.lift(dm, obj1)
    EH = ctx.lift(dm, eh) if eh else None
    if pw:
        PX, XX = ctx.lift(dm, padx), ctx.lift(dm, x)
    ctx.alias(ROOT / 'proofs/compact/found.bend')
    ctx.alias(ROOT / 'spec/primitives.bend')
    text, err = api.build_lit(name, (K, obj1, why), ctx, dm, em, rm, eps, rps, DB, EB, RB, X, SPEC, V, R, DEC, MT, OT,
                              accT, acc_body, hyps, kind)
    if text is None:
        return None, err
    # the decoder's object in clean form: OBJ == OBJ' (one rewrite per masked word), and the decoder gives OBJ'
    steps, cur = [], OBJ
    while True:
        cm = masked(cur)
        if pw:
            cm = [m for m in cm if cur[m[0]:m[1]] != PX]
        if not cm:
            break
        a2, b2, x2, k2 = cm[0]
        mot = cur[:a2] + '_' + cur[b2:]
        steps.append(f'  %Equal.sym(U32, U32.and({x2}, {2 ** k2 - 1}), MK.cf{k2}({x2}), MK.mk{k2}({x2})) :\n'
                     f'    {{{mot} == {OBJ1} : {OT}}}')
        cur = cur[:a2] + f'MK.cf{k2}({x2})' + cur[b2:]
    if pw:
        CF = f'MK.cf{8 * j + r}({XX})' if j < 3 else f'MK.cw{24 + r}({XX})'
        a2 = [m.start() for m in re.finditer(re.escape(PX) + r'(?=[},])', cur)][-1]
        mot = cur[:a2] + '_' + cur[a2 + len(PX):]
        steps.append(f'  %Equal.sym(U32, {PX}, {CF}, MK.pz{j}_{r}({XX}, eh)) :\n    {{{mot} == {OBJ1} : {OT}}}')
    ehp = f', +eh: {EH}' if eh else ''
    eha = ', eh' if eh else ''
    ecT = ctx.lift(dm, sps[4][2])
    SOME = f'{DB}.{name}_d_some(bs, n, hn, hd, ec{eha})'
    eqdefs = (f'# the decoder\'s object with its masked words in clean form (e2e/e2e_mask.bend)\n'
              f'def oeq(+bs: +List<U32>{ehp}) -> {{{OBJ} == {OBJ1} : {OT}}}:\n' + '\n'.join(steps) + '\n  {==}\n\n'
              f'def dsome(+bs: +List<U32>, +n: U32, +hn: {{List.length(&2, U32, bs) == U32.to_nat(n) : Nat}}, '
              f'+hd: {{SPX.bytes_domain(bs) == True{{}} : Bool}}, +ec: {ecT}{ehp})\n'
              f'    -> {{{DEC} == Some{{{OBJ1}}} : {MT}}}:\n'
              f'  Equal.trans({MT}, {DEC}, Some{{{OBJ}}}, Some{{{OBJ1}}}, {SOME},\n'
              f'    Equal.cong({OT}, {MT}, z => Some{{z}}, {OBJ}, {OBJ1}, oeq(bs{eha})))\n')
    SPA = re.search(r'import \.\./spec/primitives\.bend as (\w+)', text).group(1)
    eqdefs = eqdefs.replace('SPX.', SPA + '.')
    i = text.index('def gm(')
    head, tail = text[:i], text[i:]
    if not eh:
        tail = tail.replace(f'{DB}.{name}_d_some(bs, n, hn, hd, ec)', 'dsome(bs, n, hn, hd, ec)')
    else:
        FDA = re.search(r'import \.\./proofs/compact/found\.bend as (\w+)', text).group(1)
        tail = eh_tail(tail, name, DB, DEC, MT, OT, OBJ1, EH, FDA)
    text = head + eqdefs + '\n' + tail
    return text.replace(api.HEADER, HEADER, 1), None


def eh_tail(tail, name, DB, DEC, MT, OT, OBJ1, EH, FDX):
    """build_lit's ge/gr for a decoder with a padding check eh: after the length case, a case on eh (True: the
    decoder gives the clean object; False: it rejects, _d_noneh)"""
    out = []
    for fn in ('ge', 'gr'):
        m = re.search(r'^def ' + fn + r'\((.*?)\n    \+c: Bool, \+ec: (\{.*?\})\) -> (\{.*?\}):\n  match c:\n    case True\{\}:\n(.*?)\n    case False\{\}:\n      (Empty\.absurd\(.*\))\n',
                      tail, re.S | re.M)
        params, ecT, goal, tbody, fbody = m.groups()
        ect = ecT.replace('== c :', '== True{} :')
        tbody = tbody.replace(f'{DB}.{name}_d_some(bs, n, hn, hd, ec)', 'dsome(bs, n, hn, hd, ec, eh)')
        tbody = tbody.replace('{==}', '{==}')  # the clean object's eqo is in terms of dsome now
        tbody = '\n'.join('  ' + l for l in tbody.split('\n'))
        noneh = (f'Empty.absurd({goal}, {FDX}.logic__false_true(Equal.cong({MT}, Bool, z => isS(z), None{{}}, Some{{o}}, '
                 f'Equal.trans({MT}, None{{}}, {DEC}, Some{{o}}, Equal.sym({MT}, {DEC}, None{{}}, {DB}.{name}_d_noneh(bs, n, hn, hd, ec, eh)), dec))))')
        first = params.split(',')[0]
        hdr = f'def {fn}1({params}\n    +ec: {ect}, +c2: Bool, +eh: {{{EH[1:EH.rindex(" == True{} : Bool}")]} == c2 : Bool}}) -> {goal}:\n'
        new1 = hdr + f'  match c2:\n    case True{{}}:\n{tbody}\n    case False{{}}:\n      {noneh}\n'
        names = [p.split(':')[0].strip().lstrip('+-') for p in split_args(params) if p.strip()]
        call = f'{fn}1({", ".join(names)}, ec, {EH[1:EH.rindex(" == True{} : Bool}")]}, {{==}})'
        new2 = (f'def {fn}({params}\n    +c: Bool, +ec: {ecT}) -> {goal}:\n  match c:\n    case True{{}}:\n      {call}\n'
                f'    case False{{}}:\n      {fbody}\n')
        tail = tail[:m.start()] + new1 + '\n' + new2 + tail[m.end():]
    return tail
