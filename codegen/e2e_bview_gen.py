    """(iv) for a container whose field 0 is a bit list and whose other nrest fields are data (rep_X: those fields
    as witnesses, the bit list's rep_bits)."""
    D = f'T.{X}'
    xs = [f'x{i + 1}' for i in range(nrest)]
    O1 = f'{D}{{O.Bits{{FD.array__thaw(U32, t), K}}, {", ".join(xs)}}}'
    RX = lambda o: f'D.bytes(Pair.snd({D}, D.Digest, Pair.snd(B.Buf, {D} & D.Digest, T.{X}_hash_tree_root(h, {o}))))'
    G = lambda o: f'{{Some{{{RX(o)}}} == API.hash_tree_root(Spec.{X}(), RT.v_{X}({o})) : Maybe<&2, +List<U32>>}}'
    XP = ', '.join(f'+{x}: T.{{T{i}}}' for i, x in enumerate(xs))  # filled below
    return O1, RX, G, xs


