def _split_top(s):
    """the top-level comma-separated items of s"""
    out, dep, cur = [], 0, ''
    for ch in s:
        if ch in '{([':
            dep += 1
        elif ch in '})]':
            dep -= 1
        if ch == ',' and dep == 0:
            out.append(cur.strip())
            cur = ''
        else:
            cur += ch
    out.append(cur.strip())
    return out


