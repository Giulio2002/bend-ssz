"""The D twins of the word/byte list children of the encoder-window interface (proofs/obj/encx_<p>.bend):
their storage at depth dw < 31 (the bases stop at dw < 28), in the companion modules encx_<p>_d.bend.

A base child (codegen/var_plist_sub.py's ENCX, var_rec_enc's lists) states its validity OKT with a perfect tree of
depth dw < 28: the source of its words is copied through the lemmas that take dw < 28 (vlist.KK / kk_lt / hyn,
UW.hsx). The twin is the same module at dw < 31 over the lemmas that take the U form of the copy's bound
(YL(N) <= UMAX: vbenc.wob_goU / words_ok_bU, vuwd.putw_anyUW / putw_any_bytesUW, UW.hsxBU, the windows' specwD).
Where the child has a limit (its validity says N <= L) the U bound follows from it (VC.hyU over the window's hyB,
or hyLim); a progressive list has none, so its validity gets the object API's own limit N <= NMAX (the
decoded object's length: hyW).

The mirror type MW and its projections (TH, ENC, VAL, SZ, PUTX, PADB) are the base's (B0), so a container's record
holds the same MW whichever validity is used. Additive: the base module is untouched; a container's OKW twin
(codegen/okw.py) takes these laws for its list children.

  d_twin(text, p) -> the text of encx_<p>_d.bend from the text of encx_<p>.bend
  d_companions(out) -> out plus the companions of its encx_<p> entries
"""
import re

# p -> (kind, K): 'lim' the validity bounds N (K: the window's hyB exponent, W.hyB(N, N <= lim));
# 'hyL' the window's hyL (W.hyL(T, 0n, 0, N, CHKw), pw(K)); 'prog' no limit (NMAX conjunct added)
CFG = {
    'l1024_u16': ('lim', 12, 2048),
    'l128_u16': ('lim', 9, 256),
    'l123_u16': ('lim', 9, 246),
    'bl32': ('lim', 6, 32),
    'bl256': ('lim', 9, 256),
    'l131072_u64': ('hyL', 21, None),
    'pl_u8': ('prog', None, None),
    'pl_u16': ('prog', None, None),
    'pl_bool': ('prog', None, None),
    'pl_u64': ('prog', None, None),
    # BeaconState's big lists (codegen/var_rec_enc.py): balances / inactivity_scores / the participation lists (no limit
    # in the validity: the object API's NMAX), historical_roots (N <= 2^29 bytes in the base validity, and the NMAX conjunct)
    'l1099511627776_u64': ('prog', None, None),
    'l1099511627776_u8': ('prog', None, None),
    'l16777216_b32': ('prog', None, None),
}

DROP_DEFS = {'TH', 'ENC', 'VAL', 'SZ', 'PUTX', 'PADB', 'putx_go', 'bytes_go', 'putx', 'putx_bytes'}
QUAL = ('MW', 'TH', 'ENC', 'VAL', 'SZ', 'PUTX', 'PADB')

HYU = '{Nat.is_le(VC.YL(N), U32.to_nat(VB.UMAX())) == True{} : Bool}'
NMX = 'Nat.is_le(U32.to_nat(N), U32.to_nat(VB.NMAX()))'


def _blocks(text):
    """[(kind, name, start, end)] of the top-level def / law / type blocks (a block runs to the next one)."""
    ms = list(re.finditer(r'^(def|law|type) (\w+)', text, re.M))
    out = []
    for i, m in enumerate(ms):
        out.append((m.group(1), m.group(2), m.start(), ms[i + 1].start() if i + 1 < len(ms) else len(text)))
    return out


def _sub1(text, a, b, what):
    assert a in text, (what, a[:100])
    return text.replace(a, b)


def _hb_lim(p, lim):
    """the base OKT's limit conjunct as N <= lim in Nat (from ok_ex or a conjunct of it)."""
    return lim


def d_twin(text, p):
    kind, K, lim = CFG[p]
    bl = _blocks(text)
    head = text[:bl[0][2]]
    # the header comment lines before the first block stay (imports first)
    keep = []
    for k, n, a, b in bl:
        if k == 'type' and n == 'MW':
            continue
        if k in ('def', 'law') and n in DROP_DEFS:
            continue
        keep.append(text[a:b])
    t = head + ''.join(keep)
    t = re.sub(r'# GENERATED by [^\n]*\n', f'# GENERATED by codegen/encx_d.py (the D twin of encx_{p}). Do not edit.\n', t, count=1)
    # the base's MW and projections
    t = re.sub(r'(?<![\w.])(' + '|'.join(QUAL) + r')(?=[\({:\s,)])', r'B0.\1', t)
    t = re.sub(r'(?<=def )B0\.', '', t)
    t = t.replace('import ../../src/buffer.bend as B\n', 'import ../../src/buffer.bend as B\n', 1)
    imp_end = t.index('\n\n', t.index('import Base'))
    t = t[:imp_end] + f'\nimport ./encx_{p}.bend as B0' + t[imp_end:]
    # depth below 31
    t = t.replace('Nat.is_lt(dw, 28n)', 'Nat.is_lt(dw, 31n)')
    t = t.replace('FD.nat__lt_trans(dw, 28n, 31n, hdw, {==})', 'hdw')
    t = t.replace('FD.nat__lt_trans(dw, 28n, 32n, ', 'FD.nat__lt_trans(dw, 31n, 32n, ')
    t = t.replace('depth < 28 with room', 'depth < 31 with room').replace('depth dd < 29 (vuwd.putw_any', 'depth dd < 31 (vuwd.putw_anyU')
    assert not re.search(r'(?<![\d])28n(?!\+x)', t), [l for l in t.split('\n') if '28n' in l][:2]
    # hsrc takes the U bound (hy) in place of the depth
    t = _sub1(t, 'def hsrc(+dw: Nat, +N: U32, +hdw: {Nat.is_lt(dw, 31n) == True{} : Bool},',
              'def hsrc(+dw: Nat, +N: U32, +hy: ' + HYU + ',', 'hsrc')
    t = _sub1(t, 'UW.hsx(dw, 0, 0n, N, {==}, hdw, hN)', 'UW.hsxBU(dw, 0, 0n, N, {==}, hy, hN)', 'hsx')
    t = re.sub(r'hsrc\(dw, N, hdw, hN\)', 'hsrc(dw, N, hy, hN)', t)
    # the U bound of a valid object
    ex = re.search(r'def ok_ex\(.*?-> \{(.*) == True\{\} : Bool\}:', t).group(1)
    unb = kind == 'prog'
    if unb:
        # OKT = OKT0 (the base's chain) and N <= NMAX
        a = t.index('def OKT(')
        b = t.index('\ndef OK(', a)
        okt = t[a:b]
        okt0 = okt.replace('def OKT(', 'def OKT0(', 1)
        okt_new = ('def OKT(+dw: Nat, +T: FD.array__Tree<U32>, +N: U32) -> Bool: Bool.and(OKT0(dw, T, N), ' + NMX + ')\n'
                   'def ok0(+dw: Nat, +T: FD.array__Tree<U32>, +N: U32, +h: {OKT(dw, T, N) == True{} : Bool}) -> {OKT0(dw, T, N) == True{} : Bool}:\n'
                   '  FD.logic__and_left(OKT0(dw, T, N), ' + NMX + ', h)\n'
                   'def ok_nm(+dw: Nat, +T: FD.array__Tree<U32>, +N: U32, +h: {OKT(dw, T, N) == True{} : Bool}) -> {' + NMX + ' == True{} : Bool}:\n'
                   '  FD.logic__and_right(OKT0(dw, T, N), ' + NMX + ', h)\n')
        t = t[:a] + okt0 + okt_new + t[b:]
        # the chain's first projections take the OKT0 of h
        a = t.index('def ok_pf(')
        b = t.index('def ok_r2(')
        seg = t[a:b]
        seg = re.sub(r', h\)(\n|$)', r', ok0(dw, T, N, h))\1', seg)
        t = t[:a] + seg + t[b:]
        hy_body = ('VC.hyW(0n, N, ok_nm(dw, T, N, h))')
        hw32 = 'ok_nm(dw, T, N, hok)'
    else:
        if kind == 'lim':
            if ex.startswith('Bool.and(Nat.is_le(U32.to_nat(N), U32.to_nat('):
                lc, rest = _and_args(ex)
                hb = f'FD.logic__and_left({lc}, {rest}, ok_ex(dw, T, N, h))'
            else:
                assert ex.startswith('U32.is_le(N, '), ex
                L = re.match(r'U32\.is_le\(N, (\d+)\)$', ex).group(1)
                hb = f'FD.logic__subst(Bool, z => {{z == True{{}} : Bool}}, U32.is_le(N, {L}), Nat.is_le(U32.to_nat(N), U32.to_nat({L})), VU.le_u32(N, {L}), ok_ex(dw, T, N, h))'
            hy_body = f'VC.hyU(N, {K}n, {{==}}, W.hyB(N, {hb}))'
        else:
            lc, rest = _and_args(ex)
            unit, chk = _and_args(rest)
            hc = f'FD.logic__and_right({unit}, {chk}, FD.logic__and_right({lc}, {rest}, ok_ex(dw, T, N, h)))'
            hy_body = f'VC.hyU(N, {K}n, {{==}}, W.hyL(T, 0n, 0, N, {hc}))'
        hw32 = 'VB.u32_lt(N)'
    hyd = ('def hyD(+dw: Nat, +T: FD.array__Tree<U32>, +N: U32, +h: {OKT(dw, T, N) == True{} : Bool}) -> ' + HYU + ':\n  ' + hy_body + '\n\n')
    a = t.index('def hsrc(')
    t = t[:a] + hyd + t[a:]
    # wok takes hy; the drivers and laws that read the source take it from OKT
    t = _sub1(t, '+hdw: {Nat.is_lt(dw, 31n) == True{} : Bool}, +hN: {Nat.is_le(U32.to_nat(N), A.quad(VB.pw(dw))) == True{} : Bool},\n    +htz',
              '+hdw: {Nat.is_lt(dw, 31n) == True{} : Bool}, +hy: ' + HYU + ', +hN: {Nat.is_le(U32.to_nat(N), A.quad(VB.pw(dw))) == True{} : Bool},\n    +htz', 'wok sig')
    t = _sub1(t, 'VBE.wob_go(dw, T, N, VLS.KK(dw), pfT, hdw31, VLS.kk_lt(dw, hdw), VLS.hyn(dw, N, hN), hsrc(dw, N, hy, hN), htz,',
              'VBE.wob_goU(dw, T, N, pfT, hdw31, hy, hsrc(dw, N, hy, hN), htz,', 'wob_go') if 'VBE.wob_go(' in t else t
    t = re.sub(r'(?m)^(\s*)\+hdw = ok_hd\(dw, T, N, (h|hok)\)\n', lambda m: m.group(0) + f'{m.group(1)}+hy = hyD(dw, T, N, {m.group(2)})\n', t)
    t = re.sub(r'ok_hd\(dw, T, N, h\), ok_hN\(dw, T, N, h\), ok_tz', 'ok_hd(dw, T, N, h), hyD(dw, T, N, h), ok_hN(dw, T, N, h), ok_tz', t)
    t = re.sub(r'VBE\.words_ok_b\(dw, T, N, (\d+), (\d+), VLS\.KK\(dw\), (ok_pf\(dw, T, N, h\)), hdw, VLS\.kk_lt\(dw, hdw\), VLS\.hyn\(dw, N, hN\),',
               r'VBE.words_ok_bU(dw, T, N, \1, \2, \3, hdw, hy,', t)
    t = re.sub(r'VWD\.putw_any(_bytes)?W\(dd, D, X, q, r, dw, T, N, VLS\.KK\(dw\), e, hr, hd, hdw, VLS\.kk_lt\(dw, hdw\), VLS\.hyn\(dw, N, hN\),',
               r'VWD.putw_any\1UW(dd, D, X, q, r, dw, T, N, e, hr, hd, hdw, hy,', t)
    t = re.sub(r'hsrc\(dw, N, hdw, ', 'hsrc(dw, N, hy, ', t)
    t = re.sub(r'W\.specw\((.*?ok_hN\(dw, T, N, hok\)), ', lambda m: f'W.specwD({m.group(1)}, {hw32}, ', t)
    for bad in ('VLS.KK', 'VLS.kk_lt', 'VLS.hyn', 'UW.hsx('):
        assert bad not in t, (bad, [l[:160] for l in t.split('\n') if bad in l][:2])
    if not unb:
        t = t.rstrip('\n') + '\n' + _ok_db(text, t)
    return t


def _ok_db(base, d):
    """okDb: the base's validity gives the D validity (the same chain at depth below 31; a limited list needs no NMAX conjunct)."""
    import okw
    mb = re.search(r'^def OKT\(.*?\) -> Bool:\n?\s*(.*?)\ndef OK\(', base, re.M | re.S)
    md = re.search(r'^def OKT\(.*?\) -> Bool:\n?\s*(.*?)\ndef OK\(', d, re.M | re.S)
    co, cw = okw._conjs(' '.join(mb.group(1).split())), okw._conjs(' '.join(md.group(1).split()))
    assert len(co) == len(cw), (len(co), len(cw))
    n = len(co)
    suf = lambda i, c: c[i] if i == n - 1 else 'Bool.and(' + c[i] + ', ' + suf(i + 1, c) + ')'   # noqa: E731
    lines = ['      +s0 = hok']
    prf = {}
    for i in range(n):
        pi = f'p{i}' if i < n - 1 else f's{n - 1}'
        if i < n - 1:
            lines.append(f'      +p{i} = FD.logic__and_left({co[i]}, {suf(i + 1, co)}, s{i})')
            lines.append(f'      +s{i + 1} = FD.logic__and_right({co[i]}, {suf(i + 1, co)}, s{i})')
        if co[i] == cw[i]:
            prf[i] = pi
        elif co[i] == 'Nat.is_lt(dw, 28n)' and cw[i] == 'Nat.is_lt(dw, 31n)':
            prf[i] = f'FD.nat__lt_trans(dw, 28n, 31n, {pi}, {{==}})'
        else:
            raise AssertionError((co[i], cw[i]))
    res = prf[n - 1]
    for i in range(n - 2, -1, -1):
        res = f'FD.logic__and_intro({cw[i]}, {suf(i + 1, cw)}, {prf[i]}, {res})'
    return ('\n# The base validity (depth below 28) gives this one (below 31): a limited list has no NMAX conjunct.\n'
            'def okDb(+m: B0.MW, +hok: {B0.OK(m) == True{} : Bool}) -> {OK(m) == True{} : Bool}:\n  match m:\n    case B0.MW{+dw, +T, +N}:\n'
            + '\n'.join(lines) + '\n      ' + res + '\n')


def _and_args(s):
    """the two arguments of Bool.and(A, B) (balanced)"""
    assert s.startswith('Bool.and(') and s.endswith(')'), s[:60]
    inner = s[len('Bool.and('):-1]
    d = 0
    for i, c in enumerate(inner):
        if c in '({':
            d += 1
        elif c in ')}':
            d -= 1
        elif c == ',' and d == 0:
            return inner[:i], inner[i + 1:].lstrip()
    raise AssertionError(s)


_DN = {}


def d_names(p):
    """the names the D twin of p defines."""
    if p not in _DN:
        from pathlib import Path
        base = Path(__file__).resolve().parents[1] / 'proofs/obj' / f'encx_{p}.bend'
        t = base.read_text()
        d = d_twin(t, p) if p in CFG else closure_twin(t, p, **CLOSURES[p])
        _DN[p] = set(re.findall(r'^(?:def|law) (\w+)', d, re.M))
    return _DN[p]


def outputs():
    """{path: text} of the D companions, from the base modules on disk."""
    from pathlib import Path
    obj = Path(__file__).resolve().parents[1] / 'proofs/obj'
    out = {}
    for p in CFG:
        base = obj / f'encx_{p}.bend'
        if base.exists():
            out[obj / f'encx_{p}_d.bend'] = d_twin(base.read_text(), p)
    for p, cfg in CLOSURES.items():
        base = obj / f'encx_{p}.bend'
        if base.exists():
            out[obj / f'encx_{p}_d.bend'] = closure_twin(base.read_text(), p, **cfg)
    return out


def main():
    import sys
    if False:   # (the big modules are not generated)
        print('encx D twins: none in this mode')
        return
    out = outputs()
    import retired  # modules nothing imports: not written (codegen/retired.py)
    out = retired.drop(out)
    if '--check' in sys.argv:
        stale = [str(p) for p, t in out.items() if not p.exists() or p.read_text() != t]
        if stale:
            print('stale encx D twins: ' + ', '.join(stale))
            sys.exit(1)
        print('encx D twins are current')
        return
    for p, t in out.items():
        p.write_text(t)
    print(', '.join(q.name for q in out))



