def fixput_text(VLW, fts):
    L = list(VLW.FIX_HEAD) + ['', '# GENERATED by codegen/var_rlist.py (var_laws.put_lemma). Do not edit.',
                              '# The writers of the fixed field types of ExecutionRequests\' records at a word-aligned',
                              '# offset 4 P: the run of word writes VF.updv of the object\'s words.', '']
    for ft in fts:
        L += VLW.put_lemma(ft) + ['']
    return '\n'.join(L) + '\n'


def nest(ft, var, words, ind, plus=True):
    """Nested matches exposing the words of the FT object `var`; returns (lines, indent)."""
    pl = '+' if plus else ''
    lines = []
    if ft.kind == 'u64':
        ws = [f'x{len(words) + k}' for k in range(2)]
        lines.append(' ' * ind + f'match {var}:')
        lines.append(' ' * (ind + 2) + f'case O.U64{{{", ".join(pl + w for w in ws)}}}:')
        words += ws
        return lines, ind + 4
    if ft.kind == 'bytes':
        ws = [f'x{len(words) + k}' for k in range(ft.W)]
        lines.append(' ' * ind + f'match {var}:')
        lines.append(' ' * (ind + 2) + f'case {ft.rep()}{{{", ".join(pl + w for w in ws)}}}:')
        words += ws
        return lines, ind + 4
    fs = [f'{var}_{i}' for i in range(len(ft.kids))]
    lines.append(' ' * ind + f'match {var}:')
    lines.append(' ' * (ind + 2) + f'case {ft.rep()}{{{", ".join(pl + f for f in fs)}}}:')
    ind += 4
    for (c, k), f in zip(ft.kids, fs):
        ls, ind = nest(k, f, words, ind, plus)
        lines += ls
    return lines, ind


def rec_text(VLW, g, rt, walk):
    """RWD, RVW, rparts, rlen, putR of record type rt; walk = (val, sch, proof) over x0.. words, or
    (val, sch, proof, obj): then rparts goes through rpc_<R> over the words (its statement the value
    and object terms themselves) after rewriting RVW_<R>(obj) to the value (rvq_<R>), so the checker
    never compares Codec.parts(RVW_<R>(..), s) with Codec.parts(<value>, s) by running the parts
    (encx_l134217728_PendingPartialWithdrawal's rparts: 1.1 s)."""
    ft = VLW.FT(g, rt)
    R, W = rt.name, ft.W
    obj = walk[3] if len(walk) > 3 else None
    val, sch, proof = walk[:3]
    words = []
    ls, ind = nest(ft, 'r', words, 2)
    body = '\n'.join(ls)
    pad = ' ' * ind
    WL = '[' + ', '.join(words) + ']'
    out = f'''
# ---- {R}: its {W} words, value, parts and writer ----

def RWD_{R}(r: T.{R}) -> List<&2, U32>:
{body}
{pad}{WL}

def RVW_{R}(r: T.{R}) -> S.Value:
{body}
{pad}{val}

@RPARTS

def rlen_{R}(+r: T.{R}) -> {{VF.slen(RWD_{R}(r)) == {W}n : Nat}}:
{body}
{pad}{{==}}

def putR_{R}(+dd: Nat, +D: {TR}, +pos: U32, +P: Nat, +e: {{U32.to_nat(pos) == A.quad(P) : Nat}},
    +hdd: {{Nat.is_lt(dd, 29n) == {TRUE}}}, +pf: {{FD.array__perfect(U32, dd, D) == {TRUE}}},
    +hb: {{Nat.is_le(Nat.add({W}n, P), VB.pw(dd)) == {TRUE}}}, +r: T.{R})
    -> {{T.{R}_put(FD.array__thaw(U32, D), pos, r) == FD.array__thaw(U32, VF.updv(RWD_{R}(r), dd, D, P)) : Array<U32>}}:
{body}
{pad}VT2.put_{ft.p}(dd, D, pos, P, e, hdd, pf, hb, {", ".join(words)})
'''
    RP = f'''def rparts_{R}(+r: T.{R}) -> {{Codec.parts(RVW_{R}(r), {sch}) == Some{{[S.Fixed{{F.limbs(RWD_{R}(r))}}]}} : Maybe<&2, +List<S.Part>>}}:
{body}
{pad}{proof}
'''
    if obj is not None:
        ws_ = ', '.join(f'+{x}: U32' for x in words)
        wa = ', '.join(words)
        RS_ = 'Some{[S.Fixed{F.limbs(RWD_' + R + '(' + obj + '))}]} : Maybe<&2, +List<S.Part>>'
        RP = ('# its parts over the words: the value and the object as terms (rparts rewrites RVW_' + R + ' to the value first)\n'
              f'def rvq_{R}({ws_}) -> {{{val} == RVW_{R}({obj}) : S.Value}}: {{==}}\n'
              f'def rpc_{R}({ws_}) -> {{Codec.parts({val}, {sch}) == {RS_}}}:\n'
              f'  {proof}\n'
              f'def rparts_{R}(+r: T.{R}) -> {{Codec.parts(RVW_{R}(r), {sch}) == Some{{[S.Fixed{{F.limbs(RWD_{R}(r))}}]}} : Maybe<&2, +List<S.Part>>}}:\n'
              f'{body}\n'
              f'{pad}%rvq_{R}({wa}) : {{Codec.parts(_, {sch}) == {RS_}}}\n'
              f'{pad}rpc_{R}({wa})\n')
    out = out.replace('@RPARTS\n', RP, 1)
    return out, ft


