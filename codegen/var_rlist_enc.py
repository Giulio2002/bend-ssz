"""The encoder of ExecutionRequests, for codegen/var_rlist.py.

proofs/obj/var_fix_put_er.bend: the record writers at a word-aligned offset
(var_laws.put_lemma for DepositRequest, WithdrawalRequest, ConsolidationRequest).
proofs/obj/var_rlenc_ExecutionRequests.bend (stock): for each record type the record's
words RWD (by matching), its value RVW and parts, its writer at any aligned offset; for
each list the write loop (the model tree WT of the records' word runs) and the list
writer putv at a header word h and a word position Q.
"""

