def rt_def(name):
    if 'text' not in _rt_cache:
        _rt_cache['text'] = _RT.read_text()
    t = _rt_cache['text']
    m = _re.search(r'^def ' + name + r'\((.*?)\) -> (.*?):\n((?:  .*\n?)+)', t, _re.M)
