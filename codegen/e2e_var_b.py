def split_args(s):
    out, dep, cur, prev = [], 0, '', ''
    for c in s:
        if c in '([{<':
            dep += 1
        elif c in ')]}' or (c == '>' and prev not in '=-'):
            dep -= 1
        prev = c
        if c == ',' and dep == 0:
            out.append(cur.strip())
            cur = ''
        else:
            cur += c
    if cur.strip():
        out.append(cur.strip())
    return out


def call(s):
    m = _re.match(r'([\w.]+)\((.*)\)$', s.strip(), _re.S)
    return (m.group(1), split_args(m.group(2))) if m else (None, None)


