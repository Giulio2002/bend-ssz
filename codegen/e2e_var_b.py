# ---- e2e_rb, flattened: every nesting level's rep destructured in nw_X (its fields are rep's fields),
# the storage fields' witnesses computed there (ww_*) and destructured in nw2_X (a computed value is
# destructured only as a parameter; a nested WIT's innermost pair cannot be destructured at all) ----
class RBFlat:
    def __init__(self, X):
        self.X = X
        self.n = 0
        self.lines, self.eqlines, self.wit, self.params, self.args = [], [], [], [], []
        self.terms = {}
        self.alists = {}

    def fresh(self, b):
        self.n += 1
        return f'{b}{self.n}'

    def level(self, Y, PO, repv, SC):
        w = wit(Y)
        nb, nf = len(w.binders), len(w.fields)
        bn = [self.fresh('a') for _ in range(nb)]
        for (x, ty), a in zip(w.binders, bn):
            self.wit.append((a, ty))
        cur = repv
        for i in range(nb):
            q = self.fresh('q')
            self.lines.append(f'  (+{bn[i]}, {q}) = {cur}')
            cur = q
        eo = self.fresh('eo')
        rs = [self.fresh('r') for _ in range(nf)]
        if nf == 0:
            self.lines.append(f'  +{eo} = {cur}')
        elif nf == 1:
            self.lines.append(f'  (+{eo}, +{rs[0]}) = {cur}')
        else:
            q = self.fresh('q')
            self.lines.append(f'  (+{eo}, {q}) = {cur}')
            cur = q
            for j in range(nf - 1):
                if j == nf - 2:
                    self.lines.append(f'  (+{rs[j]}, +{rs[j + 1]}) = {cur}')
                else:
                    q = self.fresh('q')
                    self.lines.append(f'  (+{rs[j]}, {q}) = {cur}')
                    cur = q
        cons = w.cons
        for (x, _), nm in zip(w.binders, bn):
            cons = _re.sub(r'(?<![\w.])' + x + r'(?![\w])', nm, cons)
        cons = _re.sub(r'(?<![\w.])(pj_\w+)\(o\)', lambda m: f'RT.{m.group(1)}({PO})', cons)
        OT = w.otype
        self.params.append(f'+{eo}: {{{PO} == {cons} : {OT}}}')
        self.args.append(eo)
        steps = []
        for j, (pj, fn, sch, fty) in enumerate(w.fields):
            k, info = field_kind(fn)
            pjt = f'RT.{pj}'.replace('(o)', f'({PO})')
