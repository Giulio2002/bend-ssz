# ---- (i) of the var_bytes_enc names: from rep and the storage premises to the encode laws ----
# Premise per storage field (every nesting level): its invariant at depth below 31 (BL.sdk1 for a byte
# vector, BL.sdk for a byte list, BL.sdpv for a Bytes32 vector); rep gives the fixed fields, the object
# equations and the length bounds. The storage facts become the laws' hypotheses (room from the chunk
# count, a byte list's zero tail from TZ.tz); the object is the laws' OBJE over the fixed fields' words.
class EncX:
    def __init__(self, X, enc):
        self.X, self.enc = X, enc
        self.text = (_OBJ / f'{enc}.bend').read_text()
        ps, _, body = _def_full(self.text, 'OBJE')
        self.P = _params(ps)
        self.pn = [n for n, _ in self.P]
        law = self.text.split('law encode_eval:\n')[1].split('\ndef encode_eval(')[0]
        self.hyps = [(m.group(1), m.group(2)) for m in _re.finditer(r'^  for \+(\w+): (\{.*\})$', law, _re.M)]
        self.rhs = _re.search(r'^  \{.*? == \((OBJE\(.*?\)), (B\.Buf\{.*\})\) : ', law, _re.M).group(2)
        self.lines, self.prem, self.fixed, self.eqs, self.hypv = [], [], [], [], {}
        self.n = 0

    def fresh(self, b):
        self.n += 1
        return f'{b}{self.n}'

    def level(self, Y, PO, repv, SC, obj_fields, amap, text=None):
        """Destructure rep_Y (repv) at object PO, schema SC; obj_fields: the OBJE fields of this level in its
        module's (text) parameter names, amap: those names -> the top parameters' names. Returns the
        equation name {PO == this level's object over the witnesses}."""
        text = text or self.text
        ren = lambda t: _re.sub(r'(?<![\w.])(\w+)(?![\w{(])', lambda m: amap.get(m.group(1), m.group(1)), t) if amap else t
        obj_fields = [ren(f) if not _re.match(r'(O\.BSome\{)?\w+\.OBJE\(', f) else f for f in obj_fields]
        w = wit(Y)
        cons_f = _flat_fields(w.cons)
        assert len(cons_f) == len(obj_fields), (Y, len(cons_f), len(obj_fields))
        nb, nf = len(w.binders), len(w.fields)
        bn = [self.fresh('a') for _ in range(nb)]
        cur = repv
        for i in range(nb):
            self.lines.append(f'  (+{bn[i]}, {self.fresh("q")}) = {cur}')
            cur = f'q{self.n}'
        eo = self.fresh('eo')
        rs = [self.fresh('r') for _ in range(nf)]
        if nf == 0:
            self.lines.append(f'  +{eo} = {cur}')
        elif nf == 1:
            self.lines.append(f'  (+{eo}, +{rs[0]}) = {cur}')
        else:
            self.lines.append(f'  (+{eo}, {self.fresh("q")}) = {cur}')
            cur = f'q{self.n}'
            for j in range(nf - 1):
                if j == nf - 2:
                    self.lines.append(f'  (+{rs[j]}, +{rs[j + 1]}) = {cur}')
                else:
                    self.lines.append(f'  (+{rs[j]}, {self.fresh("q")}) = {cur}')
                    cur = f'q{self.n}'
        sub = lambda t: t.replace('(o)', f'({PO})').replace('(s)', f'({SC})') if PO != 'o' else t.replace('(s)', f'({SC})')
        # the level's equation: PO == CONS (binders named, pj over PO)
        cons = w.cons
        for (x, _), nm in zip(w.binders, bn):
            cons = _re.sub(r'(?<![\w.])' + x + r'(?![\w])', nm, cons)
        cons = _re.sub(r'(?<![\w.])(pj_\w+)\(o\)', lambda m: f'RT.{m.group(1)}({PO})', cons)
        OT = w.otype
        target_f = []   # this level's OBJE-side fields, in order
        steps = []      # (pj text, replacement term, equation name, field type)
        bi = 0
        fi = 0
        for cf, of in zip(cons_f, obj_fields):
            if bi < nb and _re.fullmatch(r'\w+', cf.strip()) and cf.strip() in [x for x, _ in w.binders]:
                # a fixed field: its witness destructured into the OBJE field's words
                idx = [x for x, _ in w.binders].index(cf.strip())
                self.fixed.append((bn[idx], w.binders[idx][1], of))
                target_f.append(of)
                continue
            pj, fn, sch, fty = w.fields[fi]
            r = rs[fi]
            fi += 1
            pjt = f'RT.{pj}'.replace('(o)', f'({PO})')
            scht = sch.replace('(s)', f'({SC})') if True else sch
            scht = _re.sub(r'(?<![\w.])s(?![\w])', SC, sch)
            k, info = field_kind(fn)
            if k == 'words':
                m = _re.match(r'O\.Words\{FD\.array__thaw\(U32, (\w+)\), (\w+)\}$', of)
                T, LEN = m.groups()
                sfx = T[1:]
                kind = {'WO.rep_bv': 'bv', 'LO.rep_bl': 'bl', 'PV.rep_pv': 'pv'}[fn]
                pv = self.fresh('hs')
                self.lines.append(f'  (+wf{sfx}, +nb{sfx}) = {r}')
                self.prem.append((pv, {'bv': 'BL.sdk1', 'bl': 'BL.sdk', 'pv': 'BL.sdpv'}[kind] + f'({pjt}, 31n)', kind, pjt, T, 'd' + sfx, LEN, sfx, r, scht))
                target_f.append(of)
                steps.append((pjt, f'O.Words{{FD.array__thaw(U32, {T}), {LEN}}}', f'ew_{sfx}', 'O.Words'))
            elif k == 'rbox':
                m = _re.match(r'O\.BSome\{(\w+)\.OBJE\((.*)\), O\.BNone\{\}\}$', of)
                al, args = m.groups()
                subenc = _re.search(r'^import \./(\S+)\.bend as ' + al + '$', text, _re.M).group(1)
                subtext = (_OBJ / f'{subenc}.bend').read_text()
                sps, _, sbody = _def_full(subtext, 'OBJE')
                spn = [n for n, _ in _params(sps)]
                sa = split_args(args)
                amap2 = {a_: amap.get(b_, b_) for a_, b_ in zip(spn, sa)}
                eb, ri = self.fresh('eb'), self.fresh('ri')
                self.lines.append(f'  (+{eb}, +{ri}) = {r}')
                inner = f'RT.pjb_{info}_bx({pjt})'
                isch = _re.sub(r'(?<![\w.])s(?![\w])', SC, sch)
                e_in = self.level(info, inner, ri, isch, _flat_fields(sbody), amap2, subtext)
                tin = self.level_terms[inner]
                BT = f'O.Boxed<{wit(info).otype}>'
                ob = f'O.BSome{{{tin}, O.BNone{{}}}}'
                ename = self.fresh('ex')
                self.eqs.append(f'  +{ename} = Equal.trans({BT}, {pjt}, O.BSome{{{inner}, O.BNone{{}}}}, {ob}, {eb}, Equal.cong({wit(info).otype}, {BT}, z => O.BSome{{z, O.BNone{{}}}}, {inner}, {tin}, {e_in}))')
                self.subimports.append((al, subenc))
                target_f.append(of)
                steps.append((pjt, ob, ename, BT))
            elif k == 'rec':
                m = _re.match(r'(\w+)\.OBJE\((.*)\)$', of)
                al, args = m.groups()
                subenc = _re.search(r'^import \./(\S+)\.bend as ' + al + '$', text, _re.M).group(1)
                subtext = (_OBJ / f'{subenc}.bend').read_text()
                sps, _, sbody = _def_full(subtext, 'OBJE')
                amap2 = {a_: amap.get(b_, b_) for a_, b_ in zip([n for n, _ in _params(sps)], split_args(args))}
                isch = _re.sub(r'(?<![\w.])s(?![\w])', SC, sch)
                e_in = self.level(info, pjt, r, isch, _flat_fields(sbody), amap2, subtext)
                self.subimports.append((al, subenc))
                target_f.append(of)
                steps.append((pjt, self.level_terms[pjt], e_in, wit(info).otype))
            elif k == 'dbox':
                m = _re.match(r'O\.BSome\{(.*), O\.BNone\{\}\}$', of)
                v, ev = self.fresh('v'), self.fresh('ev')
                self.lines.append(f'  (+{v}, +{ev}) = {r}')
                self.fixed.append((v, info, m.group(1)))
                target_f.append(of)
                steps.append((pjt, f'O.BSome{{{v}, O.BNone{{}}}}', ev, _wtype(fty)))
            else:
                raise SystemExit(f'EncX {Y}: field kind {k}')
        # PO == CONS -> PO == OBJE term: replace fixed binders by their patterns (they are matched in c2),
        # and the pj's step by step
        c0 = cons
        eq = eo
        for pjt, rep_t, en, fty in steps:
            c1 = c0.replace(pjt, rep_t, 1)
            hole = c0.replace(pjt, 'z', 1)
            en2 = self.fresh('c')
            self.eqs.append(f'  +{en2} = Equal.trans({OT}, {PO}, {c0}, {c1}, {eq}, Equal.cong({fty}, {OT}, z => {hole}, {pjt}, {rep_t}, {en}))')
            c0, eq = c1, en2
        self.level_terms = getattr(self, 'level_terms', {})
        self.level_terms[PO] = c0
        return eq


