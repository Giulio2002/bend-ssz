# ---- views of the byte-offset windows (var_bytes_<X>_win: OBJw(t, i, len), VALw(t, i, len)) ----
# vw: RT.v_X(OBJw(t, i, len)) == VALw(t, i, len) at any word offset i. The window's object with its
# variable parts as holes (OBJH) views as XVw over the holes' values (vz: rewrite each hole's view,
# then evaluate the fixed fields); vw fills the holes.
