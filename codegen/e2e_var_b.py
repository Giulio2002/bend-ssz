def _def_full(text, name):
    m = _re.search(r'^def ' + name + r'\((.*?)\) -> (.*?): (.*)$', text, _re.M)
    return m.group(1), m.group(2), m.group(3)


def _params(ps):
    return [(p.split(':')[0].strip().lstrip('+-'), p.split(':', 1)[1].strip()) for p in split_args(ps)]


def _ctor_args(term):
    m = _re.match(r'([\w.]+)\{(.*)\}$', term.strip(), _re.S)
    return m.group(1), split_args(m.group(2))


def _flat_fields(body):
    c, args = _ctor_args(body)
    out = []
    for a in args:
        m = _re.match(r'([\w.]+)\{', a)
        if m and _re.search(r'_g\d+$', m.group(1)):
            out += _ctor_args(a)[1]
        else:
            out.append(a)
    return out


