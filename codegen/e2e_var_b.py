                    holes.append(dict(obj=f, ty='O.Words', view='WO.wview', vty='+List<U32>', val=val, pf=f'BL.wbv({T}, {d}, {K}n, {LEN}, pf{sfx}, hr{sfx}, {{==}})', xey=None))
