def _defline(text, name):
    m = _re.search(r'^def ' + name + r'\((.*?)\) -> (.*?): (.*)$', text, _re.M)
    return m.group(1), m.group(2), m.group(3)


def _d_imports(text, body):
    return [l.replace('import ../../', 'import ../') for l in text.splitlines()
            if _re.match(r'import \.\./\.\./types/\S+ as (\w+_d)$', l) and _re.search(r'(?<![\w.])' + l.split()[-1] + r'\.', body)]


# holes: dicts {'obj': the part's text in OBJw, 'ty': its type, 'arg': the part at the call (W.-qualified),
# 'view': the view function of the part, 'vty': the view's type, 'val': the view's value (at the call),
# 'pf': the proof of view(arg) == val, and either 'xv': the XVw parameter it fills or 'xvt': its value's text
# inside XVw's body}. Bit vectors inside the object are found and made holes automatically.
def _bv_holes(body, xbody, qual=''):
    out = []
    for m in _re.finditer(r'(Fulu_bitvector_(\d+)_d)\.Bitvector\d+\{([^{}]*)\}', body):
        al, nbits, ws = m.group(1), int(m.group(2)), m.group(3)
        val = f'S.BitsValue{{FB.bitsof([{ws}])}}'
        assert val in xbody, ('bitvector value', nbits)
        out.append({'obj': m.group(0), 'ty': f'{al}.Bitvector{nbits}', 'arg': _qualw(m.group(0), qual), 'view': f'RN.v_bv{nbits}', 'vty': 'S.Value',
                    'val': _qualw(val, qual), 'xvt': val, 'pf': f'BV.bvh{nbits}({_qualw(ws, qual)})'})
    return out


def _qualw(t, qual):
    return t


def vw_module(X, win, holes, xvp, extra_imports=()):
    """xvp(ys): XVw's parameters after (t, i), over the param holes' values (in order)."""
    text = (_OBJ / f'{win}.bend').read_text()
    _, oty, body = _defline(text, 'OBJw')
    xps, _, xbody = _defline(text, 'XVw')
    holes = list(holes) + _bv_holes(body, xbody)
    zs = [f'z{k}' for k in range(len(holes))]
    ys = [f'Y{k}' for k in range(len(holes))]
    bh = body
    for h, z in zip(holes, zs):
        assert bh.count(h['obj']) == 1, (X, h['obj'])
        bh = bh.replace(h['obj'], z)
    xh = xbody
    inb = [(h, y) for h, y in zip(holes, ys) if 'xvt' in h]
    for h, y in inb:
        assert xh.count(h['xvt']) == 1, (X, h['xvt'])
        xh = xh.replace(h['xvt'], y)
    own = set(_re.findall(r'^def (\w+)\(', text, _re.M))
    qual = lambda t: _re.sub(r'(?<![\w.])(' + '|'.join(sorted(own, key=len, reverse=True)) + r')\(', r'W.\1(', t) if own else t
    imps = ['import Base', 'import ../src/obj.bend as O', 'import ../types/schema.bend as S', 'import ../types/primitive.bend as P',
            'import ../proofs/compact/found.bend as FD', 'import ../proofs/obj/spec_fixed.bend as F', 'import ../proofs/obj/vbuf.bend as VB',
            'import ../proofs/obj/vcopy.bend as VC', 'import ../proofs/obj/words_obj.bend as WO', 'import ../proofs/obj/root_types.bend as RT',
            f'import ../proofs/obj/{win}.bend as W', 'import ./e2e_blist.bend as BL'] + list(extra_imports)
    if inb:
        imps += ['import ../proofs/obj/spec_bits.bend as FB', 'import ../proofs/obj/root_names.bend as RN', 'import ./e2e_bvh.bend as BV']
    imps += _d_imports(text + '\n' + _RT.read_text(), body + oty + xbody + ' '.join(h['ty'] for h in holes))
    extra_x = [n for n, _ in _params(xps)][2:]
    zp = ', '.join(f'{z}: {h["ty"]}' for z, h in zip(zs, holes))
    L = ['\n'.join(dict.fromkeys(imps)), '',
         '# GENERATED by codegen/e2e_bridge.py (codegen/e2e_var_b.py). Do not edit.',
         f'# {X}\'s byte-offset window ({win}): the root view of the object it reads is its value at any',
         '# word offset i (vw). OBJH is the window\'s object with its variable parts as holes, XVH its value over them',
         '# (vz: each hole\'s view rewritten to its value, the fixed fields by evaluation).', '',
         f'def OBJH(+t: FD.array__Tree<U32>, +i: Nat, {zp}) -> {oty}: {qual(bh)}', '',
         f'def XVH({xps}{"".join(f", +{y}: {h[chr(118) + chr(116) + chr(121)]}" for h, y in inb)}) -> S.Value: {qual(xh)}', '']
    phs = [(h, y) for h, y in zip(holes, ys) if 'xvt' not in h]
    def rhs(vals):
        pv = [v for h, v in zip(holes, vals) if 'xvt' not in h]
        iv = [v for h, v in zip(holes, vals) if 'xvt' in h]
        return f'XVH(t, i, {", ".join(xvp(pv) + iv)})'
    hyps = ', '.join(f'{z}: {h["ty"]}, +{y}: {h["vty"]}, +e{k}: {{{h["view"]}({z}) == {y} : {h["vty"]}}}' for k, (z, y, h) in enumerate(zip(zs, ys, holes)))
    L.append(f'def vz(+t: FD.array__Tree<U32>, +i: Nat, {hyps}) -> {{RT.v_{X}(OBJH(t, i, {", ".join(zs)})) == {rhs(ys)} : S.Value}}:')
    for k in range(len(holes)):
        cur = [f'{holes[j]["view"]}({zs[j]})' if j < k else ('_' if j == k else ys[j]) for j in range(len(holes))]
        L.append(f'  %e{k} : {{RT.v_{X}(OBJH(t, i, {", ".join(zs)})) == {rhs(cur)} : S.Value}}')
