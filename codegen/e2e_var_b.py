def rt_def(name):
    if 'text' not in _rt_cache:
        _rt_cache['text'] = _RT.read_text()
    t = _rt_cache['text']
    m = _re.search(r'^def ' + name + r'\((.*?)\) -> (.*?):\n  (.*)$', t, _re.M)
    if m:
        return m.group(1), m.group(2), m.group(3)
    m = _re.search(r'^def ' + name + r'\((.*?)\) -> (.*?): (.*)$', t, _re.M)
    return (m.group(1), m.group(2), m.group(3)) if m else None


def rep_info(Y):
    """(binders [(x, type)], CONS, otype, fields [(pj, rep call name, schema, field type)])."""
    params, _, body = rt_def('rep_' + Y)
    otype = _re.match(r'o: (.*), \+s: S\.Schema$', params).group(1)
    binders = []
    while body.startswith('DK.Ex('):
        n, a = call(body)
        ty, lam = a
        x, rest = _re.match(r'(\w+) => (.*)$', lam, _re.S).groups()
        binders.append((x, ty))
        body = rest
    n, a = call(body) if body.startswith('DK.P2(') else (None, [body, None])
    eq, rest = a
    cons = _re.match(r'\{o == (.*) : ' + _re.escape(otype) + r'\}$', eq, _re.S).group(1)
    fields = []
    while rest is not None:
        if rest.startswith('DK.P2('):
            _, (f, rest) = call(rest)
        else:
            f, rest = rest, None
        fn, fa = call(f)
        pj = fa[0]
        pjn = call(pj)[0]
        fty = rt_def(pjn)[1]
        fields.append((pj, fn, fa[1], fty))
    return binders, cons, otype, fields


def field_kind(fn):
    if fn in WORDS_KINDS:
        return ('words', None)
    if fn.startswith('rep_') and fn.endswith('_bx'):
        body = rt_def(fn)[2]
        if body.startswith('DK.Ex('):
            _, (ty, _) = call(body)
            return ('dbox', ty)
        Z = fn[4:-3]
        return ('rbox', Z)
    if fn.startswith('rep_') and rt_def(fn):
        return ('rec', fn[4:])
    raise SystemExit(f'e2e_var_b: unknown field invariant {fn}')


class Wit:
    """Y's witnesses: [(type)], and BUILD_Y over witness names."""
    def __init__(self, Y):
        self.Y = Y
        binders, cons, otype, fields = rep_info(Y)
        self.otype, self.binders, self.cons, self.fields = otype, binders, cons, fields
        self.tys = [ty for _, ty in binders]
        self.parts = []  # per field: (kind, info, slice of witness indices)
        for pj, fn, sch, fty in fields:
            k, info = field_kind(fn)
            i0 = len(self.tys)
            if k == 'words':
                self.tys += ['FD.array__Tree<U32>', 'U32']
            elif k == 'dbox':
                self.tys += [info]
            else:
                sub = wit(info)
                self.tys += sub.tys
            self.parts.append((k, info, list(range(i0, len(self.tys)))))

    def field_term(self, j, names):
        k, info, idx = self.parts[j]
        ns = [names[i] for i in idx]
        if k == 'words':
            return f'O.Words{{FD.array__thaw(U32, {ns[0]}), {ns[1]}}}'
        if k == 'dbox':
            return f'O.BSome{{{ns[0]}, O.BNone{{}}}}'
        if k == 'rbox':
            return f'O.BSome{{{wit(info).build(ns)}, O.BNone{{}}}}'
        return wit(info).build(ns)

    def cons_with(self, names, upto, o='o'):
        """CONS with the binders named and fields < upto replaced by their witness terms."""
        c = self.cons
        for (x, _), nm in zip(self.binders, names):
            c = _re.sub(r'(?<![\w.])' + x + r'(?![\w])', nm, c)
        for j in range(upto):
            c = c.replace(self.fields[j][0], self.field_term(j, names), 1)
        if o != 'o':
            c = c.replace('(o)', f'({o})')
        return c

    def build(self, names):
        return self.cons_with(names, len(self.fields))


