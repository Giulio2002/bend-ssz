def bvn_mod(N, HEAD, sig, TR, TRUE):
    """Bitvector[N] (N <= 8, one byte) of the generic containers at any byte position: the reader
    keeps the low byte of the four-byte read at x (vedge.bend: only that byte need be in the
    buffer). For N < 8 the validator checks bits N..7 of the byte clear (CHK) and prt holds under
    CHK; for N = 8 every byte is a value (its high bits are clear: the window's bytes are bytes)."""
    import itertools
    chk = N < 8
    p = f'bv{N}'
    Tn = f'T.Bitvector{N}'
    P = 'A.quad(VB.pw(d))'
    SCH = f'S.BitVector{{{N}n}}'
    B_ = lambda b: 'True{}' if b else 'False{}'
    MP = 'Maybe<&2, +List<S.Part>>'
    a = [f'a{i}' for i in range(32)]

    def word(bits):
        t = 'WNil{}'
        for x in reversed(bits):
            t = f'WCon{{{x}, {t}}}'
        return f'U32{{{t}}}'
    L = generic_head(HEAD) + ['', '# GENERATED by codegen/var_fixx.py (codegen/var_fixx_gen.py). Do not edit.',
                              f'# {p} (Bitvector[{N}], one byte) of the generic containers at any byte position: see codegen/var_fixx_gen.py.', '']
    w = L.append
    w(common(TR, TRUE))
    if chk:
        w(f"""# the validator's check (bits {N}..7 of the byte clear)
def CHKv(+v: U32) -> Bool: U32.is_eq(U32.and(v, U32.not(O.low_mask({N}))), 0)
def CHK(+t: {TR}, +x: Nat) -> Bool: CHKv(BX(t, x))
""")
    w(f"""def OBJ(+d: Nat, +t: {TR}, +x: Nat) -> {Tn}: {Tn}{{O.keep(1, UR.RWN(t, x))}}

# (the four-byte read keeps the byte at x: x + 1 <= 4 2^d; vedge.bend)
{sig('rdx', 1)}
    -> {{T.{p}_read(UA.BF(t, n), off, 1) == (UA.BF(t, n), OBJ(d, t, x)) : B.Buf & {Tn}}}:
  +hb1 = FD.logic__subst(Nat, z => {{Nat.is_le(Nat.add(z, 1n), {P}) == {TRUE}}}, x, U32.to_nat(off), Equal.sym(Nat, U32.to_nat(off), x, e), hb)
  %Equal.sym(B.Buf & U32, B.read32(UA.BF(t, n), off), (UA.BF(t, n), VE.RV(t, n, off)), VE.rd_same(t, n, off)) :
    {{T.{p}_r0(off, _) == (UA.BF(t, n), OBJ(d, t, x)) : B.Buf & {Tn}}}
  %Equal.sym(U32, O.keep(1, VE.RV(t, n, off)), O.keep(1, UA.RW(t, off)), VE.kv1(d, t, n, off, FD.nat__lt_trans(d, 28n, 31n, hd, {{==}}), pf, hb1)) :
    {{(UA.BF(t, n), {Tn}{{_}}) == (UA.BF(t, n), OBJ(d, t, x)) : B.Buf & {Tn}}}
  %Equal.sym(U32, UA.RW(t, off), UR.RWN(t, U32.to_nat(off)), UR.rw_n(t, off)) : {{(UA.BF(t, n), {Tn}{{O.keep(1, _)}}) == (UA.BF(t, n), OBJ(d, t, x)) : B.Buf & {Tn}}}
  %Equal.sym(Nat, U32.to_nat(off), x, e) : {{(UA.BF(t, n), {Tn}{{O.keep(1, UR.RWN(t, _))}}) == (UA.BF(t, n), OBJ(d, t, x)) : B.Buf & {Tn}}}
  {{==}}
""")
    if chk:
        w(f"""# the validator on the byte at off returns CHK
{sig('ok', 1)}
    -> {{T.{p}_ok_at(UA.BF(t, n), off) == (UA.BF(t, n), CHK(t, x)) : B.Buf & Bool}}:
  +e0 = Equal.trans(Nat, U32.to_nat(U32.add(off, 0)), Nat.add(x, 0n), x, VXG.offc(d, off, 0, 0n, x, 1n, e, hd, {{==}}, {{==}}, hb), FD.nat__add_zero(x))
  +hi = VR.hiX(d, U32.add(off, 0), x, e0, VXG.ltx(x, 1n, {P}, {{==}}, hb))
  %Equal.sym(B.Buf & U32, B.byte_at(UA.BF(t, n), U32.add(off, 0)), (UA.BF(t, n), VR.VX(t, U32.add(off, 0))), VR.byte_at_ok(d, t, n, U32.add(off, 0), FD.nat__lt_trans(d, 28n, 32n, hd, {{==}}), hi, pf)) :
    {{O.pad_pick({N}, _) == (UA.BF(t, n), CHK(t, x)) : B.Buf & Bool}}
  %Equal.sym(U32, VR.VX(t, U32.add(off, 0)), BX(t, x), vx_bx(t, U32.add(off, 0), x, e0)) :
    {{O.pad_pick({N}, (UA.BF(t, n), _)) == (UA.BF(t, n), CHK(t, x)) : B.Buf & Bool}}
  {{==}}
""")
    pat = ''.join(f'WCon{{{a[i]}, ' for i in range(N)) + 'r' + '}' * N
    w(f"""# the {N} low bits
def VBN(v: U32) -> S.Value:
  match v:
    case U32{{{pat}}}: S.BitsValue{{[{', '.join(a[:N])}]}}
def VAL(+t: {TR}, +x: Nat) -> S.Value: VBN(BX(t, x))
""")
    goalv = lambda v: f'{{Codec.parts(VBN({v}), {SCH}) == Some{{[S.Fixed{{[{v}]}}]}} : {MP}}}'
    w(f"# the value's parts are the byte, when bits {N}..31 are clear: by cases on the bits, highest first,")
    w(f"# then the {N} low bits")
    zw = lambda i: word(a[:i + 1] + ['False{}'] * (31 - i))
    w(f'def z{N - 1}({", ".join("+" + x + ": Bool" for x in a[:N])}) -> {goalv(zw(N - 1))}:')
    w(f'  match {" ".join(a[:N])}:')
    for lo in itertools.product([False, True], repeat=N):
        w(f'    case {" ".join(B_(b) for b in lo)}: {{==}}')
    for i in range(N, 32 if chk else N):
        ps = ", ".join("+" + x + ": Bool" for x in a[:i + 1])
        w(f'def z{i}({ps}, +h: {{CHKv({zw(i)}) == {TRUE}}}) -> {goalv(zw(i))}:')
        w(f'  match {a[i]}:')
        wt = word(a[:i] + ['True{}'] + ['False{}'] * (31 - i))
        w(f'    case True{{}}: Empty.absurd({goalv(wt)}, FD.logic__false_true(h))')
        nxt = f'z{i - 1}({", ".join(a[:i])})' if i == N else f'z{i - 1}({", ".join(a[:i])}, h)'
        w(f'    case False{{}}: {nxt}')
    w('')
    if chk:
        w(f'def bvp(+v: U32, +h: {{CHKv(v) == {TRUE}}}) -> {goalv("v")}:')
        w('  match v:')
