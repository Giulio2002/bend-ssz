# from this many bytes the checker must not compare a size in unary (the rigid checker's stack gives out between
# 4096 and 8192 levels of a Nat comparison)
BIG = 2048


def pow2_of(n):
    """b when n = 2^b is a large power of two (a word array whose arithmetic must stay symbolic)"""
    if n >= BIG and n & (n - 1) == 0:
        return n.bit_length() - 1
    return None


def words_depth(n):
    w = ((n + 31) // 32) * 8 + 8
    return (w - 1).bit_length()


