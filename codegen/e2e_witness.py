PREFER = {}   # path -> the alias the bridge file gives it


def canon(path):
    p = Path(path).resolve()
    if p in PREFER:
        return PREFER[p]
    rel = p.relative_to(ROOT).as_posix()
    m = re.match(r'types/(\w+)_def_generated\.bend$', rel)
    if m:
        return m.group(1) + '_d'
    return 'W_' + re.sub(r'\W', '_', rel[:-len('.bend')])


_DECLS = {}   # id(mod) -> (mod, the type and constructor names its text declares)


def _decl_names(mod):
    """the names `^type N` and `^  N{` declare in mod.text (one scan per module: lift asked per token, which made
    e2e_compose quadratic, 150 of its 157 s)"""
    e = _DECLS.get(id(mod))
    if e is None or e[0] is not mod:
        e = _DECLS[id(mod)] = (mod, set(re.findall(r'^type (\w+)\b', mod.text, re.M)) | set(re.findall(r'^  (\w+)\{', mod.text, re.M)))
    return e[1]


class Ctx:
    """the imports the witness file needs, by canonical alias"""

    def __init__(self):
        self.used = {}

    def alias(self, path):
        a = canon(path)
        self.used[a] = Path(path).resolve()
        return a

    def lift(self, mod, expr):
        """an expression of module mod, with its aliases made canonical (bare names of mod qualified)"""
        def sub(m):
            q = m.group(0)
            if '.' in q:
                a, rest = q.split('.', 1)
                if a in mod.imports:
                    return self.alias(mod.imports[a]) + '.' + rest
                return q
            if q in mod.defs or q in _decl_names(mod):
                return self.alias(mod.path) + '.' + q
            return q
        return re.sub(r'(?<![\w.])[A-Za-z_]\w*(?:\.\w+)?', sub, expr)


def model_of(ctx, mod, expr):
    """the model of a default-valued expression written in module mod (its .expr: the expression, lifted)"""
    m = model_of_(ctx, mod, expr)
    m.expr = ctx.lift(mod, expr)
    return m


def model_of_(ctx, mod, expr):
    c = parse_call(expr)
    if c is None:
        raise SystemExit(f'e2e_witness: no model for {expr!r} ({mod.path.name})')
    fn, args = c
    if fn == 'O.words_new':
        return Words(int(args[0]))
    m2, name = mod.resolve(fn)
    if m2 is None or name not in m2.defs:
        raise SystemExit(f'e2e_witness: no def {fn} ({mod.path.name})')
    params, ret, body = m2.signature(name)
    if params:
        raise SystemExit(f'e2e_witness: default with params {fn}')
    b = body.strip()
    if b.startswith('O.words_new('):
        return Words(int(parse_call(b)[1][0]))
    mbits = re.fullmatch(r'O\.Bits\{Array\.new\(U32, (\d+)n, 0\), (\d+)\}', b)
    if mbits:
        return BitsM(int(mbits.group(1)), int(mbits.group(2)))
    mb = parse_call(b)
    if mb and mb[0].endswith('_bx_wrap'):
        return Box(model_of(ctx, m2, mb[1][0]), ctx.lift(m2, mb[1][0]))
    ms = re.match(r'(\w+)\{(.*)\}$', b, re.S)
    if ms and ms.group(1).endswith('_Seq'):
        items = split_top(ms.group(2))
        if items[1].strip() != '0':
            n = int(items[1].strip())
            fill = parse_call(items[0])
            fb = m2.signature(fill[0])[2].strip() if fill and fill[0] in m2.defs else ''
            mf = re.match(r'Array\.new\(([^,]+), d, (.*)\)$', fb)
            if not mf:
                raise SystemExit(f'e2e_witness: nonempty default list {fn}')
            el = model_of(ctx, m2, mf.group(2))
            return VecN(el, el.expr, ctx.lift(m2, mf.group(1)), n, (n - 1).bit_length())
        return EList((m2, items[0]))
    if ms and all(parse_call(a) for a in split_top(ms.group(2))):
        fields = []
        for a in split_top(ms.group(2)):
            sub = model_of(ctx, m2, a)
            if isinstance(sub, Cont) and sub.tname.startswith(ms.group(1) + '_g'):
                fields.extend(sub.fields)      # a group of a grouped container
            else:
                fields.append((ctx.lift(m2, a), sub))
        return Cont(m2, ms.group(1), fields)
    return Leaf(ctx.lift(m2, b))


# the element size in bytes of a byte or packed list module (its default is O.words_new(0))
def words_list_elem(path):
    n = Path(path).name
    m = re.match(r'Fulu_bytelist_\d+_def_generated\.bend$', n)
    if m:
        return 1
    m = re.match(r'Fulu_list_uint(\d+)_\d+_def_generated\.bend$', n)
    if m:
        return int(m.group(1)) // 8
    m = re.match(r'Fulu_list_bytevec_(\d+)_\d+_def_generated\.bend$', n)
    if m:
        return int(m.group(1))
    return None


def model_ne(ctx, mod, expr, lists=True):
    """the model of the non-empty object built from the default expression expr of module mod: every list
    reachable through containers and boxes holds one element (lists=False: lists stay empty). A vector of
    boxed elements (whose default holds empty boxes, BNone) holds valid ones (_bx_default()), in both
    modes. Its .expr is the object's expression."""
    c = parse_call(expr)
    if c is None:
        raise SystemExit(f'e2e_witness: no model for {expr!r} ({mod.path.name})')
    fn, args = c
    m2, name = mod.resolve(fn)
    if fn == 'O.words_new' or m2 is None or name not in m2.defs:
        return model_of(ctx, mod, expr)
    params, ret, body = m2.signature(name)
    b = body.strip()
    if b == 'O.words_new(0)' and words_list_elem(m2.path) and lists:
        k = words_list_elem(m2.path)
        m = Words(k)
        m.expr = f'O.words_new({k})'
        m.changed = True
        return m
    mb = parse_call(b)
    if mb and mb[0].endswith('_bx_wrap'):
        inner = model_ne(ctx, m2, mb[1][0], lists)
        if not getattr(inner, 'changed', False):
            return model_of(ctx, mod, expr)
        m = Box(inner, inner.expr)
        m.expr = f'{ctx.lift(m2, mb[0])}({inner.expr})'
        m.changed = True
        return m
    ms = re.match(r'(\w+)\{(.*)\}$', b, re.S)
    if ms and ms.group(1).endswith('_Seq'):
        items = split_top(ms.group(2))
        fill = parse_call(items[0])
        mw = re.search(r'Array\.set\([^,]+, arr, i, ([\w.]+_bx_wrap)\(v\)\)', m2.text)
        if items[1].strip() != '0':
            # a vector: its length is fixed; boxed elements must be valid (the default's are empty boxes)
            if not mw:
                return model_of(ctx, mod, expr)
            n = int(items[1].strip())
            d = (n - 1).bit_length()
            ty = ctx.lift(m2, re.match(r'Array<(.*)>$', m2.signature(fill[0])[1].strip()).group(1))
            el = model_of(ctx, m2, mw.group(1)[:-len('_bx_wrap')] + '_bx_default()')
            items_e = f'ALeaf{{{el.expr}}}'      # the array of 2^d copies, written out (boxes are not Data)
            for _ in range(d):
                items_e = f'ANode{{{items_e}, {items_e}}}'
            m = VecN(el, el.expr, ty, n, d)
            m.items = items_e
            m.expr = f'{ctx.lift(m2, ms.group(1))}{{{items_e}, {n}}}'
            m.changed = True
            return m
        if not lists:
            return model_of(ctx, mod, expr)
        mw = re.search(r'Array\.set\([^,]+, arr, i, ([\w.]+_bx_wrap)\(v\)\)', m2.text)
        if mw:
            wm, wn = m2.resolve(mw.group(1))
            eexpr_local = mw.group(1)[:-len('_bx_wrap')] + '_bx_default()'
        else:
            fb = m2.signature(fill[0])[2].strip()
            mf = re.match(r'Array\.new\(([^,]+), d, (.*)\)$', fb)
            if not mf:
                raise SystemExit(f'e2e_witness: no element default for {fn} ({m2.path.name})')
            eexpr_local = mf.group(2)
        elem = model_of(ctx, m2, eexpr_local)
        m = OneList(elem, elem.expr)
        m.expr = f'{ctx.lift(m2, ms.group(1))}{{ALeaf{{{elem.expr}}}, 1}}'
        m.changed = True
        return m
    if ms and all(parse_call(a) for a in split_top(ms.group(2))):
        fields, parts, changed = [], [], False
        for a in split_top(ms.group(2)):
            sub = model_ne(ctx, m2, a, lists)
            changed |= getattr(sub, 'changed', False)
            parts.append(sub.expr)
            if isinstance(sub, Cont) and sub.tname.startswith(ms.group(1) + '_g'):
                fields.extend(sub.fields)
            else:
                fields.append((sub.expr, sub))
        if not changed:
            return model_of(ctx, mod, expr)
        m = Cont(m2, ms.group(1), fields)
        m.expr = f'{ctx.lift(m2, ms.group(1))}{{{", ".join(parts)}}}'
        m.changed = True
        return m
    return model_of(ctx, mod, expr)


def nat_value(e):
    """the value of a closed numeral expression (Nn, N, U32.to_nat(N), 1n+..), else None"""
    e = e.strip()
    m = re.fullmatch(r'(\d+)n?', e)
    if m:
        return int(m.group(1))
    m = re.fullmatch(r'U32\.to_nat\((.*)\)', e)
    if m:
        return nat_value(m.group(1))
    m = re.fullmatch(r'1n\+(.*)', e)
    if m:
        v = nat_value(m.group(1))
        return None if v is None else v + 1
    return None


def parse_match(body):
    """(scrutinee, [(pattern, branch text)]) of a def body `match x:` with its cases, else None"""
    lines = body.split('\n')
    m = re.fullmatch(r'match (\w+):', lines[0].strip())
    if not m:
        return None
    rest = [l for l in lines[1:] if l.strip()]
    if not rest:
        return None
    ind = len(rest[0]) - len(rest[0].lstrip())
    cases, cur = [], None
    for l in rest:
        li = len(l) - len(l.lstrip())
        if li == ind:
            mc = re.match(r'\s*case (.*?): ?(.*)$', l)
            if not mc:
                return None
            cur = [mc.group(1).strip(), [mc.group(2)] if mc.group(2).strip() else []]
            cases.append(cur)
        elif li > ind and cur is not None:
            cur[1].append(l)
        else:
            return None
    out = []
    for pat, bl in cases:
        if len(bl) > 1 or (bl and bl[0] != bl[0].lstrip()):
            k = min(len(x) - len(x.lstrip()) for x in bl)
            text = '\n'.join(x[k:] for x in bl)
        else:
            text = bl[0].strip() if bl else ''
        out.append((pat, text.strip()))
    return m.group(1), out


