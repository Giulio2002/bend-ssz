def szr_term(syn, mod, pt, at_d):
    """the total-size premise {Nat.is_lt(SZR(U32.to_nat(F), t0, ..), pw(31n)) == True} with a large fixed part F:
    SZR adds on its first argument, so evaluating it walks F once per term; a lemma reassociates the sum to
    t0 + .. + tn + F first (F stays a U32 in the proof term)"""
    m = re.match(r'\{Nat\.is_lt\(SZR\((.*)\), VB\.pw\(31n\)\) == True\{\} : Bool\}$', pt, re.S)
    if not m:
        return None
    args = split_top(m.group(1))
    mf = re.match(r'U32\.to_nat\((\d+)\)$', args[0])
    if not mf or int(mf.group(1)) < BIG:
        return None
    ts = [f't{i}' for i in range(len(args) - 1)]
    S = ts[0]
    for t in ts[1:]:
        S = f'Nat.add({S}, {t})'
    F = 'U32.to_nat(x)'
    # A_k = add(..add(add(F, t0), t1).., tk) is add(F, S_k), by one reassociation per term
    lines = []
    Sk = [ts[0]]
    for t in ts[1:]:
        Sk.append(f'Nat.add({Sk[-1]}, {t})')
    for k in range(1, len(ts)):
        inner = f'_'
        ctx = inner
        for t in ts[k + 1:]:
            ctx = f'Nat.add({ctx}, {t})'
        lhs = f'Nat.add(Nat.add({F}, {Sk[k - 1]}), {ts[k]})'
        rhs = f'Nat.add({F}, {Sk[k]})'
        lines.append(f'  %Equal.sym(Nat, {lhs}, {rhs}, FD.nat__add_assoc({F}, {Sk[k - 1]}, {ts[k]})) : {{{ctx} == Nat.add({F}, {S}) : Nat}}')
    params = ', '.join(f'+{t}: Nat' for t in ts)
    nm = 'szr_sum'
    syn.lemmas['x000_' + nm] = (f'# SZR(F, t0, .., tn) = F + (t0 + .. + tn)\n'
                                f'def {nm}(+x: U32, {params}) -> {{BR.SZR({F}, {", ".join(ts)}) == Nat.add({F}, {S}) : Nat}}:\n'
                                + '\n'.join(lines) + '\n  {==}')
    syn.lemmas['x001_szr_lt'] = (f'def szr_lt(+x: U32, {params}, +h: {{Nat.is_lt(Nat.add({S}, {F}), VB.pw(31n)) == True{{}} : Bool}})\n'
                                 f'    -> {{Nat.is_lt(BR.SZR({F}, {", ".join(ts)}), VB.pw(31n)) == True{{}} : Bool}}:\n'
                                 f'  %Equal.sym(Nat, BR.SZR({F}, {", ".join(ts)}), Nat.add({F}, {S}), {nm}(x, {", ".join(ts)})) : {{Nat.is_lt(_, VB.pw(31n)) == True{{}} : Bool}}\n'
                                 f'  %Equal.sym(Nat, Nat.add({F}, {S}), Nat.add({S}, {F}), FD.nat__add_comm({F}, {S})) : {{Nat.is_lt(_, VB.pw(31n)) == True{{}} : Bool}}\n'
                                 f'  h')
    syn.ctx.alias(ROOT / 'proofs/obj/vbuf.bend')
    return f'szr_lt({mf.group(1)}, ' + ', '.join(at_d(a) for a in args[1:]) + ', {==})'


def bridge_decl(name):
    f = E2E / f'{name}_e2e_generated.bend'
    mod = Mod.get(f)
    d = mod.defs[f'{name}_e2e_encode']
    return mod, d


def build(name):
    mod, d = bridge_decl(name)
    PREFER.clear()
    taken = set()
    for a, pth in mod.imports.items():
        if pth not in PREFER and a not in taken:
            PREFER[pth] = a
            taken.add(a)
    PREFER[mod.path] = 'BR'
    PREFER[(E2E / 'e2e_wit.bend').resolve()] = 'WT'
    ctx = Ctx()
    ctx.alias(mod.path)
    syn = Synth(ctx)
    k = d.index('(')
    depth, j = 0, k
    while True:
        c = d[j]
        if c in '([{':
            depth += 1
        elif c in ')]}':
            depth -= 1
            if depth == 0:
                break
        j += 1
    params = split_top(d[k + 1:j])
    concl = re.search(r'\) -> (\{Some\{.*\}):\n', d, re.S).group(1)
    tmod = Mod.get(ROOT / f'types/{name}_def_generated.bend')
    X = name[len('Fulu'):] if name.startswith('Fulu') else name
    dflt = f'{X}_default()'
    obj = model_of(ctx, tmod, dflt)
    env = {'o': obj}
    dmod_alias = ctx.alias(tmod.path)
    D = f'{dmod_alias}.{dflt}'

    def at_d(t):
        t = ctx.lift(mod, t)
        return re.sub(r'(?<![\w.])o(?=[),])', D, t)
    prem = []
    for p in params[1:]:
        pn, pt = p.lstrip('+-').split(':', 1)
        env['__subj'] = None
        term = szr_term(syn, mod, pt.strip(), at_d) or syn.prove(mod, pt, env)
        prem.append((pn.strip(), at_d(pt.strip()), term))
    bralias = 'BR'
    concl_c = at_d(concl)
    ctx.alias(ROOT / 'src/obj.bend')
    ctx.alias(ROOT / 'proofs/compact/found.bend')
    lines = ['import Base']
    for a, pth in sorted(ctx.used.items(), key=lambda x: x[1].relative_to(ROOT).as_posix()):
        rel = pth.relative_to(E2E).as_posix() if pth.parent == E2E else (Path('..') / pth.relative_to(ROOT)).as_posix()
        if pth.parent == E2E:
            rel = './' + rel
        lines.append(f'import {rel} as {a}')
    txt = '\n'.join(lines) + '\n\n' + HEADER + '\n'
    txt += (f'# Non-vacuity of the encode bridge {name}_e2e_encode: every premise holds of the default object\n'
            f'# D = {X}_default() (one def per premise, named after its binder), so the bridge applies to D.\n\n')
    for nm in sorted(syn.lemmas):
        txt += syn.lemmas[nm] + '\n\n'
    for pn, pt, term in prem:
        txt += f'def premise_{pn}() -> {pt}:\n  {term}\n\n'
    txt += (f'def {name}_e2e_witness() -> {concl_c}:\n  {bralias}.{name}_e2e_encode({D}, '
            + ', '.join(f'premise_{pn}()' for pn, _, _ in prem) + ')\n')
    return txt


def outputs():
    return {E2E / f'{n}_e2e_witness_generated.bend': build(n) for n in NAMES}


def main():
    check = '--check' in sys.argv
    only = None
    if '--only' in sys.argv:
        only = sys.argv[sys.argv.index('--only') + 1].split(',')
    outs = {E2E / 'e2e_wit.bend': SUPPORT}
    for n in NAMES:
        if only and n not in only:
            continue
        outs[E2E / f'{n}_e2e_witness_generated.bend'] = build(n)
    stale = []
    for p, t in outs.items():
        if not p.exists() or p.read_text() != t:
            stale.append(p.name)
            if not check:
                p.write_text(t)
    if not only:
        have = {p.name for p in E2E.glob('*_e2e_witness_generated.bend')}
        orphans = sorted(have - {p.name for p in outs})
        for o in orphans:
            if check:
                stale.append(o + ' (orphan)')
            else:
                (E2E / o).unlink()
    if check:
        if stale:
            print('stale: ' + ', '.join(stale))
            sys.exit(1)
        print(f'e2e_witness: {len(outs)} witnesses up to date')
    else:
        print(f'e2e_witness: wrote {len(stale)} of {len(outs)}')


if __name__ == '__main__':
    main()
