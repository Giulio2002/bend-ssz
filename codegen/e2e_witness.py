def szr_term(syn, mod, pt, at_d):
    """the total-size premise {Nat.is_lt(SZR(U32.to_nat(F), t0, ..), pw(31n)) == True} with a large fixed part F:
    SZR adds on its first argument, so evaluating it walks F once per term; a lemma reassociates the sum to
    t0 + .. + tn + F first (F stays a U32 in the proof term)"""
    m = re.match(r'\{Nat\.is_lt\(SZR\((.*)\), VB\.pw\(31n\)\) == True\{\} : Bool\}$', pt, re.S)
    if not m:
        return None
    args = split_top(m.group(1))
    mf = re.match(r'U32\.to_nat\((\d+)\)$', args[0])
    if not mf or int(mf.group(1)) < BIG:
        return None
    ts = [f't{i}' for i in range(len(args) - 1)]
    S = ts[0]
    for t in ts[1:]:
        S = f'Nat.add({S}, {t})'
    F = 'U32.to_nat(x)'
    # A_k = add(..add(add(F, t0), t1).., tk) is add(F, S_k), by one reassociation per term
    lines = []
    Sk = [ts[0]]
    for t in ts[1:]:
        Sk.append(f'Nat.add({Sk[-1]}, {t})')
    for k in range(1, len(ts)):
        inner = f'_'
        ctx = inner
        for t in ts[k + 1:]:
            ctx = f'Nat.add({ctx}, {t})'
        lhs = f'Nat.add(Nat.add({F}, {Sk[k - 1]}), {ts[k]})'
        rhs = f'Nat.add({F}, {Sk[k]})'
        lines.append(f'  %Equal.sym(Nat, {lhs}, {rhs}, FD.nat__add_assoc({F}, {Sk[k - 1]}, {ts[k]})) : {{{ctx} == Nat.add({F}, {S}) : Nat}}')
    params = ', '.join(f'+{t}: Nat' for t in ts)
    nm = 'szr_sum'
    syn.lemmas['x000_' + nm] = (f'# SZR(F, t0, .., tn) = F + (t0 + .. + tn)\n'
                                f'def {nm}(+x: U32, {params}) -> {{BR.SZR({F}, {", ".join(ts)}) == Nat.add({F}, {S}) : Nat}}:\n'
                                + '\n'.join(lines) + '\n  {==}')
    syn.lemmas['x001_szr_lt'] = (f'def szr_lt(+x: U32, {params}, +h: {{Nat.is_lt(Nat.add({S}, {F}), VB.pw(31n)) == True{{}} : Bool}})\n'
                                 f'    -> {{Nat.is_lt(BR.SZR({F}, {", ".join(ts)}), VB.pw(31n)) == True{{}} : Bool}}:\n'
                                 f'  %Equal.sym(Nat, BR.SZR({F}, {", ".join(ts)}), Nat.add({F}, {S}), {nm}(x, {", ".join(ts)})) : {{Nat.is_lt(_, VB.pw(31n)) == True{{}} : Bool}}\n'
                                 f'  %Equal.sym(Nat, Nat.add({F}, {S}), Nat.add({S}, {F}), FD.nat__add_comm({F}, {S})) : {{Nat.is_lt(_, VB.pw(31n)) == True{{}} : Bool}}\n'
                                 f'  h')
    syn.ctx.alias(ROOT / 'proofs/obj/vbuf.bend')
    return f'szr_lt({mf.group(1)}, ' + ', '.join(at_d(a) for a in args[1:]) + ', {==})'


def law_files():
    """{law name: bridge file path} from e2e/manifest.json"""
    man = json.loads((E2E / 'manifest.json').read_text())
    return {l: E2E / f for f, es in man['files'].items() for e in es for l in e['laws']}


def params_of(d):
    k = d.index('(')
    depth, j = 0, k
    while True:
        c = d[j]
        if c in '([{':
            depth += 1
        elif c in ')]}':
            depth -= 1
            if depth == 0:
                break
        j += 1
    rest = d[j + 1:]
    a = rest.index('{')
    depth, e = 0, a
    while True:
        if rest[e] == '{':
            depth += 1
        elif rest[e] == '}':
            depth -= 1
            if depth == 0:
                break
        e += 1
    return split_top(d[k + 1:j]), rest[a:e + 1]


def premised(lf):
    """the names whose encode (i) or root (iv) bridge takes premises besides the object (and the buffer)"""
    out = []
    for l in sorted(lf):
        if not l.endswith('_e2e_encode'):
            continue
        n = l[:-len('_e2e_encode')]
        ep, _ = params_of(Mod.get(lf[l]).defs[l])
        rp, _ = params_of(Mod.get(lf[n + '_e2e_root']).defs[n + '_e2e_root'])
        if [x.lstrip('+-').split(':')[0].strip() for x in ep] != ['o'] or \
                [x.lstrip('+-').split(':')[0].strip() for x in rp] != ['h', 'o']:
            out.append(n)
    return out


def default_of(ctx, mod, otype, name):
    """(module, default call) of the object API's default object of the bridge's object type"""
    otype = otype.strip()
    a, _, tn = otype.rpartition('.')
    path = mod.imports.get(a) if a else mod.path
    if path is None or not re.search(r'types/\w+_def_generated\.bend$', str(path)):
        path = ROOT / f'types/{name}_def_generated.bend'
    tmod = Mod.get(path)
    for d in tmod.defs:
        if d.endswith('_default') and '_bx_' not in d:
            ps, ret, _ = tmod.signature(d)
            if not ps and ret.strip().split('.')[-1] == tn:
                return tmod, f'{d}()'
    if tn == 'U32':
        return None, '0'
    raise SystemExit(f'e2e_witness: no default {tn} in {Path(path).name}')


