class Synth:
    def __init__(self, ctx):
        self.ctx = ctx
        self.lemmas = {}
        self.named = {}

    def wz(self, n, d):
        nm = f'WZ{n}'
        self.lemmas[nm] = (f'def {nm}() -> {{O.words_new({n}) == O.Words{{FD.array__thaw(U32, FD.array__trep(U32, {d}n, 0)), {n}}} : O.Words}}:\n'
                           f'  %FD.array__new(U32, {d}n, 0) : {{O.words_new({n}) == O.Words{{_, {n}}} : O.Words}}\n'
                           f'  {{==}}')
        return f'{nm}()'

    def arg_model(self, e, env):
        """the model of an argument expression: a variable of env, or projections of one"""
        e = e.strip()
        if e in env:
            x = env[e]
            if isinstance(x, tuple):
                return x[2] if len(x) > 2 else None
            return x
        c = parse_call(e)
        if c is None:
            return None
        fn, args = c
        base = fn.split('.')[-1]
        if base == 'array__slots' and len(args) == 2:
            t = self.arg_model(args[1], env)
            return Slots(t.elem) if isinstance(t, Tree) else None
        inner = self.arg_model(args[0], env) if args else None
        if base.startswith('tfz_') and isinstance(inner, ArrM):
            return Tree(inner.elem)
        if re.match(r'pju_\w+_\d+$', base) and isinstance(inner, Cont) and len(inner.fields) == 1:
            return inner.fields[0][1]
        if re.match(r'xat_\w+$', base) and isinstance(inner, Slots):
            return inner.elem
        if re.match(r'(th|fz)_\w+$', base) and inner is not None:
            return inner
        if inner is None:
            return None
        m = re.match(r'pj_\w+_(\d+)$', base)
        if m and isinstance(inner, Cont):
            return inner.fields[int(m.group(1))][1]
        if re.match(r'pjb_\w+_bx$', base) and isinstance(inner, Box):
            return inner.inner
        return None

    def part(self, mod, pred, env):
        """one part of a split P2 chain: a nested P2 stays split, anything else is a named lemma of its predicate"""
        c = parse_call(pred.strip())
        if c and c[0].split('.')[-1] == 'P2' and mod.resolve(c[0])[0] is not None and mod.resolve(c[0])[0].path.name == 'dk.bend':
            return self.prove(mod, pred, env)
        ty = self.subst(mod, pred.strip(), env)
        term = self.prove(mod, pred, dict(env, __split=False))
        nm = f'PC{len(self.lemmas)}'
        self.lemmas[f'zz{len(self.lemmas):04d}_{nm}'] = f'def {nm}() -> {ty}:\n  {term}'
        return f'{nm}()'

    def prove(self, mod, pred, env):
        """a proof term of the Data predicate text pred (written in mod), with its variables' models in env"""
        p = pred.strip()
        if p.startswith('{'):
            return self.eq(p, dict(env, __mod=mod))
        if p.startswith('match '):
            return self.unfold(mod, p, env)
        c = parse_call(p)
        if c is None:
            raise SystemExit(f'e2e_witness: cannot read {p[:120]!r}')
        fn, args = c
        base = fn.split('.')[-1]
        m2, name = mod.resolve(fn)
        if (m2 is not None and m2.path.name == 'dk.bend') or fn in ('Ex', 'P2', 'Or2'):
            if base == 'Ex':
                lam = args[1]
                mv = re.match(r'(\w+)\s*=>\s*', lam, re.S)
                v = mv.group(1)
                wit = self.witness(mod, args[0], v, lam[mv.end():], env)
                env2 = dict(env)
                subj = env.get('__subj')
                if isinstance(subj, (OneList, VecN)) and 'array__Tree<' in args[0]:
                    env2[v] = ('val', wit, Tree(subj.elem))
                else:
                    env2[v] = ('val', wit)
                return f'({wit}, {self.prove(mod, lam[mv.end():], env2)})'
            if base == 'P2':
                if env.get('__split') or re.search(r'(?<![\w.])TOT_\w+\(', args[1]):
                    # a total-size chain: each part its own lemma, typed by its predicate (the checker would
                    # otherwise compare the parts inside the chain's type, walking the total's 2^29 term)
                    env2 = dict(env, __split=True)
                    return f'({self.part(mod, args[0], env2)}, {self.part(mod, args[1], env2)})'
                return f'({self.prove(mod, args[0], env)}, {self.prove(mod, args[1], env)})'
            if base == 'Or2':
                subj = env.get('__subj')
                mu = re.match(r'.*_c(\d+)$', subj.tname) if isinstance(subj, Cont) else None
                if mu:
                    ma0 = re.search(r'_(\d+)\(', args[0])
                    return (f'Inl{{{self.prove(mod, args[0], env)}}}' if ma0 and ma0.group(1) == mu.group(1)
                            else f'Inr{{{self.prove(mod, args[1], env)}}}')
                if (isinstance(subj, Words) and subj.n == 0) or (isinstance(subj, BitsM) and subj.k == 0):
                    return f'Inl{{{self.prove(mod, args[0], env)}}}'
                return f'Inr{{{self.prove(mod, args[1], env)}}}'
        if m2 is None or name not in m2.defs:
            raise SystemExit(f'e2e_witness: no def {fn} ({mod.path.name})')
        params, ret, body = m2.signature(name)
        env2 = {'__e': {}, '__raw': {}}
        for pn, a in zip(params, args):
            env2['__raw'][pn] = (a, env)
            mdl = self.arg_model(a, env)
            if mdl is not None:
                env2[pn] = mdl
            env2['__e'][pn] = self.subst(mod, a, env)
        if params and params[0] in env2:
            env2['__subj'] = env2[params[0]]
        elif '__subj' in env:
            env2['__subj'] = env['__subj']
        if body.startswith('match'):
            return self.unfold(m2, body, env2)
        subj = env2.get('__subj')
        full = list(m2.fullp)
        if isinstance(subj, Words) and pow2_of(subj.n) and params and params[0] in env2 \
                and re.match(r'DK\.Ex\(\w+\.array__Tree<U32>, t =>', body):
            return self.leaf(m2, name, full, params, body, env2, subj)
        if isinstance(subj, Words) and subj.n >= BIG and params and params[0] in env2:
            # a large word array: its own lemma, so that a failure is located and nothing is inlined twice
            ty = f'{self.ctx.alias(m2.path)}.{name}(' + ', '.join(env2['__e'][pn] for pn in params) + ')'
            key = ty
            if key not in self.named:
                term = self.prove(m2, body, env2)
                nm = f'big{len(self.named)}'
                self.named[key] = nm
                self.lemmas[f'z{len(self.named):03d}_{nm}'] = f'def {nm}() -> {ty}:\n  {term}'
            return f'{self.named[key]}()'
        return self.prove(m2, body, env2)

    def unfold(self, m2, body, env2):
        """a premise defined by a match, at known arguments. On a numeral k (`case 0n: A / case 1n+q: B`,
        the element-wise premises): A at 0 (over zero elements, {True{} == True{}}), B with q := k-1
        otherwise. On a boxed or mirrored element (`case MSome{v}` / `case BSome{v, ..}`) whose model is
        a box: the Some case with v the inner model. On a container mirror (`case M_X{a0, ..}`) whose
        model is a container: its fields (boxes unwrapped). Anything else keeps the old reading, R."""
        mt = parse_match(body)
        if mt is None:
            return R
        var, cases = mt
        pats = [p for p, _ in cases]
        if pats[:1] == ['0n'] and len(cases) == 2 and re.fullmatch(r'1n\+\+?\w+', pats[1]):
            raw, cenv = env2.get('__raw', {}).get(var, ('', {}))
            # the caller's Ex-bound variables (N, ..) by their witnesses
            raw = re.sub(r'(?<![\w.])[A-Za-z_]\w*(?![\w.{(])',
                         lambda m: cenv[m.group(0)][1] if isinstance(cenv.get(m.group(0)), tuple) else m.group(0), raw)
            k = nat_value(self.subst(m2, raw, cenv)) if raw else None
            if not k:
                return R
            q = pats[1][3:].lstrip('+')
            env3 = dict(env2)
            env3['__e'] = dict(env2['__e'])
            env3['__e'][q] = f'{k - 1}n'
            env3[q] = ('val', f'{k - 1}n')
            return self.prove(m2, cases[1][1], env3)
        mdl = env2.get(var)
        if isinstance(mdl, Cont):
            # a match on the container (or union option) itself: the case of its constructor, fields bound
            for pat_, sub_ in cases:
                mc = re.fullmatch(r'([\w.]+)\{(.*)\}', pat_)
                if mc and mc.group(1).split('.')[-1] == mdl.tname:
                    bs_ = [b.strip().lstrip('+') for b in split_top(mc.group(2))]
                    if len(bs_) == len(mdl.fields):
                        env3 = dict(env2)
                        env3['__e'] = dict(env2.get('__e', {}))
                        for b_, (fe, fm) in zip(bs_, mdl.fields):
                            env3[b_] = fm
                            env3['__e'][b_] = fe
                        return self.prove(m2, sub_, env3)
        if isinstance(mdl, OneList) and len(cases) == 1:
            mc = re.fullmatch(r'([\w.]+)\{(.*)\}', cases[0][0])
            if mc and mc.group(1).endswith('_Seq'):
                bs_ = [b.strip().lstrip('+') for b in split_top(mc.group(2))]
                env3 = dict(env2)
                env3['__e'] = dict(env2.get('__e', {}))
                it = f'ALeaf{{{mdl.eexpr}}}'
                env3[bs_[0]] = ('val', it, ArrM(mdl.elem))
                env3['__e'][bs_[0]] = it
                env3[bs_[1]] = ('val', '1')
                env3['__e'][bs_[1]] = '1'
                return self.prove(m2, cases[0][1], env3)
        if isinstance(mdl, EList) and len(cases) == 1:
            mc = re.fullmatch(r'([\w.]+)\{(.*)\}', cases[0][0])
            if mc and mc.group(1).endswith('_Seq'):
                bs_ = [b.strip().lstrip('+') for b in split_top(mc.group(2))]
                env3 = dict(env2)
                env3['__e'] = dict(env2.get('__e', {}))
                fm_, fe_ = mdl.fill
                env3[bs_[0]] = ('val', self.ctx.lift(fm_, fe_))
                env3['__e'][bs_[0]] = self.ctx.lift(fm_, fe_)
                env3[bs_[1]] = ('val', '0')
                env3['__e'][bs_[1]] = '0'
                return self.prove(m2, cases[0][1], env3)
        if isinstance(mdl, Words) and len(cases) == 1:
            mc = re.fullmatch(r'([\w.]+)\{(.*)\}', cases[0][0])
            if mc and mc.group(1).split('.')[-1] == 'Words':
                bs_ = [b.strip().lstrip('+') for b in split_top(mc.group(2))]
                env3 = dict(env2)
                env3['__e'] = dict(env2.get('__e', {}))
                for b_, v_ in zip(bs_, (f'FD.array__thaw(U32, FD.array__trep(U32, {mdl.d}n, 0))', f'{mdl.n}')):
                    env3[b_] = ('val', v_)
                    env3['__e'][b_] = v_
                return self.prove(m2, cases[0][1], env3)
        if isinstance(mdl, VecN) and len(cases) == 1 and getattr(mdl, 'items', None):
            mc = re.fullmatch(r'([\w.]+)\{(.*)\}', cases[0][0])
            if mc and mc.group(1).endswith('_Seq'):
                bs_ = [b.strip().lstrip('+') for b in split_top(mc.group(2))]
                env3 = dict(env2)
                env3['__e'] = dict(env2.get('__e', {}))
                env3[bs_[0]] = ('val', mdl.items, ArrM(mdl.elem))
                env3['__e'][bs_[0]] = mdl.items
                env3[bs_[1]] = ('val', f'{mdl.n}')
                env3['__e'][bs_[1]] = f'{mdl.n}'
                return self.prove(m2, cases[0][1], env3)
        if isinstance(mdl, BitsM) and len(cases) == 1:
            mc = re.fullmatch(r'([\w.]+)\{(.*)\}', cases[0][0])
            if mc and mc.group(1).split('.')[-1] == 'Bits':
                bs_ = [b.strip().lstrip('+') for b in split_top(mc.group(2))]
                env3 = dict(env2)
                env3['__e'] = dict(env2.get('__e', {}))
                for b_, v_ in zip(bs_, (f'Array.new(U32, {mdl.d}n, 0)', f'{mdl.k}')):
                    env3[b_] = ('val', v_)
                    env3['__e'][b_] = v_
                return self.prove(m2, cases[0][1], env3)
        for pat, sub in cases:
            mc = re.fullmatch(r'([\w.]+)\{(.*)\}', pat)
            if not mc:
                continue
            ctor, binders = mc.group(1).split('.')[-1], [b.strip().lstrip('+') for b in split_top(mc.group(2))]
            env3 = dict(env2)
            if ctor in ('MSome', 'BSome') and isinstance(mdl, Box):
                env3[binders[0]] = mdl.inner
                return self.prove(m2, sub, env3)
            if isinstance(mdl, Cont) and ctor.startswith('M_') and len(binders) == len(mdl.fields):
                for b, (_, fm) in zip(binders, mdl.fields):
                    env3[b] = fm.inner if isinstance(fm, Box) else fm
                return self.prove(m2, sub, env3)
        return R

    def leaf(self, m2, name, full, params, body, env2, subj):
        """a storage predicate (DK.Ex over a word tree t) of a large zero array 2^b bytes, 2^c chunks, depth d:
        a lemma with b, c, d symbolic (no unary 2^b is ever built), applied at the concrete sizes"""
        b = pow2_of(subj.n)
        c, d = b - 5, subj.d
        self.ctx.alias(E2E / 'e2e_wit.bend')
        key = ('leaf', m2.path, name)
        hyps = []
        if key not in self.named:
            sym = {'t': 'FD.array__trep(U32, d, 0)', 'dw': 'd', 'N': 'FD.u32__pow2u(b)', 'q': 'WT.QP(c)', 'r': '32n'}
            def walk(e):
                e = e.strip()
                cl = parse_call(e)
                if cl and cl[0].split('.')[-1] == 'Ex' and cl[0].startswith('DK'):
                    lam = cl[1][1]
                    mv = re.match(r'(\w+)\s*=>\s*', lam, re.S)
                    return f'({sym[mv.group(1)]}, {walk(lam[mv.end():])})'
                if cl and cl[0].split('.')[-1] == 'P2' and cl[0].startswith('DK'):
                    return f'({walk(cl[1][0])}, {walk(cl[1][1])})'
                if not e.startswith('{'):
                    raise SystemExit(f'e2e_witness: leaf {name}: cannot read {e[:80]!r}')
                if re.search(r'== O\.Words\{', e) and 'array__thaw' in e:
                    return 'ew'
                if 'array__perfect(U32' in e:
                    return 'FD.array__trep_perfect(U32, d, 0)'
                if re.search(r'U32\.to_nat\(N\) == Nat\.add\(WS\.e32\(q\), (32n|r)\)', e):
                    return 'WT.eN(c, b, eb, FD.u32__pow2u(b), FD.u32__pow2u_value(b, hb))'
                if re.search(r'Nat\.is_le\(O\.e8\(1n\+q\), \w+\.spec_common__pow2\(dw\)\)', e):
                    return 'WT.eQ(c, d, hd)'
                t = self.ctx.lift(m2, e)
                t = re.sub(r'(?<![\w.])(t|dw|N|q|r)(?![\w{(])', lambda m: sym[m.group(1)], t)
                hyps.append(t)
                return f'h{len(hyps) - 1}'
            term = walk(body)
            ps = []
            for i, fp in enumerate(full):
                mode = fp[0] if fp[0] in '+-' else ''
                pn, pt = fp.lstrip('+-').split(':', 1)
                ps.append(('-' if i == 0 else mode) + pn.strip() + ': ' + self.ctx.lift(m2, pt.strip()))
            w = params[0]
            ps += ['+c: Nat', '+b: Nat', '+d: Nat', '+eb: {Nat.add(5n, c) == b : Nat}', '+hb: {Nat.is_lt(b, 32n) == True{} : Bool}',
                   '+hd: {Nat.is_le(Nat.add(3n, c), d) == True{} : Bool}',
                   f'+ew: {{{w} == O.Words{{FD.array__thaw(U32, FD.array__trep(U32, d, 0)), FD.u32__pow2u(b)}} : O.Words}}']
            ps += [f'+h{i}: {h}' for i, h in enumerate(hyps)]
            nm = f'sym_{canon(m2.path)}_{name}'
            ret = f'{self.ctx.alias(m2.path)}.{name}(' + ', '.join(params) + ')'
            self.named[key] = (nm, len(hyps))
            self.lemmas[f'y{len(self.named):03d}_{nm}'] = f'def {nm}(' + ', '.join(ps) + f') -> {ret}:\n  {term}'
        nm, nh = self.named[key]
        args = [env2['__e'][pn] for pn in params] + [f'{c}n', f'{b}n', f'{d}n', R, R, R, self.wz(subj.n, subj.d)] + [R] * nh
        return f'{nm}(' + ', '.join(args) + ')'

    def witness(self, mod, ty, v, body, env):
        subj = env.get('__subj')
        ty = ty.strip()
        if isinstance(subj, Words):
            if ty.endswith('array__Tree<U32>'):
                return f'FD.array__trep(U32, {subj.d}n, 0)'
            if v == 'dw':
                return f'{subj.d}n'
            pw = pow2_of(subj.n)
            if v == 'N':
                return f'FD.u32__pow2u({pw}n)' if pw else f'{subj.n}'
            if v == 'q' and pw and re.search(r'U32\.to_nat\(N\) == Nat\.add\(WS\.e32\(q\), (32n|r)\)', body):
                self.ctx.alias(E2E / 'e2e_wit.bend')
                return f'WT.QP({pw - 5}n)'
            if v == 'r' and pw:
                return '32n'
            if v == 'q':
                if re.search(r'U32\.to_nat\(N\) == Nat\.add\(WS\.e32\(q\), 32n\)', body):
                    return f'{subj.n // 32 - 1}n'
                return f'{(subj.n - 1) // 32}n'
            if v == 'r':
                return f'{subj.n - 32 * ((subj.n - 1) // 32)}n'
        if isinstance(subj, BitsM):
            if ty.endswith('array__Tree<U32>'):
                return f'FD.array__trep(U32, {subj.d}n, 0)'
            if v == 'dw':
                return f'{subj.d}n'
            if v in ('K', 'N'):
                return f'{subj.k}'
        if isinstance(subj, VecN):
            if 'array__Tree<' in ty:
                ma = re.search(r'(?<![\w])(\w+\.)?am_(\w+)\(' + v + r'\)', body)
                if ma and getattr(subj, 'items', None):
                    return self.ctx.lift(mod, (ma.group(1) or '') + 'tfz_' + ma.group(2)) + f'({subj.items})'
                return f'FD.array__trep({subj.ty}, {subj.d}n, {subj.eexpr})'
            if v == 'dw':
                return f'{subj.d}n'
            if v == 'N':
                return f'{subj.n}'
        if isinstance(subj, Words) and v == 'd':
            return f'{subj.d}n'
        if isinstance(subj, Cont):
            mc = re.search(r'\{\w+ == ([\w.]+)\{(.*?)\} : ', body)
            if mc:
                cargs = [a_.strip() for a_ in split_top(mc.group(2))]
                if v in cargs and len(cargs) == len(subj.fields):
                    return subj.fields[cargs.index(v)][0]
        if isinstance(subj, OneList):
            if 'array__Tree<' in ty:
                ma = re.search(r'(?<![\w])(\w+\.)?am_(\w+)\(' + v + r'\)', body)
                if ma:
                    return self.ctx.lift(mod, (ma.group(1) or '') + 'tfz_' + ma.group(2)) + f'(ALeaf{{{subj.eexpr}}})'
                return f'FD.TLeaf{{{subj.eexpr}}}'
            if v == 'dw':
                return '0n'
            if v == 'N':
                return '1'
        if isinstance(subj, EList):
            if 'array__Tree<' in ty:
                inner = ty[ty.index('array__Tree<') + len('array__Tree<'):-1]
                mm = re.match(r'(?:(\w+)\.)?MB<', inner)
                if mm:
                    return 'FD.TLeaf{' + self.ctx.lift(mod, (mm.group(1) + '.' if mm.group(1) else '') + 'MNone') + '{}}'
                el = self.ctx.lift(mod, inner)
                return 'FD.TLeaf{' + el + '_default()}'
            if v == 'dw':
                return '0n'
            if v == 'N':
                return '0'
        if isinstance(subj, Box) and v == 'v':
            return subj.iexpr
        me = re.search(r'\{' + v + r' == (.*?) : [\w.<>&, ]+\}', body)
        if me:
            return self.subst(mod, me.group(1), env)
        if isinstance(subj, Cont):
            mx = re.match(r'x(\d+)$', v)
            if mx:
                return subj.fields[int(mx.group(1))][0]
        raise SystemExit(f'e2e_witness: no witness for {v}: {ty} of {type(subj).__name__} ({mod.path.name})')

    def subst(self, mod, e, env):
        """expression e of module mod, lifted, with its variables replaced by their models' expressions"""
        e = self.ctx.lift(mod, e)
        def sub(m):
            v = m.group(0)
            if v in env.get('__e', {}):
                return env['__e'][v]
            x = env.get(v)
            if x is None or isinstance(x, tuple) or v.startswith('__'):
                if isinstance(x, tuple):
                    return x[1]
                return v
            return x.expr
        return re.sub(r'(?<![\w.])[a-z]\w*(?![\w.{(])', sub, e)

    def _dbl(self, j, x):
        for _ in range(j):
            x = f'Nat.double({x})'
        return x

    def _chain(self, n, j, y):
        """{U32.to_nat(n) == double^j(y)}: j splits of n by its low bit (shr_split: the low j bits of n are 0), then
        {U32.to_nat(n >> j) == y} compared (n >> j levels, not n)"""
        FDA = self.ctx.alias(ROOT / 'proofs/compact/found.bend')
        if j == 0:
            return '{==}'
        L = f'Nat.add({FDA}.spec_numeric__bit_value({FDA}.u32__low_bit({n})), Nat.double(U32.to_nat(U32.shr({n}))))'
        inner = self._chain(n >> 1, j - 1, y)
        return (f'Equal.trans(Nat, U32.to_nat({n}), {L}, {self._dbl(j, y)}, {FDA}.u32__shr_split({n}), '
                f'Equal.cong(Nat, Nat, z => Nat.add({FDA}.spec_numeric__bit_value({FDA}.u32__low_bit({n})), Nat.double(z)), '
                f'U32.to_nat(U32.shr({n})), {self._dbl(j - 1, y)}, {inner}))')

    def big_nfact(self, n):
        """{U32.to_nat(n) == Nat.add(WS.e32(q), r)} for n = 32 q + r (0 < r <= 32, r = 2^t s with s odd): e32 written
        out, the sum rewritten into t doublings of 2^(5-t) q + s (WT.daddk), and n split t times by its low bit:
        nothing is compared deeper than n >> t"""
        WSA = self.ctx.alias(ROOT / 'proofs/obj/words_spec.bend')
        self.ctx.alias(E2E / 'e2e_wit.bend')
        r = n % 32 or 32
        q = (n - r) // 32
        t = (r & -r).bit_length() - 1
        D = lambda k: self._dbl(k, f'{q}n')
        T = [f'{self._dbl(i, f"Nat.add({D(5 - i)}, {r >> i}n)")}' for i in range(t + 1)]
        R = f'Nat.add({WSA}.e32({q}n), {r}n)'
        nm = f'NB{n}'
        parts = []   # one lemma entry, its defs in order (callers sort or reverse the entries)
        parts.append(f'def {nm}s0() -> {{{R} == {T[0]} : Nat}}:\n'
                     f'  Equal.cong(Nat, Nat, z => Nat.add(z, {r}n), {WSA}.e32({q}n), {D(5)}, WT.e32d({q}n))')
        # each step its own def: T(i-1) == T(i) by daddk under i - 1 doublings
        for i in range(1, t + 1):
            core = f'WT.daddk({D(5 - i)}, {r >> i}n, {r >> (i - 1)}n, {{==}})'
            if i > 1:
                core = (f'Equal.cong(Nat, Nat, z => {self._dbl(i - 1, "z")}, Nat.add({D(6 - i)}, {r >> (i - 1)}n), '
                        f'Nat.double(Nat.add({D(5 - i)}, {r >> i}n)), {core})')
            parts.append(f'def {nm}s{i}() -> {{{T[i - 1]} == {T[i]} : Nat}}:\n  {core}')
        pf = f'{nm}s0()'
        for i in range(1, t + 1):
            pf = f'Equal.trans(Nat, {R}, {T[i - 1]}, {T[i]}, {pf}, {nm}s{i}())'
        parts.append(f'def {nm}r() -> {{{R} == {T[t]} : Nat}}:\n  {pf}')
        parts.append(f'def {nm}c() -> {{U32.to_nat({n}) == {T[t]} : Nat}}:\n'
                     f'  {self._chain(n, t, f"Nat.add({D(5 - t)}, {r >> t}n)")}')
        self.lemmas[nm] = '\n\n'.join(parts) + (f'\n\ndef {nm}() -> {{U32.to_nat({n}) == {R} : Nat}}:\n'
                                                f'  Equal.trans(Nat, U32.to_nat({n}), {T[t]}, {R}, {nm}c(), Equal.sym(Nat, {R}, {T[t]}, {nm}r()))')
        return f'{nm}()'

    def big_lfact(self, n, o, k=32):
        """{U32.to_nat(WO.len(o)) == PK.e<k>(PK.cnt<k>(o))} for the n-byte object o, k-byte elements (WT.lbig<k>): n
        split log2(k) times by its low bit, then n / k compared with the count"""
        PKA = self.ctx.alias(ROOT / 'proofs/obj/packed_obj_light.bend')
        self.ctx.alias(E2E / 'e2e_wit.bend')
        j = {8: 3, 16: 4, 32: 5}[k]
        c = n // k
        Djo = self._dbl(j, f'{PKA}.cnt{k}({o})')
        nm = f'LB{n}_{k}'
        bsp, bsa = ('+bs: +List<U32>', 'bs') if re.search(r'(?<![\w.])bs(?![\w])', o) else ('', '')
        self.lemmas[nm] = (f'def {nm}({bsp}) -> {{U32.to_nat({n}) == {Djo} : Nat}}:\n'
                           f'  Equal.trans(Nat, U32.to_nat({n}), {self._dbl(j, f"{c}n")}, {Djo}, {self._chain(n, j, f"{c}n")},\n'
                           f'    Equal.cong(Nat, Nat, z => {self._dbl(j, "z")}, {c}n, {PKA}.cnt{k}({o}), {{==}}))')
        return f'WT.lbig{"" if k == 32 else k}({o}, {n}, {{==}}, {nm}({bsa}))'

    def tot_qp(self, q):
        """{Nat.is_lt(S, pw(31n)) == True} for a left-nested sum S with one progressive bit list's term QP(..) = 2^29 + 1:
        QP moved last (WT.swapq, one step per later term), then WT.tot29 with the rest compared in unary (small)"""
        m = re.match(r'^\{Nat\.is_lt\((.*), ([\w.]+)\.pw\(31n\)\) == True\{\} : Bool\}$', q, re.S)
        terms, cur = [], m.group(1)
        while True:
            ma = re.match(r'^Nat\.add\((.*)\)$', cur, re.S)
            parts = split_top(ma.group(1)) if ma else None
            if not parts or len(parts) != 2:
                terms.insert(0, cur)
                break
            terms.insert(0, parts[1])
            cur = parts[0]
        js = [i for i, t in enumerate(terms) if re.search(r'\.QP\(', t)]
        if len(js) != 1 or js[0] == 0:
            return None
        j = js[0]
        FDA = self.ctx.alias(ROOT / 'proofs/compact/found.bend')
        self.ctx.alias(E2E / 'e2e_wit.bend')
        Q = terms[j]
        U = [terms[0]]
        for t in terms[1:]:
            U.append(f'Nat.add({U[-1]}, {t})')
        W = U[j - 1]
        pf = None    # {U_k == add(W_k, Q)}
        for k in range(j + 1, len(terms)):
            Wn = f'Nat.add({W}, {terms[k]})'
            step = f'WT.swapq({W}, {Q}, {terms[k]})'
            if pf is None:
                pf = step
            else:
                pf = (f'Equal.trans(Nat, {U[k]}, Nat.add(Nat.add({W}, {Q}), {terms[k]}), Nat.add({Wn}, {Q}), '
                      f'Equal.cong(Nat, Nat, z => Nat.add(z, {terms[k]}), {U[k - 1]}, Nat.add({W}, {Q}), {pf}), {step})')
            W = Wn
        S = U[-1]
        PW = m.group(2)
        body = f'WT.tot29({W}, {Q}, {{==}}, {{==}})'
        if pf is not None:
            body = (f'{FDA}.logic__subst(Nat, z => {{Nat.is_lt(z, {PW}.pw(31n)) == True{{}} : Bool}}, Nat.add({W}, {Q}), {S}, '
                    f'Equal.sym(Nat, {S}, Nat.add({W}, {Q}), {pf}), {body})')
        nm = f'TOT{len(self.lemmas)}'
        self.lemmas[f'x5{nm}'] = f'def {nm}() -> {q}:\n  {body}'
        return f'{nm}()'

    def bz(self, d, k):
        nm = f'BZ{d}_{k}'
        self.lemmas[nm] = (f'def {nm}() -> {{O.Bits{{Array.new(U32, {d}n, 0), {k}}} == O.Bits{{FD.array__thaw(U32, FD.array__trep(U32, {d}n, 0)), {k}}} : O.Bits}}:\n'
                           f'  %FD.array__new(U32, {d}n, 0) : {{O.Bits{{Array.new(U32, {d}n, 0), {k}}} == O.Bits{{_, {k}}} : O.Bits}}\n'
                           f'  {{==}}')
        return f'{nm}()'

    def eq(self, p, env):
        subj = env.get('__subj')
        mt = re.match(r'^\{Nat\.is_lt\((.*), (\w+)\.pw\(31n\)\) == True\{\} : Bool\}$', p, re.S)
        if mt and re.search(r'(?<![\w.])QP\(', mt.group(1)) and env.get('__mod'):
            r = self.tot_qp(self.subst(env['__mod'], p, env))
            if r:
                return r
        if isinstance(subj, VecN) and 'array__thaw' in p and '== ' in p:
            q = self.subst(env['__mod'], p, env) if env.get('__mod') else p
            q = re.sub(r'(?<![\w.])[A-Za-z_]\w*(?![\w.{(])',
                       lambda m: env[m.group(0)][1] if isinstance(env.get(m.group(0)), tuple) else m.group(0), q)
            tt = f'FD.array__thaw({subj.ty}, FD.array__trep({subj.ty}, {subj.d}n, {subj.eexpr}))'
            if tt in q:
                nm = f'VZ{len(self.lemmas)}'
                self.lemmas[nm] = (f'def {nm}() -> {q}:\n  %FD.array__new({subj.ty}, {subj.d}n, {subj.eexpr}) : '
                                   f'{q.replace(tt, "_", 1)}\n  {{==}}')
                return f'{nm}()'
        if isinstance(subj, BitsM) and re.search(r'== O\.Bits\{', p) and 'array__thaw' in p:
            return self.bz(subj.d, subj.k)
        if isinstance(subj, BitsM) and 'array__perfect(U32' in p:
            return f'FD.array__trep_perfect(U32, {subj.d}n, 0)'
        if isinstance(subj, Words) and re.search(r'== O\.Words\{', p) and 'array__thaw' in p:
            return self.wz(subj.n, subj.d)
        if isinstance(subj, Words) and 'array__perfect(U32' in p:
            return f'FD.array__trep_perfect(U32, {subj.d}n, 0)'
        pw = pow2_of(subj.n) if isinstance(subj, Words) else None
        if pw and re.search(r'U32\.to_nat\(N\) == Nat\.add\(WS\.e32\(q\), (32n|r)\)', p):
            return f'WT.eN({pw - 5}n, {pw}n, {{==}}, FD.u32__pow2u({pw}n), FD.u32__pow2u_value({pw}n, {{==}}))'
        if pw and re.search(r'^\{U32\.to_nat\(WO\.len\(o\)\) == e8\(cnt8\(o\)\) : Nat\}$', p) and pw >= 3:
            self.ctx.alias(E2E / 'e2e_wit.bend')
            return f'WT.len8({env["__e"]["o"]}, {pw - 3}n, {pw}n, {subj.d}n, {{==}}, {{==}}, {self.wz(subj.n, subj.d)})'
        big = isinstance(subj, Words) and subj.n >= BIG
        if big and not pw and re.search(r'U32\.to_nat\(N\) == Nat\.add\(WS\.e32\(q\), (32n|r)\)', p):
            return self.big_nfact(subj.n)
        ml = re.search(r'^\{U32\.to_nat\(WO\.len\(o\)\) == e(8|16|32)\(cnt\1\(o\)\) : Nat\}$', p)
        if big and ml and subj.n % int(ml.group(1)) == 0 and (not pw or ml.group(1) == '16'):
            return self.big_lfact(subj.n, env["__e"]["o"], int(ml.group(1)))
        if pw and re.search(r'^\{U32\.to_nat\(WO\.len\(o\)\) == e32\(cnt32\(o\)\) : Nat\}$', p) and pw >= 5:
            self.ctx.alias(E2E / 'e2e_wit.bend')
            return f'WT.len32({env["__e"]["o"]}, {pw - 5}n, {pw}n, {subj.d}n, {{==}}, {{==}}, {self.wz(subj.n, subj.d)})'
        if pw and re.search(r'Nat\.is_le\(O\.e8\(1n\+q\), \w+\.spec_common__pow2\(dw\)\)', p):
            return f'WT.eQ({pw - 5}n, {subj.d}n, {{==}})'
        return R


