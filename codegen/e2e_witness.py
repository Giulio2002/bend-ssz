def canon(path):
    p = Path(path).resolve()
    if p in PREFER:
        return PREFER[p]
    rel = p.relative_to(ROOT).as_posix()
    m = re.match(r'types/(\w+)_def_generated\.bend$', rel)
    if m:
        return m.group(1) + '_d'
    return 'W_' + re.sub(r'\W', '_', rel[:-len('.bend')])


class Ctx:
    """the imports the witness file needs, by canonical alias"""

    def __init__(self):
        self.used = {}

    def alias(self, path):
        a = canon(path)
        self.used[a] = Path(path).resolve()
        return a

    def lift(self, mod, expr):
        """an expression of module mod, with its aliases made canonical (bare names of mod qualified)"""
        def sub(m):
            q = m.group(0)
            if '.' in q:
                a, rest = q.split('.', 1)
                if a in mod.imports:
                    return self.alias(mod.imports[a]) + '.' + rest
                return q
            if q in mod.defs or re.search(r'^type ' + re.escape(q) + r'\b', mod.text, re.M) or \
                    re.search(r'^  ' + re.escape(q) + r'\{', mod.text, re.M):
                return self.alias(mod.path) + '.' + q
            return q
        return re.sub(r'(?<![\w.])[A-Za-z_]\w*(?:\.\w+)?', sub, expr)


def model_of(ctx, mod, expr):
    """the model of a default-valued expression written in module mod (its .expr: the expression, lifted)"""
    m = model_of_(ctx, mod, expr)
    m.expr = ctx.lift(mod, expr)
    return m


def model_of_(ctx, mod, expr):
    c = parse_call(expr)
    if c is None:
        raise SystemExit(f'e2e_witness: no model for {expr!r} ({mod.path.name})')
    fn, args = c
    if fn == 'O.words_new':
        return Words(int(args[0]))
    m2, name = mod.resolve(fn)
    if m2 is None or name not in m2.defs:
        raise SystemExit(f'e2e_witness: no def {fn} ({mod.path.name})')
    params, ret, body = m2.signature(name)
    if params:
        raise SystemExit(f'e2e_witness: default with params {fn}')
    b = body.strip()
    if b.startswith('O.words_new('):
        return Words(int(parse_call(b)[1][0]))
    mb = parse_call(b)
    if mb and mb[0].endswith('_bx_wrap'):
        return Box(model_of(ctx, m2, mb[1][0]), ctx.lift(m2, mb[1][0]))
    ms = re.match(r'(\w+)\{(.*)\}$', b, re.S)
    if ms and ms.group(1).endswith('_Seq'):
        items = split_top(ms.group(2))
        if items[1].strip() != '0':
            raise SystemExit(f'e2e_witness: nonempty default list {fn}')
        return EList((m2, items[0]))
    if ms and all(parse_call(a) for a in split_top(ms.group(2))):
        fields = []
        for a in split_top(ms.group(2)):
            sub = model_of(ctx, m2, a)
            if isinstance(sub, Cont) and sub.tname.startswith(ms.group(1) + '_g'):
                fields.extend(sub.fields)      # a group of a grouped container
            else:
                fields.append((ctx.lift(m2, a), sub))
        return Cont(m2, ms.group(1), fields)
    return Leaf(ctx.lift(m2, b))


