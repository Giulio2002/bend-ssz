class Mod:
    cache = {}

    def __init__(self, path):
        self.path = path.resolve()
        self.text = self.path.read_text()
        self.imports = {}
        for m in re.finditer(r'^import (\S+) as (\w+)$', self.text, re.M):
            self.imports[m.group(2)] = (self.path.parent / m.group(1)).resolve()
        self.defs = {}
        lines = self.text.split('\n')
        i = 0
        while i < len(lines):
            l = lines[i]
            m = re.match(r'def (\w+)\(', l)
            if m:
                j = i + 1
                while j < len(lines) and (lines[j].startswith(' ') or lines[j] == ''):
                    j += 1
                self.defs[m.group(1)] = '\n'.join(lines[i:j]).rstrip()
                i = j
            else:
                i += 1

    @classmethod
    def get(cls, path):
        path = Path(path).resolve()
        if path not in cls.cache:
            cls.cache[path] = Mod(path)
        return cls.cache[path]

    def resolve(self, qname):
        """(module, name) of a qualified or bare function name as written in this module"""
        if '.' in qname:
            a, n = qname.split('.', 1)
            if a in self.imports:
                return Mod.get(self.imports[a]), n
            return None, qname
        return self, qname

    def signature(self, name):
        """(param names, return type text, body text) of a def"""
        d = self.defs[name]
        k = d.index('(')
        depth, j = 0, k
        while True:
            c = d[j]
            if c in '([{':
                depth += 1
            elif c in ')]}':
                depth -= 1
                if depth == 0:
                    break
            j += 1
        self.fullp = [p.strip() for p in split_top(d[k + 1:j])]
        params = [p.strip().lstrip('+-').split(':')[0].strip() for p in split_top(d[k + 1:j])]
        rest = d[j + 1:]
        m = re.match(r'\s*->\s*', rest)
        rest = rest[m.end():]
        # the return type ends at the first top-level ':' followed by a newline or a space
        depth, q = 0, 0
        while q < len(rest):
            c = rest[q]
            if c in '([{<':
                depth += 1
            elif c in ')]}>' and not (c == '>' and q and rest[q - 1] in '=-'):
                depth -= 1
            elif c == ':' and depth == 0:
                break
            q += 1
        return params, rest[:q].strip(), rest[q + 1:].strip()


def split_top(s):
    """split on commas at depth 0 of ( [ { and type application < >"""
    out, depth, cur, i = [], 0, [], 0
    while i < len(s):
        c = s[i]
        if c in '([{':
            depth += 1
        elif c in ')]}':
            depth -= 1
        elif c == '<' and i and (s[i - 1].isalnum() or s[i - 1] == '_'):
            depth += 1
        elif c == '>' and depth > 0 and s[i - 1] not in '=-' and s[i - 1] != ' ':
            depth -= 1
        if c == ',' and depth == 0:
            out.append(''.join(cur).strip())
            cur = []
        else:
            cur.append(c)
        i += 1
    if ''.join(cur).strip():
        out.append(''.join(cur).strip())
    return out


def parse_call(e):
    """(fn, [args]) of 'fn(args)' when e is exactly one call, else None"""
    e = e.strip()
    m = re.match(r'([\w.]+)\(', e)
    if not m:
        return None
    depth = 0
    for i in range(m.end() - 1, len(e)):
        c = e[i]
        if c in '([{':
            depth += 1
        elif c in ')]}':
            depth -= 1
            if depth == 0:
                if i != len(e) - 1:
                    return None
                return m.group(1), split_top(e[m.end():i])
    return None


