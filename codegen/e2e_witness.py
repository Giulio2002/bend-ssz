BIG = 16384


def pow2_of(n):
    """b when n = 2^b is a large power of two (a word array whose arithmetic must stay symbolic)"""
    if n >= BIG and n & (n - 1) == 0:
        return n.bit_length() - 1
    return None


def words_depth(n):
    w = ((n + 31) // 32) * 8 + 8
    return (w - 1).bit_length()


class Words:
    def __init__(self, n):
        self.n, self.d = n, words_depth(n)


