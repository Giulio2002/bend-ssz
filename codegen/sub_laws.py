def tree(leaves):
    if len(leaves) == 1:
        return f'ALeaf{{{leaves[0]}}}'
    h = len(leaves) // 2
    return f'ANode{{{tree(leaves[:h])}, {tree(leaves[h:])}}}'


def depth(nw):
    return max(0, (nw - 1).bit_length())


def wl(ws):
    return '[' + ', '.join(ws) + ']'


def bytes_of(ws, r):
    """The bytes of words ws, the last one r bytes (r = 0: whole)."""
    q = ws if r == 0 else ws[:-1]
    tail = [] if r == 0 else [f'B.byte_sel({k}, {ws[-1]})' for k in range(r)]
    if not tail:
        return f'SF.limbs({wl(q)})'
    if not q:
        return wl(tail)
    return f'List.append(&2, U32, SF.limbs({wl(q)}), {wl(tail)})'


def bd_proof(ws, r):
    """{SP.bytes_domain(bytes_of(ws, r)) == True}."""
    q = ws if r == 0 else ws[:-1]
    if r == 0:
        return f'SP2.bd_limbs({wl(q)})'
    tail = wl([f'B.byte_sel({k}, {ws[-1]})' for k in range(r)])
    rest = wl([f'B.byte_sel({k}, {ws[-1]})' for k in range(r, 4)])
    tp = f'SP2.bd_l({tail}, {rest}, SP2.bd_limbs([{ws[-1]}]))'
    if not q:
        return tp
    return f'SP2.bd_app(SF.limbs({wl(q)}), {tail}, SP2.bd_limbs({wl(q)}), {tp})'


