def unique(w, n, sig, args, BY, V, big):
    spec = f'Spec.{n}()'
    lg = '{==}'  # the validator's acceptance of the schema by evaluation (decode_unique.valid_unique)
    if big:
        # the bytes as a variable (a parameter typed with the long literal byte list
        # overflows stock Bend's stack); the same law at eby := {==}
        w(f'def {n}_spec_unique({sig}, +by: +List<U32>, +eby: {{by == {BY} : +List<U32>}}, +v: S.Value, spec: Decoding.decodes({spec}, by, v))')
        w(f'    -> {{v == {V} : S.Value}}:')
        w(f'  E.valid_unique({spec}, by, v, {V}, {lg}, spec,')
        w(f'    F.logic__subst(+List<U32>, z => Decoding.decodes({spec}, z, {V}), {BY}, by, Equal.sym(+List<U32>, by, {BY}, eby), C.{n}_spec_encode({args})))')
    else:
        w(f'def {n}_spec_unique({sig}, +v: S.Value, spec: Decoding.decodes({spec}, {BY}, v))')
        w(f'    -> {{v == {V} : S.Value}}:')
        w(f'  E.valid_unique({spec}, {BY}, v, {V}, {lg}, spec, C.{n}_spec_encode({args}))')


def forms():
    """(name, family, arg) of the generic sub-word forms this generator covers."""
    import generate as G
    import laws as LW
    import root_laws_generic as RG
    gn = RG.generic_names()
    out = []
    for n, t in gn.items():
        if not t.fixed() or LW.word_aligned(t):
            continue
        if t.kind == 'bool':
            out.append((n, 'scalar', 'bool'))
        elif t.kind == 'uint':
            out.append((n, 'scalar', {1: 'u8', 2: 'u16'}[t.fixed_size()]))
        elif t.kind == 'vector':
            e = t.elem
            k = 'bool' if e.kind == 'bool' else {1: 'u8', 2: 'u16'}[e.fixed_size()]
            out.append((n, 'vector', (k, t.size)))
        elif t.kind == 'bits':
            out.append((n, 'bits', (t.size, f'Bitvector{t.size}')))
        elif t.kind in ('container', 'pcontainer'):
            fl = []
            for f, ft in t.fields:
                assert ft.kind == 'uint', (n, ft.kind)
                fl.append((f, ft.fixed_size()))
            out.append((n, 'cont', fl))
    # the generic suite's bool form is the fork's boolean (codegen/names.py: one type, one set of
    # files): its word-level laws (one law over the byte, not the fork's per-value ones) still
    # state against the fork's runtime and schema, for the e2e bridges. (The generic uint8 form's
    # would reuse the fork's per-bit law names in spec_small.bend; its bridge uses those.)
    for n in SHARED:
        out.append((n, 'scalar', 'bool'))
    return out


