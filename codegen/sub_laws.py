        tl = [f'B.byte_sel({j}, U32.or(0, {yl}))' if j < kk else (f'B.byte_sel({j}, _)' if j == kk else f'B.byte_sel({j}, {yl})') for j in range(rb)]
        pre = f'List.append(&2, U32, SF.limbs({wl(ys[:-1])}), {wl(tl)})' if len(ys) > 1 else wl(tl)
