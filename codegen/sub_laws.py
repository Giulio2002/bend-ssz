#!/usr/bin/env python3
"""Spec codec laws for the fixed-size generic forms with sub-word leaves.

    python3 codegen/sub_laws.py [--check]

Writes proofs/obj/sub_pack.bend (the byte-level packing lemmas, proved once for
every length) and the per-form law files proofs/obj/sub_*.bend.

The forms: bool, uint8, uint16, Vector[bool/uint8/uint16, n], BitVector[n] of
partial words, the three small generic containers and the progressive
container. Their encodings are byte lists that do not fall on word boundaries.
The spec value of a form is a function of its bytes (vu8/vbool/vu16/bits), and
the spec side is proved by induction over the byte list (sub_pack), not by
cases over byte values: the only facts about a single byte are that a byte of
a word is below 256 (its high bits are clear) and what the spec encoding of a
byte-sized value is, both proved over the 32 bits of a word with linear case
splits.
"""
