def bits_laws(w, n, nbits, rec, P, BB='SP2'):
    """BitVector[nbits] of partial words: the object is the record `rec` of words."""
    nbytes = (nbits + 7) // 8
    nw = (nbytes + 3) // 4
    rb = nbytes - 4 * (nw - 1)
    r = rb % 4
    k = nbits - 32 * (nw - 1)
    rbits = nbits % 8
    m = rb - 1
    d = depth(nw)
    xs = [f'x{i}' for i in range(nw)]
    pads = [f'p{i}' for i in range((1 << d) - nw)]
    buf = f'B.Buf{{{tree(xs + pads)}, {nbytes}}}'
    obj = f'T.{rec}{{{", ".join(xs[:-1] + ([f"U32.and({xs[-1]}, {KEEP[r]})"] if r else [xs[-1]]))}}}'
    RT = f'B.Buf & Maybe<&1, T.{rec}>'
    BY = bytes_of(xs, r)
    full, last = xs[:-1], xs[-1]
    WA = wp(A)
    spec = f'Spec.{n}()'
    sig = ', '.join(f'+{x}: U32' for x in xs)
    psig = ', '.join([sig] + [f'+{p}: U32' for p in pads])
    M = f'U32.not(O.low_mask({rbits}))'
    HP = lambda x: f'{{U32.is_eq(U32.and(B.byte_sel({m}, {x}), {M}), 0) == True{{}} : Bool}}'
    hp = f', +hp: {HP(last)}' if rbits else ''
    hpa = ', hp' if rbits else ''
    tbits = A[:k]
    w(f'# ---- {n}: BitVector[{nbits}], {nbytes} bytes ----')
    w(f'# the first {k} bits of the last word')
    w(f'def {n}_tb(w: U32) -> +List<Bool>:')
    w('  match w:')
    w(f'    case {WA}: [{", ".join(tbits)}]')
    w('')
    w(f'def {n}_tb_len(+w: U32) -> {{List.length(&2, Bool, {n}_tb(w)) == {k}n : Nat}}:')
    w('  match w:')
    w(f'    case {WA}: {{==}}')
    w('')
    # pack of the tail bits: the bytes of the last word
    tbytes = [f'B.byte_sel({j}, {WA})' for j in range(rb)]
    octs = []
    for j in range(rb):
        bb = A[8 * j:8 * j + 8] if (j < rb - 1 or rbits == 0) else A[8 * j:8 * j + rbits] + [F_] * (8 - rbits)
        octs.append(f'SB.octet({", ".join(bb)})')
    w(f'def {n}_tail(+w: U32{", +hp: " + HP("w") if rbits else ""}) -> {{SB.pack({n}_tb(w)) == [{", ".join(f"B.byte_sel({j}, w)" for j in range(rb))}] : +List<U32>}}:')
    w('  match w:')
    w(f'    case {WA}:')
    RHS = f'[{", ".join(tbytes)}]'
    for j in range(rb):
        ctx = tbytes[:j] + ['_'] + octs[j + 1:]
        if j < rb - 1 or rbits == 0:
            prf = f'FB.byte{j}_octet({", ".join(A)})'
        else:
            Pj = wp(A[8 * j:8 * j + 8] + [F_] * 24)
            hpp = f'F.logic__subst(U32, z => {{U32.is_eq(U32.and(z, {M}), 0) == True{{}} : Bool}}, B.byte_sel({j}, {WA}), {Pj}, BT.sel{j}({", ".join(A)}), hp)'
            prf = (f'Equal.trans(U32, {octs[j]}, {Pj}, B.byte_sel({j}, {WA}), {BB}.pz{rbits}_7({", ".join(A[8 * j:8 * j + 8])}, {hpp}), '
                   f'Equal.sym(U32, B.byte_sel({j}, {WA}), {Pj}, BT.sel{j}({", ".join(A)})))')
        w(f'      %Equal.sym(U32, {octs[j]}, {tbytes[j]}, {prf}) :')
        w(f'        {{[{", ".join(ctx)}] == {RHS} : +List<U32>}}')
    w('      {==}')
    w('')
    BITS = f'{n}_tb({last})' if not full else f'List.append(&2, Bool, FB.bitsof({wl(full)}), {n}_tb({last}))'
    V = f'S.BitsValue{{{BITS}}}'
    # length of the bits
    if full:
        hl = (f'Equal.trans(Nat, List.length(&2, Bool, {BITS}), Nat.add(List.length(&2, Bool, FB.bitsof({wl(full)})), List.length(&2, Bool, {n}_tb({last}))), {nbits}n, '
              f'{BB}.lenb_app(FB.bitsof({wl(full)}), {n}_tb({last})), '
              f'Equal.trans(Nat, Nat.add(List.length(&2, Bool, FB.bitsof({wl(full)})), List.length(&2, Bool, {n}_tb({last}))), Nat.add(FB.bitlen({wl(full)}), {k}n), {nbits}n, '
              f'Equal.trans(Nat, Nat.add(List.length(&2, Bool, FB.bitsof({wl(full)})), List.length(&2, Bool, {n}_tb({last}))), Nat.add(FB.bitlen({wl(full)}), List.length(&2, Bool, {n}_tb({last}))), Nat.add(FB.bitlen({wl(full)}), {k}n), '
              f'Equal.cong(Nat, Nat, z => Nat.add(z, List.length(&2, Bool, {n}_tb({last}))), List.length(&2, Bool, FB.bitsof({wl(full)})), FB.bitlen({wl(full)}), FB.len_bits({wl(full)})), '
              f'Equal.cong(Nat, Nat, z => Nat.add(FB.bitlen({wl(full)}), z), List.length(&2, Bool, {n}_tb({last})), {k}n, {n}_tb_len({last}))), {{==}}))')
        pk = (f'Equal.trans(+List<U32>, SB.pack({BITS}), List.append(&2, U32, SF.limbs({wl(full)}), SB.pack({n}_tb({last}))), {BY}, {BB}.pack_app({wl(full)}, {n}_tb({last})), '
              f'Equal.cong(+List<U32>, +List<U32>, z => List.append(&2, U32, SF.limbs({wl(full)}), z), SB.pack({n}_tb({last})), [{", ".join(f"B.byte_sel({j}, {last})" for j in range(rb))}], {n}_tail({last}{hpa})))')
    else:
        hl = f'{n}_tb_len({last})'
        pk = f'{n}_tail({last}{hpa})'
    hle = f'F.logic__subst(Nat, z => {{Nat.is_eq(z, {nbits}n) == True{{}} : Bool}}, {nbits}n, List.length(&2, Bool, {BITS}), Equal.sym(Nat, List.length(&2, Bool, {BITS}), {nbits}n, {hl}), {{==}})'
    w(f'def {n}_spec_parts({sig}{hp})')
    w(f'    -> {{Codec.parts({V}, {spec}) == Some{{[S.Fixed{{{BY}}}]}} : Maybe<&2, +List<S.Part>>}}:')
    w(f'  %Equal.sym(Bool, Nat.is_eq(List.length(&2, Bool, {BITS}), {nbits}n), True{{}}, {hle}) :')
    w(f'    {{Codec.one(SBF.encoding(Bool.and(Nat.is_lt(0n, {nbits}n), _), {BITS}), Some{{{nbytes}n}}) == Some{{[S.Fixed{{{BY}}}]}} : Maybe<&2, +List<S.Part>>}}')
    w(f'  %Equal.sym(+List<U32>, SB.pack({BITS}), {BY}, {pk}) :')
    w(f'    {{Codec.one(Some{{_}}, Some{{{nbytes}n}}) == Some{{[S.Fixed{{{BY}}}]}} : Maybe<&2, +List<S.Part>>}}')
    w('  {==}')
    w('')
    args = ', '.join(xs)
    w(f'def {n}_spec_encode({sig}{hp})')
    w(f'    -> Decoding.decodes({spec}, {BY}, {V}):')
    w(f'  SF.encoding_of_parts({spec}, {V}, {BY}, {n}_spec_parts({args}{hpa}))')
    w('')
    w(f'def {n}_spec_decode({psig}{hp})')
    w(f'    -> {{T.{n}_decode({buf}, {nbytes}) == ({buf}, Some{{{obj}}}) : {RT}}}:')
    if rbits:
        w(f'  %Equal.sym(Bool, U32.is_eq(U32.and(B.byte_sel({m}, {last}), {M}), 0), True{{}}, hp) : {{T.{n}_built({nbytes}, ({buf}, _)) == ({buf}, Some{{{obj}}}) : {RT}}}')
    w('  {==}')
    w('')
    if rbits:
        w(f'# a buffer with a padding bit set is refused')
        w(f'def {n}_spec_reject_pad({psig}, +hp: {{U32.is_eq(U32.and(B.byte_sel({m}, {last}), {M}), 0) == False{{}} : Bool}})')
        w(f'    -> {{T.{n}_decode({buf}, {nbytes}) == ({buf}, None{{}}) : {RT}}}:')
        w(f'  %Equal.sym(Bool, U32.is_eq(U32.and(B.byte_sel({m}, {last}), {M}), 0), False{{}}, hp) : {{T.{n}_built({nbytes}, ({buf}, _)) == ({buf}, None{{}}) : {RT}}}')
        w('  {==}')
        w('')
    w(f'def {n}_spec_view({psig})')
    w(f'    -> {{B.emit({buf}, 0, {nw}) == ({buf}, {BY}) : B.Buf & +List<U32>}}:')
    w('  {==}')
    w('')
    ys = [f'y{i}' for i in range(nw)]
    oy = f'T.{rec}{{{", ".join(ys)}}}'
    E = f'T.{n}_encode({oy})'
    w(f'def {n}_spec_bytes({", ".join(f"+{y}: U32" for y in ys)})')
    w(f'    -> {{B.emit({E}, 0, {nw}) == ({E}, {bytes_of(ys, r)}) : B.Buf & +List<U32>}}:')
