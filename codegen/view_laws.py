"""The view of a packed list after one element is written: proofs/obj/view_<family>.bend.

The spec value of a packed list or vector (the `Sequence` of its items, the view the root and encode bridges state against)
is built from the word list of its storage, element i from the K words of block i. When the runtime writes one element
(K words at word K*J, the chain of F.array__upd that proofs/obj/coll_words.bend calls <kind>_write, words_win.bend's tk) the
view is the old view with item J replaced by the view of the new element (value_set.bend's items_set):

    view_set(c, d, t, x0..x{K-1}, J, q, hq: q == BASE(J), hb: q + K <= 2^d, pf)
        Sequence{ITEMS(c, slots(freeze(thaw(tk([x..], d, t, q, 0)))), 0)}
          == field_set(Sequence{ITEMS(c, slots(freeze(thaw(t))), 0)}, J, MK(x0..x{K-1}))

for a perfect tree t of depth d. It holds for any item count c (no relation between c and the storage is needed: a block
past the written one is the same, and the written one is inside the tree). The proof is one induction (items_set) over the
items, with the word-level facts of words_win.bend (a word before, inside or after the run). codegen/coll_laws.py composes
view_set with the runtime's write (coll_<...>_api_view_set) for each collection whose view is this family's items.

Families (FAMILIES): each has the block size K, the base word of block i, the element as the view builder reads it, and the
builder. The file proofs/obj/view_<family>.bend has: elem_to (the element is MK of the words when each word is given), the
gap lemmas (block i ends before block J when i < J), el_hit / el_same (the written element, every other one), items_same,
items_set (the induction) and view_set.

    python3 codegen/view_laws.py            # write
    python3 codegen/view_laws.py --check    # nonzero exit if an output is stale or orphaned
"""
