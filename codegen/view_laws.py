def family(name, sp):
    K = sp['K']
    BASE, MK, EL, ITEMS = sp['BASE'], sp['MK'], sp['EL'], sp['ITEMS']
    xs = ['x%d' % m for m in range(K)]
    ys = ['y%d' % m for m in range(K)]
    XS = '[%s]' % ', '.join(xs)
    KN = '%dn' % K
    out = []
    w = out.append

    def atom(W, i, m):
        return 'MR.wd(%s, Nat.add(%s, %dn))' % (W, BASE(i), m)
    imps = ['import Base', 'import ../../src/obj.bend as O', 'import ../../types/schema.bend as S', 'import ../compact/found.bend as F',
            'import ./mtree_run.bend as MR', 'import ./value_set.bend as VS', 'import ./words_rw.bend as WR', 'import ./words_win.bend as WW']
    for a, p in sp['imports'].items():
        imps.append('import %s as %s' % (p, a))
    w('\n'.join(imps))
    w('')
    w(HEADER)
    w('# The view of %s after one element (%d words at word %s) is written into perfect storage: the view before with that item replaced.' % (sp['doc'], K, BASE('J')))
    w('# See codegen/view_laws.py.')
