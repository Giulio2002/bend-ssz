def outputs():
    outs = {OBJ / ('view_%s.bend' % n): family(n, sp) for n, sp in FAMILIES.items()}
    outs[OBJ / 'view_seq.bend'] = viewseq.seq_file()
    outs[OBJ / 'view_bytes.bend'] = viewbytes.bytes_file()
    return outs


def main():
    check = '--check' in sys.argv
    outs = outputs()
    stale = [p.name for p, t in outs.items() if not p.exists() or p.read_text() != t]
    orphans = sorted({p.name for p in OBJ.glob('view_*.bend')} - {p.name for p in outs})
    if check:
        if stale or orphans:
            print('stale: ' + ', '.join(stale + [o + ' (orphan)' for o in orphans]))
            sys.exit(1)
        print('view_laws: %d files up to date' % len(outs))
        return
    for p, t in outs.items():
        if not p.exists() or p.read_text() != t:
            p.write_text(t)
    for o in orphans:
        (OBJ / o).unlink()
    print('view_laws: %d files' % len(outs))


if __name__ == '__main__':
    main()
