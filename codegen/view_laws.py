def arith_e8(K=8):
    return '''def blk(+i: Nat) -> {Nat.add(O.e8(i), 8n) == O.e8(1n+i) : Nat}:
  Equal.trans(Nat, Nat.add(O.e8(i), 8n), Nat.add(8n, O.e8(i)), O.e8(1n+i), F.nat__add_comm(O.e8(i), 8n), {==})

def mono(+a: Nat, +b: Nat, +h: {Nat.is_le(a, b) == True{} : Bool}) -> {Nat.is_le(O.e8(a), O.e8(b)) == True{} : Bool}:
  F.nat__double_le(Nat.double(Nat.double(a)), Nat.double(Nat.double(b)), F.nat__double_le(Nat.double(a), Nat.double(b), F.nat__double_le(a, b, h)))
'''


def arith_double():
    return '''def blk(+i: Nat) -> {Nat.add(Nat.double(i), 2n) == Nat.double(1n+i) : Nat}:
  Equal.trans(Nat, Nat.add(Nat.double(i), 2n), Nat.add(2n, Nat.double(i)), Nat.double(1n+i), F.nat__add_comm(Nat.double(i), 2n), {==})

def mono(+a: Nat, +b: Nat, +h: {Nat.is_le(a, b) == True{} : Bool}) -> {Nat.is_le(Nat.double(a), Nat.double(b)) == True{} : Bool}:
  F.nat__double_le(a, b, h)
'''


def arith_mul12():
    return '''def blk(+i: Nat) -> {Nat.add(Nat.mul(i, 12n), 12n) == Nat.mul(1n+i, 12n) : Nat}:
  Equal.trans(Nat, Nat.add(Nat.mul(i, 12n), 12n), Nat.add(12n, Nat.mul(i, 12n)), Nat.mul(1n+i, 12n), F.nat__add_comm(Nat.mul(i, 12n), 12n), {==})

def mono(+a: Nat, +b: Nat, +h: {Nat.is_le(a, b) == True{} : Bool}) -> {Nat.is_le(Nat.mul(a, 12n), Nat.mul(b, 12n)) == True{} : Bool}:
  match a b:
    case 0n _: F.nat__zero_le(Nat.mul(b, 12n))
    case 1n+p 0n: Empty.absurd({Nat.is_le(Nat.mul(1n+p, 12n), Nat.mul(0n, 12n)) == True{} : Bool}, F.logic__false_true(h))
    case 1n+p 1n+q: F.nat__le_add_left(Nat.mul(p, 12n), Nat.mul(q, 12n), 12n, mono(p, q, h))
'''



def pre_u64():
    """items2 (the uint64 items read by word index) and its equality with the views' structural builders"""
    t = """# element i of a uint64 list: words 2i and 2i + 1 (low, high), read by word index
def el2(+W: List<&2, U32>, +i: Nat) -> S.Value:
  S.UnsignedValue{P.UInt{MR.wd(W, Nat.add(Nat.double(i), 0n)), MR.wd(W, Nat.add(Nat.double(i), 1n)), 0, 0, 0, 0, 0, 0}}

def items2(k: Nat, +W: List<&2, U32>, +i: Nat) -> S.Value:
  match k:
    case 0n: S.EmptyItems{}
    case 1n+q: S.Items{el2(W, i), items2(q, W, 1n+i)}

# the items from the next element on are the items of the words after this element's two
def items2_shift(+k: Nat, +a: U32, +b: U32, +rest: List<&2, U32>, +i: Nat) -> {items2(k, Con{a, Con{b, rest}}, 1n+i) == items2(k, rest, i) : S.Value}:
  match k:
    case 0n: {==}
    case 1n+q:
      %Equal.sym(S.Value, items2(q, Con{a, Con{b, rest}}, 1n+(1n+i)), items2(q, rest, 1n+i), items2_shift(q, a, b, rest, 1n+i)) :
        {S.Items{el2(Con{a, Con{b, rest}}, 1n+i), _} == S.Items{el2(rest, i), items2(q, rest, 1n+i)} : S.Value}
      {==}
"""
    for name, fn in (('UL_L.uitems', 'conv_uitems'), ('PK_L.it8', 'conv_it8')):
        t += """
# the structural builder over a word list that holds its words is the indexed one
def %(fn)s(+k: Nat, +W: List<&2, U32>, +h: {Nat.is_le(Nat.double(k), F.spec_common__length(U32, W)) == True{} : Bool})
    -> {%(nm)s(k, W) == items2(k, W, 0n) : S.Value}:
  match k W:
    case 0n _: {==}
    case 1n+c Nil{}: Empty.absurd({%(nm)s(1n+c, Nil{}) == items2(1n+c, Nil{}, 0n) : S.Value}, F.logic__false_true(h))
    case 1n+c Con{a, t0}:
      match t0:
        case Nil{}: Empty.absurd({%(nm)s(1n+c, Con{a, Nil{}}) == items2(1n+c, Con{a, Nil{}}, 0n) : S.Value}, F.logic__false_true(h))
        case Con{b, rest}:
          %%Equal.sym(S.Value, items2(c, Con{a, Con{b, rest}}, 1n), items2(c, rest, 0n), items2_shift(c, a, b, rest, 0n)) :
            {%(nm)s(1n+c, Con{a, Con{b, rest}}) == S.Items{el2(Con{a, Con{b, rest}}, 0n), _} : S.Value}
          %%Equal.sym(S.Value, %(nm)s(c, rest), items2(c, rest, 0n), %(fn)s(c, rest, h)) :
            {S.Items{S.UnsignedValue{P.UInt{a, b, 0, 0, 0, 0, 0, 0}}, _} == S.Items{el2(Con{a, Con{b, rest}}, 0n), items2(c, rest, 0n)} : S.Value}
          {==}
""" % dict(nm=name, fn=fn)
    return t


