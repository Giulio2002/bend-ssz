#!/usr/bin/env python3
"""The generic SSZ schemas of the official ssz_generic suite, as generator input.

The 109 mainnet Fulu names come from codegen/fulu.yaml. The official
`ssz_generic` suite additionally exercises SSZ *forms* that are not Fulu type
names: progressive lists, progressive bit lists, progressive containers and
compatible unions, plus containers, vectors and lists over every basic type.
Those forms are part of the supported public API, so they are generated by the
same generator, from the same shape system, into types/generic_obj*.bend.

The schema descriptions themselves come from the frozen, protected
`tools/test_schemas.py` (the same source the official-case runner uses), so
this module adds no independent notion of what the official cases mean: it
only translates the frozen description into the generator's `Ty` tree and
gives each distinct container a deterministic generated name.

    python3 codegen/generic.py --list      # the distinct schemas and their names

A schema this module cannot translate raises SchemaError; the generator never
guesses, and an unsupported form is never silently accepted.
"""
import argparse
import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'codegen'))
sys.path.insert(0, str(ROOT / 'tools'))

from schema import SchemaError, Ty  # noqa: E402

# A progressive sequence has no declared limit. The generator states limits as
# U32 comparisons and treats anything at or above 2^32 as "no U32 length can
# exceed it" (generate.u32_limit), so this sentinel makes the shared list code
# emit exactly the unbounded check. It is never used as a real length.
PROG = 1 << 64


def canon(s):
    return json.dumps(s, sort_keys=True, separators=(',', ':'))


def _key(prefix, s):
    """The old hashed name of a schema (names.py maps it to the readable name)."""
    return prefix + hashlib.sha256(canon(s).encode()).hexdigest()[:10].upper()


_KT = None


def _name(prefix, s):
    """The readable name of a schema (codegen/names.py: structural names, the official class names)."""
    global _KT
    if _KT is None:
        import names as NM
        _KT = NM.key_table()
    return _KT[_key(prefix, s)]


def convert(s, where='schema'):
    """One frozen schema description as a generator `Ty`."""
    if not isinstance(s, dict) or 'kind' not in s:
        raise SchemaError(f'{where}: not a schema description')
    k = s['kind']
    if k == 'bool':
        return Ty('bool')
    if k == 'uint':
        if s['size'] not in (1, 2, 4, 8, 16, 32):
            raise SchemaError(f'{where}: unsupported uint width {s["size"]}')
        return Ty('uint', s['size'])
    if k == 'bytes':
        if s['length'] == 0:
            raise SchemaError(f'{where}: a zero-length byte vector is not an SSZ type')
        return Ty('bytes', s['length'])
    if k == 'bits':
        if s['length'] == 0:
            raise SchemaError(f'{where}: a zero-length bit vector is not an SSZ type')
        return Ty('bits', s['length'])
    if k == 'bytelist':
        return Ty('bytelist', s['limit'])
    if k == 'bitlist':
        return Ty('bitlist', s['limit'])
    if k == 'vector':
        if s['length'] == 0:
            raise SchemaError(f'{where}: a zero-length vector is not an SSZ type')
        return Ty('vector', s['length'], convert(s['element'], where + '.element'))
    if k == 'list':
        return Ty('list', s['limit'], convert(s['element'], where + '.element'))
    if k == 'progressive_list':
        return Ty('plist', PROG, convert(s['element'], where + '.element'))
    if k == 'progressive_bits':
        return Ty('pbits', PROG)
    if k in ('container', 'progressive_container'):
        # The generated field name is prefixed: a bare "B" or "D" would shadow
        # the module aliases the emitted code uses for src/buffer.bend and
        # src/digest.bend inside the same parameter list.
        fields = tuple(('f_' + f, convert(t, f'{where}.{f}')) for f, t in s['fields'])
        if not fields:
            raise SchemaError(f'{where}: a container needs at least one field')
        if k == 'container':
            return Ty('container', fields=fields, name=_name('Gc', s))
        active = tuple(int(b) for b in s['active'])
        if any(b not in (0, 1) for b in active):
            raise SchemaError(f'{where}: the active mask is a bit vector')
        if sum(active) != len(fields):
            raise SchemaError(f'{where}: the active mask must name exactly the given fields')
        if len(active) > 31:
            raise SchemaError(f'{where}: more than 31 active positions is not supported')
        return Ty('pcontainer', fields=fields, active=active, name=_name('Gp', s))
    if k == 'compatible_union':
        opts = tuple((f'o{i}', convert(t, f'{where}.option{i}')) for i, t in enumerate(s['options']))
        sels = tuple(int(x) for x in s['selectors'])
        if len(sels) != len(opts) or not opts:
            raise SchemaError(f'{where}: one selector per option')
        if any(x < 0 or x > 255 for x in sels) or len(set(sels)) != len(sels):
            raise SchemaError(f'{where}: selectors are distinct bytes')
        return Ty('cunion', fields=opts, selectors=sels, name=_name('Gu', s))
    raise SchemaError(f'{where}: unsupported generic form {k!r}')


def distinct():
    """The distinct schema descriptions of the official generic suite."""
    from test_schemas import for_case
    cases = json.loads((ROOT / 'cases.json').read_text())
    out = {}
    for c in cases:
        if '/ssz_generic/' not in c:
            continue
        raw = for_case(c)
        if raw is None:
            continue
        out.setdefault(canon(raw), raw)
    return [raw for _, raw in sorted(out.items())]


def inventory_all():
    """[(generated name, Ty or None, error or None)] for every distinct schema.

    A schema the translation refuses (a zero-length vector, say, which is not
    an SSZ type) keeps its name and carries the reason: the generator records
    it as unsupported rather than emitting a codec that guesses.
    """
    rows, seen = [], set()
    for raw in distinct():
        try:
            t = convert(raw)
            err = None
        except SchemaError as exc:
            t, err = None, str(exc)
        if t is not None and t.kind in ('container', 'pcontainer', 'cunion'):
            n = t.name
        else:
            n = _name('Gt', raw)
            if t is not None:
                t = Ty(t.kind, t.size, t.elem, t.fields, n, t.active, t.selectors)
        if t is not None and t.kind in ('bool', 'uint'):
            import names as NM
            if n in NM.fork_basic():
                continue    # the fork's own basic types (boolean, uint8/32/64/256): one type, one set of files
        if n in seen:
            raise SchemaError(f'generated name collision: {n}')
        seen.add(n)
        rows.append((n, t, err))
    return rows


def inventory():
    """{generated name: (Ty, raw)} for the schemas the generator supports."""
    out = {}
    raws = {canon(r): r for r in distinct()}
    for n, t, err in inventory_all():
        if err is None:
            out[n] = t
    byname = {}
    for raw in distinct():
        try:
            t = convert(raw)
        except SchemaError:
            continue
        n = t.name if t.kind in ('container', 'pcontainer', 'cunion') else _name('Gt', raw)
        if n not in out:
            continue
        byname[n] = (out[n], raw)
    return byname


def case_names():
    """Every official generic case mapped to the generated name of its schema."""
    from test_schemas import for_case
    byraw = {}
    for raw in distinct():
        try:
            t = convert(raw)
            n = t.name if t.kind in ('container', 'pcontainer', 'cunion') else _name('Gt', raw)
        except SchemaError:
            n = _name('Gt', raw)
        byraw[canon(raw)] = n
    cases = json.loads((ROOT / 'cases.json').read_text())
    out = {}
    for c in cases:
        if '/ssz_generic/' not in c:
            continue
        raw = for_case(c)
        if raw is None:
            continue
        out[c] = byraw[canon(raw)]
    return out


if __name__ == '__main__':
    ap = argparse.ArgumentParser()
    ap.add_argument('--list', action='store_true')
    a = ap.parse_args()
    rows = inventory_all()
    ok = [r for r in rows if r[2] is None]
    print(f'{len(rows)} distinct official generic schemas, {len(ok)} translated, '
          f'{len(rows) - len(ok)} refused as not SSZ types')
    if a.list:
        for n, t, err in rows:
            print(f'{n:14} {(t.kind if t else "REFUSED"):12} {err or ""}')
