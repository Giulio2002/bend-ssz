def info(X, amap):
    """the decode law's depth and byte size, the element bytes, the reject law's file"""
    f = OBJ / f'spec_garr_{X}.bend'
    if not f.exists():
        return None
    s = f.read_text()
    md = re.search(r'^def ' + X + r'_spec_decode\(\+t: F\.array__Tree<U32>, \+pt: \{F\.array__perfect\(U32, (\d+)n, t\) == True\{\} : Bool\}\)\n'
                   r'    -> \{' + X + r'_r\.' + X + r'_decode\(B\.Buf\{F\.array__thaw\(U32, t\), (\d+)\}, \2\)', s, re.M)
    me = re.search(r'^def ' + X + r'_spec_encode\(\+t: F\.array__Tree<U32>, \+pt: \{F\.array__perfect\(U32, (\d+)n, t\) == True\{\} : Bool\}, '
                   r'\+s: S\.Schema, \+es: \{s == Spec\.' + X + r'\(\) : S\.Schema\}\)\n    -> Decoding\.decodes\(s, SF\.limbs\(F\.array__slots\(U32, t\)\), '
                   r'S\.Sequence\{AV\.(chu\d+)\(F\.array__slots\(U32, t\)\)\}\):', s, re.M)
    mr = re.search(r'^def ' + X + r'_spec_reject\(buf: B\.Buf, \+m: U32, e: \{U32\.is_eq\(m, (\d+)\) == False\{\} : Bool\}\)', s, re.M)
    rj = amap['map'][X].get('decode_reject', [])
    if not (md and me and mr and rj) or md.group(1) != me.group(1) or md.group(2) != mr.group(1):
        return None
    eb = {'chu1': 4, 'chu2': 8, 'chu4': 16, 'chu8': 32}[me.group(2)]
    d, N = int(md.group(1)), int(md.group(2))
    if 4 * 2 ** d != N or N % eb:
        return None
    rtext = (OBJ / rj[0]['file']).read_text()
    mk = re.search(r'^def ' + X + r'_decode_reject\(\+bs: \+List<U32>, \+hn: \{Nat\.is_eq\(List\.length\(&2, U32, bs\), (' + str(N) + r'n|VRF\.SZ\(GS\.' + X + r'\(\)\))\) == False\{\} : Bool\}\) -> Decoding\.outside_image\(GS\.' + X + r'\(\), bs\):', rtext, re.M)
    if not mk:
        return None
    return {'d': d, 'N': N, 'eb': eb, 'k': N // eb, 'rj': rj[0]['file'], 'rk': mk.group(1)}


