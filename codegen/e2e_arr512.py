"""The (ii)/(iii) bridges of the word-storage vectors whose decode laws are over one perfect tree
(vec_uint{32,64,128,256}_512: spec_arr.uvec, the laws <X>_spec_decode(t, pt), <X>_spec_reject,
<X>_spec_encode(t, pt, s, es) in proofs/obj/spec_garr_<X>.bend). codegen/e2e_bridge.py calls
build() from outputs() and owns the manifest.

The loader's buffer on a byte list bs of the right length is B.Buf{thaw(segt(d, 0, wlp(bs))), N}
(e2e_load.bf), a perfect tree of the decode law's depth, whose byte view is bs (e2e_load.vw), as
for FuluBlob (e2e_fix_d.py). The decoded object's value is the object API's view
(packed_obj_light.vview<K>); e2e_vw512.vw<K> shows it is the spec encode law's value
S.Sequence{chu(slots(t))} for such an object. Sizes and depths stay symbolic (dd, ed: {dd == Dn})
as in the FuluBlob file.

build(amap) -> ({support fname: text}, {bridge fname: text}, {R: (fname, laws)})
"""
