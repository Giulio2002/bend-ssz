    # NB within NL
    L_.append(f'  +hN1 = FD.logic__subst(Nat, z => {{Nat.is_le(z, NL) == True{{}} : Bool}}, U32.to_nat(NB), Nat.add(VSP.x8(m), h), eNB, hNL)')
