def zbits():
    """from ZF(8 b, bits of u): u is zero (b = 0), or its bytes k >= b are"""
    a = bits32('a')
    ps = ', '.join(f'+{x}: Bool' for x in a)
    lst = ' <> '.join(a) + ' <> []'
    U = f'U32{{{wpat(a)}}}'
    pat = wpat(['+' + x for x in a])
    out = []
    for b in range(4):
        goals = [('w0', f'{{{U} == 0 : U32}}', '{u == 0 : U32}')] if b == 0 else \
                [(f'b{b}_{k}', f'{{{BYTE[k].format(w=U)} == 0 : U32}}', f'{{{BYTE[k].format(w="u")} == 0 : U32}}') for k in range(b, 4)]
        for nm, goal, ug in goals:
            out += [f'def zg{nm}({ps}, +h: {{HV.ZF({8 * b}n, {lst}) == True{{}} : Bool}})', f'    -> {goal}:']
            ind = '  '
            for j in range(8 * b, 32):
                out.append(f'{ind}match a{j}:')
                out.append(f'{ind}  case True{{}}: Empty.absurd({goal}, FD.logic__false_true(h))')
                out.append(f'{ind}  case False{{}}:')
                ind += '    '
            out.append(f'{ind}{{==}}')
            out += [f'def z{nm}(+u: U32, +h: {{HV.ZF({8 * b}n, BLf.wbits(u)) == True{{}} : Bool}}) -> {ug}:',
                    '  match u:', f'    case U32{{{pat}}}: zg{nm}({", ".join(a)}, h)', '']
    return '\n'.join(out)


def zbb(R, w0, b0):
    """bdrop(R, chunk q of W) is zero: word Q = 8 q + w0 has no bit set from c <= 8 b0, the words past Q are zero"""
    r4, rb = divmod(R, 4)
    first_zero = r4 + (1 if rb else 0)
    IDX = lambda j: f'Nat.add(O.e8(Nat.add(q, 0n)), {j}n)'
    lines = []
    args = []
    hps = []
    for j in range(first_zero, 8):
        if j > w0:
            lt = (f'FD.logic__subst(Nat, z => {{Nat.is_lt(z, {IDX(j)}) == True{{}} : Bool}}, {IDX(w0)}, Q, Equal.sym(Nat, Q, {IDX(w0)}, eQ), '
                  f'ltk(O.e8(Nat.add(q, 0n)), {w0}n, {j}n, {{==}}))')
            lines.append(f'  +hw{j} = hp{j}({IDX(j)}, {lt})')
            hps.append(j)
        else:  # j == w0, b0 == 0: the whole word
            lines.append(f'  +hw{j} = zw0(MR.wd(W, {IDX(j)}), zq)')
        args.append(f'hw{j}')
    if rb:
        for k in range(rb, 4):
            lines.append(f'  +hb{k} = zb{b0}_{k}(MR.wd(W, {IDX(r4)}), zq)')
            args.append(f'hb{k}')
    need_zq = rb or (w0 >= first_zero and w0 < 8)
    pre = []
    if need_zq:
        pre.append(f'  +zq = FD.logic__subst(Nat, z => {{HV.ZF({8 * b0}n, BLf.wbits(MR.wd(W, z))) == True{{}} : Bool}}, Q, {IDX(w0)}, eQ, zfm(c, {8 * b0}n, BLf.wbits(MR.wd(W, Q)), hz, hc))')
    tail = '{==}' if R == 32 else f'DZ.zb{R}(W, q' + ''.join(', ' + x for x in args) + ')'
    HP = ''.join(f', hp{j}: @+x: Nat -> @+hx: {{Nat.is_lt(Q, x) == True{{}} : Bool}} -> {{MR.wd(W, x) == 0 : U32}}' for j in (hps if R != 32 else []))
    sig_ = (f'def zbb{R}_{w0}(+W: List<&2, U32>, +q: Nat, +Q: Nat, +c: Nat{HP},\n'
            f'    +eQ: {{Q == {IDX(w0)} : Nat}}, +hz: {{HV.ZF(c, BLf.wbits(MR.wd(W, Q))) == True{{}} : Bool}}, +hc: {{Nat.is_le(c, {8 * b0}n) == True{{}} : Bool}})\n'
            f'    -> {{WS.bdrop({R}n, WS.cb(W, Nat.add(q, 0n))) == SP.zero_bytes(Nat.sub(32n, {R}n)) : +List<U32>}}:\n')
    body = [] if R == 32 else pre + lines
    return sig_ + ''.join(l + '\n' for l in body) + f'  {tail}\n'


def zbbs():
    out = []
    for R in range(1, 33):
        combos = {(R // 4, R % 4)} if R % 4 else {(R // 4 - 1, 4), (R // 4, 0)}
        for w0, b0 in sorted(combos):
            out.append(zbb(R, w0, b0))
    return '\n'.join(out)


