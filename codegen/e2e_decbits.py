def cases():
    out = [ARITH]
    for d in (0, 1):
        for v in range(32):
            out.append(case00() if (d == 0 and v == 0) else case(d, v))
        out.append(dispatch_d(d))
    out.append(TOP)
    return '\n'.join(out)


def text():
    t = IMPORTS + HEAD
    t += '\n# ---- ZF gives zw, per bit ----\n'
    for k in range(32):
        t += '\n' + zfw(k)
    t += '\n# ---- bits_above_zero gives zw, per bit ----\n'
    for k in range(32):
        t += '\n' + bzk(k)
    t += '\n' + bzw() + '\n' + lt32() + ZT + CNT + ZFM + '\n' + zbits() + '\n# ---- the zero tail of chunk q of a bit list\'s words ----\n\n' + zbbs() + TREE + cases()
    return t


def main():
    t = text()
    if '--check' in sys.argv:
        if not OUT.exists() or OUT.read_text() != t:
            print('stale: e2e/e2e_db.bend')
            sys.exit(1)
        print('e2e_decbits: up to date')
        return
    OUT.write_text(t)
    print('e2e_decbits: wrote e2e/e2e_db.bend')


if __name__ == '__main__':
    main()
