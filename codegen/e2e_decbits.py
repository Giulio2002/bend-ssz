def bits32(pre):
    return [f'{pre}{i}' for i in range(32)]


def wpat(vs):
    s = 'WNil{}'
    for v in reversed(vs):
        s = f'WCon{{{v}, {s}}}'
    return s


def byte_end(k):
    return (k // 8) * 8 + 7


def zfw(k):
    """ZF(k, bits of u) gives zw(k, u): the bits k .. the end of k's byte are clear (a case on each)"""
    a = bits32('a')
    pat = wpat(['+' + x for x in a])
    ps = ', '.join(f'+{x}: Bool' for x in a)
    lst = ' <> '.join(a) + ' <> []'
    out = []
    if k % 8 != 0:
        goal = f'{{BK.zb{k}({", ".join(a)}) == True{{}} : Bool}}'
        out += [f'def zfg{k}({ps}, +h: {{HV.ZF({k}n, {lst}) == True{{}} : Bool}})', f'    -> {goal}:']
        ind = '  '
        for j in range(k, byte_end(k) + 1):
            out.append(f'{ind}match a{j}:')
            out.append(f'{ind}  case True{{}}: Empty.absurd({goal}, FD.logic__false_true(h))')
            out.append(f'{ind}  case False{{}}:')
            ind += '    '
        out.append(f'{ind}{{==}}')
    out += [f'def zfw{k}(+u: U32, +h: {{HV.ZF({k}n, BLf.wbits(u)) == True{{}} : Bool}}) -> {{BK.zw({k}n, u) == True{{}} : Bool}}:',
            '  match u:', f'    case U32{{{pat}}}:']
    out.append('      {==}' if k % 8 == 0 else f'      zfg{k}({", ".join(a)}, h)')
    return '\n'.join(out) + '\n'


