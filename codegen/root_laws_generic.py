def generic_names():
    """{name: Ty} of the generic forms types/generic_obj.bend implements."""
    names = {}
    for n, t, err in GE.inventory_all():
        if err is not None:
            continue
        try:
            probe = G.Gen()
            probe.shape(t)
            for s in probe.order:
                G.emit_shape(s, lambda _x: None)
        except Exception:  # the generator refuses it: no code, no law
            continue
        names[n] = t
    return names


def swap_head(head):
    out = []
    for line in head:
        line = line.replace('../../types/fulu_obj.bend as T', '../../types/generic_obj.bend as T')
        line = line.replace('../../spec/fulu_schemas.bend as Spec', './generic_specs.bend as Spec')
        line = line.replace('./root_names.bend as RN', './root_gnames.bend as RN')
        out.append(line)
        if line == 'import ./packed_obj.bend as PK':
            out.append('import ./packed_bytes.bend as PB')
            out.append('import ./prog_list.bend as PG')
    return out


WIDTH = {1: 'P.U8{}', 2: 'P.U16{}', 4: 'P.U32Width{}', 8: 'P.U64{}', 16: 'P.U128{}', 32: 'P.U256{}'}


def spec_of(t):
    """The types/schema.bend term of a schema tree (every generic form)."""
    k = t.kind
    if k == 'bool':
        return 'S.Boolean{}'
    if k == 'uint':
        return f'S.Unsigned{{{WIDTH[t.size]}}}'
    if k == 'bytes':
        return f'S.ByteVector{{{t.size}n}}'
    if k == 'bytelist':
        return f'S.ByteList{{{t.size}n}}'
    if k == 'bits':
        return f'S.BitVector{{{t.size}n}}'
    if k == 'bitlist':
        return f'S.BitList{{{t.size}n}}'
    if k == 'vector':
        return f'S.Vector{{{spec_of(t.elem)}, {t.size}n}}'
    if k == 'list':
        return f'S.ListOf{{{spec_of(t.elem)}, {t.size}n}}'
    if k == 'plist':
        return f'S.ProgressiveList{{{spec_of(t.elem)}}}'
    if k == 'pbits':
        return 'S.ProgressiveBits{}'
    chain = 'S.End{}'
    for _, ft in reversed(t.fields):
        chain = f'S.Chain{{{spec_of(ft)}, {chain}}}'
    names = '[' + ', '.join(f'"{f}"' for f, _ in t.fields) + ']'
    if k == 'container':
        return f'S.Container{{{names}, {chain}}}'
    if k == 'pcontainer':
        act = '[' + ', '.join('True{}' if a else 'False{}' for a in t.active) + ']'
        return f'S.ProgressiveContainer{{{names}, {chain}, {act}}}'
    if k == 'cunion':
        sels = '[' + ', '.join(str(x) for x in t.selectors) + ']'
        return f'S.CompatibleUnion{{{sels}, {chain}}}'
    raise RA.Skip(f'no specification schema for kind {k}')


def emit_specs(names, g):
    L = ['import Base', 'import ../../types/schema.bend as S', 'import ../../types/primitive.bend as P', '',
         '# GENERATED by codegen/root_laws_generic.py. Do not edit.',
         '# The specification schema of every supported generic SSZ form (the frozen',
         '# ssz_generic descriptions of tools/test_schemas.py, via codegen/generic.py).', '']
    skipped = {}
    for n, t in names.items():
        try:
            L.append(f'def {n}() -> S.Schema: {spec_of(t)}')
        except RA.Skip as e:
            skipped[n] = str(e)
    return '\n'.join(L) + '\n', skipped


def emit_phase_a(names, g):
    RA.EXTRA_LEAVES = True
    try:
        return _emit_phase_a(names, g)
    finally:
        RA.EXTRA_LEAVES = False


EXTRA_A = ['import ./leaf_small.bend as LS', './gleaf.bend as GL', './dk.bend as DK', '../../proofs/integer_decoding.bend as ID',
           '../../proofs/power_division.bend as PD', '../../proofs/word_split.bend as WSp']


def _emit_phase_a(names, g):
    covered_shapes, skipped = [], {}
    for s in g.order:
        if s.kind == 'box':
            continue
        try:
            RA.covered(s)
            RA.spec_schema(s)
            covered_shapes.append(s)
        except RA.Skip as e:
            skipped[s.p] = str(e)
    lines = swap_head(RA.HEAD) + [x if x.startswith('import ') else 'import ' + x for x in EXTRA_A] + ['', '# GENERATED by codegen/root_laws_generic.py. Do not edit.',
                                  '# Root laws of the generic forms (Data-kind shapes), as proofs/obj/root_names.bend.', '']
    RA.PRE.clear()
    body = []
    for s in covered_shapes:
        body.append(f'# ---- {s.p} ({s.kind}) ----')
        RA.emit_shape_laws(s, body.append)
        body.extend(RA.PRE)
        RA.PRE.clear()
        body.append('')
    good = {s.p for s in covered_shapes}
    laws, status = [], {}
    for n, t in names.items():
        s = g.shape(t)
        if s.p in good:
            RA.emit_name_law(laws.append, n, s)
            status[n] = 'proved (phase A)'
        else:
            status[n] = skipped.get(s.p, 'not covered')
    return '\n'.join(lines + body + laws) + '\n', status, good


class GenB(RB.Gen):
    def __init__(self, names):
        self.names = names
        self.g = G.Gen()
        for n, t in names.items():
            self.g.shape(t)
        self.done = {}
        self.out = []
        self.phaseA = set()
        RA.EXTRA_LEAVES = True
        try:
            for s in self.g.order:
                if s.kind == 'box':
                    continue
                try:
                    RA.covered(s)
                    RA.spec_schema(s)
                    self.phaseA.add(s.p)
                except RA.Skip:
                    pass
        finally:
            RA.EXTRA_LEAVES = False


def emit_phase_b(names):
    gb = GenB(names)
    saved = RB.HEAD, RB.BIG_NAMES
    try:
        RB.HEAD = swap_head(RB.HEAD)
        RB.BIG_NAMES = ()
        text, _big, status = gb.run()
    finally:
        RB.HEAD, RB.BIG_NAMES = saved
    text = text.replace('# Root laws of the Type-kind containers (see the generator).',
                        '# Root laws of the generic forms (Type-kind shapes), as proofs/obj/root_types.bend.')
    text = text.replace('# GENERATED by codegen/root_laws_b.py.', '# GENERATED by codegen/root_laws_generic.py (via root_laws_b.py).')
    return text, status


