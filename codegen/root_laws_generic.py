    if depth == 0:
        w(f'def {n}_st(+hl: Nat, -h: B.Buf, {wargs}{aargs}) -> {{T.{s.p}_root(hl, h, {R}{{{", ".join(wsx)}}}, 0) == (h, {DIG}) : B.Buf & D.Digest}}: {{==}}')
    else:
        # The reference tree over opaque chunk digests is the runtime's node
        # shape (SHA stays unevaluated on opaque digests); the runtime root is
        # then that shape over the actual chunks, compared syntactically. A
        # direct {==} would evaluate SHA-256 over the partly known last word.
        xs = [f'x{c}' for c in range(nc)]

        def shape(d, st, inside, leaves):
            if not inside:
                return 'D.zero()' if d == 0 else f'D.zconst({d}n)'
            if d == 0:
                return leaves[st]
            half = 2 ** (d - 1)
            return f'D.node(hl, {shape(d - 1, st, True, leaves)}, {shape(d - 1, st + half, st + half < nc, leaves)})'
        xargs = ', '.join(f'+{x}: D.Digest' for x in xs)
        w(f'def {n}_shape(+hl: Nat, {xargs}) -> {{MD.rtree({depth}n, True{{}}, hl, [{", ".join(xs)}], 0n) == {shape(depth, 0, True, xs)} : D.Digest}}: {{==}}')
        w(f'def {n}_st(+hl: Nat, -h: B.Buf, {wargs}{aargs}) -> {{T.{s.p}_root(hl, h, {R}{{{", ".join(wsx)}}}, 0) == (h, {DIG}) : B.Buf & D.Digest}}:')
        w(f'  %Equal.sym(D.Digest, {DIG}, {shape(depth, 0, True, dl)}, {n}_shape(hl, {", ".join(dl)})) :')
        w(f'    {{T.{s.p}_root(hl, h, {R}{{{", ".join(wsx)}}}, 0) == (h, _) : B.Buf & D.Digest}}')
        w('  {==}')
    # The public root is the runtime root, over an opaque object (a delta step;
    # the SHA code stays unevaluated). Rewriting with it first keeps every later
    # comparison syntactic: unequal-looking roots over the partly known last word
    # would otherwise be compared by evaluating SHA-256 on both sides.
    w(f'def {n}_htr(-h: B.Buf, +o: {R}) -> {{T.{n}_hash_tree_root(h, o) == T.{s.p}_root(64n, h, o, 0) : B.Buf & D.Digest}}: {{==}}')
    # The spec relation for a root r given its gate, over an OPAQUE digest r: the
    # output Pair.snd(h, r) reduces to r itself, so no digest is ever evaluated.
    w(f'def {n}_fin(-h: B.Buf, +r: D.Digest, {wargs}{aargs}, +hg: {{Bits.bitvector_at_depth({nb}n, {depth}n, {BITS}) == Some{{D.bytes(r)}} : {M}}})')
    w(f'    -> RR.roots(S.BitsValue{{{BITS}}}, Spec.{n}(), [D.bytes(Pair.snd(B.Buf, D.Digest, (h, r)))]):')
    w(f'  ({depth}n, ({{==}}, hg))')
    # _h is stated for a symbolic hash length hl (with hl == 64n as a hypothesis):
    # D.node(hl, ...) then stays unevaluated even though the last word is built
    # from the bit variables a0.., which SHA's word operations could otherwise
    # unfold through. hl becomes 64n only in the law, over the opaque last word.
    w(f'def {n}_h(-h: B.Buf, +hl: Nat, +ehl: {{hl == 64n : Nat}}, {wargs}+t: Word({k}n))')
    w(f'    -> RR.roots(S.BitsValue{{BLP.btk({nb}n, BLP.bitsof([{", ".join(wlt)}]))}}, Spec.{n}(), [D.bytes(Pair.snd(B.Buf, D.Digest, T.{s.p}_root(hl, h, {obj}, 0)))]):')
    w('  match t:')
    w(f'    case {lowp}:')
    objx = f'{R}{{' + ', '.join(wsx) + '}'
    w(f'      %Equal.sym(B.Buf & D.Digest, T.{s.p}_root(hl, h, {objx}, 0), (h, {DIG}), {n}_st(hl, h, {wcall}{acall})) :')
    w(f'        RR.roots(S.BitsValue{{BLP.btk({nb}n, BLP.bitsof({WL}))}}, Spec.{n}(), [D.bytes(Pair.snd(B.Buf, D.Digest, _))])')
    w(f'      {n}_fin(h, {DIG}, {wcall}{acall}, {n}_g(hl, ehl, {wcall}{acall}))')
    last = ws[-1]
    shape = f'U32{{WSp.join({k}n, {32 - k}n, WSp.take({k}n, 32n, PD.bits({last})), Word.zero({32 - k}n))}}'
    mot_ws = ws[:-1] + ['_']
    E = f'{{{n}_last(o) == U32{{WSp.join({k}n, {32 - k}n, WSp.take({k}n, 32n, PD.bits({n}_last(o))), Word.zero({32 - k}n))}} : U32}}'
    # The composition for a symbolic hash length, destructuring o. The law below
    # turns the public root into the runtime root at 64n while o is still opaque
    # (with o's fields exposed, the root at 64n would reduce into SHA-256).
    w(f'def {n}_lawg(-h: B.Buf, +hl: Nat, +ehl: {{hl == 64n : Nat}}, +o: {R}, +e: {E})')
    w(f'    -> RR.roots(S.BitsValue{{{n}_bits(o)}}, Spec.{n}(), [D.bytes(Pair.snd(B.Buf, D.Digest, T.{s.p}_root(hl, h, o, 0)))]):')
    w('  match o:')
    w(f'    case {pat}:')
    w(f'      %Equal.sym(U32, {last}, {shape}, e) :')
    w(f'        RR.roots(S.BitsValue{{BLP.btk({nb}n, BLP.bitsof([{", ".join(mot_ws)}]))}}, Spec.{n}(), [D.bytes(Pair.snd(B.Buf, D.Digest, T.{s.p}_root(hl, h, {R}{{{", ".join(mot_ws)}}}, 0)))])')
    w(f'      {n}_h(h, hl, ehl, {wcall}WSp.take({k}n, 32n, PD.bits({last})))')
    w(f'# {n}: for every object whose bits past {nb} are zero, the runtime root is a')
    w('# specification root of its bits.')
    w(f'law {n}_root_correct:')
    w('  for -h: B.Buf')
    w(f'  for +o: {R}')
    w(f'  for +e: {E}')
    w(f'  RR.roots(S.BitsValue{{{n}_bits(o)}}, Spec.{n}(), [D.bytes(Pair.snd(B.Buf, D.Digest, T.{n}_hash_tree_root(h, o)))])')
    w(f'def {n}_root_correct(h, o, e):')
    w(f'  %Equal.sym(B.Buf & D.Digest, T.{n}_hash_tree_root(h, o), T.{s.p}_root(64n, h, o, 0), {n}_htr(h, o)) :')
