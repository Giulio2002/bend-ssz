def _emit_phase_a(names, g):
    covered_shapes, skipped = [], {}
    for s in g.order:
        if s.kind == 'box':
            continue
        try:
            RA.covered(s)
            RA.spec_schema(s)
            covered_shapes.append(s)
        except RA.Skip as e:
            skipped[s.p] = str(e)
    lines = swap_head(RA.HEAD) + [x if x.startswith('import ') else 'import ' + x for x in EXTRA_A] + ['', '# GENERATED by codegen/root_laws_generic.py. Do not edit.',
                                  '# Root laws of the generic forms (Data-kind shapes), as proofs/obj/root_names.bend.', '']
    if any(RA.partial_bits(s) for s in covered_shapes):
        lines += PBITS_LEMMAS
    RA.PRE.clear()
    body = []
    for s in covered_shapes:
        body.append(f'# ---- {s.p} ({s.kind}) ----')
        RA.emit_shape_laws(s, body.append)
        body.extend(RA.PRE)
        RA.PRE.clear()
        body.append('')
    good = {s.p for s in covered_shapes}
    laws, status = [], {}
    for n, t in names.items():
        s = g.shape(t)
        if s.p in good and not RA.partial_bits(s):
            RA.emit_name_law(laws.append, n, s)
            status[n] = 'proved (phase A)'
        else:
            status[n] = skipped.get(s.p, 'not covered')
    return '\n'.join(lines + body + laws) + '\n', status, good


class GenB(RB.Gen):
    def __init__(self, names):
        self.names = names
        self.g = G.Gen()
        for n, t in names.items():
            self.g.shape(t)
        self.done = {}
        self.okinfo = {}
        self.out = []
        self.phaseA = set()
        RA.EXTRA_LEAVES = True
        try:
            for s in self.g.order:
                if s.kind == 'box':
                    continue
                try:
                    RA.covered(s)
                    RA.spec_schema(s)
                    self.phaseA.add(s.p)
                except RA.Skip:
                    pass
        finally:
            RA.EXTRA_LEAVES = False


    def eqs_closed(self, p):
        """A proof of eqs_p(S) for the closed schema S of p: every component is
        a closed schema equation ({==}), in eqs_proof's structure."""
        m = self.meta[p]
        comps = []
        for i in m['eqt']:
            fs, k = m['F'][i][1], m['kinds'][i]
            if k in ('data', 'datar', 'boxD', 'xl', 'px') or (k == 'tl' and fs.elem.inner.kind != 'container'):
                comps.append('{==}')
            elif k == 'tl':
                comps.append(self.eqs_closed(fs.elem.inner.p))
            else:
                inner = fs.inner if k == 'boxT' else fs
                comps.append(self.eqs_closed(inner.p))
        if not comps:
            return 'Unit{}'
        t = comps[-1]
        for c in reversed(comps[:-1]):
            t = f'({c}, {t})'
        return t

    def union_law(self, name, s):
        """A compatible union: one constructor per option; the root mixes the
        selector into the option's root (spec/root_relation.bend Selected)."""
        p = s.p
        R = RA.qual(s.rep)
        sels = list(s.t.selectors)
        opts = [o for _, o in s.options]
        n = len(opts)
        kinds = []
        for o in opts:
            if o.data:
                if o.p not in self.phaseA:
                    raise RB.Skip(f'{p}: option {o.p} not a phase A shape')
                kinds.append('A')
            elif o.kind == 'container':
                self.shape(o)
                kinds.append('B')
            else:
                raise RB.Skip(f'{p}: option {o.p} of kind {o.kind}')
        L = []
        w = L.append
        TY = f'B.Buf & ({R} & D.Digest)'
        w(f'# ---- {p} (compatible union, selectors {sels}) ----')
        for i, o in enumerate(opts):
            RO = RA.qual(o.rep)
            w(f'def pju_{p}_{i}(o: {R}) -> {RO}:')
            w('  match o:')
            for j, o2 in enumerate(opts):
                w(f'    case {R}_c{j}{{v}}: ' + ('v' if j == i else f'T.{o.p}_default()'))

        def view(i, v):
            return f'RN.v_{opts[i].p}({v})' if kinds[i] == 'A' else f'v_{opts[i].p}({v})'

        def dig(i, v):
            return f'RN.d_{opts[i].p}(hl, {v})' if kinds[i] == 'A' else f'd_{opts[i].p}(hl, {v})'
        w(f'def v_{p}(o: {R}) -> S.Value:')
        w('  match o:')
        for i in range(n):
            w(f'    case {R}_c{i}{{v}}: S.Selected{{{sels[i]}, {view(i, "v")}}}')
        w(f'def d_{p}(+hl: Nat, o: {R}) -> D.Digest:')
        w('  match o:')
        for i in range(n):
            w(f'    case {R}_c{i}{{v}}: O.mix_len(hl, {dig(i, "v")}, {sels[i]})')
        # the representation: the object is one of its options, represented
        OS_ = [spec_of(o.t) for o in opts]
        for i, o in enumerate(opts):
            RO = RA.qual(o.rep)
            if kinds[i] == 'A':
                body = f'{{o == {R}_c{i}{{v}} : {R}}}'
                if RA.needs_rep(o):
                    body = f'DK.P2({body}, RN.rp_{o.p}(v))'
                w(f'def pc_{p}_{i}(o: {R}) -> Data: DK.Ex({RO}, v => {body})')
            else:
                w(f'def pc_{p}_{i}(o: {R}) -> Data: DK.P2({{o == {R}_c{i}{{pju_{p}_{i}(o)}} : {R}}}, rep_{o.p}(pju_{p}_{i}(o), {OS_[i]}))')
        for k in range(n - 2, -1, -1):
            nxt = f'pc_{p}_{n - 1}(o)' if k == n - 2 else f'por_{p}_{k + 1}(o)'
            w(f'def por_{p}_{k}(o: {R}) -> Data: DK.Or2(pc_{p}_{k}(o), {nxt})')
        w(f'def rep_{p}(o: {R}) -> Data: ' + (f'pc_{p}_0(o)' if n == 1 else f'por_{p}_0(o)'))
        # per option: the state law and the spec law
        for i, o in enumerate(opts):
            RO = RA.qual(o.rep)
            w(f'def stc_{p}_{i}(+hl: Nat, -h: B.Buf, -o: {R}, +seg: U32, +a: pc_{p}_{i}(o))')
            w(f'    -> {{T.{p}_root(hl, h, o, seg) == (h, (o, d_{p}(hl, o))) : {TY}}}:')
            if kinds[i] == 'A':
                if RA.needs_rep(o):
                    w('  (+v, +q) = a')
                    w('  (+eo, +rp) = q')
                else:
                    w('  (+v, +eo) = a')
                ob = f'{R}_c{i}{{v}}'
                w(f'  %Equal.sym({R}, o, {ob}, eo) : {{T.{p}_root(hl, h, _, seg) == (h, (_, d_{p}(hl, _))) : {TY}}}')
                w(f'  %Equal.sym(B.Buf & D.Digest, T.{o.p}_root(hl, h, v, seg), (h, RN.d_{o.p}(hl, v)), RN.st_{o.p}(hl, h, v, seg)) :')
                w(f'    {{T.{p}_rt{i}(hl, v, _) == (h, ({ob}, d_{p}(hl, {ob}))) : {TY}}}')
                w('  {==}')
            else:
                wv = f'pju_{p}_{i}(o)'
                ob = f'{R}_c{i}{{{wv}}}'
                w('  (+eo, +ri) = a')
                w(f'  %Equal.sym({R}, o, {ob}, eo) : {{T.{p}_root(hl, h, _, seg) == (h, (_, d_{p}(hl, _))) : {TY}}}')
                w(f'  %Equal.sym(B.Buf & ({RO} & D.Digest), T.{o.p}_root(hl, h, {wv}, seg), (h, ({wv}, d_{o.p}(hl, {wv}))), st_{o.p}(hl, h, {wv}, seg, {OS_[i]}, ri)) :')
                w(f'    {{T.{p}_rt{i}(hl, _) == (h, ({ob}, d_{p}(hl, {ob}))) : {TY}}}')
                w('  {==}')
            w(f'def rsc_{p}_{i}(+hl: Nat, +ehl: {{hl == 64n : Nat}}, -h: B.Buf, -o: {R}, +a: pc_{p}_{i}(o))')
            w(f'    -> RR.roots(v_{p}(o), Spec.{name}(), [D.bytes(d_{p}(hl, o))]):')
            if kinds[i] == 'A':
                rp = RA.needs_rep(o)
                if rp:
                    w('  (+v, +q) = a')
                    w('  (+eo, +rp) = q')
                else:
                    w('  (+v, +eo) = a')
                wv = 'v'
                ob = f'{R}_c{i}{{v}}'
                rs = f'RN.rs_{o.p}(hl, ehl, v' + (', rp)' if rp else ')')
            else:
                w('  (+eo, +ri) = a')
                wv = f'pju_{p}_{i}(o)'
                ob = f'{R}_c{i}{{{wv}}}'
                okp = '{==}'
                rs = f'rs_{o.p}(hl, ehl, h, {wv}, {OS_[i]}, ri, OS.DV0(), {{==}}, {okp}, {self.eqs_closed(o.p)})'
                # the option's digest as a value (the object is erased): its witness
                wd = f'wd_{o.p}(hl, {wv}, {OS_[i]}, ri)'
                w(f'  +dd = OS.dwv({dig(i, wv)}, {wd})')
                w(f'  +de = OS.dwe({dig(i, wv)}, {wd})')
            w(f'  %Equal.sym({R}, o, {ob}, eo) : RR.roots(v_{p}(_), Spec.{name}(), [D.bytes(d_{p}(hl, _))])')
            if kinds[i] == 'A':
                w(f'  (D.bytes({dig(i, wv)}), ({rs}, PCN.msel_{sels[i]}(hl, ehl, {dig(i, wv)})))')
            else:
                w(f'  %Equal.sym(D.Digest, {dig(i, wv)}, dd, de) : RR.roots(v_{p}({ob}), Spec.{name}(), [D.bytes(O.mix_len(hl, _, {sels[i]}))])')
                w(f'  (D.bytes(dd), (OS.dtrans({view(i, wv)}, {OS_[i]}, dd, {dig(i, wv)}, de, {rs}), PCN.msel_{sels[i]}(hl, ehl, dd)))')
        # the sum, level by level
        for kind_, res, args, call in (('st', f'{{T.{p}_root(hl, h, o, seg) == (h, (o, d_{p}(hl, o))) : {TY}}}', '+hl: Nat, -h: B.Buf, -o: {R}, +seg: U32', 'hl, h, o, seg'),
                                       ('rs', f'RR.roots(v_{p}(o), Spec.{name}(), [D.bytes(d_{p}(hl, o))])', '+hl: Nat, +ehl: {{hl == 64n : Nat}}, -h: B.Buf, -o: {R}', 'hl, ehl, h, o')):
            A_ = args.replace('{R}', R).replace('{{', '{').replace('}}', '}')
            leaf = 'stc' if kind_ == 'st' else 'rsc'
            for k in range(n - 2, -1, -1):
                w(f'def {kind_}l_{p}_{k}({A_}, +r: por_{p}_{k}(o)) -> {res}:')
                w('  match r:')
                w(f'    case Inl{{+a}}: {leaf}_{p}_{k}({call}, a)')
                nxt = f'{leaf}_{p}_{n - 1}({call}, b)' if k == n - 2 else f'{kind_}l_{p}_{k + 1}({call}, b)'
                w(f'    case Inr{{+b}}: {nxt}')
            top = f'{leaf}_{p}_0' if n == 1 else f'{kind_}l_{p}_0'
            w(f'def {kind_}_{p}({A_}, +rep: rep_{p}(o)) -> {res}: {top}({call}, rep)')
        concl = f'RR.roots(v_{p}(o), Spec.{name}(), [D.bytes(Pair.snd({R}, D.Digest, Pair.snd(B.Buf, {R} & D.Digest, T.{name}_hash_tree_root(h, o))))])'
        w(f'# {name}: for every represented object (one of its options, represented),')
        w('# the runtime root is a specification root of its value.')
        w(f'law {name}_root_correct:')
        w('  for -h: B.Buf')
        w(f'  for -o: {R}')
        w(f'  for +rep: rep_{p}(o)')
        w(f'  {concl}')
        w(f'def {name}_root_correct(h, o, rep):')
        w(f'  %Equal.sym({TY}, T.{p}_root(64n, h, o, 0), (h, (o, d_{p}(64n, o))), st_{p}(64n, h, o, 0, rep)) :')
        w(f'    RR.roots(v_{p}(o), Spec.{name}(), [D.bytes(Pair.snd({R}, D.Digest, Pair.snd(B.Buf, {R} & D.Digest, _)))])')
        w(f'  rs_{p}(64n, {{==}}, h, o, rep)')
        w('')
        return L


