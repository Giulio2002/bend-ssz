def container_partial_bits(names):
    """The partial-word bit vector shapes that are fields of containers."""
    g = G.Gen()
    out = set()
    for t in names.values():
        g.shape(t)
    for s in g.order:
        if s.kind == 'container':
            for _, fs in s.fields:
                if fs.kind == 'rec' and fs.t.kind == 'bits' and fs.t.size % 32:
                    out.add(fs.p)
    return out


def emit_bits(names):
    """The one-chunk vectors (tree depth 0) together in proofs/obj/gbits_small.bend;
    each vector with more chunks in its own proofs/obj/gbits_<name>.bend (the
    per-law split measured each: depth-0 laws cost nothing beyond the imports)."""
    g = G.Gen()
    small, files, status = [], {}, {}
    for n, t in names.items():
        if t.kind == 'bits' and t.size % 32:
            s = g.shape(t)
            if s.kind != 'rec':
                continue
            law = bits_law(n, t, s)
            if G.log2ceil(G.chunks_of(4 * s.nw)) == 0:
                small.extend(law)
            else:
                files[ROOT / 'proofs/obj' / f'gbits_{n}.bend'] = '\n'.join(BITS_HEAD + law) + '\n'
            status[n] = 'proved (generic partial-word bit vector)'
    files[ROOT / 'proofs/obj/gbits_small.bend'] = '\n'.join(BITS_HEAD + small) + '\n'
    return files, status


def union_selectors(names):
    return sorted({x for t in names.values() if t.kind == 'cunion' for x in t.selectors})


def pcont_patterns(names):
    """The active patterns of every progressive container in the generic forms."""
    pats = set()

    def walk(t):
        if t.kind == 'pcontainer':
            pats.add(tuple(t.active))
        for _, ft in getattr(t, 'fields', None) or []:
            walk(ft)
        if getattr(t, 'elem', None) is not None:
            walk(t.elem)
    for t in names.values():
        walk(t)
    return sorted(pats, key=lambda a: (len(a), a))


def main():
    names = generic_names()
    RA.PARTIAL_OK = container_partial_bits(names)
    RA.PARTIAL_HOOK = partial_bits_shape
    g = G.Gen()
    for n, t in names.items():
        g.shape(t)
    specs, sskip = emit_specs(names, g)
    ta, sa, good = emit_phase_a(names, g)
    tb, sb, tb2 = emit_phase_b(names)
    tl, sl = emit_leaves(names)
    tbits, sbits = emit_bits(names)
    sl = {**sl, **sbits}
    status = {}
    for n in names:
        st_a, st_b = sa.get(n), sb.get(n)
        if n in sl:
            status[n] = sl[n]
        elif st_a and st_a.startswith('proved'):
            status[n] = st_a
        elif st_b and st_b.startswith('proved'):
            status[n] = st_b
        else:
            status[n] = (st_b or st_a or 'not covered') + (f'; spec schema: {sskip[n]}' if n in sskip else '')
    if '--status' in sys.argv:
        for n, st in status.items():
            print(f'{n}: {st}')
        return 0
    outs = [(SPECS, specs), (PCF, PCL.emit_file(pcont_patterns(names), union_selectors(names))), (GA, ta), (GB, tb), (GB2, tb2), (GL, tl)] + sorted(tbits.items())
    if '--check' in sys.argv:
        for path, text in outs:
            if not path.exists() or path.read_text() != text:
                print(f'{path} is stale; run codegen/root_laws_generic.py')
                return 1
        print('generic root laws are current')
        return 0
    for path, text in outs:
        if not path.exists() or path.read_text() != text:
            path.write_text(text)
    return 0


