def leaf_lemmas():
    A = [f'a{i}' for i in range(16)]
    low = 'WNil{}'
    for a in reversed(A):
        low = f'WCon{{{a}, {low}}}'
    pat_hi = 'hi'
    for a in reversed(A):
        pat_hi = f'WCon{{{a}, {pat_hi}}}'
    X = 'U32{WSp.join(16n, 16n, ' + low + ', Word.zero(16n))}'
    Z7 = 'D.be_bytes(0, ' * 7 + '[]' + ')' * 7
    V = f'P.UInt{{{X}, 0, 0, 0, 0, 0, 0, 0}}'
    L = []
    w = L.append
    w('law half_shape:')
    w('  for +x: U32')
    w('  for e: {U32.is_lt(x, 65536) == True{} : Bool}')
    w('  {x == U32{WSp.join(16n, 16n, WSp.take(16n, 32n, PD.bits(x)), Word.zero(16n))} : U32}')
    w('def half_shape(x, e):')
    w('  match x:')
    w(f'    case U32{{{pat_hi}}}:')
    w(f'      Equal.cong(Word(16n), U32, hi => U32{{{pat_hi}}}, hi, Word.zero(16n),')
    w(f'        WSp.below_one(15n, hi, WSp.lt_prefix(16n, 16n, {low}, hi, WCon{{True{{}}, Word.zero(15n)}}, e)))')
    w('')
    w('law u16_w:')
    w('  for +w16: Word(16n)')
    Xw = 'U32{WSp.join(16n, 16n, w16, Word.zero(16n))}'
    w(f'  RR.roots(S.UnsignedValue{{P.UInt{{{Xw}, 0, 0, 0, 0, 0, 0, 0}}}}, S.Unsigned{{P.U16{{}}}}, [D.bytes(O.u32_chunk({Xw}))])')
    w('def u16_w(w16):')
    w('  match w16:')
    w(f'    case {low.replace("WCon{a", "WCon{+a")}:')
    w(f'      %IE.uint_hash_tree_root_correct(P.U16{{}}, {V}) :')
    w(f'        {{_ == Some{{D.be_bytes(B.swap32({X}), {Z7})}} : Maybe<&2, +List<U32>>}}')
    w(f'      %Equal.sym(+List<U32>, D.be_bytes(B.swap32({X}), {Z7}), List.append(&2, U32, I.limb({X}), {Z7}), RL.bytes_swap({X}, {Z7})) :')
    w(f'        {{I.uint_root(P.U16{{}}, {V}) == Some{{_}} : Maybe<&2, +List<U32>>}}')
    w('      {==}')
    w('')
    return L


def leaf_law(n, t):
    L = []
    w = L.append
    root = f'[D.bytes(Pair.snd(B.Buf, D.Digest, T.{n}_hash_tree_root(h, _)))]'
    if t.size == 4:
        w(f'# {n} (uint32): every value.')
        w(f'law {n}_root_correct:')
        w('  for -h: B.Buf')
        w('  for +o: U32')
        w(f'  RR.roots(S.UnsignedValue{{P.UInt{{o, 0, 0, 0, 0, 0, 0, 0}}}}, Spec.{n}(), {root.replace("_)", "o)")})')
        w(f'def {n}_root_correct(h, o): LS.u32_root(o)')
        w('')
        return L
    bound, k, lem = {1: ('256', 8, 'ID.byte_shape'), 2: ('65536', 16, 'half_shape')}[t.size]
    shape = (f'PD.embed8(WSp.take(8n, 32n, PD.bits(o)))' if t.size == 1
             else 'U32{WSp.join(16n, 16n, WSp.take(16n, 32n, PD.bits(o)), Word.zero(16n))}')
    w(f'# {n} (uint{8 * t.size}): every value below {bound} (its representation invariant).')
    w(f'law {n}_root_correct:')
    w('  for -h: B.Buf')
    w('  for +o: U32')
    w(f'  for +e: {{U32.is_lt(o, {bound}) == True{{}} : Bool}}')
    w(f'  RR.roots(S.UnsignedValue{{P.UInt{{o, 0, 0, 0, 0, 0, 0, 0}}}}, Spec.{n}(), {root.replace("_)", "o)")})')
    w(f'def {n}_root_correct(h, o, e):')
    w(f'  %Equal.sym(U32, o, {shape}, {lem}(o, e)) :')
    w(f'    RR.roots(S.UnsignedValue{{P.UInt{{_, 0, 0, 0, 0, 0, 0, 0}}}}, Spec.{n}(), {root})')
    w(f'  {"LS.u8_w" if t.size == 1 else "u16_w"}(WSp.take({k}n, 32n, PD.bits(o)))')
    w('')
    return L


def emit_leaves(names):
    laws, status = [], {}
    for n, t in names.items():
        if t.kind == 'uint' and t.size in (1, 2, 4):
            laws.extend(leaf_law(n, t))
            status[n] = 'proved (generic leaf)'
    return '\n'.join(LEAF_HEAD + leaf_lemmas() + laws) + '\n', status


