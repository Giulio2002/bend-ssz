def bits_law(n, t, s):
    import root_laws as RA
    nb, nw = t.size, s.nw
    k = nb - 32 * (nw - 1)
    R = RA.qual(s.rep).replace('T.', 'T.')
    ws = [f'w{i}' for i in range(nw)]
    A = [f'a{i}' for i in range(k)]
    low = 'WNil{}'
    for a in reversed(A):
        low = f'WCon{{{a}, {low}}}'
    lowp = low.replace('WCon{a', 'WCon{+a')
    X = f'U32{{WSp.join({k}n, {32 - k}n, {low}, Word.zero({32 - k}n))}}'
    XT = f'U32{{WSp.join({k}n, {32 - k}n, t, Word.zero({32 - k}n))}}'
    wsx = ws[:-1] + [X]
    nc = G.chunks_of(4 * nw)
    depth = G.log2ceil(nc)
    M = 'Maybe<&2, +List<U32>>'

    def digs(lst):
        out = []
        for c in range(nc):
            cw = lst[8 * c:8 * c + 8]
            out.append('D.D{' + ', '.join([f'B.swap32({x})' for x in cw] + ['0'] * (8 - len(cw))) + '}')
        return out
    Lc = '[' + ', '.join(digs(wsx)) + ']'
    WL = '[' + ', '.join(wsx) + ']'
    BITS = f'BLP.btk({nb}n, BLP.bitsof({WL}))'
    BYTES = f'WS.btake(Bp.byte_count({nb}n), FX.limbs({WL}))'
    DIG = f'MD.rtree({depth}n, True{{}}, hl, {Lc}, 0n)'
    wargs = ''.join(f'+{x}: U32, ' for x in ws[:-1])
    aargs = ', '.join(f'+{a}: Bool' for a in A)
    wcall = ''.join(f'{x}, ' for x in ws[:-1])
    acall = ', '.join(A)
    L = []
    w = L.append
    w(f'# ---- {n}: Bitvector[{nb}] ({nw} word{"s" if nw > 1 else ""}, {k} bit{"s" if k > 1 else ""} in the last) ----')
    w(f'def {n}_lh({wargs}{aargs}) -> {{Nat.is_le({nb}n, List.length(&2, Bool, BLP.bitsof({WL}))) == True{{}} : Bool}}:')
    w(f'  %Equal.sym(Nat, List.length(&2, Bool, BLP.bitsof({WL})), bl32({WL}), len_bitsof({WL})) :')
    w(f'    {{Nat.is_le({nb}n, _) == True{{}} : Bool}}')
    w('  {==}')
    w(f'def {n}_len({wargs}{aargs}) -> {{List.length(&2, Bool, {BITS}) == {nb}n : Nat}}:')
    w(f'  btk_len({nb}n, BLP.bitsof({WL}), {n}_lh({wcall}{acall}))')
    # the chunks
    w(f'def {n}_ch({wargs}{aargs}) -> {{Pack.scan({BYTES}, 31n, [], []) == MD.bytes_list({Lc}) : +List<+List<U32>>}}:')
    dl = digs(wsx)
    for c in range(nc):
        cw = wsx[8 * c:8 * c + 8]
        m = len(cw)
        done = [f'List.append(&2, U32, FX.limbs([{", ".join(wsx[8 * j:8 * j + 8])}]), SP.zero_bytes({4 * (8 - len(wsx[8 * j:8 * j + 8]))}n))' for j in range(c)]
        rest = [f'D.bytes({dl[j]})' for j in range(c + 1, nc)]
        lst = '[' + ', '.join(done + ['_'] + rest) + ']'
        w(f'  %Equal.sym(+List<U32>, D.bytes({dl[c]}), List.append(&2, U32, FX.limbs([{", ".join(cw)}]), SP.zero_bytes({4 * (8 - m)}n)), RL.bytes_{m}({", ".join(cw)})) :')
        w(f'    {{Pack.scan({BYTES}, 31n, [], []) == {lst} : +List<+List<U32>>}}')
    w('  {==}')
    # the gate
    w(f'def {n}_g(+hl: Nat, +ehl: {{hl == 64n : Nat}}, {wargs}{aargs}) -> {{Bits.bitvector_at_depth({nb}n, {depth}n, {BITS}) == Some{{D.bytes({DIG})}} : {M}}}:')
    w(f'  %Equal.sym(Nat, List.length(&2, Bool, {BITS}), {nb}n, {n}_len({wcall}{acall})) :')
    w(f'    {{Bits.vector_gate(Bool.and(Nat.is_lt(0n, {nb}n), Nat.is_eq(_, {nb}n)), {nb}n, {depth}n, {BITS}) == Some{{D.bytes({DIG})}} : {M}}}')
    w(f'  %Equal.sym(+List<U32>, Bp.pack({BITS}), {BYTES}, BLP.bpack({WL}, {nb}n, {{==}})) :')
    w(f'    {{Lim.at_depth(Bits.chunk_limit({nb}n), {depth}n, Pack.scan(_, 31n, [], [])) == Some{{D.bytes({DIG})}} : {M}}}')
    w(f'  %Equal.sym(+List<+List<U32>>, Pack.scan({BYTES}, 31n, [], []), MD.bytes_list({Lc}), {n}_ch({wcall}{acall})) :')
    w(f'    {{Lim.at_depth(Bits.chunk_limit({nb}n), {depth}n, _) == Some{{D.bytes({DIG})}} : {M}}}')
    w(f'  %Equal.sym({M}, Lim.at_depth(Bits.chunk_limit({nb}n), {depth}n, MD.bytes_list({Lc})), Some{{D.bytes(MD.rtree({depth}n, Nat.is_lt(0n, MD.dlen({Lc})), hl, {Lc}, 0n))}}, RS.at_depth_tree(Bits.chunk_limit({nb}n), {depth}n, hl, {Lc}, {{==}}, {{==}}, ehl)) :')
    w(f'    {{_ == Some{{D.bytes({DIG})}} : {M}}}')
    w('  {==}')
    # the object
    pat = f'{R}{{' + ', '.join('+' + x for x in ws) + '}'
    w(f'def {n}_last(o: {R}) -> U32:')
    w('  match o:')
    w(f'    case {pat}: {ws[-1]}')
    w(f'def {n}_bits(o: {R}) -> +List<Bool>:')
    w('  match o:')
    w(f'    case {pat}: BLP.btk({nb}n, BLP.bitsof([{", ".join(ws)}]))')
    wlt = ws[:-1] + [XT]
    obj = f'{R}{{' + ', '.join(wlt) + '}'
    # the runtime root as the reference tree, at an abstract message length
    if depth == 0:
        w(f'def {n}_st(+hl: Nat, -h: B.Buf, {wargs}{aargs}) -> {{T.{s.p}_root(hl, h, {R}{{{", ".join(wsx)}}}, 0) == (h, {DIG}) : B.Buf & D.Digest}}: {{==}}')
    else:
        # The reference tree over opaque chunk digests is the runtime's node
        # shape (SHA stays unevaluated on opaque digests); the runtime root is
        # then that shape over the actual chunks, compared syntactically. A
        # direct {==} would evaluate SHA-256 over the partly known last word.
        xs = [f'x{c}' for c in range(nc)]

        def shape(d, st, inside, leaves):
            if not inside:
                return 'D.zero()' if d == 0 else f'D.zconst({d}n)'
            if d == 0:
                return leaves[st]
            half = 2 ** (d - 1)
            return f'D.node(hl, {shape(d - 1, st, True, leaves)}, {shape(d - 1, st + half, st + half < nc, leaves)})'
        xargs = ', '.join(f'+{x}: D.Digest' for x in xs)
        w(f'def {n}_shape(+hl: Nat, {xargs}) -> {{MD.rtree({depth}n, True{{}}, hl, [{", ".join(xs)}], 0n) == {shape(depth, 0, True, xs)} : D.Digest}}: {{==}}')
        w(f'def {n}_st(+hl: Nat, -h: B.Buf, {wargs}{aargs}) -> {{T.{s.p}_root(hl, h, {R}{{{", ".join(wsx)}}}, 0) == (h, {DIG}) : B.Buf & D.Digest}}:')
        w(f'  %Equal.sym(D.Digest, {DIG}, {shape(depth, 0, True, dl)}, {n}_shape(hl, {", ".join(dl)})) :')
        w(f'    {{T.{s.p}_root(hl, h, {R}{{{", ".join(wsx)}}}, 0) == (h, _) : B.Buf & D.Digest}}')
        w('  {==}')
    # The public root is the runtime root, over an opaque object (a delta step;
    # the SHA code stays unevaluated). Rewriting with it first keeps every later
    # comparison syntactic: unequal-looking roots over the partly known last word
    # would otherwise be compared by evaluating SHA-256 on both sides.
    w(f'def {n}_htr(-h: B.Buf, +o: {R}) -> {{T.{n}_hash_tree_root(h, o) == T.{s.p}_root(64n, h, o, 0) : B.Buf & D.Digest}}: {{==}}')
    # The spec relation for a root r given its gate, over an OPAQUE digest r: the
    # output Pair.snd(h, r) reduces to r itself, so no digest is ever evaluated.
    w(f'def {n}_fin(-h: B.Buf, +r: D.Digest, {wargs}{aargs}, +hg: {{Bits.bitvector_at_depth({nb}n, {depth}n, {BITS}) == Some{{D.bytes(r)}} : {M}}})')
    w(f'    -> RR.roots(S.BitsValue{{{BITS}}}, Spec.{n}(), [D.bytes(Pair.snd(B.Buf, D.Digest, (h, r)))]):')
    w(f'  ({depth}n, ({{==}}, hg))')
    # _h is stated for a symbolic hash length hl (with hl == 64n as a hypothesis):
    # D.node(hl, ...) then stays unevaluated even though the last word is built
    # from the bit variables a0.., which SHA's word operations could otherwise
    # unfold through. hl becomes 64n only in the law, over the opaque last word.
    w(f'def {n}_h(-h: B.Buf, +hl: Nat, +ehl: {{hl == 64n : Nat}}, {wargs}+t: Word({k}n))')
    w(f'    -> RR.roots(S.BitsValue{{BLP.btk({nb}n, BLP.bitsof([{", ".join(wlt)}]))}}, Spec.{n}(), [D.bytes(Pair.snd(B.Buf, D.Digest, T.{s.p}_root(hl, h, {obj}, 0)))]):')
    w('  match t:')
    w(f'    case {lowp}:')
    objx = f'{R}{{' + ', '.join(wsx) + '}'
    w(f'      %Equal.sym(B.Buf & D.Digest, T.{s.p}_root(hl, h, {objx}, 0), (h, {DIG}), {n}_st(hl, h, {wcall}{acall})) :')
    w(f'        RR.roots(S.BitsValue{{BLP.btk({nb}n, BLP.bitsof({WL}))}}, Spec.{n}(), [D.bytes(Pair.snd(B.Buf, D.Digest, _))])')
    w(f'      {n}_fin(h, {DIG}, {wcall}{acall}, {n}_g(hl, ehl, {wcall}{acall}))')
    last = ws[-1]
    shape = f'U32{{WSp.join({k}n, {32 - k}n, WSp.take({k}n, 32n, PD.bits({last})), Word.zero({32 - k}n))}}'
    mot_ws = ws[:-1] + ['_']
    E = f'{{{n}_last(o) == U32{{WSp.join({k}n, {32 - k}n, WSp.take({k}n, 32n, PD.bits({n}_last(o))), Word.zero({32 - k}n))}} : U32}}'
    # The composition for a symbolic hash length, destructuring o. The law below
    # turns the public root into the runtime root at 64n while o is still opaque
    # (with o's fields exposed, the root at 64n would reduce into SHA-256).
    w(f'def {n}_lawg(-h: B.Buf, +hl: Nat, +ehl: {{hl == 64n : Nat}}, +o: {R}, +e: {E})')
    w(f'    -> RR.roots(S.BitsValue{{{n}_bits(o)}}, Spec.{n}(), [D.bytes(Pair.snd(B.Buf, D.Digest, T.{s.p}_root(hl, h, o, 0)))]):')
    w('  match o:')
    w(f'    case {pat}:')
    w(f'      %Equal.sym(U32, {last}, {shape}, e) :')
    w(f'        RR.roots(S.BitsValue{{BLP.btk({nb}n, BLP.bitsof([{", ".join(mot_ws)}]))}}, Spec.{n}(), [D.bytes(Pair.snd(B.Buf, D.Digest, T.{s.p}_root(hl, h, {R}{{{", ".join(mot_ws)}}}, 0)))])')
    w(f'      {n}_h(h, hl, ehl, {wcall}WSp.take({k}n, 32n, PD.bits({last})))')
    w(f'# {n}: for every object whose bits past {nb} are zero, the runtime root is a')
    w('# specification root of its bits.')
    w(f'law {n}_root_correct:')
    w('  for -h: B.Buf')
    w(f'  for +o: {R}')
    w(f'  for +e: {E}')
    w(f'  RR.roots(S.BitsValue{{{n}_bits(o)}}, Spec.{n}(), [D.bytes(Pair.snd(B.Buf, D.Digest, T.{n}_hash_tree_root(h, o)))])')
    w(f'def {n}_root_correct(h, o, e):')
    w(f'  %Equal.sym(B.Buf & D.Digest, T.{n}_hash_tree_root(h, o), T.{s.p}_root(64n, h, o, 0), {n}_htr(h, o)) :')
    w(f'    RR.roots(S.BitsValue{{{n}_bits(o)}}, Spec.{n}(), [D.bytes(Pair.snd(B.Buf, D.Digest, _))])')
    w(f'  {n}_lawg(h, 64n, {{==}}, o, e)')
    w('')
    return L


def emit_bits(names):
    """The one-chunk vectors (tree depth 0) together in proofs/obj/gbits_small.bend;
    each vector with more chunks in its own proofs/obj/gbits_<name>.bend (the
    per-law split measured each: depth-0 laws cost nothing beyond the imports)."""
    g = G.Gen()
    small, files, status = [], {}, {}
    for n, t in names.items():
        if t.kind == 'bits' and t.size % 32:
            s = g.shape(t)
            if s.kind != 'rec':
                continue
            law = bits_law(n, t, s)
            if G.log2ceil(G.chunks_of(4 * s.nw)) == 0:
                small.extend(law)
            else:
                files[ROOT / 'proofs/obj' / f'gbits_{n}.bend'] = '\n'.join(BITS_HEAD + law) + '\n'
            status[n] = 'proved (generic partial-word bit vector)'
    files[ROOT / 'proofs/obj/gbits_small.bend'] = '\n'.join(BITS_HEAD + small) + '\n'
    return files, status


def main():
    names = generic_names()
    g = G.Gen()
    for n, t in names.items():
        g.shape(t)
    specs, sskip = emit_specs(names, g)
    ta, sa, good = emit_phase_a(names, g)
    tb, sb = emit_phase_b(names)
    tl, sl = emit_leaves(names)
    tbits, sbits = emit_bits(names)
    sl = {**sl, **sbits}
    status = {}
    for n in names:
        st_a, st_b = sa.get(n), sb.get(n)
        if n in sl:
            status[n] = sl[n]
        elif st_a and st_a.startswith('proved'):
            status[n] = st_a
        elif st_b and st_b.startswith('proved'):
            status[n] = st_b
        else:
            status[n] = (st_b or st_a or 'not covered') + (f'; spec schema: {sskip[n]}' if n in sskip else '')
    if '--status' in sys.argv:
        for n, st in status.items():
            print(f'{n}: {st}')
        return 0
    outs = [(SPECS, specs), (GA, ta), (GB, tb), (GL, tl)] + sorted(tbits.items())
    if '--check' in sys.argv:
        for path, text in outs:
            if path.read_text() != text:
                print(f'{path} is stale; run codegen/root_laws_generic.py')
                return 1
        print('generic root laws are current')
        return 0
    for path, text in outs:
        if not path.exists() or path.read_text() != text:
            path.write_text(text)
    return 0


if __name__ == '__main__':
    sys.exit(main())
