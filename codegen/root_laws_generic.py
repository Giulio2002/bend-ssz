def bits_law(n, t, s):
    import root_laws as RA
    nb, nw = t.size, s.nw
    k = nb - 32 * (nw - 1)
    R = RA.qual(s.rep).replace('T.', 'T.')
    ws = [f'w{i}' for i in range(nw)]
    A = [f'a{i}' for i in range(k)]
    low = 'WNil{}'
    for a in reversed(A):
        low = f'WCon{{{a}, {low}}}'
    lowp = low.replace('WCon{a', 'WCon{+a')
    X = f'U32{{WSp.join({k}n, {32 - k}n, {low}, Word.zero({32 - k}n))}}'
    XT = f'U32{{WSp.join({k}n, {32 - k}n, t, Word.zero({32 - k}n))}}'
