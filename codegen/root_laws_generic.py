    DIG = f'MD.rtree({depth}n, True{{}}, hl, {Lc}, 0n)'
    wargs = ''.join(f'+{x}: U32, ' for x in ws[:-1])
    aargs = ', '.join(f'+{a}: Bool' for a in A)
