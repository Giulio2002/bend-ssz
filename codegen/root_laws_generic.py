def emit_phase_b(names):
    """root_gtypes.bend: the phase B laws as before (no progressive bit list
    fields, no partial-word bit vector fields, no unions); root_gtypes2.bend:
    the forms that need them (a separate module, so root_gtypes is not
    re-checked for them)."""
    saved_partial = RA.PARTIAL_OK
    RA.PARTIAL_OK = set()
    gb = GenB(names)
    RA.PARTIAL_OK = saved_partial
    saved = RB.HEAD, RB.BIG_NAMES
    try:
        RB.HEAD = swap_head(RB.HEAD)
        RB.BIG_NAMES = ()
        # the generic forms' small leaves (uint8/uint16 fields) have
        # specification schemas only with root_laws' extra leaves
        RA.EXTRA_LEAVES = True
        text, _big, status = gb.run()
        rest = {n: t for n, t in names.items() if not status.get(n, '').startswith('proved')}
        gb2 = GenB(rest)
        gb2.v2 = True
        RB.HEAD = RB.HEAD + ['import ./pbits_obj.bend as PBO', 'import ./wbits_obj.bend as WBV', 'import ./pcont.bend as PCN',
                              'import ./prog_root.bend as PR', 'import ./plist_obj.bend as PLO']
        RA.EXTRA_LEAVES = True  # GenB() resets it; also the element schemas of lists
        text2, _big2, status2 = gb2.run()
        seen = len(gb2.out)
        ulaws = []
        for n, t in rest.items():
            s = gb2.g.shape(t)
            if s.kind == 'cunion':
                try:
                    ulaws.extend(gb2.union_law(n, s))
                    status2[n] = 'proved (phase B, compatible union)'
                except RB.Skip as e:
                    status2[n] = f'phase B: {e}'
        RA.EXTRA_LEAVES = False
        text2 = text2 + '\n'.join(gb2.out[seen:] + ulaws) + '\n'
    finally:
        RB.HEAD, RB.BIG_NAMES = saved
        RA.EXTRA_LEAVES = False
    text = text.replace('# Root laws of the Type-kind containers (see the generator).',
                        '# Root laws of the generic forms (Type-kind shapes), as proofs/obj/root_types.bend.')
    text = text.replace('# GENERATED by codegen/root_laws_b.py.', '# GENERATED by codegen/root_laws_generic.py (via root_laws_b.py).')
    text2 = text2.replace('# Root laws of the Type-kind containers (see the generator).',
                          '# Root laws of the generic forms that need progressive bit lists, progressive\n'
                          '# containers, partial-word bit vector fields or unions (see root_laws_generic.py).')
    text2 = text2.replace('# GENERATED by codegen/root_laws_b.py. Do not edit.', '# GENERATED by codegen/root_laws_generic.py. Do not edit.')
    for n, st in status2.items():
        status[n] = st.replace('(phase B)', '(phase B, root_gtypes2)')
    return text, status, text2


