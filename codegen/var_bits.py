#!/usr/bin/env python3
"""The bit-list codec laws (runtime O.ok_bitlist / O.bits_in against
spec/bitfields.bend list_encoding).

    python3 codegen/var_bits.py [--check] [--no-big]

proofs/obj/vbyte.bend (generated here, stock): the byte facts by exhaustive
case analysis over the eight bits of a byte w (U32 value PD.embed8(w)):

    oct_pack   pack(b8(w) ++ R) == embed8(w) :: pack(R)
    last_pack  embed8(w) != 0: pack(btk(h, b8(w)) ++ [True]) == [embed8(w)],
               h = O.high_bit(embed8(w)), the runtime's delimiter position
    last_len   |btk(h, b8(w))| == h
    inv_k      (k = 0..7) the byte octet(b0..b_{k-1}, True, 0..) is non-zero
               and its high bit is k.

The byte-list development on top of it is proofs/obj/vbitl.bend.
"""
import sys
from itertools import product
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BYTE = ROOT / 'proofs/obj/vbyte.bend'


def word(bs):
    return ''.join(f'WCon{{{b}, ' for b in bs) + 'WNil{}' + '}' * len(bs)


def tf(b):
    return 'True{}' if b else 'False{}'


def byte_module():
    L = ['import Base', 'import ../../src/obj.bend as O', 'import ../../spec/bit_packing.bend as Bp',
         'import ../../proofs/power_division.bend as PD', 'import ../../proofs/word_split.bend as WSp',
         'import ../compact/found.bend as F', 'import ./bits_leaf.bend as BLf', 'import ./dk.bend as DK', '',
         '# GENERATED by codegen/var_bits.py. Do not edit.',
         '# Byte facts of the bit-list codec, by exhaustive case analysis over the',
         '# eight bits of a byte (see the module docstring of codegen/var_bits.py).', '']
    w = L.append
    C = [f'c{i}' for i in range(8)]
    W8 = 'WCon{+c0, WCon{+c1, WCon{+c2, WCon{+c3, WCon{+c4, WCon{+c5, WCon{+c6, WCon{+c7, WNil{}}}}}}}}}'
    w('''def b8(w: Word(8n)) -> +List<Bool>:
  match w:
    case WCon{c0, WCon{c1, WCon{c2, WCon{c3, WCon{c4, WCon{c5, WCon{c6, WCon{c7, WNil{}}}}}}}}}: [c0, c1, c2, c3, c4, c5, c6, c7]

# The low byte of a word, as the eight bits of the spec's byte.
def bits8(+v: U32) -> +List<Bool>: b8(WSp.take(8n, 32n, PD.bits(v)))

def btk(k: Nat, xs: +List<Bool>) -> +List<Bool>:
  match k:
    case 0n: []
    case 1n+p:
      match xs:
        case Nil{}: []
        case Con{+b, t}: b <> btk(p, t)

def hb(+v: U32) -> Nat: U32.to_nat(O.high_bit(v))

law oct_pack:
  for +w: Word(8n)
  for +R: +List<Bool>
  {Bp.pack(List.append(&2, Bool, b8(w), R)) == PD.embed8(w) <> Bp.pack(R) : +List<U32>}
def oct_pack(w, R):
  match w:
    case ''' + W8 + ''':
      Equal.cong(U32, +List<U32>, z => z <> Bp.pack(R), Bp.octet(c0, c1, c2, c3, c4, c5, c6, c7), PD.embed8(WCon{c0, WCon{c1, WCon{c2, WCon{c3, WCon{c4, WCon{c5, WCon{c6, WCon{c7, WNil{}}}}}}}}}),
        BLf.oct8(c0, c1, c2, c3, c4, c5, c6, c7))
''')
    # last_pack / last_len: 256 leaves
    for name, stmt in [('last_pack', lambda e: f'{{Bp.pack(List.append(&2, Bool, btk(hb({e}), b8(w)), [True{{}}])) == [{e}] : +List<U32>}}'),
                       ('last_len', lambda e: f'{{List.length(&2, Bool, btk(hb({e}), b8(w))) == hb({e}) : Nat}}')]:
        E = 'PD.embed8(w)'
        w(f'law {name}:')
        w('  for +w: Word(8n)')
        w(f'  for +nz: {{U32.is_eq({E}, 0) == False{{}} : Bool}}')
        w(f'  {stmt(E)}')
        w(f'def {name}(w, nz):')
        w('  match w:')
        for bits in product([False, True], repeat=8):
            ww = word([tf(b) for b in bits])
            if not any(bits):
                w(f'    case {ww}: Empty.absurd({stmt(f"PD.embed8({ww})").replace("b8(w)", f"b8({ww})")}, F.logic__true_false(nz))')
            else:
                w(f'    case {ww}: {{==}}')
        w('')
    # inv_k
    for k in range(8):
        bs = [f'b{i}' for i in range(k)]
        oct = 'Bp.octet(' + ', '.join(bs + ['True{}'] + ['False{}'] * (7 - k)) + ')'
        w(f'law inv{k}:')
        for b in bs:
            w(f'  for +{b}: Bool')
        w(f'  DK.P2({{U32.is_eq({oct}, 0) == False{{}} : Bool}}, {{{k}n == hb({oct}) : Nat}})')
        w(f'def inv{k}(' + ', '.join(bs) + '):')
        if k == 0:
            w('  ({==}, {==})')
        else:
            w('  match ' + ' '.join(bs) + ':')
            for bits in product([False, True], repeat=k):
                w('    case ' + ' '.join(tf(b) for b in bits) + ': ({==}, {==})')
        w('')
    return '\n'.join(L) + '\n'


def main():
    out = {BYTE: byte_module()}
    if '--check' in sys.argv:
        stale = [str(p.relative_to(ROOT)) for p, t in out.items() if not p.exists() or p.read_text() != t]
        if stale:
            print('stale generated bit-list laws: ' + ', '.join(stale))
            sys.exit(1)
        print('generated bit-list laws are current')
        return
    for p, t in out.items():
        p.write_text(t)
    print('wrote ' + ', '.join(str(p.relative_to(ROOT)) for p in out))


if __name__ == '__main__':
    main()
