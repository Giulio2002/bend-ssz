#!/usr/bin/env python3
"""Setter laws composed with the root and encode bridges: e2e/<Name>_e2e_set_generated.bend.

proofs/obj/prep_setters.bend (codegen/rep_laws.py) proves, for every field setter set_f of the
Fulu containers listed there, that it keeps the representation invariant: from rep_X(o, s) (and,
for a field with its own invariant, that invariant of the new value v) follows
rep_X(set_f(o, v), s). rep_X(o, Spec.X()) is exactly the premise of X's root bridge
(<Name>_e2e_root: the object's root is API.hash_tree_root of its view), and for a few names the
only premise of the encode bridge (<Name>_e2e_encode). So each setter law composes with those
bridges into a checked statement about an object mutated through the API:

    <Name>_e2e_set_<f>_root(h, o, v, r[, rv]):
        root(set_f(o, v)) == API.hash_tree_root(Spec.X(), view(set_f(o, v)))
    <Name>_e2e_set_<f>_encode(o, v, r[, rv])       (when the encode bridge's only premise is rep)
        Some(encode(set_f(o, v))) == API.serialize(Spec.X(), view(set_f(o, v)))

under rep_X(o, Spec.X()) (and rv). Each proof is the bridge applied to set_f(o, v) and the setter
law. A composition is emitted exactly when the bridge's premises are the object and rep (the
root bridge of every container here; the encode bridge of the containers without storage
premises); an encode bridge with storage premises (hs*, hc*, ...) needs them of set_f(o, v), which
no setter law states, so none is emitted for it (docs/PREMISES.md).

    python3 codegen/e2e_setters.py            # write
    python3 codegen/e2e_setters.py --check    # nonzero exit if any output is stale or orphaned
"""
import json
import os
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
E2E = ROOT / 'e2e'
LAWS = ROOT / 'proofs/obj/prep_setters.bend'
TYPES = ROOT / 'types'
HEADER = '# GENERATED by codegen/e2e_setters.py. Do not edit.'
LAW = re.compile(r'^law (\w+)_set_(\w+)_rep:\n((?:  .*\n)+)', re.M)
IMPORT = re.compile(r'^import (\S+) as (\w+)\s*$', re.M)
VAR_O = re.compile(r'(?<![\w.])o(?![\w.])')
VAR_S = re.compile(r'(?<![\w.])s(?![\w.])')


def imports(path):
    """{alias: root-relative path} of a .bend file"""
    out = {}
    for m in IMPORT.finditer(path.read_text()):
        out[m.group(2)] = os.path.normpath(os.path.join(os.path.relpath(path.parent, ROOT), m.group(1)))
    return out


def split_params(s):
    out, depth, cur = [], 0, ''
    for ch in s:
        if ch in '({[<':
            depth += 1
        elif ch in ')}]>':
            depth -= 1
        if ch == ',' and depth == 0:
            out.append(cur.strip())
            cur = ''
            continue
        cur += ch
    if cur.strip():
        out.append(cur.strip())
    return out


def signature(path, name):
    """(params, conclusion) of the one-line bridge `def name(params) -> {conclusion}:`"""
    lines = path.read_text().split('\n')
    start = [i for i, l in enumerate(lines) if l.startswith('def %s(' % name)]
    if len(start) != 1:
        sys.exit('e2e_setters: %s: def %s not found once' % (path.name, name))
    sig = []
    for l in lines[start[0]:]:
        sig.append(l.strip())
        if l.rstrip().endswith(':'):
            break
    m = re.match(r'def %s\((.*)\)\s*-> (\{.*\}):$' % re.escape(name), ' '.join(sig), re.S)
    return split_params(m.group(1)), m.group(2)


def bridge_file(man, name, law):
    for f, es in man['files'].items():
        for e in es:
            if law in e['laws']:
                return E2E / f
    return None


def setter_laws():
    """{container: {field: (binders [(mode, name, type)], setter expression, module alias of rep)}}"""
    out = {}
    for m in LAW.finditer(LAWS.read_text()):
        x, f, body = m.group(1), m.group(2), m.group(3)
        lines = [l.strip() for l in body.split('\n') if l.strip()]
        binders = []
        for l in lines[:-1]:
            b = re.match(r'for ([+-]?)(\w+): (.*)$', l)
            binders.append((b.group(1), b.group(2), b.group(3)))
        concl = lines[-1]
        mm = re.match(r'(\w+)\.rep_%s\((.*), s\)$' % x, concl)
        assert mm, concl
        names = [b[1] for b in binders]
        assert names[:4] == ['o', 's', 'v', 'r'] and names[4:] in ([], ['rv']), (x, f, names)
        out.setdefault(x, {})[f] = (binders, mm.group(2), mm.group(1))
    return out


BUILTIN = {'U32', 'Bool', 'Nat', 'List', 'Maybe', 'Array', 'Pair', 'Equal', 'Base', 'Word', 'Some', 'None', 'True', 'False'}


def qualify(text, mod_imps, mod_alias, mod_defs, ren):
    """text of a module requalified for the output: A.x with A an import of the module -> ren[A].x,
    a bare name the module defines -> mod_alias.name"""
    def sub(m):
        a, rest = m.group(1), m.group(2)
        if rest is not None:
            return ren.get(a, a) + '.' + rest
        return mod_alias + '.' + a if a in mod_defs else a
    return re.sub(r'(?<![\w.])([A-Za-z_]\w*)(?:\.([A-Za-z_]\w*))?', lambda m: sub(m) if (m.group(2) is not None and m.group(1) in mod_imps) or (m.group(2) is None and m.group(1) in mod_defs) else m.group(0), text)


def items(expr):
    """the elements of S.Sequence{S.Items{e0, S.Items{e1, .. S.EmptyItems{}}}}"""
    assert expr.startswith('S.Sequence{') and expr.endswith('}'), expr[:80]
    cur = expr[len('S.Sequence{'):-1]
    out = []
    while cur != 'S.EmptyItems{}':
        assert cur.startswith('S.Items{') and cur.endswith('}'), cur[:80]
        h, t = split_params(cur[len('S.Items{'):-1])
        out.append(h)
        cur = t
    return out


def view_block(path, fn):
    """(block lines, leaf line index, leaf expression) of `def fn(o: ...)` in path"""
    lines = path.read_text().split('\n')
    i = [k for k, l in enumerate(lines) if l.startswith('def %s(o: ' % fn)]
    assert len(i) == 1, (path, fn)
    j = i[0] + 1
    while j < len(lines) and lines[j].startswith(' '):
        j += 1
    blk = lines[i[0]:j]
    leaf = max(k for k, l in enumerate(blk) if 'S.Sequence{' in l)
    return blk, leaf, blk[leaf][blk[leaf].index('S.Sequence{'):].strip()


def fields_of(deftext, x):
    """[field name] of the record type x in order, the group records (x_g<k>) expanded"""
    m = re.search(r'^type %s is \w+:\n  %s\{(.*)\}$' % (x, x), deftext, re.M)
    out = []
    for fd in split_params(m.group(1)):
        n, t = [a.strip() for a in fd.split(':', 1)]
        if re.fullmatch(r'%s_g\d+' % x, t):
            out += fields_of(deftext, t)
        else:
            out.append(n)
    return out


def containers():
    """[(name, type, def file)]: the names whose def file has field setters for its own record type"""
    out = []
    for f in sorted(TYPES.glob('*_def_generated.bend')):
        t = f.read_text()
        for x in sorted(set(re.findall(r'^def (\w+)_set_\w+\(o: (\w+), ', t, re.M))):
            if x[0] == x[1] and not re.search(r'_g\d+$', x[0]) and re.search(r'^type %s is ' % x[0], t, re.M):
                out.append((f.name[:-len('_def_generated.bend')], x[0], f))
    return out


def merge(imps, new, suffix):
    """add the imports `new` to `imps`; an alias taken by another path is renamed alias_<suffix>.
    Returns the renaming to apply to the text written against `new`."""
    ren = {}
    for a, p in new.items():
        have = [k for k, q in imps.items() if q == p]
        if have:
            if have[0] != a:
                ren[a] = have[0]
            continue
        b = a
        if b in imps and imps[b] != p:
            b = a + '_' + suffix
            assert b not in imps or imps[b] == p, (a, p)
        imps[b] = p
        if b != a:
            ren[a] = b
    return ren


def rename(text, ren):
    for a, b in ren.items():
        text = re.sub(r'(?<![\w.])%s\.' % re.escape(a), b + '.', text)
    return text


def rel(p):
    r = os.path.relpath(ROOT / p, E2E)
    return r if r.startswith('.') else './' + r


def build(n, x, deff, laws, man):
    imps = {'VS': 'proofs/obj/value_set.bend'}
    dren = merge(imps, imports(deff), 'd')
    d_alias = [a for a, q in imps.items() if q == os.path.relpath(deff, ROOT)]
    if not d_alias:
        imps[n + '_d'] = os.path.relpath(deff, ROOT)
        d_alias = [n + '_d']
    DA = d_alias[0]
    deftext = deff.read_text()
    ddefs = set(re.findall(r'^(?:def|type) (\w+)', deftext, re.M))
    fields = fields_of(deftext, x)
    rb = bridge_file(man, n, n + '_e2e_root')
    if rb is None:
        return None, 0
    params, concl = signature(rb, n + '_e2e_root')
    concl = rename(concl, merge(imps, imports(rb), 'r'))
    imps['R'] = os.path.relpath(rb, ROOT)
    m = re.search(r'API\.hash_tree_root\(((?:\w+\.)?\w+\(\)), (\w+)\.(v_\w+)\(o\)\)', concl)
    spec, va, vfn = m.groups()
    vpath = ROOT / imps[va]
    vimps = imports(vpath)
    vren = merge(imps, vimps, 'v')
    vdefs = set(re.findall(r'^(?:def|type) (\w+)', vpath.read_text(), re.M))
    blk, leaf, expr = view_block(vpath, vfn)
    els = items(expr)
    assert len(els) == len(fields), (n, len(els), len(fields))
    lw = laws.get(x, {})
    if lw:
        imps['PS'] = 'proofs/obj/prep_setters.bend'
        lren = merge(imps, imports(LAWS), 'l')
    view = lambda t: '%s.%s(%s)' % (va, vfn, t)
    # the proof skeleton: the view's own matches on o, the leaf closed by computation
    skel = [qualify(l, vimps, va, vdefs, vren) for l in blk[1:leaf]]
    skel.append(blk[leaf][:blk[leaf].index('S.Sequence{')] + '{==}')
    defs, counts = [], {'view': 0, 'root': 0, 'encode': 0}
    ob = [p for p in params if re.match(r'[+-]?o:', p)][0]
    otype = ob.split(':', 1)[1].strip()
    kinds = [('root', params, concl, 'R')]
    eb = bridge_file(man, n, n + '_e2e_encode')
    if eb is not None:
        ep, ec = signature(eb, n + '_e2e_encode')
        imps['N'] = os.path.relpath(eb, ROOT)
        ec = rename(ec, merge(imps, imports(eb), 'e'))
        kinds.append(('encode', ep, ec, 'N'))
    for k, f in enumerate(fields):
        sm = re.search(r'^def %s_set_%s\(o: %s, (\+?)v: (.+?)\) -> %s:' % (x, f, x, x), deftext, re.M)
        if not sm:   # a checked setter (X_set_f -> X & Bool, a range-checked uint16): not covered here
            assert re.search(r'^def %s_set_%s\(o: %s, .*\) -> %s & Bool:' % (x, f, x, x), deftext, re.M), (n, f)
            continue
        wm = sm.group(1)
        wt = qualify(sm.group(2), imports(deff), DA, ddefs, dren)
        el = els[k]
        vs = set(re.findall(r'(?<![\w.])x(\d+)(?![\w.])', el))
        assert vs == {str(k)}, (n, f, el)
        fv = qualify(re.sub(r'(?<![\w.])x%d(?![\w.])' % k, 'w', el), vimps, va, vdefs, vren)
        setx = '%s.%s_set_%s(o, w)' % (DA, x, f)
        fs = 'VS.field_set(%s, %dn, %s)' % (view('o'), k, fv)
        vl = '%s_e2e_set_%s_view' % (n, f)
        defs.append('def %s(%so: %s, %sw: %s)\n    -> {%s == %s : S.Value}:\n%s' % (
            vl, '+' if ob.startswith('+') else '', otype, wm, wt, view(setx), fs, '\n'.join(skel)))
        counts['view'] += 1
        for kind, ps, cc, al in kinds:
            pn = [re.match(r'[+-]?(\w+)', p).group(1) for p in ps]
            law = lw.get(f)
            if pn in (['h', 'o'], ['o']):
                extra, rargs = [], ''
            elif pn in (['h', 'o', 'rep'], ['o', 'rep']) and law:
                binders, lsetx, _ = law
                extra = []
                for mode, b, t in binders[3:]:
                    extra.append('%s%s: %s' % (mode, b, re.sub(r'(?<![\w.])v(?![\w.])', 'w', rename(VAR_S.sub(spec, t), lren))))
                largs = ', '.join(spec if b[1] == 's' else ('w' if b[1] == 'v' else b[1]) for b in binders)
                rargs = ', PS.%s_set_%s_rep(%s)' % (x, f, largs)
            else:
                continue
            lhs, rhs = cc[1:-1].split(' == API.', 1)
            api, ty = rhs.rsplit(' : ', 1)
            api = 'API.' + api
            want = '%s(%s, %s)' % (api.split('(', 1)[0], spec, view('o'))
            assert api == want, (api, want)
            L = VAR_O.sub(lambda _: setx, lhs)
            fn = api.split('(', 1)[0]
            head = ['h: B.Buf'] if 'h' in pn else []
            omode = '+' if ob.startswith('+') else ''
            sig = head + ['%so: %s' % (omode, otype), '%sw: %s' % (wm, wt)] + extra
            call = '%s.%s_e2e_%s(%s%s%s)' % (al, n, kind, 'h, ' if 'h' in pn else '', setx, rargs)
            defs.append('def %s_e2e_set_%s_%s(%s)\n    -> {%s == %s(%s, %s) : %s}:\n  %%%s(o, w) : {%s == %s(%s, _) : %s}\n  %s' % (
                n, f, kind, ', '.join(sig), L, fn, spec, fs, ty, vl, L, fn, spec, ty, call))
            counts[kind] += 1
    body = '\n\n'.join(defs)
    used = [a for a in imps if re.search(r'(?<![\w.])%s\.' % re.escape(a), body)]
    lines = ['import Base'] + ['import %s as %s' % (rel(imps[a]), a) for a in sorted(used)]
    lines += ['', HEADER,
              '# %s: for each field setter set_f, the spec-value law view(set_f(o, w)) == field_set(view(o), k, view_f(w))' % n,
              '# (proofs/obj/value_set.bend: the value with field k replaced), and that law composed with the root',
              '# bridge (and the encode bridge where it applies): the root (encoding) of set_f(o, w) is the spec',
              '# root (encoding) of the value with field f replaced. Under rep, through the setter law of',
              '# proofs/obj/prep_setters.bend (set_f keeps rep), when the bridge has that premise.', '']
    return '\n'.join(lines) + body + '\n', counts


def outputs():
    man = json.loads((E2E / 'manifest.json').read_text())
    laws = setter_laws()
    outs, tot = {}, {'view': 0, 'root': 0, 'encode': 0}
    for n, x, deff in containers():
        t, c = build(n, x, deff, laws, man)
        if t:
            outs[E2E / ('%s_e2e_set_generated.bend' % n)] = t
            for k in tot:
                tot[k] += c[k]
    return outs, tot


def main():
    check = '--check' in sys.argv
    outs, tot = outputs()
    stale = []
    for p, t in outs.items():
        if not p.exists() or p.read_text() != t:
            stale.append(p.name)
            if not check:
                p.write_text(t)
    have = {p.name for p in E2E.glob('*_e2e_set_generated.bend')}
    for o in sorted(have - {p.name for p in outs}):
        if check:
            stale.append(o + ' (orphan)')
        else:
            (E2E / o).unlink()
    ndefs = sum(t.count('\ndef ') for t in outs.values())
    if check:
        if stale:
            print('stale: ' + ', '.join(stale))
            sys.exit(1)
        print('e2e_setters: %d files up to date (%d view, %d root, %d encode statements)' % (len(outs), tot['view'], tot['root'], tot['encode']))
    else:
        print('e2e_setters: wrote %d of %d files (%d view, %d root, %d encode statements)' % (len(stale), len(outs), tot['view'], tot['root'], tot['encode']))


if __name__ == '__main__':
    main()
