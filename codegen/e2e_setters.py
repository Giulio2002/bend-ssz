#!/usr/bin/env python3
"""Setter laws composed with the root and encode bridges: e2e/<Name>_e2e_set_generated.bend.

proofs/obj/prep_setters.bend (codegen/rep_laws.py) proves, for every field setter set_f of the
Fulu containers listed there, that it keeps the representation invariant: from rep_X(o, s) (and,
for a field with its own invariant, that invariant of the new value v) follows
rep_X(set_f(o, v), s). rep_X(o, Spec.X()) is exactly the premise of X's root bridge
(<Name>_e2e_root: the object's root is API.hash_tree_root of its view), and for a few names the
only premise of the encode bridge (<Name>_e2e_encode). So each setter law composes with those
bridges into a checked statement about an object mutated through the API:

    <Name>_e2e_set_<f>_root(h, o, v, r[, rv]):
        root(set_f(o, v)) == API.hash_tree_root(Spec.X(), view(set_f(o, v)))
    <Name>_e2e_set_<f>_encode(o, v, r[, rv])       (when the encode bridge's only premise is rep)
        Some(encode(set_f(o, v))) == API.serialize(Spec.X(), view(set_f(o, v)))

under rep_X(o, Spec.X()) (and rv). Each proof is the bridge applied to set_f(o, v) and the setter
law. A composition is emitted exactly when the bridge's premises are the object and rep (the
root bridge of every container here; the encode bridge of the containers without storage
premises); an encode bridge with storage premises (hs*, hc*, ...) needs them of set_f(o, v), which
no setter law states, so none is emitted for it (docs/PREMISES.md).

    python3 codegen/e2e_setters.py            # write
    python3 codegen/e2e_setters.py --check    # nonzero exit if any output is stale or orphaned
"""
import json
import os
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
E2E = ROOT / 'e2e'
LAWS = ROOT / 'proofs/obj/prep_setters.bend'
HEADER = '# GENERATED by codegen/e2e_setters.py. Do not edit.'
LAW = re.compile(r'^law (\w+)_set_(\w+)_rep:\n((?:  .*\n)+)', re.M)
IMPORT = re.compile(r'^import (\S+) as (\w+)\s*$', re.M)
VAR_O = re.compile(r'(?<![\w.])o(?![\w.])')
VAR_S = re.compile(r'(?<![\w.])s(?![\w.])')


def imports(path):
    """{alias: root-relative path} of a .bend file"""
    out = {}
    for m in IMPORT.finditer(path.read_text()):
        out[m.group(2)] = os.path.normpath(os.path.join(os.path.relpath(path.parent, ROOT), m.group(1)))
    return out


def split_params(s):
    out, depth, cur = [], 0, ''
    for ch in s:
        if ch in '({[<':
            depth += 1
        elif ch in ')}]>':
            depth -= 1
        if ch == ',' and depth == 0:
            out.append(cur.strip())
            cur = ''
            continue
        cur += ch
    if cur.strip():
        out.append(cur.strip())
    return out


def signature(path, name):
    """(params, conclusion) of the one-line bridge `def name(params) -> {conclusion}:`"""
    lines = path.read_text().split('\n')
    start = [i for i, l in enumerate(lines) if l.startswith('def %s(' % name)]
    if len(start) != 1:
        sys.exit('e2e_setters: %s: def %s not found once' % (path.name, name))
    sig = []
    for l in lines[start[0]:]:
        sig.append(l.strip())
        if l.rstrip().endswith(':'):
            break
    m = re.match(r'def %s\((.*)\)\s*-> (\{.*\}):$' % re.escape(name), ' '.join(sig), re.S)
    return split_params(m.group(1)), m.group(2)


def bridge_file(man, name, law):
    for f, es in man['files'].items():
        for e in es:
            if law in e['laws']:
                return E2E / f
    return None


def setter_laws():
    """{container: [(field, binders [(mode, name, type)], setter expression)]}"""
    out = {}
    for m in LAW.finditer(LAWS.read_text()):
        x, f, body = m.group(1), m.group(2), m.group(3)
        lines = [l.strip() for l in body.split('\n') if l.strip()]
        binders = []
        for l in lines[:-1]:
            b = re.match(r'for ([+-]?)(\w+): (.*)$', l)
            binders.append((b.group(1), b.group(2), b.group(3)))
        concl = lines[-1]
        pre = 'RT.rep_%s(' % x
        assert concl.startswith(pre) and concl.endswith(', s)'), concl
        names = [b[1] for b in binders]
        assert names[:4] == ['o', 's', 'v', 'r'] and names[4:] in ([], ['rv']), (x, f, names)
        out.setdefault(x, []).append((f, binders, concl[len(pre):-len(', s)')]))
    return out


def merge(imps, new, suffix):
    """add the imports `new` to `imps`; an alias taken by another path is renamed alias_<suffix>.
    Returns the renaming to apply to the text written against `new`."""
    ren = {}
    for a, p in new.items():
        have = [k for k, q in imps.items() if q == p]
        if have:
            if have[0] != a:
                ren[a] = have[0]
            continue
        b = a
        if b in imps and imps[b] != p:
            b = a + '_' + suffix
            assert b not in imps or imps[b] == p, (a, p)
        imps[b] = p
        if b != a:
            ren[a] = b
    return ren


def rename(text, ren):
    for a, b in ren.items():
        text = re.sub(r'(?<![\w.])%s\.' % re.escape(a), b + '.', text)
    return text


def build(x, laws, man):
    n = 'Fulu' + x
    spec = 'Spec.%s()' % x
    imps = {'PS': 'proofs/obj/prep_setters.bend'}
    lren = merge(imps, imports(LAWS), 'l')
    defs = []
    kinds = []
    for kind in ('root', 'encode'):
        bname = '%s_e2e_%s' % (n, kind)
        bf = bridge_file(man, n, bname)
        if bf is None:
            continue
        params, concl = signature(bf, bname)
        pnames = [re.match(r'[+-]?(\w+)', p).group(1) for p in params]
        if pnames not in (['h', 'o', 'rep'], ['o', 'rep']):
            continue  # premises beyond rep: no setter law provides them
        alias = 'R' if kind == 'root' else 'N'
        imps[alias] = os.path.relpath(bf, ROOT)
        concl = rename(concl, merge(imps, imports(bf), kind[0]))
        kinds.append(kind)
        for f, binders, setx in laws:
            ps = []
            if 'h' in pnames:
                ps.append(params[0])
            for mode, b, t in binders:
                if b == 's':
                    continue
                ps.append('%s%s: %s' % (mode, b, rename(VAR_S.sub(spec, t), lren)))
            args = ', '.join(b[1] if b[1] != 's' else spec for b in binders)
            call = '%s.%s_e2e_%s(%s%s, PS.%s_set_%s_rep(%s))' % (
                alias, n, kind, 'h, ' if 'h' in pnames else '', rename(setx, lren), x, f, args)
            defs.append('def %s_e2e_set_%s_%s(%s)\n    -> %s:\n  %s' % (
                n, f, kind, ', '.join(ps), VAR_O.sub(lambda _: rename(setx, lren), concl), call))
    if not defs:
        return None
    body = '\n\n'.join(defs)
    used = [a for a in imps if re.search(r'(?<![\w.])%s\.' % re.escape(a), body)]
    def rel(p):
        r = os.path.relpath(ROOT / p, E2E)
        return r if r.startswith('.') else './' + r
    lines = ['import Base'] + ['import %s as %s' % (rel(imps[a]), a) for a in sorted(used)]
    lines += ['', HEADER,
              '# %s: each field setter of %s (proofs/obj/prep_setters.bend) composed with its %s bridge%s:'
              % (n, x, ' and '.join(kinds), 's' if len(kinds) > 1 else ''),
              '# an object mutated through the API, from one satisfying rep, has the spec %s.'
              % ' and '.join({'root': 'root', 'encode': 'encoding'}[k] for k in kinds), '']
    return '\n'.join(lines) + body + '\n'


def outputs():
    man = json.loads((E2E / 'manifest.json').read_text())
    outs = {}
    for x, laws in setter_laws().items():
        t = build(x, laws, man)
        if t:
            outs[E2E / ('Fulu%s_e2e_set_generated.bend' % x)] = t
    return outs


def main():
    check = '--check' in sys.argv
    outs = outputs()
    stale = []
    for p, t in outs.items():
        if not p.exists() or p.read_text() != t:
            stale.append(p.name)
            if not check:
                p.write_text(t)
    have = {p.name for p in E2E.glob('*_e2e_set_generated.bend')}
    for o in sorted(have - {p.name for p in outs}):
        if check:
            stale.append(o + ' (orphan)')
        else:
            (E2E / o).unlink()
    ndefs = sum(t.count('\ndef ') for t in outs.values())
    if check:
        if stale:
            print('stale: ' + ', '.join(stale))
            sys.exit(1)
        print('e2e_setters: %d files, %d composed setter statements up to date' % (len(outs), ndefs))
    else:
        print('e2e_setters: wrote %d of %d files (%d composed setter statements)' % (len(stale), len(outs), ndefs))


if __name__ == '__main__':
    main()
