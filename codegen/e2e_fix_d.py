"""The fourth e2e worker's share: fixed-size names family A's templates do not cover (sub-word leaves,
bit vectors, vec_bool / vec_uint8 / vec_uint16, fixed containers with hypotheses, and the names whose
encode_eval is not an emit of the encoder). codegen/e2e_bridge.py calls build() from outputs() and owns
the manifest.

build(EB, amap, cache, vidx) -> {'support': {fname: text},      shared modules (e2e/<fname>)
                                 'files': {fname: text},        bridge files (e2e/<fname>)
                                 'cover': {X: {'i': fname, 'ii_iii': fname, 'iv': fname,
                                               'ii': 'exact' | 'view', 'premise': str}}}
EB is the e2e_bridge module (its builders and helpers), amap proofs/gate/api_map.json, cache and vidx
e2e_bridge's law cache and validity index. X is the generated name. A name with all of i / ii_iii / iv
moves from the manifest's 'uncovered' to 'fixed_size' (laws <R>_e2e_encode, <R>_e2e_decode_accept or
_decode_view, <R>_e2e_decode_reject, <R>_e2e_root); partial keys are recorded on its uncovered entry.
Texts may import ../types/fulu_obj.bend as T (or generic_obj.bend): e2e_bridge rewires them. Keep the
"# GENERATED by codegen/e2e_bridge.py" header in every file.
"""


def build(EB, amap, cache, vidx):
    return {'support': {}, 'files': {}, 'cover': {}}


