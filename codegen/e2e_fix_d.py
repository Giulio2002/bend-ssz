# ---- Type-kind containers (boxed fields): the object rebuilt from its representation's witnesses ----

def split_args(t):
    """C{a, b, ..} -> (C, [a, b, ..]) at the top level, or None"""
    m = re.match(r'([\w.]+)\{(.*)\}$', t, re.S)
    if not m:
        return None
    d, cur, out = 0, '', []
    for ch in m.group(2):
        if ch in '({[<':
            d += 1
        elif ch in ')}]>':
            d -= 1
        if ch == ',' and d == 0:
            out.append(cur.strip())
            cur = ''
            continue
        cur += ch
    if cur.strip():
        out.append(cur.strip())
    return m.group(1), out


def cargs(s, head):
    """head(a, b, ..) -> [a, b, ..] at top level ('=>' / '->' are not brackets)"""
    assert s.startswith(head + '(')
    t = s[len(head) + 1:]
    d, cur, out, i = 0, '', [], 0
    while i < len(t):
        ch = t[i]
        if t.startswith('=>', i) or t.startswith('->', i):
            cur += t[i:i + 2]
            i += 2
            continue
        if ch in '({[<':
            d += 1
        elif ch in ')}]>':
            if d == 0 and ch == ')':
                out.append(cur.strip())
                return out
            d -= 1
        if ch == ',' and d == 0:
            out.append(cur.strip())
            cur = ''
            i += 1
            continue
        cur += ch
        i += 1
    raise ValueError(s[:100])


class Rebuild:
    """destructure a representation (rep_X of root_types, and the reps / wf1 it calls in other modules)
    into copyable witnesses and a proof of {term == W}"""
    def __init__(self, EB, imp, rtfile):
        self.EB, self.imp, self.f = EB, imp, rtfile
        self.n = 0
        self.lines, self.wits, self.facts = [], [], []

    def fresh(self, b):
        self.n += 1
        return f'{b}{self.n}'

    def src(self, f):
        return (self.EB.OBJ / f).read_text()

    def repdef(self, name, f):
        """(params, body, file) of a Data-valued def"""
        src = self.src(f)
        m = re.search(r'^def ' + name + r'\((.*?)\) -> Data:\n((?:  .*\n?)+)', src, re.M)
        if not m:
            return None
        ps = [pmode(x)[1] for x in split_top_params(m.group(1))]
        return ps, ' '.join(l.strip() for l in m.group(2).split('\n') if l.strip()), f

    def resolve(self, fn, f):
        """fn (maybe qualified) called in module f -> (name, module file) or None"""
        if '.' in fn:
            q, nm = fn.split('.', 1)
            al, _ = module_info(self.EB, f)
            path = al.get(q)
            if not path or not path.startswith('proofs/obj/'):
                return None
            return nm, path[len('proofs/obj/'):]
        return fn, f

    def q(self, t, f):
        return self.imp.qual(self.EB, t, f)

    def run(self, call, term, var, sch=None):
        ps, body, f = self.repdef(call, self.f)
        env = {ps[0]: term}
        if sch and len(ps) > 1:
            env[ps[1]] = sch
        return self.body(body, env, var, term, f)

    def body(self, b, env, var, term, f):
        eqs, subs = [], []
        self.walk(b, env, var, term, eqs, subs, f)
        assert len(eqs) == 1, (b[:200], eqs)
        R, TY, E = eqs[0]
        W = R
        for st, (Wi, Ei, Ti) in subs:
            if st not in W:
                continue
            con = split_args(W)
            args = con[1]
            k = args.index(st)
            f_ = f'z => {con[0]}{{{", ".join(args[:k] + ["z"] + args[k + 1:])}}}'
            W2 = f'{con[0]}{{{", ".join(args[:k] + [Wi] + args[k + 1:])}}}'
            E = f'X.trans_e({TY}, {term}, {W}, {W2}, {E}, X.cong_e({Ti}, {TY}, {f_}, {st}, {Wi}, {Ei}))'
            W = W2
        return W, E

    def subst(self, t, env):
        for k, v in env.items():
            t = re.sub(r'(?<![\w.])' + re.escape(k) + r'(?![\w{])', v, t)
        return t

    def walk(self, b, env, var, term, eqs, subs, f):
        b = b.strip()
        if b.startswith('DK.Ex('):
            ty, rest = cargs(b, 'DK.Ex')
            mm = re.match(r'(\w+) => (.*)$', rest, re.S)
            x = self.fresh('w')
            qv = self.fresh('q')
            self.lines.append(f'(+{x}, +{qv}) = {var}')
            self.wits.append((x, self.q(ty, f)))
            env = dict(env)
            env[mm.group(1)] = x
            return self.walk(mm.group(2), env, qv, term, eqs, subs, f)
        if b.startswith('DK.P2('):
            a1, a2 = cargs(b, 'DK.P2')
            v1, v2 = self.fresh('a'), self.fresh('b')
            self.lines.append(f'(+{v1}, +{v2}) = {var}')
            self.walk(a1, env, v1, term, eqs, subs, f)
            self.walk(a2, env, v2, term, eqs, subs, f)
            return
        me = re.match(r'\{(.*) == (.*) : (.*)\}$', b, re.S)
        if me:
            L_ = self.q(self.subst(me.group(1), env), f)
            if L_ == term:
                eqs.append((self.q(self.subst(me.group(2), env), f), self.q(me.group(3), f), var))
            else:
                self.facts.append((var, self.q(self.subst(b, env), f)))
            return   # (a fact about the witnesses)
        mc = re.match(r'([\w.]+)\((.*)\)$', b, re.S)
        if mc:
            r = self.resolve(mc.group(1), f)
            d = self.repdef(*r) if r else None
            if d:
                ps, body, f2 = d
                args = cargs(b, mc.group(1))
                st = self.q(self.subst(args[0], env), f)
                env2 = {ps[0]: st}
                for pn, an in zip(ps[1:], args[1:]):
                    env2[pn] = self.q(self.subst(an, env), f)
                if st == term:
                    # the same object's other facts (e.g. rep_bv's wf1 part): its equation is the main one
                    return self.walk(body, env2, var, term, eqs, subs, f2)
                ty = re.search(r'^def ' + r[0] + r'\(\w+: ([^,)]*)', self.src(f2), re.M).group(1)
                Wi, Ei = self.body(body, env2, var, st, f2)
                subs.append((st, (Wi, Ei, self.q(ty, f2))))
                return
        raise ValueError('unsupported representation: ' + b[:120])


def split_top_params(s):
    d, cur, out = 0, '', []
    for ch in s:
        if ch in '({[<':
            d += 1
        elif ch in ')}]>':
            d -= 1
        if ch == ',' and d == 0:
            out.append(cur.strip())
            cur = ''
            continue
        cur += ch
    if cur.strip():
        out.append(cur.strip())
    return out


def root_box(EB, imp, R, X, sn, ri):
    f = ri['rt']['file']
    RT = imp.alias('proofs/obj/' + f)
    rb = Rebuild(EB, imp, f)
    W, E = rb.run(f'rep_{X}', 'o', 'rep')
    ot = imp.qual(EB, [t for _, n, t in ri['ps'] if n == 'o'][0], f)
    VIEW = lambda o: sub_o(subst_s(imp.qual(EB, ri['view'], f), sn), o)  # noqa: E731
    ROOT = lambda o: sub_o(subst_s(imp.qual(EB, ri['root'], f), sn), o)  # noqa: E731
    REP = lambda o: f'{RT}.rep_{X}({o}, Spec.{sn}())'  # noqa: E731
    Gr = lambda o: f'{{Some{{{ROOT(o)}}} == API.hash_tree_root(Spec.{sn}(), {VIEW(o)}) : Maybe<&2, +List<U32>>}}'  # noqa: E731
    Mv = imp.alias('proofs/obj/' + ri['vf'])
    wp = ', '.join(f'+{x}: {t}' for x, t in rb.wits)
    wa = ', '.join(x for x, _ in rb.wits)
    L = [f'# {R} ({X})', f'def {R}_r2(h: B.Buf, {wp}, +rep: {REP(W)}) -> {Gr(W)}:',
         f'  E.root_legal(Spec.{sn}(), {VIEW(W)}, VS.public_sound(Spec.{sn}(), {{==}}), {ROOT(W)},',
         f'    {Mv}.{ri["vl"]}({W}, Spec.{sn}(), {{==}}, rep), {RT}.{ri["rt"]["law"]}(h, {W}, Spec.{sn}(), {{==}}, rep))', '',
         f'# (iv) under rep (the root law\'s invariant); the object is rebuilt from rep\'s witnesses.',
         f'def {R}_e2e_root(h: B.Buf, -o: {ot}, +rep: {REP("o")}) -> {Gr("o")}:'] + ['  ' + l for l in rb.lines] + [
         f'  +eq = {E}',
         f'  %X.sym_e({ot}, o, {W}, eq) : {Gr("_")}',
         f'  {R}_r2(h, {wa}, FD.logic__subst({ot}, z => {REP("z")}, o, {W}, eq, rep))', '']
    return '\n'.join(L)


def align(W, P, out):
    """W (rebuilt object, witnesses as variables) against P (the encode law's object): witness -> pattern"""
    if re.match(r'\w+$', W):
        out[W] = P
        return True
    a, b = split_args(W), split_args(P)
    if not a or not b or a[0] != b[0] or len(a[1]) != len(b[1]):
        return False
    return all(align(x, y, out) for x, y in zip(a[1], b[1]))


