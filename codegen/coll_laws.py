def rel(p):
    r = os.path.relpath(ROOT / p, OBJ)
    return r if r.startswith('.') else './' + r


def outputs():
    cs = collections()
    outs, total = {CW: coll_words()}, 0
    bt, bn = coll_seq(cs)
    outs[CB] = bt
    total += bn
    bt, bn = coll_bits(cs)
    outs[CBITS] = bt
    total += bn
    bt, bn = coll_bytes(cs)
    outs[CBYTES] = bt
    total += bn
    for k in range(0, len(cs), PER_FILE):
        imps = {'F': 'proofs/compact/found.bend'}
        parts = []
        for c in cs[k:k + PER_FILE]:
            txt, m = laws(info(c), imps)
            parts.append(txt)
            total += m
        body = '\n'.join(parts)
        used = [a for a in imps if re.search(r'(?<![\w.])%s\.' % re.escape(a), body)]
        head = ['import Base'] + ['import %s as %s' % (rel(imps[a]), a) for a in used]
        head += ['', HEADER,
                 '# The collection laws of the public API (C_set, C_append, C_get, C_len), with the guards the',
                 '# runtime computes from the object; see codegen/coll_laws.py for the list of laws.', '']
        outs[OBJ / ('coll_api_%d.bend' % (k // PER_FILE))] = '\n'.join(head) + body
    return outs, total


def main():
    check = '--check' in sys.argv
    outs, total = outputs()
    stale = [p.name for p, t in outs.items() if not p.exists() or p.read_text() != t]
    orphans = sorted({p.name for p in list(OBJ.glob('coll_api_*.bend')) + list(OBJ.glob('coll_boxed.bend'))} - {p.name for p in outs})
    if check:
        if stale or orphans:
            print('stale: ' + ', '.join(stale + [o + ' (orphan)' for o in orphans]))
            sys.exit(1)
        print('coll_laws: %d files, %d collection laws up to date' % (len(outs), total))
        return
    for p, t in outs.items():
        if not p.exists() or p.read_text() != t:
            p.write_text(t)
    for o in orphans:
        (OBJ / o).unlink()
    print('coll_laws: %d files, %d collection laws' % (len(outs), total))


if __name__ == '__main__':
    main()
