#!/usr/bin/env python3
"""The collection laws of the public object API: proofs/obj/coll_api_<k>.bend.

For every collection C of the Fulu object API (the lists, vectors, byte lists and bit lists with an
element setter C_set, codegen/laws.py's COLLECTIONS), stated over the public functions C_set,
C_append, C_get and C_len with the guard they compute from the object (never a guard passed in):

    set_flag         the flag C_set returns is exactly the spec's condition GS: the index is
                     below the length (and, for byte elements, the value is a byte)
    set_rejected     when GS is False, C_set returns the object unchanged and False
    get_outside      when the index is not below the length, C_get returns the object and None
    append_flag      the flag C_append returns is exactly GA: the new length is within the limit
                     (and, for byte elements, the value is a byte)
    append_rejected  when GA is False, C_append returns the object unchanged and False

and, for the lists stored as an array of elements (C_Seq{arr, n}):

    set_length       an accepted set keeps the length
    append_length    an accepted append adds one to the length

and, for those whose elements are Data (not boxed), over storage that is a perfect tree t of
depth d < 32 (what Array.new builds and Array.set keeps; proofs/compact/found.bend's array laws):

    read_set         get(set(o, i, v), i) returns v
    other_set        get(set(o, i, v), j) returns the old element j, for j != i
    read_append      get(append(o, v), n) returns v, when the storage has room for element n
                     (n < 2^d, the append does not grow the array) and n + 1 does not wrap

The guards GS, GA and the length are read from the generated runtime (types/*_def_generated.bend),
so the statements follow it. Read-back for the boxed lists and for the packed (O.Words / O.Bits)
collections needs word-level array laws that do not exist yet (docs/RESULTS.md).

    python3 codegen/coll_laws.py            # write
    python3 codegen/coll_laws.py --check    # nonzero exit if an output is stale or orphaned
"""
import os
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'codegen'))
OBJ = ROOT / 'proofs/obj'
TYPES = ROOT / 'types'
HEADER = '# GENERATED by codegen/coll_laws.py. Do not edit.'
PER_FILE = 6
IMPORT = re.compile(r'^import (\S+) as (\w+)\s*$', re.M)


def collections():
    """the collection prefixes, in codegen/laws.py's order (its collections_<k>.bend sections)"""
    out = []
    for p in sorted(OBJ.glob('collections_*.bend')):
        out += re.findall(r'^# ---- (\w+) ----$', p.read_text(), re.M)
    return out


def split_top(s):
    out, depth, cur = [], 0, ''
    for ch in s:
        if ch in '({[<':
            depth += 1
        elif ch in ')}]>':
            depth -= 1
        if ch == ',' and depth == 0:
            out.append(cur.strip())
            cur = ''
            continue
        cur += ch
    if cur.strip():
        out.append(cur.strip())
    return out


def body(t, name):
    """the body text of `def name(...)`: the rest of its first line, or its indented lines"""
    m = re.search(r'^def %s\((.*)\) -> (.*?):(.*)$' % re.escape(name), t, re.M)
    if not m:
        return None
    if m.group(3).strip():
        return m.group(1), m.group(2), m.group(3).strip()
    lines = t[m.end():].split('\n')[1:]
    b = []
    for l in lines:
        if not l.startswith(' '):
            break
        b.append(l)
    return m.group(1), m.group(2), '\n'.join(b)


def subst_n(g, ln):
    return re.sub(r'(?<![\w.])n(?![\w.])', ln if re.fullmatch(r'\w+', ln) else '(%s)' % ln, g)


def call_args(expr, fn):
    """the top-level arguments of the call fn(...) that expr is"""
    expr = expr.strip()
    assert expr.startswith(fn + '(') and expr.endswith(')'), (fn, expr[:120])
    return split_top(expr[len(fn) + 1:-1])


def info(c):
    """everything the laws need about collection c"""
    f = [p for p in TYPES.glob('*_def_generated.bend') if re.search(r'^def %s_set\(' % c, p.read_text(), re.M)]
    assert len(f) == 1, (c, f)
    f = f[0]
    t = f.read_text()
    I = {'c': c, 'file': f, 'text': t}
    ps, rt, b = body(t, c + '_set')
    params = split_top(ps)
    I['T'] = params[0].split(':', 1)[1].strip()
    vm, vt = re.match(r'([+-]?)v: (.*)$', params[2]).groups()
    I['vm'], I['VT'] = vm, vt
    g = body(t, c + '_get')
    I['ET'] = re.match(r'.* & Maybe<&1, (.*)>$', g[1]).group(1)
    if I['T'].endswith('_Seq'):
        I['kind'] = 'seq'
        m = re.search(r'^type %s is Type:\n  %s\{items: Array<(.*)>, n: U32\}' % (I['T'], I['T']), t, re.M)
        I['EL'] = m.group(1)
        I['data'] = not I['EL'].startswith('O.Boxed<')
        I['ln'] = 'n'
        I['GS'] = call_args(b.split(': ', 1)[1] if 'case' in b else b, c + '_put_in')[0]
        a = body(t, c + '_append')
        I['GA'] = call_args(a[2].split(': ', 1)[1], c + '_app_in')[0] if a else None
        gb = g[2]
        I['GG'] = call_args(gb.split(': ', 1)[1], c + '_get_in')[0]
    else:
        I['kind'] = 'bits' if I['T'] == 'O.Bits' else 'words'
        # the length: C_len(o) = C_len_of(O.words_len(o)) with len_of -> (o, EXPR), or the storage count itself
        lcall = call_args(b, c + '_set_n')[2]
        if lcall.startswith(c + '_len('):
            lb = body(t, c + '_len')[2]
            if lb.startswith(c + '_len_of('):
                I['ln'] = re.search(r'\(o, (.*)\)$', body(t, c + '_len_of')[2].split('\n')[-1].strip()).group(1)
            else:
                I['ln'] = 'n'
        else:
            I['ln'] = 'n'
        sb = body(t, c + '_set_n')[2].split('\n')[-1].strip()
        I['GS'] = subst_n(call_args(sb, c + '_put_at')[0], I['ln'])
        a = body(t, c + '_app_n')
        if a:
            ab = a[2].split('\n')[-1].strip()
            fn = c + '_grow' if ab.startswith(c + '_grow(') else c + '_push'
            I['afn'] = fn
            args = call_args(ab, fn)
            I['GA'] = subst_n(args[0], I['ln'])
            I['aargs'] = [subst_n(x, I['ln']) for x in args[1:]]
        else:
            I['GA'] = None
        gb = body(t, c + '_get_n')[2].split('\n')[-1].strip()
        I['GG'] = subst_n(call_args(gb, c + '_get_in')[0], I['ln'])
    return I


def imports_of(path):
    return {m.group(2): os.path.normpath(os.path.join(os.path.relpath(path.parent, ROOT), m.group(1)))
            for m in IMPORT.finditer(path.read_text())}


def laws(I, imps):
    """(defs text, law count) for collection I; imps collects {alias: root-relative path}"""
    c, t = I['c'], I['text']
    dpath = os.path.relpath(I['file'], ROOT)
    DA = c + '_c'
    imps[DA] = dpath
    di = imports_of(I['file'])
    ren = {}
    for a, p in di.items():
        have = [k for k, q in imps.items() if q == p]
        if have:
            ren[a] = have[0]
        else:
            b = a if a not in imps else a + '_' + c
            imps[b] = p
            ren[a] = b
    defs = set(re.findall(r'^(?:def|type) (\w+)', t, re.M))

    def q(x):
        def sub(m):
            a, r = m.group(1), m.group(2)
            if r is not None and a in ren:
                return ren[a] + '.' + r
            if r is None and a in defs:
                return DA + '.' + a
            return m.group(0)
        return re.sub(r'(?<![\w.])([A-Za-z_]\w*)(?:\.([A-Za-z_]\w*))?', sub, x)
    T, VT, ET = q(I['T']), q(I['VT']), q(I['ET'])
    GS, GA, GG = q(I['GS']), q(I['GA']) if I['GA'] else None, q(I['GG'])
    vm = I['vm']
    out = []
    w = out.append
    if I['kind'] == 'seq':
        EL = q(I['EL'])
        OBJ = '%s.%s{arr, n}' % (DA, I['T'])
        bind = '-arr: Array<%s>, +n: U32' % EL
        put = lambda g: '%s.%s_put_in(%s, arr, n, i, v)' % (DA, c, g)
        app = lambda g: '%s.%s_app_in(%s, arr, n, v)' % (DA, c, g)
        getin = lambda g: '%s.%s_get_in(%s, arr, n, i)' % (DA, c, g)
    else:
        OBJ = '%s{ws, n}' % T
        bind = '-ws: Array<U32>, +n: U32'
        put = lambda g: '%s.%s_put_at(%s, %s, i, v)' % (DA, c, g, OBJ)
        app = lambda g: '%s.%s(%s)' % (DA, I['afn'], ', '.join([g] + [OBJ if x == 'o' else q(x) for x in I['aargs']]))
        getin = lambda g: '%s.%s_get_in(%s, %s, i)' % (DA, c, g, OBJ)
    SET = '%s.%s_set(%s, i, v)' % (DA, c, OBJ)
    APP = '%s.%s_append(%s, v)' % (DA, c, OBJ)
    GET = '%s.%s_get(%s, i)' % (DA, c, OBJ)
    # v is erased unless a guard reads it (a byte element's value check)
    vb = ('+v: %s' if re.search(r'(?<![\w.])v(?![\w.])', (GS or '') + (GA or '')) else '-v: %s') % VT
    n = 0
    w('# ---- %s ----' % c)
    # the flags: exactly the guard (a case split on the guard's value)
    w('def %s_flag_set(b: Bool, %s, +i: U32, %s) -> {Pair.snd(%s, Bool, %s) == b : Bool}:' % (c, bind, vb, T, put('b')))
    w('  match b:\n    case True{}: {==}\n    case False{}: {==}')
    w('def %s_api_set_flag(%s, +i: U32, %s) -> {Pair.snd(%s, Bool, %s) == %s : Bool}:' % (c, bind, vb, T, SET, GS))
    w('  %s_flag_set(%s, %s, i, v)' % (c, GS, 'arr, n' if I['kind'] == 'seq' else 'ws, n'))
    w('def %s_api_set_rejected(%s, +i: U32, %s, +e: {%s == False{} : Bool}) -> {%s == (%s, False{}) : %s & Bool}:' % (c, bind, vb, GS, SET, OBJ, T))
    w('  %%Equal.sym(Bool, %s, False{}, e) : {%s == (%s, False{}) : %s & Bool}' % (GS, put('_'), OBJ, T))
    w('  {==}')
    w('def %s_api_get_outside(%s, +i: U32, +e: {%s == False{} : Bool}) -> {%s == (%s, None{}) : %s & Maybe<&1, %s>}:' % (c, bind, GG, GET, OBJ, T, ET))
    w('  %%Equal.sym(Bool, %s, False{}, e) : {%s == (%s, None{}) : %s & Maybe<&1, %s>}' % (GG, getin('_'), OBJ, T, ET))
    w('  {==}')
    n += 3
    if GA:
        w('def %s_flag_append(b: Bool, %s, %s) -> {Pair.snd(%s, Bool, %s) == b : Bool}:' % (c, bind, vb, T, app('b')))
        w('  match b:\n    case True{}: {==}\n    case False{}: {==}')
        w('def %s_api_append_flag(%s, %s) -> {Pair.snd(%s, Bool, %s) == %s : Bool}:' % (c, bind, vb, T, APP, GA))
        w('  %s_flag_append(%s, %s, v)' % (c, GA, 'arr, n' if I['kind'] == 'seq' else 'ws, n'))
        w('def %s_api_append_rejected(%s, %s, +e: {%s == False{} : Bool}) -> {%s == (%s, False{}) : %s & Bool}:' % (c, bind, vb, GA, APP, OBJ, T))
        w('  %%Equal.sym(Bool, %s, False{}, e) : {%s == (%s, False{}) : %s & Bool}' % (GA, app('_'), OBJ, T))
        w('  {==}')
        n += 2
    if I['kind'] == 'seq':
        LEN = lambda x: 'Pair.snd(%s, U32, %s.%s_len(Pair.fst(%s, Bool, %s)))' % (T, DA, c, T, x)
        w('def %s_api_set_length(%s, +i: U32, %s, +e: {%s == True{} : Bool}) -> {%s == n : U32}:' % (c, bind, vb, GS, LEN(SET)))
        w('  %%Equal.sym(Bool, %s, True{}, e) : {%s == n : U32}' % (GS, LEN(put('_'))))
        w('  {==}')
        n += 1
        if GA:
            w('def %s_api_append_length(%s, %s, +e: {%s == True{} : Bool}) -> {%s == (n + 1 : U32) : U32}:' % (c, bind, vb, GA, LEN(APP)))
            w('  %%Equal.sym(Bool, %s, True{}, e) : {%s == (n + 1 : U32) : U32}' % (GA, LEN(app('_'))))
            w('  {==}')
            n += 1
        if I['data']:
            n += data_readback(w, I, DA, T, EL, ET, GS, GA, GG, vm, c)
    w('')
    return '\n'.join(out), n


def data_readback(w, I, DA, T, EL, ET, GS, GA, GG, vm, c):
    """read-back laws of a Data-element list over storage thaw(t), t a perfect tree of depth d < 32"""
    TH = 'F.array__thaw(%s, t)' % EL
    UP = lambda j, x: 'F.array__upd(%s, d, t, U32.to_nat(%s), %s)' % (EL, j, x)
    SEQ = lambda a, m: '%s.%s{%s, %s}' % (DA, I['T'], a, m)
    OBJ = SEQ(TH, 'n')
    sub = lambda g, **kw: re.sub(r'(?<![\w.])(arr|n|i)(?![\w.])', lambda m: kw.get(m.group(1), m.group(1)), g)
    GSx = sub(GS, arr=TH)
    TR = lambda x: 'Pair.fst(%s, Bool, %s)' % (T, x)
    pre = ('+d: Nat, +t: F.array__Tree<%s>, +n: U32, +i: U32, %sv: %s, +x: %s, +hd: {Nat.is_lt(d, 32n) == True{} : Bool}, '
           '+hi: {Nat.is_lt(U32.to_nat(i), F.spec_common__pow2(d)) == True{} : Bool}, '
           '+hx: {F.spec_common__nth(%s, F.array__slots(%s, t), U32.to_nat(i)) == Some{x} : Maybe<&2, %s>}, '
           '+pf: {F.array__perfect(%s, d, t) == True{} : Bool}' % (EL, '+', EL, EL, EL, EL, EL, EL))
    RES = lambda y: '(%s, Some{%s}) : %s & Maybe<&1, %s>' % (SEQ('F.array__thaw(%s, %s)' % (EL, UP('i', 'v')), 'n'), y, T, ET)
    GET = lambda o, j: '%s.%s_get(%s, %s)' % (DA, c, o, j)
    SETO = '%s.%s_set(%s, i, v)' % (DA, c, OBJ)
    AS = 'Array.set(%s, %s, i, v)' % (EL, TH)
    # set, then get the same index
    w('def %s_api_read_set(%s, +hs: {%s == True{} : Bool}) -> {%s == %s}:' % (c, pre, GSx, GET(TR(SETO), 'i'), RES('v')))
    w('  %%Equal.sym(Bool, %s, True{}, hs) : {%s == %s}' % (GSx, GET(TR('%s.%s_put_in(_, %s, n, i, v)' % (DA, c, TH)), 'i'), RES('v')))
    assert GS == GG, (c, GS, GG)   # a Data list's set and get guards are both i < n
    w('  %%Equal.sym(Bool, %s, True{}, hs) : {%s.%s_get_in(_, %s, n, i) == %s}' % (GG, DA, c, AS, RES('v')))
    w('  %%Equal.sym(Array<%s> & %s, Array.get(%s, %s, i), (F.array__thaw(%s, %s), v), F.array__get_set_same(%s, d, t, i, v, x, hd, hi, hx, pf)) : {%s.%s_took(n, _) == %s}'
      % (EL, EL, EL, AS, EL, UP('i', 'v'), EL, DA, c, RES('v')))
    w('  {==}')
    # set, then get another index
    pre2 = pre + (', +j: U32, +y: %s, +hj: {Nat.is_lt(U32.to_nat(j), F.spec_common__pow2(d)) == True{} : Bool}, '
                  '+ne: {Nat.is_eq(U32.to_nat(i), U32.to_nat(j)) == False{} : Bool}, '
                  '+hy: {F.spec_common__nth(%s, F.array__slots(%s, t), U32.to_nat(j)) == Some{y} : Maybe<&2, %s>}, '
                  '+hm: {%s == True{} : Bool}' % (EL, EL, EL, EL, sub(GG, i='j')))
    gj = sub(GG, i='j')
    w('def %s_api_other_set(%s, +hs: {%s == True{} : Bool}) -> {%s == %s}:' % (c, pre2, GSx, GET(TR(SETO), 'j'), RES('y')))
    w('  %%Equal.sym(Bool, %s, True{}, hs) : {%s == %s}' % (GSx, GET(TR('%s.%s_put_in(_, %s, n, i, v)' % (DA, c, TH)), 'j'), RES('y')))
    w('  %%Equal.sym(Bool, %s, True{}, hm) : {%s.%s_get_in(_, %s, n, j) == %s}' % (gj, DA, c, AS, RES('y')))
    w('  %%Equal.sym(Array<%s> & %s, Array.get(%s, %s, j), (F.array__thaw(%s, %s), y), F.array__get_set_other(%s, d, t, i, j, v, x, y, hd, hi, hj, ne, hx, hy, pf)) : {%s.%s_took(n, _) == %s}'
      % (EL, EL, EL, AS, EL, UP('i', 'v'), EL, DA, c, RES('y')))
    w('  {==}')
    if not GA:
        return 2
    # append, then get index n (the storage has room: no growth)
    GAx = sub(GA, arr=TH)
    N1 = '(n + 1 : U32)'
    AN = 'Array.set(%s, %s, n, v)' % (EL, TH)
    RESA = '(%s, Some{v}) : %s & Maybe<&1, %s>' % (SEQ('F.array__thaw(%s, %s)' % (EL, UP('n', 'v')), N1), T, ET)
    prea = ('+d: Nat, +t: F.array__Tree<%s>, +n: U32, +v: %s, +x: %s, +hd: {Nat.is_lt(d, 32n) == True{} : Bool}, '
            '+hr: {U32.is_lt(n, F.u32__pow2u(d)) == True{} : Bool}, '
            '+hx: {F.spec_common__nth(%s, F.array__slots(%s, t), U32.to_nat(n)) == Some{x} : Maybe<&2, %s>}, '
            '+pf: {F.array__perfect(%s, d, t) == True{} : Bool}, +hw: {U32.is_lt(n, %s) == True{} : Bool}, +ha: {%s == True{} : Bool}'
            % (EL, EL, EL, EL, EL, EL, EL, N1, GAx))
    APPO = '%s.%s_append(%s, v)' % (DA, c, OBJ)
    SEQA = lambda room: SEQ('Array.set(%s, %s, n, v)' % (EL, room), N1)
    w('def %s_api_read_append(%s) -> {%s == %s}:' % (c, prea, GET(TR(APPO), 'n'), RESA))
    w('  %%Equal.sym(Bool, %s, True{}, ha) : {%s == %s}' % (GAx, GET(TR('%s.%s_app_in(_, %s, n, v)' % (DA, c, TH)), 'n'), RESA))
    w('  %%Equal.sym(Array<%s> & U32, Array.size(%s, %s), (%s, F.u32__pow2u(d)), F.array__size_thaw(%s, d, t, pf)) : {%s == %s}'
      % (EL, EL, TH, TH, EL, GET(SEQA('%s.%s_room_sized(n, _)' % (DA, c)), 'n'), RESA))
    w('  %%Equal.sym(Bool, U32.is_lt(n, F.u32__pow2u(d)), True{}, hr) : {%s == %s}'
      % (GET(SEQA('%s.%s_room_pick(_, %s, n)' % (DA, c, TH)), 'n'), RESA))
    ga = sub(GG, n=N1, i='n', arr=AN)
    w('  %%Equal.sym(Bool, %s, True{}, hw) : {%s.%s_get_in(_, %s, %s, n) == %s}' % (ga, DA, c, AN, N1, RESA))
    w('  %%Equal.sym(Array<%s> & %s, Array.get(%s, %s, n), (F.array__thaw(%s, %s), v), F.array__get_set_same(%s, d, t, n, v, x, hd, '
      'F.array__lt_bridge(n, d, hd, True{}, hr), hx, pf)) : {%s.%s_took(%s, _) == %s}'
      % (EL, EL, EL, AN, EL, UP('n', 'v'), EL, DA, c, N1, RESA))
    w('  {==}')
    return 3


def rel(p):
    r = os.path.relpath(ROOT / p, OBJ)
    return r if r.startswith('.') else './' + r


def outputs():
    cs = collections()
    outs, total = {}, 0
    for k in range(0, len(cs), PER_FILE):
        imps = {'F': 'proofs/compact/found.bend'}
        parts = []
        for c in cs[k:k + PER_FILE]:
            txt, m = laws(info(c), imps)
            parts.append(txt)
            total += m
        body = '\n'.join(parts)
        used = [a for a in imps if re.search(r'(?<![\w.])%s\.' % re.escape(a), body)]
        head = ['import Base'] + ['import %s as %s' % (rel(imps[a]), a) for a in used]
        head += ['', HEADER,
                 '# The collection laws of the public API (C_set, C_append, C_get, C_len), with the guards the',
                 '# runtime computes from the object; see codegen/coll_laws.py for the list of laws.', '']
        outs[OBJ / ('coll_api_%d.bend' % (k // PER_FILE))] = '\n'.join(head) + body
    return outs, total


def main():
    check = '--check' in sys.argv
    outs, total = outputs()
    stale = [p.name for p, t in outs.items() if not p.exists() or p.read_text() != t]
    orphans = sorted({p.name for p in OBJ.glob('coll_api_*.bend')} - {p.name for p in outs})
    if check:
        if stale or orphans:
            print('stale: ' + ', '.join(stale + [o + ' (orphan)' for o in orphans]))
            sys.exit(1)
        print('coll_laws: %d files, %d collection laws up to date' % (len(outs), total))
        return
    for p, t in outs.items():
        if not p.exists() or p.read_text() != t:
            p.write_text(t)
    for o in orphans:
        (OBJ / o).unlink()
    print('coll_laws: %d files, %d collection laws' % (len(outs), total))


if __name__ == '__main__':
    main()
