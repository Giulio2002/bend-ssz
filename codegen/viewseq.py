VIEW_SET = '''def %(c)s_view_set(+c: Nat, +d: Nat, +t: F.array__Tree<%(E)s>, +J: Nat, +e: %(E)s, +hJ: {Nat.is_lt(J, F.spec_common__pow2(d)) == True{} : Bool},
    +pf: {F.array__perfect(%(E)s, d, t) == True{} : Bool})
    -> {S.Sequence{%(xa)s} == VS.field_set(S.Sequence{%(xb)s}, J, %(V)s(e)) : S.Value}:
  %%Equal.sym(F.array__Tree<%(E)s>, %(ftu)s, %(tu)s, F.array__freeze_thaw(%(E)s, %(tu)s)) :
    {S.Sequence{%(xi_)s} == VS.field_set(S.Sequence{%(xb)s}, J, %(V)s(e)) : S.Value}
  %%Equal.sym(F.array__Tree<%(E)s>, %(ft)s, t, F.array__freeze_thaw(%(E)s, t)) :
    {S.Sequence{%(xa2)s} == VS.field_set(S.Sequence{%(xi2)s}, J, %(V)s(e)) : S.Value}
  %%Equal.sym(List<&2, %(E)s>, %(slu)s, %(upd)s, F.array__upd_slots(%(E)s, d, t, J, e, hJ, pf)) :
    {S.Sequence{RTL.xi_%(c)s(c, _, 0n)} == VS.field_set(S.Sequence{RTL.xi_%(c)s(c, %(slt)s, 0n)}, J, %(V)s(e)) : S.Value}
  Equal.cong(S.Value, S.Value, z => S.Sequence{z}, RTL.xi_%(c)s(c, %(upd)s, 0n), VS.items_set(RTL.xi_%(c)s(c, %(slt)s, 0n), J, %(V)s(e)),
    %(c)s_xi_set(c, J, %(slt)s, 0n, J, e, {==}, F.logic__subst(Nat, z => {Nat.is_lt(J, z) == True{} : Bool}, F.spec_common__pow2(d), F.spec_common__length(%(E)s, %(slt)s), Equal.sym(Nat, F.spec_common__length(%(E)s, %(slt)s), F.spec_common__pow2(d), F.array__slots_length(%(E)s, d, t, pf)), hJ)))
'''

HELPER = '''def lt_add_succ(+a: Nat, +p: Nat) -> {Nat.is_lt(a, Nat.add(a, 1n+p)) == True{} : Bool}:
  F.logic__subst(Nat, z => {Nat.is_lt(a, z) == True{} : Bool}, 1n+Nat.add(a, p), Nat.add(a, 1n+p), Equal.sym(Nat, Nat.add(a, 1n+p), 1n+Nat.add(a, p), F.nat__add_succ(a, p)),
    F.nat__le_lt_succ(a, Nat.add(a, p), F.nat__le_add_right(a, p)))
'''


def seq_file():
    specs = seq_specs()
    imps = {'S': '../../types/schema.bend', 'F': '../compact/found.bend', 'VS': './value_set.bend', 'RTL': './root_types_light.bend', 'WR': './words_rw.bend'}
    for sp in specs.values():
        imps.update(sp['imports'])
    out = ['import Base'] + ['import %s as %s' % (p, a) for a, p in imps.items()]
    out += ['', HEADER,
            '# The view xv_<list> (root_types_light.bend) of a list of Data elements after one element is written: the view before with',
            "# that item replaced by the new element's view (value_set.bend's field_set). See codegen/view_laws.py.", '', HELPER]
    for c, sp in specs.items():
        E, V = sp['E'], sp['V']

        def upd(W, J='J', e='e'):
            return 'F.spec_common__update(%s, %s, %s, %s)' % (E, W, J, e)

        def XAT(W, i):
            return 'RTL.xat_%s(%s, %s)' % (c, W, i)

        def XI(k, W, i):
            return 'RTL.xi_%s(%s, %s, %s)' % (c, k, W, i)
        out.append('# ---- %s ----' % c)
        out.append(XAT_LEMMAS % dict(c=c, E=E, xs=XAT(upd('W'), 'J'), xn=XAT(upd('Nil{}'), 'J'), xu=XAT(upd('W'), 'i'), xw=XAT('W', 'i'),
                                     xu0=XAT(upd('Con{x, t}', '0n', 'e').replace('J', '0n'), '0n'), xw0=XAT('Con{x, t}', '0n')))
        out.append(XI_LEMMAS % dict(c=c, E=E, V=V, a=XI('k', upd('W'), 'i0'), b=XI('k', 'W', 'i0'), xu=XAT(upd('W'), 'i0'), xw=XAT('W', 'i0'), xz=XAT(upd('W'), 'z'),
                                    tu=XI('q', upd('W'), '1n+i0'), tw=XI('q', 'W', '1n+i0')))
        TU = 'F.array__upd(%s, d, t, J, e)' % E

        def SL(T):
            return 'F.array__slots(%s, %s)' % (E, T)

        def FT(T):
            return 'F.array__freeze(%s, F.array__thaw(%s, %s))' % (E, E, T)
        out.append(VIEW_SET % dict(c=c, E=E, V=V, xa='RTL.xi_%s(c, %s, 0n)' % (c, SL(FT(TU))), xb='RTL.xi_%s(c, %s, 0n)' % (c, SL(FT('t'))),
                                   ftu=FT(TU), tu=TU, ft=FT('t'), xi_='RTL.xi_%s(c, %s, 0n)' % (c, SL('_')),
                                   xa2='RTL.xi_%s(c, %s, 0n)' % (c, SL(TU)), xi2='RTL.xi_%s(c, %s, 0n)' % (c, SL('_')),
                                   slu=SL(TU), upd=upd(SL('t')), slt=SL('t')))
    return '\n'.join(out)
