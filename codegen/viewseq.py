"""The lists stored as an array of Data elements: the view xv_<list> (proofs/obj/root_types_light.bend) after one element is
written (helper of codegen/view_laws.py, which writes proofs/obj/view_seq.bend from seq_file()).

xv_<c>(Seq{arr, n}) is Sequence{xi_<c>(n, slots(freeze(arr)), 0)}, and xi_<c> builds item i from the element view of
xat_<c>(slots, i). Writing element J of a perfect tree t (F.array__upd, whose slots are spec_common__update of the slots)
gives the old items with item J replaced by the new element's view (value_set.bend's items_set)."""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OBJ = ROOT / 'proofs/obj'
HEADER = '# GENERATED by codegen/view_laws.py. Do not edit.'


def seq_specs():
    """{list name: dict(E=element type, V=element view function, T=list type, imports={alias: path})} of the lists whose view
    xv_<c> root_types_light.bend defines over Data elements"""
    t = (OBJ / 'root_types_light.bend').read_text()
    imps = {m.group(2): m.group(1) for m in re.finditer(r'^import (\S+) as (\w+)', t, re.M)}
    out = {}
    for m in re.finditer(r'^def xv_(\w+)\(o: ([^)]*)\) -> S.Value:', t, re.M):
        c = m.group(1)
        mx = re.search(r'^def xat_%s\(W: List<&2, ([^>]*)>, \+i: Nat\) -> ([^:]*):\n  match W:\n    case Nil\{\}: (.*)$' % re.escape(c), t, re.M)
        mi = re.search(r'^def xi_%s\(.*?\n    case 1n\+q: S.Items\{(RN\.\w+)\(xat_%s' % (re.escape(c), re.escape(c)), t, re.M | re.S)
        if not mx or not mi or not mx.group(3).endswith('_default()'):
            continue   # boxed elements: no Data tree to write into
        E, V = mx.group(1), mi.group(1)
        al = set(re.findall(r'\b(\w+)\.', E + ' ' + V))
        out[c] = dict(E=E, V=V, T=m.group(2), imports={a: imps[a] for a in sorted(al) if a in imps})
    return out


XAT_LEMMAS = '''def %(c)s_xat_same(+W: List<&2, %(E)s>, +J: Nat, +e: %(E)s, +h: {Nat.is_lt(J, F.spec_common__length(%(E)s, W)) == True{} : Bool})
    -> {%(xs)s == e : %(E)s}:
  match W J:
    case Nil{} _: Empty.absurd({%(xn)s == e : %(E)s}, F.nat__lt_zero_absurd(J, h))
    case Con{x, t} 0n: {==}
    case Con{x, t} 1n+p: %(c)s_xat_same(t, p, e, h)

def %(c)s_xat_other(+W: List<&2, %(E)s>, +J: Nat, +i: Nat, +e: %(E)s, +ne: {Nat.is_eq(J, i) == False{} : Bool})
    -> {%(xu)s == %(xw)s : %(E)s}:
  match W J i:
    case Nil{} _ _: {==}
    case Con{x, t} 0n 0n: Empty.absurd({%(xu0)s == %(xw0)s : %(E)s}, F.logic__false_true(Equal.sym(Bool, True{}, False{}, ne)))
    case Con{x, t} 0n 1n+b: {==}
    case Con{x, t} 1n+a 0n: {==}
    case Con{x, t} 1n+a 1n+b: %(c)s_xat_other(t, a, b, e, ne)
'''

