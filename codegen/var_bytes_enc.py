    T0 = f'OUTW({E.A}, {DO}n, VC.ZT({DO}n), 0n)'
    A0 = f'{E.A}, {DO}n, VC.ZT({DO}n), 0n'

    def tree(j):
        return 'D' if j == 0 else f'LY{j}({DA})'

