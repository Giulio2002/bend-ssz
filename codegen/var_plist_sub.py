#!/usr/bin/env python3
"""Codec laws of the bare progressive lists of sub-word elements: the generic forms
ProgressiveList[uint8] (GtDE4B86A990), ProgressiveList[uint16] (GtF23A2FB97E) and
ProgressiveList[boolean] (Gt83D8B3D008).

    python3 codegen/var_plist_sub.py [--check] [--no-big]

Writes, for each element kind k in u8, u16, bool:

    proofs/obj/big_var_winp_<k>.bend   the list at a window of any byte offset x and
        length len of a buffer (the interface of proofs/obj/vua_win.bend: CHKw,
        ok_evalw, OBJw, readw, VALw, specw, invw), so that a container holding
        such a list can import it as a child window;
    proofs/obj/big_var_plist_<X>_top.bend     ok_eval, decode_accept, decode_none,
        decode_spec, decode_reject: the window at x = 0, off = 0, len = n
        (codegen/var_win.py's top template);
    proofs/obj/big_var_plist_<X>_top_unique.bend   decode_unique;
    proofs/obj/big_var_plist_<X>_enc.bend     encode_eval, encode_spec.

The window modules are BIG (checked with `checkq --big`): the reader's list storage
is B.zeros(u) at every depth u (big_vvlz.bend's zg).  With --no-big nothing is
written.
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'codegen'))
import var_win as VW  # noqa: E402

# element kind -> (generic name, runtime prefix)
KINDS = {'u8': ('GtDE4B86A990', 'pl_u8'), 'u16': ('GtF23A2FB97E', 'pl_u16'), 'bool': ('Gt83D8B3D008', 'pl_bool')}
HDR = '# GENERATED by codegen/var_plist_sub.py. Do not edit.'


def generic(lines):
    out = []
    for ln in lines:
        ln = ln.replace('import ../../types/fulu_obj.bend as T', 'import ../../types/generic_obj.bend as T')
        ln = ln.replace('import ../../spec/fulu_schemas.bend as Spec', 'import ./generic_specs.bend as Spec')
        out.append(ln)
    return out


def win_fname(k):
    return ROOT / f'proofs/obj/big_var_winp_{k}.bend'


def top_fname(X, part=''):
    return ROOT / f'proofs/obj/big_var_plist_{X}{part}.bend'


