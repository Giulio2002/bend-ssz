def win_text(k):
    X, p = KINDS[k]
    body = {'u8': WIN_U8}[k].replace('@READW', READW)
    body = body.replace('@X(', f'{X}(').replace('@p_', f'{p}_')
    L = generic(VW.HEADX) + WIN_IMPORTS + ['', HDR,
                                           f'# ProgressiveList[{ {"u8": "uint8", "u16": "uint16", "bool": "boolean"}[k] }] ({X}) at a window of any byte offset x:',
                                           '# the interface of proofs/obj/vua_win.bend.', '']
    return '\n'.join(L) + VW.COMMONX + body


def top_text(k):
    X, p = KINDS[k]
    el = {'u8': 'S.Unsigned{P.U8{}}', 'u16': 'S.Unsigned{P.U16{}}', 'bool': 'S.Boolean{}'}[k]
    import types
    txt = VW.top_text(types.SimpleNamespace(n=X), win_fname(k).name, [])
    txt = txt.replace('Codec.parts(items, S.End{})', f'Codec.parts(items, S.Repeat{{{el}}})')
    txt = txt.replace('# GENERATED by codegen/var_win.py. Do not edit.', HDR)
    # the byte-offset window's object also takes the tree's depth
    old = f'def OBJ(+t: FD.array__Tree<U32>, +n: U32) -> T.{X}: W.OBJw(t, 0n, 0, n)'
    assert old in txt
    txt = txt.replace(old, 'def OBJ(+d: Nat, +t: FD.array__Tree<U32>, +n: U32) -> O.Words: W.OBJw(d, t, 0n, 0, n)')
    txt = txt.replace(f'T.{X}_ok(', f'T.{p}_ok(').replace(f'T.{X}_read(', f'T.{p}_read(')
    txt = txt.replace('OBJ(t, n)', 'OBJ(d, t, n)').replace(f'T.{X}_', '@@').replace(f'T.{X}', 'O.Words').replace('@@', f'T.{X}_')
    return '\n'.join(generic(txt.split('\n')))


