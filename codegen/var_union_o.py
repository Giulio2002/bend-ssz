#!/usr/bin/env python3
"""The OKW twins of the generic unions' encoder windows (codegen/var_cont_enc.py union_text): a union's encoding
below 2^31 bytes (the selector byte and the arm), in the companion module big_encx_<U>_iface_o.bend, next to the
old OK laws (unchanged, in big_encx_<U>_iface.bend, imported as OB).

    python3 codegen/var_union_o.py [--check] [--no-big]

OKW(m): the arm's OKW (its container encoding below 2^31 bytes; a one-byte record arm: its OK) and 1 + its bytes
< 2^31. The laws putxO, putx_bytesO, szxO, encx_specO, domxO, maxxO (all-record unions), sizexO and validxO are the
old laws' twins on OKW, with dd < 31 and the region below 2^32 (hl32; putxO has no hs31 premise), through the
W twins of proofs/obj/vunion.bend, vrecb.bend and the arms' own O laws (their ifaces and iface_o companions).
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import var_cont_enc as VCE  # noqa: E402

ROOT = VCE.ROOT
TRU = 'True{} : Bool'


def ofile(U):
    return ROOT / f'proofs/obj/big_encx_{U}_iface_o.bend'


def text(U):
    arms = VCE.union_arms(U)
    TY = f'Array<U32> & (T.{U} & U32)'
    L = []
    w = L.append
    imps = list(VCE.UHEAD)
    for a in arms:
        if a['kind'] == 'if':
            imps.append(f'import ./big_encx_{a["A"]}_iface.bend as EA_{a["A"]}')
            if (ROOT / f'proofs/obj/big_encx_{a["A"]}_iface_o.bend').exists():
                imps.append(f'import ./big_encx_{a["A"]}_iface_o.bend as EA_{a["A"]}o')
    imps.append(f'import ./big_encx_{U}_iface.bend as OB')
    w('\n'.join(imps))
    w('')
    w('# GENERATED by codegen/var_union_o.py. Do not edit.')
    w(f'# {U}: the OKW twins (the encoding below 2^31 bytes) of its encoder-window interface (see the generator).')
    for a in arms:
        j, A, s = a['j'], a['A'], a['s']
        S_ = str(s)
        DS = f'VU.DS(dd, D, q, r, {S_})'
        HYP = (f'+x: {"EA_" + A + ".MW" if a["kind"] == "if" else "U32"}, +dd: Nat, +D: FD.array__Tree<U32>, +X: U32, +q: Nat, +r: Nat, '
               f'+e: {{U32.to_nat(X) == Nat.add(A.quad(q), r) : Nat}}, +hr: {{Nat.is_lt(r, 4n) == {TRU}}},\n'
               f'    +hd: {{Nat.is_lt(dd, 31n) == {TRU}}}, +pf: {{FD.array__perfect(U32, dd, D) == {TRU}}},\n'
               f'    +hl: {{Nat.is_le(Nat.add(q, WD.NWN(Nat.add(r, List.length(&2, U32, OB.ENC{j}(x))))), VB.pw(dd)) == {TRU}}},\n'
               f'    +hl32: {{Nat.is_lt(Nat.add(A.quad(q), Nat.add(r, List.length(&2, U32, OB.ENC{j}(x)))), FD.spec_common__pow2(32n)) == {TRU}}},\n'
               f'    +hz: {{VS.bt(Nat.add(List.length(&2, U32, OB.ENC{j}(x)), WD.PADB(r, List.length(&2, U32, OB.ENC{j}(x)))), VS.bdr(Nat.add(A.quad(q), r), UA.BYT(D))) == UW.ZB(Nat.add(List.length(&2, U32, OB.ENC{j}(x)), WD.PADB(r, List.length(&2, U32, OB.ENC{j}(x))))) : +List<U32>}},\n'
               f'    +hok: {{OKW{j}(x) == {TRU}}}')
        if a['kind'] == 'if':
            ea = f'EA_{A}'
            eo = f'EA_{A}o'
            E = f'List.length(&2, U32, {ea}.ENC(x))'
            BW = f'Nat.is_lt(1n+{E}, VB.pw(31n))'
            END = f'(FD.array__thaw(U32, OB.PUTX{j}(x, dd, D, q, r)), (OB.TH{j}(x), OB.SZ{j}(x)))'
            w(f'''
# ---- arm {j}: {A}, selector {s} ----
def OKW{j}(+x: {ea}.MW) -> Bool: Bool.and({ea}.OKW(x), {BW})

def rtO{j}(+x: {ea}.MW, +dd: Nat, +D: FD.array__Tree<U32>, +X: U32, +q: Nat, +r: Nat, +hok0: {{{ea}.OKW(x) == {TRU}}},
    +rts: {{O.w8(FD.array__thaw(U32, D), X, {S_}) == FD.array__thaw(U32, {DS}) : Array<U32>}},
    +rta: {{T.{A}_putk(FD.array__thaw(U32, {DS}), U32.add(X, 1), {ea}.TH(x)) == (FD.array__thaw(U32, OB.PUTX{j}(x, dd, D, q, r)), ({ea}.TH(x), {ea}.SZ(x))) : Array<U32> & (T.{A} & U32)}})
    -> OB.RT{j}(x, dd, D, X, q, r):
  %Equal.sym(T.{A} & Bool, T.{A}_valid({ea}.TH(x)), ({ea}.TH(x), True{{}}), {eo}.validxO(x, hok0)) :
    {{T.{U}_pk(FD.array__thaw(U32, D), X, T.{U}_va{j}(_)) == {END} : {TY}}}
  %Equal.sym(T.{A} & U32, T.{A}_size({ea}.TH(x)), ({ea}.TH(x), {ea}.SZ(x)), {eo}.sizexO(x, hok0)) :
    {{T.{U}_putn_sz(FD.array__thaw(U32, D), X, T.{U}_sz{j}(_)) == {END} : {TY}}}
  %Equal.sym(Array<U32>, O.w8(FD.array__thaw(U32, D), X, {S_}), FD.array__thaw(U32, {DS}), rts) :
    {{T.{U}_putn_fin(OB.SZ{j}(x), T.{U}_pb{j}(T.{A}_put(_, U32.add(X, 1), {ea}.TH(x)))) == {END} : {TY}}}
  %Equal.sym(Array<U32> & (T.{A} & U32), T.{A}_putk(FD.array__thaw(U32, {DS}), U32.add(X, 1), {ea}.TH(x)), (FD.array__thaw(U32, OB.PUTX{j}(x, dd, D, q, r)), ({ea}.TH(x), {ea}.SZ(x))), rta) :
    {{T.{U}_putn_fin(OB.SZ{j}(x), T.{U}_pb{j}(T.{A}_put_drop(_))) == {END} : {TY}}}
  {{==}}

def goO{j}({HYP})
    -> DK.P2(OB.RT{j}(x, dd, D, X, q, r), OB.BY{j}(x, dd, D, q, r)):
  +E = {E}
  +hok0 = OB.and_l({ea}.OKW(x), {BW}, hok)
  +rts = VU.sel_rtW(dd, D, X, q, r, {S_}, E, e, hr, hd, hl, pf)
  +bys = VU.sel_byW(dd, D, X, q, r, {S_}, E, WD.PADB(r, 1n+E), e, hr, hd, hl, pf, hz)
  +pfs = VU.sel_pf(dd, D, q, r, {S_}, pf)
  +hX = VRX.xstart(q, r, 1n+E, dd, D, pf, hl)
  +ea = VU.arm_eW(dd, X, q, r, E, e, hr, hd, hl, hl32)
  +hla = VU.aroom(q, r, E, dd, hr, hl)
  +hl32a = VU.aroom32(q, r, E, dd, hr, hl32)
  +hza = VU.arm_hz(dd, D, q, r, {S_}, E, hr, hX, bys, hz)
  +rta = {ea}.putxO(x, dd, {DS}, U32.add(X, 1), VU.AQ(q, r), VU.AR(r), ea, VU.ar_lt(r), hd, pfs, hla, hl32a, hza, hok0)
  +bya = {ea}.putx_bytesO(x, dd, {DS}, U32.add(X, 1), VU.AQ(q, r), VU.AR(r), ea, VU.ar_lt(r), hd, pfs, hla, hl32a, hza, hok0)
  +by = VU.ubytes(dd, D, OB.PUTX{j}(x, dd, D, q, r), q, r, {S_}, {ea}.ENC(x), hr, hX, bys, bya)
  +rt = rtO{j}(x, dd, D, X, q, r, hok0, rts, rta)
  OB.mk{j}(x, dd, D, X, q, r, rt, by)

def szkO{j}(+x: {ea}.MW, +hok: {{OKW{j}(x) == {TRU}}}) -> {{U32.to_nat(OB.SZ{j}(x)) == List.length(&2, U32, OB.ENC{j}(x)) : Nat}}:
  VB.add_lt32({ea}.SZ(x), 1, {E}, {ea}.szxO(x, OB.and_l({ea}.OKW(x), {BW}, hok)),
    CS.lt32B(1n+{E}, 1n+{E}, FD.nat__le_refl(1n+{E}), OB.and_r({ea}.OKW(x), {BW}, hok)))
def specO{j}(+x: {ea}.MW, +hok: {{OKW{j}(x) == {TRU}}}) -> {{Codec.parts(OB.VAL{j}(x), Spec.{U}()) == Some{{[S.Variable{{OB.ENC{j}(x)}}]}} : Maybe<&2, +List<S.Part>>}}:
  VU.tag_v({S_}, {ea}.VAL(x), Spec.{A}(), {ea}.ENC(x), {ea}.encx_specO(x, OB.and_l({ea}.OKW(x), {BW}, hok)))
def sizeO{j}(+x: {ea}.MW, +hok: {{OKW{j}(x) == {TRU}}}) -> {{T.{U}_size(OB.TH{j}(x)) == (OB.TH{j}(x), OB.SZ{j}(x)) : T.{U} & U32}}:
  %Equal.sym(T.{A} & U32, T.{A}_size({ea}.TH(x)), ({ea}.TH(x), {ea}.SZ(x)), {eo}.sizexO(x, OB.and_l({ea}.OKW(x), {BW}, hok))) : {{T.{U}_sz{j}(_) == (OB.TH{j}(x), OB.SZ{j}(x)) : T.{U} & U32}}
  {{==}}
def validO{j}(+x: {ea}.MW, +hok: {{OKW{j}(x) == {TRU}}}) -> {{T.{U}_valid(OB.TH{j}(x)) == (OB.TH{j}(x), True{{}}) : T.{U} & Bool}}:
  %Equal.sym(T.{A} & Bool, T.{A}_valid({ea}.TH(x)), ({ea}.TH(x), True{{}}), {eo}.validxO(x, OB.and_l({ea}.OKW(x), {BW}, hok))) : {{T.{U}_va{j}(_) == (OB.TH{j}(x), True{{}}) : T.{U} & Bool}}
  {{==}}''')
        else:
            # the one-byte record arm: nothing beyond the old chain but dd < 31 (the byte writes' W twins)
            P_ = 'Nat.add(0n, 1n+VU.X0(q, r))'
            Xn = 'Nat.add(A.quad(VU.AQ(q, r)), VU.AR(r))'
            Y0 = 'U32.add(U32.add(X, 1), 0)'
            PB_ = 'WD.PADB(VU.AR(r), 1n)'
            b8 = '[U32.and(x, 255)]'
            w(f'''
# ---- arm {j}: {A}, selector {s} (a one-byte record) ----
def OKW{j}(+x: U32) -> Bool: OB.OK{j}(x)

def goO{j}({HYP})
    -> DK.P2(OB.RT{j}(x, dd, D, X, q, r), OB.BY{j}(x, dd, D, q, r)):
  +rts = VU.sel_rtW(dd, D, X, q, r, {S_}, 1n, e, hr, hd, hl, pf)
  +bys = VU.sel_byW(dd, D, X, q, r, {S_}, 1n, WD.PADB(r, 2n), e, hr, hd, hl, pf, hz)
  +pfs = VU.sel_pf(dd, D, q, r, {S_}, pf)
  +hX = VRX.xstart(q, r, 2n, dd, D, pf, hl)
  +eY = Equal.trans(Nat, U32.to_nat(U32.add(X, 1)), {Xn}, 1n+VU.X0(q, r), VU.arm_eW(dd, X, q, r, 1n, e, hr, hd, hl, hl32), VU.apos(q, r, hr))
  +hb = FD.logic__subst(Nat, z => {{Nat.is_le(z, A.quad(VB.pw(dd))) == {TRU}}}, Nat.add(VU.X0(q, r), 2n), 1n+Nat.add(VU.X0(q, r), 1n), FD.nat__add_succ(VU.X0(q, r), 1n),
    VRX.xend(q, r, 2n, dd, hl))
  +e0 = VRB.fposbW(dd, U32.add(X, 1), 0, 1n+VU.X0(q, r), 1n, eY, hd, hb, {{==}})
  +rtw = VRB.w8p_rtW(dd, {DS}, {Y0}, {P_}, x, e0, hd, hb, pfs)
  +hza = VU.arm_hz(dd, D, q, r, {S_}, 1n, hr, hX, bys, hz)
  +hz1 = FD.logic__subst(Nat, z => {{VS.bt(1n, VS.bdr(z, UA.BYT({DS}))) == UW.ZB(1n) : +List<U32>}}, {Xn}, {P_}, VU.apos(q, r, hr),
    VRX.zhead(1n, {PB_}, VS.bdr({Xn}, UA.BYT({DS})), hza))
  +byw = VRB.w8p_bytesW(dd, {DS}, {Y0}, {P_}, x, e0, hd, hb, pfs, hz1)
  +zt = VRX.ztail(1n, {PB_}, VS.bdr({Xn}, UA.BYT({DS})), hza)
  +zt2 = FD.logic__subst(+List<U32>, zz => {{VS.bt({PB_}, zz) == UW.ZB({PB_}) : +List<U32>}}, VS.bdr(1n, VS.bdr({Xn}, UA.BYT({DS}))), VS.bdr(Nat.add({Xn}, 1n), UA.BYT({DS})),
    Equal.sym(+List<U32>, VS.bdr(Nat.add({Xn}, 1n), UA.BYT({DS})), VS.bdr(1n, VS.bdr({Xn}, UA.BYT({DS}))), UW.bdr_add({Xn}, 1n, UA.BYT({DS}))), zt)
  +hzt = FD.logic__subst(Nat, z => {{VS.bt({PB_}, VS.bdr(Nat.add(z, 1n), UA.BYT({DS}))) == UW.ZB({PB_}) : +List<U32>}}, {Xn}, {P_}, VU.apos(q, r, hr), zt2)
  +ext = WD.spl_ext(UA.BYT({DS}), {P_}, {b8}, {PB_}, hzt)
  +by2p = Equal.trans(+List<U32>, UA.BYT(OB.PUTX{j}(x, dd, D, q, r)), UW.SPL(UA.BYT({DS}), {P_}, {b8}), UW.SPL(UA.BYT({DS}), {P_}, List.append(&2, U32, {b8}, UW.ZB({PB_}))), byw, ext)
  +by2 = FD.logic__subst(Nat, z => {{UA.BYT(OB.PUTX{j}(x, dd, D, q, r)) == UW.SPL(UA.BYT({DS}), z, List.append(&2, U32, {b8}, UW.ZB({PB_}))) : +List<U32>}}, {P_}, {Xn},
    Equal.sym(Nat, {Xn}, {P_}, VU.apos(q, r, hr)), by2p)
  +by = VU.ubytes(dd, D, OB.PUTX{j}(x, dd, D, q, r), q, r, {S_}, {b8}, hr, hX, bys, by2)
  +rt = OB.rt{j}(x, dd, D, X, q, r, hok, rts, rtw)
  OB.mk{j}(x, dd, D, X, q, r, rt, by)

def szkO{j}(+x: U32, +hok: {{OKW{j}(x) == {TRU}}}) -> {{U32.to_nat(OB.SZ{j}(x)) == List.length(&2, U32, OB.ENC{j}(x)) : Nat}}: {{==}}
def specO{j}(+x: U32, +hok: {{OKW{j}(x) == {TRU}}}) -> {{Codec.parts(OB.VAL{j}(x), Spec.{U}()) == Some{{[S.Variable{{OB.ENC{j}(x)}}]}} : Maybe<&2, +List<S.Part>>}}:
  OB.spec{j}(x, hok)
def sizeO{j}(+x: U32, +hok: {{OKW{j}(x) == {TRU}}}) -> {{T.{U}_size(OB.TH{j}(x)) == (OB.TH{j}(x), OB.SZ{j}(x)) : T.{U} & U32}}: {{==}}
def validO{j}(+x: U32, +hok: {{OKW{j}(x) == {TRU}}}) -> {{T.{U}_valid(OB.TH{j}(x)) == (OB.TH{j}(x), True{{}}) : T.{U} & Bool}}:
  OB.valid{j}(x, hok)''')
    LHs = '\n  '.join([
        'for +m: OB.MW', 'for +dd: Nat', 'for +D: FD.array__Tree<U32>', 'for +X: U32', 'for +q: Nat', 'for +r: Nat',
        'for +e: {U32.to_nat(X) == Nat.add(A.quad(q), r) : Nat}', f'for +hr: {{Nat.is_lt(r, 4n) == {TRU}}}',
        f'for +hd: {{Nat.is_lt(dd, 31n) == {TRU}}}', f'for +pf: {{FD.array__perfect(U32, dd, D) == {TRU}}}',
        'for +hl: {Nat.is_le(Nat.add(q, WD.NWN(Nat.add(r, List.length(&2, U32, OB.ENC(m))))), VB.pw(dd)) == True{} : Bool}',
        'for +hl32: {Nat.is_lt(Nat.add(A.quad(q), Nat.add(r, List.length(&2, U32, OB.ENC(m)))), FD.spec_common__pow2(32n)) == True{} : Bool}',
        'for +hz: {VS.bt(Nat.add(List.length(&2, U32, OB.ENC(m)), OB.PADB(r, m)), VS.bdr(Nat.add(A.quad(q), r), UA.BYT(D))) == UW.ZB(Nat.add(List.length(&2, U32, OB.ENC(m)), OB.PADB(r, m))) : +List<U32>}',
        'for +hok: {OKW(m) == True{} : Bool}'])
    cs = lambda body: '\n'.join(f'    case OB.MW{a["j"]}{{+x}}: ' + body(a['j']) for a in arms)  # noqa: E731
    GA = 'x, dd, D, X, q, r, e, hr, hd, pf, hl, hl32, hz, hok'
    mts = '\n'.join(f'    case OB.MW{a["j"]}{{+x}}: OKW{a["j"]}(x)' for a in arms)
    w(f'''
# ---- the union's OKW and its laws on it ----
def OKW(m: OB.MW) -> Bool:
  match m:
{mts}

law putxO:
  {LHs}
  {{T.{U}_putk(FD.array__thaw(U32, D), X, OB.TH(m)) == (FD.array__thaw(U32, OB.PUTX(m, dd, D, q, r)), (OB.TH(m), OB.SZ(m))) : {TY}}}
def putxO(m, dd, D, X, q, r, e, hr, hd, pf, hl, hl32, hz, hok):
  match m:
{cs(lambda j: f"OB.PA(OB.RT{j}(x, dd, D, X, q, r), OB.BY{j}(x, dd, D, q, r), goO{j}({GA}))")}

law putx_bytesO:
  {LHs}
  {{UA.BYT(OB.PUTX(m, dd, D, q, r)) == UW.SPL(UA.BYT(D), Nat.add(A.quad(q), r), List.append(&2, U32, OB.ENC(m), UW.ZB(OB.PADB(r, m)))) : +List<U32>}}
def putx_bytesO(m, dd, D, X, q, r, e, hr, hd, pf, hl, hl32, hz, hok):
  match m:
{cs(lambda j: f"OB.PB(OB.RT{j}(x, dd, D, X, q, r), OB.BY{j}(x, dd, D, q, r), goO{j}({GA}))")}

law szxO:
  for +m: OB.MW
  for +hok: {{OKW(m) == True{{}} : Bool}}
  {{U32.to_nat(OB.SZ(m)) == List.length(&2, U32, OB.ENC(m)) : Nat}}
def szxO(m, hok):
  match m:
{cs(lambda j: f"szkO{j}(x, hok)")}

law encx_specO:
  for +m: OB.MW
  for +hok: {{OKW(m) == True{{}} : Bool}}
  {{Codec.parts(OB.VAL(m), Spec.{U}()) == Some{{[S.Variable{{OB.ENC(m)}}]}} : Maybe<&2, +List<S.Part>>}}
def encx_specO(m, hok):
  match m:
{cs(lambda j: f"specO{j}(x, hok)")}

law domxO:
  for +m: OB.MW
  for +hok: {{OKW(m) == True{{}} : Bool}}
  {{SP.bytes_domain(OB.ENC(m)) == True{{}} : Bool}}
def domxO(m, hok): CS.domv(OB.VAL(m), Spec.{U}(), OB.ENC(m), {{==}}, encx_specO(m, hok))

law sizexO:
  for +m: OB.MW
  for +hok: {{OKW(m) == True{{}} : Bool}}
  {{T.{U}_size(OB.TH(m)) == (OB.TH(m), OB.SZ(m)) : T.{U} & U32}}
def sizexO(m, hok):
  match m:
{cs(lambda j: f"sizeO{j}(x, hok)")}

law validxO:
  for +m: OB.MW
  for +hok: {{OKW(m) == True{{}} : Bool}}
  {{T.{U}_valid(OB.TH(m)) == (OB.TH(m), True{{}}) : T.{U} & Bool}}
def validxO(m, hok):
  match m:
{cs(lambda j: f"validO{j}(x, hok)")}
''')
    if all(a['kind'] == 'u8' for a in arms):
        w(f'''law maxxO:
  for +m: OB.MW
  for +hok: {{OKW(m) == True{{}} : Bool}}
  {{Nat.is_le(List.length(&2, U32, OB.ENC(m)), 2n) == True{{}} : Bool}}
def maxxO(m, hok):
  match m:
{cs(lambda j: "{==}")}
''')
    return '\n'.join(L)


def main():
    out = {}
    if '--no-big' not in sys.argv:
        for U in VCE.UCONTS:
            out[ofile(U)] = text(U)
    out = VCE.RR.rewire_out(out)
    if '--check' in sys.argv:
        stale = [str(q.relative_to(ROOT)) for q, t in out.items() if not q.exists() or q.read_text() != t]
        if stale:
            print('stale generated union OKW companions: ' + ', '.join(stale))
            sys.exit(1)
        print('generated union OKW companions are current')
        return
    for q, t in out.items():
        q.write_text(t)
    print(', '.join(str(q.relative_to(ROOT)) for q in out))


if __name__ == '__main__':
    main()
