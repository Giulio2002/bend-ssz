    L1 = goal('WS.btake(U32.to_nat(n), FX.limbs(F.array__slots(U32, %s)))' % TW, 'WS.btake(U32.to_nat(n), FX.limbs(F.array__slots(U32, _)))', 'U32.to_nat(p)')
