#!/usr/bin/env python3
"""Codec laws of the generic PROGRESSIVE containers Gp4B0CA2906A and Gp66304057C3 (and,
later, Gp8A7851175B): their byte-offset window modules and whole-buffer decoder laws, by
codegen/var_winb.py's generic-name path (a ProgressiveContainer encodes as a Container of
its fields: spec/codec.bend), with their variable fields read by the child windows below.

    python3 codegen/var_gp.py [--check] [--no-big]

Writes proofs/obj/big_var_winx_<X>.bend (the window at any byte offset x) and
proofs/obj/big_var_codec_<X>.bend (ok_eval, decode_accept, decode_none, decode_spec,
decode_reject at x = 0) and big_var_codec_<X>_unique.bend (decode_unique).
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'codegen'))
import var_winb as WB  # noqa: E402
import var_win as VW  # noqa: E402
import var_plist_sub as PS  # noqa: E402

HDR = '# GENERATED by codegen/var_gp.py. Do not edit.'
# the child window of each variable field's runtime prefix
CHILDREN = {'pbits': 'big_var_winp_pbits.bend', 'l123_u16': 'var_winx_l123_u16.bend', 'pl_u64': 'big_var_winp_pl_u64.bend',
            'pl_Gc4ED9619F50': 'big_var_winx_pl_Gc4ED9619F50.bend', 'pl_pl_Gc465214E502': 'big_vvl_pl_pl_Gc465214E502.bend',
            'l10_GpF350A3C486': 'var_winx_l10_GpF350A3C486.bend', 'pl_Gp66304057C3': 'big_vvl_pl_Gp66304057C3.bend'}
NAMES = ['Gp4B0CA2906A', 'Gp66304057C3', 'Gp8A7851175B']


def chain(X):
    kids = WB.generic_schema(X)[1]
    ch = 'S.End{}'
    for k in reversed(kids):
        ch = f'S.Chain{{{k}, {ch}}}'
    return ch


def top_text(X, wmod):
    """var_win's whole-buffer template at the byte-offset window x = 0 (as var_plist_sub's lists)."""
    import types
    txt = VW.top_text(types.SimpleNamespace(n=X), wmod, [])
    txt = txt.replace('Codec.parts(items, S.End{})', f'Codec.parts(items, {chain(X)})')
    txt = txt.replace('# GENERATED by codegen/var_win.py. Do not edit.', HDR)
    old = f'def OBJ(+t: FD.array__Tree<U32>, +n: U32) -> T.{X}: W.OBJw(t, 0n, 0, n)'
    assert old in txt
    txt = txt.replace(old, f'def OBJ(+d: Nat, +t: FD.array__Tree<U32>, +n: U32) -> T.{X}: W.OBJw(d, t, 0n, 0, n)').replace('OBJ(t, n)', 'OBJ(d, t, n)')
    return '\n'.join(PS.generic(txt.split('\n')))


def unique_text(X):
    D = f'big_var_codec_{X}.bend'
    return PS.unique_text('u8').replace(PS.top_fname('GtDE4B86A990', '_top').name, D).replace('GtDE4B86A990', X).replace(PS.HDR, HDR)


def outputs(no_big):
    out = {}
    if no_big:
        return out
    WB.CHILD_MOD.update(CHILDREN)
    for X in NAMES:
        L = WB.layout(X, True, WB.FIXMOD, generic=True)
        fn = f'big_var_winx_{X}.bend'
        # the generic schema is GS.<X> (generic_specs.bend), not fulu_schemas' Spec.<X>
        out[ROOT / 'proofs/obj' / f'big_var_codec_{X}.bend'] = top_text(X, fn)
        out[ROOT / 'proofs/obj' / f'big_var_codec_{X}_unique.bend'] = unique_text(X)
        out[ROOT / 'proofs/obj' / fn] = WB.module_text(L).replace('# GENERATED by codegen/var_winb.py. Do not edit.', HDR).replace(f'Spec.{X}()', f'GS.{X}()').replace('T.U32', 'U32')
    return out


def main():
    no_big = '--no-big' in sys.argv
    out = outputs(no_big)
    if '--check' in sys.argv:
        stale = [str(p.relative_to(ROOT)) for p, t in out.items() if not p.exists() or p.read_text() != t]
        if stale:
            print('stale generated progressive containers: ' + ', '.join(stale))
            sys.exit(1)
        print('generated progressive containers are current')
        return
    for p, t in out.items():
        p.write_text(t)
    print(', '.join(str(p.relative_to(ROOT)) for p in out))


if __name__ == '__main__':
    main()
