#!/usr/bin/env python3
"""LightClientBootstrap: a container nesting LightClientHeader whose header also
holds a SyncCommittee (6156 words, array-backed). Helpers for codegen/var_bytes_nest.py:
proofs/obj/vsc.bend, the spec parts of a SyncCommittee value over any word list
of 6144 words (adapted from spec_arr_SyncCommittee.bend's tree-based statement).
"""
import re

import var_bytes as VBY

ROOT = VBY.ROOT
AB = 'F.spec_common__append(U32, F.array__slots(U32, a), F.array__slots(U32, b))'
LEN2 = ('AS.len2(F.array__slots(U32, a), F.array__slots(U32, b), 4096n, 2048n, 6144n, AS.len_tree(12n, a, 4096n, pa, {==}), '
        'AS.len_tree(11n, b, 2048n, pb, {==}), {==})')


def vsc_text():
    src = (ROOT / 'proofs/obj/spec_arr_SyncCommittee.bend').read_text().split('\n')
    i0 = [i for i, l in enumerate(src) if l.startswith('def SyncCommittee_spec_parts(')][0]
    i1 = i0 + 1
    while not src[i1].startswith('def ') and not src[i1].startswith('#'):
        i1 += 1
    body = src[i0:i1]
    head = [l for l in src if l.startswith('import ')]
    G = '[g0, g1, g2, g3, g4, g5, g6, g7, g8, g9, g10, g11]'
    gs = ', '.join(f'+g{j}: U32' for j in range(12))
    VAL = f'S.Sequence{{S.Items{{S.Sequence{{AV.ch12(W)}}, S.Items{{S.BytesValue{{SF.limbs({G})}}, S.EmptyItems{{}}}}}}}}'
    out = head + ['', '# GENERATED by codegen/var_bytes_boot.py. Do not edit.',
                  '# The spec parts of a SyncCommittee value over any list W of 6144 words (the',
                  '# statement of spec_arr_SyncCommittee.bend SyncCommittee_spec_parts with the two',
                  '# trees replaced by a word list).', '',
                  f'def sc_parts(+W: List<&2, U32>, {gs}, +hl: {{F.spec_common__length(U32, W) == 6144n : Nat}}, +s: S.Schema, +es: {{s == Spec.SyncCommittee() : S.Schema}})',
                  f'    -> {{Codec.parts({VAL}, s) == Some{{[S.Fixed{{SF.limbs(F.spec_common__append(U32, W, {G}))}}]}} : Maybe<&2, +List<S.Part>>}}:',
                  f'  %Equal.sym(+List<U32>, SF.limbs(F.spec_common__append(U32, W, {G})), List.append(&2, U32, SF.limbs(W), SF.limbs({G})), AS.limbs_app(W, {G})) :',
                  f'    {{Codec.parts({VAL}, s) == Some{{[S.Fixed{{_}}]}} : Maybe<&2, +List<S.Part>>}}']
    rest = '\n'.join(body[10:])
    assert LEN2 in rest
    rest = rest.replace(LEN2, 'hl').replace(AB, 'W')
    out.append(rest)
    return '\n'.join(out).rstrip('\n') + '\n'


def outputs():
    return {ROOT / 'proofs/obj/vsc.bend': vsc_text()}


# ---- the SyncCommittee field ---------------------------------------------------------------------

def comp_field(g, ft, inner, size):
    """A Type record [packed words of Vector[ByteVector[48], k], a byte record]: SyncCommittee."""
    (n0, s0), (n1, s1) = inner.fields
    (_, t0), (_, t1) = ft.fields
    if not (s0.kind == 'packed_elems' and t0.kind == 'vector' and t0.elem.kind == 'bytes' and t0.elem.size == 48):
        raise VBY.Skip('record: first field not a vector of Bytes48')
    ws = t0.fixed_size()
    m = re.search(rf'^def {s0.p}_read\(buf: B\.Buf, \+off: U32, \+len: U32\) -> B\.Buf & O\.Words: '
                  rf'O\.copy_into\(buf, off, {ws}, Array\.new\(U32, (\d+)n, 0\)\)$', VBY.src(), re.M)
    if not m:
        raise VBY.Skip('record: words reader shape')
    rft = VBY.FTW(g, t1)
    assert ws + rft.size == size and ws // 48 == 512
    return {'kind': 'comp', 'p': inner.p, 'size': size, 'W': size // 4, 'wp': s0.p, 'wsize': ws, 'wW': ws // 4,
            'wdz': int(m.group(1)), 'rft': rft}


def comp_obj(x, f, i='i'):
    k, wW, dz = f['k'], f['wW'], f['wdz']
    words = [x.slot(k + wW + j) for j in range(f['rft'].W)]
    return (f'T.{f["p"]}{{O.Words{{FD.array__thaw(U32, VB.mone({wW}n, Nat.add({k}n, i), 0n, {dz}n, VC.ZT({dz}n), t)), {f["wsize"]}}}, '
            f'{f["rft"].obj(words)}}}')


