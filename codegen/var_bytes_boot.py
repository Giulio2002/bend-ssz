    w(f'def winH(+d: Nat, +t: FD.array__Tree<U32>, +i: Nat, +len: U32, {VBY.PF}, +hw: {{Nat.is_le(Nat.add(A.quad(i), U32.to_nat(len)), A.quad(VB.pw(d))) == True{{}} : Bool}}, {HA})')
