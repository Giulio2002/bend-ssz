def pad_module():
    L = ['import Base', 'import ../../src/obj.bend as O', 'import ../../src/primitives.bend as I', 'import ../../spec/primitives.bend as SP',
         'import ../compact/found.bend as F', 'import ../compact/arith.bend as A', 'import ./bits_leaf.bend as BLf', 'import ./bitlist_pack.bend as BK',
         'import ./words_spec.bend as WS', 'import ./mtree_run.bend as MR', 'import ./vspec.bend as VS', 'import ./vdepth.bend as VD',
         'import ./var_bits_enc_bw.bend as BW', 'import ./vbitdl.bend as DL', '',
         '# GENERATED by codegen/var_bits_enc.py. Do not edit.',
         '# The object invariant of the bit-list root laws (bitlist_obj wfb1: the bits of the last',
         '# byte past K zero, BK.zt; the bytes of the last chunk past the byte count zero) gives',
         '# DL.HZ at word K / 32: its bits K mod 32 .. 31 are zero.', '',
         'def unth(n: Nat, xs: +List<U32>) -> U32:', '  match n:', '    case 0n:', '      match xs:', '        case Nil{}: 0', '        case Con{h, t}: h',
         '    case 1n+p:', '      match xs:', '        case Nil{}: 0', '        case Con{h, t}: unth(p, t)', '',
         'def bnth(n: Nat, xs: +List<Bool>) -> Bool:', '  match n:', '    case 0n:', '      match xs:', '        case Nil{}: False{}', '        case Con{h, t}: h',
         '    case 1n+p:', '      match xs:', '        case Nil{}: False{}', '        case Con{h, t}: bnth(p, t)', '']
    w = L.append
    for r in range(1, 32):
        j, b = r // 8, r % 8
        c = j + (1 if b else 0)
        a = [f'a{i}' for i in range(r)]
        G = lambda X: f'{{BW.hzw({r}n, {X}) == True{{}} : Bool}}'
        w(f'law hzp{r}:')
        w('  for +x: U32')
        w(f'  for +hz: {{BK.zw({r}n, x) == True{{}} : Bool}}')
        w(f'  for +hp: {{WS.bdrop({c}n, I.limb(x)) == SP.zero_bytes({4 - c}n) : +List<U32>}}')
        w(f'  {G("x")}')
        w(f'def hzp{r}(x, hz, hp):')
        w('  match x:')
        w(f'    case U32{{{word([f"+{v}" for v in a] + ["False{}"] * (32 - r))}}}: {{==}}')
        for q in range(r, 32):
            bits = [f'+{v}' for v in a] + ['False{}'] * (q - r) + ['True{}'] + [f'+c{k}' for k in range(q + 1, 32)]
            X = 'U32{' + word([v.lstrip('+') for v in bits]) + '}'
            if q < 8 * c:
                pr = 'F.logic__false_true(hz)'
            else:
                pr = (f'F.logic__true_false(Equal.cong(+List<U32>, Bool, z => bnth({q % 8}n, BLf.wbits(unth({q // 8 - c}n, z))), '
                      f'WS.bdrop({c}n, I.limb({X})), SP.zero_bytes({4 - c}n), hp))')
            w(f'    case U32{{{word(bits)}}}: Empty.absurd({G(X)}, {pr})')
        w('')
    for R in range(1, 33):
        i, c = (R - 1) // 4, (R - 1) % 4 + 1
        CB = 'WS.cb(S, Nat.add(Q, 0n))'
        w(f'law padw{R}:')
        w('  for +S: List<&2, U32>')
        w('  for +Q: Nat')
        w(f'  for +hp: {{WS.bdrop({R}n, {CB}) == SP.zero_bytes({32 - R}n) : +List<U32>}}')
        w(f'  {{WS.bdrop({c}n, I.limb(MR.wd(S, Nat.add(O.e8(Nat.add(Q, 0n)), {i}n)))) == SP.zero_bytes({4 - c}n) : +List<U32>}}')
        w(f'def padw{R}(S, Q, hp):')
        w(f'  Equal.cong(+List<U32>, +List<U32>, z => WS.btake({4 - c}n, z), WS.bdrop({R}n, {CB}), SP.zero_bytes({32 - R}n), hp)')
        w('')
    w('law cwb:')
    w('  for +b: Nat')
    w('  for +hb: {Nat.is_lt(b, 8n) == True{} : Bool}')
    w('  {VD.s_rng(3n, Nat.add(b, 7n)) == BW.CWr(b) : Nat}')
    w('def cwb(b, hb):')
    w('  match b:')
    for B in range(8):
        w(f'    case {B}n: {{==}}')
    w('    case 8n+ +e: Empty.absurd({VD.s_rng(3n, Nat.add(8n+e, 7n)) == BW.CWr(8n+e) : Nat}, F.nat__lt_zero_absurd(e, hb))')
    w('')
    CI = '{Nat.is_le(Nat.add(A.quad(i), Nat.add(j, BW.CWr(b))), 32n) == True{} : Bool}'
    w('# The offset 4 i + j + [b > 0] of a byte count in its chunk is at most 32.')
    w('law cib:')
    for v in ['j', 'b', 'i']:
        w(f'  for +{v}: Nat')
    w('  for +hj: {Nat.is_lt(j, 4n) == True{} : Bool}')
    w('  for +hb: {Nat.is_lt(b, 8n) == True{} : Bool}')
    w('  for +hi: {Nat.is_lt(i, 8n) == True{} : Bool}')
    w(f'  {CI}')
    w('def cib(j, b, i, hj, hb, hi):')
    w('  match j b i:')
    for J in range(4):
        for B in range(8):
            for I in range(8):
                w(f'    case {J}n {B}n {I}n: {{==}}')
            w(f'    case {J}n {B}n 8n+ +e: Empty.absurd({{Nat.is_le(Nat.add(A.quad(8n+e), Nat.add({J}n, BW.CWr({B}n))), 32n) == True{{}} : Bool}}, F.nat__lt_zero_absurd(e, hi))')
        w(f'    case {J}n 8n+ +e _: Empty.absurd({{Nat.is_le(Nat.add(A.quad(i), Nat.add({J}n, BW.CWr(8n+e))), 32n) == True{{}} : Bool}}, F.nat__lt_zero_absurd(e, hb))')
    w('    case 4n+ +e _ _: Empty.absurd({Nat.is_le(Nat.add(A.quad(i), Nat.add(4n+e, BW.CWr(b))), 32n) == True{} : Bool}, F.nat__lt_zero_absurd(e, hj))')
    w('')
    w('# A nonzero bit offset 8 j + b has a nonzero byte count j + [b > 0] in its word.')
    w('law cpos:')
    w('  for +j: Nat')
    w('  for +b: Nat')
    w('  for +hj: {Nat.is_lt(j, 4n) == True{} : Bool}')
    w('  for +hb: {Nat.is_lt(b, 8n) == True{} : Bool}')
    w('  for +h: {Nat.is_lt(0n, Nat.add(VS.x8(j), b)) == True{} : Bool}')
    w('  {Nat.is_lt(0n, Nat.add(j, BW.CWr(b))) == True{} : Bool}')
    w('def cpos(j, b, hj, hb, h):')
    w('  match j b:')
    for J in range(4):
        for B in range(8):
            if J == 0 and B == 0:
                w('    case 0n 0n: Empty.absurd({Nat.is_lt(0n, Nat.add(0n, BW.CWr(0n))) == True{} : Bool}, F.logic__false_true(h))')
            else:
                w(f'    case {J}n {B}n: {{==}}')
        w(f'    case {J}n 8n+ +e: Empty.absurd({{Nat.is_lt(0n, Nat.add({J}n, BW.CWr(8n+e))) == True{{}} : Bool}}, F.nat__lt_zero_absurd(e, hb))')
    w('    case 4n+ +e _: Empty.absurd({Nat.is_lt(0n, Nat.add(4n+e, BW.CWr(b))) == True{} : Bool}, F.nat__lt_zero_absurd(e, hj))')
    w('')
    W_ = 'MR.wd(S, Nat.add(O.e8(Nat.add(Q, 0n)), i))'
    RR = 'Nat.add(A.quad(i), Nat.add(j, BW.CWr(b)))'
    HZ = f'{{BK.zw(Nat.add(VS.x8(j), b), {W_}) == True{{}} : Bool}}'
    HP = f'{{WS.bdrop({RR}, WS.cb(S, Nat.add(Q, 0n))) == SP.zero_bytes(Nat.sub(32n, {RR})) : +List<U32>}}'
    GL = f'{{DL.HZ(Nat.add(VS.x8(j), b), {W_}) == True{{}} : Bool}}'
    w('# At byte j, bit b of word 8 Q + i of the storage (the last chunk Q).')
    w('law hzd:')
    for v in ['j', 'b', 'i']:
        w(f'  for +{v}: Nat')
    w('  for +S: List<&2, U32>')
    w('  for +Q: Nat')
    w('  for +hj: {Nat.is_lt(j, 4n) == True{} : Bool}')
    w('  for +hb: {Nat.is_lt(b, 8n) == True{} : Bool}')
    w('  for +hi: {Nat.is_lt(i, 8n) == True{} : Bool}')
    w(f'  for +hz: {HZ}')
    w(f'  for +hp: {HP}')
    w(f'  {GL}')
    w('def hzd(j, b, i, S, Q, hj, hb, hi, hz, hp):')
    w('  match j b i:')

    def sub(t, J, B, I):
        return t.replace('VS.x8(j)', f'VS.x8({J})').replace('Nat.add(j, ', f'Nat.add({J}, ').replace('CWr(b)', f'CWr({B})').replace('VS.x8(' + J + '), b)', f'VS.x8({J}), {B})').replace('A.quad(i)', f'A.quad({I})').replace('0n)), i))', f'0n)), {I}))')
    for J in range(4):
        for B in range(8):
            for I in range(8):
                r = 8 * J + B
                w(f'    case {J}n {B}n {I}n:')
                if r == 0:
                    w('      {==}')
                else:
                    c = J + (1 if B else 0)
                    R = 4 * I + c
                    w(f'      hzp{r}(MR.wd(S, Nat.add(O.e8(Nat.add(Q, 0n)), {I}n)), hz, padw{R}(S, Q, hp))')
            w(f'    case {J}n {B}n 8n+ +e: Empty.absurd({sub(GL, f"{J}n", f"{B}n", "8n+e")}, F.nat__lt_zero_absurd(e, hi))')
        w(f'    case {J}n 8n+ +e _: Empty.absurd({sub(GL, f"{J}n", "8n+e", "i")}, F.nat__lt_zero_absurd(e, hb))')
    w(f'    case 4n+ +e _ _: Empty.absurd({sub(GL, "4n+e", "b", "i")}, F.nat__lt_zero_absurd(e, hj))')
    return '\n'.join(L) + '\n'


def lg(x):
    """The least k with x <= 2^k."""
    k = 0
    while (1 << k) < x:
        k += 1
    return k


