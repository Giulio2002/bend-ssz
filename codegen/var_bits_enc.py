"""Encoder laws of the bit lists (O.put_bits: the words, then the delimiter
bit at position k) against spec/bitfields.bend list_encoding.

    python3 codegen/var_bits_enc.py [--check] [--no-big]

proofs/obj/var_bits_enc_bw.bend (generated, stock): for each bit position
r < 32, OR-ing bit r into a word whose bits r..31 are zero (hzw r)
appends True to its first r bits and leaves its bits past r + 1 zero; the
dispatcher dlc over byte j, bit b; dmk_dl, the runtime mask as DL(j, b); cfj,
the closed facts of each (j, b).

proofs/obj/var_bits_enc_<X>.bend (generated, stock), for each generic BitList[N]
name X (codegen/var_bits.py gbits_names): encode_eval, X_encode(O.Bits{thaw T, K})
== (O.Bits{thaw T, K}, B.Buf{thaw(OUT(T, K)), K / 8 + 1}) with OUT the explicit
tree DL.OZ (the object's words copied into a zero tree, the delimiter OR-ed in),
and encode_spec, Decoding.decodes(GS.X(), BY(T, K), BitsValue{btk(K, bitsof(slots T))})
for BY the first K / 8 + 1 bytes of OUT. Hypotheses: T perfect of depth dw < 31,
K <= N, the bits K mod 32.. of word K / 32 zero (DL.HZ), and for N >= 32 (the
sized shape, O.out_new after O.bits_sizek) the capacity check K / 32 + 1 <= 2^dw.
The hand-written libraries: proofs/obj/vbitenc.bend (put_bits over main's
VBE.put_words_any, pack_delim, the numbers of K), vbitdl.bend (words_pack),
vbitcore.bend (enc_core, enc_small, enc_sized).
"""
