def u32le(a, b, h):
    """{Nat.is_le(to_nat a, to_nat b) == True} from h: {U32.is_le(a, b) == True}"""
    return (f'FD.logic__subst(Bool, z => {{z == True{{}} : Bool}}, U32.is_le({a}, {b}), Nat.is_le(U32.to_nat({a}), U32.to_nat({b})), '
            f'VB.le_u32n({a}, {b}), {h})')


