def _cu_orwrap(x, k, n_arms):
    """the Or2 selection of arm k of n_arms: Inr^k Inl{x} (the last arm Inr^(n-1) x)"""
    r = f'Inl{{{x}}}' if k < n_arms - 1 else x
    for _ in range(k):
        r = f'Inr{{{r}}}'
    return r


