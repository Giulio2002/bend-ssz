class DSynth(W.Synth):
    def part(self, mod, pred, env):
        # a decoded object's premises are open (they use the provider's lets): a part of a split chain is proved inline, not as a closed lemma
        return self.prove(mod, pred, dict(env, __split=False))

    def witness(self, mod, ty, v, body, env):
        subj = env.get('__subj')
        if isinstance(subj, WordsFix):
            if ty.strip().endswith('array__Tree<U32>'):
                return subj.M
            if v == 'dw':
                return f'{subj.d}n'
            if v == 'N':
                return f'{subj.n}'
            if v == 'q':
                if re.search(r'U32\.to_nat\(N\) == Nat\.add\(WS\.e32\(q\), 32n\)', body):
                    return f'{subj.n // 32 - 1}n'
                return f'{(subj.n - 1) // 32}n'
            if v == 'r':
                return f'{subj.n - 32 * ((subj.n - 1) // 32)}n'
        return super().witness(mod, ty, v, body, env)

    def prove(self, mod, pred, env):
        p = pred.strip()
        c = W.parse_call(p)
        if c is not None:
            fn, args = c
            m2, name = mod.resolve(fn)
            if m2 is not None:
                key = (m2.path.name, name)
                mdl0 = self.arg_model(args[0], env) if args else None
                if isinstance(mdl0, FxWords) and key in mdl0.proofs:
                    return mdl0.proofs[key](self.subst(mod, args[1], env) if len(args) > 1 else None)
                if (name.startswith('sda_') or name.startswith('rep_') or name in SDT1) and (len(args) == 2 or (name in SDT1 and len(args) == 1)):
                    mdl = self.arg_model(args[0], env)
                    if isinstance(mdl, RLDec):
                        if name in SDT1:
                            return mdl.sda('31n')
                        a1 = self.subst(mod, args[1], env)
                        return mdl.sda(a1) if name.startswith('sda_') else mdl.rep(a1)
                if key in BITS and args:
                    mdl = self.arg_model(args[0], env)
                    if isinstance(mdl, BitsDec):
                        v_ = getattr(mdl, BITS[key])
                        if callable(v_):
                            return v_(self.subst(mod, args[1], env) if len(args) > 1 else None)
                        return v_
                if key in STORAGE and args:
                    mdl = self.arg_model(args[0], env)
                    if isinstance(mdl, WordsDec):
                        kind = STORAGE[key]
                        k = kind[-2:] + 'n' if kind[-1].isdigit() else self.subst(mod, args[1], env)
                        f = mdl.any_ if kind.startswith('any') else mdl.one
                        if f is None:
                            raise SystemExit(f'e2e_decrep: no {kind} storage fact')
                        return f(k)
        return super().prove(mod, pred, env)

    def eq(self, p, env):
        subj = env.get('__subj')
        for hk in TOT_HOOK.values():
            r_ = hk(p)
            if r_ is not None:
                return r_
        mbv = re.match(r'\{last_bv(1|2|8|257)\(o\) == ', p.strip())
        if mbv and BV_CFG and env.get('__e', {}).get('o'):   # a decoded Bitvector<K> field: its bits past K are zero (e2e_dfx.rp<K>)
            K_ = int(mbv.group(1))
            e = env['__e']['o'].strip()
            mo = re.fullmatch(r'(\w+)\.OBJ\(\w+, (\w+), (.*)\)', e, re.S)
            pth = self.ctx.used.get(mo.group(1)) if mo else None
            if pth is not None and pth.name == f'vfx_bv{K_}.bend':
                DFXA = self.ctx.alias(ROOT / 'e2e/e2e_dfx.bend')
                Y = mo.group(3)
                if K_ == 257:
                    return BV_CFG['p257'](Y)
                if K_ == 8:
                    return f'{DFXA}.rp8(d, {mo.group(2)}, {Y})'
                return f'{DFXA}.rp{K_}(d, {mo.group(2)}, {Y}, pf, {BV_CFG["room"](Y)}, {BV_CFG["hc"][K_]})'
        ms = re.fullmatch(r'\{U32\.is_lt\(o, (256|65536)\) == True\{\} : Bool\}', p.strip())
        if ms and env.get('__e', {}).get('o'):
            e = env['__e']['o'].strip()
            mo = re.fullmatch(r'(\w+)\.OBJ\(\w+, (\w+), (.*)\)', e, re.S)
            pth = self.ctx.used.get(mo.group(1)) if mo else None
            if pth is not None and pth.name in ('vfx_u16.bend', 'vfx_u8.bend'):   # a fixed field's reader: its body
                t_, x_ = mo.group(2), mo.group(3)
                if pth.name == 'vfx_u16.bend':
                    e = f"{self.ctx.alias(ROOT / 'src/obj.bend')}.keep(2, {self.ctx.alias(ROOT / 'proofs/obj/vua_rd.bend')}.RWN({t_}, {x_}))"
                else:
                    e = f"{self.ctx.alias(ROOT / 'proofs/obj/vbitl.bend')}.nthb({self.ctx.alias(ROOT / 'proofs/obj/vua.bend')}.BYT({t_}), {x_})"
            mk = re.fullmatch(r'(\w+)\.keep\((1|2), (.*)\)', e, re.S)
            if mk and (mk.group(2) == '1') == (ms.group(1) == '256'):
                MKA = self.ctx.alias(ROOT / 'e2e/e2e_mask.bend')
                nb = 8 * int(mk.group(2))
                return (f'FD.logic__subst(U32, z => {{U32.is_lt(z, {ms.group(1)}) == True{{}} : Bool}}, {MKA}.cf{nb}({mk.group(3)}), {e}, '
                        f'Equal.sym(U32, {e}, {MKA}.cf{nb}({mk.group(3)}), {MKA}.mk{nb}({mk.group(3)})), {{==}})')
            mb = re.fullmatch(r'(\w+)\.nthb\((\w+)\.BYT\((\w+)\), (.*)\)', e, re.S)
            if mb and ms.group(1) == '256':
                DPA, FXA, VRA = (self.ctx.alias(ROOT / 'e2e/e2e_dpl.bend'), self.ctx.alias(ROOT / 'proofs/obj/spec_fixed.bend'),
                                 self.ctx.alias(ROOT / 'proofs/obj/vbrt.bend'))
                return f'{DPA}.nthb_lt({mb.group(2)}.BYT({mb.group(3)}), {mb.group(4)}, {FXA}.domain_limbs({VRA}.SL({mb.group(3)})))'
        if isinstance(subj, WordsFix):
            if 'array__perfect(U32' in p:
                return subj.pf
            return W.R
        if isinstance(subj, WordsDec):
            if re.search(r'Nat\.is_le\(U32\.to_nat\(\w+\.len\(o\)\), ', p) and subj.limit:
                return subj.limit
            for pat, pr in subj.facts:
                if re.search(pat, p):
                    return pr
            return W.R
        return super().eq(p, env)


def body_of(modpath, name, subst):
    """a def's body with its parameters replaced (module aliases as written there)"""
    m = W.Mod.get(ROOT / modpath)
    params, ret, body = m.signature(name)
    for pn, v in subst.items():
        body = re.sub(r'(?<![\w.])' + re.escape(pn) + r'(?![\w])', v, body)
    return m, body


def dec_model(e, words, expand=lambda e: None, bits=None, leaf=lambda e: None):
    """the model of a decoded object's term (this file's aliases); expand(e) unfolds a call to the codec's object
    helpers (OBJw, MKw); a fixed-length word field over a VB.mone copy is WordsFix, the others words(i, expr)"""
    cnt = [0]

    def go(e, top):
        e = e.strip()
        lf_ = leaf(e)
        if lf_ is not None:
            return lf_
        x = expand(e)
        if x is not None:
            return go(x, top)
        m = re.match(r'(\w+)\.Words\{(.*)\}$', e, re.S)
        if m:
            tr, ln = W.split_top(m.group(2))
            mm = re.match(r'(\w+)\.array__thaw\(U32, (\w+)\.mone\((\d+)n, (.*), 0n, (\d+)n, (\w+)\.ZT\(\5n\), (\w+)\)\)$', tr.strip(), re.S)
            if mm and re.fullmatch(r'\d+', ln.strip()):
                M = tr.strip()[tr.index(',') + 1:-1].strip()
                pf = f'{mm.group(2)}.mone_perfect({mm.group(3)}n, {mm.group(4)}, 0n, {mm.group(5)}n, {mm.group(6)}.ZT({mm.group(5)}n), {mm.group(7)}, FD.array__trep_perfect(U32, {mm.group(5)}n, 0))'
                md = WordsFix(e, int(ln), M, int(mm.group(5)), pf)
                return md
            md = words(cnt[0], e)
            cnt[0] += 1
            return md
        if bits is not None and re.match(r'(\w+)\.Bits\{(.*)\}$', e, re.S):
            return bits(e)
        m = re.match(r'(\w+)\.BSome\{(.*)\}$', e, re.S)
        if m:
            x, rest = W.split_top(m.group(2))
            md = W.Box(go(x, False), x)
            md.expr = e
            return md
        m = re.match(r'([\w.]+)\{(.*)\}$', e, re.S)
        if m and '.' in m.group(1):
            tn = m.group(1).split('.')[-1]
            fields = []
            for a in W.split_top(m.group(2)):
                sub = go(a, False)
                if isinstance(sub, W.Cont) and sub.tname.startswith(tn + '_g'):
                    fields.extend(sub.fields)
                else:
                    fields.append((a.strip(), sub))
            md = W.Cont(None, tn, fields)
            md.expr = e
            return md
        md = W.Leaf(e)
        md.expr = e
        return md
    return go(e, True)


def container_file(name, lf, obj_mod, obj_def, obj_subst, params, lets, words, dc_path, given=None, objexpr=None, post_rep=None):
    """the decrep file of a container name: each (i)/(iv) premise of DC.OBJ(...), synthesized (DSynth) over the decoded
    object's term obj_def(obj_subst) with word fields from words(i, expr); params / lets: the p_* defs' parameters and
    shared facts"""
    import e2e_compose as C
    if callable(lf):
        lf = C.law_files()
    el, rl = lf[f'{name}_e2e_encode'], lf[f'{name}_e2e_root']
    em, rm = W.Mod.get(el), W.Mod.get(rl)
    eps, _ = C.sig(em, f'{name}_e2e_encode')
    rps, _ = C.sig(rm, f'{name}_e2e_root')
    W.PREFER.clear()
    W.PREFER[(ROOT / dc_path).resolve()] = 'DC'
    W.PREFER[(ROOT / 'e2e/e2e_dz.bend').resolve()] = 'DZ'
    W.PREFER[(ROOT / 'proofs/compact/found.bend').resolve()] = 'FD'
    W.PREFER[(ROOT / 'src/obj.bend').resolve()] = 'O'
    for p_, a_ in (('proofs/compact/arith.bend', 'A'), ('proofs/nat_order.bend', 'Order'), ('proofs/obj/vbuf.bend', 'VB'), ('proofs/obj/vcopy.bend', 'VC'),
                   ('proofs/obj/vdepth.bend', 'VD'), ('proofs/obj/vlist.bend', 'VLS'), ('proofs/obj/vspec.bend', 'VSP'), ('e2e/e2e_ulist.bend', 'UW'),
                   ('proofs/obj/vbytes.bend', 'VY'), ('e2e/e2e_blist.bend', 'BL'), ('proofs/obj/dk.bend', 'DK')):
        W.PREFER[(ROOT / p_).resolve()] = a_
    om, body = body_of(obj_mod, obj_def, obj_subst)
    taken = set(W.PREFER.values())
    for m_ in (em, rm, om):
        for a, pth in m_.imports.items():
            if pth not in W.PREFER and a not in taken:
                W.PREFER[pth] = a
                taken.add(a)
    W.PREFER.setdefault(om.path, 'WN')
    ctx = W.Ctx()
    for p_ in (dc_path, 'e2e/e2e_dz.bend', 'proofs/compact/found.bend', 'src/obj.bend', 'proofs/compact/arith.bend', 'proofs/nat_order.bend',
               'proofs/obj/vbuf.bend', 'proofs/obj/vcopy.bend', 'proofs/obj/vdepth.bend', 'proofs/obj/vlist.bend', 'proofs/obj/vspec.bend',
               'e2e/e2e_ulist.bend', 'proofs/obj/vbytes.bend', 'e2e/e2e_blist.bend'):
        ctx.alias(ROOT / p_)
    OBJ = ctx.lift(om, body)
    inv = {a: pth for pth, a in W.PREFER.items()}
    bits = None
    if callable(lets):
        r_ = lets(lambda path: ctx.alias(ROOT / path))
        lets, words = r_[0], r_[1]
        bits = r_[2] if len(r_) > 2 else None
        rlchk = r_[3] if len(r_) > 3 else None
        xleaf = r_[4] if len(r_) > 4 else None
    else:
        rlchk = None
        xleaf = None
    rl_n = [0]

    def leaf(e):
        """a record list a window reader builds (var_winx_<L>.OBJw, with an e2e_drl_<L> file): RLDec; other leaves
        the provider knows (its xleaf hook: module file name, call arguments -> model)"""
        c = W.parse_call(e)
        if c is None or '.' not in c[0]:
            return None
        al = c[0].split('.', 1)[0]
        pth = inv.get(al) or ctx.used.get(al)
        if xleaf is not None and pth is not None:
            md = xleaf(pth.name, c[0].split('.', 1)[1], c[1], e)
            if md is not None:
                return md
        if rlchk is None or not c[0].endswith('.OBJw'):
            return None
        mm = re.fullmatch(r'var_winx_(l\w+)\.bend', pth.name) if pth is not None else None
        if mm is None or not (ROOT / 'e2e' / f'e2e_drl_{mm.group(1)}.bend').exists():
            return None
        DRL = ctx.alias(ROOT / 'e2e' / f'e2e_drl_{mm.group(1)}.bend')
        hx = rlchk(rl_n[0])
        rl_n[0] += 1
        a = ', '.join(c[1])
        return RLDec(e, lambda k: f'{DRL}.sdl({a}, {k}, {{==}}, {hx})', lambda sc: f'{DRL}.rep({a}, {sc}, {{==}}, {hx})')

    def expand(e):
        c = W.parse_call(e)
        if c is None or '.' not in c[0] or not re.search(r'\.(OBJw|MKw|OBJ)$', c[0]):
            return None
        if c[0].endswith('.OBJ'):
            pth0 = inv.get(c[0].split('.', 1)[0]) or ctx.used.get(c[0].split('.', 1)[0])
            if pth0 is None or not pth0.name.startswith('vfx_'):
                return None
        al, fn = c[0].split('.', 1)
        pth = inv.get(al) or ctx.used.get(al)
        if pth is None:
            return None
        m2 = W.Mod.get(pth)
        ps, ret, bd = m2.signature(fn)
        # substitute the (already lifted) arguments after lifting the body
        bd = ctx.lift(m2, bd)
        for pn, v in zip(ps, c[1]):
            bd = re.sub(r'(?<![\w.])' + re.escape(pn) + r'(?![\w])', v, bd)
        return bd
    model = dec_model(OBJ, words, expand, bits, leaf)
    syn = DSynth(ctx)
    defs = []
    done = {}
    for tag, mod, ps in (('e', em, eps), ('r', rm, rps)):
        for m_, b, t in ps:
            if b in ('o', 'h') or b in done:
                continue
            if given and b in given:
                term = given[b](lambda path: ctx.alias(ROOT / path))
            else:
                term = syn.prove(mod, t, {'o': model, '__subj': None, '__e': {'o': objexpr or 'DC.OBJ(' + ', '.join(params[0]) + ')'}})
            ty = re.sub(r'(?<![\w.])o(?![\w{(])', objexpr or 'DC.OBJ(' + ', '.join(params[0]) + ')', ctx.lift(mod, t))
            done[b] = 1
            if post_rep is not None and b == 'rep':
                term, extra = post_rep(term, ctx, objexpr or 'DC.OBJ(' + ', '.join(params[0]) + ')')
                defs.append(extra)
            defs.append(f'def p_{b}({params[1]})\n    -> {ty}:\n' + ''.join(f'  {l}\n' for l in lets) + f'  {term}\n')
    imports = ['import Base']
    for a, pth in sorted(ctx.used.items(), key=lambda x: x[1].relative_to(ROOT).as_posix()):
        rel = ('./' + pth.name) if pth.parent == ROOT / 'e2e' else (Path('..') / pth.relative_to(ROOT)).as_posix()
        imports.append(f'import {rel} as {a}')
    for nm in sorted(syn.lemmas):
        defs.insert(0, syn.lemmas[nm])
    return '\n'.join(imports) + '\n\n' + HEADER + '\n' + f'# {name}: the (i)/(iv) premises of the decoded object DC.OBJ, for every input the codec accepts.\n\n' + '\n'.join(defs)


