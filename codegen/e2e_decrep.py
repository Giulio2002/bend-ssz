def nested(name, wins, top_hS, dc_path):
    """a container holding one ExecutionPayloadHeader through a chain of windows (outer to the header's):
    wins = [(window module, fixed size K, offset of the next window in words)], the last the header's (K = 584)"""
    def lets(al):
        A = [al(w) for w, _, _ in wins]
        out = []
        prev, i, L = 'hchk', '0n', 'n'
        for lvl, (w, K, off) in enumerate(wins):
            a, b = f'U32.is_le({K}, {L})', f'U32.is_eq({A[lvl]}.SPOw(t, {i}), {K})'
            if lvl + 1 < len(wins):
                i2, L2 = f'Nat.add({off}n, {i})', f'{A[lvl]}.LL({L})'
                c = f'{A[lvl + 1]}.CHKw(t, {i2}, {L2})'
                out.append(f'+hc{lvl} = {A[lvl]}.chk_c({a}, {b}, {c}, {prev})')
                prev, i, L = f'hc{lvl}', i2, L2
            else:
                c = f'{A[lvl]}.BLW(U32.sub({L}, {A[lvl]}.SPOw(t, {i})))'
                out.append(f'+hc{lvl} = {A[lvl]}.chk_c({a}, {b}, {c}, {prev})')
                out.append(f'+hb{lvl} = {A[lvl]}.chk_b({a}, {b}, {c}, {prev})')
                out.append(f'+hcz = FD.logic__subst(U32, z => {{{A[lvl]}.BLW(U32.sub({L}, z)) == True{{}} : Bool}}, {A[lvl]}.SPOw(t, {i}), {K}, FD.u32alg__eq_of({A[lvl]}.SPOw(t, {i}), {K}, hb{lvl}), hc{lvl})')
                L3 = f'{A[lvl]}.LL({L})'
                out.append(f'+hl = FD.logic__subst(Bool, z => {{z == True{{}} : Bool}}, U32.is_le({L3}, 32), Nat.is_le(U32.to_nat({L3}), U32.to_nat(32)), VB.le_u32n({L3}, 32), hcz)')
                out.append(f'+hy = FD.nat__le_trans(VC.YL({L3}), Nat.add(31n, U32.to_nat(32)), U32.to_nat(VB.UMAX()), Order.add_left(31n, U32.to_nat({L3}), U32.to_nat(32), hl), {{==}})')

                def words(j, e, L3=L3, i=i):
                    return WordsDec(e, any_=lambda k: f'DZ.dec_bytes({L3}, Nat.add(146n, {i}), t, {k}, {{==}}, hy)', limit='hl')
        return out, words
    ps = f'+t: FD.array__Tree<U32>, +n: U32, +hS: {top_hS}, +hchk: {{DC.CHK(t, n) == True{{}} : Bool}}'
    return container_file(name, lambda: None, wins[0][0], 'OBJw', {'t': 't', 'i': '0n', 'len': 'n'}, (['t', 'n'], ps), lets, None, dc_path)


