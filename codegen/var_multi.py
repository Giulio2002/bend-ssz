def outputs():
    names = schema.load(ROOT / 'codegen/fulu.yaml')
    g = G.Gen()
    for n, t in names.items():
        g.shape(t)
    out = {ROOT / 'proofs/obj/vmul.bend': (ROOT / 'codegen/vmul.bend.in').read_text(),
           ROOT / 'proofs/obj/var_fix_types_m.bend': fix_types(g, names),
           ROOT / 'proofs/obj/vzeros.bend': zeros_text(),
           ROOT / f'proofs/obj/var_codec_{X}.bend': dec_text()}
    return out


def main():
    out = outputs()
    if '--check' in sys.argv:
        stale = [str(p.relative_to(ROOT)) for p, t in out.items() if not p.exists() or p.read_text() != t]
        if stale:
            print('stale: ' + ', '.join(stale))
            sys.exit(1)
        print('multi-variable laws are current')
        return
    for p, t in out.items():
        p.write_text(t)
    print(f'{len(out)} files')


if __name__ == '__main__':
    main()
