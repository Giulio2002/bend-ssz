def fix_types(g, names):
    fts = []
    for f, ft in names[X].fields:
        if ft.fixed() and ft.kind == 'container':
            for d in VLW.FT(g, ft).deps():
                if d.p not in [x.p for x in fts]:
                    fts.append(d)
    u = VLW.FT(g, names[X].fields[0][1])
    if u.p not in [x.p for x in fts]:
        fts.insert(0, u)
    return VLW.fix_module(fts).replace('codegen/var_laws.py', 'codegen/var_multi.py (codegen/var_laws.py fix_module)')


ZK = 24


def zeros_text():
    L = ['import Base', 'import ../../src/buffer.bend as B', 'import ../compact/found.bend as FD', '',
         '# GENERATED by codegen/var_multi.py. Do not edit.',
         f'# The runtime zero array of depth k <= {ZK} is Array.new(U32, k, 0), case by case (the',
         f'# comparison of the closed trees of 2^{ZK} leaves takes about a minute on stock Bend).', '',
         f'def zat(+du: U32, +k: Nat, +e: {{U32.to_nat(du) == k : Nat}}, +hk: {{Nat.is_le(k, {ZK}n) == True{{}} : Bool}})',
         '    -> {B.zeros(du) == Array.new(U32, k, 0) : Array<U32>}:', '  match k:']
    for j in range(ZK + 1):
        L.append(f'    case {j}n:')
        L.append(f'      %Equal.sym(U32, du, {j}, FD.u32__injective(du, {j}, e)) : {{B.zeros(_) == Array.new(U32, {j}n, 0) : Array<U32>}}')
        L.append('      {==}')
    L.append(f'    case {ZK + 1}n+p: Empty.absurd({{B.zeros(du) == Array.new(U32, {ZK + 1}n+p, 0) : Array<U32>}}, FD.logic__false_true(hk))')
    return '\n'.join(L) + '\n'


