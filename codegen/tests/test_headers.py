"""Every `# GENERATED` header the generators write is the layout-independent form (core/writer.py: header)."""
import re
import unittest

from codegen.core import writer
from codegen.core.paths import CODEGEN

# literals that are not a header of a file: docstrings and the writer's own pattern
SKIP_FILES = ('writer.py', 'test_headers.py', 'test_writer.py')
PLACEHOLDER = re.compile(r'GENERATED by (@GEN@|\{GEN\}|\{gen\}|\[\^\\n\]|\(\\S\+\)|\(codegen/|\(\?:)')


def header_lines():
    for p in sorted(CODEGEN.rglob('*.py')):
        if p.name in SKIP_FILES:
            continue
        for i, line in enumerate(p.read_text(errors='replace').splitlines(), 1):
            if 'GENERATED by' in line and '# GENERATED' in line:
                yield p, i, line


class HeaderLiteralTest(unittest.TestCase):
    def test_no_path_in_header_literals(self):
        bad = [f'{p.relative_to(CODEGEN)}:{i}' for p, i, l in header_lines() if re.search(r'GENERATED (?:by|from) [^\'"]*codegen/', l)]
        self.assertEqual(bad, [], 'a header must not name a path: the file moves, the header must not')

    def test_header_literals_have_the_standard_form(self):
        bad = []
        for p, i, l in header_lines():
            m = re.search(r'# GENERATED by ([^ ]+)', l)
            if m is None or PLACEHOLDER.search(l):
                continue
            if not re.match(r"[\w{}]+$", m.group(1)) or '(codegen' not in l[m.end():m.end() + 14]:
                bad.append(f'{p.relative_to(CODEGEN)}:{i}: {l.strip()[:100]}')
        self.assertEqual(bad, [])

    def test_templates_have_no_path_in_their_headers(self):
        bad = [f'{p.name}:{i}' for p in sorted((CODEGEN / 'templates').glob('*.in'))
               for i, l in enumerate(p.read_text().splitlines(), 1) if l.startswith('# GENERATED') and 'codegen/' in l]
        self.assertEqual(bad, [])

    def test_generated_names_are_registered_or_libraries(self):
        names = {p.stem for p in CODEGEN.rglob('*.py')}
        bad = set()
        for p, i, l in header_lines():
            m = re.search(r'# GENERATED by (\w+) \(codegen', l)
            if m and m.group(1) not in names:
                bad.add((p.name, m.group(1)))
        self.assertEqual(sorted(bad), [], 'a header names a generator that does not exist')

    def test_writer_regexp_accepts_the_standard_header(self):
        self.assertRegex(writer.header('x'), writer.HEADER_RE)


if __name__ == '__main__':
    unittest.main()
