"""codegen/core/writer.py: the GENERATED header, ownership, and the --check / write protocol."""
import contextlib
import io
import unittest
from pathlib import Path

from codegen.core import writer
from codegen.core.paths import ROOT

TMP = ROOT / 'build' / 'test_writer'


class HeaderTest(unittest.TestCase):
    def test_header_is_layout_independent(self):
        h = writer.header('e2e_witness')
        self.assertEqual(h, '# GENERATED by e2e_witness (codegen). Do not edit.')
        self.assertNotIn('/', h)

    def test_header_detail(self):
        self.assertEqual(writer.header('e2e_bridge', 'e2e_var_b'), '# GENERATED by e2e_bridge (codegen: e2e_var_b). Do not edit.')

    def test_header_matches_pattern(self):
        for h in (writer.header('a'), writer.header('a', 'b c')):
            self.assertRegex(h, writer.HEADER_RE)

    def test_owner_reads_new_and_old_forms(self):
        self.assertEqual(writer.owner(writer.header('var_laws') + '\nbody'), 'var_laws')
        self.assertEqual(writer.owner('import x\n\n# GENERATED by codegen/var_bits.py. Do not edit.\n'), 'var_bits')
        self.assertEqual(writer.owner('# GENERATED by codegen/proofs/var/var_bits.py (codegen/x.py). Do not edit.'), 'var_bits')
        self.assertIsNone(writer.owner('def f(): pass'))

    def test_is_foreign(self):
        TMP.mkdir(parents=True, exist_ok=True)
        f = TMP / 'a.bend'
        f.write_text(writer.header('gen_a') + '\n')
        self.assertFalse(writer.is_foreign(f, 'gen_a'))
        self.assertTrue(writer.is_foreign(f, 'gen_b'))
        f.write_text('no header\n')
        self.assertFalse(writer.is_foreign(f, 'gen_b'))

    def test_rebrand(self):
        t = writer.header('var_laws') + '\n# see codegen/proofs/var/var_laws.py\n'
        r = writer.rebrand(t, 'var_laws', 'var_bytes')
        self.assertIn('by var_bytes (codegen)', r)
        self.assertIn('codegen/proofs/var/var_bytes.py', r)
        self.assertNotIn('var_laws', r)
        self.assertIn('(codegen: var_laws fix_module)', writer.rebrand(t, 'var_laws', 'var_multi', 'var_laws fix_module'))


class SyncTest(unittest.TestCase):
    def setUp(self):
        TMP.mkdir(parents=True, exist_ok=True)
        self.a, self.b = TMP / 'x.bend', TMP / 'y.bend'
        for p in (self.a, self.b):
            p.unlink(missing_ok=True)

    def run_check(self, out, orphans=()):
        buf = io.StringIO()
        with contextlib.redirect_stdout(buf):
            try:
                writer.check(out, 'stale: ', 'current', orphans=orphans)
                code = 0
            except SystemExit as e:
                code = e.code
        return code, buf.getvalue()

    def test_missing_file_is_stale(self):
        code, out = self.run_check({self.a: 'x\n'})
        self.assertEqual(code, 1)
        self.assertIn('stale: build/test_writer/x.bend', out)

    def test_written_file_is_current(self):
        writer.write({self.a: 'x\n', self.b: 'y\n'})
        self.assertEqual(self.run_check({self.a: 'x\n', self.b: 'y\n'}), (0, 'current\n'))
        code, out = self.run_check({self.a: 'x\n', self.b: 'changed\n'})
        self.assertEqual(code, 1)
        self.assertIn('y.bend', out)
        self.assertNotIn('x.bend', out)

    def test_orphans_fail_check_and_are_removed_by_write(self):
        writer.write({self.a: 'x\n', self.b: 'y\n'})
        orphan = str(self.b.relative_to(ROOT))
        code, out = self.run_check({self.a: 'x\n'}, orphans=[orphan])
        self.assertEqual(code, 1)
        self.assertIn(orphan, out)
        writer.write({self.a: 'x\n'}, orphans=[orphan])
        self.assertFalse(self.b.exists())
        self.assertEqual(self.run_check({self.a: 'x\n'}), (0, 'current\n'))

    def tearDown(self):
        for p in (self.a, self.b):
            p.unlink(missing_ok=True)


class RelTest(unittest.TestCase):
    def test_rel(self):
        self.assertEqual(writer.rel(ROOT / 'proofs' / 'obj' / 'x.bend'), 'proofs/obj/x.bend')
        self.assertIsInstance(ROOT, Path)


if __name__ == '__main__':
    unittest.main()
