"""Generate proofs/type_validator_complete.bend.

Enumerates Schema constructors only (needed for the nested Union pattern);
no test values or protocol inputs are enumerated.
"""
from pathlib import Path

CTORS = [("Boolean", 0), ("Unsigned", 1), ("ByteVector", 1), ("ByteList", 1), ("BitVector", 1), ("BitList", 1),
         ("Vector", 2), ("ListOf", 2), ("Container", 2), ("Union", 1), ("Null", 0), ("Chain", 2), ("End", 0),
         ("Repeat", 1), ("Named", 2), ("ProgressiveList", 1), ("ProgressiveBits", 0), ("ProgressiveContainer", 3),
         ("CompatibleUnion", 2)]


def pat(name, n, p):
    return "T.%s{%s}" % (name, ", ".join("%s%d" % (p, i) for i in range(n)))


def ands(parts):
    """parts: [(bool_expr, proof)] -> (expr, proof) of right-nested conjunction."""
    expr, proof = parts[-1]
    for e, p in reversed(parts[:-1]):
        proof = "V.and_true(%s, %s, %s, %s)" % (e, expr, p, proof)
        expr = "Bool.and(%s, %s)" % (e, expr)
    return expr, proof


HEADER = '''import Base
import ../types/schema.bend as T
import ../src/schema.bend as I
import ../src/lists.bend as Lists
import ../spec/type_legality.bend as S
import ./compatibility_equivalence.bend as Compatibility
import ./validator_selectors.bend as Selectors
import ./validator_metadata.bend as Metadata
import ./validator_fields.bend as Fields
import ./primitive_invariants.bend as V
import ./lists.bend as L
import ./type_validator_soundness.bend as Sound
import ../spec/compatibility.bend as C

# Converse of type_validator_soundness: every independently legal schema is
# accepted by the actual validator. Generated by
# tools/generate_type_validator_complete.py (constructor enumeration only).
law positive:
  for +fields: T.Schema
  for legal: {Nat.is_lt(0n, S.field_count(fields)) == True{} : Bool}
  {Nat.is_lt(0n, I.count(fields)) == True{} : Bool}
def positive(fields, legal):
  %Equal.sym(Nat, I.count(fields), S.field_count(fields), Metadata.field_count(fields)) : {Nat.is_lt(0n, _) == True{} : Bool}
  legal

law limited:
  for +fields: T.Schema
  for +limit: Nat
  for legal: {Nat.is_le(S.field_count(fields), limit) == True{} : Bool}
  {Nat.is_le(I.count(fields), limit) == True{} : Bool}
def limited(fields, limit, legal):
  %Equal.sym(Nat, I.count(fields), S.field_count(fields), Metadata.field_count(fields)) : {Nat.is_le(_, limit) == True{} : Bool}
  legal

law active_length:
  for +active: +List<Bool>
  for legal: {Nat.is_le(List.length(&2, Bool, active), 256n) == True{} : Bool}
  {Nat.is_le(Lists.length(Bool, active), 256n) == True{} : Bool}
def active_length(active, legal):
  %Equal.sym(Nat, Lists.length(Bool, active), List.length(&2, Bool, active), L.length_correct(Bool, active)) : {Nat.is_le(_, 256n) == True{} : Bool}
  legal

law active_count:
  for +active: +List<Bool>
  for +fields: T.Schema
  for legal: {S.active_count(active) == S.field_count(fields) : Nat}
  {Nat.is_eq(I.active_count(active, 0n), I.count(fields)) == True{} : Bool}
def active_count(active, fields, legal):
  %Equal.sym(Nat, I.active_count(active, 0n), S.active_count(active), Metadata.active_count(active)) : {Nat.is_eq(_, I.count(fields)) == True{} : Bool}
  %Equal.sym(Nat, I.count(fields), S.field_count(fields), Metadata.field_count(fields)) : {Nat.is_eq(S.active_count(active), _) == True{} : Bool}
  Fields.equality_complete(S.active_count(active), S.field_count(fields), legal)

law selector_count:
  for +ids: +List<U32>
  for +fields: T.Schema
  for legal: {List.length(&2, U32, ids) == S.field_count(fields) : Nat}
  {Nat.is_eq(Lists.length(U32, ids), I.count(fields)) == True{} : Bool}
def selector_count(ids, fields, legal):
  %Equal.sym(Nat, Lists.length(U32, ids), List.length(&2, U32, ids), L.length_correct(U32, ids)) : {Nat.is_eq(_, I.count(fields)) == True{} : Bool}
  %Equal.sym(Nat, I.count(fields), S.field_count(fields), Metadata.field_count(fields)) : {Nat.is_eq(List.length(&2, U32, ids), _) == True{} : Bool}
  Fields.equality_complete(List.length(&2, U32, ids), S.field_count(fields), legal)

law last_active:
  for +active: +List<Bool>
  for legal: {S.last_active(active) == True{} : Bool}
  {I.ends_active(active, False{}) == True{} : Bool}
def last_active(active, legal):
  %Equal.sym(Bool, I.ends_active(active, False{}), S.last_active(active), Fields.last_active(active)) : {_ == True{} : Bool}
  legal

law options_tail:
  for +options: T.Schema
  for +valid: {I.valid_go(options, True{}) == True{} : Bool}
  for compatible: C.mutually_compatible(options)
  {Bool.and(I.valid_go(options, True{}), I.compatible_go(Nat.mul(1024n, 1n+I.weight(options)), 1, options, options)) == True{} : Bool}
def options_tail(options, valid, compatible):
  V.and_true(I.valid_go(options, True{}), I.compatible_go(Nat.mul(1024n, 1n+I.weight(options)), 1, options, options), valid, Compatibility.options_complete(options, Sound.sound(options, True{}, valid), compatible))


# One option-list head, once. The same extraction was written out for each of
# the eighteen non-null head constructors; a law statement is elaborated in
# every importing module, so those eighteen copies were a large part of this
# module's checker memory. See the mirror image in type_validator_soundness.
law union_complete_at:
  for +h: T.Schema
  for +tail: T.Schema
  for +forest: Bool
  for legal: {forest == False{} : Bool} & {Nat.is_le(S.field_count(tail), 127n) == True{} : Bool} & S.legal(h, False{}) & S.legal(tail, True{})
  for rh: @e: S.legal(h, False{}) -> {I.valid_go(h, False{}) == True{} : Bool}
  for rt: @e: S.legal(tail, True{}) -> {I.valid_go(tail, True{}) == True{} : Bool}
  {Bool.and(Bool.not(forest), Bool.and(Nat.is_le(I.count(tail), 127n), Bool.and(I.valid_go(h, False{}), I.valid_go(tail, True{})))) == True{} : Bool}
def union_complete_at(h, tail, forest, legal, rh, rt):
  (f, lim, head, rest) = legal
  V.and_true(Bool.not(forest), Bool.and(Nat.is_le(I.count(tail), 127n), Bool.and(I.valid_go(h, False{}), I.valid_go(tail, True{}))),
    Selectors.not_false(forest, f),
    V.and_true(Nat.is_le(I.count(tail), 127n), Bool.and(I.valid_go(h, False{}), I.valid_go(tail, True{})),
      limited(tail, 127n, lim),
      V.and_true(I.valid_go(h, False{}), I.valid_go(tail, True{}), rh(head), rt(rest))))

law complete:
  for +schema: T.Schema
  for +forest: Bool
  for legal: S.legal(schema, forest)
  {I.valid_go(schema, forest) == True{} : Bool}
def complete(schema, forest, legal):
  match schema:
'''

NF = "Selectors.not_false(forest, f)"


def case(lines, pattern, names, parts):
    lines.append("    case %s:" % pattern)
    if len(names) == 1:
        lines.append("      f = legal")
    else:
        lines.append("      (%s) = legal" % ", ".join(names))
    lines.append("      " + ands(parts)[1])


def main():
    out = []
    nf = ("Bool.not(forest)", NF)
    for name, n in CTORS:
        p = pat(name, n, "x")
        if name in ("Boolean", "Unsigned", "ByteList", "BitList", "ProgressiveBits"):
            case(out, p, ["f"], [nf])
        elif name in ("ByteVector", "BitVector"):
            case(out, p, ["f", "pos"], [nf, ("Nat.is_lt(0n, x0)", "pos")])
        elif name == "Vector":
            case(out, p, ["f", "pos", "e"], [nf, ("Nat.is_lt(0n, x1)", "pos"), ("I.valid_go(x0, False{})", "complete(x0, False{}, e)")])
        elif name in ("ListOf", "ProgressiveList"):
            case(out, p, ["f", "e"], [nf, ("I.valid_go(x0, False{})", "complete(x0, False{}, e)")])
        elif name == "Container":
            case(out, p, ["f", "named", "fields"], [nf, ("I.named_fields_valid(x0, x1)", "Fields.named_complete(x0, x1, named)"), ("I.valid_go(x1, True{})", "complete(x1, True{}, fields)")])
        elif name == "ProgressiveContainer":
            case(out, p, ["f", "named", "fields", "len", "last", "count"], [nf,
                 ("I.named_fields_valid(x0, x1)", "Fields.named_complete(x0, x1, named)"),
                 ("I.valid_go(x1, True{})", "complete(x1, True{}, fields)"),
                 ("Nat.is_le(Lists.length(Bool, x2), 256n)", "active_length(x2, len)"),
                 ("I.ends_active(x2, False{})", "last_active(x2, last)"),
                 ("Nat.is_eq(I.active_count(x2, 0n), I.count(x1))", "active_count(x2, x1, count)")])
        elif name == "CompatibleUnion":
            case(out, p, ["f", "pos", "count", "ids", "options", "compatible"], [nf,
                 ("Nat.is_lt(0n, I.count(x1))", "positive(x1, pos)"),
                 ("Nat.is_eq(Lists.length(U32, x0), I.count(x1))", "selector_count(x0, x1, count)"),
                 ("I.selectors_valid(x0, [])", "Selectors.complete(x0, ids)"),
                 ("Bool.and(I.valid_go(x1, True{}), I.compatible_go(Nat.mul(1024n, 1n+I.weight(x1)), 1, x1, x1))", "options_tail(x1, complete(x1, True{}, options), compatible)")])
        elif name == "Chain":
            case(out, p, ["f", "h", "t"], [("forest", "f"), ("I.valid_go(x0, False{})", "complete(x0, False{}, h)"), ("I.valid_go(x1, True{})", "complete(x1, True{}, t)")])
        elif name == "End":
            out.append("    case %s: legal" % p)
        elif name in ("Null", "Repeat", "Named"):
            out.append("    case %s: Empty.absurd({False{} == True{} : Bool}, legal)" % p)
        elif name == "Union":
            for un, um in CTORS:
                if un != "Chain":
                    out.append("    case T.Union{%s}: Empty.absurd({False{} == True{} : Bool}, legal)" % pat(un, um, "u"))
                    continue
                for hn, hm in CTORS:
                    h = pat(hn, hm, "h")
                    pattern = "T.Union{T.Chain{%s, tail}}" % h
                    if hn == "Null":
                        case(out, pattern, ["f", "pos", "lim", "rest"], [nf,
                             ("Nat.is_lt(0n, I.count(tail))", "positive(tail, pos)"),
                             ("Nat.is_le(I.count(tail), 127n)", "limited(tail, 127n, lim)"),
                             ("I.valid_go(tail, True{})", "complete(tail, True{}, rest)")])
                    else:
                        # One shared helper instead of a per-head conjunct
                        # rebuild (a proof-checking memory blow-up).
                        out.append("    case %s:" % pattern)
                        out.append("      union_complete_at(%s, tail, forest, legal, e => complete(%s, False{}, e), e => complete(tail, True{}, e))" % (h, h))
    footer = '''
law public_complete:
  for +schema: T.Schema
  for legal: S.type_legal(schema)
  {I.valid(schema) == True{} : Bool}
def public_complete(schema, legal): complete(schema, False{}, legal)
'''
    Path(__file__).resolve().parents[1].joinpath("proofs/type_validator_complete.bend").write_text(HEADER + "\n".join(out) + "\n" + footer)


if __name__ == "__main__":
    main()
