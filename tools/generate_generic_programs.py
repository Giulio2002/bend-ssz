"""Write benchmarks/compact/g{dec,enc,root}.bend: the decode, encode and root
programs for the official ssz_generic schemas. They are the Fulu programs
(benchmarks/compact/{dec,enc,root}.bend) with the schema index swapped for
types/generic_cschema_index.bend, so the two sets cannot drift apart."""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
for program in ('dec', 'enc', 'root'):
    source = (ROOT / 'benchmarks/compact' / (program + '.bend')).read_text()
    swapped = source.replace('../../types/fulu_cschema_index.bend', '../../types/generic_cschema_index.bend')
    assert swapped != source, program
    header = ('# Generated by tools/generate_generic_programs.py from %s.bend: the same program\n'
              '# over the ssz_generic schema table (build/generic-index.json). Do not edit.\n' % program)
    (ROOT / 'benchmarks/compact' / ('g' + program + '.bend')).write_text(header + swapped)
print('wrote benchmarks/compact/g{dec,enc,root}.bend')
