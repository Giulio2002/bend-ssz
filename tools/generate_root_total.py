def pat(name, n, p):
    return "T.%s{%s}" % (name, ", ".join("%s%d" % (p, i) for i in range(n)))


def absurd(goal, proof="legal"):
    return "Empty.absurd(%s, W.false_true(%s))" % (goal, proof)


def conj(xs):
    e = xs[-1]
    for x in reversed(xs[:-1]):
        e = "Bool.and(%s, %s)" % (x, e)
    return e


def pick(xs, idx, proof):
    for i in range(idx):
        proof = "V.and_right(%s, %s, %s)" % (xs[i], conj(xs[i + 1:]), proof)
    if idx < len(xs) - 1:
        proof = "V.and_left(%s, %s, %s)" % (xs[idx], conj(xs[idx + 1:]), proof)
    return proof


