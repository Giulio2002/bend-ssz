            b = body.get((v, s))
            if b is None:
                lines.append("        case %s:\n          match rel:" % sp)
            elif "\n" in b:
                lines.append("        case %s:\n          %s" % (sp, b))
            else:
                lines.append("        case %s: %s" % (sp, b))
