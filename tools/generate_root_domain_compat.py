def pat(name, n, p):
    return "T.%s{%s}" % (name, ", ".join("%s%d" % (p, i) for i in range(n)))


def helper_digests(text):
    out = {}
    for m in re.finditer(r'^def (\w+)\(.*?(?=^def |\Z)', text, re.S | re.M):
        body = re.sub(r'\n#[^\n]*', '', m.group(0)).strip()
        out[m.group(1)] = hashlib.sha256(body.encode()).hexdigest()
    return out


