#!/usr/bin/env python3
"""mkprobe12.py TREE OUT.bend KIND...: the round-12 probe of the cached-tree API through public calls only. Run on the server.

For every cached list kind named (its def file stem, e.g. Fulu_list_Withdrawal_16), one SSZ_CASE (1, 2, ... in the order given):
build the list with the public X_append (two default elements; one for a limit-1 list; transactions: [01], [02]), then
c = X_cache(list), X_cached_root(c), and print the cached root, the plain root of X_uncache(c), the plain root of a fresh copy of
the same list (X_hash_tree_root's _root at hl = 64) and the length of X_uncache(c). The spec: all three roots are
hash_tree_root(List[T, N]) of the same value, and the length is the list's."""
import os, re, sys

tree, out = sys.argv[1:3]
kinds = sys.argv[3:]
T = os.path.join(tree, 'types')
imp, defs, cases = ['import Base', 'import ../../../../../src/buffer.bend as B', 'import ../../../../../src/obj.bend as O',
                    'import ../../../../../src/digest.bend as D', 'import ../../../../../benchmarks/compact/objio.bend as IOx'], [], []
seen = set()
defs.append('''def rs(d: D.Digest) -> String:
  match d:
    case D.D{+a, +b1, +c, +d1, +e, +f, +g, +h}: U32.show(a) ++ "," ++ U32.show(b1) ++ "," ++ U32.show(h)
''')
for ci, k in enumerate(kinds, 1):
    dt = open(os.path.join(T, k + '_def_generated.bend')).read()
    p = re.search(r'^def (\w+)_cached_root\(', dt, re.M).group(1)
    m = re.search(r'^def %s_append\(o: %s_Seq, v: ([\w.]+)\)' % (p, p), dt, re.M)
    elt = m.group(1)
    A, AH = 'K%d' % ci, 'K%dH' % ci
    imp.append('import ../../../../../types/%s_def_generated.bend as %s' % (k, A))
    imp.append('import ../../../../../types/%s_hashtreeroot_generated.bend as %s' % (k, AH))
    if elt == 'O.Words':
        e1 = 'O.Words{Array.set(U32, Array.new(U32, 3n, 0), 0, 1), 1}'
        e2 = 'O.Words{Array.set(U32, Array.new(U32, 3n, 0), 0, 2), 1}'
    else:
        mod, nm = elt.split('.')
        if mod not in seen:
            f = re.search(r'^import \./(\S+) as %s$' % mod, dt, re.M).group(1)
            imp.append('import ../../../../../types/%s as %s' % (f, mod))
            seen.add(mod)
        e1 = e2 = '%s.%s_default()' % (mod, nm)
    lim1 = bool(re.search(r'U32\.is_lt\(n, 1\)', dt))
    S, C = '%s.%s_Seq' % (A, p), '%s.%s_Cached' % (A, p)
    two = '%s.%s_default()' % (A, p)
    for e in ([e1] if lim1 else [e1, e2]):
        two = 'k%d_fst(%s.%s_append(%s, %s))' % (ci, A, p, two, e)
    defs.append('''def k{i}_fst(pair: {S} & Bool) -> {S}:
  (o, ok) = pair
  o
def k{i}_two() -> {S}: {two}
def k{i}_plain(pair: B.Buf & ({S} & D.Digest)) -> String:
  (h, r) = pair
  (o, d) = r
  rs(d)
def k{i}_len(pair: {S} & U32) -> String:
  (o, +n) = pair
  U32.show(n)
def k{i}_cmp(pair: B.Buf & ({C} & D.Digest)) -> IO(Unit):
  (h, r) = pair
  (c, d) = r
  IO.print("c{i} {p} cached=" ++ rs(d) ++ " plain_uncache=" ++ k{i}_plain({AH}.{p}_root(64n, O.hasher(), {A}.{p}_uncache(c), 0)) ++ " plain_fresh=" ++ k{i}_plain({AH}.{p}_root(64n, O.hasher(), k{i}_two(), 0)) ++ " len_uncache=" ++ k{i}_len({A}.{p}_len({A}.{p}_uncache({A}.{p}_cache(k{i}_two())))))
'''.format(i=ci, S=S, C=C, two=two, p=p, A=A, AH=AH))
    cases.append((ci, '%s.%s_cached_root(64n, O.hasher(), %s.%s_cache(k%d_two()), 0)' % (A, p, A, p, ci), 'k%d_cmp' % ci))
disp = ['def dispatch(+c: U32) -> IO(Unit):', '  match c:']
for ci, e, f in cases[:-1]:
    disp.append('    case %d: %s(%s)' % (ci, f, e))
disp.append('    case _: %s(%s)' % (cases[-1][2], cases[-1][1]))
body = '\n'.join(imp) + '\n\n# Round-12 probe a (generated by r12/mkprobe12.py): X_cache of a non-empty list, X_cached_root, X_uncache; public calls only.\n# SSZ_CASE: ' + \
    ', '.join('%d %s' % (i + 1, k) for i, k in enumerate(kinds)) + '\n\n' + '\n'.join(defs) + '\n' + '\n'.join(disp) + '''

def main() -> IO(Unit):
  do IO<Unit>:
    +c : U32 <- IOx.env_u32("SSZ_CASE")
    dispatch(c)
'''
open(out, 'w').write(body)
print('cases', len(cases))
