#!/usr/bin/env python3
"""Generate the reference-side registry for the native SSZ benchmark.

Container types come from the pinned go-eth2-client (which carries the pinned
fastssz generated code); which fork package is the right one for a Fulu
fixture is decided by the harness, by round-tripping the official bytes and
comparing the official root, not by guessing here - every candidate package
that defines the type is registered.

The contract's non-container types (uint*, byte vectors, byte lists) have no
go-eth2-client type. They are implemented directly against the pinned fastssz
hasher from the frozen schema in spec/fulu_schemas.bend, which is exactly what
fastssz's own code generator emits for such fields: marshalling is a copy and
hashing is `ssz.Hasher`.
"""
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from generate_bench_schema import Schemas, fixed_size

ROOT = Path(__file__).resolve().parents[1]
def _modcache():
    """The Go module cache holding the pinned go-eth2-client (go.sum pins it)."""
    import subprocess
    try:
        out = subprocess.run(['go', 'env', 'GOMODCACHE'], capture_output=True, text=True, check=True).stdout.strip()
        if out:
            return Path(out)
    except (OSError, subprocess.CalledProcessError):
        pass
    return Path.home() / 'go/pkg/mod'


GOETH = _modcache() / 'github.com/attestantio/go-eth2-client@v0.27.2/spec'
if not GOETH.is_dir():
    raise SystemExit(f'pinned go-eth2-client v0.27.2 not in the Go module cache ({GOETH}); run `go mod download` in benchmarks/fastssz')
PACKAGES = ['phase0', 'altair', 'bellatrix', 'capella', 'deneb', 'electra', 'fulu']


def go_candidates():
    """type name -> packages of go-eth2-client that define SSZ methods for it."""
    found = {}
    for path in GOETH.rglob('*.go'):
        if path.parent.name not in PACKAGES:
            continue
        text = path.read_text(errors='ignore')
        for m in re.finditer(r'func \(\w+ \*(\w+)\) UnmarshalSSZ\(', text):
            found.setdefault(m.group(1), set()).add(path.parent.name)
    return {name: sorted(pkgs, key=PACKAGES.index) for name, pkgs in found.items()}


def main():
    contract = json.loads((ROOT / 'benchmarks/performance_contract.json').read_text())
    names = sorted({op.rsplit('.', 1)[0] for op in contract['required_operations']})
    schemas = Schemas()
    candidates = go_candidates()

    generated = set()
    encoding = ROOT / 'benchmarks/fastssz/gen/types_encoding.go'
    if encoding.exists():
        generated = set(re.findall(r'func \(\w+ \*(\w+)\) UnmarshalSSZ\(', encoding.read_text()))

    containers, simples, unsupported = [], {}, []
    for name in names:
        node = schemas.resolve(name)
        kind = node['kind']
        if kind == 'container':
            if name in candidates:
                for pkg in candidates[name]:
                    containers.append((name, pkg))
            elif name in generated:
                # Emitted from the frozen schema and compiled by pinned fastssz
                # sszgen (tools/generate_missing_go_types.py).
                containers.append((name, 'gen'))
            else:
                unsupported.append(name)
        elif kind == 'boolean':
            simples[name] = {'kind': 'boolean', 'size': 1}
        elif kind in ('uint', 'byte_vector'):
            simples[name] = {'kind': 'fixed', 'size': fixed_size(node)}
        elif kind == 'vector' and node['element']['kind'] == 'byte_vector' and node['element']['size'] == 32:
            simples[name] = {'kind': 'fixed', 'size': fixed_size(node)}
        elif kind == 'byte_list':
            simples[name] = {'kind': 'byte_list', 'limit': node['limit']}
        else:
            unsupported.append(name)

    used = sorted({pkg for _, pkg in containers})
    lines = [
        '// Code generated by tools/generate_bench_go.py; DO NOT EDIT.',
        'package main',
        '',
        'import (',
    ]
    for pkg in used:
        if pkg == 'gen':
            lines.append('\t"local/ssz-bench/gen"')
        else:
            lines.append(f'\t"github.com/attestantio/go-eth2-client/spec/{pkg}"')
    lines += [')', '', '// Every go-eth2-client type that carries pinned fastssz code for a contract',
              '// type name. The harness picks the one that reproduces the official bytes',
              '// and root for a fixture.',
              'var containerImpls = map[string]func() sszObject{']
    for name, pkg in containers:
        lines.append(f'\t"{pkg}.{name}": func() sszObject {{ return new({pkg}.{name}) }},')
    lines += ['}', '',
              '// Contract type names that have no go-eth2-client SSZ type.',
              'var containerCandidates = map[string][]string{']
    grouped = {}
    for name, pkg in containers:
        grouped.setdefault(name, []).append(f'{pkg}.{name}')
    for name in sorted(grouped):
        joined = ', '.join(f'"{k}"' for k in grouped[name])
        lines.append(f'\t"{name}": {{{joined}}},')
    lines += ['}', '',
              '// Non-container contract types, implemented against the pinned fastssz',
              '// hasher straight from the frozen schema.',
              'var simpleSpecs = map[string]simpleSpec{']
    for name in sorted(simples):
        spec = simples[name]
        if spec['kind'] == 'boolean':
            lines.append(f'\t"{name}": {{fixed: true, size: 1, boolean: true}},')
        elif spec['kind'] == 'fixed':
            lines.append(f'\t"{name}": {{fixed: true, size: {spec["size"]}}},')
        else:
            lines.append(f'\t"{name}": {{fixed: false, limit: {spec["limit"]}}},')
    lines += ['}', '']
    (ROOT / 'benchmarks/fastssz/generated.go').write_text('\n'.join(lines))

    report = {
        'container_impls': sorted(grouped),
        'simple_types': sorted(simples),
        'unsupported': sorted(unsupported),
    }
    (ROOT / 'benchmarks/reference_coverage.json').write_text(json.dumps(report, indent=2) + '\n')
    print('containers:', len(grouped), 'simple:', len(simples), 'unsupported:', len(unsupported))
    if unsupported:
        print('no pinned reference implementation for:', ', '.join(sorted(unsupported)))


if __name__ == '__main__':
    main()
