def pat(name, n, p):
    return "T.%s{%s}" % (name, ", ".join("%s%d" % (p, i) for i in range(n)))


def absurd(goal, proof="legal"):
    return "Empty.absurd(%s, W.false_true(%s))" % (goal, proof)


def union_forest_absurd(goal_of, indent="      "):
    lines = [indent + "match u0:"]
    for n, k in SCHEMAS:
        if n == "Chain":
            lines.append(indent + "  case T.Chain{c0, c1}:")
            lines.append(indent + "    match c0:")
            for m, j in SCHEMAS:
                lines.append(indent + "      case %s: %s" % (pat(m, j, "d"), absurd(goal_of("T.Union{T.Chain{%s, c1}}" % pat(m, j, "d")))))
        else:
            lines.append(indent + "  case %s: %s" % (pat(n, k, "o"), absurd(goal_of("T.Union{%s}" % pat(n, k, "o")))))
    return "\n".join(lines)


