#!/usr/bin/env python3
"""Generate benchmarks/schemas.bend: the frozen contract's type names mapped to
the independent Fulu schemas, so one native benchmark executable can run every
required operation without a per-type build."""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CONTRACT = json.loads((ROOT / 'benchmarks/performance_contract.json').read_text())
NAMES = sorted({op.rsplit('.', 1)[0] for op in CONTRACT['required_operations']})
DEFS = set(re.findall(r'^def (\w+)\(\)', (ROOT / 'spec/fulu_schemas.bend').read_text(), re.M))

missing = [n for n in NAMES if n not in DEFS]
if missing:
    raise SystemExit('spec/fulu_schemas.bend does not define: ' + ', '.join(missing))

lines = [
    'import Base',
    'import ../types/schema.bend as T',
    'import ../spec/fulu_schemas.bend as S',
    '',
    '# Generated by tools/generate_bench_dispatch.py - do not edit by hand.',
    '#',
    '# The benchmark contract names types as strings; the schemas themselves come',
    '# from the independent specification module, unchanged. Branches are thunks so',
    '# that selecting one type never builds the other 108 schemas.',
    '',
    'def pick(ok: Bool, s: Unit -> T.Schema, rest: Unit -> Maybe<&2, T.Schema>) -> Maybe<&2, T.Schema>:',
    '  match ok:',
    '    case True{}: Some{s(Unit{})}',
    '    case False{}: rest(Unit{})',
    '',
    'def schema_of(+name: String) -> Maybe<&2, T.Schema>:',
]
body = ''
for name in NAMES:
    body += f'pick(String.eq(name, "{name}"), u => S.{name}(), u => '
body += 'None{}' + ')' * len(NAMES)
lines.append('  ' + body)
lines.append('')
(ROOT / 'benchmarks/schemas.bend').write_text('\n'.join(lines))
print('benchmarks/schemas.bend:', len(NAMES), 'types')
