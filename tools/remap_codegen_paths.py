#!/usr/bin/env python3
"""Port code written against the flat codegen/ layout to the purpose-directory layout (codegen/MOVES.tsv).

    python3 tools/remap_codegen_paths.py FILE...                  # rewrite old references in place (any text file)
    python3 tools/remap_codegen_paths.py --place codegen/new_gen.py proofs/var   # also move a NEW flat generator into
                                                                  # codegen/proofs/var/, add the root preamble, and
                                                                  # print the codegen/registry.py line to add

What it rewrites in a python file: `import X [as Y]` / `from X import ...` of a moved module -> `from codegen.<dir> import X`,
`__import__('X')`, `ROOT = Path(__file__).resolve().parents[1]` (adjusted to the new depth for a placed file),
`sys.path.insert(0, ... 'codegen')`, and every `codegen/X.py` / `codegen/X.bend.in` path to the new one. Header literals
`# GENERATED by codegen/X.py (...)` become `# GENERATED by X (codegen: ...)`. In any text file only the paths are rewritten.
It is idempotent. Review the diff; `python3 -m unittest discover codegen/tests -t .` then checks imports, headers and the registry.
"""
import ast
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def moves():
    rows = [l.split('\t') for l in (ROOT / 'codegen/MOVES.tsv').read_text().splitlines() if l and not l.startswith('#')]
    return {Path(o).name: n for o, n in rows}


MOVED = moves()
STEM_DIR = {Path(n).stem: str(Path(n).parent.relative_to('codegen')).replace('/', '.') for n in MOVED.values() if n.endswith('.py')}
G = r'codegen/(?:[A-Za-z0-9_]+/)*([A-Za-z0-9_]+)\.py'


def pkg(stem):
    return 'codegen.' + STEM_DIR[stem]


def map_paths(t):
    t = re.sub(r'codegen/([A-Za-z0-9_]+)\.py\b', lambda m: MOVED[m.group(1) + '.py'] if m.group(1) + '.py' in MOVED else m.group(0), t)
    return re.sub(r'codegen/([A-Za-z0-9_]+\.bend\.in)', lambda m: MOVED.get(m.group(1), m.group(0)), t)


def map_header(line):
    if 'GENERATED' not in line:
        return line
    line = re.sub(r'GENERATED from codegen/(?:[A-Za-z0-9_]+/)*([A-Za-z0-9_]+\.bend\.in) by ' + G, r'GENERATED from \1 by \2 (codegen)', line)

    def detail(m):
        d = re.sub(G, r'\1', m.group(2))
        d = re.sub(r'codegen/(?:[A-Za-z0-9_]+/)*([A-Za-z0-9_]+\.bend\.in)', r'\1', d)
        return f'GENERATED by {m.group(1)} (codegen: {d})'
    line = re.sub(r'GENERATED by ' + G + r' \(([^)]*)\)', detail, line)
    return re.sub(r'GENERATED by ' + G, r'GENERATED by \1 (codegen)', line)


def map_imports(t):
    out = []
    for line in t.split('\n'):
        m = re.match(r'^(\s*)import ([A-Za-z0-9_]+)(?: as (\w+))?(\s*(?:#.*)?)$', line)
        if m and m.group(2) in STEM_DIR:
            ind, mod, al, tail = m.groups()
            line = f'{ind}from {pkg(mod)} import {mod}' + (f' as {al}' if al else '') + tail
        else:
            m = re.match(r'^(\s*)from ([A-Za-z0-9_]+) import (.*)$', line)
            if m and m.group(2) in STEM_DIR:
                line = f'{m.group(1)}from {pkg(m.group(2))}.{m.group(2)} import {m.group(3)}'
        out.append(line)
    t = '\n'.join(out)
    return re.sub(r"__import__\('([A-Za-z0-9_]+)'\)", lambda m: f"__import__('{pkg(m.group(1))}.{m.group(1)}', fromlist=['_'])" if m.group(1) in STEM_DIR else m.group(0), t)


def rewrite(t, py, depth=None):
    if py:
        t = map_imports(t)
        t = re.sub(r"^sys\.path\.insert\(0, str\(ROOT / 'codegen'\)\)\n", '', t, flags=re.M)
        t = re.sub(r"^sys\.path\.insert\(0, str\(Path\(__file__\)\.resolve\(\)\.parent\)\)\n", '', t, flags=re.M)
        if depth is not None:
            t = t.replace('Path(__file__).resolve().parents[1]', f'Path(__file__).resolve().parents[{depth + 1}]')
    t = map_paths(t)
    return '\n'.join(map_header(l) for l in t.split('\n')) if py else t


PRE = '''import sys as _sys
import pathlib as _pathlib
_sys.path.insert(0, str(_pathlib.Path(__file__).resolve().parents[%d]))  # the repository root: `codegen` is importable when this file runs as a script
'''


def main(argv):
    if argv[:1] == ['--place']:
        src, d = Path(argv[1]), argv[2]
        stem = src.stem
        dst = ROOT / 'codegen' / d / src.name
        dst.parent.mkdir(parents=True, exist_ok=True)
        for q in [dst.parent] + list(dst.parent.parents):
            if q == ROOT / 'codegen' or q == ROOT:
                break
            (q / '__init__.py').touch()
        subprocess.check_call(['git', 'mv', str(src), str(dst)], cwd=ROOT)
        depth = len(Path(d).parts) + 0
        t = rewrite(dst.read_text(), True, depth)
        tree = ast.parse(t)
        ins = tree.body[0].end_lineno if tree.body and isinstance(tree.body[0], ast.Expr) and isinstance(getattr(tree.body[0], 'value', None), ast.Constant) else 0
        L = t.split('\n')
        L[ins:ins] = (PRE % (depth + 1)).rstrip('\n').split('\n')
        dst.write_text('\n'.join(L))
        print(f"moved {src} -> {dst.relative_to(ROOT)}; add to codegen/registry.py:\n    Gen('{stem}', '{d}'),")
        return 0
    for f in argv:
        p = Path(f)
        t0 = p.read_text()
        t = rewrite(t0, p.suffix == '.py')
        if t != t0:
            p.write_text(t)
            print('rewrote', f)
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
