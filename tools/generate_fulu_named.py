"""Generate proofs/fulu_named.bend: name-indexed adapter laws for every frozen
Fulu name, dispatching to the checked per-representation adapter laws.
Reads only the generated types/fulu.bend dispatch (no fixtures or outputs)."""
import re
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
src = (ROOT / 'types/fulu.bend').read_text()
block = src[src.index('def Name.to_ssz('):src.index('def Name.from_ssz(')]
pairs = re.findall(r'case Name_(\w+)\{\}: (\w+)\.to_value\(v\)', block)
assert len(pairs) == 109, len(pairs)
out = ['''import Base
import ../types/fulu_model.bend as F
import ../types/schema.bend as T
import ../spec/type_legality.bend as Legal
import ../spec/representation.bend as Shape
import ./fulu_normative.bend as Named
import ./fulu_adapter_inverse.bend as Inverse
import ./fulu_adapter_preservation.bend as Preservation
import ./fulu_adapter_complete.bend as Complete

# Generated by tools/generate_fulu_named.py. Every law is stated over the closed
# name index F.Name (all 109 frozen mainnet Fulu names, including names without
# official test cases) and is discharged by the per-name checked laws.
law legal:
  for +name: F.Name
  Legal.type_legal(F.Name.schema(name))
def legal(name):
  match name:''']
for n, h in pairs:
    out.append('    case F.Name_%s{}: Named.%s_normative_legal()' % (n, n))
out.append('''
law inverse:
  for +name: F.Name
  for +value: F.Name.Value(name)
  {F.Name.from_ssz(name, F.Name.to_ssz(name, value)) == Some{value} : Maybe<&2, F.Name.Value(name)>}
def inverse(name, value):
  match name:''')
for n, h in pairs:
    out.append('    case F.Name_%s{}: Inverse.%s_inverse(value)' % (n, h))
out.append('''
def preserves(name: F.Name, original: T.Value, result: Maybe<&2, F.Name.Value(name)>) -> Type:
  match result:
    case None{}: Unit
    case Some{value}: {F.Name.to_ssz(name, value) == original : T.Value}

BRIDGES

law sound:
  for +name: F.Name
  for +original: T.Value
  preserves(name, original, F.Name.from_ssz(name, original))
def sound(name, original):
  match name:''')
for n, h in pairs:
    out.append('    case F.Name_%s{}: %s_bridge(original, F.%s.from_value(original), Preservation.%s_sound(original))' % (n, n, h, h))
out.append('''
law complete:
  for +name: F.Name
  for +original: T.Value
  for +shape: {Shape.shape(original, Shape.erase(F.Name.schema(name))) == True{} : Bool}
  {Complete.present(F.Name.Value(name), F.Name.from_ssz(name, original)) == True{} : Bool}
def complete(name, original, shape):
  match name:''')
for n, h in pairs:
    out.append('    case F.Name_%s{}: Complete.%s_complete(original, shape)' % (n, h))
bridges = []
for n, h in pairs:
    bridges.append('''law %s_bridge:
  for +original: T.Value
  for +result: Maybe<&2, F.%s()>
  for known: Preservation.%s_preserves(original, result)
  preserves(F.Name_%s{}, original, result)
def %s_bridge(original, result, known):
  match result:
    case None{}: Unit{}
    case Some{value}: known
''' % (n, h, h, n, n))
text = '\n'.join(out) + '\n'
text = text.replace('BRIDGES', '\n'.join(bridges))
(ROOT / 'proofs/fulu_named.bend').write_text(text)
