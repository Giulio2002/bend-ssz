#!/usr/bin/env python3
"""Round-3 crash hunt (c): generate the batch mutation driver for one real Fulu container.

    python3 tools/crash_hunt/gen_mutbatch.py --name BeaconState --out tools/crash_hunt/mb_BeaconState.bend

The driver (one process, 10^5 mutants) reads a seed encoding (SSZ_INPUT) and an op file (SSZ_OPS, little-endian u32 words:
word 0 = count, then 7 words per mutant: size, i1, new1, old1, i2, new2, old2; i = word index into the seed buffer; the two writes
are applied before `<Name>_decode_checked(buf, size)` and undone (old values) afterwards). Per mutant it prints one line

    <Name> <n> d=0                                   decode_checked answered None
    <Name> <n> d=1 e=<ser ok> sz=<size out> a=<cs of the input window> b=<cs of the serialized bytes> [r=<root words>]

so the harness can compare the verdict with the reference port and check canonicity (accepted => serialize(decode(x)) == x).
SSZ_ROOT_EVERY=k: the root of every k-th accepted mutant is printed (0: never).
Bend allows no mutual recursion, so the loop is one self-recursive def that takes the previous step's result as a parameter.
"""
import argparse

TEMPLATE = '''import Base
import ../../src/buffer.bend as B
import ../../src/digest.bend as D
import ../../src/obj.bend as O
import ../../types/%(MOD)s_def_generated.bend as Dd
import ../../types/%(MOD)s_decode_ssz_generated.bend as Dx
import ../../types/%(MOD)s_encode_ssz_generated.bend as Ex
import ../../types/%(MOD)s_hashtreeroot_generated.bend as Hx
import ../../benchmarks/compact/objio.bend as IOx

# GENERATED by tools/crash_hunt/gen_mutbatch.py. Round-3 crash hunt (c): batch mutation driver for %(MOD)s.

def cs_go(+k: Nat, +i: U32, +acc: U32, pair: B.Buf & U32) -> B.Buf & U32:
  match k:
    case 0n:
      (b, +w) = pair
      (b, (acc * 31 + w : U32))
    case 1n+q:
      (b, +w) = pair
      cs_go(q, (i + 1 : U32), (acc * 31 + w : U32), B.word(b, (i + 1 : U32)))

def cs_fin(pair: B.Buf & U32) -> U32:
  (b, +x) = pair
  x

def cs_pick(zero: Bool, b: B.Buf, +words: U32) -> B.Buf & U32:
  match zero:
    case True{}: (b, 7)
    case False{}: cs_go(U32.to_nat((words - 1 : U32)), 0, 7, B.word(b, 0))

def tmask(+r: U32) -> U32:
  match r:
    case 0: 0
    case 1: 255
    case 2: 65535
    case _: 16777215

def tail_mask(+sz: U32, pair: B.Buf & U32) -> B.Buf & U32:
  (b, +w) = pair
  (b, (w .&. tmask((sz .&. 3 : U32)) : U32))

def wcs3(+x: U32, pair: B.Buf & U32) -> B.Buf & U32:
  (b, +t) = pair
  (b, (x * 5 + t : U32))

def wcs2(+sz: U32, pair: B.Buf & U32) -> B.Buf & U32:
  (b, +x) = pair
  wcs3(x, tail_mask(sz, B.word(b, U32.shrn(sz, 2n))))

# the checksum of the window [0, sz) of b, and b back
def window_keep(b: B.Buf, +sz: U32) -> B.Buf & U32: wcs2(sz, cs_pick(U32.is_eq(U32.shrn(sz, 2n), 0), b, U32.shrn(sz, 2n)))

def window_cs(b: B.Buf, +sz: U32) -> U32: cs_fin(window_keep(b, sz))

def apply(buf: B.Buf, +idx: U32, +v: U32) -> B.Buf:
  match buf:
    case B.Buf{ws, +len}: B.Buf{Array.set(U32, ws, idx, v), len}

def restore(buf: B.Buf, +i1: U32, +o1: U32, +i2: U32, +o2: U32) -> B.Buf: apply(apply(buf, i2, o2), i1, o1)

def pick_root(+every: U32, +i: U32) -> Bool:
  match every:
    case 0: False{}
    case _: U32.is_eq(U32.mod(i, every), 0)

def fin_line(+i: U32, ok: Bool, +sz: U32, +a: U32, +b: U32) -> String:
  "%(N)s " ++ U32.show(i) ++ " d=1 e=" ++ O.pick_str(ok) ++ " sz=" ++ U32.show(sz) ++ " a=" ++ U32.show(a) ++ " b=" ++ U32.show(b)

# the result of one mutant: its line, the seed buffer with the writes undone, and the op buffer
def done(line: String, +i1: U32, +o1: U32, +i2: U32, +o2: U32, buf: B.Buf, ops: B.Buf) -> String & (B.Buf & B.Buf): (line, (restore(buf, i1, o1, i2, o2), ops))

def root_done(line: String, +i1: U32, +o1: U32, +i2: U32, +o2: U32, buf: B.Buf, ops: B.Buf, pair: B.Buf & (Dd.%(N)s & D.Digest)) -> String & (B.Buf & B.Buf):
  (h, r) = pair
  (o, d) = r
  done(line ++ " r=" ++ IOx.words(d), i1, o1, i2, o2, buf, ops)

def after_root(line: String, +i1: U32, +o1: U32, +i2: U32, +o2: U32, buf: B.Buf, ops: B.Buf, want: Bool, o: Dd.%(N)s) -> String & (B.Buf & B.Buf):
  match want:
    case True{}: root_done(line, i1, o1, i2, o2, buf, ops, Hx.%(N)s_hash_tree_root(O.hasher(), o))
    case False{}: done(line, i1, o1, i2, o2, buf, ops)

def ser_cmp3(+i: U32, +ev: U32, +i1: U32, +o1: U32, +i2: U32, +o2: U32, ops: B.Buf, o: Dd.%(N)s, ok: Bool, +osz: U32, +bcs: U32, pair: B.Buf & U32) -> String & (B.Buf & B.Buf):
  (buf, +acs) = pair
  after_root(fin_line(i, ok, osz, acs, bcs), i1, o1, i2, o2, buf, ops, pick_root(ev, i), o)

def ser_cmp2(+i: U32, +ev: U32, +sz: U32, +i1: U32, +o1: U32, +i2: U32, +o2: U32, ops: B.Buf, buf: B.Buf, o: Dd.%(N)s, ok: Bool, +osz: U32, +bcs: U32) -> String & (B.Buf & B.Buf):
  ser_cmp3(i, ev, i1, o1, i2, o2, ops, o, ok, osz, bcs, window_keep(buf, sz))

def ser_cmp(+i: U32, +ev: U32, +sz: U32, +i1: U32, +o1: U32, +i2: U32, +o2: U32, ops: B.Buf, buf: B.Buf, o: Dd.%(N)s, ok: Bool, ob: B.Buf) -> String & (B.Buf & B.Buf):
  match ob:
    case B.Buf{ows, +osz}: ser_cmp2(i, ev, sz, i1, o1, i2, o2, ops, buf, o, ok, osz, window_cs(B.Buf{ows, osz}, osz))

def after_ser(+i: U32, +ev: U32, +sz: U32, +i1: U32, +o1: U32, +i2: U32, +o2: U32, ops: B.Buf, buf: B.Buf, pair: Dd.%(N)s & O.Encoded) -> String & (B.Buf & B.Buf):
  (o, e) = pair
  match e:
    case O.Encoded{ok, ob}: ser_cmp(i, ev, sz, i1, o1, i2, o2, ops, buf, o, ok, ob)

def after_dec(+i: U32, +ev: U32, +sz: U32, +i1: U32, +o1: U32, +i2: U32, +o2: U32, ops: B.Buf, pair: B.Buf & Maybe<&1, Dd.%(N)s>) -> String & (B.Buf & B.Buf):
  (buf, m) = pair
  match m:
    case None{}: done("%(N)s " ++ U32.show(i) ++ " d=0", i1, o1, i2, o2, buf, ops)
    case Some{o}: after_ser(i, ev, sz, i1, o1, i2, o2, ops, buf, Ex.%(N)s_serialize(o))

def run(+i: U32, +ev: U32, +sz: U32, +i1: U32, +n1: U32, +o1: U32, +i2: U32, +n2: U32, +o2: U32, ops: B.Buf, seed: B.Buf) -> String & (B.Buf & B.Buf):
  after_dec(i, ev, sz, i1, o1, i2, o2, ops, Dx.%(N)s_decode_checked(apply(apply(seed, i1, n1), i2, n2), sz))

# ---- reading the seven words of a mutant ------------------------------------------------------------------------------------
def w7(+i: U32, +ev: U32, +sz: U32, +i1: U32, +n1: U32, +o1: U32, +i2: U32, +n2: U32, seed: B.Buf, pair: B.Buf & U32) -> String & (B.Buf & B.Buf):
  (ops, +o2) = pair
  run(i, ev, sz, i1, n1, o1, i2, n2, o2, ops, seed)
def w6(+i: U32, +ev: U32, +sz: U32, +i1: U32, +n1: U32, +o1: U32, +i2: U32, seed: B.Buf, pair: B.Buf & U32) -> String & (B.Buf & B.Buf):
  (ops, +n2) = pair
  w7(i, ev, sz, i1, n1, o1, i2, n2, seed, B.word(ops, (7 + 7 * i : U32)))
def w5(+i: U32, +ev: U32, +sz: U32, +i1: U32, +n1: U32, +o1: U32, seed: B.Buf, pair: B.Buf & U32) -> String & (B.Buf & B.Buf):
  (ops, +i2) = pair
  w6(i, ev, sz, i1, n1, o1, i2, seed, B.word(ops, (6 + 7 * i : U32)))
def w4(+i: U32, +ev: U32, +sz: U32, +i1: U32, +n1: U32, seed: B.Buf, pair: B.Buf & U32) -> String & (B.Buf & B.Buf):
  (ops, +o1) = pair
  w5(i, ev, sz, i1, n1, o1, seed, B.word(ops, (5 + 7 * i : U32)))
def w3(+i: U32, +ev: U32, +sz: U32, +i1: U32, seed: B.Buf, pair: B.Buf & U32) -> String & (B.Buf & B.Buf):
  (ops, +n1) = pair
  w4(i, ev, sz, i1, n1, seed, B.word(ops, (4 + 7 * i : U32)))
def w2(+i: U32, +ev: U32, +sz: U32, seed: B.Buf, pair: B.Buf & U32) -> String & (B.Buf & B.Buf):
  (ops, +i1) = pair
  w3(i, ev, sz, i1, seed, B.word(ops, (3 + 7 * i : U32)))
def w1(+i: U32, +ev: U32, seed: B.Buf, pair: B.Buf & U32) -> String & (B.Buf & B.Buf):
  (ops, +sz) = pair
  w2(i, ev, sz, seed, B.word(ops, (2 + 7 * i : U32)))

def one(+i: U32, +ev: U32, seed: B.Buf, ops: B.Buf) -> String & (B.Buf & B.Buf): w1(i, ev, seed, B.word(ops, (1 + 7 * i : U32)))

# the loop prints the previous mutant's line, then computes the next one
def loop(+k: Nat, +i: U32, +ev: U32, st: String & (B.Buf & B.Buf)) -> IO(Unit):
  match k st:
    case 0n Tuple{line, r}: IO.print("DONE")
    case 1n+q Tuple{line, r}:
      (seed, ops) = r
      do IO<Unit>:
        IO.print(line)
        loop(q, (i + 1 : U32), ev, one(i, ev, seed, ops))

def with_ops(+ev: U32, seed: B.Buf, pair: B.Buf & U32) -> IO(Unit):
  (ops, +osz) = pair
  loop(U32.to_nat(U32.div((osz - 4 : U32), 28)), 0, ev, ("SEED", (seed, ops)))

def with_seed(+ev: U32, pair: B.Buf & U32) -> IO(Unit):
  (seed, +ssz) = pair
  do IO<Unit>:
    IO.print("SEED size=" ++ U32.show(ssz))
    path : String <- IO.try(String, IO.get_env("SSZ_OPS"))
    ops : B.Buf & U32 <- IOx.read_all(path)
    with_ops(ev, seed, ops)

def main() -> IO(Unit):
  do IO<Unit>:
    +ev : U32 <- IOx.env_u32("SSZ_ROOT_EVERY")
    seed : B.Buf & U32 <- IOx.load()
    with_seed(ev, seed)
'''


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--name', required=True)
    ap.add_argument('--out', required=True)
    ap.add_argument('--generic', action='store_true', help='a name of the generic schemas: no Fulu prefix on the type files')
    a = ap.parse_args()
    open(a.out, 'w').write(TEMPLATE % {'N': a.name, 'MOD': a.name if a.generic else 'Fulu' + a.name})


main()
