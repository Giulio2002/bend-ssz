#!/usr/bin/env python3
"""Crash hunt round 5 (a): the root's clean-copy path (O.wcn / O.zeros_copy, R2-02 (b), CH-11, R4-01) for EVERY packed kind of
tools/crash_hunt/gen_packed_diff.SPECS, at many sizes and storage depths.

    python3 tools/crash_hunt/r5/gen_dirty.py gen            (writes tools/crash_hunt/r5/dirty/dt_<id>.bend)
    python3 tools/crash_hunt/r5/gen_dirty.py run --jobs 4   (server; needs build/ch5/dt_<id>)

A program builds, for SSZ_N (bytes; bits for bit lists) and SSZ_D (array depth), the DIRTY object: every word of a 2^D-word array is
FILL, except that the bytes (bits) of the last data word past the length are cleared (so `_valid` may be 1), and the CLEAN object: the same
data words in a 2^(D+4)-word array of zeros. It prints `valid=<dirty valid> cvalid=<clean valid> eq=<root(dirty) == root(clean)>`.
Verdict WRONG: both valid and the roots differ (the root of a valid object must be the root of its bytes)."""
import argparse, collections, json, os, re, subprocess, sys
from concurrent.futures import ThreadPoolExecutor
HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, '..', '..', '..'))
sys.path.insert(0, os.path.join(HERE, '..'))
import gen_packed_diff as G  # noqa: E402

FILL = {'bool': 0x01010101, 'bit': 0xFFFFFFFF}
UNIT = {'u8': 1, 'u16': 2, 'u32': 4, 'u64': 8, 'u128': 16, 'u256': 32, 'b32': 32, 'b48': 48, 'cell': 2048, 'bool': 1, 'bit': 1}

PROG = '''import Base
import ../../../../src/buffer.bend as B
import ../../../../src/digest.bend as D
import ../../../../src/obj.bend as O
import ../../../../types/%(file)s_hashtreeroot_generated.bend as Hh
import ../../../../types/%(file)s_encode_ssz_generated.bend as Ee
import ../../../../benchmarks/compact/objio.bend as IOx

# GENERATED by tools/crash_hunt/r5/gen_dirty.py (round 5: dirty storage past the length, root vs the clean copy) for %(file)s

def fill() -> U32: %(FILL)d

def fw(k: Nat, +i: U32, arr: Array<U32>) -> Array<U32>:
  match k:
    case 0n: arr
    case 1n+q: fw(q, (i + 1 : U32), Array.set(U32, arr, i, fill()))

def tailmask(+r: U32) -> U32:
  match r:
    case 0: 0
    case _: (O.pick(U32.is_lt(r, 32), (U32.shl_by(1, r) - 1 : U32), 4294967295))

def lastw(+n: U32, arr: Array<U32>) -> Array<U32>: Array.set(U32, arr, %(WIDX)s, (fill() .&. tailmask(%(TBITS)s) : U32))

def clean(+n: U32, +d: U32) -> %(OT)s: %(OT)s{lastw(n, fw(U32.to_nat(%(WIDX)s), 0, Array.new(U32, U32.to_nat((d + 4 : U32)), 0))), n}

def dirty(+n: U32, +d: U32) -> %(OT)s: %(OT)s{lastw(n, Array.new(U32, U32.to_nat(d), fill())), n}

def rv(pair: B.Buf & (%(OT)s & D.Digest)) -> D.Digest:
  (h, r) = pair
  (o, d) = r
  d

def vv(pair: %(OT)s & Bool) -> Bool:
  (o, ok) = pair
  ok

def deq(+a: D.Digest, +b: D.Digest) -> Bool:
  match a b:
    case D.D{+a0, +a1, +a2, +a3, +a4, +a5, +a6, +a7} D.D{+b0, +b1, +b2, +b3, +b4, +b5, +b6, +b7}:
      Bool.and(Bool.and(Bool.and(U32.is_eq(a0, b0), U32.is_eq(a1, b1)), Bool.and(U32.is_eq(a2, b2), U32.is_eq(a3, b3))),
               Bool.and(Bool.and(U32.is_eq(a4, b4), U32.is_eq(a5, b5)), Bool.and(U32.is_eq(a6, b6), U32.is_eq(a7, b7))))

def show(ok: Bool, cok: Bool, +a: D.Digest, +b: D.Digest) -> IO(Unit):
  IO.print("valid=" ++ O.pick_str(ok) ++ " cvalid=" ++ O.pick_str(cok) ++ " eq=" ++ O.pick_str(deq(a, b)) ++ " dirty=" ++ IOx.words(a) ++ " clean=" ++ IOx.words(b))

def main() -> IO(Unit):
  do IO<Unit>:
    +n : U32 <- IOx.env_u32("SSZ_N")
    +d : U32 <- IOx.env_u32("SSZ_D")
    show(vv(Ee.%(P)s_valid(dirty(n, d))), vv(Ee.%(P)s_valid(clean(n, d))), rv(Hh.%(P)s_root(64n, O.hasher(), dirty(n, d), 0)), rv(Hh.%(P)s_root(64n, O.hasher(), clean(n, d), 0)))
'''

def render(s):
    bit = s['kind'] == 'bit'
    return PROG % dict(file=s['file'], FILL=FILL.get(s['kind'], 0xA5A5A5A5), OT='O.Bits' if bit else 'O.Words', P=s['prefix'],
                       WIDX='U32.shrn(n, 5n)' if bit else 'U32.shrn(n, 2n)', TBITS='(n .&. 31 : U32)' if bit else '(8 * (n .&. 3 : U32) : U32)')

def sizes(s):
    u = UNIT[s['kind']]
    if s['shape'] == 'vector':
        ns = [s['vn'] * u]
    else:
        lim = s['limit']
        cap = (lim * u if lim is not None else 10 ** 9)
        base = list(range(0, 70)) + [95, 96, 97, 127, 128, 129, 255, 256, 257, 511, 512, 513, 1023, 1024, 1025, 4095, 4096, 4097]
        if s['kind'] == 'bit':
            base += [2047, 2048, 2049, 8191, 8192, 8193]
        ns = sorted({(x // u) * u for x in base if (x // u) * u <= cap} | ({cap, cap - u} if lim is not None and cap < 10 ** 6 else set()))
    out = []
    for n in ns:
        words = (n + 31) // 32 + 1 if s['kind'] == 'bit' else (n + 3) // 4
        d0 = max(0, (max(words, 1) - 1).bit_length())
        for d in sorted({d0, d0 + 1, d0 + 3}):
            if d <= 22:
                out.append((n, d))
    return out

def main():
    ap = argparse.ArgumentParser(); ap.add_argument('mode', choices=['gen', 'run']); ap.add_argument('--jobs', type=int, default=4); ap.add_argument('--only', default='')
    a = ap.parse_args()
    specs = [s for s in G.SPECS if not a.only or s['id'] in a.only.split(',')]
    od = os.path.join(HERE, 'dirty')
    if a.mode == 'gen':
        os.makedirs(od, exist_ok=True)
        for s in specs:
            open(os.path.join(od, 'dt_%s.bend' % s['id']), 'w').write(render(s))
        print('generated', len(specs)); return
    tally, finds = collections.Counter(), []
    def work(s):
        prog = os.path.join(REPO, 'build', 'ch5', 'dt_' + s['id'])
        res = []
        if not os.path.exists(prog):
            return s, None
        for n, d in sizes(s):
            env = {**os.environ, 'SSZ_N': str(n), 'SSZ_D': str(d)}
            try:
                r = subprocess.run(['nice', '-n', '19', prog, '--threads', '1', '--gpu', 'off'], env=env, capture_output=True, text=True, timeout=120)
                res.append((n, d, r.returncode, r.stdout.strip(), r.stderr[-200:]))
            except subprocess.TimeoutExpired:
                res.append((n, d, 'timeout', '', ''))
        return s, res
    with ThreadPoolExecutor(a.jobs) as ex:
        for s, res in ex.map(work, specs):
            if res is None:
                tally['NOBIN'] += 1; print('nobin', s['id']); continue
            for n, d, rc, so, se in res:
                if rc != 0 or 'eq=' not in so:
                    tally['CRASH'] += 1; finds.append({'id': s['id'], 'n': n, 'd': d, 'rc': rc, 'out': so[:200], 'err': se}); continue
                v, cv, eq = (re.search(k + r'=(\d)', so).group(1) for k in ('valid', 'cvalid', 'eq'))
                if v == '1' and cv == '1' and eq == '0':
                    tally['WRONG'] += 1; finds.append({'id': s['id'], 'n': n, 'd': d, 'out': so})
                elif v != cv:
                    tally['VALID_DIFFERS'] += 1; finds.append({'id': s['id'], 'n': n, 'd': d, 'why': 'valid differs dirty vs clean', 'out': so})
                else:
                    tally['OK'] += 1
            print(s['id'], len(res), flush=True)
    for f in finds[:200]: print(json.dumps(f))
    print('FINAL', dict(tally), 'findings', len(finds))

if __name__ == '__main__':
    main()
