"""Crash hunt round 5 (a): plain list and cached list in LOCKSTEP for every boxed list kind with a cache.

    python3 tools/crash_hunt/r5/gen_lock.py gen       (writes tools/crash_hunt/r5/lock/lk_<id>.bend)

A program keeps a plain list L and a cached list C (C = cache(default)) and applies SSZ_STEPS pseudo-random operations
(LCG from SSZ_SEED) to both: append / capp (3 in 8), set / cset (2 in 8), take / ctake (2 in 8), nothing (1 in 8), at indices
0..19. After every step it compares the flags (append, set) or the Some/None of the take, and root(L) with cached_root(C).
At the end it also compares root(L) with root(uncache(C)). Prints `bad=<mismatching steps> first=<first one> n=<len>`.
Elements are distinct (built from the LCG value); byte-list elements have dirty storage past their length."""
