#!/usr/bin/env python3
"""Round-3 crash hunt (b)/(d): cached roots against plain roots and the reference, for EVERY list of composites.

    python3 tools/crash_hunt/gen_cache_diff.py gen --repo . --out tools/crash_hunt/cd
    python3 tools/crash_hunt/gen_cache_diff.py run --repo . --cs CS --out DIR [--only id,id] [--jobs 2]     (server; build/ch/cd_<id>)

Each program starts a cached list (`<P>_cache(default)`) and a plain list, applies the same SSZ_N appends (`_capp` / `_append`), reports
both roots, then SSZ_SETS sets (`_cset` / `_set`) at pseudo-random indices, and reports again. Values come from the LCG x' = x * 1664525 +
1013904223 (replicated in Python): the first scalar setter of the element is used (U64 or U32), everything else stays default. The expected
root is computed by the reference port from the same value, so the check is cached == plain == reference.
"""
import argparse
import collections
import glob
import json
import os
import re
import subprocess
import sys
from concurrent.futures import ThreadPoolExecutor

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '..', 'spec_audit'))
M32 = 0xFFFFFFFF


def nx(x):
    return (x * 1664525 + 1013904223) & M32


PROG = '''import Base
import ../../../src/buffer.bend as B
import ../../../src/digest.bend as D
import ../../../src/obj.bend as O
import ../../../types/%(file)s_def_generated.bend as Dd
import ../../../types/%(file)s_hashtreeroot_generated.bend as Hh
%(ELIMP)s
import ../../../benchmarks/compact/objio.bend as IOx

# GENERATED by tools/crash_hunt/gen_cache_diff.py (round-3 crash hunt: cached vs plain root of %(file)s)

type St is Type:
  St{c: Dd.%(P)s_Cached, s: Dd.%(P)s_Seq}

def nx(+x: U32) -> U32: (x * 1664525 + 1013904223 : U32)

def elem(+x: U32) -> %(ELT)s: %(ELEM)s

def b_step3(c: Dd.%(P)s_Cached, pair: Dd.%(P)s_Seq & Bool) -> St:
  (s, ok) = pair
  St{c, s}
def b_step2(+x: U32, s: Dd.%(P)s_Seq, pair: Dd.%(P)s_Cached & Bool) -> St:
  (c, ok) = pair
  b_step3(c, Dd.%(P)s_append(s, elem(x)))
def b_step(+x: U32, c: Dd.%(P)s_Cached, s: Dd.%(P)s_Seq) -> St: b_step2(x, s, Dd.%(P)s_capp(c, elem(x)))
def b_loop(+k: Nat, +x: U32, st: St) -> St & U32:
  match k st:
    case 0n St{c, s}: (St{c, s}, x)
    case 1n+q St{c, s}: b_loop(q, nx(x), b_step(x, c, s))

def s_step3(c: Dd.%(P)s_Cached, pair: Dd.%(P)s_Seq & Bool) -> St:
  (s, ok) = pair
  St{c, s}
def s_step2(+x: U32, +i: U32, s: Dd.%(P)s_Seq, pair: Dd.%(P)s_Cached & Bool) -> St:
  (c, ok) = pair
  s_step3(c, Dd.%(P)s_set(s, i, elem(x)))
def s_step(+x: U32, +n: U32, c: Dd.%(P)s_Cached, s: Dd.%(P)s_Seq) -> St: s_step2(x, U32.mod(U32.shrn(x, 4n), n), s, Dd.%(P)s_cset(c, U32.mod(U32.shrn(x, 4n), n), elem(x)))
def s_loop(+k: Nat, +x: U32, +n: U32, st: St) -> St & U32:
  match k st:
    case 0n St{c, s}: (St{c, s}, x)
    case 1n+q St{c, s}: s_loop(q, nx(x), n, s_step(x, n, c, s))

def clen_of(pair: Dd.%(P)s_Cached & U32) -> U32:
  (c, +n) = pair
  n

# ---- report 2 (after the sets): the end --------------------------------------------------------------------------------
def r2b(line: String, pair: B.Buf & (Dd.%(P)s_Seq & D.Digest)) -> IO(Unit):
  (h, r) = pair
  (s, d2) = r
  IO.print(line ++ " plain=" ++ IOx.words(d2))
def r2a(s: Dd.%(P)s_Seq, pair: B.Buf & (Dd.%(P)s_Cached & D.Digest)) -> IO(Unit):
  (h, r) = pair
  (c, d1) = r
  r2b("after_set cached=" ++ IOx.words(d1), Hh.%(P)s_root(64n, O.hasher(), s, 0))
def rep_set(st: St) -> IO(Unit):
  match st:
    case St{c, s}: r2a(s, Dd.%(P)s_cached_root(64n, O.hasher(), c, 0))

def drop_x(pair: St & U32) -> St:
  (st, +x) = pair
  st

def p2(+n: U32, +sets: U32, +x: U32, st: St) -> IO(Unit):
  rep_set(drop_x(s_loop(U32.to_nat(O.pick(U32.is_eq(n, 0), 0, sets)), x, n, st)))

# ---- report 1 (after the appends): prints, then goes on to the sets ----------------------------------------------------
def r1c(+n: U32, +sets: U32, +x: U32, c: Dd.%(P)s_Cached, line: String, pair: B.Buf & (Dd.%(P)s_Seq & D.Digest)) -> IO(Unit):
  (h, r) = pair
  (s, d2) = r
  do IO<Unit>:
    IO.print(line ++ " plain=" ++ IOx.words(d2))
    p2(n, sets, x, St{c, s})
def r1b(+n: U32, +sets: U32, +x: U32, s: Dd.%(P)s_Seq, pair: B.Buf & (Dd.%(P)s_Cached & D.Digest)) -> IO(Unit):
  (h, r) = pair
  (c, d1) = r
  r1c(n, sets, x, c, "after_app cached=" ++ IOx.words(d1), Hh.%(P)s_root(64n, O.hasher(), s, 0))
def p1(+n: U32, +sets: U32, pair: St & U32) -> IO(Unit):
  (st, +x) = pair
  match st:
    case St{c, s}: r1b(n, sets, x, s, Dd.%(P)s_cached_root(64n, O.hasher(), c, 0))

def go(+n: U32, +sets: U32, +seed: U32) -> IO(Unit): p1(n, sets, b_loop(U32.to_nat(n), seed, St{Dd.%(P)s_cache(Dd.%(P)s_default()), Dd.%(P)s_default()}))

def main() -> IO(Unit):
  do IO<Unit>:
    +n : U32 <- IOx.env_u32("SSZ_N")
    +sets : U32 <- IOx.env_u32("SSZ_SETS")
    +seed : U32 <- IOx.env_u32("SSZ_SEED")
    go(n, sets, seed)
'''


def specs(repo):
    out = []
    for f in sorted(glob.glob(os.path.join(repo, 'types', '*_def_generated.bend'))):
        s = open(f).read()
        if '_cached_root(' not in s:
            continue
        file = os.path.basename(f)[:-len('_def_generated.bend')]
        m = re.search(r'^def (\w+)_append\(o: \w+, v: ([\w.]+)\)', s, re.M)
        P, vt = m.group(1), m.group(2)
        lim = re.search(r'^def %s_append\(.*?app_in\(U32\.is_lt\(n, (\d+)\)' % re.escape(P), s, re.M | re.S)
        limit = int(lim.group(1)) if lim else None
        sp = dict(id=file, file=file, P=P, vt=vt, limit=limit)
        if vt == 'O.Words':
            sp.update(elimp='', elt='O.Words', elem='O.words_new(U32.shrn(x, 28n))', el=None, field=None, fkind='words')
        else:
            alias, el = vt.split('.')
            imp = re.search(r'^import \./(\w+)_def_generated\.bend as %s$' % re.escape(alias), s, re.M)
            efile = imp.group(1)
            es = open(os.path.join(repo, 'types', efile + '_def_generated.bend')).read()
            sets = re.findall(r'^def %s_set_(\w+)\(o: %s, \+v: (O\.U64|U32)\)' % (re.escape(el), re.escape(el)), es, re.M)
            elimp = 'import ../../../types/%s_def_generated.bend as %s' % (efile, alias)
            if sets:
                field, fk = sets[0]
                val = 'O.U64{x, nx(x)}' if fk == 'O.U64' else 'x'
                sp.update(elimp=elimp, elt=vt, elem='%s.%s_set_%s(%s.%s_default(), %s)' % (alias, el, field, alias, el, val), el=el, field=field, fkind=fk)
            else:
                sp.update(elimp=elimp, elt=vt, elem='%s.%s_default()' % (alias, el), el=el, field=None, fkind=None)
        out.append(sp)
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('mode', choices=['gen', 'run'])
    ap.add_argument('--repo', default='.')
    ap.add_argument('--cs')
    ap.add_argument('--out', required=True)
    ap.add_argument('--only', default='')
    ap.add_argument('--jobs', type=int, default=2)
    a = ap.parse_args()
    only = [x for x in a.only.split(',') if x]
    sps = [s for s in specs(a.repo) if not only or s['id'] in only]
    if a.mode == 'gen':
        os.makedirs(a.out, exist_ok=True)
        for s in sps:
            open(os.path.join(a.out, 'cd_%s.bend' % s['id']), 'w').write(PROG % dict(file=s['file'], P=s['P'], ELIMP=s['elimp'], ELT=s['elt'], ELEM=s['elem']))
        json.dump(sps, open(os.path.join(a.out, 'cd_specs.json'), 'w'), indent=1)
        print('generated', len(sps))
        return
    import ssz_ref as S
    from constants import ref_generic
    from refparse import Ref
    ref = Ref(a.cs)
    gen = ref_generic(a.cs)
    tally = collections.Counter()
    findings = []

    def typeof(name):
        try:
            return ref.type_of(name)
        except Exception:
            return gen[name][0]

    def val_of(s, x):
        return (x | (nx(x) << 32)) if s['fkind'] == 'O.U64' else x

    def expected(s, n, sets, seed):
        lim = s['limit'] if s['limit'] is not None else 2 ** 32
        if s['fkind'] == 'words':
            et = ('bytelist', 2 ** 30)
            mk = lambda x: bytes(x >> 28)
        else:
            et = typeof(s['el'])
            zero = S.zero_value(et)
            names = [nm for nm, _ in et[1]]
            fi = names.index(s['field']) if s['field'] in names else None

            def mk(x):
                v = list(zero) if isinstance(zero, list) else zero
                if fi is not None and s['field']:
                    v = list(zero)
                    v[fi] = val_of(s, x)
                return v
        vals, x = [], seed
        for _ in range(n):
            if len(vals) < lim:
                vals.append(mk(x))
            x = nx(nx(x)) if False else nx(x)
        L = 2 ** 40 if (s['limit'] is None or s['limit'] == 4294967295) else s['limit']
        r1 = S.hash_tree_root(('list', et, L), vals)
        if n > 0:
            for _ in range(sets):
                i = (x >> 4) % n
                if i < len(vals):
                    vals[i] = mk(x)
                x = nx(x)
        r2 = S.hash_tree_root(('list', et, L), vals)
        if s['fkind'] != 'words' and s['field'] and s['field'] not in [nm for nm, _ in et[1]]:
            return None, None
        return r1, r2

    def scen(s):
        lim = s['limit']
        ns = {0, 1, 2, 3, 4, 5, 7, 8, 9, 16, 17, 33, 100}
        if lim is not None and lim <= 300:
            ns |= {lim - 1, lim, lim + 1, lim + 2}
            ns = {n for n in ns if 0 <= n <= lim + 2}
        return [(n, sets, 7 + n) for n in sorted(ns) for sets in (0, 9)]

    def work(s):
        prog = os.path.join(a.repo, 'build', 'ch', 'cd_' + s['id'])
        res = []
        for n, sets, seed in scen(s):
            env = {**os.environ, 'SSZ_N': str(n), 'SSZ_SETS': str(sets), 'SSZ_SEED': str(seed)}
            try:
                r = subprocess.run(['nice', '-n', '19', prog, '--threads', '1', '--gpu', 'off'], env=env, capture_output=True, text=True, timeout=120)
                res.append(((n, sets, seed), r.returncode, r.stdout, r.stderr))
            except subprocess.TimeoutExpired:
                res.append(((n, sets, seed), 'timeout', '', ''))
        return s, res
    with ThreadPoolExecutor(a.jobs) as ex:
        for s, res in ex.map(work, sps):
            bad = 0
            for case, rc, so, se in res:
                n, sets, seed = case
                lines = {l.split()[0]: dict(p.split('=', 1) for p in l.split()[1:]) for l in so.splitlines() if l.startswith('after_')}
                if rc != 0 or 'after_set' not in lines:
                    tally['CRASH'] += 1
                    findings.append({'class': 'CRASH', 'id': s['id'], 'case': case, 'rc': rc, 'err': se[-200:]})
                    bad += 1
                    continue
                probs = []
                try:
                    e1, e2 = expected(s, n, sets, seed)
                except Exception as ex_:
                    e1 = e2 = None
                    probs.append('reference failed: %r' % ex_)
                for key, e in (('after_app', e1), ('after_set', e2)):
                    L = lines.get(key)
                    if not L:
                        probs.append('missing ' + key)
                        continue
                    if L['cached'] != L['plain']:
                        probs.append('%s: cached != plain' % key)
                    if e is not None and L['plain'] != ','.join(str(int.from_bytes(e[i:i + 4], 'big')) for i in range(0, 32, 4)):
                        probs.append('%s: plain != reference' % key)
                if probs:
                    tally['WRONG'] += 1
                    bad += 1
                    findings.append({'class': 'WRONG', 'id': s['id'], 'case': case, 'why': probs})
                else:
                    tally['OK'] += 1
            print(s['id'], 'cases', len(res), 'bad', bad, flush=True)
    os.makedirs(a.out, exist_ok=True)
    json.dump({'tally': dict(tally), 'findings': findings[:300]}, open(os.path.join(a.out, 'cache_diff.json'), 'w'), indent=1)
    print('FINAL', dict(tally))


if __name__ == '__main__':
    main()
