"""Generate proofs/decode_shape.bend.

Enumerates Schema/Value representation constructors only (Bend's checker needs
explicit constructors to reduce the independent encoder); no protocol inputs,
test values or fixture data are enumerated.
"""
from pathlib import Path

SCHEMAS = [("Boolean", 0), ("Unsigned", 1), ("ByteVector", 1), ("ByteList", 1), ("BitVector", 1), ("BitList", 1),
           ("Vector", 2), ("ListOf", 2), ("Container", 2), ("Union", 1), ("Null", 0), ("Chain", 2), ("End", 0),
           ("Repeat", 1), ("Named", 2), ("ProgressiveList", 1), ("ProgressiveBits", 0), ("ProgressiveContainer", 3),
           ("CompatibleUnion", 2)]
VALUES = [("BooleanValue", 1), ("UnsignedValue", 1), ("BytesValue", 1), ("BitsValue", 1), ("Sequence", 1),
          ("Items", 2), ("EmptyItems", 0), ("Selected", 2), ("NullValue", 0)]


def pat(name, n, p):
    return "T.%s{%s}" % (name, ", ".join("%s%d" % (p, i) for i in range(n)))


def absurd(goal):
    return "Empty.absurd(%s, W.false_true(legal))" % goal


HEADER = '''import Base
import ../types/schema.bend as T
import ../src/schema.bend as I
import ../src/lists.bend as Lists
import ../spec/codec.bend as S
import ../spec/schema.bend as SS
import ../spec/primitives.bend as SP
import ../spec/bytes.bend as SBytes
import ../spec/byte_list.bend as SByteList
import ../spec/bitfields.bend as SBits
import ./layout_image_headers.bend as H
import ./decode_facts.bend as F
import ./leaf_sizes.bend as Leaf
import ./primitive_invariants.bend as V
import ./word_facts.bend as W

# Generated by tools/generate_decode_shape.py (constructor enumeration only).
# Every independently encoded value of a validated schema has the layout shape
# consumed by the actual decoder: one fragment whose fixed/variable kind and
# byte length are the schema's normative fixed size, and forest/repeat width
# lists matching the actual decoder's width requests.
'''


def union_forest_absurd(goal_of):
    # valid_go(Union{os}, True) is False for every nested option shape.
    lines = ["      match u0:"]
    for n, k in SCHEMAS:
        if n == "Chain":
            lines.append("        case T.Chain{c0, c1}:")
            lines.append("          match c0:")
            for m, j in SCHEMAS:
                lines.append("            case %s: %s" % (pat(m, j, "d"), absurd(goal_of("T.Union{T.Chain{%s, c1}}" % pat(m, j, "d")))))
        else:
            lines.append("        case %s: %s" % (pat(n, k, "o"), absurd(goal_of("T.Union{%s}" % pat(n, k, "o")))))
    return "\n".join(lines)


def main():
    out = [HEADER]
    # ok_single
    out.append('''law ok_single:
  for +schema: T.Schema
  for legal: {I.valid_go(schema, False{}) == True{} : Bool}
  {F.ok(schema) == True{} : Bool}
def ok_single(schema, legal):
  match schema:''')
    for n, k in SCHEMAS:
        p = pat(n, k, "s")
        if n in ("Chain", "End", "Repeat"):
            out.append("    case %s: %s" % (p, absurd("{F.ok(%s) == True{} : Bool}" % p)))
        elif n == "Null":
            out.append("    case %s: {==}" % p)
        else:
            out.append("    case %s: legal" % p)
    # ok_forest
    out.append('''
law ok_forest:
  for +schema: T.Schema
  for legal: {I.valid_go(schema, True{}) == True{} : Bool}
  {F.ok(schema) == True{} : Bool}
def ok_forest(schema, legal):
  match schema:''')
    for n, k in SCHEMAS:
        p = pat(n, k, "s") if n != "Union" else "T.Union{u0}"
        if n == "Chain":
            out.append("    case %s: legal" % p)
        elif n in ("End", "Null"):
            out.append("    case %s: {==}" % p)
        elif n == "Union":
            out.append("    case %s:" % p)
            out.append(union_forest_absurd(lambda s: "{F.ok(%s) == True{} : Bool}" % s))
        else:
            out.append("    case %s: %s" % (p, absurd("{F.ok(%s) == True{} : Bool}" % p)))
    # head_single
    out.append('''
law head_single:
  for +schema: T.Schema
  for +value: T.Value
  for +result: Maybe<&2, +List<T.Part>>
  for legal: {I.valid_go(schema, False{}) == True{} : Bool}
  for known: F.fact(schema, value, result)
  F.single_result(SS.fixed_size(schema), result)
def head_single(schema, value, result, legal, known):
  match schema:''')
    for n, k in SCHEMAS:
        p = pat(n, k, "s")
        if n in ("Chain", "End", "Repeat"):
            out.append("    case %s: %s" % (p, absurd("F.single_result(SS.fixed_size(%s), result)" % p)))
        else:
            out.append("    case %s: known" % p)
    # forest_view
    out.append('''
law forest_view:
  for +schema: T.Schema
  for +value: T.Value
  for +result: Maybe<&2, +List<T.Part>>
  for legal: {I.valid_go(schema, True{}) == True{} : Bool}
  for known: F.fact(schema, value, result)
  F.chain_fact(F.widths(schema), SS.fixed_size(schema), result)
def forest_view(schema, value, result, legal, known):
  match schema:''')
    for n, k in SCHEMAS:
        p = pat(n, k, "s") if n != "Union" else "T.Union{u0}"
        if n in ("Chain", "End"):
            out.append("    case %s: known" % p)
        elif n == "Union":
            out.append("    case %s:" % p)
            out.append(union_forest_absurd(lambda s: "F.chain_fact(F.widths(%s), SS.fixed_size(%s), result)" % (s, s)))
        else:
            out.append("    case %s: %s" % (p, absurd("F.chain_fact(F.widths(%s), SS.fixed_size(%s), result)" % (p, p))))
    # concatenation lemmas
    out.append('''
law chain_parts:
  for +width: Maybe<&2, Nat>
  for +hs: +List<T.Part>
  for +ws: +List<Maybe<&2, Nat>>
  for +size: Maybe<&2, Nat>
  for +ts: +List<T.Part>
  for single: F.single(width, hs)
  for known: F.chain_fact(ws, size, Some{ts})
  F.chain_fact(width <> ws, SS.sum(width, size), Some{List.append(&2, T.Part, hs, ts)})
def chain_parts(width, hs, ws, size, ts, single, known):
  match hs:
    case Nil{}:
      match single:
    case Con{T.Fixed{xs}, Nil{}}:
      (same, tot) = known
      %Equal.sym(Maybe<&2, Nat>, width, Some{List.length(&2, U32, xs)}, single) : F.chain_fact(_ <> ws, SS.sum(_, size), Some{T.Fixed{xs} <> ts})
      %same : F.chain_fact(Some{List.length(&2, U32, xs)} <> _, SS.sum(Some{List.length(&2, U32, xs)}, size), Some{T.Fixed{xs} <> ts})
      %tot : F.chain_fact(Some{List.length(&2, U32, xs)} <> H.widths(ts), SS.sum(Some{List.length(&2, U32, xs)}, _), Some{T.Fixed{xs} <> ts})
      ({==}, {==})
    case Con{T.Variable{xs}, Nil{}}:
      (same, tot) = known
      %Equal.sym(Maybe<&2, Nat>, width, None{}, single) : F.chain_fact(_ <> ws, SS.sum(_, size), Some{T.Variable{xs} <> ts})
      %same : F.chain_fact(None{} <> _, SS.sum(None{}, size), Some{T.Variable{xs} <> ts})
      ({==}, {==})
    case Con{T.Fixed{xs}, Con{p, q}}:
      match single:
    case Con{T.Variable{xs}, Con{p, q}}:
      match single:

law chain_concat:
  for +width: Maybe<&2, Nat>
  for +head: Maybe<&2, +List<T.Part>>
  for +ws: +List<Maybe<&2, Nat>>
  for +size: Maybe<&2, Nat>
  for +tail: Maybe<&2, +List<T.Part>>
  for single: F.single_result(width, head)
  for known: F.chain_fact(ws, size, tail)
  F.chain_fact(width <> ws, SS.sum(width, size), S.concatenate(head, tail))
def chain_concat(width, head, ws, size, tail, single, known):
  match head tail:
    case None{} _: Unit{}
    case Some{hs} None{}: Unit{}
    case Some{hs} Some{ts}: chain_parts(width, hs, ws, size, ts, single, known)

law repeat_parts:
  for +width: Maybe<&2, Nat>
  for +hs: +List<T.Part>
  for +ws: +List<Maybe<&2, Nat>>
  for +ts: +List<T.Part>
  for single: F.single(width, hs)
  for known: F.repeat_fact(ws, Some{ts})
  F.repeat_fact(width <> ws, Some{List.append(&2, T.Part, hs, ts)})
def repeat_parts(width, hs, ws, ts, single, known):
  match hs:
    case Nil{}:
      match single:
    case Con{T.Fixed{xs}, Nil{}}:
      %Equal.sym(Maybe<&2, Nat>, width, Some{List.length(&2, U32, xs)}, single) : F.repeat_fact(_ <> ws, Some{T.Fixed{xs} <> ts})
      %known : F.repeat_fact(Some{List.length(&2, U32, xs)} <> _, Some{T.Fixed{xs} <> ts})
      {==}
    case Con{T.Variable{xs}, Nil{}}:
      %Equal.sym(Maybe<&2, Nat>, width, None{}, single) : F.repeat_fact(_ <> ws, Some{T.Variable{xs} <> ts})
      %known : F.repeat_fact(None{} <> _, Some{T.Variable{xs} <> ts})
      {==}
    case Con{T.Fixed{xs}, Con{p, q}}:
      match single:
    case Con{T.Variable{xs}, Con{p, q}}:
      match single:

law repeat_concat:
  for +width: Maybe<&2, Nat>
  for +head: Maybe<&2, +List<T.Part>>
  for +ws: +List<Maybe<&2, Nat>>
  for +tail: Maybe<&2, +List<T.Part>>
  for single: F.single_result(width, head)
  for known: F.repeat_fact(ws, tail)
  F.repeat_fact(width <> ws, S.concatenate(head, tail))
def repeat_concat(width, head, ws, tail, single, known):
  match head tail:
    case None{} _: Unit{}
    case Some{hs} None{}: Unit{}
    case Some{hs} Some{ts}: repeat_parts(width, hs, ws, ts, single, known)
''')
    # facts
    out.append('''law facts:
  for +value: T.Value
  for +schema: T.Schema
  for +legal: {F.ok(schema) == True{} : Bool}
  F.fact(schema, value, S.parts(value, schema))
def facts(value, schema, legal):
  match value:''')
    PROG_REST = "Bool.and(Nat.is_le(Lists.length(Bool, s2), 256n), Bool.and(I.ends_active(s2, False{}), Nat.is_eq(I.active_count(s2, 0n), I.count(s1))))"
    for vn, vk in VALUES:
        out.append("    case %s:" % pat(vn, vk, "v"))
        out.append("      match schema:")
        for sn, sk in SCHEMAS:
            p = pat(sn, sk, "s")
            proof = "Unit{}"
            if vn == "BooleanValue" and sn == "Boolean":
                proof = "F.boolean_fact(v0)"
            elif vn == "UnsignedValue" and sn == "Unsigned":
                proof = "F.one_fixed(SP.uint_encoding(s0, v0), SP.byte_width(s0), Leaf.uint_sized(s0, v0))"
            elif vn == "BytesValue" and sn == "ByteVector":
                proof = "F.one_fixed(SBytes.vector_encoding(s0, v0), s0, Leaf.byte_vector_sized(s0, v0))"
            elif vn == "BytesValue" and sn == "ByteList":
                proof = "F.one_variable(SByteList.encoding(s0, v0))"
            elif vn == "BitsValue" and sn == "BitVector":
                proof = "F.one_fixed(SBits.vector_encoding(s0, v0), Nat.div(Nat.add(s0, 7n), 8n), Leaf.bit_vector_sized(s0, v0))"
            elif vn == "BitsValue" and sn == "BitList":
                proof = "F.one_variable(SBits.list_encoding(s0, v0))"
            elif vn == "BitsValue" and sn == "ProgressiveBits":
                proof = "F.one_variable(SBits.list_encoding(List.length(&2, Bool, v0), v0))"
            elif vn == "NullValue" and sn == "Null":
                proof = "{==}"
            elif vn == "EmptyItems" and sn == "End":
                proof = "({==}, {==})"
            elif vn == "EmptyItems" and sn == "Repeat":
                proof = "{==}"
            elif vn == "Items" and sn == "Chain":
                vs = "V.and_left(I.valid_go(s0, False{}), I.valid_go(s1, True{}), legal)"
                vr = "V.and_right(I.valid_go(s0, False{}), I.valid_go(s1, True{}), legal)"
                proof = ("chain_concat(SS.fixed_size(s0), S.parts(v0, s0), F.widths(s1), SS.fixed_size(s1), S.parts(v1, s1), "
                         "head_single(s0, v0, S.parts(v0, s0), %s, facts(v0, s0, ok_single(s0, %s))), "
                         "forest_view(s1, v1, S.parts(v1, s1), %s, facts(v1, s1, ok_forest(s1, %s))))" % (vs, vs, vr, vr))
            elif vn == "Items" and sn == "Repeat":
                proof = ("repeat_concat(SS.fixed_size(s0), S.parts(v0, s0), List.replicate(Maybe<&2, Nat>, S.count(v1), SS.fixed_size(s0)), S.parts(v1, T.Repeat{s0}), "
                         "head_single(s0, v0, S.parts(v0, s0), legal, facts(v0, s0, ok_single(s0, legal))), facts(v1, T.Repeat{s0}, legal))")
            elif vn == "Sequence" and sn == "Vector":
                proof = ("F.vector_fact(SS.fixed_size(s0), s1, S.count(v0), S.parts(v0, T.Repeat{s0}), "
                         "facts(v0, T.Repeat{s0}, V.and_right(Nat.is_lt(0n, s1), I.valid_go(s0, False{}), legal)))")
            elif vn == "Sequence" and sn == "ListOf":
                proof = "F.require_fact(Nat.is_le(S.count(v0), s1), None{}, S.aggregate(S.parts(v0, T.Repeat{s0}), None{}), e => F.aggregate_variable(S.parts(v0, T.Repeat{s0})))"
            elif vn == "Sequence" and sn == "ProgressiveList":
                proof = "F.aggregate_variable(S.parts(v0, T.Repeat{s0}))"
            elif vn == "Sequence" and sn in ("Container", "ProgressiveContainer"):
                if sn == "Container":
                    vf = "V.and_right(I.named_fields_valid(s0, s1), I.valid_go(s1, True{}), legal)"
                else:
                    vf = ("V.and_left(I.valid_go(s1, True{}), %s, V.and_right(I.named_fields_valid(s0, s1), Bool.and(I.valid_go(s1, True{}), %s), legal))"
                          % (PROG_REST, PROG_REST))
                proof = ("F.aggregate_any(SS.fixed_size(s1), S.parts(v0, s1), F.chain_total(F.widths(s1), SS.fixed_size(s1), S.parts(v0, s1), "
                         "forest_view(s1, v0, S.parts(v0, s1), %s, facts(v0, s1, ok_forest(s1, %s)))))" % (vf, vf))
            elif vn == "Selected" and sn == "Union":
                proof = "F.option_fact(SS.option(s0, U32.to_nat(v0)), v1, v0)"
            elif vn == "Selected" and sn == "CompatibleUnion":
                proof = "F.option_fact(SS.compatible_option(s0, s1, v0), v1, v0)"
            out.append("        case %s: %s" % (p, proof))
    Path("proofs/decode_shape.bend").write_text("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
